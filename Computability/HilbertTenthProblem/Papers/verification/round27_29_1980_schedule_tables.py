#!/usr/bin/env python3
"""Generate both complete 98-instruction tables and their 97-step composition."""
from pathlib import Path

import round27_1980_unit_center_certificate as coding
import round28_1980_relaxed_auxiliary_certificate as pell
import round29_1980_composed_certificate as composed
from round24_26_1980_schedule_tables import generate


if __name__ == "__main__":
    for certificate, count, suffix in ((coding, 98, "98_encoding"),
                                       (pell, 98, "98_pell"),
                                       (composed, 97, "97")):
        generate(certificate, count, suffix)
        output = (Path(__file__).resolve().parent.parent / "1980"
                  / f"jones1980_theorem5_{suffix}_schedule.tex")
        generated = output.read_text(encoding="utf-8")
        generated = generated.replace("Generated by round24_26_1980_schedule_tables.py",
                                      "Generated by round27_29_1980_schedule_tables.py")
        output.write_text(generated, encoding="utf-8", newline="\n")
