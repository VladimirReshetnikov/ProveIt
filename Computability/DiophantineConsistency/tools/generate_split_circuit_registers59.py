#!/usr/bin/env python3
"""Generate local source-register normal forms using certified DAG power cuts."""
from pathlib import Path
import importlib.util,argparse,json
ROOT=Path(__file__).resolve().parents[1]
s=importlib.util.spec_from_file_location('steps',ROOT/'tools/generate_split_recipe_steps59.py')
g=importlib.util.module_from_spec(s);s.loader.exec_module(g)
ns=g.nodes;labels=g.labels;base=g.base

def rules(root,cuts=None,forcebase=False):
 cuts=cuts or {};seen=set();result=[]
 def walk(i):
  if i in seen:return
  seen.add(i)
  if i in cuts:result.append(cuts[i]);return
  if i==base and not(forcebase and i==root):return
  if labels[i] and not(i==base and forcebase and i==root):
   result.append(f'natural_power_{i}');return
  result.append(f'natural_step_{i}')
  if ns[i]['kind']in['add','sub','mul']:
   walk(ns[i]['left']);walk(ns[i]['right'])
 walk(root)
 return result

def render():
 out=['''import DiophantineConsistency.SplitCircuitSteps59
import DiophantineConsistency.SplitNinePolynomial59
import Mathlib.Data.Fin.VecNotation

/-! # Fixed-leaf bindings and source-register identities for the counted DAG
Generated by tools/generate_split_circuit_registers59.py. Each proof cuts at
certified source-base powers and uses only the relevant local gate equations.
No whole-program or multivariate-polynomial expansion is used. -/
namespace DiophantineConsistency.SplitCircuitRegisters59
open SplitCircuitSteps59
set_option maxRecDepth 30000
set_option maxHeartbeats 3000000
variable {R : Type*} [CommRing R]

/-- Exact nonliteral coefficient recipes, followed by base and threshold scales. -/
def fixedLeaves (ports : Fin 4 → R) (height scale : R) : Fin 12 → R :=
  ![2*ports 1,-2*ports 0,-2*ports 1,-2-2*ports 1,
    2*ports 0+2*ports 0*ports 1,-4*ports 0,
    2*ports 0-2*ports 2-2*ports 3,-ports 0,
    -2*ports 0^2,2*ports 0^2-2*ports 0*ports 3,4096*height,scale]
''']
 B='naturalRegister (fixedLeaves ports height scale) x 36'
 entries=[
 ('natural_baseRegister',36,'SplitNinePolynomial59.sourceBase height (x 0+1)',{},True,['sourceBase']),
 ('natural_kernel0Register',81,f'SplitNinePolynomial59.kernel0 ports ({B})',{},False,['kernel0','SplitKernelData59.coefficients0','SplitKernelData59.positions0']),
 ('natural_kernel1Register',180,f'SplitNinePolynomial59.kernel1 ports ({B})',{},False,['kernel1','SplitKernelData59.coefficients1','SplitKernelData59.positions1']),
 ('natural_kernel2Register',279,f'SplitNinePolynomial59.kernel2 ports ({B})',{},False,['kernel2','SplitKernelData59.coefficients2','SplitKernelData59.positions2']),
 ('natural_ellRegister',324,f'SplitNinePolynomial59.ell ({B})',{},False,['ell','SplitCertificate59.weights']),
 ('natural_targetsRegister',378,f'SplitNinePolynomial59.targets ({B})',{},False,['targets','SplitCertificate59.targets']),
 ('natural_thresholdRegister',409,f'SplitNinePolynomial59.threshold scale ({B}) (x 0+1)',{},False,['threshold']),
 ('natural_marginScaleRegister',415,f'SplitNinePolynomial59.marginScale ({B}) (x 0+1)',{},False,['marginScale']),
 ]
 cuts={81:'natural_kernel0Register',180:'natural_kernel1Register',279:'natural_kernel2Register',324:'natural_ellRegister',378:'natural_targetsRegister'}
 for name,idx,expr,defs in [
 ('natural_sourceHighRegister',393,f'SplitNinePolynomial59.sourceHigh ports ({B}) (x 1+1)',['sourceHigh']),
 ('natural_sourceSRegister',395,f'SplitNinePolynomial59.sourceS ports ({B}) (x 1+1)',['sourceS','sourceHigh']),
 ('natural_sourceTRegister',386,f'SplitNinePolynomial59.sourceT ({B}) (x 0+1)',['sourceT']),
 ('natural_blockLengthRegister',403,f'SplitNinePolynomial59.blockLength ({B}) (x 0+1)',['blockLength']),
 ('natural_sourceRankRegister',414,f'SplitNinePolynomial59.sourceRank ports ({B}) (x 0+1) (x 1+1)',['sourceRank','blockLength','sourceS','sourceT','sourceHigh'])]:
  entries.append((name,idx,expr,cuts,False,defs))
 for name,idx,expr,cuts,force,defs in entries:
  rs=rules(idx,cuts,force)
  ds=['SplitNinePolynomial59.'+d if'.'not in d else d for d in defs]
  out.append(f'''theorem {name} (ports : Fin 4 → R) (height scale : R) (x : Fin 9 → R) :
    naturalRegister (fixedLeaves ports height scale) x {idx} =
      {expr} := by
  simp only [''')
  out.append(','.join(rs)+']\n')
  out.append('  simp [fixedLeaves,'+','.join(ds)+',Fin.sum_univ_succ]\n  <;> ring\n')
 out.append('end DiophantineConsistency.SplitCircuitRegisters59\n')
 return '\n'.join(out)

if __name__=='__main__':
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');a=ap.parse_args()
 p=ROOT/'Lean/DiophantineConsistency/SplitCircuitRegisters59.lean';text=render()
 if a.check:g.g.require(p.read_text()==text,'generated source register proofs differ')
 else:p.write_text(text)
 print(json.dumps({'status':'PASS'if a.check else'GENERATED','identities':13,'parent':g.g.PINS['natural']},sort_keys=True))
