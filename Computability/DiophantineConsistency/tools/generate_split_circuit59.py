#!/usr/bin/env python3
"""Generate kernel-checked topological/liveness/count data from pinned inert DAGs."""
import argparse, collections, hashlib, json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'candidates/split116-compact/compact54-sharp/generated'
OUT=ROOT/'Lean/DiophantineConsistency/SplitCircuit59.lean'
PINS={
 'positive':'c3d16f56ca868cf1a0773889ed06e89a865ea41057497467325ef2c09e7de96f',
 'natural':'cb0caa3a14370e9a5d43be9cabbfef86f92481301b09f4fd7bc7c19f550804db',
}
VARIABLES=['b','g','h','s','w','C','i','j','n']
FIXED=['c001','c004','c005','c006','c007','c008','c010','c011','c015','c016','base_scale','threshold_scale']


def require(p,m):
 if not p: raise ValueError(m)


def read(domain):
 path=DATA/f'split_116_{domain}.json'
 raw=path.read_bytes()
 require(hashlib.sha256(raw).hexdigest()==PINS[domain],'SHA256 '+domain)
 doc=json.loads(raw)
 require(doc['schema']=='free-carrier-split-nine-adjunct-v1','schema')
 require(doc['variables']==VARIABLES,'input order')
 nodes=doc['nodes'];out=doc['output'];parents=[[] for _ in nodes]
 for i,n in enumerate(nodes):
  k=n['kind']
  if k=='variable':
   require(set(n)=={'kind','name'} and n['name'] in VARIABLES,'input')
  elif k=='fixed':
   require(set(n)=={'kind','name'} and n['name'] in FIXED,'fixed')
  elif k=='literal':
   require(set(n)=={'kind','value'} and type(n['value']) is int,'literal')
  else:
   require(k in ['add','sub','mul'] and set(n)=={'kind','left','right'},'binarykind')
   for q in [n['left'],n['right']]:
    require(type(q)is int and 0<=q<i,'topology')
    parents[q].append(i)
 require(type(out)is int and out==len(nodes)-1,'lastoutput')
 live=set();todo=[out]
 while todo:
  i=todo.pop()
  if i in live:continue
  live.add(i)
  if nodes[i]['kind'] in ['add','sub','mul']:todo += [nodes[i]['left'],nodes[i]['right']]
 require(live==set(range(len(nodes))),'liveness')
 counts=collections.Counter(n['kind'] for n in nodes)
 expected={'positive':{'add':162,'sub':22,'mul':289},'natural':{'add':170,'sub':21,'mul':289}}[domain]
 require({k:counts[k] for k in expected}==expected,'binarycounts')
 require(doc['operation_counts']==expected and doc['total_operations']==sum(expected.values()),'claimedcounts')
 require(counts['variable']==9 and counts['fixed']==12 and counts['literal']==14,'leafcounts')
 require({n['name'] for n in nodes if n['kind']=='variable'}==set(VARIABLES),'allinputs')
 require({n['name'] for n in nodes if n['kind']=='fixed'}==set(FIXED),'allfixed')
 require(all(type(i)is int and 0<=i<len(nodes) for i in doc['named_nodes'].values()),'namedindices')
 consumers=[min(parents[i]) for i in range(out)]
 return doc,consumers


def lean_node(n):
 k=n['kind']
 if k=='variable':return f'.input ⟨{VARIABLES.index(n["name"])},by decide⟩'
 if k=='fixed':return f'.constant ⟨{FIXED.index(n["name"])},by decide⟩'
 if k=='literal':return f'.literal ({n["value"]})'
 return f'.{k} {n["left"]} {n["right"]}'


def render():
 text=['''import DiophantineConsistency.ArithmeticDAG
import Mathlib.Data.Fin.VecNotation

/-!
# Literal compact54-sharp split116 binary circuit

Generated by tools/generate_split_circuit59.py from two SHA-pinned inert JSONs.
Fixed leaves are12 independent parameters. The module checks topology,
all-node liveness, operation counts and polynomial semantics. It does not
identify this DAG with a higher-level arithmetic recipe or calibrate native ports.
-/
namespace DiophantineConsistency.SplitCircuit59
open ArithmeticDAG
set_option maxRecDepth 20000
set_option maxHeartbeats 12000000
set_option synthInstance.maxSize 512

''']
 text.append('def variableNames : Fin 9 → String := !['+','.join(json.dumps(x)for x in VARIABLES)+']\n')
 text.append('def fixedNames : Fin 12 → String := !['+','.join(json.dumps(x)for x in FIXED)+']\n')
 text.append('theorem variableNames_injective : Function.Injective variableNames := by decide +kernel\n')
 text.append('theorem fixedNames_injective : Function.Injective fixedNames := by decide +kernel\n')
 for domain in PINS:
  doc,consumers=read(domain);nodes=doc['nodes'];out=doc['output'];count=doc['total_operations']
  text.append(f'def {domain}SHA256 : String := "{PINS[domain]}"\n')
  text.append(f'def {domain}Nodes : List (Node 9 12) :=\n  ['+',\n   '.join(map(lean_node,nodes))+']\n')
  text.append(f'def {domain}Output : ℕ := {out}\n')
  text.append(f'def {domain}Named : List (String × ℕ) :=\n  ['+',\n   '.join(f'({json.dumps(k)},{v})'for k,v in doc['named_nodes'].items())+']\n')
  text.append(f'def {domain}Consumers : List ℕ :=\n  ['+','.join(map(str,consumers))+']\n')
  text.append(f'theorem {domain}_length : {domain}Nodes.length = {len(nodes)} := by decide +kernel\n')
  text.append(f'theorem {domain}_topological : Topological {domain}Nodes := by decide +kernel\n')
  text.append(f'''private theorem {domain}_consumer_certificate : ∀ i : Fin {out},
    i.val < {domain}Consumers.getD i.val 0 ∧
    {domain}Consumers.getD i.val 0 ≤ {out} ∧
    i.val ∈ ({domain}Nodes.getD ({domain}Consumers.getD i.val 0) (.literal 0)).dependencies :=
  by decide +kernel

theorem {domain}_all_live (i : ℕ) (hi : i < {domain}Nodes.length) :
    Reaches {domain}Nodes {domain}Output i := by
  have hc : ∀ j < {out}, ∃ k, j < k ∧ k ≤ {out} ∧ Edge {domain}Nodes j k := by
    intro j hj
    exact ⟨{domain}Consumers.getD j 0,{domain}_consumer_certificate ⟨j,hj⟩⟩
  apply reaches_of_laterConsumer {domain}Nodes {out} hc i
  rw [{domain}_length] at hi
  omega
''')
  text.append(f'theorem {domain}_operation_count : operationCount {domain}Nodes = {count} := by decide +kernel\n')
  for name,k in [('literals',0),('inputs',1),('fixed',2),('additions',3),('subtractions',4),('multiplications',5)]:
   cnt={0:14,1:9,2:12,3:doc['operation_counts']['add'],4:doc['operation_counts']['sub'],5:doc['operation_counts']['mul']}[k]
   text.append(f'theorem {domain}_{name}_count : kindCount {domain}Nodes {k} = {cnt} := by decide +kernel\n')
  text.append(f'''theorem {domain}_live_operation_count :
    liveOperationCount {domain}Nodes {domain}Output = {count} := by
  rw [liveOperationCount_eq {domain}Nodes {domain}Output {domain}_all_live]
  exact {domain}_operation_count
''')
  text.append(f'theorem {domain}_all_inputs : ∀ i : Fin 9, Node.input i ∈ {domain}Nodes := by decide +kernel\n')
  text.append(f'theorem {domain}_all_fixed : ∀ i : Fin 12, Node.constant i ∈ {domain}Nodes := by decide +kernel\n')
  text.append(f'theorem {domain}_named_indices : ∀ p ∈ {domain}Named, p.2 < {domain}Nodes.length := by decide +kernel\n')
  text.append(f'''def {domain}Value {{R : Type*}} [CommRing R] (p : Fin 12 → R) (x : Fin 9 → R) : R :=
  value {domain}Nodes {domain}Output p x

noncomputable def {domain}Polynomial (p : Fin 12 → ℤ) : MvPolynomial (Fin 9) ℤ :=
  polynomial {domain}Nodes {domain}Output p

theorem eval_{domain}Polynomial (p : Fin 12 → ℤ) (x : Fin 9 → ℤ) :
    MvPolynomial.eval x ({domain}Polynomial p) = {domain}Value p x :=
  eval_polynomial {domain}Nodes {domain}Output p x

theorem {domain}Value_map {{R S : Type*}} [CommRing R] [CommRing S]
    (φ : R →+* S) (p : Fin 12 → R) (x : Fin 9 → R) :
    {domain}Value (fun i => φ (p i)) (fun i => φ (x i)) = φ ({domain}Value p x) :=
  value_map φ {domain}Nodes {domain}Output p x
''')
 text.append('end DiophantineConsistency.SplitCircuit59\n')
 return '\n'.join(text)


def main():
 parser=argparse.ArgumentParser(description=__doc__);parser.add_argument('--check',action='store_true');args=parser.parse_args()
 text=render()
 if args.check:require(OUT.read_text()==text,'generated Lean differs')
 else:OUT.write_text(text)
 print(json.dumps({'status':'PASS'if args.check else'GENERATED','pins':PINS,'positive_operations':473,'natural_operations':480,'fixed_leaves':12,'inputs':9},sort_keys=True))
if __name__=='__main__':main()
