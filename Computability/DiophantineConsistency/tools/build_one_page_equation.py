#!/usr/bin/env python3
"""Build the self-contained equation page and audit its printed seed."""
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import tempfile
from pathlib import Path

DIRECTORY = Path(__file__).resolve().parents[1] / "candidates/one-page"


def require(condition, message):
    if not condition:
        raise ValueError(message)


def sha(raw):
    return hashlib.sha256(raw).hexdigest()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="compare all generated files")
    args = parser.parse_args()
    seed = (DIRECTORY / "COMPACT54_SEED.txt").read_text().strip()
    require(seed.isdigit() and len(seed) == 1294, "complete decimal seed")
    display = ("%% Generated by tools/build_one_page_equation.py; concatenate these lines.\n"
               + "\n".join(seed[i:i + 62] + r"\par" for i in range(0, len(seed), 62)) + "\n")
    source = (DIRECTORY / "equation.tex").read_bytes()
    require(re.findall(rb"\\input\{([^}]+)\}", source) == [b"seed-display.tex"],
            "no unprinted external mathematical data")
    with tempfile.TemporaryDirectory(prefix="proveit-one-page-") as scratch:
        scratch = Path(scratch)
        (scratch / "equation.tex").write_bytes(source)
        (scratch / "seed-display.tex").write_text(display)
        proc = subprocess.run(["pdflatex", "-interaction=nonstopmode", "-halt-on-error",
                               "equation.tex"], cwd=scratch, capture_output=True, text=True)
        require(proc.returncode == 0, "pdflatex failed:\n" + proc.stdout[-4000:])
        log = (scratch / "equation.log").read_text()
        require("Overfull" not in log, "overfull typesetting box")
        pdf = scratch / "equation.pdf"
        info = subprocess.check_output(["pdfinfo", str(pdf)], text=True)
        require(re.search(r"^Pages:\s+1$", info, re.M) is not None, "exactly one page")
        require("612 x 792 pts (letter)" in info, "ordinary letter-size page")
        rendered = subprocess.check_output(["pdftotext", "-raw", str(pdf), "-"], text=True)
        recovered = "".join(re.findall(r"^\s*(\d{10,})\s*$", rendered, re.M))
        require(recovered == seed, "complete seed survives PDF rendering")
        raw = pdf.read_bytes()
    receipt = {
        "status": "PASS", "pages": 1, "paper": "US Letter, 612 x 792 points",
        "overfull_boxes": 0, "printed_seed_digits": len(recovered),
        "printed_seed_matches": True, "tex_sha256": sha(source),
        "seed_display_sha256": sha(display.encode()), "pdf_sha256": sha(raw),
        "pdf_bytes": len(raw),
        "scope": "Presentation, full printed numeral and reproducible PDF only. "
                 "Coefficient identities have a separate complete-byte audit; "
                 "the native/internal-ZFC calibration remains open in Lean.",
    }
    outputs = {"seed-display.tex": display.encode(), "equation.pdf": raw,
               "ONE_PAGE_RENDER.json": (json.dumps(receipt, indent=2) + "\n").encode()}
    for name, data in outputs.items():
        target = DIRECTORY / name
        if args.check:
            require(target.read_bytes() == data, "reproduction differs: " + name)
        else:
            target.write_bytes(data)
    print(json.dumps(receipt, indent=2))


if __name__ == "__main__":
    main()
