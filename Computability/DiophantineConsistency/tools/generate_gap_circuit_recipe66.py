#!/usr/bin/env python3
"""Generate a local-register proof joining the counted natural DAG to its scalar recipe."""
from pathlib import Path
import importlib.util,argparse,json
ROOT=Path(__file__).resolve().parents[1]
s=importlib.util.spec_from_file_location('registers',ROOT/'tools/generate_gap_circuit_registers66.py')
g=importlib.util.module_from_spec(s);s.loader.exec_module(g)

def render():
 out=['''import DiophantineConsistency.GapCircuitRegisters66
import DiophantineConsistency.SplitJointPower59

/-! # Identification of the counted H2082 DAG with the scalar polynomial recipe
Generated by tools/generate_gap_circuit_recipe66.py. The proof uses only
local gate equations, named source registers, and small ring identities. -/
namespace DiophantineConsistency.GapCircuitRecipe66
open GapCircuitSteps66 GapCircuitRegisters66
set_option maxRecDepth 30000
set_option maxHeartbeats 3000000
variable {R : Type*} [CommRing R]

/-- The literal 450-operation natural DAG evaluates to the published scalar recipe.
The fixed leaves are the eleven explicit integer-polynomial recipes in the four
abstract native ports and the two independent height and threshold scales. -/
theorem naturalValue_eq_recipe (ports : Fin 4 → R) (height scale : R) (x : Fin 9 → R) :
    GapCircuit66.naturalValue (fixedLeaves ports height scale) x =
      GapNinePolynomial66.value ports height scale x := by
  let b := x 0+1
  let g := x 1+1
  let h := x 2+1
  let s := x 3+1
  let w := x 4+1
  let C := x 5+1
  let i := x 6+1
  let j := x 7
  let n := x 8+1
  let base := GapNinePolynomial66.sourceBase height b
  let rank := GapNinePolynomial66.sourceRank ports base b g
  let N := GapNinePolynomial66.threshold scale base
  let t := GapNinePolynomial66.marginScale base b
  change naturalRegister (fixedLeaves ports height scale) x 483 =
    GapNinePolynomial66.ratioValue rank N b g t h s w C i j n
''']
 inputs=[(10,'b'),(11,'g'),(12,'h'),(13,'s'),(14,'w'),(15,'C'),(16,'i'),(7,'j'),(17,'n')]
 cuts={}
 for idx,v in inputs:
  rs=g.rules(idx)
  out.append(f'''  have h{idx} : naturalRegister (fixedLeaves ports height scale) x {idx} = {v} := by
    simp [{v},{','.join(rs)}]
''')
  cuts[idx]=f'h{idx}'
 for idx,v,lemma in [(20,'base','natural_baseRegister'),(383,'rank','natural_sourceRankRegister'),(378,'N','natural_thresholdRegister'),(384,'t','natural_marginScaleRegister')]:
  rhs='[natural_baseRegister,base,rank,N,t,b,g]'
  out.append(f'''  have h{idx} : naturalRegister (fixedLeaves ports height scale) x {idx} = {v} := by
    simpa only {rhs} using ({lemma} ports height scale x)
''')
  cuts[idx]=f'h{idx}'
 out.append('''  unfold GapNinePolynomial66.ratioValue
  extract_lets U Y M P K a B1 W J Q D E F G H I k V0 V1 m omega theta
  clear_value
    (dU : U = N^2*w) (dY : Y = N^2*s) (dM : M = rank*Y)
    (dP : P = 2*M^2*U) (dK : K = rank+1+h*(P-1))
    (da : a = M*(U+1)) (dB1 : B1 = 2*rank+1) (dW : W = b*w)
    (dJ : J = 4*a-5) (dQ : Q = 3*W*C-2*(W^2-1))
    (dD : D = (a^2-1)*C^2+1) (dE : E = i*J*D*C^2)
    (dF : F = (a^2-1)*E^2+1) (dG : G = a+F*(C*D+1-a))
    (dH : H = C+F*(B1+j*C)) (dI : I = (G^2-1)*H^2+1)
    (dk : k = i*J*C) (dV0 : V0 = P*K)
    (dV1 : V1 = k*(8*D^2-4*D-1)*G*H)
    (dm : m = K^2*(4*t-g)-16*t*(C-K*Y)^2)
    (domega : omega = J*m)
    (dtheta : theta = J*(n+W^2)+Q-omega*(V0+V1))
    b g h s w C i j n base rank N t
''')
 stages=[
 (386,'U','dU'),(387,'Y','dY'),(388,'M','dM'),(391,'P','dP'),
 (395,'K','dK'),(397,'a','da'),(399,'B1','dB1'),(400,'W','dW'),
 (404,'J','dJ'),(410,'Q','dQ'),(415,'D','dD'),(417,'k','dk'),
 (419,'E','dE,dk'),(422,'F','dF'),(427,'G','dG'),(431,'H','dH'),
 (436,'I','dI'),(437,'V0','dV0'),
 (441,'(P^2-1)*K^2+1','dV0'),(443,'D*F*I',None),
 (453,'m','dm'),(461,'V1','dV1'),(462,'omega','domega'),
 (469,'theta','dtheta')]
 for idx,expr,defs in stages:
  # Only traverse the current register, keeping earlier named registers opaque.
  rs=g.rules(idx,cuts)
  out.append(f'''  have h{idx} : naturalRegister (fixedLeaves ports height scale) x {idx} = {expr} := by
    simp only [{','.join(rs)}]
''')
  if defs:out.append('    rw ['+defs+'] <;> ring\n')
  else:out.append('    ring\n')
  cuts[idx]=f'h{idx}'
 rs=g.rules(483,cuts)
 out.append(f'''  simp only [{','.join(rs)},NearSquareFinalizer.norm]
  ring

/-- The independently certified 17-multiplication reduction preserves the same recipe. -/
theorem jointNaturalValue_eq_recipe (ports : Fin 4 → R) (height scale : R) (x : Fin 9 → R) :
    SplitJointCircuit59.naturalValue (fixedLeaves ports height scale) x =
      GapNinePolynomial66.value ports height scale x := by
  rw [SplitJointPower59.naturalValue_eq_parent,naturalValue_eq_recipe]

/-- Ring homomorphisms preserve all eleven explicitly bound fixed leaves. -/
theorem map_fixedLeaves {{S : Type*}} [CommRing S] (f : R →+* S)
    (ports : Fin 4 → R) (height scale : R) :
    (fun i => f (fixedLeaves ports height scale i)) =
      fixedLeaves (fun i => f (ports i)) (f height) (f scale) := by
  funext i
  fin_cases i <;>
    simp [fixedLeaves,map_add,map_sub,map_mul,map_neg,map_pow,map_ofNat]

/-- Equality of the actual parent polynomial data, not merely agreement on
sampled integer inputs. The height exponent is twice the half-height parameter. -/
theorem naturalPolynomial_eq_recipe (ports : Fin 4 → ℤ) (a : ℕ) :
    GapCircuit66.naturalPolynomial (fixedLeaves ports ((2:ℤ)^(2*a)) ((2:ℤ)^(15*a+79))) =
      GapNinePolynomial66.polynomial ports a := by
  change GapCircuit66.naturalValue
    (fun i => MvPolynomial.C (fixedLeaves ports ((2:ℤ)^(2*a)) ((2:ℤ)^(15*a+79)) i))
    MvPolynomial.X = _
  rw [map_fixedLeaves]
  exact naturalValue_eq_recipe (fun i => MvPolynomial.C (ports i))
    (MvPolynomial.C ((2:ℤ)^(2*a))) (MvPolynomial.C ((2:ℤ)^(15*a+79))) MvPolynomial.X

/-- The operation-reduced natural polynomial is exactly the source-equivalent
nine-variable polynomial for every supplied four-port tuple. -/
theorem jointNaturalPolynomial_eq_recipe (ports : Fin 4 → ℤ) (a : ℕ) :
    SplitJointCircuit59.naturalPolynomial (fixedLeaves ports ((2:ℤ)^(2*a)) ((2:ℤ)^(15*a+79))) =
      GapNinePolynomial66.polynomial ports a := by
  rw [SplitJointPower59.naturalPolynomial_eq_parent,naturalPolynomial_eq_recipe]

end DiophantineConsistency.GapCircuitRecipe66
''')
 text='\n'.join(out)
 text=text.replace('import DiophantineConsistency.SplitJointPower59\n','')
 first=text.index('/-- The independently certified')
 last=text.index('/-- Ring homomorphisms',first)
 text=text[:first]+text[last:]
 first=text.index('/-- The operation-reduced')
 last=text.index('end DiophantineConsistency.GapCircuitRecipe66',first)
 text=text[:first]+text[last:]
 return text

if __name__=='__main__':
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');a=ap.parse_args()
 p=ROOT/'Lean/DiophantineConsistency/GapCircuitRecipe66.lean';text=render()
 if a.check:g.g.g.require(p.read_text()==text,'generated scalar recipe proof differs')
 else:p.write_text(text)
 print(json.dumps({'status':'PASS'if a.check else'GENERATED','parent':g.g.g.PINS['natural'],'tail_register_identities':24},sort_keys=True))
