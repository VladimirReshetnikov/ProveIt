#!/usr/bin/env python3
"""Generate Lean evaluations of the literal P67/P69 DAGs and their formal bridge."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
BASELINE = ROOT / 'Computability/DiophantineConsistency/con-zfc-diophantine-forms/36-small-tuple/baseline/product67.json'
CIRCUIT = ROOT / 'Computability/DiophantineConsistency/circuits/p69_unscaled.json'
OUTPUT = ROOT / 'Computability/DiophantineConsistency/Lean/DiophantineConsistency/ShortCircuit.lean'
base, new = (json.loads(p.read_text()) for p in (BASELINE, CIRCUIT))
assert base['witnesses'] == new['witnesses'] and base['fixed_numerals'] == new['fixed_numerals']
assert base['source'][:56] == new['source'][:56]


def bindings():
    return '\n'.join('  let ' + name + ' := ' + ('v' if name in new['witnesses'] else 'p') + ' ' + str(i)
                     for names in (new['witnesses'], new['fixed_numerals'])
                     for i, name in enumerate(names))


def schedule(gates):
    return '\n'.join(f'  let {name} := {left} {op} {right}' for name, op, left, right in gates)


header = f'''import DiophantineConsistency.ShortEquation
import Mathlib.Algebra.MvPolynomial.Eval
import Mathlib.Data.Fin.VecNotation

/-!
# The literal 69-operation polynomial and its local correctness

Generated by `tools/build_short_lean.py` from the two literal circuit DAGs.
P67 SHA-256: {hashlib.sha256(BASELINE.read_bytes()).hexdigest()}
P69 SHA-256: {hashlib.sha256(CIRCUIT.read_bytes()).hexdigest()}

There are fifteen positive unknowns and four fixed coefficient ports.
This module proves equality for the actual multivariate polynomial, then
its zero equivalence to the baseline P67. It supplies no native-window
compiler correctness theorem and makes no independent Con(ZFC) claim.
-/

namespace DiophantineConsistency.ShortCircuit

open MvPolynomial

variable {{R S : Type*}} [CommRing R] [CommRing S]

/-- Literal evaluations use these witness coordinates:
`J F alpha z f h i T s w tau eta zeta y gamma`.
The parameter coordinates are `beta K0 MC MF`, with MF shifted. -/
def value (p : Fin 4 → R) (v : Fin 15 → R) : R :=
{bindings()}
{schedule(new['source'])}
  polynomial

/-- The exact baseline 67-gate evaluation, with the same coordinate order. -/
def baselineValue (p : Fin 4 → R) (v : Fin 15 → R) : R :=
{bindings()}
{schedule(base['source'])}
  polynomial

/-- Arithmetic blocks used only to prove the identity of the literal outputs. -/
structure Core (R : Type*) where
  n0 : R
  n1 : R
  nk : R
  nt : R
  delta : R
  a : R
  c : R
  i : R
  f : R
  gap : R
  y : R

def core (p : Fin 4 → R) (v : Fin 15 → R) : Core R :=
{bindings()}
{schedule([row for row in new['source'][:56] if row[0] != 'norm_pair'])}
  ⟨norm_first, norm_main, norm_index, norm_transport, A, R12, R10a,
    i, f, aux_square_gap, y⟩
'''
proofs = r'''
def coreValue (b : Core R) : R :=
  let c2 := b.c * b.c
  let root := b.i * c2
  let rootSquare := root * root
  let scaledRootSquare := b.delta * rootSquare
  let strong := b.f * b.f - scaledRootSquare
  let coefficient := b.delta * (b.f * b.f - 1)
  let auxiliary := coefficient * b.gap + b.y * b.y
  (((b.n0 * b.n1) * auxiliary) * b.nk * b.nt) * strong - 1

def coreBaselineValue (b : Core R) : R :=
  let c2 := b.c * b.c
  let dc2 := b.delta * c2
  let root := b.i * dc2
  let rootSquare := root * root
  let scaledFSquare := b.delta * (b.f * b.f)
  let strong := scaledFSquare - rootSquare
  let auxiliary := rootSquare * b.gap + b.y * b.y
  (((b.n0 * b.n1) * auxiliary) * b.nk * b.nt) * strong - b.delta

theorem value_eq_core (p : Fin 4 → R) (v : Fin 15 → R) :
    value p v = coreValue (core p v) := rfl

theorem baselineValue_eq_core (p : Fin 4 → R) (v : Fin 15 → R) :
    baselineValue p v = coreBaselineValue (core p v) := rfl

theorem coreValue_eq (b : Core R) :
    coreValue b =
      (b.n0 * b.n1 * b.nk * b.nt) *
        (b.delta * (b.f ^ 2 - 1) * b.gap + b.y ^ 2) *
          (b.f ^ 2 - b.delta * (b.i * b.c ^ 2) ^ 2) - 1 := by
  unfold coreValue
  ring

theorem coreBaselineValue_eq (b : Core R) :
    coreBaselineValue b =
      (b.n0 * b.n1 * b.nk * b.nt) *
        (b.delta ^ 2 * (b.i * b.c ^ 2) ^ 2 * b.gap + b.y ^ 2) *
          (b.delta * b.f ^ 2 - b.delta ^ 2 * (b.i * b.c ^ 2) ^ 2) - b.delta := by
  unfold coreBaselineValue
  ring

private theorem discriminant_identity (a : R) : a * a + (4 * a + 3) = (a + 2) ^ 2 - 1 := by
  ring

theorem core_delta (p : Fin 4 → R) (v : Fin 15 → R) :
    (core p v).delta = ((core p v).a + 2) ^ 2 - 1 := by
  exact discriminant_identity _

theorem core_a_pos (p : Fin 4 → ℤ) (v : Fin 15 → ℤ)
    (hbeta : 0 < p 0) (hv : ∀ j, 0 < v j) : 0 < (core p v).a := by
  have hJ := hv 0
  have hs := hv 8
  have hw := hv 9
  dsimp only [core]
  positivity

/-- Equality of the complete positive zero sets of the two literal circuits. -/
theorem value_zero_iff_baselineValue_zero (p : Fin 4 → ℤ) (v : Fin 15 → ℤ)
    (hbeta : 0 < p 0) (hv : ∀ j, 0 < v j) :
    value p v = 0 ↔ baselineValue p v = 0 := by
  rw [value_eq_core, baselineValue_eq_core, coreValue_eq, coreBaselineValue_eq]
  have ha := core_a_pos p v hbeta hv
  have hdelta : ((core p v).a + 2) ^ 2 - 1 ≠ 0 := by
    nlinarith
  have h := ShortEquation.scaled_zero_iff_reduced
    (m := (core p v).n0 * (core p v).n1 * (core p v).nk * (core p v).nt)
    (a := (core p v).a) (f := (core p v).f)
    (t := (core p v).i * (core p v).c ^ 2)
    (gap := (core p v).gap) (y := (core p v).y) hdelta
  rw [← core_delta p v] at h
  exact h.symm

/-- A ring homomorphism transports the full literal arithmetic schedule. -/
theorem value_map (φ : R →+* S) (p : Fin 4 → R) (v : Fin 15 → R) :
    φ (value p v) = value (fun i => φ (p i)) (fun i => φ (v i)) := by
  simp only [value, map_add, map_sub, map_mul, map_one, map_ofNat]

/-- The actual ordinary integer multivariate polynomial represented by P69. -/
noncomputable def polynomial (p : Fin 4 → ℤ) : MvPolynomial (Fin 15) ℤ :=
  value (fun i => MvPolynomial.C (p i)) MvPolynomial.X

theorem eval_polynomial (p : Fin 4 → ℤ) (v : Fin 15 → ℤ) :
    MvPolynomial.eval v (polynomial p) = value p v := by
  simpa only [polynomial, MvPolynomial.eval_C, MvPolynomial.eval_X] using
    value_map (MvPolynomial.eval v) (fun i => MvPolynomial.C (p i)) MvPolynomial.X

/-- The formal bridge includes evaluation of the actual fifteen-variable polynomial. -/
theorem eval_polynomial_zero_iff_baselineValue_zero
    (p : Fin 4 → ℤ) (v : Fin 15 → ℤ)
    (hbeta : 0 < p 0) (hv : ∀ j, 0 < v j) :
    MvPolynomial.eval v (polynomial p) = 0 ↔ baselineValue p v = 0 := by
  rw [eval_polynomial]
  exact value_zero_iff_baselineValue_zero p v hbeta hv

#print axioms eval_polynomial_zero_iff_baselineValue_zero

end DiophantineConsistency.ShortCircuit
'''
OUTPUT.write_text(header + proofs)
print(OUTPUT.relative_to(ROOT))
