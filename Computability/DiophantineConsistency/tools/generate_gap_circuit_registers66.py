#!/usr/bin/env python3
"""Bind the11 H2082 fixed leaves and check each named source register locally."""
from pathlib import Path
import importlib.util,argparse,json
ROOT=Path(__file__).resolve().parents[1]
s=importlib.util.spec_from_file_location('steps',ROOT/'tools/generate_gap_recipe_steps66.py')
g=importlib.util.module_from_spec(s);s.loader.exec_module(g)
ns=g.nodes;labels=g.labels;base=g.base;named=g.doc['named_nodes']

def rules(root,cuts=None,forcebase=False):
 cuts=cuts or {};seen=set();result=[]
 def walk(i):
  if i in seen:return
  seen.add(i)
  if i in cuts:result.append(cuts[i]);return
  if i==base and not(forcebase and i==root):return
  if labels[i]and not(i==base and forcebase and i==root):result.append(f'natural_power_{i}');return
  result.append(f'natural_step_{i}')
  if ns[i]['kind']in['add','sub','mul']:walk(ns[i]['left']);walk(ns[i]['right'])
 walk(root);return result

def render():
 out=['''import DiophantineConsistency.GapCircuitSteps66
import DiophantineConsistency.GapNinePolynomial66
import Mathlib.Data.Fin.VecNotation
/-! # Exact fixed-leaf and named-source binding for the H2082 counted circuit
Generated by tools/generate_gap_circuit_registers66.py from pinned inert DAGs.
Every proof cuts at certified base powers and already checked named registers. -/
namespace DiophantineConsistency.GapCircuitRegisters66
open GapCircuitSteps66
set_option maxRecDepth 30000
set_option maxHeartbeats 3000000
variable {R : Type*} [CommRing R]

def fixedLeaves (ports : Fin 4 → R) (height scale : R) : Fin 11 → R :=
  ![4096*height,2*ports 1,-2*ports 1,-2-2*ports 1,
    2*ports 0+2*ports 0*ports 1,-2*ports 2-2*ports 3,-4*ports 0,
    -ports 0,-2*ports 0*ports 3,-2*ports 0^2,scale]
''']
 B=f'naturalRegister (fixedLeaves ports height scale) x {base}'
 entries=[
 ('natural_baseRegister','B','GapNinePolynomial66.sourceBase height (x 0+1)',True,['sourceBase']),
 ('natural_kernel0Register','Dcode0',f'GapNinePolynomial66.kernel0 ports ({B})',False,['kernel0','GapKernelData66.coefficients0','GapKernelData66.positions0']),
 ('natural_kernel1Register','Dcode1',f'GapNinePolynomial66.kernel1 ports ({B})',False,['kernel1','GapKernelData66.coefficients1','GapKernelData66.positions1']),
 ('natural_kernel2Register','Dcode2',f'GapNinePolynomial66.kernel2 ports ({B})',False,['kernel2','GapKernelData66.coefficients2','GapKernelData66.positions2']),
 ('natural_ellRegister','ell',f'GapNinePolynomial66.ell ({B})',False,['ell','GapCertificate66.weights','SplitCertificate59.weights']),
 ('natural_targetsRegister','targets',f'GapNinePolynomial66.targets ({B})',False,['targets','GapCertificate66.targets']),
 ('natural_thresholdRegister','N',f'GapNinePolynomial66.threshold scale ({B})',False,['threshold']),
 ('natural_marginScaleRegister','capbase',f'GapNinePolynomial66.marginScale ({B}) (x 0+1)',False,['marginScale']),
 ('natural_sourceHighRegister','Jcode',f'GapNinePolynomial66.sourceHigh ports ({B}) (x 1+1)',False,['sourceHigh']),
 ('natural_sourceSRegister','Scode',f'GapNinePolynomial66.sourceS ports ({B}) (x 1+1)',False,['sourceS']),
 ('natural_sourceTRegister','Tcode',f'GapNinePolynomial66.sourceT ({B}) (x 0+1)',False,['sourceT']),
 ('natural_blockLengthRegister','L',f'GapNinePolynomial66.blockLength ({B}) (x 0+1)',False,['blockLength']),
 ('natural_sourceRankRegister','R',f'GapNinePolynomial66.sourceRank ports ({B}) (x 0+1) (x 1+1)',False,['sourceRank'])]
 cuts={}
 for name,key,expr,force,defs in entries:
  idx=named[key];rs=rules(idx,cuts,force);ds=['GapNinePolynomial66.'+d if'.'not in d else d for d in defs]
  out.append(f'''theorem {name} (ports : Fin 4 → R) (height scale : R) (x : Fin 9 → R) :
    naturalRegister (fixedLeaves ports height scale) x {idx} = {expr} := by
  simp only [{','.join(rs)}]
  simp [fixedLeaves,{','.join(ds)},Fin.sum_univ_succ]
  <;> ring
''')
  if idx!=base:cuts[idx]=name
 out.append('end DiophantineConsistency.GapCircuitRegisters66\n');return '\n'.join(out)

if __name__=='__main__':
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');a=ap.parse_args()
 p=ROOT/'Lean/DiophantineConsistency/GapCircuitRegisters66.lean';text=render()
 if a.check:g.g.require(p.read_text()==text,'generated source register proofs differ')
 else:p.write_text(text)
 print(json.dumps({'status':'PASS'if a.check else'GENERATED','identities':13,'parent':g.g.PINS['natural']},sort_keys=True))
