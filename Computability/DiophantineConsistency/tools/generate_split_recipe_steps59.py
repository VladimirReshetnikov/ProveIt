#!/usr/bin/env python3
"""Emit local equations and source-base power cuts for the pinned natural DAG."""
from pathlib import Path
import importlib.util,argparse,json
ROOT=Path(__file__).resolve().parents[1]
s=importlib.util.spec_from_file_location('parent',ROOT/'tools/generate_split_circuit59.py')
g=importlib.util.module_from_spec(s);s.loader.exec_module(g)
doc,_=g.read('natural');nodes=doc['nodes'];base=doc['named_nodes']['B']
labels=[0]*len(nodes)
for i,n in enumerate(nodes):
 if i==base:labels[i]=1
 elif n['kind']=='mul' and labels[n['left']] and labels[n['right']]:
  labels[i]=labels[n['left']]+labels[n['right']]

def rhs(n):
 k=n['kind']
 if k=='literal':return f'(({n["value"]} : ℤ) : R)'
 if k=='variable':return f'x ⟨{g.VARIABLES.index(n["name"])},by decide⟩'
 if k=='fixed':return f'p ⟨{g.FIXED.index(n["name"])},by decide⟩'
 op={'add':'+','sub':'-','mul':'*'}[k]
 return f'naturalRegister p x {n["left"]} {op} naturalRegister p x {n["right"]}'

def render():
 out=['''import DiophantineConsistency.ArithmeticDAGSemantics
import DiophantineConsistency.SplitCircuit59

/-! # Local scalar equations for the pinned natural split116 parent DAG
Generated by tools/generate_split_recipe_steps59.py. All results follow from
the actual list evaluator and its closed topology certificate. -/
namespace DiophantineConsistency.SplitCircuitSteps59
open ArithmeticDAG
set_option maxRecDepth 20000
set_option maxHeartbeats 600000
variable {R : Type*} [CommRing R]

def naturalRegister (p : Fin 12 → R) (x : Fin 9 → R) (i : ℕ) : R :=
  (run p x SplitCircuit59.naturalNodes []).getD i 0
''']
 for i,n in enumerate(nodes):
  out.append(f'''theorem natural_step_{i} (p : Fin 12 → R) (x : Fin 9 → R) :
    naturalRegister p x {i} = {rhs(n)} :=
  run_node_equation p x SplitCircuit59.naturalNodes SplitCircuit59.natural_topological {i}
    (by rw [SplitCircuit59.natural_length];decide)
''')
 for i,e in enumerate(labels):
  if not e or i==base:continue
  n=nodes[i];cuts=[f'natural_power_{j}' for j in dict.fromkeys([n['left'],n['right']]) if j!=base]
  out.append(f'''theorem natural_power_{i} (p : Fin 12 → R) (x : Fin 9 → R) :
    naturalRegister p x {i} = naturalRegister p x {base} ^ {e} := by
  rw [natural_step_{i}]
''')
  if cuts:out.append('  simp only ['+','.join(cuts)+']\n')
  out.append('  ring\n')
 out.append('end DiophantineConsistency.SplitCircuitSteps59\n')
 return '\n'.join(out)

if __name__=='__main__':
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');a=ap.parse_args()
 p=ROOT/'Lean/DiophantineConsistency/SplitCircuitSteps59.lean';text=render()
 if a.check:g.require(p.read_text()==text,'generated local equations differ')
 else:p.write_text(text)
 print(json.dumps({'status':'PASS'if a.check else'GENERATED','parent':g.PINS['natural'],'equations':len(nodes),'powers':sum(e!=0 for e in labels)-1},sort_keys=True))
