#!/usr/bin/env python3
"""Emit the H2082 three literal kernels, exact source binding and sharp port bounds."""
from pathlib import Path
import importlib.util,argparse,json
ROOT=Path(__file__).resolve().parents[1]
s=importlib.util.spec_from_file_location('cert',ROOT/'tools/generate_gap_certificate66.py')
g=importlib.util.module_from_spec(s);s.loader.exec_module(g)

def render():
 source,layout,kernels,*_=g.read()
 header='''import DiophantineConsistency.GapGeometry66
import DiophantineConsistency.SplitKernelData59
/-! # The85 literal H2082 kernel records and their sharp generic height
Generated by tools/generate_gap_kernels66.py from SHA-pinned inert JSON.
All coefficient ports remain parameters. -/
namespace DiophantineConsistency.GapKernelData66
open Polynomial
open scoped BigOperators
open SplitKernelData59 (coeff_sparseKernel sparseKernel_degree sparseKernel_height)
set_option maxRecDepth 20000
set_option maxHeartbeats 3000000
variable {R : Type*} [CommRing R]
noncomputable abbrev sparseKernel {n : ℕ} (e : Fin n → ℕ) (a : Fin n → R) : R[X] :=
  SplitKernelData59.sparseKernel e a
'''
 out=[header];coeffs=[]
 for ch in kernels['kernels']:
  k=ch['degree'];terms=ch['terms'];n=len(terms);d=layout['kernel_degrees'][k]
  cs=[g.g.coefficient({tuple(v['port_powers']):v['integer']for v in t['coefficient']})for t in terms];coeffs.append(cs)
  out.append(f'def positions{k} : Fin {n} → ℕ := '+g.g.vec([str(t['exponent'])for t in terms])+'\n')
  out.append(f'def coefficients{k} (ports : Fin 4 → R) : Fin {n} → R := '+g.g.vec(cs)+'\n')
  out.append(f'theorem positions{k}_injective : Function.Injective positions{k} := by decide +kernel\n')
  out.append(f'theorem positions{k}_le : ∀ i, positions{k} i ≤ {d} := by decide +kernel\n')
  out.append(f'noncomputable def D{k} (ports : Fin 4 → R) : R[X] := sparseKernel positions{k} (coefficients{k} ports)\n')
  out.append(f'theorem degree_D{k} (ports : Fin 4 → R) : (D{k} ports).natDegree ≤ {d} := sparseKernel_degree _ _ positions{k}_le\n')
 out.append('''theorem leading_D2 (ports : Fin 4 → R) : (D2 ports).coeff 1850 = 1 := by
  change (sparseKernel positions2 (coefficients2 ports)).coeff (positions2 42) = 1
  rw [coeff_sparseKernel _ positions2_injective]
  rfl
''')
 for k in range(len(coeffs)):
  out.append(f'''theorem records{k}_lt (ports : Fin 4 → ℤ) (B K : ℤ)
    (hB : 2 ≤ B) (hK : 16*B ≤ K)
    (hb : 0 ≤ ports 0 ∧ ports 0 < B)
    (hk : 0 ≤ ports 1 ∧ ports 1 < K)
    (hm : 0 ≤ ports 2 ∧ ports 2 < B)
    (hf : 0 ≤ ports 3 ∧ ports 3 < 2*B) :
    ∀ i, |coefficients{k} ports i| < 2*B*K := by
  obtain ⟨hsq,hp,hl,hBK⟩ := SplitKernelData59.port_box_facts ports B K hB hK hb hk hm hf
  intro i
  fin_cases i <;> dsimp [coefficients{k}] <;> rw [abs_lt] <;> constructor <;>
    nlinarith only [hB,hK,hb.1,hb.2,hk.1,hk.2,hm.1,hm.2,hf.1,hf.2,hsq,hp,hl,hBK,sq_nonneg B]
''')
 for k in range(3):
  out.append(f'''theorem height_D{k} (ports : Fin 4 → ℤ) (H : ℤ) (hH : 0 ≤ H)
    (h : ∀ i, |coefficients{k} ports i| ≤ H) (j : ℕ) : |(D{k} ports).coeff j| ≤ H :=
  sparseKernel_height _ positions{k}_injective _ hH h j
''')
 out.append('end DiophantineConsistency.GapKernelData66\n')
 wrapper=(ROOT/'Lean/DiophantineConsistency/SplitKernels59.lean').read_text()
 start=wrapper.index('noncomputable abbrev D0');end=wrapper.index('theorem kernelBounds_pow')
 body=wrapper[start:end].replace('SplitKernelData59','GapKernelData66').replace('SplitCertificate59','GapCertificate66')
 body=body.replace('∀ k,sourceRows ports x k = 0','∀ k,GapSource66.rows ports x k = 0')
 body=body.replace('≤ 2161','≤ 2082')
 body=body.replace('targets,weights,','targets,weights,SplitCertificate59.weights,')
 body=body.replace('GapKernelData66.sparseKernel,','GapKernelData66.sparseKernel,SplitKernelData59.sparseKernel,')
 body+='''
theorem degree_D2_exact [Nontrivial R] (ports : Fin 4 → R) :
    (D2 ports).natDegree = 1850 :=
  natDegree_eq_of_le_of_coeff_ne_zero (GapKernelData66.degree_D2 ports)
    (by rw [GapKernelData66.leading_D2]; exact one_ne_zero)

theorem kernel_heights_box (ports : Fin 4 → ℤ) (B K : ℤ)
    (hB : 2 ≤ B) (hK : 16*B ≤ K)
    (hb : 0 ≤ ports 0 ∧ ports 0 < B)
    (hk : 0 ≤ ports 1 ∧ ports 1 < K)
    (hm : 0 ≤ ports 2 ∧ ports 2 < B)
    (hf : 0 ≤ ports 3 ∧ ports 3 < 2*B) :
    (∀ j, |(D0 ports).coeff j| ≤ 2*B*K) ∧
    (∀ j, |(D1 ports).coeff j| ≤ 2*B*K) ∧
    (∀ j, |(D2 ports).coeff j| ≤ 2*B*K) := by
  have hH : 0 ≤ 2*B*K := by nlinarith
  exact ⟨GapKernelData66.height_D0 ports _ hH
      (fun i => (GapKernelData66.records0_lt ports B K hB hK hb hk hm hf i).le),
    GapKernelData66.height_D1 ports _ hH
      (fun i => (GapKernelData66.records1_lt ports B K hB hK hb hk hm hf i).le),
    GapKernelData66.height_D2 ports _ hH
      (fun i => (GapKernelData66.records2_lt ports B K hB hK hb hk hm hf i).le)⟩

theorem kernel_heights_pow (ports : Fin 4 → ℤ) (p q : ℕ)
    (hp : 1 ≤ p) (hpq : p+4 ≤ q)
    (hb : 0 ≤ ports 0 ∧ ports 0 < 2^p)
    (hk : 0 ≤ ports 1 ∧ ports 1 < 2^q)
    (hm : 0 ≤ ports 2 ∧ ports 2 < 2^p)
    (hf : 0 ≤ ports 3 ∧ ports 3 < 2*2^p) :
    (∀ j, |(D0 ports).coeff j| ≤ 2^(p+q+1)) ∧
    (∀ j, |(D1 ports).coeff j| ≤ 2^(p+q+1)) ∧
    (∀ j, |(D2 ports).coeff j| ≤ 2^(p+q+1)) := by
  have hB : (2:ℤ) ≤ 2^p := by
    simpa using (pow_le_pow_right₀ (by norm_num : (1:ℤ) ≤ 2) hp)
  have hK : 16*(2:ℤ)^p ≤ 2^q := by
    calc
      16*(2:ℤ)^p = 2^(p+4) := by rw [pow_add];norm_num;ring
      _ ≤ 2^q := pow_le_pow_right₀ (by norm_num) hpq
  have he : 2*(2:ℤ)^p*2^q = 2^(p+q+1) := by
    rw [pow_add,pow_add]
    ring
  rw [← he]
  exact kernel_heights_box ports _ _ hB hK hb hk hm hf
'''
 wrap=['''import DiophantineConsistency.GapCertificate66
import DiophantineConsistency.GapKernelData66
/-! # The H2082 literal three kernels equal the extracted85 source channels -/
namespace DiophantineConsistency.GapKernels66
open Polynomial SidonPositions SelectiveQuadraticCoding DegreeSeparatedCoding
open GapCertificate66
open scoped BigOperators
set_option maxRecDepth 20000
set_option maxHeartbeats 8000000
variable {R : Type*} [CommRing R]
''',body,
'''theorem source_one_not_zero (ports : Fin 4 → ℤ) :
    GapSource66.rows ports (fun _ => 1) 9 = -7 := by
  change (-3 : ℤ)+1+(-4)*1+(-1)*(1^2) = -7
  norm_num

theorem source_zero_has_nonzero_digit (ports : Fin 4 → ℤ) (z : Fin 31 → ℕ)
    (hsource : ∀ k, GapSource66.rows ports (fun i => (z i : ℤ)+1) k = 0) :
    ∃ i, 0<z i := by
  by_contra hn
  have hz : ∀ i, z i=0 := by
    intro i
    have hi : ¬0<z i := fun h => hn ⟨i,h⟩
    omega
  have he : (fun i => (z i : ℤ)+1)=(fun _ => 1) := by
    funext i
    rw [hz i]
    norm_num
  have h := hsource 9
  rw [he,source_one_not_zero] at h
  norm_num at h
end DiophantineConsistency.GapKernels66
''']
 return {'GapKernelData66.lean':'\n'.join(out),'GapKernels66.lean':'\n'.join(wrap)}

if __name__=='__main__':
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');a=ap.parse_args()
 for name,text in render().items():
  p=ROOT/'Lean/DiophantineConsistency'/name
  if a.check:g.g.require(p.read_text()==text,'generated kernel differs '+name)
  else:p.write_text(text)
 print(json.dumps({'status':'PASS'if a.check else'GENERATED','records':85,'degrees':[1627,1941,1850],'source_product_degree':2082},sort_keys=True))
