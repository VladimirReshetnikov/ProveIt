#!/usr/bin/env python3
"""Emit the H2082 85-record geometry/source certificate from pinned inert JSON.
The source equations themselves are reused from the frozen GapSource66 module.
"""
from pathlib import Path
from collections import defaultdict
from itertools import combinations_with_replacement
import argparse,hashlib,importlib.util,json
ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'candidates/gap2082-compact54/data/H2082'
PINS={'source.json':'e4f50dbede42c421defa2d7d36268413351dd1e023763c584ea34f3b9a827957',
      'layout.json':'d4b85e61d6cc88a385d608f11a938f8b36bf4280940f4d236be897573d3b6f51',
      'kernels.json':'7a2a497fdb37c41e0246b4ef6dc2ccdba8c32f5ac5b4f00be454d1e4bf1b37d4'}
s=importlib.util.spec_from_file_location('base',ROOT/'tools/generate_split_certificate59.py')
g=importlib.util.module_from_spec(s);s.loader.exec_module(g)

def read():
 docs={}
 for name,pin in PINS.items():
  raw=(DATA/name).read_bytes();g.require(hashlib.sha256(raw).hexdigest()==pin,'input pin '+name);docs[name]=json.loads(raw)
 source,layout,kernels=[docs[n]for n in PINS]
 names=source['variables']+source['constants']
 g.require(names[-4:]==['beta','K0','MC','MF'],'port order')
 rows=[]
 for i,eq in enumerate(source['equations']):
  g.require(eq['number']==i+1,'source order')
  row={tuple(t['powers']):t['coefficient']for t in eq['terms']}
  g.require(row==g.parse(eq['residual'],names),'source sparse/text identity')
  rows.append(row)
 g.require(len(rows)==22,'source rows')
 order=[i-1 for i in layout['order']];g.require(sorted(order)==list(range(22)),'row permutation')
 delivered=[rows[i]for i in order]
 w=layout['weights'];E=layout['targets']
 g.require(w==[1,7,61,36,16,85,20,67,43,11,34,13,96,80,29,50,2,109,110,112,116,91,53,55,27,101,92,9,107,37,60],'literal weights')
 g.require(max(E)==2050 and len(set(E))==22,'targets')
 a0=[];a1=[];a2=[]
 for row in delivered:
  c={};l={};q={}
  for m,p in g.grouping(row).items():
   d=sum(m);g.require(d<=2,'quadratic row')
   if d==0:c=p
   elif d==1:l[m.index(1)]=p
   else:q[tuple(i for i,e in enumerate(m)for _ in range(e))]=p
  a0.append(c);a1.append(l);a2.append(q)
 g.require((sum(bool(x)for x in a0),sum(map(len,a1)),sum(map(len,a2)))==(6,36,43),'85 channel records')
 pairs=sorted({p for row in a2 for p in row});allpairs=list(combinations_with_replacement(range(31),2))
 g.require(len(pairs)==39,'active pairs')
 for p in pairs:g.require([q for q in allpairs if w[q[0]]+w[q[1]]==w[p[0]]+w[p[1]]]==[p],'pair isolation')
 expected=[{}for _ in range(3)]
 for k in range(22):
  if a0[k]:expected[0][E[k]]={m:2*c for m,c in a0[k].items()}
  for i,p in a1[k].items():
   g.require(w[i]<=E[k],'linear span')
   g.require(all(w[j]+E[k]-w[i]!=E[l]for l in range(22)if k!=l for j in range(31)),'linear cross')
   pos=E[k]-w[i];g.require(pos not in expected[1],'linear duplicate');expected[1][pos]={m:2*c for m,c in p.items()}
  for(i,j),p in a2[k].items():
   g.require(w[i]+w[j]<=E[k],'quadratic span')
   g.require(all(w[a]+w[b]+E[k]-w[i]-w[j]!=E[l]for l in range(22)if k!=l for a,b in allpairs),'quadratic cross')
   pos=E[k]-w[i]-w[j];g.require(pos not in expected[2],'quadratic duplicate');expected[2][pos]={m:(2 if i==j else 1)*c for m,c in p.items()}
 for ch in kernels['kernels']:
  actual={t['exponent']:{tuple(v['port_powers']):v['integer']for v in t['coefficient']}for t in ch['terms']}
  g.require(actual==expected[ch['degree']],'literal kernel mismatch')
 return source,layout,kernels,rows,delivered,order,w,E,a0,a1,a2,pairs

HEADER='''open Polynomial SidonPositions SelectiveQuadraticCoding DegreeSeparatedCoding
open scoped BigOperators
set_option maxRecDepth 20000
set_option maxHeartbeats 8000000
set_option synthInstance.maxSize 512
variable {R : Type*} [CommRing R]
'''

def render():
 source,layout,kernels,rows,delivered,order,w,E,a0,a1,a2,pairs=read()
 indices=[[pairs.index(p)for p in sorted(row)]for row in a2]
 geometry=['''import DiophantineConsistency.SplitGeometry59
/-! # Literal H2082 weight, target and same-degree isolation certificate
Generated by tools/generate_gap_certificate66.py from SHA-pinned inert JSON.
Source e4f50dbede42c421defa2d7d36268413351dd1e023763c584ea34f3b9a827957.
All31 coordinates are actual source inputs; there is no dummy coordinate. -/
namespace DiophantineConsistency.GapCertificate66
''',HEADER,
'''abbrev weights : Fin 31 → ℕ := SplitCertificate59.weights
theorem weights_injective : Function.Injective weights := SplitCertificate59.weights_injective
theorem maximum_weight : ∀ i, weights i ≤ 116 := SplitCertificate59.maximum_weight
theorem weights_positive : ∀ i, 0 < weights i := SplitCertificate59.weights_positive
''',
 'def targets : Fin 22 → ℕ := '+g.vec(list(map(str,E)))+'\n',
 'theorem targets_injective : Function.Injective targets := by decide +kernel\n',
 'def activePair : Fin 39 → PairIndex 30 :=\n  '+g.vec(list(map(g.pairlit,pairs)))+'\n',
 'theorem active_isolated : ∀ i, Isolated weights (activePair i) := by\n  unfold Isolated\n  decide +kernel\n',
 'def linearSupport : Fin 22 → Finset (Fin 31) :=\n  '+g.vec([g.fset(sorted(p))for p in a1])+'\n',
 'def quadraticIndices : Fin 22 → Finset (Fin 39) :=\n  '+g.vec([g.fset(p)for p in indices])+'\n',
 'def quadraticSupport (k : Fin 22) : Finset (PairIndex 30) :=\n  (quadraticIndices k).image activePair\n']
 old=(ROOT/'Lean/DiophantineConsistency/SplitGeometry59.lean').read_text()
 geometry.append(old[old.index('theorem linear_span'):old.index('/-- The31 actual input positions')])
 geometry.append('''def inputPositions : Finset ℕ := Finset.univ.image weights
def targetPositions : Finset ℕ := Finset.univ.image targets
theorem inputPositions_card : inputPositions.card = 31 := by decide +kernel
theorem targetPositions_card : targetPositions.card = 22 := by decide +kernel
theorem inputPositions_range : inputPositions ⊆ Finset.range 117 := by decide +kernel
theorem maximum_target : ∀ k, targets k ≤ 2050 := by decide +kernel
theorem targetPositions_range : targetPositions ⊆ Finset.range 2083 := by decide +kernel
theorem inputPositions_zero : 0 ∉ inputPositions := by decide +kernel
end DiophantineConsistency.GapCertificate66
''')
 ca0=[g.coefficient(p)for p in a0]
 ca1=[g.function([(i,g.coefficient(p))for i,p in sorted(row.items())])for row in a1]
 ca2=[g.function([(g.pairlit(i),g.coefficient(p))for i,p in sorted(row.items())],'p')for row in a2]
 cert=['''import DiophantineConsistency.GapGeometry66
import DiophantineConsistency.GapSource66
/-! # The H2082 degree-separated coefficients bind to the frozen source66 rows
Generated by tools/generate_gap_certificate66.py from85 pinned records.
The source is GapSource66.rows itself, not a second transcription. -/
namespace DiophantineConsistency.GapCertificate66
''',HEADER,
 'def rowOrder : Fin 22 → Fin 22 := '+g.vec(list(map(str,order)))+'\n',
 'theorem rowOrder_surjective : Function.Surjective rowOrder := by decide +kernel\n',
 '''def deliveredRows (ports : Fin 4 → R) (x : Fin 31 → R) (k : Fin 22) : R :=
  GapSource66.rows ports x (rowOrder k)

 theorem delivered_zero_iff (ports : Fin 4 → R) (x : Fin 31 → R) :
    (∀ k, deliveredRows ports x k = 0) ↔ ∀ k, GapSource66.rows ports x k = 0 := by
  constructor
  · intro h k
    obtain ⟨l,rfl⟩ := rowOrder_surjective k
    exact h l
  · intro h k
    exact h (rowOrder k)
''',
 'def constantCoefficient (ports : Fin 4 → R) : Fin 22 → R :=\n  '+g.vec(ca0)+'\n',
 'def linearCoefficient (ports : Fin 4 → R) : Fin 22 → Fin 31 → R :=\n  '+g.vec(ca1)+'\n',
 'def quadraticCoefficient (ports : Fin 4 → R) : Fin 22 → PairIndex 30 → R :=\n  '+g.vec(ca2)+'\n']
 cert.append('''theorem rowValue_eq_source (ports : Fin 4 → R) (x : Fin 31 → R) (k : Fin 22) :
    value (constantCoefficient ports k) (linearSupport k) (linearCoefficient ports k)
      (quadraticSupport k) (quadraticCoefficient ports k) x = deliveredRows ports x k := by
  fin_cases k <;>
    dsimp [constantCoefficient, linearCoefficient, quadraticCoefficient, linearSupport,
      quadraticSupport, quadraticIndices, activePair, deliveredRows, GapSource66.rows, rowOrder] <;>
    simp [value, linearValue, rowValue] <;> ring
''')
 cert.append('''theorem coeff_source_rows (ports : Fin 4 → R) (x : Fin 31 → R) (k : Fin 22) :
    (product weights x (constantCoefficient ports) linearSupport (linearCoefficient ports)
      quadraticSupport (quadraticCoefficient ports) targets).coeff (targets k) =
        2*deliveredRows ports x k := by
  rw [coeff_product weights weights_injective x (constantCoefficient ports)
    linearSupport (linearCoefficient ports) quadraticSupport (quadraticCoefficient ports)
    targets targets_injective linear_span linear_cross quadratic_span quadratic_isolated
    quadratic_cross k,rowValue_eq_source]

theorem coeff_zero_iff_source_zero (ports : Fin 4 → ℤ) (x : Fin 31 → ℤ) :
    (∀ k, (product weights x (constantCoefficient ports) linearSupport (linearCoefficient ports)
      quadraticSupport (quadraticCoefficient ports) targets).coeff (targets k) = 0) ↔
        ∀ k, GapSource66.rows ports x k = 0 := by
  rw [← delivered_zero_iff]
  constructor
  · intro h k
    have hh := h k
    rw [coeff_source_rows] at hh
    exact (mul_eq_zero.mp hh).resolve_left (by norm_num : (2:ℤ)≠0)
  · intro h k
    rw [coeff_source_rows,h k,mul_zero]
end DiophantineConsistency.GapCertificate66
''')
 return {'GapGeometry66.lean':'\n'.join(geometry),'GapCertificate66.lean':'\n'.join(cert)}

if __name__=='__main__':
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');args=ap.parse_args()
 for name,text in render().items():
  path=ROOT/'Lean/DiophantineConsistency'/name
  if args.check:g.require(path.read_text()==text,'generated certificate differs '+name)
  else:path.write_text(text)
 print(json.dumps({'status':'PASS'if args.check else'GENERATED','records':85,'channels':[6,36,43],'pins':PINS},sort_keys=True))
