#!/usr/bin/env python3
"""Supply finite degree labels for the pinned H2082 natural DAG.

The Lean kernel verifies every label against actual circuit data. These are
upper bounds; the separate finalizer proof recovers cancellation.
"""
import argparse
import importlib.util
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location(
    'circuit66', ROOT / 'tools/generate_gap_circuit66.py')
g = importlib.util.module_from_spec(spec)
spec.loader.exec_module(g)


def render():
    dag, _ = g.read('natural')
    degree = []
    for n in dag['nodes']:
        kind = n['kind']
        if kind == 'variable':
            d = 1
        elif kind in ('literal', 'fixed'):
            d = 0
        elif kind == 'mul':
            d = degree[n['left']] + degree[n['right']]
        else:
            d = max(degree[n['left']], degree[n['right']])
        degree.append(d)
    g.require(degree[-1] == 2063116, 'naive output degree')
    labels = '[\n' + ',\n'.join(
        '    ' + ','.join(map(str, degree[i:i+16]))
        for i in range(0, len(degree), 16)) + ']'
    return f'''import DiophantineConsistency.ArithmeticDAGDegree
import DiophantineConsistency.GapCircuitSteps66

/-! # Checked degree labels for the literal H2082 natural DAG
Generated by tools/generate_gap_degree66.py from SHA-pinned inert data.
Labels certify upper bounds and deliberately make no exact-degree claim. -/
namespace DiophantineConsistency.GapCircuitDegree66
open ArithmeticDAG GapCircuitSteps66
set_option maxRecDepth 30000
set_option maxHeartbeats 3000000

def naturalDegrees : List ℕ :=
  {labels}

def naturalDegree (i : ℕ) : ℕ := naturalDegrees.getD i 0

theorem naturalDegrees_length : naturalDegrees.length=484 := by decide +kernel

theorem natural_certificate :
    DegreeCertificate GapCircuit66.naturalNodes (fun _ => 1) naturalDegree := by
  decide +kernel

/-- Arbitrary polynomial inputs of degree at most one, with any fixed integers. -/
theorem naturalRegister_degree_le {{σ : Type*}} (p : Fin 11 → ℤ)
    (x : Fin 9 → MvPolynomial σ ℤ) (hx : ∀ i,(x i).totalDegree ≤ 1)
    (i : ℕ) (hi : i<484) :
    (naturalRegister (fun k => MvPolynomial.C (p k)) x i).totalDegree ≤ naturalDegree i :=
  value_degree_le p x (fun _ => 1) hx GapCircuit66.naturalNodes
    GapCircuit66.natural_topological naturalDegree natural_certificate i
      (by simpa only [GapCircuit66.natural_length] using hi)

/-- The naive bound is weaker than the cancellation-aware finalizer bound. -/
theorem naturalPolynomial_degree_le_naive (p : Fin 11 → ℤ) :
    (GapCircuit66.naturalPolynomial p).totalDegree ≤ 2063116 :=
  naturalRegister_degree_le p MvPolynomial.X (fun _ => by simp) 483 (by decide)

end DiophantineConsistency.GapCircuitDegree66
'''


if __name__ == '__main__':
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--check', action='store_true')
    args = ap.parse_args()
    p = ROOT / 'Lean/DiophantineConsistency/GapCircuitDegree66.lean'
    out = render()
    if args.check:
        g.require(p.read_text() == out, 'generated degree certificate differs')
    else:
        p.write_text(out)
    print(json.dumps({'status': 'PASS' if args.check else 'GENERATED',
                      'labels': 484, 'naive_upper_bound': 2063116}, sort_keys=True))
