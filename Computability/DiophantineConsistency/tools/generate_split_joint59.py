#!/usr/bin/env python3
"""Check/emit literal joint-power DAGs and their universal rewrite certificates."""
from pathlib import Path
import argparse,hashlib,json,importlib.util,collections
ROOT=Path(__file__).resolve().parents[1]
DATA=ROOT/'candidates/split116-joint-powers'
spec=importlib.util.spec_from_file_location('parent_generator',ROOT/'tools/generate_split_circuit59.py')
g=importlib.util.module_from_spec(spec);spec.loader.exec_module(g)
PINS={'positive':'83a14b00d3312f08da5ee578ab4926a2c36bff8f317145f81fd3c4b4edc60b87',
      'natural':'06177528b9791a93588d3843a9f894b9d8abf299c25a0faa569b3f422925562c'}
REWRITE_PINS={'positive':'84aea2496f184c5b5640c4555a82a02fd33d3f878efbd62078891244645c8b22',
              'natural':'0c2a7599e10ffbc4383903c492fc34082ceab8f24366343c87c88b41ff32f760'}
PARENT_PINS=dict(g.PINS)
require=g.require
cache={}

def read_child(domain):
 raw=(DATA/f'split_116_{domain}.json').read_bytes()
 require(hashlib.sha256(raw).hexdigest()==PINS[domain],'child pin')
 d=json.loads(raw);ns=d['nodes'];out=d['output']
 require(d['schema']=='free-carrier-split-nine-adjunct-v1'and d['variables']==g.VARIABLES,'schema/input')
 parents=[[]for _ in ns]
 for i,n in enumerate(ns):
  k=n['kind']
  if k in ['add','sub','mul']:
   require(set(n)=={'kind','left','right'},'binary schema')
   for j in[n['left'],n['right']]:
    require(type(j)is int and 0<=j<i,'topology');parents[j].append(i)
  elif k=='variable':require(set(n)=={'kind','name'}and n['name']in g.VARIABLES,'input')
  elif k=='fixed':require(set(n)=={'kind','name'}and n['name']in g.FIXED,'fixed')
  elif k=='literal':require(set(n)=={'kind','value'}and type(n['value'])is int,'literal')
  else:raise ValueError('node kind')
 require(out==len(ns)-1,'output')
 live=set();todo=[out]
 while todo:
  i=todo.pop()
  if i in live:continue
  live.add(i)
  if ns[i]['kind']in['add','sub','mul']:todo.extend([ns[i]['left'],ns[i]['right']])
 require(live==set(range(len(ns))),'all live')
 counts=collections.Counter(n['kind']for n in ns)
 expected={'positive':{'add':162,'sub':22,'mul':272},'natural':{'add':170,'sub':21,'mul':272}}[domain]
 require(d['operation_counts']==expected and d['total_operations']==sum(expected.values()),'metadatacounts')
 require(all(counts[k]==v for k,v in expected.items()),'actualcounts')
 require(counts['variable']==9 and counts['fixed']==12 and counts['literal']==14,'leafcounts')
 require({n['name']for n in ns if n['kind']=='variable'}==set(g.VARIABLES),'all inputs')
 require({n['name']for n in ns if n['kind']=='fixed'}==set(g.FIXED),'all fixed')
 require(all(type(j)is int and 0<=j<len(ns)for j in d['named_nodes'].values()),'namedbounds')
 return d,[min(parents[i])for i in range(out)]

def labels(ns,base):
 es=[0]*len(ns)
 for i,n in enumerate(ns):
  if i==base:es[i]=1
  elif n['kind']=='mul'and es[n['left']]and es[n['right']]:es[i]=es[n['left']]+es[n['right']]
 return es

def certificate(domain):
 old,_=g.read(domain);new,_=read_child(domain)
 raw=(DATA/f'{domain}_rewrite.json').read_bytes()
 require(hashlib.sha256(raw).hexdigest()==REWRITE_PINS[domain],'rewrite pin')
 r=json.loads(raw)
 require(r['parent_sha256']==PARENT_PINS[domain]and r['child_sha256']==PINS[domain],'receipt binding')
 ob=r['base_node'];nb=r['retained_remap'][str(ob)]
 require(ob==old['named_nodes']['B']and nb==new['named_nodes']['B'],'base binding')
 ol=labels(old['nodes'],ob);nl=labels(new['nodes'],nb)
 require(sum(e!=0 for e in ol)==108 and sum(e!=0 for e in nl)==91,'powercounts')
 inverse=[0]*len(new['nodes'])
 inverse_sources=collections.defaultdict(list)
 for i,j in r['retained_remap'].items():inverse_sources[j].append(int(i))
 for j,e in enumerate(nl):
  if e==0 or j==nb:
   candidates=inverse_sources[j];require(len(candidates)==1,'retained inverse')
   inverse[j]=candidates[0]
 def related(i,j):return 0<=i<len(ol)and(inverse[j]==i if nl[j]==0 else ol[i]==nl[j])
 for j,n in enumerate(new['nodes']):
  if nl[j]==0 or j==nb:
   i=inverse[j];require(0<=i<len(ol),'oldindex')
   o=old['nodes'][i];require(n['kind']==o['kind'],'samekind')
   if n['kind']in['add','sub','mul']:
    require(related(o['left'],n['left'])and related(o['right'],n['right']),'reference correspondence')
   else:require(n==o,'leaf correspondence')
  else:require(n['kind']=='mul'and nl[n['left']]and nl[n['right']]and nl[j]==nl[n['left']]+nl[n['right']],'new powerstep')
 require(nl[-1]==0 and inverse[-1]==old['output'],'outputbinding')
 cache[domain]=(old,new,r,ob,nb,ol,nl,inverse)
 return cache[domain]

def render_rewrite():
 out=['''import DiophantineConsistency.ArithmeticDAGPowers
import DiophantineConsistency.SplitCircuit59
import DiophantineConsistency.SplitJointCircuit59

/-! # Exact universal equality of the joint-power and parent circuits
Generated by tools/generate_split_joint59.py from pinned DAG and rewrite JSON.
Every label and retained reference is checked by the Lean kernel. -/
namespace DiophantineConsistency.SplitJointPower59
open ArithmeticDAG
namespace Parent
abbrev positiveNodes := SplitCircuit59.positiveNodes
abbrev naturalNodes := SplitCircuit59.naturalNodes
end Parent
namespace Child
abbrev positiveNodes := SplitJointCircuit59.positiveNodes
abbrev naturalNodes := SplitJointCircuit59.naturalNodes
end Child
set_option maxRecDepth 20000
set_option maxHeartbeats 12000000
set_option synthInstance.maxSize 512
''']
 for domain in PINS:
  old,new,r,ob,nb,ol,nl,im=cache[domain]
  for name,vs in [('oldLabels',ol),('newLabels',nl),('indexMap',im)]:
   out.append(f'def {domain}_{name}Data : List ℕ := ['+','.join(map(str,vs))+']\n')
   out.append(f'def {domain}_{name} (i : ℕ) : ℕ := {domain}_{name}Data.getD i 0\n')
  out.append(f'''private theorem {domain}_old_steps : ∀ i : Fin {len(ol)},
    i.val ≠ {ob} → {domain}_oldLabels i.val ≠ 0 →
      PowerStep Parent.{domain}Nodes {domain}_oldLabels i.val := by decide +kernel

private theorem {domain}_new_steps : ∀ i : Fin {len(nl)},
    PowerRewriteStep Parent.{domain}Nodes Child.{domain}Nodes
      {domain}_oldLabels {domain}_newLabels {domain}_indexMap {nb} i.val := by decide +kernel

theorem {domain}Value_eq_parent {{R : Type*}} [CommRing R] (p : Fin 12 → R) (x : Fin 9 → R) :
    SplitJointCircuit59.{domain}Value p x = SplitCircuit59.{domain}Value p x := by
  apply value_eq_of_powerRewrite p x Parent.{domain}Nodes Child.{domain}Nodes
    SplitCircuit59.{domain}_topological SplitJointCircuit59.{domain}_topological
    {domain}_oldLabels {domain}_newLabels {domain}_indexMap
    {ob} {nb} {old['output']} {new['output']}
  · decide +kernel
  · decide +kernel
  · decide +kernel
  · intro i hi
    exact {domain}_old_steps ⟨i,by simpa only [Parent.{domain}Nodes,SplitCircuit59.{domain}_length] using hi⟩
  · intro i hi
    exact {domain}_new_steps ⟨i,by simpa only [Child.{domain}Nodes,SplitJointCircuit59.{domain}_length] using hi⟩
  · rw [Child.{domain}Nodes,SplitJointCircuit59.{domain}_length]
    decide
  · decide +kernel
  · decide +kernel

theorem {domain}Polynomial_eq_parent (p : Fin 12 → ℤ) :
    SplitJointCircuit59.{domain}Polynomial p = SplitCircuit59.{domain}Polynomial p :=
  {domain}Value_eq_parent (fun i => MvPolynomial.C (p i)) MvPolynomial.X
''')
 out.append('end DiophantineConsistency.SplitJointPower59\n')
 return '\n'.join(out)

def main():
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--check',action='store_true');a=ap.parse_args()
 for domain in PINS:certificate(domain)
 g.PINS=PINS;g.read=read_child
 text=g.render().replace('DiophantineConsistency.SplitCircuit59','DiophantineConsistency.SplitJointCircuit59')
 text=text.replace('# Literal compact54-sharp split116 binary circuit','# Literal joint-power compact54-sharp split116 binary circuit').replace('tools/generate_split_circuit59.py','tools/generate_split_joint59.py')
 files={ROOT/'Lean/DiophantineConsistency/SplitJointCircuit59.lean':text,
        ROOT/'Lean/DiophantineConsistency/SplitJointPower59.lean':render_rewrite()}
 for p,t in files.items():
  if a.check:require(p.read_text()==t,'generated Lean differs '+str(p))
  else:p.write_text(t)
 print(json.dumps({'status':'PASS'if a.check else'GENERATED','positive':456,'natural':463,'pins':PINS,'rewrite_pins':REWRITE_PINS},sort_keys=True))
if __name__=='__main__':main()
