"""Render the complete literal residual list, without symbolic abbreviations."""
import argparse
import json
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def term(coefficient, monomial):
    sign = "-" if coefficient < 0 else "+"
    n = abs(coefficient)
    body = str(n) if n != 1 or not monomial else ""
    width = 4.9 * len(body)
    for variable, exponent in sorted(Counter(monomial).items()):
        body += "X_{" + str(variable) + "}"
        width += 9.0 + 3.7 * len(str(variable))
        if exponent > 1:
            body += "^{" + str(exponent) + "}"
            width += 5.5
    return sign, body, width + 11.0


def render():
    data = json.loads((ROOT / "direct/natural358/equation.json").read_text())
    if len(data["residuals"]) != 275 or len(data["variables"]) != 358:
        raise ValueError("Unexpected final residual census")
    lines = [
        "% Generated by code/render_residuals.py from direct/natural358/equation.json.",
        "% Complete integer coefficients; no omitted terms or symbolic constants.",
        r"\begingroup\small",
        r"\setlength{\jot}{2pt}",
        r"\allowdisplaybreaks[4]",
        r"\begin{align*}",
    ]
    for index, row in enumerate(data["residuals"]):
        pieces, current, width = [], [], 0.0
        for coefficient, monomial in row["terms"]:
            sign, body, size = term(coefficient, monomial)
            if current and width + size > 408:
                pieces.append(current)
                current, width = [], 0.0
            current.append((sign, body))
            width += size
        if current:
            pieces.append(current)
        for part, piece in enumerate(pieces):
            prefix = "r_{" + str(index) + "} &= " if part == 0 else r"&\quad "
            text = ""
            for j, (sign, body) in enumerate(piece):
                if part == 0 and j == 0:
                    text += ("-" if sign == "-" else "") + body
                else:
                    text += " " + sign + " " + body
            ending = r" \\[3pt]" if part == len(pieces) - 1 else r" \\*"
            if index == len(data["residuals"]) - 1 and part == len(pieces) - 1:
                ending = ""
            lines.append(prefix + text + ending)
    lines.extend([r"\end{align*}", r"\endgroup", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = render()
    path = ROOT / "residuals.tex"
    if args.check:
        if path.read_text() != result:
            raise ValueError("Printed residuals differ from the literal equation")
        print("PASS: the printed residuals match the literal equation.")
    else:
        path.write_text(result)
        print("Wrote the complete residual appendix.")
