#!/usr/bin/env python3
"""Render literal equation appendices and metrics; --check binds the report to data.

Only the Python standard library is needed. No algebra is delegated to TeX.
The exact polynomial expansion is checked separately by arithmetic/verify.py.
"""
from pathlib import Path
from collections import Counter
import argparse
import hashlib
import json

ROOT = Path(__file__).resolve().parent


def term_tex(coefficient, indices, first=False):
    sign = "-" if coefficient < 0 else ("" if first else "+")
    magnitude = abs(coefficient)
    factors = []
    for index, exponent in sorted(Counter(indices).items()):
        atom = "x_{%d}" % index
        if exponent != 1:
            atom += "^{%d}" % exponent
        factors.append(atom)
    coeff = str(magnitude) if magnitude != 1 or not factors else ""
    return sign + coeff + "".join(factors)


def residuals(relative, symbol):
    path = ROOT / relative
    raw = path.read_bytes()
    equation = json.loads(raw)
    rows = equation["residuals"]
    lines = [
        "% Generated by render_report_inputs.py; do not edit manually.",
        "% Source SHA-256: " + hashlib.sha256(raw).hexdigest(),
        r"\begingroup",
        r"\footnotesize",
        r"\setlength{\jot}{3pt}",
        r"\allowdisplaybreaks[4]",
        r"\begin{align*}",
    ]
    for j, row in enumerate(rows):
        terms = row["terms"]
        for start in range(0, len(terms), 6):
            chunk = terms[start:start + 6]
            lead = "%s_{%d} &={}" % (symbol, j) if start == 0 else r"&\quad{}"
            rendered = " ".join(term_tex(c, inds, start + k == 0)
                                for k, (c, inds) in enumerate(chunk))
            end = start + 6 >= len(terms)
            suffix = (r" \\[3pt]" if end else r" \\*")
            if j == len(rows) - 1 and end:
                suffix = ""
            lines.append(lead + rendered + suffix)
    lines += [r"\end{align*}", r"\endgroup", ""]
    return "\n".join(lines)


