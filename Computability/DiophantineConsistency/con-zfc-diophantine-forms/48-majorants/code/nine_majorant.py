"""A sparse-source Jones tail with a sharper polynomial radical majorant.

The majorant and h-weight are proved in HIGHER_MAJORANT.md.
The certificate evaluates D^16 times the primary polynomial, not the same polynomial.
Every expression here is a polynomial; e is an explicit product, not a quotient.
"""

def finish(d,v,b,B,N,R,cap,certificate=False):
    c,add,mul,sub,pw,save=d.c,d.add,d.mul,d.sub,d.pow,d.save
    U=save('U',mul(pw(N,2),v['w']))
    Y=save('Y',mul(pw(N,2),v['s']))
    M=save('M',mul(R,Y))
    P=save('P',mul(c(2),pw(M,2),U))
    K=save('K',add(R,c(1),mul(v['h'],sub(P,c(1)))))
    A=save('A',mul(M,add(U,c(1))))
    B1=add(mul(c(2),R),c(1))
    W1=mul(b,v['w'])
    C=save('C',add(B1,W1,v['phi']))
    J=save('J',sub(mul(c(4),A),c(5)))
    Q=save('Q',sub(mul(c(3),W1,C),mul(c(2),sub(pw(W1,2),c(1)))))
    Am1=sub(pw(A,2),c(1))
    D=save('D',add(mul(Am1,pw(C,2)),c(1)))
    e=save('e',mul(v['i'],J,C))
    E=save('E',mul(e,D,C))
    F=save('F',add(mul(Am1,pw(E,2)),c(1)))
    G=save('G',add(A,mul(F,sub(add(mul(C,D),c(1)),A))))
    H=save('H',add(B1,mul(v['j'],C)))
    I=save('I',add(mul(sub(pw(G,2),c(1)),pw(H,2)),c(1)))
    a0=save('a0',add(sub(pw(mul(P,K),2),pw(K,2)),c(1)))
    a1=save('a1',mul(c(2048**2),D,F,I))
    u=save('u',mul(J,F))
    vc=save('v',add(mul(Q,F),mul(J,sub(H,C))))
    m=save('m',sub(mul(sub(pw(K,2),mul(c(4),pw(sub(C,mul(K,Y)),2))),cap),mul(c(8),v['g'],pw(K,2))))
    L=save('major_L',sub(add(mul(C,D),c(1)),A))
    Nstar=save('major_Nstar',add(mul(c(2),G),L))
    Dm1=sub(D,c(1))
    e2=pw(e,2)
    N2=save('major_N2',mul(c(2),e2,Dm1,L))
    N1=save('major_N1',add(mul(D,N2),mul(c(3),C)))
    N3=save('major_N3',mul(c(2),e2,sub(L,C)))
    N4=save('major_N4',mul(c(2),e2,C))
    corr=save('major_correction',add(mul(c(256),v['i'],add(e2,c(2))),c(2048)))
    tpoly=sub(sub(mul(c(1024),pw(D,2)),mul(c(512),D)),c(128))
    T=save('major_T',add(mul(e,sub(sub(sub(sub(mul(tpoly,Nstar),mul(c(64),N1)),mul(c(40),N2)),mul(c(28),N3)),mul(c(21),N4))),corr))
    Bgap=save('major_Bgap',add(mul(c(2),P,add(P,R)),c(1)))
    V=save('Vmajor',add(mul(T,H),Bgap))
    Md=save('Mdiv',add(Q,H))
    Om=save('Omega',mul(u,m))
    E0=save('E0',sub(add(mul(u,add(v['n'],Md)),vc),mul(c(2),Om,Md)))
    Th=save('Theta',sub(E0,mul(Om,v['h'],V)))
    if certificate:
        D2,D3,D4,D8,D16=(pw(D,k) for k in (2,3,4,8,16))
        r1=save('major_r1',sub(c(3),A))
        r2=save('major_r2',add(mul(c(3),C,D),r1))
        r3=save('major_r3',add(mul(c(2),e2,sub(A,c(1)),D2),r2))
        r4=save('major_r4',add(mul(c(2),e2,sub(sub(c(1),A),C),D3),r3))
        tn=save('major_tnum',sub(sub(sub(sub(sub(sub(mul(c(1024),pw(D,6)),mul(c(512),pw(D,5))),mul(c(128),D4)),mul(c(64),D3)),mul(c(40),D2)),mul(c(28),D)),c(21)))
        dn=save('major_dnum',add(mul(c(33792),pw(D,5)),mul(c(10560),D4),mul(c(4928),D3),mul(c(2464),D2),mul(c(1176),D),c(441)))
        rn=save('major_Rnum',add(mul(e,add(mul(c(64),r1,D3),mul(c(40),r2,D2),mul(c(28),r3,D),mul(c(21),r4))),mul(corr,D4)))
        X=save('major_X',mul(e2,D3,Dm1))
        deltaT8=save('deltaT8',add(mul(e2,dn,pw(Nstar,2)),mul(c(1024**2),D8,sub(mul(X,pw(L,2)),mul(c(4),D,G,add(mul(C,D),c(1))))),mul(c(2),e,tn,Nstar,rn),pw(rn,2)))
        deltaV8=save('deltaV8',add(mul(pw(H,2),deltaT8),mul(c(2048**2),D,F,D8,sub(pw(H,2),c(1))),mul(D8,add(mul(c(2),T,H,Bgap),pw(Bgap,2)))))
        other=save('inner_other',sub(sub(pw(E0,2),mul(c(2),E0,Om,v['h'],V)),mul(pw(Om,2),a0)))
        inn8=save('inner_D8',add(mul(D8,other),mul(pw(Om,2),pw(v['h'],2),deltaV8)))
        return sub(pw(inn8,2),mul(c(4),D16,pw(Om,4),pw(v['h'],2),a0,a1))
    inn=save('inner',sub(pw(Th,2),mul(pw(Om,2),add(a0,mul(pw(v['h'],2),a1)))))
    return sub(pw(inn,2),mul(c(4),pw(Om,4),pw(v['h'],2),a0,a1))
