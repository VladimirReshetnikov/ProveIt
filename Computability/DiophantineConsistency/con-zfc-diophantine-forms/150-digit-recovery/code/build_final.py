#!/usr/bin/env python3
"""Reconstruct the final quartic from frozen, invertible integer maps.

Only the Python standard library is needed. The search that chose these maps
is not needed to reconstruct the polynomial. Default: compare, without edits.
"""
import argparse
import copy
import hashlib
import json
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

def need(ok, message):
    if not ok:
        raise ValueError(message)

def blob(obj):
    return (json.dumps(obj, sort_keys=True, separators=(',', ':')) + '\n').encode()

def load(path):
    return json.loads(path.read_text())

def collect(terms):
    p = defaultdict(int)
    for coefficient, monomial in terms:
        need(type(coefficient) is int, 'noninteger coefficient')
        need(all(type(i) is int and i >= 0 for i in monomial), 'bad monomial')
        p[tuple(sorted(monomial))] += coefficient
    return {m: c for m, c in p.items() if c}

def terms(p):
    return [[c, list(m)] for m, c in sorted(p.items())]

def linear_add(p, q, k):
    result = dict(p)
    for m, c in q.items():
        value = result.get(m, 0) + k*c
        if value:
            result[m] = value
        else:
            result.pop(m, None)
    return result

def shear(p, i, j, k):
    """Substitute old x_j = new x_j + k new x_i."""
    result = defaultdict(int)
    for m, c in p.items():
        block = {(): c}
        for v in m:
            next_block = defaultdict(int)
            for t, a in block.items():
                next_block[tuple(sorted(t+(v,)))] += a
                if v == j:
                    next_block[tuple(sorted(t+(i,)))] += k*a
            block = next_block
        for t, a in block.items():
            result[t] += a
    return {m: c for m, c in result.items() if c}

def sos(rows):
    result = defaultdict(int)
    for p in rows:
        a = list(p.items())
        for i, (m, c) in enumerate(a):
            for j in range(i, len(a)):
                n, d = a[j]
                result[tuple(sorted(m+n))] += c*d*(1 if i == j else 2)
    return {m: c for m, c in result.items() if c}

def tex_term(m, c, initial=False):
    powers = Counter(m)
    word = '\\,'.join('z_{'+str(i+1)+'}'+('^{'+str(e)+'}' if e > 1 else '')
                      for i, e in sorted(powers.items()))
    magnitude = str(abs(c)) if abs(c) != 1 or not word else ''
    body = magnitude + ('\\,' if magnitude and word else '') + word
    return ('-' if c < 0 else ('' if initial else '+')) + body

def tex_rows(rows):
    out = ['% Complete final quadratic residuals. Generated by code/build_final.py.']
    for index, p in enumerate(rows, 1):
        a = sorted(p.items())
        out.append('\\begin{equation*}\\begin{aligned}')
        # Four terms per line fits every actual row at the report font size.
        for start in range(0, len(a), 4):
            text = ' '.join(tex_term(m, c, initial=(start == 0 and j == 0))
                            for j, (m, c) in enumerate(a[start:start+4]))
            left = 'R_{'+str(index)+'}&=' if start == 0 else '&\\quad '
            out.append(left+text+(' \\\\' if start+4 < len(a) else ''))
        out.append('\\end{aligned}\\end{equation*}')
    return '\n'.join(out)+'\n'

def build():
    source_path = ROOT/'source/equation247_weak/equation.json'
    source_bytes = source_path.read_bytes()
    need(hashlib.sha256(source_bytes).hexdigest() ==
         '14b814894521add09fb6847e59de2d802f2e466f6f9fc724f346a21461125a6b',
         'raw quartic differs from the audited endpoint')
    source = json.loads(source_bytes)
    n = len(source['variables'])
    rows = [collect(r['terms']) for r in source['residuals']]
    initial = copy.deepcopy(rows)
    coordinate = load(ROOT/'certificates/coordinate_shears.json')['history']
    row_ops = load(ROOT/'certificates/row_operations.json')
    matrix = [{(i,): 1} for i in range(n)]
    for step in coordinate:
        i, j, k = step['i'], step['j'], step['k']
        need(all(type(a) is int for a in (i, j, k)) and 0 <= i < n and
             0 <= j < n and i != j, 'invalid coordinate shear')
        rows = [shear(r, i, j, k) for r in rows]
        matrix = [shear(r, i, j, k) for r in matrix]
    for i, j, k in row_ops:
        need(all(type(a) is int for a in (i, j, k)) and 0 <= i < len(rows) and
             0 <= j < len(rows) and i != j, 'invalid residual operation')
        rows[i] = linear_add(rows[i], rows[j], k)
    reverse = copy.deepcopy(rows)
    for i, j, k in reversed(row_ops):
        reverse[i] = linear_add(reverse[i], reverse[j], -k)
    for step in reversed(coordinate):
        reverse = [shear(r, step['i'], step['j'], -step['k']) for r in reverse]
    need(reverse == initial, 'complete inverse identity failed')
    need(max(len(m) for r in rows for m in r) == 2, 'residual degree changed')
    polynomial = sos(rows)
    used = {i for m in polynomial for i in m}
    need(used == set(range(n)), 'an advertised coordinate is unused')
    metrics = {
        'variables': n, 'domain': 'unrestricted integers', 'quadratic_residuals': len(rows),
        'degree': max(map(len, polynomial)), 'collected_monomials': len(polynomial),
        'coefficient_height': max(map(abs, polynomial.values())),
        'residual_height': max(abs(c) for r in rows for c in r.values()),
        'residual_monomials': sum(map(len, rows)),
        'coordinate_shears': len(coordinate), 'residual_row_operations': len(row_ops),
    }
    equation = {
        'schema': 'proveit_quadratic_residuals_v1', 'domain': 'unrestricted integers',
        'polynomial': 'sum(square(row) for row in residuals)',
        'source_snapshot': '3ecd6a6cf53d47519228328567f45fb7ee9781d9',
        'variables': [{'name': 'z_'+str(i+1), 'kind': 'unrestricted_integer',
                       'pre_shear_origin': v} for i, v in enumerate(source['variables'])],
        'residuals': [{'label': 'R_'+str(i+1), 'terms': terms(r)} for i, r in enumerate(rows)],
    }
    expanded = {'schema': 'expanded_integer_polynomial_v1', 'variables': n,
                'domain': 'unrestricted integers', 'terms': terms(polynomial)}
    mapping = {'schema': 'integral_coordinate_map_v1', 'determinant': 1,
               'meaning': 'Old coordinate i equals the polynomial at index i in new z coordinates.',
               'old_coordinates': [terms(p) for p in matrix]}
    readable = '\n'.join('R_'+str(i+1)+' = '+str(terms(r)) for i, r in enumerate(rows))+'\n'
    paths = {
        'equations/quartic247/equation.json': blob(equation),
        'equations/quartic247/expanded_polynomial.json': blob(expanded),
        'equations/quartic247/metrics.json': blob(metrics),
        'equations/quartic247/coordinate_map.json': blob(mapping),
        'equations/quartic247/residuals.txt': readable.encode(),
        'report_inputs/residuals.tex': tex_rows(rows).encode(),
        'report_inputs/metrics.tex': (
            '\\newcommand{\\FinalTerms}{'+format(metrics['collected_monomials'], ',')+'}\n'
            '\\newcommand{\\FinalHeight}{'+format(metrics['coefficient_height'], ',')+'}\n'
            '\\newcommand{\\FinalRows}{'+str(metrics['quadratic_residuals'])+'}\n').encode(),
    }
    return paths, metrics

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--write', action='store_true', help='regenerate the final finite data')
    args = ap.parse_args()
    paths, metrics = build()
    for name, data in paths.items():
        path = ROOT/name
        if args.write:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(data)
        else:
            need(path.read_bytes() == data, 'reconstruction mismatch: '+name)
    print(json.dumps({'status': 'PASS', 'mode': 'write' if args.write else 'check',
                      'exact_inverse': True, 'files': len(paths), 'metrics': metrics}, sort_keys=True))

if __name__ == '__main__':
    main()
