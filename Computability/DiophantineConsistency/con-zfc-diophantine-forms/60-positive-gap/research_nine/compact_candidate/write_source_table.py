#!/usr/bin/env python3
"""Emit the readable source table after an exact independent record comparison.

The checked polynomial expressions below are written directly in source symbols.
They are not parsed from, or imported from, the circuit/source builder.  Only the
small standard-library sparse polynomial class of the independent auditor is
reused.  No native coefficient payload is needed: all four ports stay formal.
"""
from pathlib import Path
import hashlib, json
from audit_circuit import Polynomial, require

ROOT=Path(__file__).resolve().parent
NAMES='J F alpha z f h i o j s w t eta zeta y gamma N E p c a X D C2 S F2 V g I Baux Delta'.split()
PORTS=['beta','K0','MC','MF']
LATEX_NAMES=[r'J',r'F',r'\alpha',r'z',r'f',r'h',r'i',r'o',r'j',r's',r'w',r't',r'\eta',r'\zeta',r'y',r'\gamma',r'N',r'E',r'p',r'c',r'a',r'X',r'D',r'C_2',r'S',r'F_2',r'V',r'g',r'I',r'\mathcal B',r'\Delta']

def main():
    n=35
    vs=[Polynomial.variable(n,i) for i in range(n)]
    J,F,alpha,z,f,h,i,o,j,s,w,t,eta,zeta,y,gamma,N,E,p,c,a,X,D,C2,S,F2,V,g,I,Baux,Delta,beta,K0,MC,MF=vs
    q=beta*J+1;k=eta+zeta
    rows=[
      S-q**2,
      N-S*q,
      X-w*q,
      a-E-s*N,
      E-(a-E)*X,
      c-eta-k*(a-E),
      p-E*(c-eta),
      t**2+2*p*t-k*p-1,
      D-X-c*a-(4*a+3)*gamma,
      Delta-(a+1)*(a+3),
      C2-c**2,
      D**2-C2*Delta-1,
      k+V-h*E-j*c-1,
      j*c-V+alpha*(1-S)+F*(N-S-q+1)+(q-1)*(q-N)-J*(MC+MF*q),
      K0*(q-F-alpha)+X-F-w*(F+alpha)+(q-1)*(1-z),
      F2-f**2,
      c+V-f*o,
      g+V**2-y**2,
      I-i*C2,
      Baux-I**2,
      Baux+(1-F2)*Delta,
      y**2-g*Baux-1]
    tex=[
      r'S-q^2',
      r'N-Sq',
      r'X-wq',
      r'a-E-sN',
      r'E-(a-E)X',
      r'c-\eta-k(a-E)',
      r'p-E(c-\eta)',
      r't^2+2pt-kp-1',
      r'D-X-ca-(4a+3)\gamma',
      r'\Delta-(a+1)(a+3)',
      r'C_2-c^2',
      r'D^2-C_2\Delta-1',
      r'k+V-hE-jc-1',
      r'\begin{aligned}[t] &jc-V+\alpha(1-S)+F(N-S-q+1)\\ &\quad +(q-1)(q-N)-J(M_C+M_Fq)\end{aligned}',
      r'\begin{aligned}[t] &K_0(q-F-\alpha)+X-F-w(F+\alpha)\\ &\quad +(q-1)(1-z)\end{aligned}',
      r'F_2-f^2',
      r'c+V-fo',
      r'g+V^2-y^2',
      r'I-iC_2',
      r'\mathcal B-I^2',
      r'\mathcal B+(1-F_2)\Delta',
      r'y^2-g\mathcal B-1']
    source_path=ROOT/'data/parent_source.json';source=json.loads(source_path.read_text())
    reconstructed=[Polynomial.constant(n,0) for _ in range(22)]
    for rec in source:
        coefficient=Polynomial.constant(n,0)
        for term in rec['coefficient']:
            value=Polynomial.constant(n,term['coefficient'])
            for v,e in zip(vs[31:],term['powers']):value*=v**e
            coefficient+=value
        monomial=Polynomial.constant(n,1)
        for vindex in rec['monomial']:monomial*=vs[vindex]
        # Weighted constant/linear/diagonal entries already equal 2*rho;
        # mixed entries acquire the factor 2 from the convolution expansion.
        if len(rec['monomial'])==2 and rec['monomial'][0]!=rec['monomial'][1]:coefficient*=2
        reconstructed[rec['row']-1]+=coefficient*monomial
    for row,(given,formula) in enumerate(zip(reconstructed,rows),1):
        require(given.terms==(2*formula).terms,'Source expression mismatch, row '+str(row))
    layout=json.loads((ROOT/'data/split_code.json').read_text())
    targets=dict(zip(layout['order'],layout['targets']))
    require(set(targets)==set(range(1,23)),'Incomplete row-target assignment')
    out=[r'% Generated by write_source_table.py after exact formal-port comparison.',
         r'% Requires amsmath, longtable and needspace. This is an input fragment.',
         r'\subsection{The exact positive quadratic source}',
         r'All 31 variables in this table range over the positive integers.  The four symbols',
         r'$\beta,K_0,M_C,M_F$ are the coherent compact coefficient tuple; $M_F$ denotes',
         r'the port named \texttt{MF\_source} in its native binding.  Write',
         r'\[q=\beta J+1,\qquad k=\eta+\zeta.\]',
         r'The source system is $\rho_r=0$ for $1\leq r\leq22$.  The last column gives',
         r'the target exponent $\lambda_r$ assigned to that residual in the frozen packing layout.',
         r'These are local source symbols: for example, $a,c,D,N$ in this table do not denote',
         r'the outer encoding constants or the Jones-tail registers.',
         r'\begingroup',r'\renewcommand{\arraystretch}{1.22}',
         r'\begin{longtable}{@{}r p{0.73\linewidth} r@{}}',
         r'\hline',r'$r$ & $\rho_r$ & $\lambda_r$\\',r'\hline',r'\endfirsthead',
         r'\hline',r'$r$ & $\rho_r$ & $\lambda_r$\\',r'\hline',r'\endhead']
    for r,formula in enumerate(tex,1):out.append(f'{r} & \\({formula}\\) & {targets[r]}\\\\')
    out += [r'\hline',r'\end{longtable}',r'\endgroup',
            r'The variable $z$ in row 15 is the original transport variable.  The shifted',
            r'positive transport coordinate used by the native source is $z_{\mathrm s}=z-1$;',
            r'the positive inverse requires the source-kernel bound $z\geq2$.  The coefficient',
            r'$M_F$ retains its native binding in this change of variable.',
            r'The new coordinates are $p=P-(\eta+\zeta)$, $t=\tau-p$, and $S=L_{\rm old}+1$.',
            r'Rows 14 and 15 include the invertible row operations',
            r'$\rho_{14}=r_{14}+r_2$ and $\rho_{15}=r_{15}+r_3$.',
            r'\Needspace{16\baselineskip}',
            r'\paragraph{Variable indices and weights.}',
            r'The monomial records use the following zero-based indices and code weights $w_i$.',
            r'The unique zero weight is attached to $y$.',
            r'\begin{center}',
            r'\begin{tabular}{@{}r l r@{\qquad}r l r@{\qquad}r l r@{}}',r'\hline',
            r'$i$ & variable & $w_i$ & $i$ & variable & $w_i$ & $i$ & variable & $w_i$\\',r'\hline']
    for start in range(11):
        cells=[]
        for index in (start,start+11,start+22):
            if index<31:cells.extend([str(index),f'${LATEX_NAMES[index]}$',str(layout['weights'][index])])
            else:cells.extend(['','',''])
        out.append(' & '.join(cells)+r'\\')
    out += [r'\hline',r'\end{tabular}',r'\end{center}',
            r'\paragraph{Weighted-record convention.}',
            r'For a monomial $x^\alpha$ with $|\alpha|\leq2$, the stored coefficient is',
            r'$(2-|\alpha|)!\,\alpha!$ times its coefficient in $\rho_r$.  Thus constants,',
            r'linear terms, and diagonal quadratic terms are doubled; mixed quadratic',
            r'terms are unchanged.  The source has 86 weighted records.  The script',
            r'\texttt{write\_source\_table.py} verifies every displayed residual exactly over',
            r'$\mathbb Z[\beta,K_0,M_C,M_F]$ before writing this table.']
    path=ROOT/'source_equations.tex';path.write_text('\n'.join(out)+'\n')
    receipt={'status':'PASS','residuals':22,'weighted_records':len(source),
             'coefficient_ring':'Z[beta,K0,MC,MF]','source_sha256':hashlib.sha256(source_path.read_bytes()).hexdigest(),
             'tex_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),'row_targets':targets,
             'scope':'Exact sparse-polynomial equality of the 22 displayed source formulas and all weighted records; no fixed-port specialization or modular sampling.'}
    (ROOT/'generated/SOURCE_TABLE_AUDIT.json').write_text(json.dumps(receipt,indent=2)+'\n')
    print(json.dumps(receipt,indent=2))

if __name__=='__main__':main()
