#!/usr/bin/env python3
"""Produce or check a self-contained LaTeX source for the complete report."""
import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent
INPUT = re.compile(r"\\input\{([^{}]+)\}")


def expand(path, stack=()):
    path = path.resolve()
    if path in stack or path.parent != ROOT:
        raise ValueError("Recursive or nonlocal LaTeX input: " + str(path))
    text = path.read_text(encoding="utf-8")
    def replace(match):
        child = ROOT / match.group(1)
        if not child.suffix:
            child = child.with_suffix(".tex")
        return ("% BEGIN embedded " + child.name + "\n" +
                expand(child, stack + (path,)) +
                "\n% END embedded " + child.name + "\n")
    return INPUT.sub(replace, text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "report.tex"
    rendered = "% Generated by assemble.py; edit main.tex and its inputs.\n" + expand(ROOT / "main.tex")
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != rendered:
            raise SystemExit("Single-file LaTeX source differs; run report/assemble.py")
        print("PASS: standalone report.tex matches all component inputs")
    else:
        target.write_text(rendered, encoding="utf-8")
        print("Wrote " + str(target))


if __name__ == "__main__":
    main()
