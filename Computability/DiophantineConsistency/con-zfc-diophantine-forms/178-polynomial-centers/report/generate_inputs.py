#!/usr/bin/env python3
"""Generate the article's four literal-data inputs from packaged JSON.

Only the Python standard library is required. --check reconstructs every
generated byte in memory and compares it with the shipped TeX inputs.
The source JSON defines the polynomials; this script renders those data.
"""
from pathlib import Path
import argparse
import json
import re

HERE=Path(__file__).resolve().parent
ROOT=HERE.parent


def load(path):
    return json.loads(path.read_text())


def require(condition,message):
    if not condition:raise ValueError(message)


def code(value):
    require(isinstance(value,str) and all(c.isalnum() or c in '._' for c in value),
            'unsupported register character')
    return r'\code{'+value+'}'


def operand(value):
    if type(value) is int:return r'\('+str(value)+r'\)'
    return code(value)


def graph_inputs():
    graph=load(ROOT/'whole_product/equation.json')
    rows=graph['source']
    require(graph['operations']==len(rows),'graph operation count')
    require(graph['domain']=='strictly positive integers' and len(graph['witnesses'])==10,
            'article domain and number of witnesses')
    require(graph['exact_degree']==208,'article degree')
    counts={op:sum(r[1]==op for r in rows) for op in ('*','+','-')}
    require(counts==graph['operation_breakdown'],'graph operation classes')
    known=set(graph['witnesses']+graph['fixed_numerals'])
    dependencies={}
    for register,op,a,b in rows:
        require(register not in known and op in counts,'valid circuit register')
        require(all(type(x) is int or x in known for x in (a,b)),'topological circuit')
        known.add(register);dependencies[register]=(a,b)
    live=set()
    def visit(name):
        if type(name) is int or name in live:return
        live.add(name)
        for arg in dependencies.get(name,()):visit(arg)
    visit(graph['output'])
    require(live==known,'all printed circuit gates, variables and constants must be live')
    metrics='\n'.join([
        '% Generated by generate_inputs.py from whole_product/equation.json.',
        r'\newcommand{\PrimaryOps}{'+str(len(rows))+'}',
        r'\newcommand{\PrimaryMul}{'+str(counts['*'])+'}',
        r'\newcommand{\PrimaryAdd}{'+str(counts['+'])+'}',
        r'\newcommand{\PrimarySub}{'+str(counts['-'])+'}',
        ''])
    text=[
        '% Generated by generate_inputs.py; all live source rows in order.',
        'The last register, '+code(graph['output'])+r', is $P_{208}$.',
        r'\begingroup',
        r'\fontsize{8.5}{10.2}\selectfont',
        r'\setlength{\tabcolsep}{6pt}',
        r'\setlength{\LTleft}{0pt}',
        r'\setlength{\LTright}{\fill}',
        r'\renewcommand{\arraystretch}{1.0}',
        r'\begin{longtable}{@{}rll@{}}',
        r'\toprule',
        r'Row & Register & Right-hand side\\',
        r'\midrule',
        r'\endfirsthead',
        r'\toprule',
        r'Row & Register & Right-hand side (continued)\\',
        r'\midrule',
        r'\endhead',
        r'\midrule',
        r'\multicolumn{3}{r}{Continued on next page}\\',
        r'\endfoot',
        r'\bottomrule',
        r'\endlastfoot',
    ]
    optex={'*':r'\(\times\)','+':r'\(+\)','-':r'\(-\)'}
    for j,(name,op,a,b) in enumerate(rows,1):
        text.append(str(j)+' & '+code(name)+' & '+operand(a)+' '+optex[op]+' '+operand(b)+r'\\')
    text.extend([r'\end{longtable}',r'\endgroup',''])
    return metrics,'\n'.join(text),len(rows)


def direct_table():
    profiles=[
        ('natural203','Natural, principal',r'$\N$'),
        ('natural203_reduced','Natural, lower height',r'$\N$'),
        ('natural203_sparse','Natural, alternate basis',r'$\N$'),
        ('natural204','Natural, intermediate',r'$\N$'),
        ('radical233','Integer, principal',r'$\Z$'),
        ('radical234_sparse','Integer, sparse',r'$\Z$'),
    ]
    text=[
        '% Generated by generate_inputs.py from the six packaged metrics files.',
        r'\begin{center}',
        r'\small',
        r'\begin{tabular}{llrrrr}',
        r'\toprule',
        r'Profile & Domain & Variables & Rows & Terms & Height\\',
        r'\midrule',
    ]
    for dirname,label,domain in profiles:
        metric=load(ROOT/'direct'/dirname/'metrics.json')
        equation=load(ROOT/'direct'/dirname/'equation.json')
        require(metric['degree']==4,'direct-table quartic degree')
        require(metric['rows']==len(equation['residuals']),'direct-table row count')
        require(metric['variables']==len(equation['variables']),'direct-table variable count')
        require(equation['domain']==('nonnegative integers' if domain==r'$\N$' else 'unrestricted integers'),
                'direct-table domain '+dirname)
        values=[f'{metric[k]:,}' for k in ('variables','rows','monomials','height')]
        text.append(label+' & '+domain+' & '+' & '.join(values)+r'\\')
    text.extend([r'\bottomrule',r'\end{tabular}',r'\end{center}',
                 'All six polynomials have exact degree four. Terms and height refer',
                 'to the collected quartic; height is the largest absolute coefficient.',''])
    return '\n'.join(text)


def term_piece(coefficient,monomial,first=False):
    require(type(coefficient) is int and coefficient!=0,'nonzero integer residual coefficient')
    require(len(monomial)<=2 and all(type(j) is int and 0<=j<203 for j in monomial),
            'quadratic residual monomial')
    require(monomial==sorted(monomial),'canonical monomial order')
    if not monomial:
        body=str(abs(coefficient))
    else:
        if len(monomial)==2 and monomial[0]==monomial[1]:
            body='x_{'+str(monomial[0])+'}^{2}'
        else:
            body=''.join('x_{'+str(j)+'}' for j in monomial)
        if abs(coefficient)!=1:body=str(abs(coefficient))+r'\,'+body
    sign='-' if coefficient<0 else '' if first else '+'
    return sign+body


def residuals():
    eq=load(ROOT/'direct/natural203/equation.json')
    require(eq['schema']=='finite_quadratic_residuals_v1','residual schema')
    require(eq['domain']=='nonnegative integers','natural residual domain')
    require(len(eq['variables'])==203 and len(eq['residuals'])==155,'literal appendix dimensions')
    require(eq['polynomial']=='sum(square(row) for row in residuals)','literal sum-of-squares definition')
    text=[
        '% Generated by generate_inputs.py from direct/natural203/equation.json.',
        '% The q_i order is exactly the residual-list order; indices are zero based.',
        r'\begingroup',
        r'\fontsize{9}{11}\selectfont',
        r'\allowdisplaybreaks[0]',
        r'\setlength{\abovedisplayskip}{3pt}',
        r'\setlength{\belowdisplayskip}{3pt}',
        r'\setlength{\abovedisplayshortskip}{3pt}',
        r'\setlength{\belowdisplayshortskip}{3pt}',
        r'\setlength{\jot}{1pt}',
    ]
    total=0
    for j,row in enumerate(eq['residuals']):
        terms=row['terms']
        require(bool(terms),'nonempty residual')
        require(len({tuple(m) for c,m in terms})==len(terms),'collected residual terms')
        rendered=[term_piece(c,m,first=(t==0)) for t,(c,m) in enumerate(terms)]
        total+=len(rendered)
        text.append('% residual '+str(j)+'; '+str(len(terms))+' literal terms')
        text.append(r'\begin{align*}')
        for start in range(0,len(rendered),4):
            prefix='q_{'+str(j)+'} &={}' if start==0 else r'&\quad '
            line=prefix+' '.join(rendered[start:start+4])
            if start+4<len(rendered):line+=r'\\'
            text.append(line)
        text.append(r'\end{align*}')
    text.extend([r'\endgroup',''])
    require(total==load(ROOT/'direct/natural203/metrics.json')['residual_terms'],
            'every residual term printed exactly once')
    return '\n'.join(text),total


def check_printed_residuals(text):
    """Read the printed algebra back independently of term_piece()."""
    equations=load(ROOT/'direct/natural203/equation.json')['residuals']
    blocks=re.findall(r'\\begin\{align\*\}(.*?)\\end\{align\*\}',text,re.S)
    require(len(blocks)==len(equations),'printed residual block count')
    term_pattern=re.compile(r'([+-]?)([0-9]*)((?:x_\{[0-9]+\}(?:\^\{2\})?)*)')
    variable_pattern=re.compile(r'x_\{([0-9]+)\}(\^\{2\})?')
    for j,(block,row) in enumerate(zip(blocks,equations)):
        head=re.match(r'\s*q_\{([0-9]+)\}\s*&=\{\}',block)
        require(head is not None and int(head.group(1))==j,'printed residual index')
        expression=block[head.end():].replace(r'&\quad','').replace(r'\\','').replace(r'\,','')
        expression=re.sub(r'\s+','',expression)
        terms=[];position=0
        while position<len(expression):
            match=term_pattern.match(expression,position)
            require(match is not None and match.end()>position,'parse printed residual term')
            sign,digits,variables=match.groups()
            require(bool(digits or variables),'nonempty printed term')
            coefficient=int(digits) if digits else 1
            if sign=='-':coefficient=-coefficient
            monomial=[]
            for index,squared in variable_pattern.findall(variables):
                monomial.extend([int(index)]*(2 if squared else 1))
            terms.append([coefficient,monomial]);position=match.end()
        require(terms==row['terms'],'printed quadratic differs from literal JSON at row '+str(j))
    return len(blocks)


def main():
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    metrics,circuit,nrows=graph_inputs()
    appendix,nterms=residuals()
    printed_rows=check_printed_residuals(appendix)
    output={'metrics.tex':metrics,'circuit.tex':circuit,
            'direct_table.tex':direct_table(),'residuals203.tex':appendix}
    for name,contents in output.items():
        path=HERE/name
        if args.check:
            require(path.exists() and path.read_text()==contents,'generated input mismatch: '+name)
        else:
            path.write_text(contents)
    print(json.dumps({'status':'checked' if args.check else 'generated',
                      'files':list(output),'circuit_rows':nrows,
                      'natural_residuals':printed_rows,'natural_variables':203,
                      'printed_residual_terms':nterms,'direct_profiles':6},indent=2))


if __name__=='__main__':main()
