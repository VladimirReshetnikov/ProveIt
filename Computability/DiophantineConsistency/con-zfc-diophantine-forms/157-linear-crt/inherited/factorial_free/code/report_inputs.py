#!/usr/bin/env python3
"""Generate, or exactly check, the data-dependent LaTeX report inputs."""
from pathlib import Path
import argparse
import json

ROOT = Path(__file__).resolve().parents[1]


def load(path):
    return json.loads((ROOT / path).read_text())


def generated():
    principal = load("direct/principal/METRICS.json")
    companion = load("direct/companion/METRICS.json")
    audit = load("direct/review/FINAL_CHECK_NORMAL.json")
    parent = audit["parent"]["metrics"]
    profile = audit["profiles"]["factorial_free_affine"]
    projection = profile["projection"]
    first = profile["endpoints"]["factorial_free_affine242_balanced"]["finite_maps"]
    second = profile["endpoints"]["factorial_free_affine241_balanced"]["finite_maps"]
    macros = {
        "NewVars": principal["variables"],
        "NewRows": principal["rows"],
        "NewTerms": f'{principal["monomials"]:,}',
        "NewHeight": f'{principal["height"]:,}',
        "NewLast": principal["variables"] - 1,
        "NewLastRow": principal["rows"] - 1,
    }
    results = "% Generated by code/report_inputs.py; do not edit by hand.\n"
    results += "".join("\\newcommand{\\" + key + "}{" + str(value) + "}\n"
                       for key, value in macros.items())
    table = [
        "% Generated from the retained metrics and independent audit.",
        r"\begin{center}\small",
        r"\setlength{\tabcolsep}{5pt}",
        r"\begin{tabular}{lrrrrr}",
        r"\toprule",
        r"Equation over $\Z$ & Variables & Rows & Degree & Terms & Height\\",
        r"\midrule",
    ]
    for label, metric in [("Matched parent", parent),
                          ("Principal", principal), ("Dense companion", companion)]:
        values = [str(metric[key]) if key not in ("monomials", "height")
                  else f"{metric[key]:,}"
                  for key in ("variables", "rows", "degree", "monomials", "height")]
        table.append(label + " & " + " & ".join(values) + r"\\")
    table += [
        r"\bottomrule",
        r"\end{tabular}",
        r"\end{center}",
        r"Here \emph{terms} means nonzero monomials after complete collection,",
        r"and height is the largest absolute coefficient in that expansion.",
        r"The principal equation saves ten variables and four residuals relative",
        r"to its matched parent. Its support decreases by 322 monomials and its",
        r"coefficient height by approximately $93.80\%$.",
        r"The maximum absolute coefficient in a quadratic residual is $64$",
        r"for both new endpoints.",
    ]
    verification = r"""
\subsection{Finite audit results}

The normal audit first reconstructs the inherited 252-coordinate source
and expansion. For the new source it checks @HORN@ Horn factorization edits,
@MONIC@ unit-monic projections, and the removal of @UNUSED@ coordinates
that do not occur in the retained system. The final maps contain
@SHEARS@ integral coordinate shears and @EXPOSURES@ affine-exposure row
operations. The principal then uses @P1@ affine projections and @R1@
final row operations; the companion uses @P2@ and @R2@, respectively.
The checker independently collects every coefficient of both quartics.
It imports no producer module. Seven deliberate corruptions are rejected.
The new finite checks also pass with Python's \texttt{-O} flag, so their
validity does not depend on enabled \texttt{assert} statements.

A separately authored checker reconstructs the eighteen power requests,
thirty-seven distinct frame atoms, fourteen principal Pell pairs, five
base moduli, and the derived consecutive-index pair in the changed raw
source. It too passes normally and with \texttt{-O}.

A fresh reconstruction reproduces eighteen JSON files byte for byte,
checks twelve endpoint alias files, and verifies six readable exports.
The small-case number-theory script separately exercises the new coverage,
range, CRT precision, label, parity, and cofinality arguments, including
an explicit counterexample without the radius hypothesis. These finite
regressions supplement the unbounded proofs; they are not substitutes for
those proofs or for a formal proof-assistant development.
""".strip() + "\n"
    replacements = {
        "@HORN@": projection["horn_edits"],
        "@MONIC@": projection["monic_projections"],
        "@UNUSED@": projection["unused_removed"],
        "@SHEARS@": first["coordinate_shears"],
        "@EXPOSURES@": first["affine_exposure_operations"],
        "@P1@": first["unit_affine_projections"],
        "@R1@": first["final_row_operations"],
        "@P2@": second["unit_affine_projections"],
        "@R2@": second["final_row_operations"],
    }
    for key, value in replacements.items():
        verification = verification.replace(key, str(value))
    readable = (ROOT / "direct/principal/residuals.tex").read_text()
    # Keep each individual residual on one page; permit breaks between rows.
    readable = readable.replace(r"\\" + "\n", r"\\*" + "\n")
    residuals = (r"\begingroup" + "\n" + r"\small" + "\n"
                 + r"\setlength{\jot}{0pt}" + "\n"
                 + readable
                 + r"\endgroup" + "\n")
    return {"results.tex": results,
            "comparison.tex": "\n".join(table) + "\n",
            "verification.tex": verification,
            "residuals.tex": residuals}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, content in generated().items():
        destination = ROOT / "report" / name
        if args.check:
            if not destination.is_file() or destination.read_text() != content:
                raise RuntimeError(f"Report input differs: {destination}")
        else:
            destination.write_text(content)
    print(json.dumps({"status": "PASS", "mode": "check" if args.check else "write",
                      "report_inputs": sorted(generated())}, sort_keys=True))


if __name__ == "__main__":
    main()
