#!/usr/bin/env python3
"""Reproduce the complete source34 tuple offline using only the standard library.

The exact authenticated upstream constructor proves its finite hypotheses.
This wrapper binds every regenerated byte to the preserved upstream manifest
and emits a complete four-port binding for the new integer equation.
"""
import json
import struct
import zlib
from provenance import (ROOT, require, sha256, verify_sources, load_source34,
                        make_binding, write_json)


def canonical_gzip(raw):
    # Source34's gzip format: no filename, zero timestamp, level9, Unix OS byte.
    compressor = zlib.compressobj(level=9, method=zlib.DEFLATED, wbits=-15)
    body = compressor.compress(raw)+compressor.flush()
    trailer = struct.pack('<II', zlib.crc32(raw)&0xffffffff, len(raw)&0xffffffff)
    return bytes.fromhex('1f8b0800000000000203')+body+trailer


def main():
    source_count = verify_sources()
    upstream = load_source34('authenticated_source34_constructor', 'build_coefficients.py')
    values, audit = upstream.construct()
    # JSON object keys are strings; the original Python audit uses integer keys.
    audit = json.loads(json.dumps(audit))
    manifest_path = ROOT/'upstream'/'source34'/'PAYLOAD_BINDING.json'
    inherited = json.loads(manifest_path.read_text())
    require(audit == inherited['audit'], 'complete upstream finite audit')
    require(set(values) == set(inherited['payloads']), 'complete coefficient set')
    out = ROOT/'payloads'
    out.mkdir(exist_ok=True)
    raw_values = {}
    for name,value in values.items():
        raw = value.to_bytes((value.bit_length()+7)//8, 'little')
        compressed = canonical_gzip(raw)
        expected = inherited['payloads'][name]
        actual = dict(bits=value.bit_length(), bytes=len(raw), sha256=sha256(raw),
                      gzip_bytes=len(compressed), gzip_sha256=sha256(compressed))
        require(actual == expected, 'exact raw and compressed payload: '+name)
        (out/(name+'.bin')).write_bytes(raw)
        (out/(name+'.bin.gz')).write_bytes(compressed)
        raw_values[name] = raw
    # Preserve the complete authentic source manifest, including its historical pin.
    (out/'COEFFICIENT_BINDING.json').write_bytes(manifest_path.read_bytes())
    binding = make_binding(raw_values, inherited)
    write_json(ROOT/'COEFFICIENT_BINDING.json', binding)
    receipt = {
        'status': 'PASS', 'authenticated_source_files': source_count,
        'upstream_builder_git_blob': 'b85e416b8a8b823c01c8ecacd85eebef7f5c69b5',
        'ordered_machine_actions': 430, 'ordered_tiles': 943,
        'basis_convolution_checks': audit['basis_convolution_checks'],
        'all_raw_and_gzip_hashes_match_upstream': True,
        'raw_bytes': sum(len(x) for x in raw_values.values()),
        'gzip_bytes': sum(inherited['payloads'][n]['gzip_bytes'] for n in values),
        'tuple_sha256': binding['tuple_sha256'], 'finite_audit': audit,
        'scope': 'Literal data, complete finite compiler hypotheses and port binding; universal proof remains the preserved mathematical dependency.'
    }
    write_json(ROOT/'BUILD_CHECKS.json', receipt)
    print(json.dumps(receipt, indent=2))


if __name__ == '__main__':
    main()
