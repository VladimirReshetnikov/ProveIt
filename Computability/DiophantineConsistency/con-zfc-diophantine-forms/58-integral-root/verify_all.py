#!/usr/bin/env python3
"""Run all finite checks; this does not test the consistency of ZFC."""
import hashlib
import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SCRIPTS = [
    'code/build.py',
    'code/domain_translations.py',
    'code/verify.py',
    'code/independent_check.py',
    'twelve/build_p12.py',
    'twelve/check_p12.py',
    'coefficients/audit_coefficients.py',
]


def circuit_hashes():
    files = list((ROOT/'circuits').glob('*.json'))
    files += list((ROOT/'twelve').glob('p12_desaturated_*.json'))
    return {str(p.relative_to(ROOT)): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in sorted(files)}


def main():
    before = circuit_hashes()
    records = []
    for script in SCRIPTS:
        command = [sys.executable]
        if sys.flags.optimize:
            command.append('-O')
        command.append(str(ROOT/script))
        process = subprocess.run(command, cwd=ROOT, text=True, capture_output=True)
        record = {'script': script, 'returncode': process.returncode,
                  'stdout_sha256': hashlib.sha256(process.stdout.encode()).hexdigest(),
                  'stderr_sha256': hashlib.sha256(process.stderr.encode()).hexdigest()}
        records.append(record)
        if process.returncode:
            print(process.stdout)
            print(process.stderr, file=sys.stderr)
            raise RuntimeError('Verification failed: '+script)
        print('PASS '+script, flush=True)
    after = circuit_hashes()
    if before != after:
        raise ValueError('Published circuit files did not regenerate byte-for-byte')
    receipt = {'status': 'PASS', 'optimization_mode': bool(sys.flags.optimize),
               'circuit_regeneration_byte_identical': True,
               'circuit_hashes': after, 'checks': records,
               'scope': 'Finite arithmetic, source and artifact checks. No semantic proof assistant or consistency test.'}
    suffix = '_OPTIMIZED' if sys.flags.optimize else ''
    (ROOT/'certificates'/('VERIFY_ALL'+suffix+'.json')).write_text(json.dumps(receipt, indent=2)+'\n')
    print('PASS: all checks; '+str(len(after))+' circuit files regenerated byte-for-byte.')


if __name__ == '__main__':
    main()
