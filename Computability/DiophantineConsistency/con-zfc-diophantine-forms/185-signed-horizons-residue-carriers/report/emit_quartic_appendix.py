#!/usr/bin/env python3
"""Print the complete Q214 residual list, or authenticate its TeX rendering."""
import argparse
from collections import Counter
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT.parent / 'quartic/affine_horizons/p214_scaled_square/equation.json'
TARGET = ROOT / 'quartic_residuals.tex'


def render():
    raw = SOURCE.read_bytes()
    equation = json.loads(raw)
    if len(equation['variables']) != 214 or len(equation['residuals']) != 153:
        raise ValueError('Unexpected quartic dimensions')
    lines = [
        '% Generated by emit_quartic_appendix.py; do not hand-edit.',
        '% Source SHA-256: ' + hashlib.sha256(raw).hexdigest(),
        r'\begingroup\small',
        r'\setlength{\jot}{1.5pt}',
        r'\begin{align*}',
    ]
    for index, residual in enumerate(equation['residuals']):
        terms = []
        for coefficient, monomial in residual['terms']:
            if not isinstance(coefficient, int) or not coefficient:
                raise ValueError('Noncanonical coefficient')
            if len(monomial) > 2 or any(i < 0 or i >= 214 for i in monomial):
                raise ValueError('Bad monomial')
            factors = []
            for variable, power in sorted(Counter(monomial).items()):
                factor = 'x_{' + str(variable) + '}'
                if power != 1:
                    factor += '^{' + str(power) + '}'
                factors.append(factor)
            body = ''.join(factors)
            magnitude = abs(coefficient)
            if magnitude != 1 or not body:
                body = str(magnitude) + body
            sign = '-' if coefficient < 0 else '+'
            terms.append((sign, body))
        if not terms:
            raise ValueError('Empty residual')
        chunks = [terms[i:i + 5] for i in range(0, len(terms), 5)]
        for line_index, chunk in enumerate(chunks):
            prefix = ('R_{' + str(index) + '} &= ') if line_index == 0 else r'&\quad '
            rendered = []
            for term_index, (sign, body) in enumerate(chunk):
                if line_index == 0 and term_index == 0 and sign == '+':
                    rendered.append(body)
                else:
                    rendered.append(sign + body)
            suffix = r'\\' if index != 152 or line_index + 1 < len(chunks) else ''
            lines.append(prefix + ' '.join(rendered) + suffix)
    lines.extend([r'\end{align*}', r'\endgroup', ''])
    return '\n'.join(lines)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    data = render()
    if args.check:
        if TARGET.read_text(encoding='utf-8') != data:
            raise SystemExit('FAIL: the printed residual list differs from the literal equation')
        print(json.dumps({'status': 'PASS', 'variables': 214, 'printed_residuals': 153,
                          'source_sha256': hashlib.sha256(SOURCE.read_bytes()).hexdigest()}))
    else:
        TARGET.write_text(data, encoding='utf-8')
        print(json.dumps({'status': 'PASS', 'written': TARGET.name, 'residuals': 153}))
