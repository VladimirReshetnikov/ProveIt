#!/usr/bin/env python3
"""Render the complete 508-variable/308-row principal system as LaTeX.

The default input is the adjacent packet's direct/principal/equation.json.
No development-workspace path is embedded. Use --check to verify that the
delivered residuals.tex is byte-for-byte the deterministic rendering.
"""
from collections import Counter
import argparse
import hashlib
import json
from pathlib import Path
import sys


HERE = Path(__file__).resolve().parent


def require(condition, message):
    if not condition:
        raise ValueError(message)


def term_body(coefficient, monomial):
    factors = []
    for index, exponent in sorted(Counter(monomial).items()):
        factor = rf'x_{{{index}}}'
        if exponent != 1:
            factor += rf'^{{{exponent}}}'
        factors.append(factor)
    body = r'\,'.join(factors)
    magnitude = abs(coefficient)
    if not factors:
        return str(magnitude)
    if magnitude != 1:
        body = str(magnitude) + r'\,' + body
    return body


def render(source_bytes):
    data = json.loads(source_bytes)
    require(data.get('domain') == 'unrestricted integers',
            'The principal input must have unrestricted integer domain.')
    variables = data.get('variables')
    residuals = data.get('residuals')
    require(isinstance(variables, list) and len(variables) == 508,
            'Expected exactly 508 principal variables.')
    require(isinstance(residuals, list) and len(residuals) == 308,
            'Expected exactly 308 principal residuals.')
    source_terms = 0
    rows = []
    for row_index, residual in enumerate(residuals):
        terms = residual.get('terms')
        require(isinstance(terms, list) and terms,
                f'Residual {row_index} must have a nonempty term list.')
        seen = set()
        formatted = []
        for term_index, term in enumerate(terms):
            require(isinstance(term, list) and len(term) == 2,
                    f'Malformed term in residual {row_index}.')
            coefficient, monomial = term
            require(type(coefficient) is int and coefficient != 0,
                    f'Nonintegral or zero coefficient in residual {row_index}.')
            require(isinstance(monomial, list) and len(monomial) <= 2,
                    f'Nonquadratic monomial in residual {row_index}.')
            require(all(type(index) is int and 0 <= index < 508
                        for index in monomial),
                    f'Unknown variable index in residual {row_index}.')
            require(monomial == sorted(monomial),
                    f'Noncanonical monomial in residual {row_index}.')
            key = tuple(monomial)
            require(key not in seen,
                    f'Duplicate uncollected monomial in residual {row_index}.')
            seen.add(key)
            sign = '-' if coefficient < 0 else ('+' if term_index else '')
            body = term_body(coefficient, monomial)
            formatted.append((sign + ' ' + body).strip())
        source_terms += len(terms)
        rows.append(formatted)

    sha = hashlib.sha256(source_bytes).hexdigest()
    out = [
        '% Deterministically generated by generate_residuals.py; do not edit.',
        f'% Source SHA256: {sha}',
        '% Source: direct/principal/equation.json (packet-relative).',
        f'% Variables: 508; residuals: 308; source terms: {source_terms}.',
        r'\section{Complete quadratic residuals of the principal equation}',
        r'\label{app:principal-residuals}',
        '',
        r'The unknowns are $x_0,\ldots,x_{507}\in\mathbb Z$, with the',
        r'zero-based coordinate order of \file{direct/principal/equation.json}.',
        r'The following list contains every term of all $308$ integral',
        r'quadratic residuals. The single principal equation is exactly',
        r'\[',
        r'  P_{508}(x_0,\ldots,x_{507})',
        r'  =\sum_{j=0}^{307}Q_j(x_0,\ldots,x_{507})^2=0.',
        r'\]',
        r'The symbols $Q_j$ are polynomial abbreviations, not additional',
        r'unknowns. Every coefficient is printed below; no term is omitted.',
        '',
        r'\begingroup',
        r'\footnotesize',
        r'\allowdisplaybreaks[4]',
        r'\setlength{\jot}{2pt}',
        r'\begin{align*}',
    ]
    for row_index, formatted in enumerate(rows):
        chunks = [formatted[start:start+4]
                  for start in range(0, len(formatted), 4)]
        for chunk_index, chunk in enumerate(chunks):
            prefix = rf' Q_{{{row_index}}}={{}}& ' if chunk_index == 0 else r' &{} '
            line = prefix + ' '.join(chunk)
            if chunk_index < len(chunks)-1:
                line += r' \\*'
            elif row_index < len(rows)-1:
                line += r' \\[3pt]'
            out.append(line)
    out.extend([r'\end{align*}', r'\endgroup', ''])
    return '\n'.join(out).encode('utf-8'), {
        'variables': 508, 'residuals': 308, 'source_terms': source_terms,
        'source_sha256': sha,
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--input', type=Path,
                        default=HERE.parent / 'direct' / 'principal' / 'equation.json')
    parser.add_argument('--output', type=Path, default=HERE / 'residuals.tex')
    parser.add_argument('--check', action='store_true',
                        help='Compare exact rendered bytes and do not write files.')
    args = parser.parse_args()
    rendered, metadata = render(args.input.read_bytes())
    if args.check:
        require(args.output.is_file(), 'The rendered residual file is missing.')
        require(args.output.read_bytes() == rendered,
                'Residuals differ from the complete deterministic rendering.')
        metadata['mode'] = 'check'
    else:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_bytes(rendered)
        metadata['mode'] = 'write'
    metadata['status'] = 'PASS'
    print(json.dumps(metadata, sort_keys=True))


if __name__ == '__main__':
    try:
        main()
    except (ValueError, OSError, json.JSONDecodeError) as exc:
        print(f'Residual rendering failed: {exc}', file=sys.stderr)
        raise SystemExit(1)
