#!/usr/bin/env python3
"""Construct six complete ordinary polynomials from frozen finite parents."""
from collections import Counter
from copy import deepcopy
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent
CASES = [
    ('uncentered', 'saturated_upper', 89, 288),
    ('upper', 'saturated_upper', 91, 283),
    ('sharp', 'saturated_sharp', 92, 278),
    ('direct_uncentered', 'direct_saturated_upper', 94, 262),
    ('direct_upper', 'direct_saturated_upper', 96, 258),
    ('direct_sharp', 'direct_saturated_sharp', 97, 254),
]

def construct(name, parent, operations, degree):
    old = json.loads((ROOT/'parents'/f'{parent}.json').read_text())
    out = deepcopy(old)
    uncentered = 'uncentered' in name
    rows = []
    for row in old['source']:
        register, op, a, b = row
        if register == 'L' or register == 'q4':
            continue
        if uncentered and register in ['Cg', 'nVCg']:
            continue
        if register == 'P1' and name.startswith('direct_'):
            row = ['P1', '*', 'q3', 'qbJ']
        else:
            rename = {'L': 'cTR'} | ({'nVCg': 'nV'} if uncentered else {})
            row = [register, op] + [rename.get(x, x) for x in [a, b]]
        rows.append(row)
    out.update(name=name, source=rows, operations=len(rows),
               operation_breakdown=dict(Counter(r[1] for r in rows)),
               exact_degree=degree,
               proof='PROOF.md: coprime recovery, auxiliary growth, transport, completeness, global degree.',
               parent_file=f'parents/{parent}.json')
    if len(rows) != operations:
        raise ValueError((name, len(rows), operations))
    return out

def main():
    checking = '--check' in sys.argv
    receipts = []
    for name, parent, count, degree in CASES:
        result = construct(name, parent, count, degree)
        content = json.dumps(result, indent=2) + '\n'
        target = ROOT/'equations'/f'{name}.json'
        if checking:
            if target.read_text() != content:
                raise ValueError('Different generated bytes: ' + name)
        else:
            target.write_text(content)
        receipts.append({'name': name, 'operations': count, 'degree': degree})
    print(json.dumps({'status': 'PASS', 'mode': 'check' if checking else 'write', 'circuits': receipts}, indent=2))

if __name__ == '__main__':
    main()
