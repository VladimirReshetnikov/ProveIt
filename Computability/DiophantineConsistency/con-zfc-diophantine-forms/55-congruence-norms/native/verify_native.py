#!/usr/bin/env python3
"""Bounded offline regeneration of the exact native tuple and dependency inventory.

This does not simulate K215 or invoke a Lean compiler. Python standard library only.
"""
from pathlib import Path
import gzip,hashlib,importlib.util,json,shutil,subprocess,sys,tempfile

ROOT=Path(__file__).resolve().parent
def need(ok,message):
    if not ok:raise AssertionError(message)
def sha(data):return hashlib.sha256(data).hexdigest()
def main():
    manifest=json.loads((ROOT/'SOURCE_MANIFEST.json').read_text())
    for row in manifest['files']:
        data=(ROOT/row['local_path']).read_bytes()
        need(sha(data)==row['sha256'],'source SHA256: '+row['local_path'])
        need(hashlib.sha1(b'blob '+str(len(data)).encode()+b'\0'+data).hexdigest()==row['git_blob_sha'],
             'source Git blob: '+row['local_path'])
    coef=ROOT/'coefficients';binding=json.loads((coef/'COEFFICIENT_BINDING.json').read_text())
    with tempfile.TemporaryDirectory(prefix='conzfc-native-') as temp:
        stage=Path(temp)/'coefficients';shutil.copytree(coef,stage)
        run=subprocess.run([sys.executable,'-B',str(stage/'build_coefficients.py')],
                           text=True,capture_output=True,check=True,timeout=180)
        generated=json.loads(run.stdout)
        ports=[]
        for row in binding['files']:
            actual=(stage/'payloads'/(row['port']+'.bin')).read_bytes()
            saved=gzip.decompress((coef/row['file']).read_bytes())
            need(actual==saved,'regenerated bytes: '+row['port'])
            need(sha(actual)==row['sha256'],'payload digest: '+row['port'])
            need(int.from_bytes(actual,'little').bit_length()==row['bit_length'],'payload bit length')
            ports.append(dict(port=row['port'],raw_bytes=len(actual),sha256=sha(actual),bit_length=row['bit_length']))
        # Gzip wrapper metadata varies with Python/zlib; the mathematical bytes must be exact.
        need(generated['geometry']==binding['geometry'],'geometry receipt')
        need(generated['padding']==binding['padding'],'rank-controller receipt')
        need(generated['mask_checks']==binding['mask_checks'],'mask receipt')
    rows=[]
    for line in (ROOT/'calibration/k215.tm').read_text().splitlines():
        fields=line.split()
        if not fields or fields[0].startswith('#'):continue
        q,b,v,d,t=fields
        rows.append([int(q),int(b),int(v),{'L':-1,'R':1}[d],int(t)])
    literal=json.loads((coef/'upstream/k215_transitions.json').read_text())['transitions']
    need(rows==literal,'literal machine/table projection')
    need(len(rows)==430 and len({(q,b) for q,b,*_ in rows})==430,'literal action census')
    formal=ROOT/'k215_formal'
    driver=formal/'Computability/BusyBeaver/Research/ZFC/k225-formal/verification/k215/lean/build.py'
    spec=importlib.util.spec_from_file_location('native_k215_inventory',driver)
    module=importlib.util.module_from_spec(spec);spec.loader.exec_module(module)
    inv=module.inventory(formal)
    need(len(inv['modules'])==168,'pinned formal closure census')
    need(inv['external_imports']==['Init'],'formal closure has unexpected external imports')
    for client in ['EndpointAudit215.lean','K215Audit.lean']:
        need((driver.parent/client).is_file(),'missing formal endpoint client')
    result=dict(status='PASS',source_commit=manifest['commit'],verified_source_files=len(manifest['files']),
                literal_machine_actions=len(rows),reconstructed_wang_tiles=943,native_basis_checks=generated['geometry']['native_basis_checks'],
                native_support_size=generated['geometry']['support_size'],ports=ports,
                finite_geometry=generated['geometry'],finite_rank_controller=generated['padding'],
                formal_project_modules=len(inv['modules']),formal_external_imports=inv['external_imports'],
                formal_endpoint_clients=2,formal_kernel_build_performed=False,
                machine_execution_performed=False,
                scope='Offline bounded coefficient regeneration, literal projection, source identity, and complete K215 project-import inventory; not a new kernel proof replay.')
    (ROOT/'VERIFICATION.json').write_text(json.dumps(result,indent=2)+'\n')
    print(json.dumps(result,indent=2))
if __name__=='__main__':main()
