#!/usr/bin/env python3
"""Export the fixed sparse equation to its human-readable representations.

No mathematical inference is made here. The independent checker in
check_report.py reads the generated TeX back and compares every coefficient.
"""
from pathlib import Path
import hashlib
import json

ROOT = Path(__file__).resolve().parents[1]


def term_text(coef, monomial, first, latex=False):
    sign = ('-' if coef < 0 else '') if first else (' - ' if coef < 0 else ' + ')
    value = abs(coef)
    if latex:
        if len(monomial) == 2 and monomial[0] == monomial[1]:
            body = 'x_{%d}^{2}' % monomial[0]
        else:
            body = ''.join('x_{%d}' % i for i in monomial)
        prefix = str(value) if value != 1 or not monomial else ''
    else:
        if len(monomial) == 2 and monomial[0] == monomial[1]:
            body = 'x%d^2' % monomial[0]
        else:
            body = '*'.join('x%d' % i for i in monomial)
        prefix = str(value) + ('*' if monomial else '') if value != 1 or not monomial else ''
    return sign + prefix + body


def estimated_width(coef, monomial):
    # Conservative estimate in points at the appendix's ten-point setting.
    coeff = 0 if abs(coef) == 1 and monomial else 5 * len(str(abs(coef)))
    if len(monomial) == 2 and monomial[0] == monomial[1]:
        variables = 14 + 4 * len(str(monomial[0]))
    else:
        variables = sum(10 + 4 * len(str(i)) for i in monomial)
    return 12 + coeff + variables


def main():
    eq_path = ROOT / 'equation/equation.json'
    eq = json.loads(eq_path.read_text())
    met = json.loads((ROOT / 'equation/METRICS.json').read_text())
    macros = {
        'NumVars': str(met['variables']), 'LastVar': str(met['variables'] - 1),
        'NumRows': str(met['rows']), 'LastRow': str(met['rows'] - 1),
        'NumTerms': format(met['monomials'], ','),
        'CoeffHeight': format(met['height'], ','),
    }
    (ROOT / 'report/metrics.tex').write_text(
        '% Generated by code/export_equation.py.\n' + ''.join(
            '\\newcommand{\\%s}{%s}\n' % (k, v) for k, v in macros.items()))
    tex = ['% Generated directly from equation/equation.json.',
           r'\begingroup', r'\small', r'\interdisplaylinepenalty=10000',
           r'\setlength{\jot}{3pt}']
    plain = ['P_225(x0,...,x224) = sum(R_j^2 for j=0,...,161).',
             'Domain: all 225 coordinates are unrestricted integers.', '']
    rowmap = ['row\tlabel\tterms']
    for j, row in enumerate(eq['residuals']):
        chunks, parts, width = [], [], 0
        for k, (coef, monomial) in enumerate(row['terms']):
            weight = estimated_width(coef, monomial)
            if parts and width + weight > 405:
                chunks.append(''.join(parts)); parts = []; width = 0
            parts.append(term_text(coef, monomial, k == 0, latex=True))
            width += weight
        if parts:
            chunks.append(''.join(parts))
        tex.extend(['%% residual %d' % j, r'\begin{align*}'])
        for k, chunk in enumerate(chunks):
            lead = 'R_{%d}={}& ' % j if k == 0 else '&{} '
            tex.append(lead + chunk.strip() + (r' \\' if k + 1 < len(chunks) else ''))
        tex.append(r'\end{align*}')
        plain.append('R%d = %s' % (j, ''.join(term_text(c, m, k == 0)
                        for k, (c, m) in enumerate(row['terms']))))
        rowmap.append('%d\t%s\t%d' % (j, row['label'], len(row['terms'])))
    tex.append(r'\endgroup')
    (ROOT / 'report/residuals.tex').write_text('\n'.join(tex) + '\n')
    (ROOT / 'equation/residuals.txt').write_text('\n'.join(plain) + '\n')
    (ROOT / 'equation/residual_labels.tsv').write_text('\n'.join(rowmap) + '\n')
    (ROOT / 'equation/variables.tsv').write_text(
        'index\tname\tkind\n' + ''.join('%d\t%s\t%s\n' %
        (i, v['name'], v['kind']) for i, v in enumerate(eq['variables'])))
    ids = [r'The repository snapshot is',
           r'\begin{center}\small\texttt{a0ef2df5bb1f73c35cd334bbc7f53553350ef06a}.\end{center}',
           'The SHA-256 identities below fix the literal input and output.',
           r'\begin{description}[style=nextline]']
    for label, path in [
        ('Pinned 245-variable parent', ROOT / 'inputs/parent245.json'),
        ('Final 225-variable residual specification', eq_path),
        ('Collected 7,867-term polynomial', ROOT / 'equation/expanded_polynomial.json'),
        ('Final metrics', ROOT / 'equation/METRICS.json'),
    ]:
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        ids.extend([r'\item[%s]' % label, r'{\small\texttt{%s}}' % digest])
    ids.extend([r'\end{description}',
                r'The package-wide \path{SHA256SUMS} authenticates the remaining files,',
                r'including this report after PDF compilation. \path{provenance/SOURCES.json}',
                'records the source origins and exact paths. Hashes identify artifacts;',
                'their agreement does not replace the mathematical proof.'])
    (ROOT / 'report/identities.tex').write_text('\n'.join(ids) + '\n')
    print(json.dumps({'result': 'exported', 'rows': len(eq['residuals']),
                      'tex': 'report/residuals.tex'}))


if __name__ == '__main__':
    main()
