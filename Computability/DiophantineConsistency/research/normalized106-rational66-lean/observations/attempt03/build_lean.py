#!/usr/bin/env python3
"""Generate literal 66/67 Lean rows, with the historical 106-syntax binding."""
import hashlib,json,sys
from pathlib import Path
if not sys.flags.isolated or not sys.flags.no_site or sys.flags.optimize:
    raise SystemExit('use python3 -I -S -B without optimization')
HERE=Path(__file__).resolve().parent
ROOT=HERE.parent
TEMPLATE=ROOT/'rational-carrier64-lean-identity/RationalCarrier64.lean'
GRAPH=ROOT/'normalized106-rational66/polynomial.json'
def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
if sha(TEMPLATE)!='8676e328432ca3fd070dbd4abe6ae097137138aff4b2ceeead955e671f8b9a3b':raise RuntimeError('template hash')
if sha(GRAPH)!='61784a1cdc3594174c3e321712322cebdffff20be51ef7f2bc0feb3b8f9498a4':raise RuntimeError('graph hash')
g=json.loads(GRAPH.read_bytes());rows=g['source'];i=next(i for i,r in enumerate(rows) if r[0]=='q2minus1');end=next(i for i,r in enumerate(rows) if r[0]=='R');prefix=rows[:i];suffix=rows[end+1:]
if len(prefix)!=28 or end-i+1!=5 or len(suffix)!=33:raise RuntimeError('unexpected graph cuts')
used={str(v) for row in suffix for v in row[2:]}
aliases=['  let R := rank']
aliases += [f'  let {n} := p {i}' for i,n in enumerate(['beta','K0','MC','MF']) if n in used]
aliases += [f'  let {n} := v {i}' for i,n in enumerate(g['witnesses']) if n in used]
aliases += [f'  let {r[0]} := h.{r[0]}' for r in prefix if r[0] in used]
suffixlean=['def suffix (p : Fin 4 → R) (v : Fin 14 → R) (h : Head R) (rank : R) : R :=',*aliases,
            *[f'  let {name} := {x} {op} {y}' for name,op,x,y in suffix],'  polynomial','']
s=TEMPLATE.read_text()
s=s.replace('import DiophantineConsistency.Carrier65','import DiophantineConsistency.ModelCarrierSyntax',1)
s=s.replace('Literal 64 and 65 row graphs; generated by generate.py from the frozen JSON.',
            'Literal 66 and 67 row graphs; generated by build_lean.py from the frozen JSON.',1)
begin=s.index('def suffix ');end=s.index('def value64 ',begin)
s=s[:begin]+'\n'.join(suffixlean)+'\n'+s[end:]
s=s.replace('DiophantineConsistency.RationalCarrier64','DiophantineConsistency.Normalized106Rational66')
for a,b in [('rank64','rank66'),('rank65','rank67'),('value64','value66'),('value65','value67')]:s=s.replace(a,b)
begin=s.index('/-- Binding to the existing 65-operation arithmetic front. -/')
s=s[:begin]+'''/-- Reassociate the graph's strong-factor product locally. -/
theorem strong_factor (d i c : R) :
    (i*i)*(d*(c*c))*(c*c) = d*((i*(c*c))*(i*(c*c))) := by
  ring

/-- Bind the literal 67-row graph to the historical 106 expression. -/
theorem value67_eq_syntax (p : Fin 4 → ℤ) (v : Fin 14 → R) :
    value67 (fun j => (p j : R)) v =
      (ModelCarrierCurrent.expressionAt106 p).evalRing v := by
  simp only [value67, head, rank67, suffix, ModelCarrierCurrent.expressionAt106,
    Expr.evalRing_add, Expr.evalRing_sub, Expr.evalRing_mul, Expr.evalRing_pow,
    Expr.evalRing_var, Expr.evalRing_constant, Expr.evalRing_ofNat,
    Nat.cast_ofNat, Nat.cast_one, pow_succ, pow_zero, one_mul, strong_factor]
  simp only [mul_assoc]

/-- Literal 66 output equals the 106 syntax under the two fixed-leaf equations. -/
theorem value66_eq_syntax (p : Fin 4 → ℤ) (v : Fin 14 → R) (Urank Wrank : R)
    (hu : (p 0 : R) * Urank = (p 3 : R)) (hw : Wrank = (p 2 : R) - (p 3 : R)) :
    value66 (fun j => (p j : R)) v Urank Wrank =
      (ModelCarrierCurrent.expressionAt106 p).evalRing v := by
  rw [values_equal _ _ Urank Wrank hu hw, value67_eq_syntax]

#print axioms values_equal
#print axioms value67_eq_syntax
#print axioms value66_eq_syntax

end DiophantineConsistency.Normalized106Rational66
'''
out=HERE/'Normalized106Rational66.lean'
if out.exists():raise RuntimeError('refusing to overwrite existing source')
out.write_text(s)
print(sha(out))
