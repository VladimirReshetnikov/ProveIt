"""Find top-level theorem/lemma blocks whose full text (name-normalized) recurs across files."""
import os,re,glob,hashlib,collections,sys
roots=sys.argv[1:]
blocks=collections.defaultdict(list)
start=re.compile(r'^(?:/--[\s\S]*?-/\n)?(?:@\[[^\]]*\]\s*)?(?:private\s+|protected\s+)?(theorem|lemma)\s+(\S+)',re.M)
for r in roots:
    for p in glob.glob(r):
        s=open(p,encoding='utf-8',errors='replace').read()
        if re.search(r'(?i)generated by|do not edit',s[:1500]): continue
        ms=list(start.finditer(s))
        for k,m in enumerate(ms):
            end=ms[k+1].start() if k+1<len(ms) else len(s)
            body=s[m.start():end]
            body=re.split(r'\n(?=(?:/--|def |abbrev |structure |inductive |instance |namespace |end |section |open |variable |noncomputable |private def ))',body)[0]
            name=m.group(2)
            norm=body.replace(name,'NAME').strip()
            if norm.count('\n')<4: continue
            blocks[hashlib.md5(norm.encode()).hexdigest()].append((p,name,norm.count('\n')+1))
dups=[(v[0][2]*(len(v)-1),v) for v in blocks.values() if len({x[0] for x in v})>1]
dups.sort(reverse=True)
print('duplicate groups',len(dups),'redundant lines',sum(d[0] for d in dups))
for save,v in dups[:25]:
    print(save,v[0][2],'x',len(v),v[0][1],'|',', '.join(os.path.basename(x[0]) for x in v[:5]))
