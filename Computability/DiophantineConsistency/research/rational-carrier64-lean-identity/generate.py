#!/usr/bin/env python3
"""Generate the literal-row Lean graph from the two frozen JSON descriptions."""
import hashlib
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
P64 = ROOT / 'rational-carrier64-independent/polynomial.json'
P65 = ROOT / 'rational-carrier64-independent/source/parent65.json'
OUT = HERE / 'RationalCarrier64.lean'

def main():
    d64, d65 = (json.loads(p.read_bytes()) for p in (P64, P65))
    a, b = d64['source'], d65['source']
    if len(a) != 64 or len(b) != 65:
        raise RuntimeError('wrong graph size')
    r64 = next(i for i, row in enumerate(a) if row[0] == 'R')
    r65 = next(i for i, row in enumerate(b) if row[0] == 'R')
    start64 = next(i for i, row in enumerate(a) if row[0] == 'q2minus1')
    start65 = next(i for i, row in enumerate(b) if row[0] == 'q2minus1')
    if a[:start64] != b[:start65] or a[r64 + 1:] != b[r65 + 1:]:
        raise RuntimeError('prefix/suffix mismatch')
    if d64['witnesses'] != d65['witnesses']:
        raise RuntimeError('witness mismatch')
    prefix, rank64, rank65, suffix = a[:start64], a[start64:r64 + 1], b[start65:r65 + 1], a[r64 + 1:]
    def aliases(kind, rs):
        used = {str(value) for row in rs for value in row[2:]}
        if kind == 'head':
            return [f'  let {name} := p {i}' for i,name in enumerate(['beta', 'K0', 'MC', 'MF']) if name in used] + [f'  let {name} := v {i}' for i,name in enumerate(d64['witnesses']) if name in used]
        return [f'  let {row[0]} := h.{row[0]}' for row in prefix if row[0] in used]
    def rows(rs):
        return [f'  let {name} := {x} {op} {y}' for name,op,x,y in rs]
    code = [
        'import DiophantineConsistency.Carrier65', '',
        '/-! Literal 64 and 65 row graphs; generated by generate.py from the frozen JSON. -/',
        'namespace DiophantineConsistency.RationalCarrier64', '',
        'variable {R : Type*} [CommRing R]', '',
        'structure Head (R : Type*) where',
        *[f'  {row[0]} : R' for row in prefix], '',
        'def head (p : Fin 4 → R) (v : Fin 14 → R) : Head R :=',
        *aliases('head', prefix), *rows(prefix), '  ⟨' + ', '.join(row[0] for row in prefix) + '⟩', '',
        'def rank64 (h : Head R) (J Urank Wrank : R) : R :=',
        *aliases('tail', rank64), *rows(rank64), '  R', '',
        'def rank65 (h : Head R) (J MC MF : R) : R :=',
        *aliases('tail', rank65), *rows(rank65), '  R', '',
        'def suffix (p : Fin 4 → R) (v : Fin 14 → R) (h : Head R) (rank : R) : R :=',
        '  let R := rank', *aliases('head', suffix), *aliases('tail', suffix), *rows(suffix), '  polynomial', '',
        'def value64 (p : Fin 4 → R) (v : Fin 14 → R) (Urank Wrank : R) : R :=',
        '  let h := head p v', '  suffix p v h (rank64 h (v 0) Urank Wrank)', '',
        'def value65 (p : Fin 4 → R) (v : Fin 14 → R) : R :=',
        '  let h := head p v', '  suffix p v h (rank65 h (v 0) (p 2) (p 3))', '',
        '/-- Pure commutative-ring identity; neither division nor cancellation is used. -/',
        'theorem rank_identity (beta J gap Urank MC MF : R) (h : beta * Urank = MF) :',
        '    ((beta * J + 1)^2 - 1) * (gap + Urank) + J * (MC - MF) =',
        '      gap * ((beta * J + 1)^2 - 1) + (MC + (beta * J + 1) * MF) * J := by',
        '  have hz : beta * Urank - MF = 0 := sub_eq_zero.mpr h',
        '  calc',
        '    _ = gap * ((beta * J + 1)^2 - 1) + (MC + (beta * J + 1) * MF) * J +',
        '        J * ((beta * J + 1) + 1) * (beta * Urank - MF) := by ring',
        '    _ = _ := by rw [hz, mul_zero, add_zero]', '',
        'theorem ranks_equal (p : Fin 4 → R) (v : Fin 14 → R) (Urank Wrank : R)',
        '    (hu : p 0 * Urank = p 3) (hw : Wrank = p 2 - p 3) :',
        '    rank64 (head p v) (v 0) Urank Wrank =',
        '      rank65 (head p v) (v 0) (p 2) (p 3) := by',
        '  subst Wrank',
        '  change (((p 0 * v 0 + 1) * (p 0 * v 0 + 1)) - 1) *',
        '      ((head p v).gap + Urank) + v 0 * (p 2 - p 3) =',
        '    (head p v).gap * (((p 0 * v 0 + 1) * (p 0 * v 0 + 1)) - 1) +',
        '      (p 2 + (p 0 * v 0 + 1) * p 3) * v 0',
        '  simpa only [pow_two] using rank_identity (p 0) (v 0) (head p v).gap Urank (p 2) (p 3) hu', '',
        '/-- Pointwise equality of the complete literal-row outputs. -/',
        'theorem values_equal (p : Fin 4 → R) (v : Fin 14 → R) (Urank Wrank : R)',
        '    (hu : p 0 * Urank = p 3) (hw : Wrank = p 2 - p 3) :',
        '    value64 p v Urank Wrank = value65 p v := by',
        '  simp only [value64, value65, ranks_equal p v Urank Wrank hu hw]', '',
        'theorem zero_iff (p : Fin 4 → R) (v : Fin 14 → R) (Urank Wrank : R)',
        '    (hu : p 0 * Urank = p 3) (hw : Wrank = p 2 - p 3) :',
        '    value64 p v Urank Wrank = 0 ↔ value65 p v = 0 := by',
        '  rw [values_equal p v Urank Wrank hu hw]', '',
        '/-- Binding to the existing 65-operation arithmetic front. -/',
        'theorem value65_eq_carrier (p : Fin 4 → R) (v : Fin 14 → R) :',
        '    value65 p v = Carrier65.value p v := by',
        '  simp only [value65, head, rank65, suffix, Carrier65.value, Carrier65.core,',
        '    pow_succ, pow_zero, one_mul, mul_assoc]', '',
        '#print axioms values_equal', '#print axioms zero_iff', '#print axioms value65_eq_carrier', '',
        'end DiophantineConsistency.RationalCarrier64', '' ]
    result = '\n'.join(code)
    OUT.write_text(result)
    print('source', hashlib.sha256(result.encode()).hexdigest())
    print('input64', hashlib.sha256(P64.read_bytes()).hexdigest())
    print('input65', hashlib.sha256(P65.read_bytes()).hexdigest())
    print('prefix/rank64/rank65/suffix', len(prefix),len(rank64),len(rank65),len(suffix))

if __name__ == '__main__':
    main()
