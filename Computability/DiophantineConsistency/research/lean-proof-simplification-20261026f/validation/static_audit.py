#!/usr/bin/env python3
"""Read-only lexical Lean audit; NOT an elaborator or a proof checker.

Usage: python static_audit.py PATH/TO/Lean --json audit.json --csv modules.csv
Only source files beneath the supplied directory are read. This script uses
only the Python standard library, makes no network calls, and never runs Lean,
Lake, repository generators, subprocesses, or source code.
"""
from __future__ import annotations
import argparse, collections, csv, hashlib, json, re
from pathlib import Path


def mask_noncode(s: str) -> str:
    """Mask nested Lean comments and quoted strings, retaining line offsets.

    This deliberately is not a complete Lean parser. Macro quotations remain
    code. A quoted identifier may contain a flagged word: review hits manually.
    """
    out = list(s)
    i, n = 0, len(s)
    def blank(a, b):
        for k in range(a,b):
            if out[k] not in '\r\n': out[k] = ' '
    while i < n:
        if s.startswith('--', i):
            j = s.find('\n', i)
            j = n if j < 0 else j
            blank(i,j); i=j
        elif s.startswith('/-', i):
            start=i; depth=1; i+=2
            while i<n and depth:
                if s.startswith('/-',i): depth+=1; i+=2
                elif s.startswith('-/',i): depth-=1; i+=2
                else: i+=1
            blank(start,i)
        elif s[i] == '"':
            start=i; i+=1
            while i<n:
                if s[i]=='\\': i+=2
                elif s[i]=='"': i+=1; break
                else: i+=1
            blank(start,min(i,n))
        elif s[i]=='r' and (m:=re.match(r'r(#+)"',s[i:])):
            start=i; ending='"'+m.group(1); i+=len(m.group(0))
            end=s.find(ending,i); i=n if end<0 else end+len(ending)
            blank(start,i)
        else: i+=1
    return ''.join(out)

PATTERNS = {
    'sorry_or_admit': r'\b(?:sorry|admit|sorryAx)\b',
    'axiom_declaration': r'(?m)^\s*(?:(?:private|protected)\s+)?axiom\s+',
    'native_proof_tactic': r'\bnative_decide\b|\bdecide\s+\+native\b|\bbv_decide\b',
    'native_reflection_symbol': r'\bLean\.(?:ofReduceBool|ofReduceNat|reduceBool|reduceNat)\b',
    'unsafe_or_external': r'\bunsafe\b|@\[\s*(?:extern|implemented_by)\b',
}
DECL_RE = re.compile(r'(?m)^\s*(?:(?:private|protected|noncomputable|unsafe)\s+)*(theorem|lemma|def|abbrev|opaque|axiom|structure|inductive|class|instance)\b')

def audit(root: Path):
    files=[]; hits=[]; modules={}; hashes=collections.defaultdict(list)
    for p in sorted(root.rglob('*.lean')):
        rel=p.relative_to(root).as_posix(); raw=p.read_bytes(); s=raw.decode('utf-8'); code=mask_noncode(s)
        digest=hashlib.sha256(raw).hexdigest(); hashes[digest].append(rel)
        name=rel[:-5].replace('/','.')
        imports=re.findall(r'(?m)^\s*import\s+([^\n]+)',code)
        imports=[t for line in imports for t in line.split()]
        modules[name]=imports
        group='checks' if rel.startswith('checks/') or re.search(r'(?:Checks|Audit)\.lean$',rel) else 'library'
        counts=collections.Counter(DECL_RE.findall(code))
        rec={'path':rel,'module':name,'group':group,'generated_header':bool(re.search(r'Generated by',s[:1500],re.I)),
             'bytes':len(raw),'lines':len(s.splitlines()),'nonblank_code_lines':sum(bool(x.strip()) for x in code.splitlines()),
             'declarations':sum(counts.values()),'theorem_lemma':counts['theorem']+counts['lemma'],
             'print_axioms':len(re.findall(r'#print\s+axioms\b',code)),
             'guard_msgs':len(re.findall(r'#guard_msgs\b',code)),
             'decide_kernel':len(re.findall(r'\bdecide\s+\+kernel\b',code)),
             'sha256':digest,'imports':imports}
        files.append(rec)
        for kind,pat in PATTERNS.items():
            for m in re.finditer(pat,code):
                line=s.count('\n',0,m.start())+1
                # Whitespace in anchored patterns may include earlier newlines.
                at=m.start()+len(m.group(0))-len(m.group(0).lstrip())
                line=s.count('\n',0,at)+1
                hits.append({'path':rel,'line':line,'kind':kind,'match':m.group(0).strip(),
                             'text':s.splitlines()[line-1].strip()})
    local_edges=[{'from':a,'to':b} for a,bs in modules.items() for b in bs if b in modules]
    unresolved=sorted({b for bs in modules.values() for b in bs if b not in modules})
    totals={k:sum(f[k] for f in files) for k in ('bytes','lines','nonblank_code_lines','declarations','theorem_lemma','print_axioms','guard_msgs','decide_kernel')}
    totals.update(files=len(files),check_files=sum(f['group']=='checks' for f in files),generated_files=sum(f['generated_header'] for f in files))
    return {'schema_version':1,'scope':str(root),'warning':'Lexical static audit only; not a transitive axiom or build certificate.',
            'totals':totals,'files':files,'hits':hits,'local_import_edges':local_edges,'external_imports':unresolved,
            'duplicate_content_groups':[ps for ps in hashes.values() if len(ps)>1]}

def main():
    ap=argparse.ArgumentParser(description=__doc__); ap.add_argument('root',type=Path); ap.add_argument('--json',type=Path); ap.add_argument('--csv',type=Path)
    args=ap.parse_args(); result=audit(args.root)
    if args.json: args.json.write_text(json.dumps(result,indent=2,ensure_ascii=False)+'\n')
    if args.csv:
        rows=[{k:v for k,v in f.items() if k!='imports'} for f in result['files']]
        with args.csv.open('w',newline='') as out:
            writer=csv.DictWriter(out,fieldnames=list(rows[0]) if rows else ['path']); writer.writeheader(); writer.writerows(rows)
    print(json.dumps({'totals':result['totals'],'hits':result['hits']},indent=2,ensure_ascii=False))
if __name__=='__main__': main()
