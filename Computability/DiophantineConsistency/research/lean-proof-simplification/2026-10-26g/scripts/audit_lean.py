#!/usr/bin/env python3
"""Reproducible source-size inventory for the DiophantineConsistency Lean subtree.

This is a lexical inventory, not a Lean parser, correctness audit, profiler, or
prediction of proof-term size. Physical lines count splitlines(); code lines
count nonblank lines after nested Lean comments and string literals are blanked.
Declaration counts include attributes and modifiers on the declaration line.
Generated-header and check-file categories are explicit filename/text heuristics.
Run: python3 circuit_metrics.py /path/to/DiophantineConsistency/Lean --output DIR
"""
from __future__ import annotations
import argparse, collections, csv, hashlib, json, re, subprocess
from pathlib import Path

# Preserve line breaks, so anchors remain lines of the original source.
def blank_comments_strings(s: str) -> str:
    out=list(s); i=0; depth=0; quoted=False
    def blank(a,b):
        for k in range(a,b):
            if out[k] not in '\r\n': out[k]=' '
    while i<len(s):
        if depth:
            if s.startswith('/-',i): blank(i,i+2); depth+=1; i+=2
            elif s.startswith('-/',i): blank(i,i+2); depth-=1; i+=2
            else: blank(i,i+1); i+=1
        elif quoted:
            if s[i]=='\\' and i+1<len(s): blank(i,i+2); i+=2
            elif s[i]=='"': blank(i,i+1); quoted=False; i+=1
            else: blank(i,i+1); i+=1
        elif s.startswith('/-',i): blank(i,i+2); depth=1; i+=2
        elif s.startswith('--',i):
            j=s.find('\n',i)
            if j<0:j=len(s)
            blank(i,j); i=j
        elif s[i]=='"': blank(i,i+1); quoted=True; i+=1
        else:i+=1
    return ''.join(out)

THEOREM=re.compile(r'(?m)^[ \t]*(?:@\[[^\n]*\][ \t]*)*(?:(?:private|protected|noncomputable|unsafe)\s+)*(?:theorem|lemma)\s+([^\s(:]+)')
COMMAND=re.compile(r'(?m)^(?:@\[[^\n]*\]\s*)*(?:(?:private|protected|noncomputable|unsafe)\s+)*(?:theorem|lemma|def|abbrev|instance|structure|inductive|namespace|end|section|set_option|open|attribute|variable|local)\b')
TOKENS=['simp','simp_all','simpa','rw','omega','ring','ring_nf','linarith','nlinarith','norm_num','decide','native_decide','sorry','admit','axiom']

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('lean_root',type=Path); ap.add_argument('--output',type=Path,default=Path('metrics'))
    args=ap.parse_args(); root=args.lean_root.resolve(); args.output.mkdir(parents=True,exist_ok=True)
    rows=[]; dup=collections.defaultdict(list); bodies=collections.defaultdict(list)
    for p in sorted(root.rglob('*.lean')):
        rel=p.relative_to(root)
        if any(x in {'.lake','.git','build'} for x in rel.parts):continue
        data=p.read_bytes(); text=data.decode('utf-8'); lines=text.splitlines(); code=blank_comments_strings(text)
        decls=list(THEOREM.finditer(code)); token_counts={t:len(re.findall(r'(?<![\w.])'+t+r'(?![\w.])',code)) for t in TOKENS}
        category='audit/check' if rel.parts[0]=='checks' or p.stem.endswith(('Checks','Audit')) else 'implementation/umbrella'
        row={'path':str(rel),'physical_lines':len(lines),'nonblank_lines':sum(bool(x.strip()) for x in lines),'code_lines_lexical':sum(bool(x.strip()) for x in code.splitlines()),'utf8_bytes':len(data),'max_line_characters':max(map(len,lines),default=0),'theorem_lemma_declarations_lexical':len(decls),'generated_header':'Generated by' in '\n'.join(lines[:30]),'category':category,'sha256':hashlib.sha256(data).hexdigest(),**{t+'_tokens':n for t,n in token_counts.items()}}
        rows.append(row);dup[row['sha256']].append(str(rel))
        commands=list(COMMAND.finditer(code))
        for m in decls:
            # The block ends at the next unindented command. Extract only tactic
            # proofs; this is a candidate finder, not a semantic clone detector.
            end=next((x.start() for x in commands if x.start()>m.start() and x.start()>=m.end()),len(code))
            block=code[m.end():end];start=re.search(r':=\s*by\b',block)
            if start:
                body=block[start.end():].strip();n=sum(bool(x.strip()) for x in body.splitlines())
                if n>=4:
                    key=' '.join(body.split());bodies[key].append({'path':str(rel),'declaration':m.group(1),'line':code[:m.start()].count('\n')+1,'body_nonblank_lines':n})
    sums=['physical_lines','nonblank_lines','code_lines_lexical','utf8_bytes','theorem_lemma_declarations_lexical']
    def total(rs):return {'files':len(rs),**{k:sum(x[k] for x in rs) for k in sums}}
    try:sha=subprocess.run(['git','-C',str(root),'rev-parse','HEAD'],capture_output=True,text=True,check=True).stdout.strip()
    except Exception:sha=None
    summary={'source_commit':sha,'root_name':root.name,'definitions':{'physical_lines':'len(UTF-8 source.splitlines())','nonblank_lines':'physical lines containing non-whitespace characters','code_lines_lexical':'nonblank lines after nested comments and ordinary string literals are replaced with spaces','theorem_lemma_declarations_lexical':'anchored lexical count; attributes/modifiers supported, not a Lean elaboration count','token_counts':'lexical token appearances; not dynamic tactic counts','generated_header':'literal Generated by in first 30 source lines','audit/check':'path under checks/ or filename stem ending Checks/Audit','duplicate_proof_bodies':'lexical candidates with >=4 nonblank body lines after := by, whitespace-normalized; manual inspection required'},'totals':total(rows),'by_category':{k:total([r for r in rows if r['category']==k]) for k in sorted({r['category'] for r in rows})},'by_generated_header':{str(k):total([r for r in rows if r['generated_header']==k]) for k in (True,False)},'token_totals':{t:sum(r[t+'_tokens'] for r in rows) for t in TOKENS},'exact_duplicate_files':[v for v in dup.values() if len(v)>1],'largest_files':sorted(rows,key=lambda r:r['physical_lines'],reverse=True)[:30]}
    (args.output/'summary.json').write_text(json.dumps(summary,ensure_ascii=False,indent=2)+'\n')
    (args.output/'files.json').write_text(json.dumps(rows,ensure_ascii=False,indent=2)+'\n')
    with (args.output/'files.csv').open('w',newline='') as f:
        w=csv.DictWriter(f,fieldnames=list(rows[0]));w.writeheader();w.writerows(rows)
    candidates=sorted((v for v in bodies.values() if len(v)>1),key=lambda v:sum(x['body_nonblank_lines'] for x in v),reverse=True)
    (args.output/'duplicate-proof-candidates.json').write_text(json.dumps(candidates,ensure_ascii=False,indent=2)+'\n')
    # Focused, reproducible measurements used by the circuit audit.
    family=root/'DiophantineConsistency'
    focused={'step_files':[], 'row_identity_files':[], 'register_files':[]}
    for stem in ['GapCircuitSteps66','SplitCircuitSteps59']:
        path=family/(stem+'.lean')
        if not path.exists(): continue
        text=path.read_text(); lines=text.splitlines()
        step=next(i for i,x in enumerate(lines) if x.startswith('theorem natural_step_'))
        power=next(i for i,x in enumerate(lines) if x.startswith('theorem natural_power_'))
        focused['step_files'].append({'file':stem+'.lean','physical_lines':len(lines),
            'gate_theorems':len(re.findall(r'^theorem natural_step_',text,re.M)),
            'power_theorems':len(re.findall(r'^theorem natural_power_',text,re.M)),
            'gate_declaration_segment_lines':power-step,
            'power_declaration_segment_lines':len(lines)-1-power})
    for stem in ['GapCertificate66','SplitCertificate59','NativeQuadraticParent']:
        path=family/(stem+'.lean')
        if not path.exists(): continue
        text=path.read_text(); lines=text.splitlines()
        first=next(i for i,x in enumerate(lines) if x.startswith('private theorem rowIdentity_'))
        last=next(i for i,x in enumerate(lines) if x.startswith('theorem rowValue_eq_'))
        focused['row_identity_files'].append({'file':stem+'.lean',
            'row_identity_declarations':len(re.findall(r'^private theorem rowIdentity_',text,re.M)),
            'row_identity_segment_lines':last-first})
    for stem in ['GapCircuitRegisters66','SplitCircuitRegisters59','GapCircuitRecipe66','SplitCircuitRecipe59']:
        path=family/(stem+'.lean')
        if not path.exists(): continue
        text=path.read_text(); lines=text.splitlines()
        focused['register_files'].append({'file':stem+'.lean','physical_lines':len(lines),
            'utf8_bytes':len(text.encode()),'max_line_characters':max(map(len,lines)),
            'step_name_occurrences':len(re.findall(r'\bnatural_step_\d+\b',text)),
            'power_name_occurrences':len(re.findall(r'\bnatural_power_\d+\b',text))})
    gap=family/'GapCircuitTranslation66.lean'; split=family/'SplitCircuitTranslation59.lean'
    substitutions=[['GapCircuit','SplitCircuit'],['66','59'],['H2082','split116'],
        ['Fin 11','Fin 12'],['Node 9 11','Node 9 12'],['477','508'],['484','515'],
        ['421','452'],['428','459'],['476','507'],['483','514'],
        ['443-operation','473-operation'],['450-operation','480-operation']]
    if gap.exists() and split.exists():
        transformed=gap.read_text()
        for before,after in substitutions: transformed=transformed.replace(before,after)
        focused['translation_comparison']={'substitutions_in_order':substitutions,
            'exactly_equal_after_substitutions':transformed==split.read_text()}
    (args.output/'focused-circuits.json').write_text(json.dumps(focused,ensure_ascii=False,indent=2)+'\n')
    print(json.dumps({k:summary[k] for k in ['source_commit','totals','by_category','by_generated_header','token_totals']},ensure_ascii=False,indent=2))
    print('Exact duplicate files:',len(summary['exact_duplicate_files']))
    print('Duplicate tactic-body candidate clusters:',len(candidates))
if __name__=='__main__':main()
