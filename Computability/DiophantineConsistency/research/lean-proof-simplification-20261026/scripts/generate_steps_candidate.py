#!/usr/bin/env python3
"""Prepare non-mutating Steps refactor candidates from pinned Lean source.

The generator derives exponent labels from existing theorem statements. A
Lean PowerStep certificate rechecks all labels against the literal circuit;
the generator is not part of the mathematical trust boundary.
"""
from pathlib import Path
import argparse
import difflib
import hashlib
import json
import re

FAMILIES = (
    ("GapCircuitSteps66", "GapCircuit66", 11, 484, 20),
    ("SplitCircuitSteps59", "SplitCircuit59", 12, 515, 36),
)


def render(source, module, circuit, fixed, length, base):
    power_re = re.compile(
        r"theorem natural_power_(\d+) (\(p : Fin \d+ → R\) \(x : Fin 9 → R\) :\n"
        r"    naturalRegister p x \d+ = naturalRegister p x (\d+) \^ (\d+)) := by\n"
        r".*?(?=\ntheorem |\nend )", re.S)
    matches = list(power_re.finditer(source))
    assert matches, module
    labels = [0] * length
    labels[base] = 1
    for m in matches:
        assert int(m[3]) == base
        labels[int(m[1])] = int(m[4])
    label_lines = ["    " + ",".join(map(str, labels[i:i+20]))
                   for i in range(0, len(labels), 20)]
    label_data = ",\n".join(label_lines)
    helpers = f'''
/-- One local-equation theorem specializes to every generated step. -/
private theorem natural_step (p : Fin {fixed} → R) (x : Fin 9 → R)
    (i : Fin {length}) :
    naturalRegister p x i.val =
      ({circuit}.naturalNodes.getD i.val (.literal 0)).evalAt p x
        (naturalRegister p x) :=
  run_node_equation p x {circuit}.naturalNodes {circuit}.natural_topological i.val
    (by simpa only [{circuit}.natural_length] using i.isLt)

/-- Zero marks a register with no asserted pure-power specification. -/
private def naturalPowerLabels : List ℕ :=
  [
{label_data}
  ]

private def naturalPowerLabel (i : ℕ) : ℕ := naturalPowerLabels.getD i 0

set_option maxHeartbeats 12000000 in
private theorem natural_power_certificate : ∀ i : Fin {length},
    i.val ≠ {base} → naturalPowerLabel i.val ≠ 0 →
      PowerStep {circuit}.naturalNodes naturalPowerLabel i.val := by
  decide +kernel

/-- Reuses the existing generic soundness theorem for exponent labels. -/
private theorem natural_power (p : Fin {fixed} → R) (x : Fin 9 → R)
    (i : Fin {length}) (hi : naturalPowerLabel i.val ≠ 0) :
    naturalRegister p x i.val = naturalRegister p x {base} ^ naturalPowerLabel i.val :=
  run_power p x {circuit}.naturalNodes {circuit}.natural_topological
    naturalPowerLabel {base} (by decide)
    (fun j hj => natural_power_certificate
      ⟨j, by simpa only [{circuit}.natural_length] using hj⟩)
    i.val (by simpa only [{circuit}.natural_length] using i.isLt) hi
'''
    source = source.replace("import DiophantineConsistency.ArithmeticDAGSemantics",
                            "import DiophantineConsistency.ArithmeticDAGPowers", 1)
    source = source.replace("Generated by tools/", "Refactor candidate; original generator tools/", 1)
    source = source.replace("All results follow from", "Intended proofs use", 1)
    source = source.replace("theorem natural_step_0", helpers + "\ntheorem natural_step_0", 1)
    pattern = (r"  run_node_equation p x " + circuit + r"\.naturalNodes " +
               circuit + r"\.natural_topological (\d+)\n" +
               r"    \(by rw \[" + circuit + r"\.natural_length\];decide\)")
    source, nsteps = re.subn(pattern,
        lambda m: f"  natural_step p x ⟨{m[1]}, by decide⟩", source)
    assert nsteps == length, (module, nsteps)
    source, npowers = power_re.subn(lambda m:
        f"theorem natural_power_{m[1]} {m[2]} :=\n"
        f"  natural_power p x ⟨{m[1]}, by decide⟩ (by decide)\n", source)
    assert npowers == len(matches)
    return source, nsteps, npowers


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("repo", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    patch = []
    stats = []
    for module, circuit, fixed, length, base in FAMILIES:
        rel = Path("Computability/DiophantineConsistency/Lean/DiophantineConsistency") / (module + ".lean")
        before = (args.repo / rel).read_text()
        after, steps, powers = render(before, module, circuit, fixed, length, base)
        target = args.output / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(after)
        patch.extend(difflib.unified_diff(before.splitlines(True), after.splitlines(True),
                     fromfile="a/" + str(rel), tofile="b/" + str(rel)))
        stats.append({"file": str(rel), "source_sha256": hashlib.sha256(before.encode()).hexdigest(),
                      "candidate_sha256": hashlib.sha256(after.encode()).hexdigest(),
                      "source_lines": len(before.splitlines()),
                      "candidate_lines": len(after.splitlines()),
                      "source_nonblank_lines": sum(bool(s.strip()) for s in before.splitlines()),
                      "candidate_nonblank_lines": sum(bool(s.strip()) for s in after.splitlines()),
                      "public_step_statements_preserved": steps,
                      "public_power_statements_preserved": powers,
                      "source_ring_calls": len(re.findall(r"^\s*ring$", before, re.M)),
                      "candidate_ring_calls": len(re.findall(r"^\s*ring$", after, re.M)),
                      "status": "candidate source; Lean compilation not yet performed"})
    (args.output / "generated-steps.patch").write_text("".join(patch))
    (args.output / "generated-steps-metrics.json").write_text(json.dumps(stats, indent=2) + "\n")
    print(json.dumps(stats, indent=2))


if __name__ == "__main__":
    main()
