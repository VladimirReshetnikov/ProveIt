#!/usr/bin/env python3
"""Replay the packaged finite certificates using Python's standard library.

Runs in an isolated temporary directory, checks every generated exact result
against the shipped reference JSON, and leaves the delivered files unchanged.
The --quick option omits only the independent ten-group root replay.
"""
from pathlib import Path
import argparse
import json
import os
import shutil
import subprocess
import sys
import tempfile
import time


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


ROOT = Path(__file__).resolve().parent
CODE = ROOT / 'code'
RESULTS = ROOT / 'results'

# A generated filename of None means that the complete result is JSON stdout.
# Dependencies are deliberately ordered: independent audits read certificates
# just regenerated by the producing checkers in the same temporary directory.
TASKS = (
    ('anchored_root', 'anchored_backend_checker.py', (),
     'anchored_backend_certificate.json', 'anchored_backend_certificate.json'),
    ('anchored_thirteen', 'check_anchored_thirteen.py', (),
     'anchored_thirteen_certificate.json', 'anchored_thirteen_certificate.json'),
    ('independent_thirteen_and_schedule', 'independent_thirteen_audit.py', (),
     'independent_thirteen_audit.json', 'independent_thirteen_audit.json'),
    ('inherited_nine_consistency', 'check_consistent_certificate.py', (),
     None, 'consistent_certificate.json'),
    ('inherited_nine_optimum', 'fixed_menu_optimal_certificate.py', (),
     'fixed_menu_optimal_certificate.json', 'fixed_menu_optimal_certificate.json'),
    ('local_obstructions', 'check_local_obstructions.py', (),
     None, 'local_obstruction_checks.json'),
    ('selector_semantics', 'verify_selector.py', (),
     'selector_checks.json', 'selector_checks.json'),
    ('independent_anchored_root', 'independent_affine_audit.py',
     ('anchored_backend_certificate.json', '--output', 'independent_anchored_audit.json'),
     'independent_anchored_audit.json', 'independent_anchored_audit.json'),
)

# Exact rational intervals, coefficients, witnesses, plans, support counts,
# pruning bounds, and all acceptance metadata are compared. These fields
# contain wall-clock timing or convenient decimal displays of exact fields.
DISPLAY_OR_TIMING_KEYS = frozenset((
    'elapsed_seconds', 'coefficient_display', 'coefficient_displays',
    'displays', 'exact_weight_display',
))


def exact_view(value):
    if isinstance(value, dict):
        result = {}
        for key, item in value.items():
            if key in DISPLAY_OR_TIMING_KEYS:
                continue
            if key == 'certificate' and isinstance(item, str):
                result[key] = Path(item).name
            else:
                result[key] = exact_view(item)
        return result
    if isinstance(value, list):
        return [exact_view(item) for item in value]
    return value


def first_difference(expected, actual, location='$'):
    if type(expected) is not type(actual):
        return '{}: types differ ({} vs {})'.format(
            location, type(expected).__name__, type(actual).__name__)
    if isinstance(expected, dict):
        if set(expected) != set(actual):
            return '{}: keys differ (missing {}, extra {})'.format(
                location, sorted(set(expected)-set(actual)),
                sorted(set(actual)-set(expected)))
        for key in sorted(expected):
            difference = first_difference(expected[key], actual[key], location+'.'+key)
            if difference:
                return difference
        return None
    if isinstance(expected, list):
        if len(expected) != len(actual):
            return '{}: list lengths differ ({} vs {})'.format(
                location, len(expected), len(actual))
        for i, (left, right) in enumerate(zip(expected, actual)):
            difference = first_difference(left, right, '{}[{}]'.format(location, i))
            if difference:
                return difference
        return None
    if expected != actual:
        return '{}: expected {}, obtained {}'.format(
            location, repr(expected)[:180], repr(actual)[:180])
    return None


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--quick', action='store_true',
                        help='skip only the independent ten-group root replay')
    parser.add_argument('--output', type=Path,
                        help='optionally save the verification summary to this path')
    args = parser.parse_args()
    require(sys.version_info >= (3, 9), 'Python 3.9 or later is required')
    require(CODE.is_dir() and RESULTS.is_dir(), 'Missing code/ or results/ directory')
    started = time.perf_counter()
    records = []
    skipped = []
    environment = os.environ.copy()
    environment['PYTHONDONTWRITEBYTECODE'] = '1'
    environment['PYTHONHASHSEED'] = '0'
    environment['PYTHONPATH'] = ''
    flags = ['-O'] if sys.flags.optimize else []

    with tempfile.TemporaryDirectory(prefix='sat-compatible-affine-') as temporary:
        work = Path(temporary)
        for source in CODE.glob('*.py'):
            shutil.copy2(source, work/source.name)
        # Adjacent JSON supports direct use of the independent scripts.
        # The two producers below regenerate it before either audit runs.
        for source in CODE.glob('*.json'):
            shutil.copy2(source, work/source.name)
        for name, script, arguments, generated, reference in TASKS:
            if args.quick and name == 'independent_anchored_root':
                skipped.append(name)
                continue
            print('Checking {} ...'.format(name), file=sys.stderr, flush=True)
            step_started = time.perf_counter()
            command = [sys.executable] + flags + [str(work/script)] + list(arguments)
            process = subprocess.run(command, cwd=work, env=environment,
                                     capture_output=True, text=True)
            require(process.returncode == 0,
                    '{} failed with exit code {}\n{}\n{}'.format(
                        name, process.returncode,
                        process.stdout[-4000:], process.stderr[-4000:]))
            if generated is None:
                actual = json.loads(process.stdout)
                (work/reference).write_text(json.dumps(actual, indent=2)+'\n')
            else:
                target = work/generated
                require(target.is_file(), '{} did not generate {}'.format(name, generated))
                actual = json.loads(target.read_text())
            expected = json.loads((RESULTS/reference).read_text())
            expected_status = ('finite checks passed; proofs are in the note'
                               if name == 'local_obstructions' else 'PASS')
            require(actual.get('status') == expected_status,
                    '{} returned an unexpected status'.format(name))
            difference = first_difference(exact_view(expected), exact_view(actual))
            require(difference is None,
                    '{} differs from the frozen exact reference: {}'.format(name, difference))
            records.append({'check': name, 'status': 'PASS', 'reference': reference,
                            'exact_reference_match': True,
                            'elapsed_seconds': round(time.perf_counter()-step_started, 6)})
            print('  PASS ({:.3f} s)'.format(records[-1]['elapsed_seconds']),
                  file=sys.stderr, flush=True)

    summary = {
        'status': 'PASS',
        'mode': 'quick' if args.quick else 'all',
        'python_version': sys.version.split()[0],
        'child_optimization_flag': '-O' if flags else 'none',
        'checks_passed': len(records),
        'checks_skipped': skipped,
        'checks': records,
        'safe_eventual_time_and_space_coefficient': '29.149',
        'reference_comparison': (
            'Exact JSON fields match; wall-clock times and decimal displays are excluded, '
            'and input certificate paths are compared by filename.'),
        'isolation': 'All checker writes occurred in an automatically removed temporary directory.',
        'elapsed_seconds': round(time.perf_counter()-started, 6),
        'scope': (
            'Finite support certificates, exact schedule bounds, selector fixtures, and scoped '
            'obstruction checks. This does not implement or independently rebuild the imported '
            'analytic contractor, matrix algorithms, or complete SAT solver.'),
    }
    text = json.dumps(summary, indent=2)+'\n'
    if args.output is not None:
        destination = args.output.resolve()
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(text)
    print(text, end='')


if __name__ == '__main__':
    try:
        main()
    except (RuntimeError, OSError, ValueError, json.JSONDecodeError) as error:
        print('VERIFICATION FAILED: {}'.format(error), file=sys.stderr)
        raise SystemExit(1)
