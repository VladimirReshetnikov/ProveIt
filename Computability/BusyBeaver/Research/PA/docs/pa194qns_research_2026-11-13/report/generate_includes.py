#!/usr/bin/env python3
"""Regenerate report data tables from frozen evidence; standard library only."""
from pathlib import Path
import json

HERE=Path(__file__).resolve().parent
ROOT=HERE.parent

def read(path):
    return json.loads((ROOT/path).read_text())

def esc(value):
    swaps={'\\':r'\textbackslash{}','&':r'\&','%':r'\%','$':r'\$',
           '#':r'\#','_':r'\_','{':r'\{','}':r'\}',
           '~':r'\textasciitilde{}','^':r'\textasciicircum{}'}
    return ''.join(swaps.get(c,c) for c in str(value)).replace(chr(96),'')

def number(value):
    return f'{value:,}'

def write(name,text):
    (HERE/name).write_text('% Generated by generate_includes.py.\n'+text+'\n')

def metrics():
    a=read('machines/PA194QNS/construction_receipt.json')
    b=read('machines/PA194QS/construction_receipt.json')
    ia=read('verification/recorded/PA194QNS/receipt.json')
    ib=read('verification/recorded/PA194QS/receipt.json')
    rows=[
      ('Working controls / transition rows','194 / 388','194 / 388'),
      ('Primitive source sites',number(a['source_sites']),number(b['source_sites'])),
      ('Zero/positive source outcomes',number(a['source_outcomes']),number(b['source_outcomes'])),
      ('Construction symbolic steps',number(a['symbolic_runtime']['total_steps']),number(b['symbolic_runtime']['total_steps'])),
      ('Independent literal symbolic steps',number(ia['symbolic_steps']),number(ib['symbolic_steps'])),
      ('Maximum literal steps per contract',ia['maximum_symbolic_steps'],ib['maximum_symbolic_steps']),
      ('Smallest duration constant',ia['minimum_positive_duration_constant'],ib['minimum_positive_duration_constant']),
      ('Generic list lemmas rederived',ia['list_lemmas_rederived_from_actual_rows'],ib['list_lemmas_rederived_from_actual_rows']),
      ('Simultaneous local fold cases',a['simultaneous_fold_cases'],b['simultaneous_fold_cases']),
      ('Literal blank initialization steps',number(ia['startup_steps']),number(ib['startup_steps']))]
    body='\n'.join(' & '.join(map(esc,row))+r'\\' for row in rows)
    write('verified_summary.tex',r'''\begin{center}\small
\begin{tabular}{lrr}
\toprule Verified quantity & PA194QNS & PA194QS\\\midrule
'''+body+r'''
\bottomrule\end{tabular}\end{center}
The two symbolic step totals count operations in their respective proof
engines; they are not measurements of a particular natural-valued TM run.
Both engines cover arbitrary register values, not a finite register bound.''')

