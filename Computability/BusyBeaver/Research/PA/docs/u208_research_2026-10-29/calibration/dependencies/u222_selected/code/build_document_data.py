#!/usr/bin/env python3
"""Generate exact LaTeX metadata and the complete table appendix from this release."""
from pathlib import Path
import hashlib
import json
import sys


def require(ok, message):
    if not ok:
        raise ValueError(message)


def main():
    root = Path(__file__).resolve().parent.parent
    source = json.loads((root / 'machine/sites.json').read_text())
    construction = json.loads((root / 'machine/construction.json').read_text())
    summary = json.loads((root / 'machine/machine_summary.json').read_text())
    boot = json.loads((root / 'evidence/startup.json').read_text())
    runtime = json.loads((root / 'evidence/runtime.json').read_text())
    n = summary['working_states']
    cases = sum(2 if op == 'CD' else 1 for _, op, _ in source)
    require(runtime['status'] == 'UNIVERSAL_MATHEMATICAL_PASS', 'Runtime did not pass')
    require(runtime['expected_cases'] == runtime['proved_cases'] == cases,
            'Incomplete runtime coverage')
    require(boot['status'] == 'CALIBRATED_DIRTY_ROOT_SEED', 'Startup did not pass')
    require(construction['unshifted'] and not construction['upper_first'],
            'This paper describes the unshifted, lower-first construction')
    table = {}
    for line in (root / 'machine/u.tm').read_text().splitlines():
        if not line or line.startswith('#'):
            continue
        q, bit, w, d, target = line.split()
        table[int(q), int(bit)] = f'{w}{d}{target}'
    require(set(table) == {(q,b) for q in range(n) for b in (0,1)},
            'Dense table is incomplete')
    values = {
        'Nstates': n, 'LastState': n-1, 'Saving': 238-n,
        'Nrows': len(table), 'Nsites': len(source),
        'Ndag': construction['metrics']['dag_nodes'],
        'Ndepth': construction['metrics']['maximum_depth'],
        'Nzeros': construction['metrics']['maximum_zero_run'],
        'Ncases': cases, 'BootSteps': boot['steps'],
        'ClauseOrder': 'lower-first', 'Hbody': 'I(L_n,I(U_n,F))',
        'DenseHash': summary['dense_sha256'],
        'NativeHash': summary['native_sha256'],
        'SourceHash': summary['source_sha256'],
    }
    for name, filename in [('DenseHash','u.tm'),('NativeHash','u.native.tm'),
                            ('SourceHash','sites.json')]:
        require(hashlib.sha256((root/'machine'/filename).read_bytes()).hexdigest()
                == values[name], 'Machine identity mismatch')
    (root/'paper/metadata.tex').write_text(
        '% Generated by code/build_document_data.py; do not edit by hand.\n' +
        ''.join('\\newcommand{\\'+name+'}{'+str(value)+'}\n'
                for name,value in values.items()))
    width = (n+2)//3
    lines = [
        '% Generated from every row of machine/u.tm.\n',
        '\\small\n',
        '\\begin{longtable}{@{}rll@{\\hspace{1.2em}}rll@{\\hspace{1.2em}}rll@{}}\n',
        '\\toprule\n',
        '$q$ & read 0 & read 1 & $q$ & read 0 & read 1 & $q$ & read 0 & read 1\\\\\n',
        '\\midrule\\endfirsthead\n',
        '\\toprule\n',
        '$q$ & read 0 & read 1 & $q$ & read 0 & read 1 & $q$ & read 0 & read 1\\\\\n',
        '\\midrule\\endhead\n',
        '\\bottomrule\\endfoot\n',
    ]
    for j in range(width):
        cells = []
        for k in range(3):
            q = j+k*width
            cells.extend([str(q), '\\texttt{'+table[q,0]+'}',
                           '\\texttt{'+table[q,1]+'}'] if q<n else ['','',''])
        lines.append(' & '.join(cells)+'\\\\\n')
    lines.extend(['\\end{longtable}\n','\\normalsize\n'])
    (root/'paper/transition_table.tex').write_text(''.join(lines))
    print(json.dumps({'status':'DOCUMENT_DATA_MATCH_EXACT_MACHINE', **values}, indent=2))


if __name__ == '__main__':
    main()
