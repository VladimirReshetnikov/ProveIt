#!/usr/bin/env python3
"""Regenerate, or audit, the exact LaTeX appendix from the dense table."""
from pathlib import Path
import argparse
import tm

ROOT = Path(__file__).resolve().parents[1]


def render():
    table = tm.read_table((ROOT / 'machine/gc215.tm').read_bytes())
    assert set(table) == {(q, b) for q in range(215) for b in (0, 1)}
    lines = [r'% Generated by checks/render_dense_table.py; audited by verify.py.',
             r'\begingroup\small',
             r'\setlength{\tabcolsep}{4pt}',
             r'\begin{longtable}{@{}rll@{\qquad}rll@{\qquad}rll@{\qquad}rll@{}}',
             r'\toprule',
             r'$q$ & Read 0 & Read 1 & $q$ & Read 0 & Read 1 & $q$ & Read 0 & Read 1 & $q$ & Read 0 & Read 1\\',
             r'\midrule\endfirsthead',
             r'\toprule',
             r'$q$ & Read 0 & Read 1 & $q$ & Read 0 & Read 1 & $q$ & Read 0 & Read 1 & $q$ & Read 0 & Read 1\\',
             r'\midrule\endhead',
             r'\midrule\multicolumn{12}{r}{Continued on the next page}\\\endfoot',
             r'\bottomrule\endlastfoot']
    for i in range(54):
        cells = []
        for q in (i, i + 54, i + 108, i + 162):
            if q >= 215:
                cells.extend(['', '', ''])
                continue
            cells.append(str(q))
            for b in (0, 1):
                w, d, z = table[q, b]
                label = 'H' if z == 215 else str(z)
                cells.append(r'\texttt{' + f'{w}{"R" if d == 1 else "L"}{label}' + '}')
        lines.append(' & '.join(cells) + r'\\')
    lines.extend([r'\end{longtable}', r'\endgroup', ''])
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    target = ROOT / 'report/sections/dense_table.tex'
    expected = render()
    if args.write:
        target.write_text(expected)
    else:
        assert target.read_text() == expected, 'Dense appendix differs from machine table'
    print('PASS: all 430 dense transition rows agree with the LaTeX appendix.')


if __name__ == '__main__':
    main()
