ROW_KEYS = [(75,0),(75,1),(255,0),(255,1),(97,0),(97,1),
            (112,0),(131,1),(73,0),(73,1),(83,0),(83,1),
            (95,0),(95,1),(109,0),(109,1),(112,1),(131,0),(48,0),(48,1),(63,0),(63,1)]

def pinned(path, kind):
    data = path.read_bytes()
    if hashlib.sha256(data).hexdigest() != PINS[kind]:
        raise ValueError(f"changed {kind} input: {path}")
    return data

def parse(data):
    start, rows = None, {}
    for line in data.decode('ascii').splitlines():
        if line.startswith('#! start '):
            if start is not None: raise ValueError('duplicate start')
            start = int(line.split()[-1])
        if not line or line.startswith('#'): continue
        q,b,w,d,t = line.split()
        q,b,w,t = map(int,(q,b,w,t))
        if (q,b) in rows or b not in (0,1) or w not in (0,1) or d not in ('L','R'):
            raise ValueError('invalid or duplicate row')
        rows[q,b]=(w,d,t)
    return start, rows

def generate(canonical, old, renumbering):
    start, rows = parse(pinned(canonical,'canonical'))
    oldstart, oldrows = parse(pinned(old,'old'))
    mapping = json.loads(pinned(renumbering,'renumbering'))
    labels = mapping['canonical_to_old']
    oldnew = {int(k):v for k,v in mapping['old_to_canonical'].items()}
    if start != 0 or oldstart != 97 or len(labels) != 250 or len(set(labels)) != 250:
        raise ValueError('invalid start or state census')
    if oldnew != {**{q:i for i,q in enumerate(labels)},254:250}:
        raise ValueError('renumbering is not the exact bijection plus terminal')
    if set(rows) != {(q,b) for q in range(250) for b in (0,1)}:
        raise ValueError('canonical table is not exactly 500 total rows')
    if set(oldrows) != {(q,b) for q in labels for b in (0,1)}:
        raise ValueError('old table domains differ')
    converted = {(oldnew[q],b):(w,d,oldnew[t]) for (q,b),(w,d,t) in oldrows.items()}
    if converted != rows or any(t>250 for w,d,t in rows.values()):
        raise ValueError('row-by-row renumbering or target bound failed')
    if [(q,b) for (q,b),(w,d,t) in rows.items() if t==250] != [(74,1)]:
        raise ValueError('unexpected halt edge')
    if oldnew[96] != 92: raise ValueError('wrong dispatch state')
    for target, incoming in [(97,{(255,0)}),(255,{(75,0)})]:
        if {k for k,v in oldrows.items() if v[2]==target} != incoming:
            raise ValueError('incoming graph changed')
    def literal(row):
        w,d,t=row
        return f"({'true' if w else 'false'}, .{'right' if d=='R' else 'left'}, {t})"
    lines=[f"  ({literal(rows[q,0])}, {literal(rows[q,1])}){',' if q<249 else ''} -- {q}; old{labels[q]}" for q in range(250)]
    text=HEADER+'\n'.join(lines)+BODY
    text+='\n'.join('  '+', '.join(map(str,labels[i:i+20]))+(',' if i+20<250 else '') for i in range(0,250,20))
    text+=MAPPING+'\n'.join(f'  | {old} => {new}' for new,old in enumerate(labels))+FOOTER
    for q,b in ROW_KEYS:
        w,d,t=oldrows[q,b]
        if t==254: raise ValueError('unexpected key-row halt')
        bs='true' if b else 'false'
        text+=f'''\ntheorem rowPrefix250_old{q}_{bs} :
    machinePrefix250.transition (oldStatePrefix250 {q}) {bs} =
      ⟨{'true' if w else 'false'}, .{'right' if d=='R' else 'left'}, some (oldStatePrefix250 {t})⟩ := by decide +kernel
'''
    return text+'\nend SetTheory.BusyBeaver.ZFC\n'

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--source',type=Path,default=HERE/'candidate-prefix250/zfc_prefix250.tm')
    p.add_argument('--old-source',type=Path,default=HERE/'candidate-prefix250/zfc_prefix250_old.tm')
    p.add_argument('--renumbering',type=Path,default=HERE/'candidate-prefix250/renumbering.json')
    p.add_argument('--output',type=Path,default=HERE.parents[1]/'Lean/BusyBeaver/ZFC/TablePrefix250.lean')
    p.add_argument('--check',action='store_true')
    a=p.parse_args()
    result=generate(a.source,a.old_source,a.renumbering)
    if a.check:
        if a.output.read_text()!=result: raise ValueError('generated source differs')
    else:
        a.output.parent.mkdir(parents=True,exist_ok=True)
        a.output.write_text(result)
    print(json.dumps({'status':'IDENTICAL' if a.check else 'GENERATED','working_states':250,
        'transition_rows':500,'start':0,'dispatch':92,'halt':250,'input_sha256':PINS,
        'source_sha256':hashlib.sha256(result.encode()).hexdigest(),'kernel_checked':False}))

if __name__=='__main__':main()
