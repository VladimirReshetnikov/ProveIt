#!/usr/bin/env python3
"""Generate BusyBeaver/ZFC/RMEquiv254.lean: the path semantics of the 219-node DAG.

`RMEquiv.halts_iff_iterHalts` needs a well-formedness certificate: a height
table `H` (acyclicity within the decoder fuel) and break/continue bound tables
`B`, `C` (nothing escapes the root). This script computes the least such
tables for `Dag254.dagNodes` and writes them as literals; the Lean kernel
re-checks them with `RMEquiv.wfCheck`, so the script is untrusted.

Usage (from the repository root):
    py -I Computability/BusyBeaver/Research/ZFC/generate_rmequiv254.py
"""

from __future__ import annotations

import re
import sys
from functools import lru_cache
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
SOURCE = REPO / "Computability/BusyBeaver/Lean/BusyBeaver/ZFC/Dag254.lean"
TARGET = REPO / "Computability/BusyBeaver/Lean/BusyBeaver/ZFC/RMEquiv254.lean"
ROW = re.compile(r"^\s*\|\s*(\d+)\s*=>\s*\((\(?\.[a-z]+(?:\s+\d+)?\)?),\s*(\(?\.[a-z]+(?:\s+\d+)?\)?)\)", re.M)
NN = 219


def parse(edge: str) -> tuple[str, int]:
    parts = edge.strip().strip("()").lstrip(".").split()
    return (parts[0], int(parts[1]) if len(parts) > 1 else 0)


def main() -> int:
    text = SOURCE.read_text(encoding="utf-8")
    nodes = {int(m.group(1)): (parse(m.group(2)), parse(m.group(3))) for m in ROW.finditer(text)}
    assert sorted(nodes) == list(range(NN)), "expected nodes 0..218"

    @lru_cache(maxsize=None)
    def h(n: int) -> int:
        return 1 + max((h(e[1]) if e[0] == "node" else 0) for e in nodes[n])

    def b_edge(e) -> int:
        return {"node": lambda: b(e[1]), "decnz": lambda: 1, "brk": lambda: e[1]}.get(e[0], lambda: 0)()

    def c_edge(e) -> int:
        return {"node": lambda: c(e[1]), "cont": lambda: e[1]}.get(e[0], lambda: 0)()

    @lru_cache(maxsize=None)
    def b(n: int) -> int:
        car, cdr = nodes[n]
        return max(b_edge(car) - 1, b_edge(cdr), 0)

    @lru_cache(maxsize=None)
    def c(n: int) -> int:
        car, cdr = nodes[n]
        return max(c_edge(car), c_edge(cdr) - 1, 0)

    H = [h(n) for n in range(NN)]
    B = [b(n) for n in range(NN)]
    C = [c(n) for n in range(NN)]
    assert H[0] <= NN + 1 and B[0] == 0 and C[0] == 0, (H[0], B[0], C[0])

    def lit(xs: list[int]) -> str:
        rows = [", ".join(map(str, xs[i:i + 30])) for i in range(0, len(xs), 30)]
        return "[" + ",\n  ".join(rows) + "]"

    out = f'''import BusyBeaver.ZFC.RMEquiv
import BusyBeaver.ZFC.L2Root254

/-!
The 219-node program in the path semantics.

`Dag254.dag254` read as a path program (`RMEquiv.ofDag dag254 219`) is
well-formed: the tables below, generated by
`Computability/BusyBeaver/Research/ZFC/generate_rmequiv254.py` and re-checked
by the kernel, give every node a height (root height {H[0]}, within the decoder
fuel 220) and show that no break or continue escapes the root. Composed with
L2, the path program halts from the boot registers iff the falsity code is
derivable in the code calculus.
-/

namespace SetTheory.BusyBeaver.ZFC.RMEquiv254

open RMDag Dag254 RMEquiv Code254

/-- Heights. -/
def tH : List Nat := {lit(H)}

/-- Largest break level each node can exit with. -/
def tB : List Nat := {lit(B)}

/-- Largest continue level each node can exit with. -/
def tC : List Nat := {lit(C)}

theorem wfCheck254 :
    wfCheck dag254 219 (fun n => tH.getD n 0) (fun n => tB.getD n 0) (fun n => tC.getD n 0) = true := by
  decide +kernel

theorem wf254 : WF dag254 219 := wfCheck_sound wfCheck254

/-- The 219-node program as a path program. -/
def pathDag254 : RegisterPath.Program := ofDag dag254 219

/-- Path halting of the 219-node program is iterated structured halting. -/
theorem path_halts_iff_iter (R : Regs) : RegisterPath.Halts pathDag254 ⟨[], R⟩ ↔ IterHalts dag254 R :=
  halts_iff_iterHalts wf254 R

/-- **L3 + L2 + L1.** The 219-node program in Wade's path semantics, started at
the empty instruction pointer with `nextproof = 2`, halts iff the falsity code
is derivable in the code calculus. -/
theorem path_halts_iff : RegisterPath.Halts pathDag254 ⟨[], upd (fun _ => 0) 0 2⟩ ↔ C254 F :=
  (path_halts_iff_iter _).trans L2.program_halts_iff

end SetTheory.BusyBeaver.ZFC.RMEquiv254
'''
    TARGET.write_text(out, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}: H(root)={H[0]}, max H={max(H)}, max B={max(B)}, max C={max(C)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
