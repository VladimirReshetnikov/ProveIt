#!/usr/bin/env python3
"""Generate BusyBeaver/ZFC/Dag254.lean from the pinned upstream Dag254.v.

The 219-node register program is the Wade TMBuilder compile of Mira-Cult's
source program, as frozen in Jeff's published verification
(lib/jeff-busy-beaver-zfc254/ZF/m254/coq/prog/Dag254.v, upstream commit
297ab8df7e5de329605c3875b4934643b371a5e3).  This script transcribes that
data table into Lean syntax, preserving node numbers and source names, and
checks the count and the register numbering header.  It performs no other
transformation.

Usage (from the repository root):
    py -I Computability/BusyBeaver/Research/ZFC/generate_dag254_lean.py
"""

from __future__ import annotations

import hashlib
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
SOURCE = REPO / "lib/jeff-busy-beaver-zfc254/ZF/m254/coq/prog/Dag254.v"
TARGET = REPO / "Computability/BusyBeaver/Lean/BusyBeaver/ZFC/Dag254.lean"

EDGE = re.compile(r"E(Node|Inc|Decnz|Break|Continue|Halt)(?:\s+(\d+))?")
ROW = re.compile(r"\|\s*(\d+)\s*=>\s*\((E\w+(?:\s+\d+)?),\s*(E\w+(?:\s+\d+)?)\)\s*\(\*\s*(.*?)\s*\*\)")


def lean_edge(text: str) -> str:
    m = EDGE.fullmatch(text.strip())
    if not m:
        raise ValueError(text)
    kind, arg = m.group(1), m.group(2)
    name = {"Node": "node", "Inc": "inc", "Decnz": "decnz", "Break": "brk",
            "Continue": "cont", "Halt": "halt"}[kind]
    return f".{name}" if arg is None else f"(.{name} {arg})"


def main() -> int:
    data = SOURCE.read_bytes()
    text = data.decode("utf-8")
    if "Registers (declaration order): nextproof 0, topwff 1, wffstack 2, axiomcode 3, param1 4, " \
       "param2 5, scratch1 6, scratch2 7, prooflist 8." not in text:
        raise SystemExit("unexpected register header")
    rows = [(int(m.group(1)), m.group(2), m.group(3), m.group(4)) for m in ROW.finditer(text)]
    nums = [r[0] for r in rows]
    if nums != list(range(219)):
        raise SystemExit(f"expected nodes 0..218, got {len(nums)}")
    digest = hashlib.sha256(data).hexdigest()
    out = []
    w = out.append
    w("import BusyBeaver.ZFC.RMDag")
    w("")
    w("/-!")
    w("The 219-node register program of the base-4 ZFC machines.")
    w("")
    w("Generated by `Computability/BusyBeaver/Research/ZFC/generate_dag254_lean.py`")
    w("from the pinned `lib/jeff-busy-beaver-zfc254/ZF/m254/coq/prog/Dag254.v`")
    w(f"(SHA-256 `{digest}`).")
    w("That file is Jeff's transcription of the Wade TMBuilder compile of Mira-Cult's")
    w("source program at busy-beaver commit `297ab8df7e5de329605c3875b4934643b371a5e3`;")
    w("this is an attributed data port and does not relicense the upstream snapshot.")
    w("The attributed public 253-state machine runs the same program.")
    w("")
    w("Registers: nextproof 0, topwff 1, wffstack 2, axiomcode 3, param1 4, param2 5,")
    w("scratch1 6, scratch2 7, prooflist 8. Node 0 is the root `main().0`.")
    w("-/")
    w("")
    w("namespace SetTheory.BusyBeaver.ZFC.Dag254")
    w("")
    w("open RMDag")
    w("")
    w("def dagNodes : Nat → Edge × Edge")
    for n, a, b, name in rows:
        w(f"  | {n} => ({lean_edge(a)}, {lean_edge(b)})  -- {name}")
    w("  | _ => (.halt, .halt)")
    w("")
    w("def dag254 : Prog := ⟨dagNodes, 0⟩")
    w("")
    w("end SetTheory.BusyBeaver.ZFC.Dag254")
    w("")
    TARGET.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET} ({len(rows)} nodes, source sha256 {digest})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
