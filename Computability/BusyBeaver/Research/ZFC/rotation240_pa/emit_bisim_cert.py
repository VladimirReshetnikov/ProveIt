"""Emit the Lean certificate module for the dag254-path / Rotation240 bisimulation.

Machine A is the path program `ofDag dag254 219` (its decoder tree unfolds the
219-node DAG of the L2 proof); machine B is the rotated 240-state source.

Rows use physical register indices (`Permutation252Frame.physOf`), as the Lean
row tables do, so offset vectors are indexed physically. Entry 0 is the start
pair (control 1, control 1, zero offsets). The output is untrusted: the Lean
kernel re-checks every entry with `ArithmeticControlBisim.checkFrom`.
"""
import os
import sys

from catalogues import dag254, rotation240
import explore_bisim

PHYS = {0: 6, 1: 2, 2: 0, 3: 4, 4: 3, 5: 7, 6: 8, 7: 5, 8: 1}


def physical_rows(cat):
    out = []
    for op, r, n0, n1 in cat.rows():
        out.append((op, PHYS[r] if op in (1, 2) else 0, n0, n1))
    return out


def max_segment(rows):
    best = 0
    for c in range(1, len(rows) + 1):
        _, _, n = explore_bisim.segment(rows, c)
        best = max(best, n)
    return best


def main(out_path):
    A = physical_rows(dag254())
    B = physical_rows(rotation240())
    order, err = explore_bisim.explore(A, B, 1, 1)
    if err:
        raise SystemExit("exploration failed: %r" % (err,))
    index = {st: k for k, st in enumerate(order)}
    entries = []
    for (i, j, al, be) in order:
        tA, uA, _ = explore_bisim.segment(A, i)
        tB, uB, _ = explore_bisim.segment(B, j)
        opA, rA, a0, a1 = A[tA - 1]
        opB, _, b0, b1 = B[tB - 1]
        if opA == 4 and opB == 4:
            s0 = s1 = 0
        else:
            a = [al[k] + uA[k] for k in range(9)]
            b = [be[k] + uB[k] for k in range(9)]
            m = [min(a[k], b[k]) for k in range(9)]
            na = tuple(a[k] - m[k] for k in range(9))
            nb = tuple(b[k] - m[k] for k in range(9))
            s0 = index[(a0, b0, na, nb)]
            s1 = index[(a1, b1, na, nb)]
        entries.append((i, j, al, be, s0, s1))
    fuel = max(max_segment(A), max_segment(B)) + 2
    nonzero = sum(1 for e in entries if any(e[2]) or any(e[3]))

    def vec(v):
        return "[" + ",".join(str(x) for x in v) + "]"

    lines = []
    lines.append("import BusyBeaver.ZFC.PackedTables")
    lines.append("")
    lines.append("set_option autoImplicit false")
    lines.append("")
    lines.append("/-!")
    lines.append("Generated by `Research/ZFC/rotation240_pa/emit_bisim_cert.py`; untrusted data.")
    lines.append("An offset segment bisimulation between the dag254 path program and Rotation240")
    lines.append("control catalogues: %d entries, %d with a nonzero offset. Entry 0 is the" % (len(entries), nonzero))
    lines.append("start pair.")
    lines.append("Tables are packed into single natural-number literals (`PackedTables`): the")
    lines.append("two control catalogues (36-bit rows) and the certificate (96-bit entries).")
    lines.append("The row tables define the two interpreters; `ControlBisimRotation240`")
    lines.append("re-checks every certificate entry.")
    lines.append("-/")
    lines.append("")
    lines.append("namespace SetTheory.BusyBeaver.ZFC.BisimCertRotation240")
    lines.append("open ArithmeticControlBisim PackedTables")
    lines.append("")
    lines.append("def fuel : Nat := %d" % fuel)
    lines.append("def size : Nat := %d" % len(entries))
    lines.append("")
    def pack_rows(rows):
        n = 0
        for k, (op, reg, n0, n1) in enumerate(rows):
            assert op < 8 and reg < 9 and n0 < 8192 and n1 < 8192
            n |= (op | reg << 3 | n0 << 7 | n1 << 20) << (36 * k)
        return n

    def pack_vec(v):
        assert len(v) == 9 and all(0 <= x < 4 for x in v)
        return sum(x << (2 * k) for k, x in enumerate(v))

    def pack_entries(es):
        n = 0
        for k, (i, j, al, be, s0, s1) in enumerate(es):
            assert i < 8192 and j < 8192 and s0 < 4096 and s1 < 4096
            x = i | j << 13 | pack_vec(al) << 26 | pack_vec(be) << 44 | s0 << 62 | s1 << 74
            n |= x << (96 * k)
        return n

    for name, value, count in (("tableD", pack_rows(A), len(A)), ("tableR", pack_rows(B), len(B)),
                               ("certPacked", pack_entries(entries), len(entries))):
        lines.append("/-- Packed table, %d slots. -/" % count)
        lines.append("def %s : Nat :=" % name)
        h = "%x" % value
        lines.append("  0x" + h)
        lines.append("")
    lines.append("def countD : Nat := %d" % len(A))
    lines.append("def countR : Nat := %d" % len(B))
    lines.append("")
    lines.append("end SetTheory.BusyBeaver.ZFC.BisimCertRotation240")
    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    print("entries", len(entries), "nonzero", nonzero, "fuel", fuel)


if __name__ == "__main__":
    main(sys.argv[1])
