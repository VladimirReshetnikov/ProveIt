"""Build dagDom: dag219 with Source 149's dominated AX word (the 218-dominated and 217 program).

  python make_dagdom.py DAG219_NODES_JSON OUT_DIR [OUT_LEAN]

dag219's AX routine, node 236, is a chain of macro atoms whose word starts

  a, b, Q, READ_H, c, push, read, I, a, I, a, c, I, b, c, I, I, I, ...

(a = par1 166, b = par2 121, c = par3 168, Q = wal 180, I = cons 119, READ_H = read_p2 176,
push = 171, read = the literal read 158/208 of the fourth field into the current formula).
Source 149 replaces this prefix by

  a, b, Q, c, a, READ_H, READ_D, I, a, I, a, c, I, b, c, I, I, I

(READ_D = read_p1 175): GEN is emitted at U = D + z before the local reads, C → U is formed from
the loaded U, and the delayed read of x turns the parameter into A = U + x. The rest of the word
is unchanged. The new prefix is node 236 and the appended nodes 467..483, whose last node
continues into the old chain. Writes OUT_DIR/dagdom_nodes.json (with the new `word236`) and
OUT_DIR/dagdom_sites.json, and with OUT_LEAN the Lean definition `DagDom.dagDom` (dag219
patched at those nodes).
"""
import json
import sys
from pathlib import Path

from make_dag219 import sites

OLD = [166, 121, 180, 176, 168, 171, 158, 208, 119, 166, 119, 166, 168, 119, 121, 168, 119, 119, 119]
NEW = [166, 121, 180, 168, 166, 176, 175, 119, 166, 119, 166, 168, 119, 121, 168, 119, 119, 119]


def main(src, outdir, lean=None):
    d = json.load(open(src))
    nn = d["nnodes"]
    assert nn == 467
    nodes = {int(k): (tuple(v[0]), tuple(v[1])) for k, v in d["nodes"].items()}
    chain, n = [], 236
    while True:
        a, b = nodes[n]
        chain.append(n)
        if b[0] == "N" and b[1] >= 301 and b[1] not in chain:
            n = b[1]
            continue
        break
    atoms = [nodes[m][0][1] for m in chain] + [nodes[chain[-1]][1][1]]
    assert atoms[:len(OLD)] == OLD, atoms[:len(OLD)]
    rest = chain[len(OLD)]                       # the chain node of the first unchanged atom
    ids = [236] + list(range(nn, nn + len(NEW) - 1))
    for i, atom in enumerate(NEW):
        nxt = ids[i + 1] if i + 1 < len(NEW) else rest
        nodes[ids[i]] = (("N", atom), ("N", nxt))
    nn += len(NEW) - 1
    word = NEW + atoms[len(OLD):]
    out = Path(outdir)
    json.dump({"nnodes": nn, "word236": word,
               "nodes": {str(k): [list(v[0]), list(v[1])] for k, v in sorted(nodes.items())}},
              open(out / "dagdom_nodes.json", "w"))
    s = sites(nodes, 0, nn)
    json.dump(s, open(out / "dagdom_sites.json", "w"))
    print(f"dagDom: {nn} nodes, {len(s)} leaves, max depth {max(len(x[0]) for x in s)}, "
          f"new chain nodes {ids[0]}, {ids[1]}..{ids[-1]} -> {rest}")
    if lean:
        rows = "\n".join(f"  | {m} => some (.node {nodes[m][0][1]}, .node {nodes[m][1][1]})" for m in ids)
        Path(lean).write_text(f"""import BusyBeaver.ZFC.Dag219

/-!
The structured register program of the 217-state machine (`dagDom`), Source 149's dominated AX.

`dag219` with the prefix of the AX word (node 236's chain) replaced: the old prefix
`a, b, Q, READ_H, c, push, read, I, a, I, a, c, I, b, c, I, I, I` becomes
`a, b, Q, c, a, READ_H, READ_D, I, a, I, a, c, I, b, c, I, I, I` (`a, b, c` = `par1, par2, par3`,
`Q` = `wal`, `I` = `cons`, `READ_H, READ_D` = `read_p2, read_p1`; nodes 166, 121, 168, 180, 119,
176, 175). The new prefix is node 236 and nodes {ids[1]}-{ids[-1]}, continuing into the old chain at
node {rest}; every other node is dag219's. Generated by
`Research/ZFC/k225-formal/make_dagdom.py`.
-/

namespace SetTheory.BusyBeaver.ZFC.DagDom

open RMDag

/-- The new prefix of the AX word. -/
def axNodes : Nat → Option (Edge × Edge)
{rows}
  | _ => none

def dagNodes (n : Nat) : Edge × Edge := (axNodes n).getD (Dag219.dagNodes n)

def dagDom : Prog := ⟨dagNodes, 0⟩

end SetTheory.BusyBeaver.ZFC.DagDom
""", encoding="utf-8", newline="\n")
        print("wrote", lean)


if __name__ == "__main__":
    main(*sys.argv[1:])
