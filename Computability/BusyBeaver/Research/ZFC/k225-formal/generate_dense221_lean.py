"""Write KDense221.lean: the 221-state machine as a literal `Core` machine, and its relabelling.

  python generate_dense221_lean.py

Reads the canonical dense table `rocq/rocq-extension/inputs/221/table.tm` (states 0..220, target
221 = halt) and the dense-to-K230 label map `dense_labels` of the Rocq `Dense221.v`. The module
defines `machine221 : Machine 221` and proves by one kernel check that every dense row commutes
with the relabelling into `tm221` (K230 labels, terminal 230).
"""
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEAN = HERE.parents[2] / "Lean" / "BusyBeaver" / "ZFC"
EXT = HERE / "rocq" / "rocq-extension"
TABLE = EXT / "inputs/221/table.tm"
DENSE_V = EXT / "coq/221/Dense221.v"


def main():
    T = {}
    for line in open(TABLE):
        if line.startswith("#") or not line.strip():
            continue
        q, b, w, d, n = line.split()
        T[int(q), int(b)] = (w == "1", d == "R", int(n))
    assert sorted(T) == [(q, b) for q in range(221) for b in (0, 1)]
    src = DENSE_V.read_text(encoding="utf-8")
    labels = [int(x) for x in re.search(r"Definition dense_labels : list nat := \[([^\]]*)\]", src).group(1).split(";")]
    assert len(labels) == 222 and labels[221] == 230 and len(set(labels)) == 222

    def r(x):
        w, d, n = x
        return f"({str(w).lower()}, {str(d).lower()}, {n})"

    rows = ",\n  ".join(f"({r(T[q, 0])}, {r(T[q, 1])})" for q in range(221))
    lab = ", ".join(map(str, labels[:221]))
    body = f"""import BusyBeaver.ZFC.KDenseBridge
import BusyBeaver.ZFC.KTable221

/-!
The 221-state machine, as a literal two-symbol `Machine 221` (the canonical dense table
`inputs/221/table.tm` of the Rocq extension: states `0 .. 220`, target `221` halts), and its
relabelling into the K230-label table `tm221` (`denseLabels`, the Rocq `Dense221.dense_labels`).
`commutes` checks all 221 states and both symbols in one kernel decision.
Generated by `Research/ZFC/k225-formal/generate_dense221_lean.py`.
-/

namespace SetTheory.BusyBeaver.ZFC.KDense221

open KTableCore KDenseBridge

set_option maxRecDepth 100000

/-- Row `q`: the actions on reading `0` and `1`, as `(write, moveRight, next)`; `next = 221` halts. -/
def rows221 : List ((Bool × Bool × Nat) × (Bool × Bool × Nat)) := [
  {rows}]

def act (x : Bool × Bool × Nat) : Action 221 :=
  {{ write := x.1, move := if x.2.1 then .right else .left,
    next := if h : x.2.2 < 221 then some ⟨x.2.2, h⟩ else none }}

/-- **The 221-state machine.** -/
def machine221 : Machine 221 where
  transition q b :=
    let r := rows221.getD q.val ((false, true, 221), (false, true, 221))
    act (if b then r.2 else r.1)

/-- Dense state `q` is K230 label `denseLabels[q]`. -/
def denseLabels : List Nat := [{lab}]

def expand (q : Nat) : Nat := denseLabels.getD q 230

theorem rows221_length : rows221.length = 221 := rfl

theorem commutes : Commutes machine221 tm221 expand 230 := by
  unfold Commutes
  decide +kernel

theorem terminal (b : Bool) : tm221 230 b = none := rfl

end SetTheory.BusyBeaver.ZFC.KDense221
"""
    (LEAN / "KDense221.lean").write_text(body, encoding="utf-8", newline="\n")
    print("wrote KDense221.lean")


if __name__ == "__main__":
    main()
