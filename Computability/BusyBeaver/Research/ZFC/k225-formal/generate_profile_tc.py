"""Fork six lemmas of ProfileComposition.lean to need only transitive containers.

  python generate_profile_tc.py      (from Computability/BusyBeaver/Lean)

`union_edges_of_instance`, `composition_of_instances`, `eqv_trans_of_instances`,
`join_edges_of_instances`, `eqv_matching_of_instances` and `eqv_extensionality_of_instances` take
the full CP hypothesis `Containers mem` but read only its transitive half. The tagged domain of
the 221's lower chain has transitive containers but no literal power containers, so the copies
(suffix `TC`) take `TransContainers mem`. Every definition stays the original one, so the existing
collection-instance lemmas apply unchanged. Writes BusyBeaver/ZFC/KProfileTC.lean.
"""
import re
from pathlib import Path

D = Path("BusyBeaver/ZFC")
src = (D / "ProfileComposition.lean").read_text(encoding="utf-8")
NAMES = ["union_edges_of_instance", "composition_of_instances", "eqv_trans_of_instances",
         "join_edges_of_instances", "eqv_matching_of_instances", "eqv_extensionality_of_instances"]


def block(name):
    i = src.index(f"theorem {name} ")
    # include a preceding doc comment
    j = src.rfind("\n\n", 0, i)
    if src[j + 2:i].startswith("/--"):
        i = j + 2
    m = re.search(r"\n(?=(theorem |def |#print|/--|end ))", src[src.index(f"theorem {name} ") + 1:])
    k = src.index(f"theorem {name} ") + 1 + m.start()
    return src[i:k].rstrip() + "\n"


out = []
for n in NAMES:
    b = block(n)
    b = b.replace("(hContainers : Containers mem)", "(hContainers : TransContainers mem)")
    b = b.replace("obtain ⟨domain, hFamily, hTrans, _⟩ := hContainers family",
                  "obtain ⟨domain, hFamily, hTrans⟩ := hContainers family")
    for m in NAMES:
        b = re.sub(rf"\b{m}\b", m + "TC", b)
    # names that ProfilePairs also defines resolve to ProfileComposition's inside the original
    b = re.sub(r"(?<![\w.])orderedPair_code_congr\b", "ProfileComposition.orderedPair_code_congr", b)
    assert "Containers mem)" not in b.replace("TransContainers mem)", "")
    out.append(b)
body = "\n".join(out)
text = f"""import BusyBeaver.ZFC.ProfileComposition

/-!
Profile-coded bisimulation lemmas that need only transitive containers.

Copies of six lemmas of `ProfileComposition` (suffix `TC`), whose proofs read only the transitive
half of the CP hypothesis `Containers`. The tagged domain of the 221's lower chain has transitive
containers but no literal power containers. Every definition is the original one.
Generated by `Research/ZFC/k225-formal/generate_profile_tc.py`; do not edit.
-/

namespace SetTheory.BusyBeaver.ZFC.KProfileTC

open Profile ProfilePairs ProfileCollection ProfileComposition

universe u
variable {{V : Type u}}

/-- Every set lies in a transitive set. -/
def TransContainers (mem : V → V → Prop) : Prop :=
  ∀ a, ∃ v, mem a v ∧ PositiveClosure.Transitive mem v

{body}
end SetTheory.BusyBeaver.ZFC.KProfileTC
"""
(D / "KProfileTC.lean").write_text(text, encoding="utf-8", newline="\n")
print("wrote KProfileTC.lean,", len(text.splitlines()), "lines")
