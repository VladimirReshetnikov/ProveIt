#!/usr/bin/env python3
"""Generate a Coq/Rocq compatibility component from exact maintained definitions.

No original executor definition is reimplemented.  The extracted blocks are
verbatim source substrings.  Only external types/imports are replaced with a
direction enum and a universally quantified transition table, so the algebraic
statement is independent of the literal table and register soundness proofs.
The production-import adapter uses the identical proof body.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parent
REL = Path('Computability/BusyBeaver/Research/ZFC/k225-formal/rocq/rocq-extension/coq/215/Runtime230Core.v')

def digest(data):
    return hashlib.sha256(data).hexdigest()

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--repo', type=Path)
    ap.add_argument('--templates', type=Path)
    args = ap.parse_args()
    source = ((args.repo / REL) if args.repo else (ROOT / 'upstream' / REL.name)).read_bytes()
    text = source.decode()
    spans = [
        ('effects', 'Inductive eff : Type', 'Definition box_list'),
        ('branch', 'Definition branch : Type', 'Definition valid'),
        ('oracle', 'Definition skip_target', '(** ** Segments'),
        ('segments', 'Inductive seg : Type', 'Definition seg_list'),
        ('configurations', 'Definition sconf : Type', 'Definition conc'),
        ('executor', 'Definition peel_left', 'Fixpoint exec'),
    ]
    blocks = []
    manifest = []
    for label, start, end in spans:
        i = text.index(start)
        j = text.index(end, i)
        block = text[i:j]
        blocks.append(block)
        manifest.append({'label': label, 'start_byte': len(text[:i].encode()),
                         'end_byte': len(text[:j].encode()),
                         'sha256': digest(block.encode())})
    proof = (ROOT / 'FrameProofBody.v.inc').read_text()
    header = '''(** Generated by prepare_rocq.py. Exact production definition slices follow.
    Coq compatibility component, NOT a rebuilt Rocq K215 endpoint. *)
From Coq Require Import Lists.List Bool.Bool Arith.PeanoNat.
Import ListNotations.
Module ExtractedK215Frame.
Inductive dir : Type := L | R.
Section GenericMachine.
Variable tmn : nat -> bool -> option (bool * dir * nat).
'''
    footer = '''
End GenericMachine.
Print Assumptions sstep_add_left_eq.
Print Assumptions run_local_add_left.
Print Assumptions unguarded_empty_left_fails.
Print Assumptions run_local_sound.
Print Assumptions run_local_frame_sound.
End ExtractedK215Frame.
'''
    (ROOT / 'K215FrameStandalone.v').write_text(header + '\n'.join(blocks) + proof + footer)
    production = '''(** Production import adapter; not compiled by the compatibility check.
    Run with the repository's Rocq9.1 K215F load paths. *)
From Coq Require Import Lists.List Bool.Bool Arith.PeanoNat.
From BusyCoq Require Import TM.
From K215F Require Import TM230 Runtime230Core.
Import ListNotations.
Module K215LeftFrame.
'''
    (ROOT / 'K215LeftFrame.v').write_text(production + proof + '''
Print Assumptions sstep_add_left_eq.
Print Assumptions run_local_add_left.
Print Assumptions run_local_frame_sound.
End K215LeftFrame.
''')
    dest = ROOT / 'upstream' / 'Runtime230Core.v'
    dest.parent.mkdir(exist_ok=True)
    dest.write_bytes(source)
    record = {'source_path': str(REL), 'source_sha256': digest(source),
              'definition_blocks': manifest,
              'proof_body_sha256': digest(proof.encode()),
              'standalone_sha256': digest((ROOT / 'K215FrameStandalone.v').read_bytes()),
              'production_adapter_sha256': digest((ROOT / 'K215LeftFrame.v').read_bytes()),
              'scope': 'Exact executor definition slices; arbitrary table. No concrete-tape semantic instantiation or endpoint rebuild.'}
    base = args.repo / REL.parent if args.repo else ROOT / 'upstream'
    table_src = (base / 'Table230.v').read_bytes()
    tm_src = (base / 'TM230.v').read_bytes()
    table = table_src.decode()
    table = table[table.index('Definition table230'):]
    tm = tm_src.decode()
    tm = tm[tm.index('Definition tmn'):tm.index('Definition tm :')]
    data_name = 'templates-q1q2.json'
    data_src = (args.templates if args.templates else ROOT / 'upstream' / data_name).read_bytes()
    templates = json.loads(data_src)['templates_data']
    if len(templates) != 20 or [x['id'] for x in templates] != list(range(20)):
        raise ValueError('Expected exact new 20-template q1/q2 family')
    def b(v):
        if v not in (0, 1, False, True):
            raise ValueError(v)
        return 'true' if v else 'false'
    def seg(s):
        if s[0] == 'b':
            return '(SB %s)' % b(s[1])
        if s[0] == 'r':
            return '(SR %s %d %d)' % (b(s[1]), s[2], s[3])
        if s == ['x', 'none', 0]:
            return '(SBox (BPlain FNone))'
        raise ValueError(s)
    def conf(s):
        q, onl, l, r = s
        return '(%d, %s, [%s], [%s])' % (q, b(onl), '; '.join(map(seg,l)), '; '.join(map(seg,r)))
    concrete = '''(** Generated exact-table replay checks for the new 20-template q1/q2 family.
    These are symbolic local equations; the full endpoint is not rebuilt. *)
From Coq Require Import Lists.List Bool.Bool Arith.PeanoNat.
Require Import K215FrameStandalone.
Import ListNotations ExtractedK215Frame.
Module ConcreteK215Frames.
'''
    concrete += table + '\n' + tm + '\n'
    for item in templates:
        num = item['id']
        if not any(step['moved'] for step in item['trace']):
            raise ValueError('Expected positive local run')
        concrete += f'Definition start{num} : sconf := {conf(item["start"])}.\n'
        concrete += f'Definition finish{num} : sconf := {conf(item["pre_home"])}.\n'
        concrete += f'''Lemma local{num} : run_local tmn {item['steps']} None start{num} = Some (finish{num}, true).
Proof. vm_compute. reflexivity. Qed.
Lemma framed{num} : forall frame,
  run_local tmn {item['steps']} None (add_left frame start{num}) =
    Some (add_left frame finish{num}, true).
Proof. intro frame. apply run_local_add_left. exact local{num}. Qed.
'''
    concrete += '\n' + '\n'.join(f'Print Assumptions framed{i}.' for i in range(len(templates)))
    concrete += '\nEnd ConcreteK215Frames.\n'
    (ROOT / 'K215FrameTemplates.v').write_text(concrete)
    for name, data in [('Table230.v', table_src), ('TM230.v', tm_src), (data_name, data_src)]:
        (ROOT / 'upstream' / name).write_bytes(data)
    record['concrete_templates'] = {
        'count': len(templates), 'symbolic_steps': sum(t['steps'] for t in templates),
        'maximum_steps': max(t['steps'] for t in templates),
        'table_source_sha256': digest(table_src),
        'table_definition_sha256': digest(table.encode()),
        'machine_source_sha256': digest(tm_src),
        'machine_definition_sha256': digest(tm.encode()),
        'template_source_path': data_name,
        'template_source_sha256': digest(data_src),
        'generated_sha256': digest(concrete.encode()),
    }
    lean_rel = Path('Computability/BusyBeaver/Lean/BusyBeaver/ZFC/KTable215.lean')
    native_rel = Path('Computability/BusyBeaver/Research/ZFC/candidate-k215/k215.native.tm')
    lean_src = ((args.repo / lean_rel) if args.repo else ROOT / 'upstream' / lean_rel.name).read_bytes()
    native_src = ((args.repo / native_rel) if args.repo else ROOT / 'upstream' / native_rel.name).read_bytes()
    coq_rows = re.findall(r'\((true|false), ([LR]), (\d+), (true|false), ([LR]), (\d+)\)', table)
    disabled = {int(x) for x in re.findall(r'Nat.eqb q (\d+)', tm)}
    coq_actions = {}
    for q, row in enumerate(coq_rows):
        if q not in disabled:
            for symbol, (write, direction, target) in enumerate((row[:3], row[3:])):
                coq_actions[q, symbol] = (int(write == 'true'), direction, int(target))
    atom = r'(none|some \((true|false), (true|false), (\d+)\))'
    lean_rows = re.findall(r'\(' + atom + r', ' + atom + r'\)', lean_src.decode())
    lean_actions = {}
    for q, row in enumerate(lean_rows):
        for symbol, (value, write, direction, target) in enumerate((row[:4], row[4:])):
            if value != 'none':
                lean_actions[q, symbol] = (int(write == 'true'), 'R' if direction == 'true' else 'L', int(target))
    native_actions = {}
    relabel = {301: 102, 302: 120, 254: 230}
    for line in native_src.decode().splitlines():
        if not line or line.startswith('#'):
            continue
        q, symbol, write, direction, target = line.split()
        q, symbol, write, target = map(int, (q, symbol, write, target))
        key = relabel.get(q, q), symbol
        if key in native_actions:
            raise ValueError('Noninjective source relabeling')
        native_actions[key] = (write, direction, relabel.get(target, target))
    if len(coq_rows) != 230 or len(lean_rows) != 226 or len(disabled) != 15:
        raise ValueError('Unexpected sparse table size')
    if len(coq_actions) != 430 or coq_actions != lean_actions or coq_actions != native_actions:
        raise ValueError('Literal K215 table bindings differ')
    for name, data in [(lean_rel.name, lean_src), (native_rel.name, native_src)]:
        (ROOT / 'upstream' / name).write_bytes(data)
    record['literal_table_binding'] = {
        'working_states': 215, 'actions_compared': 430,
        'coq_sparse_slots': len(coq_rows), 'lean_sparse_slots': len(lean_rows),
        'disabled_states': sorted(disabled),
        'native_to_formal': relabel,
        'native_sha256': digest(native_src), 'lean_table_sha256': digest(lean_src),
        'coq_equals_native': True, 'coq_equals_lean': True,
        'halt_state': 230,
        'status': 'Finite parser equality audit, separate from Coq kernel replay checks',
    }
    (ROOT / 'EXTRACTION.json').write_text(json.dumps(record, indent=2) + '\n')
    print(json.dumps(record, indent=2))

if __name__ == '__main__':
    main()
