#!/usr/bin/env python3
from pathlib import Path
import hashlib
import json
HERE=Path(__file__).resolve().parent
EXPECTED={'k215.native.tm':'9683d6ed9628e6ce407c315b08f5da3d063da94e92706f275ca0f33e8272e4b2','marker215.native.tm':'e5907f08e0752eada0e25bbf33680341e80e5fe94b52b409aea1ed039edda252'}
def read(name):
 b=(HERE/'upstream'/name).read_bytes();assert hashlib.sha256(b).hexdigest()==EXPECTED[name]
 t={}
 for s in b.decode().splitlines():
  if not s.strip() or s.startswith('#'):continue
  q,r,w,d,n=s.split();t[int(q),int(r)]=(int(w),1 if d=='R' else -1,int(n))
 return t
K=read('k215.native.tm');M=read('marker215.native.tm')
qs=sorted(set(q for q,b in K));assert len(qs)==215 and set(K)==set(M)
phi={q:i for i,q in enumerate(qs)};phi[254]=215
head='''import Std

/-! Exact dense copies of pinned ProveIt tables, mechanically generated by
`generate_cm215_data.py`; original native byte hashes are checked there.
State 215 is a totalized absorbing terminal, not an extra working state. -/
namespace CM215
abbrev State := Fin 216
structure Row where
  w : Bool
  d : Int
  next : State
  deriving DecidableEq, Repr
'''
for q in [0,52,129,150,154,156,168,176,185,254]:head+=f'abbrev s{q} : State := {phi[q]}\n'
head+='\n'
for name,t in [('K',K),('M',M)]:
 head+=f'def {name} (q : State) (b : Bool) : Row :=\n  match q.val with\n'
 for q in qs:
  r=[]
  for b in [0,1]:
   w,d,n=t[q,b];r.append(f'⟨{str(bool(w)).lower()}, {d}, {phi[n]}⟩')
  head+=f'  | {phi[q]} => if b then {r[1]} else {r[0]}\n'
 head+='  | _ => ⟨b, 0, s254⟩\n\n'
head+='end CM215\n'
(HERE/'CM215Data.lean').write_text(head)
(HERE/'cm215_state_map.json').write_text(json.dumps(phi,indent=2)+'\n')
print('Generated exact table data:',len(qs),'working states,',len(K),'rows each')
