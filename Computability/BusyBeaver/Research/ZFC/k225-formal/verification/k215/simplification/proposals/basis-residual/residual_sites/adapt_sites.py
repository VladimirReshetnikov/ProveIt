"""Keep upstream subtree partition/data; switch the leaf contract producer."""
from pathlib import Path
import re,json,hashlib,argparse

p=argparse.ArgumentParser(description=__doc__)
p.add_argument('--repo',type=Path,required=True)
p.add_argument('--out',type=Path,required=True,help='Destination Lean source root')
args=p.parse_args()
upstream=args.repo/'Computability/BusyBeaver/Lean/BusyBeaver/ZFC'
out=args.out/'BusyBeaver/ZFC'
out.mkdir(parents=True,exist_ok=True)
metrics=[]
for old in sorted(upstream.glob('KSites215Batch*.lean')):
    raw=old.read_text()
    new=raw.replace('KSites215','KResidualSites215')
    new=new.replace('import BusyBeaver.ZFC.KFastSites215','import BusyBeaver.ZFC.KResidual215')
    new=new.replace('KSim.checkEdge tm215','KResidual215.residualTest tm215')
    new=new.replace('KFastSites215.allSites_of_fast','KResidual215.allSites_of_fast')
    assert 'KFastSites215' not in new and 'KSim.checkEdge' not in new
    new=new.replace("The 215's decoder sites", "Residual K215 decoder sites")
    new=new.replace('Generated by `Research/ZFC/k225-formal/generate_sites215_lean.py`.',
                    'Partition inherited unchanged from generate_sites215_lean.py; checker changed by adapt_sites.py.')
    target=out/old.name.replace('KSites215','KResidualSites215')
    target.write_text(new)
    metrics.append({'before':old.name,'after':target.name,'leaf_counts':[int(x) for x in re.findall(r'/-- (\d+) leaves\.',raw)],'original_sha256':hashlib.sha256(old.read_bytes()).hexdigest(),'new_sha256':hashlib.sha256(target.read_bytes()).hexdigest()})
raw=(upstream/'KSites215.lean').read_text()
new=raw.replace('KSites215','KResidualSites215').replace('KSim.checkEdge tm215','KResidual215.residualTest tm215')
start=new.index('theorem covered :')
new=new[:start]+'''theorem covered (B : KRuntimeCore.BoxLemmas tm215) :
    KSim.SemanticCovered tm215 KSource215.p215 :=
  KResidual215.covered_of_residual B all_sites

/-- The same concrete relation and both halting directions, now using the
shared prefix once and checked residual executions at all source leaves. -/
theorem halts_iff (B : KRuntimeCore.BoxLemmas tm215)
    (hNH : ∀ b, tm215 230 b = none) {c : Configuration} {T : KZip.Conf}
    (hc : KSim.Rel KSource215.p215 c T) :
    RegisterPath.Halts KSource215.p215 c ↔ KZip.Halts tm215 T :=
  KSim.Semantic.halts_iff (covered B) hNH hc

#print axioms all_sites
#print axioms covered
#print axioms halts_iff
end SetTheory.BusyBeaver.ZFC.KResidualSites215
'''
new=new.replace('every leaf of the source tree passes the symbolic site check',
                'every leaf of the source tree passes the residual site check')
new=new.replace('Generated by `Research/ZFC/k225-formal/generate_sites215_lean.py`.',
                'Partition inherited unchanged from generate_sites215_lean.py; checker changed by adapt_sites.py.')
(out/'KResidualSites215.lean').write_text(new)
(args.out/'partition.json').write_text(json.dumps(metrics,indent=2)+'\n')
print('Retained',sum(sum(x['leaf_counts']) for x in metrics),'leaves in',sum(len(x['leaf_counts']) for x in metrics),'blocks and',len(metrics),'batches.')
