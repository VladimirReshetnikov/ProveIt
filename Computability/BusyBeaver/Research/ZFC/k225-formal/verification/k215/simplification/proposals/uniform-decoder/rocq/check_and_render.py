#!/usr/bin/env python3
"""Check explicit implication proof instances and render a generic Rocq core.

This checker does no unification or proof search. The proof data was expanded
from ProveIt's pinned derivation_core.txt by its existing untrusted renderer.
Every MP equation and every side-condition witness is independently checked
before ordinary Rocq proof terms are emitted. The Rocq kernel remains the
authority; successful Python execution is not a formal verification claim.
"""
from __future__ import annotations
import argparse
import hashlib
import json
import re
from pathlib import Path

ROW = [[[0, 1], 2], [[2, 0], [3, 0]]]
ROW_GUARDS = [[1, 2]]
GOALS = {
    'rho8_all': ROW,
    'composition': [[0, 1], [[1, 2], [0, 2]]],
    'prefixing': [[0, 1], [[2, 0], [2, 1]]],
}


def require(ok, message):
    if not ok:
        raise ValueError(message)


def variables(t):
    if type(t) is int:
        require(t >= 0, 'negative or truth variable is not allowed')
        return {t}
    require(type(t) is list and len(t) == 2, 'malformed formula')
    return variables(t[0]) | variables(t[1])


def instantiate(t, args):
    if type(t) is int:
        require(t < len(args), 'missing explicit argument')
        return args[t]
    return [instantiate(t[0], args), instantiate(t[1], args)]


def subterm(u, a):
    return u == a or (type(a) is list and (subterm(u, a[0]) or subterm(u, a[1])))


def check(data):
    require(data['format'] == 'dominated-implication-explicit-v1', 'format')
    require(data['row'] == ROW and data['row_guards'] == ROW_GUARDS,
            'wrong restricted axiom')
    known = {'row': (ROW, ROW_GUARDS)}
    for step in data['steps']:
        name, goal, guards = step['name'], step['formula'], step['guards']
        require(type(name) is str and re.fullmatch(r'd[1-9][0-9]*', name),
                'malformed theorem name')
        require(name not in known, 'duplicate theorem')
        scope = variables(goal)
        for u, a in guards:
            scope |= variables(u) | variables(a)
        values = []
        for key in ('major', 'minor'):
            premise = step[key]
            require(premise['ref'] in known, 'forward or unknown reference')
            formula, conditions = known[premise['ref']]
            args = premise['args']
            needed = variables(formula)
            for u, a in conditions:
                needed |= variables(u) | variables(a)
            require(len(args) == 1 + max(needed), 'wrong argument count')
            for t in args:
                require(variables(t) <= scope, 'unbound instance variable')
            for u, a in conditions:
                u, a = instantiate(u, args), instantiate(a, args)
                require([u, a] in guards or subterm(u, a),
                        'unjustified domination in ' + name)
            values.append(instantiate(formula, args))
        require(values[0] == [values[1], goal], 'bad MP equation in ' + name)
        known[name] = goal, guards
    require(set(data['goals']) == set(GOALS), 'wrong public goals')
    for name, goal in data['goals'].items():
        require(goal['formula'] == GOALS[name], 'wrong target formula')
        require(known[goal['ref']] == (goal['formula'], []), 'guarded public theorem')
    return known


def term(t, nested=False):
    if type(t) is int:
        return 'v' + str(t)
    body = 'wim ' + term(t[0], True) + ' ' + term(t[1], True)
    return '(' + body + ')' if nested else body


def guard(u, a, assumptions):
    if [u, a] in assumptions:
        return 'hb' + str(assumptions.index([u, a]))
    if u == a:
        return '(refl L _)'
    if type(a) is list and subterm(u, a[0]):
        return '(grow_left L ' + term(a[1], True) + ' ' + guard(u, a[0], assumptions) + ')'
    if type(a) is list and subterm(u, a[1]):
        return '(grow_right L ' + term(a[0], True) + ' ' + guard(u, a[1], assumptions) + ')'
    raise ValueError('no domination witness')


def premise(p, assumptions, known):
    ref, args = p['ref'], p['args']
    _, conditions = known[ref]
    suffix = [guard(instantiate(u, args), instantiate(a, args), assumptions)
              for u, a in conditions]
    if ref == 'row':
        args = [args[2], args[3], args[0], args[1]]
        ref = 'restricted_row h'
    return '(' + ' '.join([ref] + [term(a, True) for a in args] + suffix) + ')'


HEAD = '''(** Representation-independent dominated implication, from the exact
    58-step derivation in ProveIt at 2ca3a5c16f0876d2cab842056353c03a1ed2f5f0.
    The independent Python checker validates explicit MP instances. This file
    contains ordinary proof terms; no evaluator, axiom, or truth code is used.
    Generated by check_and_render.py from expanded_proof.json. *)
Set Universe Polymorphism.
Module DominatedImplication.

Record Language (A : Type) := {
  imp : A -> A -> A;
  below : A -> A -> Prop;
  refl : forall a, below a a;
  grow_left : forall u x y, below u x -> below u (imp x y);
  grow_right : forall u y x, below u y -> below u (imp x y)
}.
Arguments imp {A} _ _ _.
Arguments below {A} _ _ _.
Arguments refl {A} _ _.
Arguments grow_left {A} _ {u x} _ _.
Arguments grow_right {A} _ {u y} _ _.

Definition rho8 {A : Type} (L : Language A) (a b c u : A) : A :=
  imp L (imp L (imp L c u) a) (imp L (imp L a c) (imp L b c)).

Record Restricted {A : Type} (L : Language A) (T : A -> Prop) : Prop := {
  mp : forall a b, T (imp L a b) -> T a -> T b;
  restricted_row : forall a b c u, below L u a -> T (rho8 L a b c u)
}.
Arguments mp {A L T} _ _ _ _ _.
Arguments restricted_row {A L T} _ _ _ _ _ _.

Section Derivation.
Context {A : Type} {L : Language A} {T : A -> Prop}.
Variable h : Restricted L T.
Local Notation wim := (imp L).

'''

TAIL = '''(** The public interface matches the current representation-independent
    Lean core; prefixing is stated as a rule in lift_right. *)
Theorem rho8_all (a b c u : A) : T (rho8 L a b c u).
Proof. exact (d56 c u a b). Qed.

Theorem composition (a b c : A) :
  T (wim (wim a b) (wim (wim b c) (wim a c))).
Proof. exact (d58 a b c). Qed.

Theorem lift_right (a b : A) (hab : T (wim a b)) (x : A) :
  T (wim (wim x a) (wim x b)).
Proof. exact (mp h _ _ (d55 a b x) hab). Qed.

End Derivation.
Print Assumptions rho8_all.
Print Assumptions composition.
Print Assumptions lift_right.
End DominatedImplication.
'''


def render(data, known):
    blocks = []
    for s in data['steps']:
        vs = variables(s['formula'])
        for u, a in s['guards']:
            vs |= variables(u) | variables(a)
        args = ' '.join('v' + str(v) for v in sorted(vs))
        guards = ''.join(' (hb%d : below L %s %s)' %
                         (i, term(u, True), term(a, True))
                         for i, (u, a) in enumerate(s['guards']))
        major = premise(s['major'], s['guards'], known)
        minor = premise(s['minor'], s['guards'], known)
        blocks.append('Local Lemma %s (%s : A)%s :\n  T (%s).\n'
                      'Proof. exact (mp h _ _ %s %s). Qed.\n' %
                      (s['name'], args, guards, term(s['formula']), major, minor))
    return HEAD + '\n'.join(blocks) + '\n' + TAIL


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--input', type=Path, default=Path(__file__).with_name('expanded_proof.json'))
    ap.add_argument('--output', type=Path)
    a = ap.parse_args()
    data = json.loads(a.input.read_text())
    known = check(data)
    source = render(data, known)
    if a.output:
        a.output.write_text(source)
    print(json.dumps({'status': 'all_explicit_instances_checked', 'steps': len(data['steps']),
                      'source_sha256': hashlib.sha256(source.encode()).hexdigest(),
                      'source_bytes': len(source.encode()),
                      'source_lines': len(source.splitlines())}, indent=2))


if __name__ == '__main__':
    main()
