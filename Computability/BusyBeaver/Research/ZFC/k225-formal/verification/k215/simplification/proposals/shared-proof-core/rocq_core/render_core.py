#!/usr/bin/env python3
"""Untrusted Rocq renderer for the pinned 58-step representation-independent plan.

The proof search and unification are inherited from ProveIt at commit
2ca3a5c16f0876d2cab842056353c03a1ed2f5f0. Only this renderer is new.
The result is a direct proof, independently checked by the Rocq/Coq kernel.
"""
from pathlib import Path
import importlib.util
import argparse

HERE = Path(__file__).resolve().parent
ap = argparse.ArgumentParser(description=__doc__)
ap.add_argument("--renderer", type=Path, default=HERE / "upstream/generate_domrho8_cd.py")
ap.add_argument("--derivation", type=Path, default=HERE / "upstream/derivation_core.txt")
ap.add_argument("--output", type=Path, default=HERE / "src/K215F/DominatedImplication.v")
args = ap.parse_args()
spec = importlib.util.spec_from_file_location("upstream_renderer", args.renderer)
u = importlib.util.module_from_spec(spec)
spec.loader.exec_module(u)


class CoreSyntax(u.Syntax):
    def __init__(self):
        self.rocq = self.core = True

    def le(self, a, b, hyps):
        if (a, b) in hyps:
            return "hb%d" % hyps.index((a, b))
        if a == b:
            return "(refl L _)"
        return super().le(a, b, hyps)

    def lemma(self, name, t, cons, major, minor):
        vs = u.variables(t, [])
        for c in cons:
            u.variables(c[0], vs)
            u.variables(c[1], vs)
        binders = " ".join("v%d" % v for v in sorted(vs))
        hyps = "".join(" (hb%d : %s ≼ %s)" % (k, self.term(a), self.term(b))
                       for k, (a, b) in enumerate(cons))
        assert major[0] != "truth" and minor[0] != "truth"
        assert not (major[4] or minor[4])
        mp = "%s %s" % (self.use(major, cons), self.use(minor, cons))
        return "Local Lemma %s (%s : A)%s :\n  T (%s).\nProof. exact (dmp h _ _ %s). Qed.\n" % (
            name, binders, hyps, self.term(t), mp)


HEAD = '''(** Representation-independent dominated implication.
    The 58-step plan is exactly the one used by the pinned Lean production core.
    This file has no imports, truth constant, code arithmetic, or normalization.
    Generated by render_core.py; the generator is untrusted. *)
Set Universe Polymorphism.

Record Language (A : Type) := {
  imp : A -> A -> A;
  below : A -> A -> Prop;
  refl : forall a, below a a;
  grow_left : forall u x y, below u x -> below u (imp x y);
  grow_right : forall u y x, below u y -> below u (imp x y)
}.
Arguments imp {A} _ _ _.
Arguments below {A} _ _ _.
Arguments refl {A} _ _.
Arguments grow_left {A} _ _ _ _ _.
Arguments grow_right {A} _ _ _ _ _.

Definition rho8 {A : Type} (L : Language A) (a b c u : A) : A :=
  imp L (imp L (imp L c u) a) (imp L (imp L a c) (imp L b c)).

Record Restricted {A : Type} (L : Language A) (T : A -> Prop) : Prop := {
  dmp : forall a b, T (imp L a b) -> T a -> T b;
  drho8 : forall a b c u, below L u a -> T (rho8 L a b c u)
}.
Arguments dmp {A L T} _ _ _ _ _.
Arguments drho8 {A L T} _ _ _ _ _ _.

Section Derivation.
Context {A : Type} (L : Language A) (T : A -> Prop) (h : Restricted L T).
Local Notation wim := (imp L).
Local Infix "≼" := (below L) (at level 70).
Local Definition le_l {u x : A} y (hu : u ≼ x) : u ≼ wim x y := grow_left L u x y hu.
Local Definition le_r {u y : A} x (hu : u ≼ y) : u ≼ wim x y := grow_right L u y x hu.

'''

TAIL = '''
(** Restricted rows and modus ponens derive every unrestricted row. *)
Theorem rho8_all a b c u : T (rho8 L a b c u).
Proof. exact (d56 c u a b). Qed.

Theorem composition a b c : T (wim (wim a b) (wim (wim b c) (wim a c))).
Proof. exact (d58 a b c). Qed.

Theorem lift_right a b : T (wim a b) -> forall x, T (wim (wim x a) (wim x b)).
Proof. intros hab x. exact (dmp h _ _ (d55 a b x) hab). Qed.

(** Existing shared nodes already prove K and Peirce. *)
Theorem basisK a b : T (wim a (wim b a)).
Proof. exact (d12 a b). Qed.

Theorem basisPeirce a b : T (wim (wim (wim a b) a) a).
Proof. exact (d18 a b). Qed.

(** Three further detachments exchange proved antecedents. *)
Local Lemma exchange a b c : T (wim a (wim b c)) -> T (wim b (wim a c)).
Proof.
 intro habc. exact (dmp h _ _
   (dmp h _ _ (composition b (wim (wim b c) c) (wim a c)) (d36 b c))
   (dmp h _ _ (composition a (wim b c) c) habc)).
Qed.

(** Two detachments and exchange give S: five new detachments in total. *)
Theorem basisS a b c :
    T (wim (wim a (wim b c)) (wim (wim a b) (wim a c))).
Proof.
 apply (exchange (wim a b) (wim a (wim b c)) (wim a c)).
 exact (dmp h _ _
   (dmp h _ _ (composition (wim a b) (wim (wim b c) (wim a c))
      (wim (wim a (wim b c)) (wim a c))) (composition a b c))
   (d47 (wim b c) a c)).
Qed.
End Derivation.

Print Assumptions rho8_all.
Print Assumptions composition.
Print Assumptions lift_right.
Print Assumptions basisK.
Print Assumptions basisPeirce.
Print Assumptions basisS.
'''


def main():
    rows, goals = u.read(args.derivation)
    steps, names = u.steps(rows, core=True)
    assert len(steps) == 58
    for goal, expected in [(u.ROW, "d56"), (u.COMPOSITION, "d58"), (u.PREFIX, "d55")]:
        idx = next(i for i, g in goals if g == goal)
        assert names[idx] == expected and not rows[idx][3]
    syn = CoreSyntax()
    out = HEAD + "\n".join(syn.lemma(*s) for s in steps) + TAIL
    args.output.write_text(out, encoding="utf-8")


if __name__ == "__main__":
    main()
