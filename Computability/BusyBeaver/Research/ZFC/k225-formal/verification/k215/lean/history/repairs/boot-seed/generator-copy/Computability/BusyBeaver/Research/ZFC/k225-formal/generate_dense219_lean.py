"""Write KDense219.lean: the 219-state machine as a literal `Core` machine, and its relabelling.

  python generate_dense219_lean.py

Reads the canonical dense table `candidate-k219/k219.tm` (states 0..218, target 219 = halt) and
the dense-to-sparse label map of `lean219/labels.json` (Source 140's canonical-to-native map with
the renaming 254 -> 230, 301 -> 102, 302 -> 120 of prepare_k219.py). The module defines
`machine219 : Machine 219` and proves by one kernel check that every dense row commutes with the
relabelling into `tm219` (K230 labels, terminal 230).
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEAN = HERE.parents[2] / "Lean" / "BusyBeaver" / "ZFC"
TABLE = HERE.parent / "candidate-k219" / "k219.tm"
LABELS = HERE / "lean219" / "labels.json"


def main():
    T = {}
    for line in open(TABLE):
        if line.startswith("#") or not line.strip():
            continue
        q, b, w, d, n = line.split()
        T[int(q), int(b)] = (w == "1", d == "R", int(n))
    assert sorted(T) == [(q, b) for q in range(219) for b in (0, 1)]
    labels = json.load(open(LABELS))["dense_to_sparse"]
    assert len(labels) == 220 and labels[219] == 230 and len(set(labels)) == 220

    def r(x):
        w, d, n = x
        return f"({str(w).lower()}, {str(d).lower()}, {n})"

    rows = ",\n  ".join(f"({r(T[q, 0])}, {r(T[q, 1])})" for q in range(219))
    lab = ", ".join(map(str, labels[:219]))
    body = f"""import BusyBeaver.ZFC.KDenseBridge
import BusyBeaver.ZFC.KTable219

/-!
The 219-state machine, as a literal two-symbol `Machine 219` (the canonical dense table
`candidate-k219/k219.tm`: states `0 .. 218`, target `219` halts), and its relabelling into the
K230-label table `tm219` (`denseLabels`, from Source 140's canonicalization and the renaming of
`lean219/labels.json`). `commutes` checks all 219 states and both symbols in one kernel decision.
Generated by `Research/ZFC/k225-formal/generate_dense219_lean.py`.
-/

namespace SetTheory.BusyBeaver.ZFC.KDense219

open KTableCore KDenseBridge

set_option maxRecDepth 100000

/-- Row `q`: the actions on reading `0` and `1`, as `(write, moveRight, next)`; `next = 219` halts. -/
def rows219 : List ((Bool × Bool × Nat) × (Bool × Bool × Nat)) := [
  {rows}]

def act (x : Bool × Bool × Nat) : Action 219 :=
  {{ write := x.1, move := if x.2.1 then .right else .left,
    next := if h : x.2.2 < 219 then some ⟨x.2.2, h⟩ else none }}

/-- **The 219-state machine.** -/
def machine219 : Machine 219 where
  transition q b :=
    let r := rows219.getD q.val ((false, true, 219), (false, true, 219))
    act (if b then r.2 else r.1)

/-- Dense state `q` is sparse label `denseLabels[q]`. -/
def denseLabels : List Nat := [{lab}]

def expand (q : Nat) : Nat := denseLabels.getD q 230

theorem rows219_length : rows219.length = 219 := rfl

theorem commutes : Commutes machine219 tm219 expand 230 := by
  unfold Commutes
  decide +kernel

theorem terminal (b : Bool) : tm219 230 b = none := rfl

end SetTheory.BusyBeaver.ZFC.KDense219
"""
    (LEAN / "KDense219.lean").write_text(body, encoding="utf-8", newline="\n")
    print("wrote KDense219.lean")


if __name__ == "__main__":
    main()
