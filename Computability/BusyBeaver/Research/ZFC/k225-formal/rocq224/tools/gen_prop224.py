"""Transfer K230's bundle-free logic proofs to the 224's calculus by renaming.

CD230.v (implicational theorems from rho8 by condensed detachment) and the propositional part
of Comp_Prop230.v (deduction theorem, explosion, double negation, conjunction) use only
T_mp, T_r6 and T_r8, which thm224 has as U_mp, U_r6, U_r8. The copies are renamed
thm230 -> thm224, der230 -> der224, T_ -> U_. [tau] stays K230's (referred to qualified)."""
import re
from pathlib import Path

BASE = Path(r"C:\Users\vresh\AppData\Local\Temp\claude\C--ProveIt--claude-worktrees-merge-article-groups-491e11\31b37d1b-6b02-4181-babf-8c85ac50cb17\scratchpad")
V = BASE / "rocq225/pkg/vendor/k230-rocq/coq/logic"
OUT = BASE / "k224rocq/src"


def rename(s):
    s = s.replace("thm230", "thm224").replace("der230", "der224")
    s = re.sub(r"\bT_(mp|gen|true|r[1-8])\b", r"U_\1", s)
    assert "T_bundle" not in s
    return s


cd = (V / "CD230.v").read_text()
cd = cd.replace("From K230L Require Import Codes230 Thm230.", "From K230L Require Import Codes230.\nFrom K224 Require Import Thm224.")
cd = rename(cd).replace("(** * CD230:", "(** * CD224 (renamed copy of K230's CD230):")
(OUT / "CD224.v").write_text(cd, newline="\n")

cp = (V / "Comp_Prop230.v").read_text()
cut = cp.index("(** ** The lprov axioms *)")
cp = cp[:cut]
a = cp.index("Fixpoint tau"); b = cp.index("Lemma thm_I")
cp = cp[:a] + "Notation tau := K230L.Comp_Prop230.tau.\n\n" + cp[b:]
cp = cp.replace("From Coq Require Import Arith Lia List.\nFrom ZF Require Import Logic L1_LDef.\nFrom K230L Require Import Codes230 Thm230 CD230.",
                "From Stdlib Require Import Arith Lia List.\nFrom ZF Require Import Logic L1_LDef.\nFrom K230L Require Import Codes230.\nFrom K230L Require Comp_Prop230.\nFrom K224 Require Import Thm224 CD224.")
assert "Require Import Codes230.\nFrom K230L Require Comp_Prop230." in cp
cp = rename(cp)
cp = "(** Propositional part of K230's Comp_Prop230.v, transferred to thm224 by renaming\n    (generated by gen_prop224.py). *)\n" + cp
(OUT / "Prop224.v").write_text(cp, newline="\n")
print("wrote CD224.v, Prop224.v")
