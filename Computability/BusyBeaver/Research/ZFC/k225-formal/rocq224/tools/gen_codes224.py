"""Write src/Codes224.v from the 224's emitter contract (Source 125, portable/theory/emitter_contract.json).
The contract's expressions use I/R/Q/E for the codes wim/wel/wal/weq and 1 for F."""
import json
from pathlib import Path

BASE = Path(r"C:\Users\vresh\AppData\Local\Temp\claude\C--ProveIt--claude-worktrees-merge-article-groups-491e11\31b37d1b-6b02-4181-babf-8c85ac50cb17\scratchpad")
C = json.load(open(BASE / "intake181/fresh/K224_Construction_2026-10-20/K224_Construction_2026-10-20/portable/theory/emitter_contract.json"))
OP = {"I": "wim", "R": "wel", "Q": "wal", "E": "weq"}


def term(e):
    if isinstance(e, str):
        return e
    if isinstance(e, int):
        assert e == 1
        return "F"
    return "(" + OP[e[0]] + " " + " ".join(term(x) for x in e[1:]) + ")"


canon = C["canonical_expression"]
orig = C["original_expression"]
# canonical = I(I(I(Q(c,X),1), I(V_R, I(H_E,1))), 1): split off the fused K core N(Q(c,X))
assert canon[0] == "I" and canon[2] == 1 and canon[1][0] == "I"
kf = canon[1][1]
assert kf[0] == "I" and kf[2] == 1 and kf[1][0] == "Q" and kf[1][1] == "c"
X = kf[1][2]

out = f"""(** The 224's numerical axiom bundle (Source 125), read from its exact emitter contract.
    Generated by gen_codes224.py; the two conversion lemmas pin the contract's expressions. *)
From Coq Require Import Arith Lia.
From K230S Require Import KCode230.

(** Fused K core: K230's [kcore a b c c] with its three [E_x (A & B)] double negations cancelled. *)
Definition kf224 (a b c : nat) : nat := wn (wal c {term(X)}).

(** The restricted equality helper: its binder is the relational code [wel a b] = 4 P(a,b) + 1. *)
Definition helper224 (a b : nat) : nat := wim (weq a b) (wal (wel a b) (weq a b)).

Definition vrel (a b c : nat) : nat := wim (wel a b) (wal c (wel a b)).

(** Fused bundle: [A & (B & C)] with the inner double negation cancelled. *)
Definition bundle224 (a b c : nat) : nat := wn (wim (kf224 a b c) (wim (vrel a b c) (wn (helper224 a b)))).

Lemma bundle224_contract a b c : {term(canon)} = bundle224 a b c.
Proof. reflexivity. Qed.

Lemma bundle230_contract a b c : {term(orig)} = bundle230 a b c.
Proof.
  unfold bundle230, k230, kcore, ksubset, krequest, vacuity230, wa, wex, wn. reflexivity.
Qed.

Lemma bundle224_ne_F a b c : bundle224 a b c <> F.
Proof. apply wn_ne_F. Qed.
"""
(BASE / "k224rocq/src").mkdir(parents=True, exist_ok=True)
(BASE / "k224rocq/src/Codes224.v").write_text(out, newline="\n")
print("wrote Codes224.v")
