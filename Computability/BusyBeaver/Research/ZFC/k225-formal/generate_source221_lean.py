"""Generate BusyBeaver/ZFC/KSource221.lean: the 221's source program and dag222 halt alike.

`p221` is the 221's rotated 4,744-leaf source (candidate-k221/sites_logical.json), hash-consed
as in Source 123's `source_data.program_text`. The other side is `dag222` itself, read as a path
program (`RMEquiv.ofDag dag222 461`); its well-formedness tables (heights, break and continue
bounds) are computed here and re-checked by the kernel, as in `generate_rmequiv254.py`. The
offset certificate comes from `gen_cert.py` (the same 2,247 entries as the Rocq
`Cert221Offsets.v`). Everything emitted is untrusted; the kernel re-checks it in chunks.

Usage (from the repository root):
    python Computability/BusyBeaver/Research/ZFC/k225-formal/generate_source221_lean.py DAG222_NODES_JSON DAG222_SITES_JSON"""
import json, sys
from functools import lru_cache
from pathlib import Path

HERE = Path(__file__).resolve().parent
REPO = HERE.parents[4]
sys.path.insert(0, str(HERE))
sys.setrecursionlimit(100000)
from gen_cert import load, Tree, generate  # noqa: E402
from generate_source225_lean import dag, program, cert_block  # noqa: E402

TARGET = REPO / "Computability/BusyBeaver/Lean/BusyBeaver/ZFC/KSource221.lean"
SITES221 = REPO / "Computability/BusyBeaver/Research/ZFC/candidate-k221/sites_logical.json"


def wf_tables(nodes_json):
    d = json.load(open(nodes_json))
    nn = d["nnodes"]
    nodes = {int(k): v for k, v in d["nodes"].items()}
    kind = {"N": "node", "EInc": "inc", "EDecnz": "decnz", "EBreak": "brk", "EContinue": "cont", "EHalt": "halt"}
    nodes = {n: tuple((kind[a[0]], a[1] if a[1] is not None else 0) for a in v) for n, v in nodes.items()}

    @lru_cache(maxsize=None)
    def h(n):
        return 1 + max((h(e[1]) if e[0] == "node" else 0) for e in nodes[n])

    def b_edge(e):
        return {"node": lambda: b(e[1]), "decnz": lambda: 1, "brk": lambda: e[1]}.get(e[0], lambda: 0)()

    def c_edge(e):
        return {"node": lambda: c(e[1]), "cont": lambda: e[1]}.get(e[0], lambda: 0)()

    @lru_cache(maxsize=None)
    def b(n):
        car, cdr = nodes[n]
        return max(b_edge(car) - 1, b_edge(cdr), 0)

    @lru_cache(maxsize=None)
    def c(n):
        car, cdr = nodes[n]
        return max(c_edge(car), c_edge(cdr) - 1, 0)

    H = [h(n) for n in range(nn)]
    B = [b(n) for n in range(nn)]
    C = [c(n) for n in range(nn)]
    assert H[0] <= nn + 1 and B[0] == 0 and C[0] == 0, (H[0], B[0], C[0])
    return nn, H, B, C


def lit(xs):
    rows = [", ".join(map(str, xs[i:i + 30])) for i in range(0, len(xs), 30)]
    return "[" + ",\n  ".join(rows) + "]"


def main():
    nodes_json, dag_sites = sys.argv[1], sys.argv[2]
    nn, H, B, C = wf_tables(nodes_json)
    L1, L2 = load(SITES221), load(dag_sites)
    n1, r1 = dag(L1)
    n2, r2 = dag(L2)
    entries = generate(Tree(L1), Tree(L2))
    mirror = [(b, a, -z, j, k) for a, b, z, j, k in entries]
    nz = sum(1 for e in entries if e[2] != 0)
    out = f"""import BusyBeaver.ZFC.RMOffsetBisim
import BusyBeaver.ZFC.RMEquiv
import BusyBeaver.ZFC.Seed222

/-!
The source program of the 221-state machine and the structured seed-K 222 program halt alike.

`p221` is the 221's rotated {len(L1):,}-leaf source (`candidate-k221/sites_logical.json`) as a
hash-consed DAG ({len(n1)} nodes). `pathDag222` is `dag222` read as a path program; its
well-formedness tables (root height {H[0]}) are re-checked by the kernel. The rotated source and
`dag222` differ by closed reassociations and the AX node's chain layout, so an offset segment
bisimulation relates them: {len(entries)} pairs of register-test sites, {nz} of them offset. The
certificate is from `k225-formal/gen_cert.py` (the Rocq `Cert221Offsets.v` has the same entries)
and is checked here in chunks, with its mirror for the converse.

`p221_boot_iff`: the 221's source, from the boot registers, halts iff the code 1 is derivable in
the 222/221 calculus.

Generated by `Computability/BusyBeaver/Research/ZFC/k225-formal/generate_source221_lean.py`.
-/

namespace SetTheory.BusyBeaver.ZFC.KSource221

open RegisterPath RMBisim RMOffsetBisim
set_option maxRecDepth 65536
set_option maxHeartbeats 8000000

/-! ## dag222 as a path program -/

def tH : List Nat := {lit(H)}

def tB : List Nat := {lit(B)}

def tC : List Nat := {lit(C)}

theorem wfCheck222 :
    RMEquiv.wfCheck Dag222.dag222 {nn} (fun n => tH.getD n 0) (fun n => tB.getD n 0)
      (fun n => tC.getD n 0) = true := by
  decide +kernel

theorem wf222 : RMEquiv.WF Dag222.dag222 {nn} := RMEquiv.wfCheck_sound wfCheck222

def pathDag222 : Program := RMEquiv.ofDag Dag222.dag222 {nn}

theorem path_iff_iter (R : RMDag.Regs) :
    Halts pathDag222 ⟨[], R⟩ ↔ RMDag.IterHalts Dag222.dag222 R :=
  RMEquiv.halts_iff_iterHalts wf222 R

/-! ## The 221's source -/

"""
    out += program("p221", n1, r1, f"The 221's source as a {len(n1)}-node DAG (root {r1}).") + "\n"
    out += "/-- The 221's decoder tree, computed from the program. -/\ndef t221 : Tree := ptree p221\n\n"
    out += "/-- dag222's decoder tree, computed from the program. -/\ndef tD : Tree := ptree pathDag222\n\n"
    out += "theorem t221_eq : ptree p221 = t221 := by rfl\n\ntheorem tD_eq : ptree pathDag222 = tD := by rfl\n\n"
    out += "/-! ## Forward certificate (221 → dag222) -/\n\n" + cert_block("fwd", entries, "t221", "tD")
    out += "\n/-! ## Mirrored certificate (dag222 → 221) -/\n\n" + cert_block("bwd", mirror, "tD", "t221")
    out += """
theorem fwd_start' : obranchOk (ptree p221) (ptree pathDag222) fwdCert [] [] 0 0 = true := by
  rw [t221_eq, tD_eq]; exact fwd_start

theorem fwd_all' : allO (oentryOk (ptree p221) (ptree pathDag222) fwdCert) fwdCert = true := by
  rw [t221_eq, tD_eq]; exact fwd_all

theorem bwd_start' : obranchOk (ptree pathDag222) (ptree p221) bwdCert [] [] 0 0 = true := by
  rw [t221_eq, tD_eq]; exact bwd_start

theorem bwd_all' : allO (oentryOk (ptree pathDag222) (ptree p221) bwdCert) bwdCert = true := by
  rw [t221_eq, tD_eq]; exact bwd_all

/-- **The 221's source and dag222 halt alike**, from every register file. -/
theorem p221_halts_iff (R : Registers) : Halts p221 ⟨[], R⟩ ↔ Halts pathDag222 ⟨[], R⟩ :=
  ⟨ocheck_halts fwd_start' fwd_all' R, ocheck_halts bwd_start' bwd_all' R⟩

/-- **Program layer of the 221.** From the boot registers (`nextproof = 3`, `param1 = 3`), the
221's source halts iff the code 1 is derivable in the 222/221 calculus. -/
theorem p221_boot_iff : Halts p221 ⟨[], L2K.bootRegs⟩ ↔ KCode222.C222 Code254.F :=
  (p221_halts_iff _).trans ((path_iff_iter _).trans L2K.dag222_seed_iff)

#print axioms p221_boot_iff

end SetTheory.BusyBeaver.ZFC.KSource221
"""
    TARGET.write_text(out, encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}: {len(entries)} entries ({nz} offset), {len(n1)} / {len(n2)} DAG nodes, "
          f"root height {H[0]}, {len(out) // 1024} KB")


if __name__ == "__main__":
    main()
