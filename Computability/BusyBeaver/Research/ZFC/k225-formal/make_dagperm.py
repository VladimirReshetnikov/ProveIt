"""Build dagPerm: dagDom with the command-local field reads and permuted commands (the 215's program).

  python make_dagperm.py DAGDOM_NODES_JSON OUT_DIR [OUT_LEAN]

The 215's source applies the command-permuted K216's recipe (Source 159) to the 217's: the common
read of the counter field before dispatch is removed, each command that needs the field reads it
itself, and the three small command bodies are permuted to NIP 0, DROP 1, MP 2. On dagDom's
macro DAG that is:

* the root reads only the selector: node 139 = (read_ac 174, dispatch 141), node 140 unused;
* MP reads its field before loading it: node 484 = (read_p1 175, MP body 150);
* AX keeps U = d: the read of x moves from after READ_H to before the next load of the
  parameter, so node 471 = (READ_H 176, 485), 485 = (cons 119, 486), 486 = (read_p1 175, 474);
* the dispatch runs NIP at selector 0 and MP at selector 2: node 141 = (142, NIP 152),
  node 147 = (148, 484); DROP stays at selector 1 (node 144).

Writes OUT_DIR/dagperm_nodes.json (with the new `word236`) and OUT_DIR/dagperm_sites.json, and
with OUT_LEAN the Lean definition `DagPerm.dagPerm` (dagDom patched at those nodes).
"""
import json
import sys
from pathlib import Path

from make_dag219 import sites


def main(src, outdir, lean=None):
    d = json.load(open(src))
    nn = d["nnodes"]
    assert nn == 484
    nodes = {int(k): (tuple(v[0]), tuple(v[1])) for k, v in d["nodes"].items()}
    N = lambda m: ("N", m)
    assert nodes[0] == (N(133), N(139)) and nodes[139] == (N(174), N(140)) and nodes[140] == (N(175), N(141))
    assert nodes[141] == (N(142), N(150)) and nodes[147] == (N(148), N(152)) and nodes[144] == (N(145), N(121))
    assert nodes[471] == (N(176), N(472)) and nodes[472] == (N(175), N(473)) and nodes[473] == (N(119), N(474))
    assert nodes[474][0] == N(166)
    patch = {139: (N(174), N(141)), 141: (N(142), N(152)), 147: (N(148), N(484)),
             484: (N(175), N(150)), 471: (N(176), N(485)), 485: (N(119), N(486)), 486: (N(175), N(474))}
    nodes.update(patch)
    nn = 487
    chain, n = [], 236
    while True:
        a, b = nodes[n]
        chain.append(n)
        if b[0] == "N" and b[1] >= 301 and b[1] not in chain:
            n = b[1]
            continue
        break
    word = [nodes[m][0][1] for m in chain] + [nodes[chain[-1]][1][1]]
    out = Path(outdir)
    json.dump({"nnodes": nn, "word236": word,
               "nodes": {str(k): [list(v[0]), list(v[1])] for k, v in sorted(nodes.items())}},
              open(out / "dagperm_nodes.json", "w"))
    s = sites(nodes, 0, nn)
    json.dump(s, open(out / "dagperm_sites.json", "w"))
    print(f"dagPerm: {nn} nodes, {len(s)} leaves, max depth {max(len(x[0]) for x in s)}, word {word[:12]}")
    if lean:
        rows = "\n".join(f"  | {m} => some (.node {v[0][1]}, .node {v[1][1]})" for m, v in sorted(patch.items()))
        Path(lean).write_text(f"""import BusyBeaver.ZFC.DagDom

/-!
The structured register program of the 215-state machine (`dagPerm`).

`dagDom` with the command-permuted K216's recipe (Source 159): the root reads only the selector
(node 139 = (read_ac, dispatch)), MP reads its own field (node 484 = (read_p1, MP body)), AX
keeps `U = d` and reads `x` just before its next load of the parameter (nodes 471, 485, 486),
and the dispatch runs NIP at selector 0, DROP at 1 and MP at 2 (nodes 141, 147). Every other
node is dagDom's. Generated by `Research/ZFC/k225-formal/make_dagperm.py`.
-/

namespace SetTheory.BusyBeaver.ZFC.DagPerm

open RMDag

/-- The changed and new nodes. -/
def permNodes : Nat → Option (Edge × Edge)
{rows}
  | _ => none

def dagNodes (n : Nat) : Edge × Edge := (permNodes n).getD (DagDom.dagNodes n)

def dagPerm : Prog := ⟨dagNodes, 0⟩

end SetTheory.BusyBeaver.ZFC.DagPerm
""", encoding="utf-8", newline="\n")
        print("wrote", lean)


if __name__ == "__main__":
    main(*sys.argv[1:])
