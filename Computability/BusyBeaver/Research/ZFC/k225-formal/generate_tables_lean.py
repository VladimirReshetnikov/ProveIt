"""Write the literal K-family tables as Lean modules.

  python generate_tables_lean.py K230.tm 230 OUT_DIR
  python generate_tables_lean.py table_k230labels.tm 225 OUT_DIR
  python generate_tables_lean.py candidate224.k.tm 224 OUT_DIR

The input is a `.tm` file in K230 labels (`q b w d n` rows). Labels without rows (K230's terminal
state 230, and the labels a variant deletes) become `(none, none)`. The output module
`KTable<N>.lean` defines `table<N>` and `tm<N> := tmOf table<N>`.
"""
import os, sys

HEADER = {
    "230": ("K230's frozen table (Elliot Glazer's k230-rocq, `machine/k230.tm`, commit `3142e4d`),\n"
            "in K230's own labels; label 230 is the terminal state."),
    "224": ("The 224-state candidate's table in K labels (Source 125, `portable/machine/results/\n"
            "candidate224.k.tm`); labels 79, 140, 175, 191, 208 and 229 are deleted, 230 is terminal."),
    "225": ("The 225-state candidate's table in K230 labels (`inputs/225/table_k230labels.tm` of the\n"
            "Rocq extension); labels 79, 140, 175, 208 and 229 are deleted, 230 is terminal."),
    "221": ("The 221-state machine's table in K230 labels (`inputs/221/table_k230labels.tm` of the\n"
            "Rocq extension; native label 254 renamed 230); labels 79, 140, 175, 191, 192, 208, 219,\n"
            "226 and 229 are deleted, 230 is terminal."),
    "219": ("The 219-state machine's table in K230 labels (`lean219/k219_k230labels.tm`: Source 140's\n"
            "native table with halt 254 renamed 230 and its new states 301, 302 renamed into the freed\n"
            "labels 102, 120); 230 is terminal."),
    "218": ("The 218-state machine's table in K230 labels (`lean218/k218_k230labels.tm`: Source 144's\n"
            "native table with halt 254 renamed 230 and the states 301, 302 renamed into the freed\n"
            "labels 102, 120, as for the 219); 230 is terminal."),
}


def load(path):
    T = {}
    for line in open(path):
        if line.startswith("#") or not line.strip():
            continue
        q, b, w, d, n = line.split()
        T[int(q), int(b)] = (w == "1", d == "R", int(n))
    return T


def lit(r):
    if r is None:
        return "none"
    w, d, n = r
    return f"some ({str(w).lower()}, {str(d).lower()}, {n})"


def main(src, tag, out):
    T = load(src)
    top = max(q for q, _ in T)
    rows = [f"  ({lit(T.get((q, 0)))}, {lit(T.get((q, 1)))})" for q in range(top + 1)]
    body = (
        "import BusyBeaver.ZFC.KTableCore\n\n"
        f"/-!\n{HEADER[tag]}\nGenerated by `Research/ZFC/k225-formal/generate_tables_lean.py`; do not edit.\n-/\n\n"
        "namespace SetTheory.BusyBeaver.ZFC.KTableCore\n\n"
        f"def table{tag} : List (Row × Row) := [\n" + ",\n".join(rows) + "]\n\n"
        f"def tm{tag} : KZip.TMN := tmOf table{tag}\n\n"
        "end SetTheory.BusyBeaver.ZFC.KTableCore\n")
    path = os.path.join(out, f"KTable{tag}.lean")
    open(path, "w", encoding="utf-8", newline="\n").write(body)
    print(path, top + 1, "labels")


if __name__ == "__main__":
    main(*sys.argv[1:])
