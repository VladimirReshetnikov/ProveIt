"""Generate the 219's balanced lookup tree and its blank-tape bootstrap checkpoints as Lean modules.

  python generate_boot219_lean.py [CHUNK_DEPTH]

Reads `lean219/k219_k230labels.tm` (K230 labels), simulates the blank-tape
run exactly as `KBoot.lstep` does (list zippers, no blank trimming) for 409,835 steps, and checks
that it ends in state 84 with `[true]` to the left and K230's boot tape to the right. It writes

  KFast219.lean           the lookup tree `tt219` and `fastOf tt219 = tm219`;
  KBoot219Chunk<i>.lean   one checkpoint per 2^CHUNK_DEPTH steps (the remainder in binary blocks);
  KBoot219.lean           the chain, ending in `boot : Reach tm219 (zc 0 [] []) (zc 84 [true] bootRight)`.

The checkpoints are untrusted data; the kernel re-runs every block.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEAN = HERE.parents[2] / "Lean" / "BusyBeaver" / "ZFC"
TABLE = HERE / "lean219/k219_k230labels.tm"
STEPS = 312617
NS = "SetTheory.BusyBeaver.ZFC.KBoot219"


def load():
    T = {}
    for line in open(TABLE):
        if line.startswith("#") or not line.strip():
            continue
        q, b, w, d, n = line.split()
        T[int(q), int(b)] = (w == "1", d == "R", int(n))
    return T


def row(r):
    if r is None:
        return "none"
    w, d, n = r
    return f"some ({str(w).lower()}, {str(d).lower()}, {n})"


def tree(T, idx, stride, depth):
    if depth == 0:
        return f"(.leaf ({row(T.get((idx, 0)))}) ({row(T.get((idx, 1)))}))"
    a = tree(T, idx, stride * 2, depth - 1)
    b = tree(T, idx + stride, stride * 2, depth - 1)
    return f"(.node {a} {b})"


def step(T, s):
    q, l, r = s
    rh = r[0] if r else False
    x = T.get((q, int(rh)))
    if x is None:
        return None
    w, right, q2 = x
    if right:
        return (q2, [w] + l, r[1:])
    return (q2, l[1:], [l[0] if l else False, w] + r[1:])


def bools(xs):
    rows = [", ".join("true" if b else "false" for b in xs[i:i + 24]) for i in range(0, len(xs), 24)]
    return "[" + ",\n    ".join(rows) + "]"


def conf(s):
    q, l, r = s
    return f"({q}, {bools(l)},\n  {bools(r)})"


def sepsR(vs):
    out = []
    for v in vs:
        out += [False] + [True] * (v + 1)
    return out


def main():
    depth = int(sys.argv[1]) if len(sys.argv) > 1 else 14
    T = load()
    # lookup tree: q's bits least significant first, 8 levels
    src = ("import BusyBeaver.ZFC.KBoot\nimport BusyBeaver.ZFC.KTable219\n\n"
           "/-! The 219's table (K230 labels) as a balanced lookup tree; agreement is a kernel check.\n"
           "Generated by `Research/ZFC/k225-formal/generate_boot219_lean.py`. -/\n\n"
           "namespace SetTheory.BusyBeaver.ZFC.KBoot219\n\nopen KBoot KTableCore\n\n"
           "set_option maxRecDepth 100000\n\n"
           f"def tt219 : TT :=\n  {tree(T, 0, 1, 8)}\n\n"
           "theorem table219_length : table219.length = 229 := rfl\n\n"
           "theorem fast_lt : ∀ q, q < 256 → ∀ b : Bool, fastOf tt219 q b = tm219 q b := by\n"
           "  decide +kernel\n\n"
           "theorem fast219 (q : Nat) (b : Bool) : fastOf tt219 q b = tm219 q b := by\n"
           "  by_cases h : q < 256\n"
           "  · exact fast_lt q h b\n"
           "  · have h2 : table219[q]? = none := List.getElem?_eq_none (by rw [table219_length]; omega)\n"
           "    simp [fastOf, h, tm219, tmOf, h2]\n\n"
           f"end {NS}\n")
    (LEAN / "KFast219.lean").write_text(src, encoding="utf-8", newline="\n")
    # bootstrap run, cut into blocks: full chunks of 2^depth, then the remainder's binary digits
    blocks = [depth] * (STEPS >> depth) + [k for k in range(depth - 1, -1, -1) if (STEPS >> k) & 1]
    assert sum(2 ** k for k in blocks) == STEPS
    s = (0, [], [])
    cps = [s]
    for k in blocks:
        for _ in range(2 ** k):
            s = step(T, s)
            assert s is not None
        cps.append(s)
    q, l, r = s
    regs = [0, 0, 0, 3, 0, 0, 3, 0, 0] + [1] * 130
    right = [False] * 144 + [True] + sepsR(regs)
    lt = l[:]
    while lt and not lt[-1]:
        lt.pop()
    rt = r[:]
    while rt and not rt[-1]:
        rt.pop()
    assert q == 84 and lt == [True] and rt == right, (q, lt[:10], len(rt), len(right))
    pl, pr = len(l) - 1, len(r) - len(right)
    names = []
    for i, k in enumerate(blocks):
        name = f"KBoot219Chunk{i:03d}"
        names.append(name)
        prev = "KBoot219Fast" if i == 0 else f"KBoot219Chunk{i - 1:03d}"
        imp = "import BusyBeaver.ZFC.KFast219" if i == 0 else f"import BusyBeaver.ZFC.{prev}"
        before = "(0, [], [])" if i == 0 else f"cp{i}"
        body = (f"{imp}\n\n/-! Bootstrap of the 219, steps {sum(2 ** b for b in blocks[:i])} to "
                f"{sum(2 ** b for b in blocks[:i + 1])} (a block of 2^{k}).\n"
                "Generated by `Research/ZFC/k225-formal/generate_boot219_lean.py`. -/\n\n"
                f"namespace {NS}\n\nopen KBoot\n\nset_option maxRecDepth 100000\n\n"
                f"def cp{i + 1} : LConf :=\n  {conf(cps[i + 1])}\n\n"
                f"theorem block{i + 1} : lblock (fastOf tt219) {k} {before} = some cp{i + 1} := by\n"
                "  decide +kernel\n\n"
                f"end {NS}\n")
        (LEAN / f"{name}.lean").write_text(body, encoding="utf-8", newline="\n")
    n = len(blocks)
    chain = " |>.trans ".join(f"(lblock_reach fast219 block{i + 1})" for i in range(n))
    fin = (f"import BusyBeaver.ZFC.{names[-1]}\nimport BusyBeaver.ZFC.KRuntimeCore\n\n"
           "/-!\nThe 219's exact blank-tape bootstrap (port of K230's `Boot230.v`). After 312,617 steps the\n"
           "machine is in state 84 with `[true]` to its left, a gap of 144 blank cells, and 139 register\n"
           "blocks: the boot registers (`nextproof = 3`, `param1 = 3`) in physical order, then 130 spare\n"
           "blocks holding 1. Checked in kernel blocks against the literal table.\n"
           "Generated by `Research/ZFC/k225-formal/generate_boot219_lean.py`.\n-/\n\n"
           f"namespace {NS}\n\nopen KZip KBoot KTableCore\n\nset_option maxRecDepth 100000\n\n"
           "def bootVs : List Nat := [0, 0, 0, 3, 0, 0, 3, 0, 0] ++ List.replicate 130 1\n\n"
           "def bootRight : List Bool := List.replicate 144 false ++ true :: KRuntimeCore.sepsR bootVs\n\n"
           f"theorem cp_left : cp{n}.2.1 = [true] ++ List.replicate {pl} false := by decide +kernel\n\n"
           f"theorem cp_right : cp{n}.2.2 = bootRight ++ List.replicate {pr} false := by decide +kernel\n\n"
           f"theorem cp_state : cp{n}.1 = 84 := rfl\n\n"
           f"theorem boot_run : Reach tm219 (zc 0 [] []) (lconc cp{n}) :=\n  {chain}\n\n"
           "theorem boot : Reach tm219 (zc 0 [] []) (zc 84 [true] bootRight) := by\n"
           f"  have h := boot_run\n  simp only [lconc, cp_state, cp_left, cp_right, zc_padl, zc_padr] at h\n  exact h\n\n"
           f"end {NS}\n")
    (LEAN / "KBoot219.lean").write_text(fin, encoding="utf-8", newline="\n")
    print(f"{n} blocks {blocks}; final left pad {pl}, right pad {pr}; |l|={len(l)} |r|={len(r)}")


if __name__ == "__main__":
    main()
