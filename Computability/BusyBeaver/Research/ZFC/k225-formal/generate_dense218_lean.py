"""Write KDense218.lean: the 218-state machine as a literal `Core` machine, and its relabelling.

  python generate_dense218_lean.py

Reads the canonical dense table `candidate-k218/k218.tm` (states 0..217, target 218 = halt) and
the dense-to-sparse label map of `lean218/labels.json` (Source 144's canonical-to-native map with
the renaming 254 -> 230, 301 -> 102, 302 -> 120 of prepare_k218.py). The module defines
`machine218 : Machine 218` and proves by one kernel check that every dense row commutes with the
relabelling into `tm218` (K230 labels, terminal 230).
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEAN = HERE.parents[2] / "Lean" / "BusyBeaver" / "ZFC"
TABLE = HERE.parent / "candidate-k218" / "k218.tm"
LABELS = HERE / "lean218" / "labels.json"


def main():
    T = {}
    for line in open(TABLE):
        if line.startswith("#") or not line.strip():
            continue
        q, b, w, d, n = line.split()
        T[int(q), int(b)] = (w == "1", d == "R", int(n))
    assert sorted(T) == [(q, b) for q in range(218) for b in (0, 1)]
    labels = json.load(open(LABELS))["dense_to_sparse"]
    assert len(labels) == 219 and labels[218] == 230 and len(set(labels)) == 219

    def r(x):
        w, d, n = x
        return f"({str(w).lower()}, {str(d).lower()}, {n})"

    rows = ",\n  ".join(f"({r(T[q, 0])}, {r(T[q, 1])})" for q in range(218))
    lab = ", ".join(map(str, labels[:218]))
    body = f"""import BusyBeaver.ZFC.KDenseBridge
import BusyBeaver.ZFC.KTable218

/-!
The 218-state machine, as a literal two-symbol `Machine 218` (the canonical dense table
`candidate-k218/k218.tm`: states `0 .. 217`, target `218` halts), and its relabelling into the
K230-label table `tm218` (`denseLabels`, from Source 144's canonicalization and the renaming of
`lean218/labels.json`). `commutes` checks all 218 states and both symbols in one kernel decision.
Generated by `Research/ZFC/k225-formal/generate_dense218_lean.py`.
-/

namespace SetTheory.BusyBeaver.ZFC.KDense218

open KTableCore KDenseBridge

set_option maxRecDepth 100000

/-- Row `q`: the actions on reading `0` and `1`, as `(write, moveRight, next)`; `next = 218` halts. -/
def rows218 : List ((Bool × Bool × Nat) × (Bool × Bool × Nat)) := [
  {rows}]

def act (x : Bool × Bool × Nat) : Action 218 :=
  {{ write := x.1, move := if x.2.1 then .right else .left,
    next := if h : x.2.2 < 218 then some ⟨x.2.2, h⟩ else none }}

/-- **The 218-state machine.** -/
def machine218 : Machine 218 where
  transition q b :=
    let r := rows218.getD q.val ((false, true, 218), (false, true, 218))
    act (if b then r.2 else r.1)

/-- Dense state `q` is sparse label `denseLabels[q]`. -/
def denseLabels : List Nat := [{lab}]

def expand (q : Nat) : Nat := denseLabels.getD q 230

theorem rows218_length : rows218.length = 218 := rfl

theorem commutes : Commutes machine218 tm218 expand 230 := by
  unfold Commutes
  decide +kernel

theorem terminal (b : Bool) : tm218 230 b = none := rfl

end SetTheory.BusyBeaver.ZFC.KDense218
"""
    (LEAN / "KDense218.lean").write_text(body, encoding="utf-8", newline="\n")
    print("wrote KDense218.lean")


if __name__ == "__main__":
    main()
