"""Write KDense215.lean: the 215-state machine as a literal `Core` machine, and its relabelling.

  python generate_dense215_lean.py

Reads the canonical dense table `candidate-k215/k215.tm` (states 0..214, target 215 = halt) and
the dense-to-sparse label map of `lean215/labels.json` (the 215's canonical-to-native map with
the renaming 254 -> 230, 301 -> 102, 302 -> 120 of prepare_k215.py). The module defines
`machine215 : Machine 215` and proves by one kernel check that every dense row commutes with the
relabelling into `tm215` (K230 labels, terminal 230).
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEAN = HERE.parents[2] / "Lean" / "BusyBeaver" / "ZFC"
TABLE = HERE.parent / "candidate-k215" / "k215.tm"
LABELS = HERE / "lean215" / "labels.json"


def main():
    T = {}
    for line in open(TABLE):
        if line.startswith("#") or not line.strip():
            continue
        q, b, w, d, n = line.split()
        T[int(q), int(b)] = (w == "1", d == "R", int(n))
    assert sorted(T) == [(q, b) for q in range(215) for b in (0, 1)]
    labels = json.load(open(LABELS))["dense_to_sparse"]
    assert len(labels) == 216 and labels[215] == 230 and len(set(labels)) == 216

    def r(x):
        w, d, n = x
        return f"({str(w).lower()}, {str(d).lower()}, {n})"

    rows = ",\n  ".join(f"({r(T[q, 0])}, {r(T[q, 1])})" for q in range(215))
    lab = ", ".join(map(str, labels[:215]))
    body = f"""import BusyBeaver.ZFC.KDenseBridge
import BusyBeaver.ZFC.KTable215

/-!
The 215-state machine, as a literal two-symbol `Machine 215` (the canonical dense table
`candidate-k215/k215.tm`: states `0 .. 214`, target `215` halts), and its relabelling into the
K230-label table `tm215` (`denseLabels`, from the 215's canonicalization and the renaming of
`lean215/labels.json`). `commutes` checks all 215 states and both symbols in one kernel decision.
Generated by `Research/ZFC/k225-formal/generate_dense215_lean.py`.
-/

namespace SetTheory.BusyBeaver.ZFC.KDense215

open KTableCore KDenseBridge

set_option maxRecDepth 100000

/-- Row `q`: the actions on reading `0` and `1`, as `(write, moveRight, next)`; `next = 215` halts. -/
def rows215 : List ((Bool × Bool × Nat) × (Bool × Bool × Nat)) := [
  {rows}]

def act (x : Bool × Bool × Nat) : Action 215 :=
  {{ write := x.1, move := if x.2.1 then .right else .left,
    next := if h : x.2.2 < 215 then some ⟨x.2.2, h⟩ else none }}

/-- **The 215-state machine.** -/
def machine215 : Machine 215 where
  transition q b :=
    let r := rows215.getD q.val ((false, true, 215), (false, true, 215))
    act (if b then r.2 else r.1)

/-- Dense state `q` is sparse label `denseLabels[q]`. -/
def denseLabels : List Nat := [{lab}]

def expand (q : Nat) : Nat := denseLabels.getD q 230

theorem rows215_length : rows215.length = 215 := rfl

theorem commutes : Commutes machine215 tm215 expand 230 := by
  unfold Commutes
  decide +kernel

theorem terminal (b : Bool) : tm215 230 b = none := rfl

end SetTheory.BusyBeaver.ZFC.KDense215
"""
    (LEAN / "KDense215.lean").write_text(body, encoding="utf-8", newline="\n")
    print("wrote KDense215.lean")


if __name__ == "__main__":
    main()
