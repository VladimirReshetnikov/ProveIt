"""Write KDense217.lean: the 217-state machine as a literal `Core` machine, and its relabelling.

  python generate_dense217_lean.py

Reads the canonical dense table `candidate-k217/k217.tm` (states 0..216, target 217 = halt) and
the dense-to-sparse label map of `lean217/labels.json` (Source 152's canonical-to-native map with
the renaming 254 -> 230, 301 -> 102, 302 -> 120 of prepare_k217.py). The module defines
`machine217 : Machine 217` and proves by one kernel check that every dense row commutes with the
relabelling into `tm217` (K230 labels, terminal 230).
"""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEAN = HERE.parents[2] / "Lean" / "BusyBeaver" / "ZFC"
TABLE = HERE.parent / "candidate-k217" / "k217.tm"
LABELS = HERE / "lean217" / "labels.json"


def main():
    T = {}
    for line in open(TABLE):
        if line.startswith("#") or not line.strip():
            continue
        q, b, w, d, n = line.split()
        T[int(q), int(b)] = (w == "1", d == "R", int(n))
    assert sorted(T) == [(q, b) for q in range(217) for b in (0, 1)]
    labels = json.load(open(LABELS))["dense_to_sparse"]
    assert len(labels) == 218 and labels[217] == 230 and len(set(labels)) == 218

    def r(x):
        w, d, n = x
        return f"({str(w).lower()}, {str(d).lower()}, {n})"

    rows = ",\n  ".join(f"({r(T[q, 0])}, {r(T[q, 1])})" for q in range(217))
    lab = ", ".join(map(str, labels[:217]))
    body = f"""import BusyBeaver.ZFC.KDenseBridge
import BusyBeaver.ZFC.KTable217

/-!
The 217-state machine, as a literal two-symbol `Machine 217` (the canonical dense table
`candidate-k217/k217.tm`: states `0 .. 216`, target `217` halts), and its relabelling into the
K230-label table `tm217` (`denseLabels`, from Source 152's canonicalization and the renaming of
`lean217/labels.json`). `commutes` checks all 217 states and both symbols in one kernel decision.
Generated by `Research/ZFC/k225-formal/generate_dense217_lean.py`.
-/

namespace SetTheory.BusyBeaver.ZFC.KDense217

open KTableCore KDenseBridge

set_option maxRecDepth 100000

/-- Row `q`: the actions on reading `0` and `1`, as `(write, moveRight, next)`; `next = 217` halts. -/
def rows217 : List ((Bool × Bool × Nat) × (Bool × Bool × Nat)) := [
  {rows}]

def act (x : Bool × Bool × Nat) : Action 217 :=
  {{ write := x.1, move := if x.2.1 then .right else .left,
    next := if h : x.2.2 < 217 then some ⟨x.2.2, h⟩ else none }}

/-- **The 217-state machine.** -/
def machine217 : Machine 217 where
  transition q b :=
    let r := rows217.getD q.val ((false, true, 217), (false, true, 217))
    act (if b then r.2 else r.1)

/-- Dense state `q` is sparse label `denseLabels[q]`. -/
def denseLabels : List Nat := [{lab}]

def expand (q : Nat) : Nat := denseLabels.getD q 230

theorem rows217_length : rows217.length = 217 := rfl

theorem commutes : Commutes machine217 tm217 expand 230 := by
  unfold Commutes
  decide +kernel

theorem terminal (b : Bool) : tm217 230 b = none := rfl

end SetTheory.BusyBeaver.ZFC.KDense217
"""
    (LEAN / "KDense217.lean").write_text(body, encoding="utf-8", newline="\n")
    print("wrote KDense217.lean")


if __name__ == "__main__":
    main()
