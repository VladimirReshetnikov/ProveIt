#!/usr/bin/env python3
"""Generate L2Dom.lean: the program layer of dagDom outside the AX routine, by transfer.

  python generate_l2dom.py DAG222_NODES_JSON DAGDOM_NODES_JSON [perm]   (from Computability/BusyBeaver/Lean)

With `perm` and dagPerm's node data (make_dagperm.py) it writes L2Perm.lean for the 215.

dagDom agrees with dag222 on every node below 461 except the equality test (node 123, whose two
routines have the same contract, `Dag219.eq222` / `Dag219.eq219`) and the AX routine (node 236).
The nodes below 461 from which node 236 is unreachable form a closed set (`RMTransfer.Closed`),
so every L2K lemma about such a node holds for dagDom with the same statement: this script
copies the statements of the lemmas the AX routine and the root step use, and proves each by
`RMTransfer.node_transfer`. The set and its closedness are recomputed here and re-checked by
the kernel.
"""
import json
import re
import sys
from pathlib import Path

D = Path("BusyBeaver/ZFC")


def retarget(text):
    """the 215's program dagPerm (make_dagperm.py) instead of dagDom"""
    for a, b in [("L2AxiomsDom", "L2AxiomsPerm"), ("dagDom", "dagPerm"), ("DagDom", "DagPerm"),
                 ("L2Dom", "L2Perm"), ("EnumDom", "EnumPerm"),
                 ("the 217's dominated AX word", "the 215's AX word (the read of `x` after the first `I`)")]:
        text = text.replace(a, b)
    return text

VARIANT = sys.argv[3] if len(sys.argv) > 3 else "dom"
d222 = json.load(open(sys.argv[1]))
dD = json.load(open(sys.argv[2]))
n222 = {int(k): v for k, v in d222["nodes"].items()}
nD = {int(k): v for k, v in dD["nodes"].items()}

# ancestors of 236 in dag222 (nodes from which 236 is reachable), below 461
anc = {236}
changed = True
while changed:
    changed = False
    for n, (a, b) in n222.items():
        if n not in anc and any(e[0] == "N" and e[1] in anc for e in (a, b)):
            anc.add(n)
            changed = True
anc = sorted(anc)
ok = lambda n: n < 461 and n not in anc
for n in range(461):
    if ok(n) and n != 123:
        assert n222[n] == nD[n], n
        for e in n222[n]:
            assert e[0] != "N" or ok(e[1]), (n, e)

NAMES = ["pushwff", "par1", "par2", "par3", "cons", "wel_m", "wal_m", "weq_m", "wn_m", "wa_m",
         "wex_m", "read_p2", "read_p1", "read_ac", "loop192", "ifeq_clear", "loop211", "loop197",
         "fetch_zero", "fetch_pos", "mp_branch", "nip_branch", "nip_halt"]
src = "".join((D / f).read_text(encoding="utf-8") for f in
              ["L2Lib222.lean", "L2Macros222.lean", "L2Control222.lean"])
lemmas = []
for name in NAMES:
    m = re.search(r"^((?:/--(?:(?!-/).)*-/\n)?)theorem " + re.escape(name) + r" (.*?) :=(?: by)?\s*\n",
                  src, re.S | re.M)
    assert m, name
    doc, sig = m.group(1), m.group(2)
    binders = re.findall(r"\((\w+) :", sig.split(" : Rn")[0].split(" :\n")[0])
    args = " ".join(binders)
    if "∃ R'" in sig:
        sig = sig.replace("Run dag222", "Run dagDom")
        pf = f"let ⟨R', h⟩ := L2K.{name} {args}\n  ⟨R', tr rfl h⟩"
    else:
        assert re.search(r": *\n? *Rn \(\.node \d+\)", sig), (name, sig)
        pf = f"tr rfl (L2K.{name} {args})"
    lemmas.append(f"{doc}theorem {name} {sig} :=\n  {pf}\n")

anc_lit = ", ".join(map(str, anc))
out = f"""import BusyBeaver.ZFC.DagDom
import BusyBeaver.ZFC.Dag219Bisim
import BusyBeaver.ZFC.L2Control222
import BusyBeaver.ZFC.RMTransfer

/-!
The program layer of `dagDom` outside its AX routine, by transfer from `dag222`.

`dagDom` keeps every node of `dag222` below 461 except the equality test (node 123: Source
140's routine, with the same contract as the old one) and the AX routine (node 236). The nodes
below 461 from which node 236 is unreachable (`ok`) form a closed set: their contents agree,
their children stay in the set, and node 123 runs alike in both programs (`closed222`). So every
L2K lemma about such a node holds for `dagDom` as stated; the lemmas below are those the AX
routine and the root step use.
Generated by `Research/ZFC/k225-formal/generate_l2dom.py`.
-/

namespace SetTheory.BusyBeaver.ZFC.L2Dom

open RMDag DagDom Code254 RMTransfer
open L2K (AS enc Clean upd_np upd_tw upd_ws upd_ac upd_p1 upd_p2 upd_s1 upd_s2 upd_pl updAS)

attribute [local irreducible] Code254.P

abbrev Rn (e : Edge) (st st' : AS) : Prop := Run dagDom e (enc st) .normal (enc st')

theorem seqAS {{n : Nat}} {{a b : Edge}} (hn : dagDom.nodes n = (a, b)) {{s0 s1 s2 : AS}}
    (ha : Run dagDom a (enc s0) .normal (enc s1)) (hb : Run dagDom b (enc s1) .normal (enc s2)) :
    Rn (.node n) s0 s2 := seq hn ha hb

theorem rn_eq {{e : Edge}} {{s s1 s2 : AS}} (h : Rn e s s1) (he : s1 = s2) : Rn e s s2 := he ▸ h

/-! ## The closed sets -/

/-- dagDom's equality test is dag219's: node 123 and nodes 461-466. -/
def okEq (n : Nat) : Bool := n == 123 || (461 ≤ n && n ≤ 466)

theorem closedEq : Closed Dag219.dag219 dagDom okEq :=
  closed_of_bounded (N := 467)
    (fun n hn => by
      simp only [okEq, Bool.or_eq_true, Bool.and_eq_true, decide_eq_true_eq, beq_iff_eq] at hn; omega)
    (by decide +kernel)

theorem eqDom (R : Regs) :
    Run dagDom (.node 123) R (Dag219.eqExit R) (Dag219.setR R 0 0) :=
  node_transfer closedEq rfl (Dag219.eq219 R)

/-- The nodes of `dag222` from which the AX routine (node 236) is reachable. -/
def anc : List Nat := [{anc_lit}]

/-- Below 461, and away from the AX routine. -/
def ok (n : Nat) : Bool := n < 461 && !(anc.contains n)

theorem closed222 : Closed Dag222.dag222 dagDom ok :=
  closed_of_contract (N := 461) (n0 := 123)
    (fun n hn => by simp only [ok, Bool.and_eq_true, decide_eq_true_eq] at hn; exact hn.1)
    (by decide +kernel) (contract _ _ Dag219.eq222 eqDom)

theorem tr {{n : Nat}} (hn : ok n = true) {{R : Regs}} {{x : Exit}} {{R' : Regs}}
    (h : Run Dag222.dag222 (.node n) R x R') : Run dagDom (.node n) R x R' :=
  node_transfer closed222 hn h

/-! ## The transferred lemmas -/

""" + "\n".join(lemmas) + """
end SetTheory.BusyBeaver.ZFC.L2Dom
"""
name = "L2Dom"
if VARIANT == "perm":
    out, name = retarget(out), "L2Perm"
(D / f"{name}.lean").write_text(out, encoding="utf-8", newline="\n")
print(f"wrote {name}.lean:", len(anc), "ancestors of 236,", len(lemmas), "lemmas")
