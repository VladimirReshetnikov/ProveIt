"""Generate the 215's decoder-site coverage: every leaf of the source tree passes `KSim.checkEdge tm215`.

  python generate_sites215_lean.py pilot LEAVES          one block of about LEAVES leaves (timing)
  python generate_sites215_lean.py full LEAVES PER_FILE   the whole tree

The tree is cut into subtrees of at most LEAVES leaves. Each block uses a kernel
decision with the existing balanced table and transfers it through fast215 equality:
`allSites (checkEdge tm215) revPrefix (descend t215 P) = true`, PER_FILE of them per module
(`KSites215Batch<i>`). `KSites215` joins them with `allSites_join` up to the root, as in the 240's
coverage (`SitesRotation240`). The Rocq endpoint checks the same leaves with the same executor
(`Interpreter230Check.all_leaves_check`), so every block should pass.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
from gen_cert import load  # noqa: E402

LEAN = HERE.parents[2] / "Lean" / "BusyBeaver" / "ZFC"
SITES = HERE.parent / "candidate-k215" / "sites215.json"
NS = "SetTheory.BusyBeaver.ZFC.KSites215"
TEST = "(KSim.checkEdge tm215)"
T = "KSource215.t215"
HEAD = ("import BusyBeaver.ZFC.KSource215Program\nimport BusyBeaver.ZFC.KFastSites215\n")
OPEN = f"namespace {NS}\n\nopen RegisterPath RMBisim SiteCoverage KTableCore\n\n"


def bl(P):
    return "[" + ", ".join("true" if b else "false" for b in P) + "]"


def cut(leaf, limit):
    inner = {p[:i] for p in leaf for i in range(len(p))}
    count = {}

    def cnt(p):
        if p in leaf:
            return 1
        if p not in count:
            count[p] = cnt(p + (False,)) + cnt(p + (True,))
        return count[p]

    blocks, joins = [], []

    def go(p):
        assert p in leaf or p in inner
        if cnt(p) <= limit:
            blocks.append(p)
        else:
            go(p + (False,))
            go(p + (True,))
            joins.append(p)

    go(())
    return blocks, joins, cnt


def stmt(P):
    return f"allSites {TEST} {bl(tuple(reversed(P)))}\n      (descend {T} {bl(P)}) = true"


def main():
    mode, limit = sys.argv[1], int(sys.argv[2])
    leaf = load(SITES)
    blocks, joins, cnt = cut(leaf, limit)
    if mode == "pilot":
        P = max((p for p in blocks if cnt(p) <= limit), key=cnt)
        body = (HEAD + f"\n/-! Pilot: one site block of {cnt(P)} leaves. -/\n\n" + OPEN +
                f"theorem pilot :\n    {stmt(P)} := by\n  exact KFastSites215.allSites_of_fast (by decide +kernel)\n\nend {NS}\n")
        (LEAN / "KSites215Pilot.lean").write_text(body, encoding="utf-8", newline="\n")
        print("pilot", len(P), "deep,", cnt(P), "leaves")
        return
    per = int(sys.argv[3])
    idx = {p: i for i, p in enumerate(blocks)}
    files = []
    for f in range(0, len(blocks), per):
        part = blocks[f:f + per]
        nm = f"KSites215Batch{f // per:03d}"
        files.append(nm)
        lines = [HEAD, f"\n/-! The 215's decoder sites, blocks {f} to {f + len(part) - 1} "
                 f"({sum(cnt(p) for p in part)} leaves).\nGenerated by "
                 "`Research/ZFC/k225-formal/generate_sites215_lean.py`. -/\n\n", OPEN]
        for p in part:
            lines.append(f"/-- {cnt(p)} leaves. -/\ntheorem block_{idx[p]} :\n    {stmt(p)} := by\n"
                         "  exact KFastSites215.allSites_of_fast (by decide +kernel)\n\n")
        lines.append(f"end {NS}\n")
        (LEAN / f"{nm}.lean").write_text("".join(lines), encoding="utf-8", newline="\n")
    out = ["import BusyBeaver.ZFC.KSource215Program\n" +
           "".join(f"import BusyBeaver.ZFC.{nm}\n" for nm in files),
           "\n/-!\nThe 215's decoder-site coverage: every leaf of the source tree passes the symbolic site check\n"
           f"`KSim.checkEdge tm215` ({len(leaf)} leaves in {len(blocks)} kernel blocks, joined to the root).\n"
           "Generated by `Research/ZFC/k225-formal/generate_sites215_lean.py`.\n-/\n\n", OPEN]
    def proof(p, indent=2):
        if p in idx:
            return f"block_{idx[p]}"
        pad = " " * (indent + 2)
        return ("(allSites_join _ _ _ _\n" + pad + proof(p + (False,), indent + 2) +
                "\n" + pad + proof(p + (True,), indent + 2) + ")")

    out.append(f"theorem all_sites : allSites {TEST} [] {T} = true :=\n  {proof(())}\n\n"
               "theorem covered : KSim.Covered tm215 KSource215.p215 :=\n"
               f"  KSim.covered_of_allSites tm215 KSource215.p215 {T} KSource215.t215_eq all_sites\n\n"
               f"end {NS}\n")
    (LEAN / "KSites215.lean").write_text("".join(out), encoding="utf-8", newline="\n")
    print(f"{len(leaf)} leaves, {len(blocks)} blocks in {len(files)} files, {len(joins)} joins")


if __name__ == "__main__":
    main()
