#!/usr/bin/env python3
"""Generate BusyBeaver/ZFC/Dag222.lean: the structured seed-K 222 program (dag222).

dag222 is Elliot Glazer's Dag230 (k230-rocq 3142e4d, coq/prog/Dag230.v) with the AX node 236
rebuilt by rocq224/tools/make_dag222.py (the rho7 word becomes the merged equality row G, the
bundle word the helper-free seed bundle). Dag230 itself is Jeff's 219-node dag254 with two
nodes changed (136: the QT loop rotation, through the new node 300; 149: the AX leaf now
enters node 236) and nodes 219-300 added. The node data are read from the dag222_nodes.json
written by make_dag222.py, the same data as the Rocq Dag222.v.

Usage: generate_dag222_lean.py DAG222_NODES_JSON OUT_LEAN"""
import json
import sys

src, out = sys.argv[1], sys.argv[2]
d = json.load(open(src))
nn = d["nnodes"]
nodes = {int(k): v for k, v in d["nodes"].items()}
assert sorted(nodes) == list(range(nn))

NAMES = {"N": "node", "EInc": "inc", "EDecnz": "decnz", "EBreak": "brk", "EContinue": "cont", "EHalt": "halt"}


def edge(e):
    op, a = e
    k = NAMES[op]
    return "(.halt)" if k == "halt" else f"(.{k} {a})"


lines = [
    "import BusyBeaver.ZFC.RMDag",
    "",
    "/-!",
    "The structured register program of the seed-K 222 and of the 221-state machine (`dag222`).",
    "",
    "Generated by `Computability/BusyBeaver/Research/ZFC/k225-formal/generate_dag222_lean.py` from",
    "the node data of `k225-formal/rocq224/src/Dag222.v`. It is Elliot Glazer's `Dag230`",
    "(k230-rocq `3142e4d`) with the AX node 236 rebuilt to emit the merged equality row G and the",
    "helper-free seed bundle. `Dag230` is Jeff's 219-node `dag254` with node 136 (the QT loop",
    "rotation, through node 300) and node 149 (the AX leaf, now entering node 236) changed, and",
    f"nodes 219-300 added; nodes 301-{nn - 1} continue node 236's word.",
    "-/",
    "",
    "namespace SetTheory.BusyBeaver.ZFC.Dag222",
    "",
    "open RMDag",
    "",
    "def dagNodes : Nat → Edge × Edge",
]
for n in range(nn):
    a, b = nodes[n]
    lines.append(f"  | {n} => ({edge(a)}, {edge(b)})")
lines += ["  | _ => ((.halt), (.halt))", "", "def dag222 : Prog := ⟨dagNodes, 0⟩", "",
          "end SetTheory.BusyBeaver.ZFC.Dag222", ""]
open(out, "w", encoding="utf-8", newline="\n").write("\n".join(lines))
print("wrote", out, nn, "nodes")
