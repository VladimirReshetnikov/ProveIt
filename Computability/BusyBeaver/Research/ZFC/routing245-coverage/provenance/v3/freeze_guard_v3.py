#!/usr/bin/env python3
"""Freeze only the exact successor manifest pin after root source emission; no proof execution."""
from pathlib import Path
import argparse,ast,hashlib,json
HERE=Path(__file__).resolve().parent
TEMPLATE_SHA='12723bc4949146d5657afb68a34b1c590f0221e8daef3f986f4d66e27b5af7a0'
GENERATOR_SHA='2c385ee00333bc4dec8a3b257ff7042de309368140f8b8eb536a6bce06e82f21'
def sha(p):return hashlib.sha256(Path(p).read_bytes()).hexdigest()
def need(c,m):
 if not c:raise ValueError(m)
def main():
 ap=argparse.ArgumentParser(description=__doc__);ap.add_argument('--manifest',type=Path,required=True);ap.add_argument('--output',type=Path,required=True);a=ap.parse_args()
 template=HERE/'check-production-v3.template.py';need(sha(template)==TEMPLATE_SHA,'Template changed.')
 p=a.manifest.resolve();d=json.loads(p.read_text());need(d['status']=='GENERATED_SOURCE_ONLY_UNBUILT','Wrong manifest status.')
 need(d['generator']['sha256']==GENERATOR_SHA==sha(d['generator']['path']),'Generator identity differs.')
 need((d['generated_units'],d['reused_unit_count'],d['chunks'],d['joins'],d['leaves'],d['guard_cases'],d['decoder_depth'])==(209,17,236,235,6460,8391,51),'Wrong successor census.')
 need((d['max_guards_per_cut'],d['max_cuts_per_module'],d['max_batch_guards'],d['joins_per_module'])==(64,1,64,16),'Wrong grouping.')
 need((d['generated_probes'],d['generated_callers'],d['complete_probes'],d['complete_callers'])==(431,431,476,479),'Wrong proof census.')
 for u in d['units']:
  for role in ('source','audit'):need(sha(p.parent/u[role])==u[role+'_sha256'],'Generated bytes changed.')
 need(len(d['units'])==209 and sum(u['kind']=='closed_cuts'for u in d['units'])==190 and
      [u['kind']for u in d['units'][:3]]==['closed_refined_child','closed_refined_child','refined_cut_composition'],
      'Wrong refined cut module schedule.')
 need(d['effective_frontier_cuts']==237 and d['effective_binary_joins']==236 and
      [u['guard_cases'] if 'guard_cases'in u else u['guards'] for u in d['units'][:2]]==[26,35],
      'Wrong child coverage.')
 text=template.read_text();old='MANIFEST_SHA=None  # Pin after root emits and reviews the refined source manifest.'
 need(text.count(old)==1,'Manifest placeholder differs.');text=text.replace(old,'MANIFEST_SHA='+repr(sha(p)))
 # Keep emitted source paths explicit; no output/source overrides are hidden.
 olddefault="default=HERE/'sources/generation.json'";need(text.count(olddefault)==1,'Manifest default differs.')
 text=text.replace(olddefault,'default=Path('+repr(str(p))+')');ast.parse(text)
 out=a.output.resolve();need(out.parent==HERE,'Guard must remain beside its exact generator/template.');need(not out.exists(),'Never overwrite a frozen guard.');out.write_text(text)
 print(json.dumps({'status':'GUARD_SOURCE_ONLY_NOT_EXECUTED','manifest':{'path':str(p),'sha256':sha(p)},'guard':{'path':str(out),'sha256':sha(out)},'template_sha256':TEMPLATE_SHA},indent=2))
if __name__=='__main__':main()
