"""Class-step degrees at any parameter exponent P and Bohr exponent T.

`step_count_le` and `step_exp_inv_le` (route (II), Notes L.6) and their Fejér copies
(`…_fejer`, generated by `assemble_csdfejer.py`) used the same proof with
`stepP k, stepT k` resp. `fejerStepP k, fejerStepT k`, and with the six bounds of
`Proofs16ClassStepBounds(Fejer)`. Here the proof is stated once, with those bounds as hypotheses and
the degrees `…W P T`; both families are instances. Statements unchanged.
"""
import re

from foldlib import Fold

D, DF = 'Proofs16ClassStepDegrees', 'Proofs16ClassStepDegreesFejer'
F = Fold()


def sub1(t, a, b):
    assert t.count(a) == 1, (t.count(a), a[:90])
    return t.replace(a, b)


DEGS = '''/-! ### The degrees at any parameter exponent `P` and Bohr exponent `T`

The degrees above are these at `P = stepP k`, `T = stepT k`, and the Fejér
degrees of `Proofs16ClassStepDegreesFejer` are these at `fejerStepP k`,
`fejerStepT k` (both by `rfl`). -/

def stepY1W (P k : Nat) : Nat := 2 * P + k + 9
def stepQrDegW (P k D : Nat) : Nat := 2 ^ k * (D * stepY1W P k)
def stepSDegW (P k D : Nat) : Nat := stepQrDegW P k D + (P + 2) + 7
def stepPbDegW (P k D : Nat) : Nat := D * (stepSDegW P k D + 2 * P + 8)
def stepEbDegW (P D : Nat) : Nat := D * (2 * P + 9)
def stepErDegW (P k D : Nat) : Nat := (4 + D * stepY1W P k) * 2 ^ k
def stepBqDegW (P k D : Nat) : Nat := 4 + (stepEbDegW P D + 1) * 2 ^ (k + 2)
def stepLDegW (P k D : Nat) : Nat := stepBqDegW P k D + (stepErDegW P k D + stepEbDegW P D)
def stepZDegW (P T D : Nat) : Nat := T + stepEbDegW P D + 4
def stepCountDegW (P k D : Nat) : Nat :=
  (P + 2) + (2 * stepSDegW P k D + stepPbDegW P k D + stepPbDegW P k D)
def stepExpDegW (P T k D : Nat) : Nat :=
  stepZDegW P T D + 1 + stepLDegW P k D + stepPbDegW P k D + 5

'''
APPLIED = [('stepY1 k', 'stepY1W P k'), ('stepQrDeg k D', 'stepQrDegW P k D'),
           ('stepSDeg k D', 'stepSDegW P k D'), ('stepPbDeg k D', 'stepPbDegW P k D'),
           ('stepEbDeg k D', 'stepEbDegW P D'), ('stepErDeg k D', 'stepErDegW P k D'),
           ('stepBqDeg k D', 'stepBqDegW P k D'), ('stepLDeg k D', 'stepLDegW P k D'),
           ('stepZDeg k D', 'stepZDegW P T D'), ('stepCountDeg k D', 'stepCountDegW P k D'),
           ('stepExpDeg k D', 'stepExpDegW P T k D'), ('stepP k', 'P'), ('stepT k', 'T'),
           ('classPieces gamma theta k', 'm'), ('classBudget theta gamma k', 'tS'),
           ('classDelta theta gamma k', 'gS'), ('section16Zeta theta gamma k', 'zeta')]
BARE = ['stepY1', 'stepQrDeg', 'stepSDeg', 'stepPbDeg', 'stepEbDeg', 'stepErDeg', 'stepBqDeg',
        'stepLDeg', 'stepZDeg', 'stepCountDeg', 'stepExpDeg']
INPUTS = ['  obtain ⟨hb, -⟩ := classBudget_pos_le k ht ht1 hg hg1\n',
          '  obtain ⟨hb, hb1⟩ := classBudget_pos_le k ht ht1 hg hg1\n',
          '  obtain ⟨-, -, hd, hd1⟩ := section16_theta_delta_bounds k ht ht1 hg hg1\n',
          '  have hm := classPieces_le_stepP k hg hg1 ht ht1\n',
          '  have hgd := twoDiv_gamma_le k hg hg1 ht ht1\n',
          '  have hdd := twoDiv_delta_le k hg hg1 ht ht1\n',
          '  have hPk := stepP_ge k\n',
          '  set m := m\n', '  set tS := tS\n']


def generalize(text):
    for a, b in APPLIED:
        text = re.sub(r"(?<![\w'.])" + re.escape(a) + r"(?![\w'])", b, text)
    for a in BARE:
        text = re.sub(r"(?<![\w'.])" + re.escape(a) + r"(?![\w'])", a + 'W', text)
    for line in INPUTS:
        text = text.replace(line, '')
    return text


# --- step_count_le
cnt = F.take(D, 'step_count_le')
g = generalize(cnt)
g = sub1(g, '/-- **The count of the next class.** -/\ntheorem step_count_le {k D : Nat}',
         '/-- **The count of the next class**, from the class-step bounds at `P`. -/\n'
         'theorem step_count_le_W {k D P : Nat}')
g = sub1(g, '    (hr : 0 < rho) (hr1 : rho ≤ 1) (n : Nat) :\n',
         '    (hr : 0 < rho) (hr1 : rho ≤ 1) (n : Nat) {m : Nat} {tS : Real} (hb : 0 < tS)\n'
         '    (hm : (m : Real) ≤ (2 / (gamma * theta)) ^ P)\n'
         '    (hgd : 2 / (gamma * tS) ≤ (2 / (gamma * theta)) ^ (P + 1)) (hPk : k + 8 ≤ P) :\n')
cnt_inst = cnt[:cnt.index(':= by')] + ''':=
  step_count_le_W hD hV hVV hg hg1 ht ht1 hr hr1 n (P := stepP k)
    (classBudget_pos_le k ht ht1 hg hg1).1 (classPieces_le_stepP k hg hg1 ht ht1)
    (twoDiv_gamma_le k hg hg1 ht ht1) (stepP_ge k)
'''
F.insert(D, g + '\n' + cnt_inst, 'step_exp_inv_le')

# --- step_exp_inv_le
ex = F.take(D, 'step_exp_inv_le')
g = generalize(ex)
g = sub1(g, 'theorem step_exp_inv_le {k D : Nat}', 'theorem step_exp_inv_le_W {k D P T : Nat}')
g = sub1(g, '/-- **The width exponent of the next class.** -/\n',
         '/-- **The width exponent of the next class**, from the class-step bounds at `(P, T)`. -/\n')
g = sub1(g, '    (hr : 0 < rho) (hr1 : rho ≤ 1) (n : Nat) :\n    let M := n * m\n    let tS := tS\n    let gS := gS\n',
         '    (hr : 0 < rho) (hr1 : rho ≤ 1) (n : Nat) {m : Nat} {tS gS zeta : Real}\n'
         '    (hb : 0 < tS) (hb1 : tS ≤ 1) (hd : 0 < gS) (hd1 : gS ≤ 1)\n'
         '    (hz : 0 < zeta ∧ zeta ≤ 1 ∧ zeta⁻¹ ≤ Real.exp ((2 / (gamma * theta)) ^ T))\n'
         '    (hm : (m : Real) ≤ (2 / (gamma * theta)) ^ P)\n'
         '    (hgd : 2 / (gamma * tS) ≤ (2 / (gamma * theta)) ^ (P + 1))\n'
         '    (hdd : 2 / (gS * tS) ≤ (2 / (gamma * theta)) ^ (P + 1)) (hPk : k + 8 ≤ P) :\n'
         '    let M := n * m\n')
g = sub1(g, '  intro M tS gS e\n', '  intro M e\n')
g = sub1(g, '  obtain ⟨hz0, hz1, hzi⟩ := section16Zeta_inv_le_gen k hg ht\n', '  obtain ⟨hz0, hz1, hzi⟩ := hz\n')
g = sub1(g, '      unfold stepZDegW stepT\n      omega\n', '      unfold stepZDegW\n      omega\n')
g = sub1(g, '    unfold stepZDegW stepT\n    have : 1 ≤ 2 ^ (2 ^ (k + 6)) := Nat.one_le_two_pow\n    omega\n',
         '    have : 1 ≤ stepEbDegW P D := Nat.mul_pos (by omega) (by omega)\n    unfold stepZDegW\n    omega\n')
ex_inst = ex[:ex.index(':= by')] + ''':=
  have hb := classBudget_pos_le k ht ht1 hg hg1
  have hd := section16_theta_delta_bounds k ht ht1 hg hg1
  step_exp_inv_le_W hD hV hVV hK hp hKV hpV hg hg1 ht ht1 hr hr1 n (P := stepP k) (T := stepT k)
    hb.1 hb.2 hd.2.2.1 hd.2.2.2 (section16Zeta_inv_le_gen k hg ht)
    (classPieces_le_stepP k hg hg1 ht ht1) (twoDiv_gamma_le k hg hg1 ht ht1)
    (twoDiv_delta_le k hg hg1 ht ht1) (stepP_ge k)
'''
F.insert(D, g + '\n' + ex_inst, 'step_thr_le')
s = F.get(D)
F.text[D] = sub1(s, '/-! ### Bases -/\n', DEGS + '/-! ### Bases -/\n')

# --- Fejér instances
F.reprove(DF, 'step_count_le_fejer', '''
  step_count_le_W hD hV hVV hg hg1 ht ht1 hr hr1 n (P := fejerStepP k)
    (classBudgetW_pos_le k (fejerThetaOne_bounds k ht ht1 hg hg1).1
      (fejerThetaOne_bounds k ht ht1 hg hg1).2).1
    (classPiecesFejer_le_gen k hg hg1 ht ht1) (twoDiv_gamma_le_fejer k hg hg1 ht ht1)
    (by have := fejerStepP_ge k; omega)''')
F.reprove(DF, 'step_exp_inv_le_fejer', '''
  have hf := fejerThetaOne_bounds k ht ht1 hg hg1
  have hb := classBudgetW_pos_le k hf.1 hf.2
  have hd := section16_theta_delta_bounds_with hf.1 hf.2
  step_exp_inv_le_W hD hV hVV hK hp hKV hpV hg hg1 ht ht1 hr hr1 n (P := fejerStepP k)
    (T := fejerStepT k) hb.1 hb.2 hd.2.2.1 hd.2.2.2 (tightZeta_fejer_inv_le_gen k hg hg1 ht ht1)
    (classPiecesFejer_le_gen k hg hg1 ht ht1) (twoDiv_gamma_le_fejer k hg hg1 ht ht1)
    (twoDiv_delta_le_fejer k hg hg1 ht ht1) (by have := fejerStepP_ge k; omega)''')
F.commit()
