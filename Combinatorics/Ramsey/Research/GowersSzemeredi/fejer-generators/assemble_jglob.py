def skip_ws(t, k):
    while t[k] in ' \n':
        k += 1
    return k


def cover_widths(t):
    """coverWidth EB ((fun s => s / 2 / QB (s / 2)) (singlePieceTheta X 1)) (coverWidth EB (singlePieceTheta X 1) L)
       -> jointSliceWidth EB X 1 L"""
    out, pos = [], 0
    key = 'coverWidth '
    while True:
        i = t.find(key, pos)
        while i > 0 and (t[i - 1].isalnum() or t[i - 1] == '_'):
            i = t.find(key, i + 1)
        if i < 0:
            out.append(t[pos:]); break
        j = skip_ws(t, i + len(key))
        e1 = arg_end(t, j); EB = t[j:e1]
        k2 = skip_ws(t, e1)
        if not t.startswith('((fun s => s / 2 /', k2):
            out.append(t[pos:e1]); pos = e1; continue
        e2 = arg_end(t, k2); A2 = t[k2:e2]
        m = re.search(r'\(singlePieceTheta (.*) 1\)\)$', A2, re.S)
        assert m, A2[:200]
        X = m.group(1)
        k3 = skip_ws(t, e2)
        e3 = arg_end(t, k3); A3 = t[k3 + 1:e3 - 1]
        pre = 'coverWidth ' + EB
        assert A3.startswith(pre), A3[:120]
        rest = A3[len(pre):].strip()
        pre2 = '(singlePieceTheta ' + X + ' 1)'
        rest_n = re.sub(r'\s+', ' ', rest)
        pre2_n = re.sub(r'\s+', ' ', pre2)
        assert rest_n.startswith(pre2_n), (rest_n[:150], pre2_n)
        L = rest_n[len(pre2_n):].strip()
        out.append(t[pos:i])
        out.append('jointSliceWidth ' + EB + ' ' + re.sub(r'\s+', ' ', X) + ' 1 ' + L)
        pos = e3
    return ''.join(out)


