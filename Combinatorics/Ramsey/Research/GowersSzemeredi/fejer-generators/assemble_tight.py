"""Proofs16UniformCoverTwoTight: the dimension-two count at W^(2^39) (Notes L.16y)."""
from pathlib import Path

GS = Path(r'C:\ProveIt\.claude\worktrees\q-fabius-deformations-merge-9bc27b\Combinatorics\Ramsey\Lean\GowersSzemeredi')


def text(name):
    return (GS / f'{name}.lean').read_text(encoding='utf-8')


def sub(t, pairs):
    for a, b in pairs:
        assert a in t, ('missing', a[:100])
        t = t.replace(a, b)
    return t


F = '(10002 * (2 ^ 23 + 1) : Nat)'

# the face count at the unrounded exponent
sc = text('Proofs18FejerSeedCounts')
a = sc.index('theorem polyPieceFaceCountW_fejer_le_power')
b = sc.index('/-- The number of pieces')
face = sc[a:b]
face = sub(face, [
    ('theorem polyPieceFaceCountW_fejer_le_power', 'theorem polyPieceFaceCountW_fejer_le_tight'),
    ('(2 / (gamma * theta)) ^ ((2 : Nat) ^ 38) := by', f'(2 / (gamma * theta)) ^ {F} := by'),
    ('have hBF := section16BaseFamilyBound_le_dyadic_power hg hg1 hb hb1',
     'have hBF := section16BaseFamilyBound_le_power hg hg1 hb hb1'),
    ('''  calc (2 / (gamma * b)) ^ ((2 : Nat) ^ 14)
      ≤ (u ^ ((2 : Nat) ^ 23 + 1)) ^ ((2 : Nat) ^ 14) :=
        pow_le_pow_left₀ (div_pos (by norm_num) (mul_pos hg hb)).le hbase _
    _ = u ^ (((2 : Nat) ^ 23 + 1) * (2 : Nat) ^ 14) := (pow_mul _ _ _).symm
    _ ≤ u ^ ((2 : Nat) ^ 38) := pow_le_pow_right₀ hu1 (by norm_num)''',
     f'''  calc (2 / (gamma * b)) ^ (10002 : Nat)
      ≤ (u ^ ((2 : Nat) ^ 23 + 1)) ^ (10002 : Nat) :=
        pow_le_pow_left₀ (div_pos (by norm_num) (mul_pos hg hb)).le hbase _
    _ = u ^ ((2 ^ 23 + 1) * 10002) := (pow_mul _ _ _).symm
    _ = u ^ {F} := by rw [mul_comm]'''),
])

# the count
uc = text('Proofs16UniformCoverTwoSplit')
a = uc.index('theorem uniTwoFejerCount_le_split ')
b = uc.index('/-- The samples of the dimension-two family, in two bases. -/')
cnt = uc[a:b]
cnt = sub(cnt, [
    ('theorem uniTwoFejerCount_le_split ', 'theorem uniTwoFejerCount_le_split_tight '),
    ('((n : Real) + 1) ^ 11 * splitW V theta gamma rho ^ ((2 : Nat) ^ 41) := by',
     '((n : Real) + 1) ^ 11 * splitW V theta gamma rho ^ ((2 : Nat) ^ 39) := by'),
    ('''  obtain ⟨hM, hqf, -⟩ := two_split_basics hV hg hg1 ht ht1 hr hr1 n''',
     f'''  obtain ⟨hM, -, -⟩ := two_split_basics hV hg hg1 ht ht1 hr hr1 n
  have hqf : (polyPieceFaceCountW (fejerThetaOne theta gamma 1) gamma : Real) ≤
      ((n : Real) + 1) ^ 0 * splitW V theta gamma rho ^ {F} := by
    obtain ⟨-, hvW, -, -⟩ := splitW_facts hV hg hg1 ht ht1 hr hr1
    obtain ⟨hu2, -, -, -, -⟩ := prod_scale_basic hg hg1 ht ht1
    have hu0 : (0 : Real) ≤ 2 / (gamma * theta) := le_trans (by norm_num) hu2
    rw [pow_zero, one_mul]
    exact (polyPieceFaceCountW_fejer_le_tight hg hg1 ht ht1).trans (pow_le_pow_left₀ hu0 hvW _)'''),
])
cnt = cnt.replace('(2 : Nat) ^ 38', F)
assert '2 ^ 41' not in cnt and '^ 38' not in cnt

# the seed
tt = text('Proofs16SplitTwoTrackClasses')
a = tt.index('/-- **Dimension two as a two-track class**')
b = tt.index('/-! ### The two-track recursion -/')
seed = tt[a:b]
seed = sub(seed, [
    ('/-- **Dimension two as a two-track class**: count `(11, 2^41)`, exponent `(29, 2^46)`. -/',
     '/-- **Dimension two as a two-track class at the tight count**: count `(11, 2^39)`, exponent `(29, 2^46)`. -/'),
    ('theorem splitUniformClass2_two ', 'theorem splitUniformClass2_two_tight '),
    ('Nonempty (SplitUniformClass2 2 V 11 ((2 : Nat) ^ 41) 29 ((2 : Nat) ^ 46))',
     'Nonempty (SplitUniformClass2 2 V 11 ((2 : Nat) ^ 39) 29 ((2 : Nat) ^ 46))'),
    ('exact uniTwoFejerCount_le_split hV hg hg1 ht ht1 hr hr1 n',
     'exact uniTwoFejerCount_le_split_tight hV hg hg1 ht ht1 hr hr1 n'),
])

HEAD = '''import GowersSzemeredi.Proofs16SplitTwoTrackClasses

/-! **The dimension-two count at `W^(2^39)`** (Notes L.16y).

The face count of the dimension-two family is
`max(1, ⌊γ⁻²/lemma163Alpha γ b⌋) ≤ (2/(γb))^10002`
(`section16BaseFamilyBound_le_power`). The corpus rounds the exponent `10002`
to `2^14` and the result to `u^(2^38)`; unrounded it is
`u^(10002·(2^23+1)) ≈ u^(2^36.29)` (`polyPieceFaceCountW_fejer_le_tight`). The
count of the dimension-two class is about six times the face degree, so it is
at most `(n+1)^11·W^(2^39)` (`uniTwoFejerCount_le_split_tight`; it was
`W^(2^41)`), and dimension two is a two-track class at count `(11, 2^39)`
(`splitUniformClass2_two_tight`). Generated by `assemble_tight.py`. -/
set_option autoImplicit false
noncomputable section
namespace LeanProofs.GowersSzemeredi
open BaseCase

'''
out = HEAD + face + cnt + seed + 'end LeanProofs.GowersSzemeredi\n'
(GS / 'Proofs16UniformCoverTwoTight.lean').write_text(out, encoding='utf-8', newline='\n')
print('wrote', len(out.splitlines()))
