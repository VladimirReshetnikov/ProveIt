    m = {'splitQuad': 'splitQuad3', 'splitQuad_two': 'splitQuad3_two', 'splitQuad_succ': 'splitQuad3_succ',
         'split_quad_le_max': 'split_quad3_le_max', 'splitUniformClass2_all': 'splitUniformClass2_all3',
         'split_quad_le_uDegT2': 'split_quad3_le_uDegT3'}
