def text(name):
    return (GS / f'{name}.lean').read_text(encoding='utf-8')


JSET = {'GenParamsJ', 'densDegJ', 'expDegJ', 'rhoDegJ', 'threshDegJ', 'yIn_boundsJ', 'Eloc_inv_leJ',
        'rho1_inv_leJ', 'nestExp_inv_leJ', 'spectrum_exps_inv_leJ', 'slice_exps_inv_leJ', 'MReq_le_expJ',
        'Tloc_le_expJ', 'coverPrec_gen_bounds_fejerJ', 'tightHyp_of_profiles_fejerJ'}
KPRE = ('envStepKTx', 'envBound_stepKx', 'genMuXK', 'envBound_allXK')


def ren(tok):
    if tok in JSET:
        return tok + 'T3'
    if tok.startswith('rhoDegJ_'):
        return 'rhoDegJT3_' + tok[len('rhoDegJ_'):]
    for p in KPRE:
        if tok.startswith(p):
            return p + '3' + tok[len(p):]
    for a, b in (('tDegZ', 'tDegT3'), ('uDegZ', 'uDegT3'), ('classZ', 'classT3')):
        tok = tok.replace(a, b)
    return tok


def rename(t):
    return re.sub(r"[A-Za-z_][A-Za-z0-9_']*", lambda m: ren(m.group(0)), t)


