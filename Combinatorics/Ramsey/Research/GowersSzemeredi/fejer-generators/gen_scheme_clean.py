"""Slice schemes, cleanup: the joint chain's intermediate instances have no users.

Only `single_piece_lift_global_cover_with_joint` is used (by the inverse step). The joint line-cell,
affine-cell, spectrum-cover and core instances and `jointSliceWidth_mono` (now `wid_mono` of the
scheme) are deleted; `Proofs16JointSliceSpectrum` and `Proofs16JointSliceCore` become empty and are
removed. Docstrings describe the scheme.
"""
from foldlib import Fold

F = Fold()
JC, JS, JK, JG = ('Proofs16JointSliceCell', 'Proofs16JointSliceSpectrum', 'Proofs16JointSliceCore',
                  'Proofs16JointSliceGlobal')
F.delete_decl(JC, 'single_piece_on_line_cell_of_joint_slices')
for n in ('jointSliceWidth_mono', 'single_piece_on_affine_cell_joint', 'single_piece_of_spectrum_cover_for_joint'):
    F.delete_decl(JS, n)
F.delete_decl(JK, 'single_piece_lift_core_rem_joint')
F.delete_module(JS, ['Proofs16JointSliceCell', 'Proofs16SinglePieceSpectrum'])
F.delete_module(JK, ['Proofs16JointSliceCell', 'Proofs16SinglePieceSpectrum', 'Proofs16VertexWithCovers'])


def sub1(m, a, b):
    s = F.get(m)
    assert s.count(a) == 1, (m, s.count(a), a[:80])
    F.text[m] = s.replace(a, b)


sub1(JC, '''/-! **Joint slices: the line-cell lemma with the two anchor sections covered
together** (Notes L.16q).''', '''/-! **Joint slices: the two anchor sections covered together** (Notes L.16q).''')
sub1(JC, '''Steps 1, 2, 4 and 5 are those of `single_piece_on_line_cell_of_slices`
verbatim (generated by `assemble_jslice.py`). -/''', '''This is the slice scheme `jointSliceScheme`. The line-cell, affine-cell,
spectrum-cover and core lemmas of the single-piece lift hold for every slice
scheme (`single_piece_on_line_cell_of_scheme` and its successors), so the
joint-slice lift is their instance (`single_piece_lift_global_cover_with_joint`). -/''')
s = F.get(JG)
i, j = s.index('/-!'), s.index('-/', s.index('/-!'))
print('--- JointSliceGlobal docstring (before) ---')
print(s[i:j + 2])
