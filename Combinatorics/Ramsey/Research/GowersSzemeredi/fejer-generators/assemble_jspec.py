def arg_end(t, i):
    """index just past the balanced argument starting at t[i] (either '(' group or a token)."""
    if t[i] == '(':
        depth = 0
        for j in range(i, len(t)):
            if t[j] == '(':
                depth += 1
            elif t[j] == ')':
                depth -= 1
                if depth == 0:
                    return j + 1
        raise ValueError('unbalanced')
    m = re.match(r'[^\s()]+', t[i:])
    return i + m.end()


def joint_widths(t):
    """w (c (singlePieceTheta X q)) (w (singlePieceTheta X q) Y)  ->  jointSliceWidth Es X q Y."""
    key = 'w (c (singlePieceTheta '
    out, pos = [], 0
    while True:
        i = t.find(key, pos)
        while i > 0 and (t[i - 1].isalnum() or t[i - 1] == '_'):
            i = t.find(key, i + 1)
        if i < 0:
            out.append(t[pos:]); break
        out.append(t[pos:i])
        j = i + len(key)
        xe = arg_end(t, j); X = t[j:xe]
        qe = arg_end(t, xe + 1); Q = t[xe + 1:qe]
        assert t[qe:qe + 2] == '))', t[i:i + 120]
        k = qe + 2
        # whitespace (possibly newline) then (w (singlePieceTheta X q) Y)
        while t[k] in ' \n':
            k += 1
        assert t[k] == '(', t[i:i + 200]
        ge = arg_end(t, k)
        inner = t[k + 1:ge - 1]
        pre = 'w (singlePieceTheta ' + X + ' ' + Q + ')'
        assert inner.startswith(pre), (inner[:100], pre)
        Y = inner[len(pre):].strip()
        out.append('jointSliceWidth Es ' + X + ' ' + Q + ' ' + Y)
        pos = ge
    return ''.join(out)


def sub(t, pairs):
    for a, b in pairs:
        assert a in t, ('missing', a[:110])
        t = t.replace(a, b)
    return t


