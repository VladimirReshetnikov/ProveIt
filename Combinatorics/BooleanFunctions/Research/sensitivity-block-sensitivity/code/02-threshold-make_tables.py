#!/usr/bin/env python3
"""Generate non-proof display tables from exact recurrence values."""
from __future__ import annotations
import csv, json, math
from decimal import Decimal, localcontext
from pathlib import Path
from profiles import Parameters, compute_profiles, summarize
ROOT=Path(__file__).resolve().parents[1]

def alpha(beta,A):
    with localcontext() as c:
        c.prec=60
        return Decimal(beta).ln()/Decimal(A).ln()

def coarse(p, sharper=False):
    a,b,j,h=p.depth+1,p.block_length*p.base_blocks,0,0
    for _ in range(p.depth):
        if sharper:
            aa=max((p.forbidden-1)*a+b,(p.forbidden-2)*a+b+h,(p.forbidden-4)*a+3*h)
            jj=max((p.forbidden-1)*a+h,(p.forbidden-2)*a+2*h,(p.forbidden-4)*a+3*h)
        else:
            aa=p.forbidden*a+b+3*h
            jj=p.forbidden*a+3*h
        a,b,j,h=aa,p.degree*a+p.positions*b,jj,p.degree*j+p.positions*b
    return max(p.copies*a,b)

p=Parameters();layers=compute_profiles(p);s=summarize(p,layers);beta=s['beta']
rows=[]
rows.append(('Uniform four-profile bounds',coarse(p)))
rows.append(('Uniform profiles with joint gate budgets',coarse(p,True)))
rows.append(('Threshold profiles, separate list budgets',summarize(p,compute_profiles(p,packing=False))['A']))
rows.append(('Threshold profiles, no interval clipping',summarize(p,compute_profiles(p,clipping=False))['A']))
rows.append(('Full threshold-resolved certificate',s['A']))
with (ROOT/'results'/'ablation.csv').open('w',newline='') as f:
    w=csv.writer(f);w.writerow(['method','A_upper_bound','log_beta_over_log_A'])
    for name,A in rows:w.writerow([name,A,str(alpha(beta,A))])
source=[]
for d in range(1,201):
    M=9**(d+1)
    A=2*(d+2)*M**(d+1)
    b=M*M*(2*M*M+1)**d
    source.append((alpha(b,A),d))
source.sort(reverse=True)
(ROOT/'results'/'source_parameter_scan.json').write_text(json.dumps({
    'scope':'Numerical scan of depths 1..200, taking the smallest permitted M=9^(d+1) in the source sufficient bound. Not a global optimization of all source constructions.',
    'best_depth_in_scan':source[0][1],'best_alpha_in_scan':str(source[0][0]),
    'displayed_depth_9_alpha':str(next(a for a,d in source if d==9))},indent=2)+'\n')
chunks=[];v=s['A']
while v:chunks.append(v%10**30);v//=10**30
assert len(chunks)==3
with (ROOT/'results'/'generated_constants.tex').open('w') as f:
    f.write('% Generated by code/make_tables.py; decimal displays are not the proof.\n')
    f.write('\\newcommand{\\SeedAlpha}{'+format(alpha(beta,s['A']),'.15f')+'}\n')
    f.write('\\newcommand{\\SourceScanAlpha}{'+format(source[0][0],'.9f')+'}\n')
    f.write('\\newcommand{\\SourceScanDepth}{'+str(source[0][1])+'}\n')
    for name,val in zip(('Alow','Amid','Ahigh'),chunks):
        f.write('\\newcommand{\\'+name+'}{'+str(val)+'}\n')
with (ROOT/'results'/'ablation_table.tex').open('w') as f:
    for name,A in rows:
        f.write(name+' & '+format(alpha(beta,A),'.9f')+' \\\\\n')
with (ROOT/'results'/'layers_table.tex').open('w') as f:
    for z in layers:
        H=z['H']
        def lv(x):return '--' if x==0 else f'{math.log10(x):.5f}'
        f.write(f"{z['level']} & {H} & {lv(z['s0'][1])} & {lv(z['s1'][1])} & {lv(z['j0'][1][H])} & {lv(z['j1'][1][H])} \\\\\n")
print('Source scan:',source[0])
for name,A in rows:print(name,alpha(beta,A))
