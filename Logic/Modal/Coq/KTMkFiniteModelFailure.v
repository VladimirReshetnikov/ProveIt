(**
  The finite-model-property failure of KTMk.

  This module ports the proved surface of the pinned Foundation file
  [Modal/Kripke/Logic/KTMk.lean].  KTMk is the normal logic generated by T
  and Makinson's two-variable axiom Mk.  Its intended frames are reflexive
  frames satisfying [frame_makinson].

  The central result is deliberately stated for a fixed model, just as in
  Foundation: every finite model in which all KTMk theorems hold validates
  every instance of Four.  Starting from a failure of Four, Mk produces a
  world at the next box depth.  T makes worlds at distinct depths distinct,
  so an arbitrarily long list of such worlds contradicts an explicit finite
  cover.  This avoids Foundation's more elaborate list-chain construction.

  The pinned proof of canonicality for Mk, in [Modal/Kripke/AxiomMk.lean],
  is literally [sorry].  Consequently no canonical-completeness theorem is
  asserted here.  Soundness, consistency, the fixed-model finite theorem,
  the recession counterframe, failure of the finite model property, and the
  two strict hierarchy results are all proved without admissions.
*)

