(**
  The generic equivalence between WithRE and normal Hilbert calculi.

  This is an independent Rocq port of Foundation's theorem
  [equiv_WithRE_Normal_of_provable_axiomInstances] from
  [Modal/Hilbert/WithRE_Normal.lean].  The two local calculi package their
  modal generators differently: [with_re_proves] substitutes its raw
  axioms at the constructor, while [normal_proves] has modal K as a
  hardcoded generator and takes its additional schema instances directly.
  The two premise predicates below record those exact constructor surfaces.

  As in the source theorem, replacement for the normal target and
  necessitation for the WithRE target are hypotheses.  Neither rule is
  silently added to the corresponding raw calculus.
*)

From FoundationModal Require Import
  Syntax Axioms NormalHilbert LogicInfrastructure EntailmentExtensions
  HilbertWithRE.

Set Implicit Arguments.
Unset Strict Implicit.
Set Universe Polymorphism.

(** Every substituted instance generated by [WRE_axm] is provable in the
    selected normal system. *)
Definition with_re_axiom_instances_provable_in_normal
    {AtomType : Type} (AxE : with_re_axiom AtomType)
    (AxN : modal_axiom_schema) : Prop :=
  forall (p : formula AtomType) (sigma : AtomType -> formula AtomType),
    AxE p -> normal_proves AxN (substitute sigma p).

(** The non-propositional generators of [normal_proves].  Modal K belongs
    here because it is hardcoded in the local normal calculus rather than
    represented by [AxN]. *)
Inductive normal_generator {AtomType : Type} (AxN : modal_axiom_schema)
    : formula AtomType -> Prop :=
| normal_generator_modal_K : forall p q,
    normal_generator AxN (K p q)
| normal_generator_extra : forall p,
    AxN AtomType p -> normal_generator AxN p.

Arguments normal_generator_modal_K {AtomType AxN} p q.
Arguments normal_generator_extra {AtomType AxN p} _.

(** Every modal generator of the selected normal system is provable in the
    WithRE system. *)
Definition normal_generators_provable_in_with_re
    {AtomType : Type} (AxE : with_re_axiom AtomType)
    (AxN : modal_axiom_schema) : Prop :=
  forall p, normal_generator AxN p -> with_re_proves AxE p.

Theorem with_re_normal_equiv_of_provable_generators :
  forall (AtomType : Type) (AxE : with_re_axiom AtomType)
         (AxN : modal_axiom_schema),
    replacement_of_equivalents (@normal_proves AxN AtomType) ->
    necessitation (@with_re_proves AtomType AxE) ->
    with_re_axiom_instances_provable_in_normal AxE AxN ->
    normal_generators_provable_in_with_re AxE AxN ->
    logic_equiv (@with_re_proves AtomType AxE)
                (@normal_proves AxN AtomType).
Proof.
  intros AtomType AxE AxN Hnormal_re Hwith_re_nec HAxE HAxN.
  apply logic_equiv_of_provable; intro p; split.
  - intro Hp; induction Hp.
    + now apply HAxE.
    + exact (Np_mp IHHp1 IHHp2).
    + now apply Hnormal_re.
    + apply Np_imply_K.
    + apply Np_imply_S.
    + apply Np_elim_contra.
  - intro Hp; induction Hp.
    + apply WRE_imply_K.
    + apply WRE_imply_S.
    + apply WRE_elim_contra.
    + apply HAxN. apply normal_generator_modal_K.
    + apply HAxN. now apply normal_generator_extra.
    + exact (WRE_mp IHHp1 IHHp2).
    + now apply Hwith_re_nec.
Qed.

(** Source-facing alias. *)
Definition equiv_WithRE_Normal_of_provable_axiomInstances :=
  @with_re_normal_equiv_of_provable_generators.
