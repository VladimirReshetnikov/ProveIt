(** Generic canonicality of Geach axioms.

    This ports the canonical-frame section of
    Foundation/Modal/Kripke/AxiomGeach.lean.  Foundation uses a two-sided
    maximal-consistent tableau.  The Coq proof instead builds a one-sided
    Lindenbaum seed: formulas forced forward from the first branch are added
    positively, while formulas forbidden by the second branch are added
    negatively.  Finite support reduces consistency to one implication, and
    the canonical truth lemma handles all iterated modality bookkeeping. *)

From Stdlib Require Import Lists.List.
From FoundationModal Require Import
  Syntax Axioms Kripke LogicInfrastructure EntailmentExtensions Correspondence
  HilbertK NormalHilbert
  CanonicalK CanonicalExtensions FiniteMaximalContext FiniteCanonicalSupport
  GLModalDisjunction CanonicalK4n.

Import ListNotations.

Set Implicit Arguments.
Unset Strict Implicit.
Set Universe Polymorphism.

(** The raw schema generated by one Geach tuple. *)
Definition schema_Geach (g : geach_tuple) : modal_axiom_schema :=
  fun AtomType p => exists q : formula AtomType, p = Geach g q.

Lemma schema_Geach_substitution_closed :
  forall g, schema_substitution_closed (schema_Geach g).
Proof.
  intros g A B sigma p [q ->].
  exists (substitute sigma q). unfold Geach. simpl.
  now rewrite !substitute_dia_iter, !substitute_box_iter,
    !substitute_dia_iter.
Qed.

Lemma schema_Geach_proves :
  forall g (p : formula nat), normal_proves (schema_Geach g) (Geach g p).
Proof. intros g p. apply Np_extra. now exists p. Qed.

(** Elementary list witnesses used by the finite seed argument. *)
Lemma list_exists_of_in :
  forall (A : Type) (P : A -> Prop) (xs : list A) x,
    In x xs -> P x -> Exists P xs.
Proof.
  intros A P xs x Hx HP. induction xs as [|y ys IH]; simpl in Hx.
  - contradiction.
  - destruct Hx as [-> | Hx].
    + now constructor.
    + apply Exists_cons_tl. now apply IH.
Qed.

Lemma list_exists_witness :
  forall (A : Type) (P : A -> Prop) (xs : list A),
    Exists P xs -> exists x, In x xs /\ P x.
Proof.
  intros A P xs H. induction H.
  - exists x. split; [now left | exact H].
  - destruct IHExists as [y [Hy HPy]].
    exists y. split; [now right | exact HPy].
Qed.

(** The two propositional projections needed to compress a finite
    inconsistency into one implication. *)
Definition normal_proves_classical (Ax : modal_axiom_schema) :
    classical_logic (@normal_proves Ax nat).
Proof.
  constructor.
  - intros p Htaut. apply K_proves_normal, K_complete.
    now apply classical_tautology_valid.
  - intros p q. apply Np_mp.
Defined.

Lemma normal_proves_list_conj2_elim :
  forall Ax (Gamma : list (formula nat)) p,
    In p Gamma ->
    normal_proves Ax (Imp (logic_list_conj2 Gamma) p).
Proof.
  intros Ax Gamma p Hp.
  apply (logic_classical_tautology (normal_proves_classical Ax)).
  intro rho. change
    (classical_eval rho (logic_list_conj2 Gamma) -> classical_eval rho p).
  rewrite classical_eval_list_conj2, Forall_forall.
  intro Hall. now apply Hall.
Qed.

Lemma normal_proves_neg_list_disj2_elim :
  forall Ax (Gamma : list (formula nat)) p,
    In p Gamma ->
    normal_proves Ax (Imp (Neg (logic_list_disj2 Gamma)) (Neg p)).
Proof.
  intros Ax Gamma p Hp.
  apply (logic_classical_tautology (normal_proves_classical Ax)).
  intro rho. unfold Neg; simpl.
  intros Hnone Hsat. apply Hnone.
  apply (proj2 (classical_eval_list_disj2 rho Gamma)).
  now apply (list_exists_of_in (P := classical_eval rho) Hp).
Qed.

(** A source formula is either forced through the first branch or forbidden
    through the second. *)
Definition normal_geach_seed Ax (g : geach_tuple)
    (Y Z : normal_maximal_consistent_theory Ax) : theory nat :=
  fun p =>
    normal_mct_mem Y (box_iter (geach_m g) p) \/
    exists q,
      p = Neg q /\
      normal_mct_mem Z (Neg (dia_iter (geach_n g) q)).

Lemma normal_geach_seed_finite_split :
  forall Ax g (Y Z : normal_maximal_consistent_theory Ax) Delta,
    (forall p, In p Delta -> normal_geach_seed g Y Z p) ->
    exists Gamma Theta,
      (forall p, In p Gamma ->
        normal_mct_mem Y (box_iter (geach_m g) p)) /\
      (forall p, In p Theta ->
        normal_mct_mem Z (Neg (dia_iter (geach_n g) p))) /\
      list_subset Delta (Gamma ++ map Neg Theta).
Proof.
  intros Ax g Y Z Delta. induction Delta as [|p Delta IH]; intro Hall.
  - exists [], []. repeat split; intros q Hq; inversion Hq.
  - assert (Hp := Hall p (or_introl eq_refl)).
    assert (Hrest : forall q, In q Delta -> normal_geach_seed g Y Z q).
    { intros q Hq. apply Hall. now right. }
    destruct (IH Hrest) as [Gamma [Theta [HGamma [HTheta Hcover]]]].
    destruct Hp as [Hp | [q [-> Hq]]].
    + exists (p :: Gamma), Theta. repeat split.
      * intros r [-> | Hr]; [exact Hp | now apply HGamma].
      * exact HTheta.
      * intros r [-> | Hr].
        -- apply in_or_app. left. now left.
        -- specialize (Hcover r Hr). apply in_app_or in Hcover.
           destruct Hcover as [Hcover | Hcover].
           ++ apply in_or_app. left. now right.
           ++ apply in_or_app. now right.
    + exists Gamma, (q :: Theta). repeat split.
      * exact HGamma.
      * intros r [-> | Hr]; [exact Hq | now apply HTheta].
      * intros r [Hr | Hr].
        -- subst r. apply in_or_app. right. simpl. now left.
        -- specialize (Hcover r Hr). apply in_app_or in Hcover.
           destruct Hcover as [Hcover | Hcover].
           ++ apply in_or_app. now left.
           ++ apply in_or_app. right. simpl. now right.
Qed.

(** Accessibility supplies the corresponding iterated diamond membership in
    the source maximal theory. *)
Lemma normal_canonical_dia_iter_mem_of_rel_iter :
  forall Ax n (M N : normal_maximal_consistent_theory Ax) p,
    rel_iter (@normal_canonical_relation Ax) n M N ->
    normal_mct_mem N p -> normal_mct_mem M (dia_iter n p).
Proof.
  intros Ax n M N p HMN HNp.
  apply (proj2 (@normal_canonical_truth_lemma Ax (dia_iter n p) M)).
  apply satisfies_dia_iter_intro. exists N. split; [exact HMN |].
  now apply (proj1 (@normal_canonical_truth_lemma Ax p N)).
Qed.

(** The box/diamond duality needed for the negative half of the seed is
    proved semantically at the canonical valuation, avoiding any extra
    substitution-closure premise on the ambient schema. *)
Lemma normal_mct_box_iter_to_neg_dia_iter_neg :
  forall Ax n (M : normal_maximal_consistent_theory Ax) p,
    normal_mct_mem M (box_iter n p) ->
    normal_mct_mem M (Neg (dia_iter n (Neg p))).
Proof.
  intros Ax n M p Hbox.
  apply (proj2 (@normal_canonical_truth_lemma Ax
    (Neg (dia_iter n (Neg p))) M)).
  unfold Neg; simpl. intro Hdia.
  destruct (satisfies_dia_iter_elim Hdia) as [N [HMN Hneg]].
  pose proof
    (proj1 (@normal_canonical_truth_lemma Ax (box_iter n p) M) Hbox)
    as Hboxsat.
  pose proof (proj1 (@satisfies_box_iter nat
    (normal_canonical_frame Ax) (@normal_canonical_valuation Ax)
    n M p) Hboxsat N HMN) as Hp.
  exact (Hneg Hp).
Qed.

Lemma normal_geach_seed_consistent :
  forall Ax g (X Y Z : normal_maximal_consistent_theory Ax),
    (forall p : formula nat, normal_proves Ax (Geach g p)) ->
    rel_iter (@normal_canonical_relation Ax) (geach_i g) X Y ->
    rel_iter (@normal_canonical_relation Ax) (geach_j g) X Z ->
    normal_theory_consistent Ax (normal_geach_seed g Y Z).
Proof.
  intros Ax g X Y Z HGeach HXY HXZ Hbottom.
  destruct (normal_derives_finite_support Hbottom)
    as [Delta [HDelta HbottomDelta]].
  destruct (normal_geach_seed_finite_split HDelta)
    as [Gamma [Theta [HGamma [HTheta Hcover]]]].
  set (gamma := logic_list_conj2 Gamma).
  set (delta := logic_list_disj2 Theta).
  assert (Hbottom' : normal_derives Ax
      (theory_insert (theory_insert empty_theory gamma) (Neg delta))
      Bottom).
  {
    eapply normal_derives_context_cut; [|exact HbottomDelta].
    intros p Hp. specialize (Hcover p Hp).
    apply in_app_or in Hcover. destruct Hcover as [HpG | HpT].
    - eapply ND_mp.
      + apply ND_theorem. unfold gamma.
        exact (@normal_proves_list_conj2_elim Ax Gamma p HpG).
      + apply ND_assumption. right. now left.
    - apply in_map_iff in HpT.
      destruct HpT as [q [Hq HpT]]. subst p.
      eapply ND_mp.
      + apply ND_theorem. unfold delta.
        exact (@normal_proves_neg_list_disj2_elim Ax Theta q HpT).
      + apply ND_assumption. now left.
  }
  assert (Hnotnot : normal_derives Ax
      (theory_insert empty_theory gamma) (Neg (Neg delta))).
  { exact (normal_derives_deduction Hbottom'). }
  assert (Hdelta : normal_derives Ax
      (theory_insert empty_theory gamma) delta).
  { exact (normal_derives_dne Hnotnot). }
  assert (Himp_der : normal_derives Ax empty_theory (Imp gamma delta)).
  { exact (normal_derives_deduction Hdelta). }
  pose proof (proj1 (normal_derives_empty_iff Ax (Imp gamma delta))
    Himp_der) as Himp.

  assert (Hboxgamma :
    normal_mct_mem Y (box_iter (geach_m g) gamma)).
  {
    apply (proj2 (@normal_canonical_truth_lemma Ax
      (box_iter (geach_m g) gamma) Y)).
    apply (proj2 (@satisfies_box_iter nat
      (normal_canonical_frame Ax) (@normal_canonical_valuation Ax)
      (geach_m g) Y gamma)).
    intros U HYU.
    apply (proj1 (@classical_eval_satisfies nat
      (normal_canonical_frame Ax) (@normal_canonical_valuation Ax)
      U gamma)).
    unfold gamma. apply (proj2 (classical_eval_list_conj2 _ Gamma)).
    rewrite Forall_forall. intros q Hq.
    apply (proj2 (@classical_eval_satisfies nat
      (normal_canonical_frame Ax) (@normal_canonical_valuation Ax) U q)).
    pose proof (proj1 (@normal_canonical_truth_lemma Ax
      (box_iter (geach_m g) q) Y) (HGamma q Hq)) as Hqbox.
    exact (proj1 (@satisfies_box_iter nat
      (normal_canonical_frame Ax) (@normal_canonical_valuation Ax)
      (geach_m g) Y q) Hqbox U HYU).
  }
  assert (Hboxdelta :
    normal_mct_mem Y (box_iter (geach_m g) delta)).
  {
    apply (proj2 (@normal_canonical_truth_lemma Ax
      (box_iter (geach_m g) delta) Y)).
    apply (proj2 (@satisfies_box_iter nat
      (normal_canonical_frame Ax) (@normal_canonical_valuation Ax)
      (geach_m g) Y delta)).
    intros U HYU.
    pose proof (proj1 (@normal_canonical_truth_lemma Ax
      (box_iter (geach_m g) gamma) Y) Hboxgamma) as HgammaBoxSat.
    pose proof (proj1 (@satisfies_box_iter nat
      (normal_canonical_frame Ax) (@normal_canonical_valuation Ax)
      (geach_m g) Y gamma) HgammaBoxSat U HYU) as HgammaSat.
    assert (HimpU : normal_mct_mem U (Imp gamma delta)).
    { apply normal_mct_derivable_mem. apply ND_theorem. exact Himp. }
    pose proof (proj1 (@normal_canonical_truth_lemma Ax
      (Imp gamma delta) U) HimpU) as HimpSat.
    exact (HimpSat HgammaSat).
  }
  assert (Hantecedent : normal_mct_mem X
      (dia_iter (geach_i g) (box_iter (geach_m g) delta))).
  { exact (normal_canonical_dia_iter_mem_of_rel_iter HXY Hboxdelta). }
  assert (Hconclusion : normal_mct_mem X
      (box_iter (geach_j g) (dia_iter (geach_n g) delta))).
  {
    apply normal_mct_derivable_mem. eapply ND_mp.
    - apply ND_theorem. exact (HGeach delta).
    - apply ND_assumption. exact Hantecedent.
  }
  pose proof (proj1 (@normal_canonical_rel_iter_iff_box_iter
    Ax (geach_j g) X Z) HXZ _ Hconclusion) as HdiaZ.
  pose proof (proj1 (@normal_canonical_truth_lemma Ax
    (dia_iter (geach_n g) delta) Z) HdiaZ) as HdiaZsat.
  destruct (satisfies_dia_iter_elim HdiaZsat) as [U [HZU HdeltaU]].
  pose proof (proj2 (@classical_eval_satisfies nat
    (normal_canonical_frame Ax) (@normal_canonical_valuation Ax)
    U delta) HdeltaU) as HevalDelta.
  unfold delta in HevalDelta.
  apply (proj1 (classical_eval_list_disj2 _ Theta)) in HevalDelta.
  destruct (list_exists_witness HevalDelta) as [q [Hq Hqeval]].
  pose proof (HTheta q Hq) as HnegDia.
  pose proof (proj1 (@normal_canonical_truth_lemma Ax
    (Neg (dia_iter (geach_n g) q)) Z) HnegDia) as HnegDiaSat.
  unfold Neg in HnegDiaSat; simpl in HnegDiaSat.
  apply HnegDiaSat. apply satisfies_dia_iter_intro.
  exists U. split; [exact HZU |].
  now apply (proj1 (@classical_eval_satisfies nat
    (normal_canonical_frame Ax) (@normal_canonical_valuation Ax) U q)).
Qed.

(** Generic canonicality.  Unlike the source typeclass instance, the exact
    theoremhood dependency is explicit and no global consistency premise is
    required: the presence of the two input canonical worlds supplies all
    consistency data needed by the construction. *)
Theorem normal_canonical_geach_convergent :
  forall Ax g,
    (forall p : formula nat, normal_proves Ax (Geach g p)) ->
    geach_convergent (normal_canonical_frame Ax) g.
Proof.
  intros Ax g HGeach X Y Z HXY HXZ.
  destruct (normal_lindenbaum_extension
    (normal_geach_seed_consistent HGeach HXY HXZ)) as [U Hinclude].
  exists U. split.
  - apply (proj2 (@normal_canonical_rel_iter_iff_box_iter
      Ax (geach_m g) Y U)).
    intros p Hp. apply Hinclude. now left.
  - apply (proj2 (@normal_canonical_rel_iter_iff_box_iter
      Ax (geach_n g) Z U)).
    intros p Hp. apply normal_mct_derivable_mem, normal_derives_dne.
    apply ND_assumption. apply Hinclude. right.
    exists (Neg p). split; [reflexivity |].
    now apply normal_mct_box_iter_to_neg_dia_iter_neg.
Qed.

Corollary schema_Geach_canonical_frame :
  forall g,
    geach_convergent (normal_canonical_frame (schema_Geach g)) g.
Proof.
  intros g. apply normal_canonical_geach_convergent.
  intro p. exact (@schema_Geach_proves g p).
Qed.
