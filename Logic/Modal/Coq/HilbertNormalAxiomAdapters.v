(**
  Raw-axiom capability adapters for the normal Hilbert calculus.

  This file independently ports the complete 25-declaration generic adapter
  section of the pinned Foundation module
  [Modal/Hilbert/Normal/Basic.lean], from the [HasK] instance through
  [HasGeach].  Each theorem instantiates the witness formula retained by the
  corresponding [raw_axioms_has_*] record.  A decidable equality on atoms is
  explicit wherever that instantiation must distinguish one or two witness
  atoms.

  Foundation's [Logic.IsNormal] is structural: it packages classical
  propositional structure, modal K, diamond duality, substitution, and
  necessitation.  Its classical structure is constructively generated by the
  Lukasiewicz basis, and its definitional diamond duality is derived by the
  surrounding typeclass hierarchy.  The corresponding proof is stored
  explicitly below in [structural_normal_entailment].  This is deliberately
  not this repository's stronger extensional [normal_logic], which assumes
  every semantically classical tautology as a primitive interface field.
*)

From FoundationModal Require Import
  Syntax Axioms LogicInfrastructure EntailmentExtensions
  EntailmentNamedExtensions HilbertAxiom HilbertWithRE HilbertNormal.

