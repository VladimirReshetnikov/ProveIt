  - exact (raw_Mk_mem Hraw).
Qed.

Lemma normal_hilbert_has_H :
  forall (AtomType : Type) (Ax : raw_modal_axiom AtomType),
    atom_decidable_equality AtomType ->
    raw_axioms_has_H1 Ax ->
    has_H (@normal_hilbert_proves AtomType Ax).
Proof.
  intros AtomType Ax eq_dec Hraw; constructor; intro p.
  eapply (@normal_hilbert_instantiate_unary AtomType Ax eq_dec
    (@H AtomType) (raw_H1_p Hraw));
    [reflexivity | exact (raw_H1_mem Hraw)].
Qed.

Lemma normal_hilbert_has_Geach :
  forall (AtomType : Type) (Ax : raw_modal_axiom AtomType) g,
    atom_decidable_equality AtomType ->
    raw_axioms_has_Geach g Ax ->
    has_Geach g (@normal_hilbert_proves AtomType Ax).
Proof.
  intros AtomType Ax g eq_dec Hraw; constructor; intro p.
  eapply (@normal_hilbert_instantiate_unary AtomType Ax eq_dec
    (@Geach AtomType g) (raw_Geach_p Hraw)).
  - intros sigma x. unfold Geach; simpl.
    now rewrite !substitute_dia_iter, !substitute_box_iter,
      !substitute_dia_iter.
  - exact (raw_Geach_mem Hraw).
Qed.
