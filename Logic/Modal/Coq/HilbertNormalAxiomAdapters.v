(** The weakest local structural counterpart of Foundation's
    [Logic.IsNormal].  The source's [Cl] superclass is represented by its
    constructive Lukasiewicz basis rather than by this repository's stronger
    extensional tautology closure.  Diamond duality remains explicit, as it
    is in the source interface, even though the proof is derivable here from
    the Lukasiewicz basis and the definitional box encoding of diamond. *)
Record structural_normal_entailment {AtomType}
    (L0 : modal_logic_set AtomType) : Prop := {
  structural_normal_lukasiewicz : lukasiewicz_entailment L0;
  structural_normal_K : has_K L0;
  structural_normal_dia_duality : has_DiaDuality L0;
  structural_normal_substitution : logic_substitution_closed L0;
  structural_normal_necessitation : necessitation L0
}.

(** * Constructive propositional support for definitional diamond duality *)

Lemma normal_hilbert_identity :
  forall (AtomType : Type) (Ax : raw_modal_axiom AtomType)
         (p : formula AtomType),
    normal_hilbert_proves Ax (Imp p p).
Proof.
  intros AtomType Ax p.
  eapply NH_mp.
  - eapply NH_mp.
    + exact (NH_imply_S p (Imp p p) p).
    + exact (NH_imply_K p (Imp p p)).
  - exact (NH_imply_K p p).
Qed.

Lemma normal_hilbert_imply_intro :
  forall (AtomType : Type) (Ax : raw_modal_axiom AtomType)
         (p q : formula AtomType),
    normal_hilbert_proves Ax q ->
    normal_hilbert_proves Ax (Imp p q).
Proof.
  intros AtomType Ax p q Hq.
  eapply NH_mp; [exact (NH_imply_K q p) | exact Hq].
Qed.

Lemma normal_hilbert_under_mp :
  forall (AtomType : Type) (Ax : raw_modal_axiom AtomType)
         (a p q : formula AtomType),
    normal_hilbert_proves Ax (Imp a (Imp p q)) ->
    normal_hilbert_proves Ax (Imp a p) ->
    normal_hilbert_proves Ax (Imp a q).
Proof.
  intros AtomType Ax a p q Hpq Hp.
  eapply NH_mp.
  - eapply NH_mp; [exact (NH_imply_S a p q) | exact Hpq].
  - exact Hp.
Qed.

Lemma normal_hilbert_and_intro :
  forall (AtomType : Type) (Ax : raw_modal_axiom AtomType)
         (p q : formula AtomType),
    normal_hilbert_proves Ax p ->
    normal_hilbert_proves Ax q ->
    normal_hilbert_proves Ax (And p q).
Proof.
  intros AtomType Ax p q Hp Hq.
  unfold And, Neg.
  set (a := Imp p (Imp q Bottom)).
  pose proof
    (@normal_hilbert_imply_intro AtomType Ax a q Hq) as Haq.
  pose proof
    (@normal_hilbert_imply_intro AtomType Ax a p Hp) as Hap.
  pose proof (@normal_hilbert_identity AtomType Ax a) as Haa.
  change (normal_hilbert_proves Ax (Imp a (Imp p (Imp q Bottom)))) in Haa.
  pose proof
    (@normal_hilbert_under_mp AtomType Ax a p (Imp q Bottom) Haa Hap)
    as Hanq.
  exact (@normal_hilbert_under_mp AtomType Ax a q Bottom Hanq Haq).
Qed.

Lemma normal_hilbert_iff_refl :
  forall (AtomType : Type) (Ax : raw_modal_axiom AtomType)
         (p : formula AtomType),
    normal_hilbert_proves Ax (Iff p p).
Proof.
  intros AtomType Ax p; unfold Iff.
  apply normal_hilbert_and_intro; apply normal_hilbert_identity.
Qed.

Lemma normal_hilbert_has_DiaDuality :
  forall (AtomType : Type) (Ax : raw_modal_axiom AtomType),
    has_DiaDuality (@normal_hilbert_proves AtomType Ax).
Proof.
  intros AtomType Ax; constructor; intro p.
  unfold DiaDuality, Dia.
  apply normal_hilbert_iff_refl.
Qed.

(** * Generic raw-template instantiation *)

Lemma normal_hilbert_instantiate_unary :
  forall (AtomType : Type) (Ax : raw_modal_axiom AtomType)
         (eq_dec : atom_decidable_equality AtomType)
         (Schema : formula AtomType -> formula AtomType) a,
    (forall sigma x,
      substitute sigma (Schema x) = Schema (substitute sigma x)) ->
    Ax (Schema (Atom a)) ->
    forall p, normal_hilbert_proves Ax (Schema p).
Proof.
  intros AtomType Ax eq_dec Schema a Hschema Hmem p.
  pose proof
    (@NH_axm AtomType Ax (Schema (Atom a))
      (with_re_single_substitution eq_dec a p) Hmem) as Hproof.
  rewrite Hschema in Hproof; simpl in Hproof.
  rewrite with_re_single_substitution_at in Hproof.
  exact Hproof.
Qed.

Lemma normal_hilbert_instantiate_binary :
  forall (AtomType : Type) (Ax : raw_modal_axiom AtomType)
         (eq_dec : atom_decidable_equality AtomType)
         (Schema : formula AtomType -> formula AtomType -> formula AtomType)
         a b,
    a <> b ->
    (forall sigma x y,
      substitute sigma (Schema x y) =
      Schema (substitute sigma x) (substitute sigma y)) ->
    Ax (Schema (Atom a) (Atom b)) ->
    forall p q, normal_hilbert_proves Ax (Schema p q).
Proof.
  intros AtomType Ax eq_dec Schema a b Hab Hschema Hmem p q.
  pose proof
    (@NH_axm AtomType Ax (Schema (Atom a) (Atom b))
      (with_re_double_substitution eq_dec a b p q) Hmem) as Hproof.
  rewrite Hschema in Hproof; simpl in Hproof.
  rewrite with_re_double_substitution_left in Hproof.
  rewrite with_re_double_substitution_right in Hproof by exact Hab.
  exact Hproof.
Qed.

(** * The 25 declarations from Normal/Basic.lean *)

Lemma normal_hilbert_has_K :
  forall (AtomType : Type) (Ax : raw_modal_axiom AtomType),
    atom_decidable_equality AtomType ->
    raw_axioms_has_K Ax ->
    has_K (@normal_hilbert_proves AtomType Ax).
Proof.
  intros AtomType Ax eq_dec Hraw; constructor; intros p q.
  eapply (@normal_hilbert_instantiate_binary AtomType Ax eq_dec
    (@K AtomType) (raw_K_p Hraw) (raw_K_q Hraw)).
  - exact (raw_K_ne Hraw).
  - reflexivity.
  - exact (raw_K_mem Hraw).
Qed.

Lemma normal_hilbert_is_normal :
  forall (AtomType : Type) (Ax : raw_modal_axiom AtomType),
    atom_decidable_equality AtomType ->
    raw_axioms_has_K Ax ->
    structural_normal_entailment (@normal_hilbert_proves AtomType Ax).
Proof.
  intros AtomType Ax eq_dec Hraw; constructor.
  - apply normal_hilbert_lukasiewicz.
  - now apply normal_hilbert_has_K.
  - apply normal_hilbert_has_DiaDuality.
  - exact (@normal_hilbert_proves_substitute AtomType Ax).
  - apply normal_hilbert_necessitation.
Qed.

