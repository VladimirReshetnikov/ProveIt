(**
  The quasinormal modal logic S.

  This module ports the active theorem surface of Foundation's pinned
  [Modal/Logic/S/Basic.lean].  The logic S is the least quasinormal sum of
  GL and the single formula [T (Atom 0)].  Closure under substitution turns
  that one generator into every instance [T p], but no necessitation rule is
  added to the sum.

  Foundation also exposes a recursor in which substitution is invisible:
  an S theorem is generated by GL theorems, arbitrary T instances, and modus
  ponens.  The private auxiliary judgement below proves the same normal-form
  principle without changing the definition of [S_proves].
*)

From FoundationModal Require Import
  Syntax Axioms NormalHilbert LogicInfrastructure GLGrzDerivations.

Set Implicit Arguments.
Unset Strict Implicit.
Set Universe Polymorphism.

(** The singleton right summand used in Foundation's definition of S. *)
Definition S_atomic_T_axiom : modal_logic_set nat :=
  fun p => p = T (Atom 0).

(** Foundation [Modal.S]. *)
Definition S_proves : modal_logic_set nat :=
  logic_sum_quasi_normal (@GL_proves nat) S_atomic_T_axiom.

(** Foundation's [Modal.S.IsQuasiNormal] instance. *)
Theorem S_quasi_normal : quasi_normal_logic S_proves.
Proof.
  unfold S_proves.
  apply logic_sum_quasi_normal_quasi_left.
  exact (normal_quasi GL_normal_logic).
Qed.

(** The canonical inclusion [GL <= S]. *)
Theorem GL_weaker_than_S : logic_subset (@GL_proves nat) S_proves.
Proof.
  intros p Hp. now apply LSQ_mem_left.
Qed.

(** The distinguished generator itself belongs to S. *)
Theorem S_proves_atomic_T : S_proves (T (Atom 0)).
Proof.
  apply LSQ_mem_right. reflexivity.
Qed.

(** Foundation's [Entailment.HasAxiomT Modal.S] instance.  Every T instance
    is one substitution instance of the distinguished atomic generator. *)
Theorem S_proves_T : forall p : formula nat, S_proves (T p).
Proof.
  intro p.
  pose proof
    (LSQ_substitute (fun _ : nat => p) S_proves_atomic_T) as Hsub.
  exact Hsub.
Qed.

(** A named form of S's structural substitution rule. *)
Theorem S_proves_substitute :
  forall (sigma : nat -> formula nat) p,
    S_proves p -> S_proves (substitute sigma p).
Proof.
  intros sigma p Hp. now apply LSQ_substitute.
Qed.

(** GL does not prove the atomic T instance.  The short syntactic argument
    reuses the existing consistency/unprovability theorem for GL.  If atomic
    T were provable, substitution would give [box bottom -> bottom]; boxing
    it and applying Loeb's axiom would give [box bottom], hence bottom. *)
Theorem GL_unprovable_atomic_T : ~ GL_proves (T (Atom 0)).
Proof.
  intro HT.
  pose proof
    (@normal_proves_substitute schema_L schema_L_substitution_closed
      nat nat (fun _ => Bottom) (T (Atom 0)) HT) as HT_bottom.
  simpl in HT_bottom.
  apply (@GL_is_consistent nat).
  eapply Np_mp.
  - exact HT_bottom.
  - eapply Np_mp.
    + exact (GL_proves_L Bottom).
    + exact (Np_nec HT_bottom).
Qed.

(** Foundation's strict inclusion [GL < S]. *)
Theorem GL_strictly_weaker_S :
  logic_strictly_weaker (@GL_proves nat) S_proves.
Proof.
  split.
  - exact GL_weaker_than_S.
  - exists (T (Atom 0)); split.
    + exact S_proves_atomic_T.
    + exact GL_unprovable_atomic_T.
Qed.

(** * A substitution-free presentation and recursor *)

Module SDerivationInternal.

Inductive derives : formula nat -> Prop :=
| derives_GL : forall p, GL_proves p -> derives p
| derives_T : forall p, derives (T p)
| derives_mp : forall p q,
    derives (Imp p q) -> derives p -> derives q.

Lemma derives_substitute :
  forall p, derives p ->
  forall sigma : nat -> formula nat, derives (substitute sigma p).
Proof.
  intros p Hp; induction Hp; intro sigma; simpl.
  - apply derives_GL.
    eapply (@normal_proves_substitute schema_L
      schema_L_substitution_closed nat nat sigma p).
    exact H.
  - apply derives_T.
  - eapply derives_mp; eauto.
Qed.

Lemma derives_to_S : forall p, derives p -> S_proves p.
Proof.
  intros p Hp; induction Hp.
  - now apply GL_weaker_than_S.
  - apply S_proves_T.
  - eapply LSQ_mp; eassumption.
Qed.

Lemma S_to_derives : forall p, S_proves p -> derives p.
Proof.
  intros p Hp; induction Hp.
  - now apply derives_GL.
  - unfold S_atomic_T_axiom in H. subst p. apply derives_T.
  - eapply derives_mp; eassumption.
  - now apply derives_substitute.
Qed.

End SDerivationInternal.

(** The source-equivalent characterization used to justify the compact
    eliminator below. *)
Theorem S_derivation_iff :
  forall p, S_proves p <-> SDerivationInternal.derives p.
Proof.
  intro p; split.
  - apply SDerivationInternal.S_to_derives.
  - apply SDerivationInternal.derives_to_S.
Qed.

(** Foundation [Modal.S.rec'].  For proposition-valued motives, every S
    proof can be consumed using only the GL, T, and modus-ponens cases; the
    substitution constructor has been normalized into the first two cases. *)
Theorem S_proves_induction :
  forall (P : formula nat -> Prop),
    (forall p, GL_proves p -> P p) ->
    (forall p, P (T p)) ->
    (forall p q, P (Imp p q) -> P p -> P q) ->
    forall p, S_proves p -> P p.
Proof.
  intros P HGL HT Hmp p Hp.
  apply SDerivationInternal.S_to_derives in Hp.
  induction Hp.
  - now apply HGL.
  - apply HT.
  - eapply Hmp; eassumption.
Qed.

(** Familiar aliases matching the source vocabulary. *)
Definition S_rec := S_proves_induction.
Definition S_axiomT := S_proves_T.
