(** * Generic and named soundness *)

Definition schema_valid_on_frame (Ax : modal_axiom_schema) (F : frame) : Prop :=
  forall (AtomType : Type) (p : formula AtomType), Ax AtomType p -> valid F p.

Theorem normal_proves_sound_on_frame :
  forall Ax (AtomType : Type) (F : frame) (p : formula AtomType),
    schema_valid_on_frame Ax F ->
    normal_proves Ax p -> valid F p.
Proof.
  intros Ax AtomType F p HAx Hp; induction Hp.
  - apply valid_Hilbert_imply_K.
  - apply valid_Hilbert_imply_S.
  - apply valid_Hilbert_elim_contra.
  - apply valid_K.
  - now apply HAx.
  - eapply valid_mp; eauto.
  - now apply valid_nec.
Qed.

Lemma schema_union_valid_on_frame :
  forall Ax Ay F,
    schema_valid_on_frame Ax F ->
    schema_valid_on_frame Ay F ->
    schema_valid_on_frame (schema_union Ax Ay) F.
Proof.
  intros Ax Ay F HAx HAy A p [Hp | Hp].
  - now apply HAx.
  - now apply HAy.
Qed.

Lemma schema_T_valid_on_reflexive :
  forall F, frame_reflexive F -> schema_valid_on_frame schema_T F.
Proof. intros F HF A p [q ->]. now apply valid_T_of_reflexive. Qed.

Lemma schema_D_valid_on_serial :
  forall F, frame_serial F -> schema_valid_on_frame schema_D F.
Proof. intros F HF A p [q ->]. now apply valid_D_of_serial. Qed.

Lemma schema_B_valid_on_symmetric :
  forall F, frame_symmetric F -> schema_valid_on_frame schema_B F.
Proof. intros F HF A p [q ->]. now apply valid_B_of_symmetric. Qed.

Lemma schema_Four_valid_on_transitive :
  forall F, frame_transitive F -> schema_valid_on_frame schema_Four F.
Proof. intros F HF A p [q ->]. now apply valid_Four_of_transitive. Qed.

Lemma schema_Five_valid_on_right_euclidean :
  forall F,
    frame_right_euclidean F -> schema_valid_on_frame schema_Five F.
Proof. intros F HF A p [q ->]. now apply valid_Five_of_right_euclidean. Qed.

Lemma schema_L_valid_on_GL_frame :
  forall F,
    frame_transitive F -> frame_converse_well_founded F ->
    schema_valid_on_frame schema_L F.
Proof. intros F HT HC A p [q ->]. now apply valid_Loeb_of_transitive_cwf. Qed.

Lemma schema_Grz_valid_on_Grz_frame :
  forall F,
    frame_reflexive F -> frame_transitive F ->
    frame_weak_converse_well_founded F ->
    schema_valid_on_frame schema_Grz F.
Proof.
  intros F HR HT HW A p [q ->].
  now apply valid_Grz_of_reflexive_transitive_weak_cwf.
Qed.

Theorem KT_proves_sound_on_reflexive_frame :
  forall (AtomType : Type) (F : frame) (p : formula AtomType),
    frame_reflexive F -> KT_proves p -> valid F p.
Proof.
