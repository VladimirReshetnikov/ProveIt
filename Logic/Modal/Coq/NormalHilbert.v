(** * Concrete consistency witnesses *)

Definition reflexive_singleton_frame : frame :=
  {| World := unit;
     Rel := fun _ _ => True |}.

Lemma reflexive_singleton_reflexive :
  frame_reflexive reflexive_singleton_frame.
Proof. intros []; constructor. Qed.

Lemma reflexive_singleton_serial :
  frame_serial reflexive_singleton_frame.
Proof. intros []; exists tt; constructor. Qed.

Lemma reflexive_singleton_symmetric :
  frame_symmetric reflexive_singleton_frame.
Proof. intros [] [] _; constructor. Qed.

Lemma reflexive_singleton_transitive :
  frame_transitive reflexive_singleton_frame.
Proof. intros [] [] [] _ _; constructor. Qed.

Lemma reflexive_singleton_right_euclidean :
  frame_right_euclidean reflexive_singleton_frame.
Proof. intros [] [] [] _ _; constructor. Qed.

Lemma reflexive_singleton_weak_cwf :
  frame_weak_converse_well_founded reflexive_singleton_frame.
Proof.
  intros X [x Hx]. exists x; split; [exact Hx |].
  intros y _ _. now destruct x, y.
Qed.

Lemma irreflexive_singleton_transitive :
  frame_transitive irreflexive_singleton_frame.
Proof. intros [] [] [] H; contradiction. Qed.

Lemma irreflexive_singleton_cwf :
  frame_converse_well_founded irreflexive_singleton_frame.
Proof.
  intros X [x Hx]. exists x; split; [exact Hx |].
  intros y _ Hxy. exact Hxy.
Qed.

Theorem normal_consistent_of_sound_inhabited_frame :
  forall Ax (F : frame),
    (exists w : World F, True) ->
    schema_valid_on_frame Ax F ->
    forall AtomType : Type,
      ~ normal_proves Ax (@Bottom AtomType).
Proof.
  intros Ax F [w _] HAx AtomType Hbottom.
  pose proof
    (@normal_proves_sound_on_frame Ax AtomType F Bottom HAx Hbottom)
    as Hvalid.
  exact (Hvalid (fun _ _ => False) w).
Qed.

Theorem KT_is_consistent : forall AtomType, ~ @KT_proves AtomType Bottom.
Proof.
  apply (normal_consistent_of_sound_inhabited_frame
    (Ax := schema_T) (F := reflexive_singleton_frame)).
  - now exists tt.
  - apply schema_T_valid_on_reflexive.
    exact reflexive_singleton_reflexive.
Qed.

