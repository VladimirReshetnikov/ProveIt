(**
  Normal Hilbert systems generated by additional modal axiom schemata.

  Foundation presents named systems such as KT, K4, S4, K5, S5, GL, and
  Grz as extensions of one common normal Hilbert calculus.  This module gives
  that abstraction directly in Coq.  An axiom schema is polymorphic in the
  atom type, so substitution closure can be stated once and inherited by
  every named system below.

  The module establishes the structural metatheory, embeds the concrete
  calculus [K_proves], and proves framewise soundness and consistency for the
  principal named systems.  Canonical completeness for extensions is kept
  separate: unlike soundness, it requires a Lindenbaum construction indexed
  by the chosen schema and proofs that its canonical frame has the desired
  relational properties.
*)

From FoundationModal Require Import
  Syntax Axioms HilbertK Kripke HilbertKSoundness Correspondence Loeb
  CorrespondenceExtensions.

Set Implicit Arguments.
Unset Strict Implicit.
Set Universe Polymorphism.

(** * Generic normal systems *)

Definition modal_axiom_schema : Type :=
  forall AtomType : Type, formula AtomType -> Prop.

Definition empty_schema : modal_axiom_schema :=
  fun _ _ => False.

Definition schema_union (Ax Ay : modal_axiom_schema) : modal_axiom_schema :=
  fun AtomType p => Ax AtomType p \/ Ay AtomType p.

Definition schema_included (Ax Ay : modal_axiom_schema) : Prop :=
  forall AtomType p, Ax AtomType p -> Ay AtomType p.

Definition schema_substitution_closed (Ax : modal_axiom_schema) : Prop :=
  forall (A B : Type) (sigma : A -> formula B) p,
    Ax A p -> Ax B (substitute sigma p).

Inductive normal_proves (Ax : modal_axiom_schema) {AtomType : Type}
    : formula AtomType -> Prop :=
| Np_imply_K : forall p q,
    normal_proves Ax (Hilbert_imply_K p q)
| Np_imply_S : forall p q r,
    normal_proves Ax (Hilbert_imply_S p q r)
| Np_elim_contra : forall p q,
    normal_proves Ax (Hilbert_elim_contra p q)
| Np_modal_K : forall p q,
    normal_proves Ax (K p q)
| Np_extra : forall p,
    Ax AtomType p -> normal_proves Ax p
| Np_mp : forall p q,
    normal_proves Ax (Imp p q) ->
    normal_proves Ax p ->
    normal_proves Ax q
| Np_nec : forall p,
    normal_proves Ax p -> normal_proves Ax (Box p).

Arguments Np_imply_K {Ax AtomType} p q.
Arguments Np_imply_S {Ax AtomType} p q r.
Arguments Np_elim_contra {Ax AtomType} p q.
Arguments Np_modal_K {Ax AtomType} p q.
Arguments Np_extra {Ax AtomType p} _.
Arguments Np_mp {Ax AtomType p q} _ _.
Arguments Np_nec {Ax AtomType p} _.

Lemma normal_proves_weaken :
  forall Ax Ay (Hinc : schema_included Ax Ay)
         (AtomType : Type) (p : formula AtomType),
    normal_proves Ax p -> normal_proves Ay p.
Proof.
  intros Ax Ay Hinc AtomType p Hp; induction Hp.
  - apply Np_imply_K.
  - apply Np_imply_S.
  - apply Np_elim_contra.
  - apply Np_modal_K.
  - apply Np_extra. now apply Hinc.
  - eapply Np_mp; eauto.
  - now apply Np_nec.
Qed.

Lemma normal_proves_substitute :
  forall Ax,
    schema_substitution_closed Ax ->
    forall (A B : Type) (sigma : A -> formula B) p,
      normal_proves Ax p ->
      normal_proves Ax (substitute sigma p).
Proof.
  intros Ax Hclosed A B sigma p Hp; induction Hp; simpl.
  - apply Np_imply_K.
  - apply Np_imply_S.
  - apply Np_elim_contra.
  - apply Np_modal_K.
  - apply Np_extra. now apply Hclosed.
  - eapply Np_mp; eauto.
  - now apply Np_nec.
Qed.

Lemma K_proves_normal :
  forall Ax (AtomType : Type) (p : formula AtomType),
    K_proves p -> normal_proves Ax p.
Proof.
  intros Ax AtomType p Hp; induction Hp.
  - apply Np_imply_K.
  - apply Np_imply_S.
  - apply Np_elim_contra.
  - apply Np_modal_K.
  - eapply Np_mp; eauto.
  - now apply Np_nec.
Qed.

Theorem empty_normal_proves_iff_K :
  forall (AtomType : Type) (p : formula AtomType),
    normal_proves empty_schema p <-> K_proves p.
Proof.
  intros AtomType p; split.
  - intro Hp; induction Hp.
    + apply Kp_imply_K.
    + apply Kp_imply_S.
    + apply Kp_elim_contra.
    + apply Kp_modal_K.
    + contradiction.
    + eapply Kp_mp; eauto.
    + now apply Kp_nec.
  - apply K_proves_normal.
Qed.

Lemma empty_schema_substitution_closed :
  schema_substitution_closed empty_schema.
Proof. intros A B sigma p H; contradiction. Qed.

Lemma schema_union_substitution_closed :
  forall Ax Ay,
    schema_substitution_closed Ax ->
    schema_substitution_closed Ay ->
    schema_substitution_closed (schema_union Ax Ay).
Proof.
  intros Ax Ay HAx HAy A B sigma p [Hp | Hp].
  - left. now apply HAx.
  - right. now apply HAy.
Qed.

(** * Named axiom schemata *)

Definition schema_T : modal_axiom_schema :=
  fun AtomType p => exists q : formula AtomType, p = T q.

Definition schema_D : modal_axiom_schema :=
  fun AtomType p => exists q : formula AtomType, p = D q.

Definition schema_B : modal_axiom_schema :=
  fun AtomType p => exists q : formula AtomType, p = B q.

Definition schema_Four : modal_axiom_schema :=
  fun AtomType p => exists q : formula AtomType, p = Four q.

Definition schema_Five : modal_axiom_schema :=
  fun AtomType p => exists q : formula AtomType, p = Five q.

Definition schema_L : modal_axiom_schema :=
  fun AtomType p => exists q : formula AtomType, p = L q.

Definition schema_Grz : modal_axiom_schema :=
  fun AtomType p => exists q : formula AtomType, p = Grz q.

Lemma schema_T_substitution_closed : schema_substitution_closed schema_T.
Proof. intros A B sigma p [q ->]. exists (substitute sigma q). reflexivity. Qed.

Lemma schema_D_substitution_closed : schema_substitution_closed schema_D.
Proof. intros A B sigma p [q ->]. exists (substitute sigma q). reflexivity. Qed.

Lemma schema_B_substitution_closed : schema_substitution_closed schema_B.
Proof. intros A B sigma p [q ->]. exists (substitute sigma q). reflexivity. Qed.

Lemma schema_Four_substitution_closed :
  schema_substitution_closed schema_Four.
