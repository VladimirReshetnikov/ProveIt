Definition K_normal_proves {AtomType} : formula AtomType -> Prop :=
  @normal_proves empty_schema AtomType.
Definition KT_proves {AtomType} : formula AtomType -> Prop :=
  @normal_proves schema_T AtomType.
Definition KD_proves {AtomType} : formula AtomType -> Prop :=
  @normal_proves schema_D AtomType.
Definition KB_proves {AtomType} : formula AtomType -> Prop :=
  @normal_proves schema_B AtomType.
Definition K4_proves {AtomType} : formula AtomType -> Prop :=
  @normal_proves schema_Four AtomType.
Definition K5_proves {AtomType} : formula AtomType -> Prop :=
  @normal_proves schema_Five AtomType.
Definition S4_schema := schema_union schema_T schema_Four.
Definition S4_proves {AtomType} : formula AtomType -> Prop :=
  @normal_proves S4_schema AtomType.
Definition S5_schema := schema_union schema_T schema_Five.
Definition S5_proves {AtomType} : formula AtomType -> Prop :=
  @normal_proves S5_schema AtomType.
Definition GL_proves {AtomType} : formula AtomType -> Prop :=
  @normal_proves schema_L AtomType.
Definition Grz_proves {AtomType} : formula AtomType -> Prop :=
  @normal_proves schema_Grz AtomType.

Lemma K_weaker_than_normal :
  forall Ax (AtomType : Type) (p : formula AtomType),
    K_normal_proves p -> normal_proves Ax p.
Proof.
  intros Ax AtomType p Hp.
  apply K_proves_normal.
  now apply (proj1 (empty_normal_proves_iff_K p)).
Qed.

Lemma KT_weaker_than_S4 :
  forall (AtomType : Type) (p : formula AtomType),
    KT_proves p -> S4_proves p.
Proof.
  intros AtomType p.
  apply normal_proves_weaken.
  intros A q Hq. now left.
Qed.

