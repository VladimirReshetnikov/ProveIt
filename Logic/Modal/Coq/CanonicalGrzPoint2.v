(**
  Finite completeness and hierarchy results for Grz.2.

  This module ports the checked theorem surface of Foundation's
  [Modal/Kripke/Logic/GrzPoint2.lean].  The completeness proof follows the
  source construction at the semantic level.  A failed Grz.2 formula first
  yields a finite Grz countermodel to the implication from the Point2 axioms
  on its atoms.  We restrict that model to the cone generated by the failure
  world and adjoin one reflexive universal terminal.  Point2 makes all
  maximal worlds agree on the relevant atoms, so the new terminal can be
  valued by their common atomic theory without changing truth below it.

  Lists replace Foundation's finite sets.  Repetition in [formula_atoms]
  is harmless and avoids imposing decidable equality on arbitrary atoms.
*)

