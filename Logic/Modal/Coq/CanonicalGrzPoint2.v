(** * Reflexive terminal worlds *)

(** Foundation calls a world terminal when all of its successors are the
    world itself.  This is deliberately different from [frame_terminal],
    which is the strict/irreflexive notion used elsewhere in this port. *)
Definition frame_reflexive_terminal (F : frame) (t : World F) : Prop :=
  forall y : World F, Rel F t y -> t = y.

Definition frame_reflexive_terminals (F : frame) : World F -> Prop :=
  @frame_reflexive_terminal F.

Definition frame_reflexive_terminals_of
  (F : frame) (x t : World F) : Prop :=
  relation_positive_closure (Rel F) x t /\
  @frame_reflexive_terminal F t.

Arguments frame_reflexive_terminal F t : clear implicits.
Arguments frame_reflexive_terminals F t : clear implicits.
Arguments frame_reflexive_terminals_of F x t : clear implicits.

(** The local frame representation does not build inhabitation into
    [frame], so Foundation's positive-cardinality helper is represented by
    a nonempty explicit cover under an explicit inhabitation premise. *)
Lemma finite_frame_exists_nonempty_cover :
  forall F : frame,
    finite_frame F ->
    (exists w : World F, True) ->
    exists cover : list (World F),
      cover <> [] /\ forall w : World F, In w cover.
Proof.
  intros F [cover Hcover] [w _]. exists cover; split.
  - intro Heq. subst cover. specialize (Hcover w). contradiction.
  - exact Hcover.
Qed.

Lemma frame_exists_reflexive_terminal :
  forall (F : frame) (x : World F),
    frame_mckinsey F ->
    exists t : World F,
      frame_reflexive_terminal F t /\ Rel F x t.
Proof.
  intros F x Hmck. destruct (Hmck x) as [t [Rxt Ht]].
  exists t; split; assumption.
Qed.

Lemma satisfies_box_at_reflexive_terminal :
  forall (AtomType : Type) (F : frame) (V : valuation AtomType F)
         (x : World F) (p : formula AtomType),
    frame_reflexive_terminal F x ->
    satisfies F V x p -> satisfies F V x (Box p).
Proof.
  intros AtomType F V x p Hterminal Hp y Rxy.
  pose proof (Hterminal y Rxy) as Hxy. now subst y.
Qed.

Lemma not_satisfies_dia_at_reflexive_terminal :
  forall (AtomType : Type) (F : frame) (V : valuation AtomType F)
         (x : World F) (p : formula AtomType),
    frame_reflexive_terminal F x ->
    ~ satisfies F V x p -> ~ satisfies F V x (Dia p).
Proof.
  intros AtomType F V x p Hterminal Hnotp Hdia.
  unfold Dia, Neg in Hdia; simpl in Hdia.
  apply Hdia. intros y Rxy Hpy.
  pose proof (Hterminal y Rxy) as Hxy. subst y. contradiction.
Qed.

(** * Schema, calculus, and guarded syntactic reduction *)

Definition GrzPoint2_schema : modal_axiom_schema :=
  schema_union schema_Grz schema_Point2.

Definition GrzPoint2_proves {AtomType} : formula AtomType -> Prop :=
  @normal_proves GrzPoint2_schema AtomType.

Lemma GrzPoint2_schema_substitution_closed :
  schema_substitution_closed GrzPoint2_schema.
Proof.
  apply schema_union_substitution_closed.
  - exact schema_Grz_substitution_closed.
  - exact schema_Point2_substitution_closed.
Qed.

Definition GrzPoint2_normal_logic :
    normal_logic (@GrzPoint2_proves nat) :=
  @normal_proves_logic_is_normal
    GrzPoint2_schema GrzPoint2_schema_substitution_closed.

Definition GrzPoint2_classical_logic :
    classical_logic (@GrzPoint2_proves nat) :=
  quasi_classical (normal_quasi GrzPoint2_normal_logic).

Lemma Grz_weaker_than_GrzPoint2 :
  forall (AtomType : Type) (p : formula AtomType),
    Grz_proves p -> GrzPoint2_proves p.
Proof.
  intros AtomType p Hp. eapply normal_proves_weaken; [| exact Hp].
  intros A q Hq. now left.
Qed.

Lemma GrzPoint2_proves_Grz_axiom :
  forall p : formula nat, GrzPoint2_proves (Grz p).
Proof. intro p. apply Np_extra. left. now exists p. Qed.

Lemma GrzPoint2_proves_Point2 :
  forall p : formula nat, GrzPoint2_proves (Point2 p).
Proof. intro p. apply Np_extra. right. now exists p. Qed.

Lemma atom_subformula_in_formula_atoms :
  forall (AtomType : Type) (p : formula AtomType) (a : AtomType),
    In (Atom a) (subformulas p) -> In a (formula_atoms p).
Proof.
  intros AtomType p; induction p as [b | | q IHq r IHr | q IHq];
    intros a Ha; simpl in *.
  - destruct Ha as [Ha | []]. now inversion Ha; left.
  - destruct Ha as [Ha | []]. discriminate.
  - destruct Ha as [Ha | Ha]; [discriminate |].
    apply in_app_iff in Ha. apply in_app_iff.
    destruct Ha as [Ha | Ha]; [left; now apply IHq | right; now apply IHr].
  - destruct Ha as [Ha | Ha]; [discriminate |]. now apply IHq.
Qed.

Definition grzpoint2_atom_axioms (p : formula nat)
    : list (formula nat) :=
  map (fun a => Point2 (Atom a)) (formula_atoms p).

Definition grzpoint2_atom_guard (p : formula nat) : formula nat :=
  logic_list_conj (grzpoint2_atom_axioms p).

(** This is the finite-conjunction presentation of Foundation's
    [GrzPoint2_of_Grz]. *)
Lemma GrzPoint2_of_Grz :
  forall p : formula nat,
    Grz_proves (Imp (grzpoint2_atom_guard p) p) ->
    GrzPoint2_proves p.
Proof.
  intros p Himp. eapply Np_mp.
  - eapply normal_proves_weaken; [| exact Himp].
    intros A q Hq. now left.
  - unfold grzpoint2_atom_guard, grzpoint2_atom_axioms.
    apply logic_list_conj_intro.
    + exact GrzPoint2_classical_logic.
    + intros q Hq. apply in_map_iff in Hq.
      destruct Hq as [a [<- _]]. apply GrzPoint2_proves_Point2.
Qed.

Lemma not_Grz_of_not_GrzPoint2 :
  forall p : formula nat,
    ~ GrzPoint2_proves p ->
    ~ Grz_proves (Imp (grzpoint2_atom_guard p) p).
Proof.
  intros p Hnot Hgrz. apply Hnot. now apply GrzPoint2_of_Grz.
Qed.

(** * Finite Grz.2 frames, soundness, and consistency *)

Definition GrzPoint2_finite_frame_class (F : frame) : Prop :=
  finite_frame F /\ frame_is_partial_order F /\
  frame_piecewise_strongly_convergent F.

Lemma GrzPoint2_finite_frame_is_S4Point2McK :
  forall F,
    GrzPoint2_finite_frame_class F -> S4Point2McK_frame_class F.
Proof.
  intros F [Hfinite [[HR [HT HA]] HC]]. repeat split.
  - exact HR.
  - exact HT.
  - apply finite_partial_order_mckinsey; [exact Hfinite |].
    now repeat split.
  - exact HC.
Qed.

Theorem GrzPoint2_proves_sound_on_finite_frame :
  forall (AtomType : Type) (F : frame) (p : formula AtomType),
    GrzPoint2_finite_frame_class F ->
    GrzPoint2_proves p -> valid F p.
Proof.
  intros AtomType F p [Hfinite [[HR [HT HA]] HC]] Hp.
  eapply normal_proves_sound_on_frame; [| exact Hp].
  apply schema_union_valid_on_frame.
  - apply schema_Grz_valid_on_Grz_frame.
    + exact HR.
    + exact HT.
    + now apply finite_transitive_antisymmetric_weak_cwf.
  - now apply schema_Point2_valid_on_piecewise_strongly_convergent.
Qed.

Lemma grzpoint2_reflexive_singleton_finite :
  finite_frame reflexive_singleton_frame.
Proof. exists [tt]. intros []; simpl; auto. Qed.

Lemma grzpoint2_reflexive_singleton_antisymmetric :
  frame_antisymmetric reflexive_singleton_frame.
Proof. intros [] [] _ _. reflexivity. Qed.

Lemma grzpoint2_reflexive_singleton_strongly_convergent :
  frame_piecewise_strongly_convergent reflexive_singleton_frame.
Proof. intros [] [] [] _ _. exists tt; split; constructor. Qed.

Lemma grzpoint2_reflexive_singleton_in_finite_class :
  GrzPoint2_finite_frame_class reflexive_singleton_frame.
Proof.
  split; [exact grzpoint2_reflexive_singleton_finite |]. split.
  - split; [exact reflexive_singleton_reflexive |]. split.
    + exact reflexive_singleton_transitive.
    + exact grzpoint2_reflexive_singleton_antisymmetric.
  - exact grzpoint2_reflexive_singleton_strongly_convergent.
Qed.

Theorem GrzPoint2_is_consistent :
  forall AtomType, ~ @GrzPoint2_proves AtomType Bottom.
Proof.
  intros AtomType Hbottom.
  pose proof (GrzPoint2_proves_sound_on_finite_frame
    (F := reflexive_singleton_frame) (p := @Bottom AtomType)
    grzpoint2_reflexive_singleton_in_finite_class Hbottom) as Hvalid.
  exact (Hvalid (fun _ _ => False) tt).
Qed.

(** * Semantic finite conjunctions *)

Lemma satisfies_logic_list_conj :
  forall (AtomType : Type) (F : frame) (V : valuation AtomType F)
         (w : World F) (Gamma : list (formula AtomType)),
    satisfies F V w (logic_list_conj Gamma) <->
    Forall (satisfies F V w) Gamma.
Proof.
  intros AtomType F V w Gamma; induction Gamma as [|p Gamma IH].
  - cbn [logic_list_conj]. split.
    + intros _. exact (Forall_nil (satisfies F V w)).
    + intros _. exact (@satisfies_top AtomType F V w).
  - change
      (satisfies F V w (And p (logic_list_conj Gamma)) <->
       Forall (satisfies F V w) (p :: Gamma)).
    rewrite satisfies_and, IH, Forall_cons_iff. reflexivity.
Qed.

Lemma satisfies_grzpoint2_atom_guard :
  forall (F : frame) (V : valuation nat F) (w : World F)
         (p : formula nat),
    satisfies F V w (grzpoint2_atom_guard p) ->
    forall a, In a (formula_atoms p) ->
      satisfies F V w (Point2 (Atom a)).
Proof.
  intros F V w p Hguard a Ha.
  apply (proj1 (@satisfies_logic_list_conj nat F V w
    (grzpoint2_atom_axioms p))) in Hguard.
  rewrite Forall_forall in Hguard. apply Hguard.
  unfold grzpoint2_atom_axioms. apply in_map_iff.
  exists a. split; [reflexivity | exact Ha].
Qed.

(** * Adjoining one reflexive universal terminal *)

Definition grzpoint2_adjoin_terminal_frame (F : frame) : frame :=
  {| World := (World F + unit)%type;
     Rel := fun x y =>
       match x, y with
       | inl u, inl v => Rel F u v
       | _, inr _ => True
       | inr _, inl _ => False
       end |}.

Definition grzpoint2_adjoin_terminal_valuation
    {AtomType : Type} (F : frame) (V : valuation AtomType F)
    : valuation AtomType (grzpoint2_adjoin_terminal_frame F) :=
  fun a x =>
    match x with
    | inl y => V a y
    | inr _ => forall t : World F,
        frame_reflexive_terminal F t -> V a t
    end.

Arguments grzpoint2_adjoin_terminal_valuation {AtomType} F V.

Lemma grzpoint2_adjoin_terminal_finite :
  forall F,
    finite_frame F -> finite_frame (grzpoint2_adjoin_terminal_frame F).
Proof.
  intros F [cover Hcover].
  exists (map (@inl (World F) unit) cover ++ [inr tt]).
  intros [x | []].
  - apply in_or_app. left. apply in_map. apply Hcover.
  - apply in_or_app. right. now left.
Qed.

Lemma grzpoint2_adjoin_terminal_reflexive :
  forall F,
    frame_reflexive F ->
    frame_reflexive (grzpoint2_adjoin_terminal_frame F).
Proof. intros F HR [x | []]; simpl; auto. Qed.

Lemma grzpoint2_adjoin_terminal_transitive :
  forall F,
    frame_transitive F ->
    frame_transitive (grzpoint2_adjoin_terminal_frame F).
Proof.
  intros F HT [x | []] [y | []] [z | []]; simpl; intros Hxy Hyz;
    try contradiction; auto; eauto.
Qed.

Lemma grzpoint2_adjoin_terminal_antisymmetric :
  forall F,
    frame_antisymmetric F ->
    frame_antisymmetric (grzpoint2_adjoin_terminal_frame F).
Proof.
  intros F HA [x | []] [y | []]; simpl; intros Hxy Hyx;
    try contradiction; try reflexivity.
  f_equal. now apply HA.
Qed.

Lemma grzpoint2_adjoin_terminal_strongly_convergent :
  forall F,
    frame_piecewise_strongly_convergent
      (grzpoint2_adjoin_terminal_frame F).
Proof.
  intros F x y z _ _. exists (@inr (World F) unit tt).
  split.
  - destruct y as [u | []]; exact Logic.I.
  - destruct z as [u | []]; exact Logic.I.
Qed.

Lemma grzpoint2_adjoin_terminal_in_finite_class :
  forall F,
    finite_frame F -> frame_is_partial_order F ->
    GrzPoint2_finite_frame_class
      (grzpoint2_adjoin_terminal_frame F).
Proof.
  intros F Hfinite [HR [HT HA]]. repeat split.
  - now apply grzpoint2_adjoin_terminal_finite.
  - now apply grzpoint2_adjoin_terminal_reflexive.
  - now apply grzpoint2_adjoin_terminal_transitive.
  - now apply grzpoint2_adjoin_terminal_antisymmetric.
  - apply grzpoint2_adjoin_terminal_strongly_convergent.
Qed.

(** * Atomic agreement and truth preservation *)

Lemma grzpoint2_root_atom_agreement :
  forall (F : frame) (V : valuation nat F) (r : World F)
         (target : formula nat),
    frame_reflexive F -> frame_root F r ->
    satisfies F V r (grzpoint2_atom_guard target) ->
    forall a, In a (formula_atoms target) ->
    forall t t' : World F,
      frame_reflexive_terminal F t ->
      frame_reflexive_terminal F t' ->
      V a t -> V a t'.
Proof.
  intros F V r target HR Hroot Hguard a Ha t t' Ht Ht' Hat.
  pose proof (satisfies_grzpoint2_atom_guard Hguard Ha) as Hpoint2.
  assert (Hdiabox : satisfies F V r (Dia (Box (Atom a)))).
  {
    apply satisfies_dia_intro. exists t; split.
    - now apply frame_root_access_of_reflexive with (r := r).
    - now apply satisfies_box_at_reflexive_terminal.
  }
  assert (Hboxdia : satisfies F V r (Box (Dia (Atom a))))
    by exact (Hpoint2 Hdiabox).
  specialize (Hboxdia t'
    (frame_root_access_of_reflexive HR Hroot t')).
  destruct (@satisfies_dia_elim nat F V t' (Atom a) Hboxdia)
    as [u [Rt'u Hau]].
  pose proof (Ht' u Rt'u) as Heq. now subst u.
Qed.

Lemma grzpoint2_terminal_top_truth :
  forall (F : frame) (V : valuation nat F) (r : World F)
         (target : formula nat),
    frame_reflexive F -> frame_root F r ->
    satisfies F V r (grzpoint2_atom_guard target) ->
    forall (q : formula nat), In q (subformulas target) ->
    forall t : World F,
      frame_reflexive_terminal F t ->
      (satisfies F V t q <->
       satisfies (grzpoint2_adjoin_terminal_frame F)
         (grzpoint2_adjoin_terminal_valuation F V) (inr tt) q).
Proof.
  intros F V r target HR Hroot Hguard q.
  induction q as [a | | p IHp q IHq | p IHp];
    intros Hsub t Hterminal; simpl.
  - split.
    + intros Hat t' Ht'.
      exact (@grzpoint2_root_atom_agreement F V r target
        HR Hroot Hguard a
        (atom_subformula_in_formula_atoms Hsub)
        t t' Hterminal Ht' Hat).
    + intro Hall. exact (Hall t Hterminal).
  - tauto.
  - assert (HpSub : In p (subformulas target)).
    {
      eapply subformulas_trans; [exact Hsub |].
      apply subformulas_imp_left, subformulas_self.
    }
    assert (HqSub : In q (subformulas target)).
    {
      eapply subformulas_trans; [exact Hsub |].
      apply subformulas_imp_right, subformulas_self.
    }
    rewrite (IHp HpSub t Hterminal), (IHq HqSub t Hterminal).
    reflexivity.
  - assert (HpSub : In p (subformulas target)).
    {
      eapply subformulas_trans; [exact Hsub |].
      apply subformulas_box, subformulas_self.
    }
    split.
    + intros Hbox [u | []] Rtop.
      * contradiction.
      * apply (proj1 (IHp HpSub t Hterminal)).
        apply Hbox with (u := t). apply HR.
    + intros Hbox u Rtu.
      pose proof (Hterminal u Rtu) as Heq. subst u.
      apply (proj2 (IHp HpSub t Hterminal)).
      apply Hbox with (u := inr tt). constructor.
Qed.

Lemma grzpoint2_adjoin_terminal_truth :
  forall (F : frame) (V : valuation nat F) (r : World F)
         (target : formula nat),
    finite_frame F -> frame_is_partial_order F -> frame_root F r ->
    satisfies F V r (grzpoint2_atom_guard target) ->
    forall (q : formula nat), In q (subformulas target) ->
    forall y : World F,
      (satisfies F V y q <->
       satisfies (grzpoint2_adjoin_terminal_frame F)
         (grzpoint2_adjoin_terminal_valuation F V) (inl y) q).
Proof.
  intros F V r target Hfinite Horder Hroot Hguard.
  destruct Horder as [HR [HT HA]].
  assert (Horder : frame_is_partial_order F) by now repeat split.
  pose proof (finite_partial_order_mckinsey Hfinite Horder) as Hmck.
  intro q; induction q as [a | | p IHp q IHq | p IHp];
    intros Hsub y; simpl.
  - reflexivity.
  - tauto.
  - assert (HpSub : In p (subformulas target)).
    {
      eapply subformulas_trans; [exact Hsub |].
      apply subformulas_imp_left, subformulas_self.
    }
    assert (HqSub : In q (subformulas target)).
    {
      eapply subformulas_trans; [exact Hsub |].
      apply subformulas_imp_right, subformulas_self.
    }
    rewrite (IHp HpSub y), (IHq HqSub y). reflexivity.
  - assert (HpSub : In p (subformulas target)).
    {
      eapply subformulas_trans; [exact Hsub |].
      apply subformulas_box, subformulas_self.
    }
    split.
    + intros Hbox [u | []] Ryu.
      * apply (proj1 (IHp HpSub u)). now apply Hbox with (u := u).
      * destruct (Hmck y) as [t [Ryt Hterminal]].
        apply (proj1 (@grzpoint2_terminal_top_truth
          F V r target HR Hroot Hguard p HpSub t Hterminal)).
        now apply Hbox with (u := t).
    + intros Hbox u Ryu.
      apply (proj2 (IHp HpSub u)).
      apply Hbox with (u := inl u). exact Ryu.
Qed.

(** * Finite completeness *)

Lemma grzpoint2_guarded_mini_countermodel :
  forall p : formula nat,
    ~ GrzPoint2_proves p ->
    exists X : World
      (grz_mini_frame (Imp (grzpoint2_atom_guard p) p)),
      satisfies (grz_mini_frame (Imp (grzpoint2_atom_guard p) p))
        (@grz_mini_valuation (Imp (grzpoint2_atom_guard p) p)) X
        (grzpoint2_atom_guard p) /\
      ~ satisfies (grz_mini_frame (Imp (grzpoint2_atom_guard p) p))
        (@grz_mini_valuation (Imp (grzpoint2_atom_guard p) p)) X p.
Proof.
  intros p Hnot.
  destruct (grz_mini_countermodel (not_Grz_of_not_GrzPoint2 Hnot))
    as [X Hfailure].
  exists X. split.
  - apply NNPP. intro Hnotguard. apply Hfailure. simpl.
    intro Hguard. contradiction.
  - intro Hp. apply Hfailure. simpl. intros _. exact Hp.
Qed.

Theorem GrzPoint2_finite_complete :
  forall p : formula nat,
    normal_valid_on_class GrzPoint2_finite_frame_class p ->
    GrzPoint2_proves p.
Proof.
  intros p Hvalid. apply NNPP. intro Hnot.
  destruct (grzpoint2_guarded_mini_countermodel Hnot)
    as [X [Hguard Hnotp]].
  set (target := Imp (grzpoint2_atom_guard p) p).
  set (F := grz_mini_frame target).
  set (V := @grz_mini_valuation target).
  set (G := point_generated_frame F X).
  set (VG := point_generated_valuation V X).
  set (r := point_generated_root F X).
  assert (HFclass : Grz_finite_frame_class F).
  { unfold F, target. apply grz_mini_frame_in_finite_class. }
  destruct HFclass as [HFfinite HForder].
  destruct HForder as [HFref [HFtrans HFanti]].
  assert (HGfinite : finite_frame G).
  { unfold G. now apply point_generated_frame_finite. }
  assert (HGorder : frame_is_partial_order G).
  {
    unfold G. apply point_generated_partial_order.
    split; [exact HFref |]. split; assumption.
  }
  assert (HGroot : frame_root G r).
  { unfold G, r. apply point_generated_rooted. }
  assert (HGguard : satisfies G VG r (grzpoint2_atom_guard p)).
  {
    unfold G, VG, r. apply (proj2
      (@point_generated_truth_at_root nat F V X HFtrans
        (grzpoint2_atom_guard p))). exact Hguard.
  }
  assert (HGnotp : ~ satisfies G VG r p).
  {
    intro Hsat. apply Hnotp. unfold G, VG, r in Hsat.
    apply (proj1 (@point_generated_truth_at_root nat F V X HFtrans p)).
    exact Hsat.
  }
  pose proof (Hvalid (grzpoint2_adjoin_terminal_frame G)
    (grzpoint2_adjoin_terminal_in_finite_class HGfinite HGorder)
    (grzpoint2_adjoin_terminal_valuation G VG) (inl r)) as Hsatp.
  apply HGnotp.
  apply (proj2 (grzpoint2_adjoin_terminal_truth
    HGfinite HGorder HGroot HGguard (subformulas_self p) r)).
  exact Hsatp.
Qed.

Theorem GrzPoint2_finite_sound_complete :
  forall p : formula nat,
    GrzPoint2_proves p <->
    normal_valid_on_class GrzPoint2_finite_frame_class p.
Proof.
  intro p; split.
  - intros Hp F HF. now apply GrzPoint2_proves_sound_on_finite_frame.
  - apply GrzPoint2_finite_complete.
Qed.

(** * Strict hierarchy *)

Lemma grzpoint2_fork_finite : finite_frame point2_fork_frame.
Proof. exists [W0; W1; W2]. intros []; simpl; auto. Qed.

Lemma grzpoint2_fork_antisymmetric :
  frame_antisymmetric point2_fork_frame.
Proof.
  intros x y Hxy Hyx. destruct x, y; simpl in *; try reflexivity;
    intuition discriminate.
Qed.

Lemma grzpoint2_fork_in_Grz_finite_frame_class :
  Grz_finite_frame_class point2_fork_frame.
Proof.
  split; [exact grzpoint2_fork_finite |]. repeat split.
  - exact point2_fork_reflexive.
  - exact point2_fork_transitive.
  - exact grzpoint2_fork_antisymmetric.
Qed.

Lemma Grz_not_proves_Point2_atom :
  ~ Grz_proves (Point2 (Atom 0)).
Proof.
  intro Hp.
  pose proof (Grz_finite_sound Hp
    grzpoint2_fork_in_Grz_finite_frame_class) as Hvalid.
  apply point2_fork_not_piecewise_strongly_convergent.
  now apply (proj1
    (valid_Point2_iff_strong_confluence point2_fork_frame)).
Qed.

Theorem Grz_strictly_weaker_GrzPoint2 :
  normal_strictly_weaker Grz_proves GrzPoint2_proves.
Proof.
  split.
  - intros p Hp. now apply Grz_weaker_than_GrzPoint2.
  - exists (Point2 (Atom 0)); split.
    + apply GrzPoint2_proves_Point2.
