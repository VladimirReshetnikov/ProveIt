Proof.
  intros pointwiseRoot hpointwise.
  unfold coqRestrictedPANativeAxiomRowsTargetWitnessesRoot.
  apply templateExistentialWitnessIntroductionFrom_derives.
  rewrite coqRestrictedPANativeAxiomRowsTarget_total_open_ready.
  exact (coqRestrictedPANativeAxiomRowsOpenedTargetRoot_derives
    pointwiseRoot hpointwise).
Qed.

(** Rebuild the adequacy block around an arbitrary deepest pointwise root. *)
Definition coqRestrictedPANativeAxiomRowsAdequacyWitnessesRoot
    (deepRoot : TemplateRawProof) : TemplateRawProof :=
  rawCoqTemplateNestedExEliminationFromRoot 5
    coqRestrictedPANativeAxiomRowsShiftedAdequateBodyTemplate
    (rawCoqTemplateRenameN 14
      coqRestrictedPANativeAxiomRowsTargetTemplate)
    coqRestrictedPANativeAxiomRowsAfterBoundedContext
    coqRestrictedPANativeAxiomRowsShiftedAdequateRoot deepRoot.

(** Rebuild boundedness around the completed adequacy block. *)
Definition coqRestrictedPANativeAxiomRowsBoundedWitnessesRoot
    (deepRoot : TemplateRawProof) : TemplateRawProof :=
  rawCoqTemplateNestedExEliminationFromRoot 5
    coqRestrictedPANativeAxiomRowsShiftedBoundedBodyTemplate
    (rawCoqTemplateRenameN 9
      coqRestrictedPANativeAxiomRowsTargetTemplate)
    coqRestrictedPANativeAxiomRowsAfterWitnessContext
    coqRestrictedPANativeAxiomRowsShiftedBoundedRoot
    (coqRestrictedPANativeAxiomRowsAdequacyWitnessesRoot deepRoot).

(** The witnessed-context package is the head of the ready context, so the
    shorter head-assumption eliminator closes its entire nine-witness block. *)
Definition coqRestrictedPANativeAxiomRowsAllWitnessesRoot
    (deepRoot : TemplateRawProof) : TemplateRawProof :=
  rawCoqTemplateNestedExEliminationRoot 9
    coqRestrictedPANativeAxiomRowsWitnessBodyTemplate
    coqRestrictedPANativeAxiomRowsTargetTemplate
    [coqRestrictedPANativeAxiomRowsBoundedContextTemplate;
     coqRestrictedPANativeAxiomRowsAdequateContextTemplate;
     coqRestrictedPANativeAxiomRowsFieldTemplate;
     coqRestrictedPANativeAxiomRowsTransferSourceTemplate]
    (coqRestrictedPANativeAxiomRowsBoundedWitnessesRoot deepRoot).

Theorem coqRestrictedPANativeAxiomRowsAllWitnessesRoot_derives :
  forall deepRoot,
  TemplateRawDerives coqRestrictedPANativeAxiomRowsDeepContext
    coqRestrictedPANativeAxiomRowsShiftedTargetTemplate deepRoot ->
  TemplateRawDerives coqRestrictedPANativeAxiomRowsReadyContext
    coqRestrictedPANativeAxiomRowsTargetTemplate
    (coqRestrictedPANativeAxiomRowsAllWitnessesRoot deepRoot).
Proof.
  intros deepRoot hdeep.
  unfold coqRestrictedPANativeAxiomRowsAllWitnessesRoot,
    coqRestrictedPANativeAxiomRowsReadyContext.
  apply rawCoqTemplateNestedExEliminationRoot_derives.
  unfold coqRestrictedPANativeAxiomRowsBoundedWitnessesRoot.
  apply rawCoqTemplateNestedExEliminationFromRoot_derives.
  - rewrite <- coqRestrictedPANativeAxiomRowsShiftedBounded_shape.
    apply templateRawDerives_assumption.
    exact coqRestrictedPANativeAxiomRows_shifted_bounded_in.
  - rewrite coqRestrictedPANativeAxiomRowsTarget_rename_9_5.
    unfold coqRestrictedPANativeAxiomRowsAdequacyWitnessesRoot.
    apply rawCoqTemplateNestedExEliminationFromRoot_derives.
    + rewrite <- coqRestrictedPANativeAxiomRowsShiftedAdequate_shape.
      apply templateRawDerives_assumption.
      exact coqRestrictedPANativeAxiomRows_shifted_adequate_in.
    + rewrite coqRestrictedPANativeAxiomRowsTarget_rename_14_5.
      exact hdeep.
Qed.

(** ------------------------------------------------------------------
    Close the five public assumptions into one reusable logical law. *)

Definition coqRestrictedPANativeAxiomRowsLawTemplate : TemplateFormula :=
  tfImp coqRestrictedPANativeAxiomRowsTransferSourceTemplate
    (tfImp coqRestrictedPANativeAxiomRowsFieldTemplate
      (tfImp coqRestrictedPANativeAxiomRowsAdequateContextTemplate
        (tfImp coqRestrictedPANativeAxiomRowsBoundedContextTemplate
          (tfImp coqRestrictedPANativeAxiomRowsWitnessContextTemplate
            coqRestrictedPANativeAxiomRowsTargetTemplate)))).

Definition coqRestrictedPANativeAxiomRowsAfterTransferContext
    : TemplateContext :=
  [coqRestrictedPANativeAxiomRowsTransferSourceTemplate].

Definition coqRestrictedPANativeAxiomRowsAfterFieldContext
    : TemplateContext :=
  [coqRestrictedPANativeAxiomRowsFieldTemplate;
   coqRestrictedPANativeAxiomRowsTransferSourceTemplate].

Definition coqRestrictedPANativeAxiomRowsAfterAdequacyContext
    : TemplateContext :=
  [coqRestrictedPANativeAxiomRowsAdequateContextTemplate;
   coqRestrictedPANativeAxiomRowsFieldTemplate;
   coqRestrictedPANativeAxiomRowsTransferSourceTemplate].

Definition coqRestrictedPANativeAxiomRowsAfterBoundedContextForLaw
    : TemplateContext :=
  [coqRestrictedPANativeAxiomRowsBoundedContextTemplate;
   coqRestrictedPANativeAxiomRowsAdequateContextTemplate;
   coqRestrictedPANativeAxiomRowsFieldTemplate;
   coqRestrictedPANativeAxiomRowsTransferSourceTemplate].

Definition coqRestrictedPANativeAxiomRowsLawRoot
    (deepRoot : TemplateRawProof) : TemplateRawProof :=
  trpImpI [] coqRestrictedPANativeAxiomRowsTransferSourceTemplate
    (tfImp coqRestrictedPANativeAxiomRowsFieldTemplate
      (tfImp coqRestrictedPANativeAxiomRowsAdequateContextTemplate
        (tfImp coqRestrictedPANativeAxiomRowsBoundedContextTemplate
          (tfImp coqRestrictedPANativeAxiomRowsWitnessContextTemplate
            coqRestrictedPANativeAxiomRowsTargetTemplate))))
    (trpImpI coqRestrictedPANativeAxiomRowsAfterTransferContext
      coqRestrictedPANativeAxiomRowsFieldTemplate
      (tfImp coqRestrictedPANativeAxiomRowsAdequateContextTemplate
        (tfImp coqRestrictedPANativeAxiomRowsBoundedContextTemplate
          (tfImp coqRestrictedPANativeAxiomRowsWitnessContextTemplate
            coqRestrictedPANativeAxiomRowsTargetTemplate)))
      (trpImpI coqRestrictedPANativeAxiomRowsAfterFieldContext
        coqRestrictedPANativeAxiomRowsAdequateContextTemplate
        (tfImp coqRestrictedPANativeAxiomRowsBoundedContextTemplate
          (tfImp coqRestrictedPANativeAxiomRowsWitnessContextTemplate
            coqRestrictedPANativeAxiomRowsTargetTemplate))
        (trpImpI coqRestrictedPANativeAxiomRowsAfterAdequacyContext
          coqRestrictedPANativeAxiomRowsBoundedContextTemplate
          (tfImp coqRestrictedPANativeAxiomRowsWitnessContextTemplate
            coqRestrictedPANativeAxiomRowsTargetTemplate)
          (trpImpI coqRestrictedPANativeAxiomRowsAfterBoundedContextForLaw
            coqRestrictedPANativeAxiomRowsWitnessContextTemplate
            coqRestrictedPANativeAxiomRowsTargetTemplate
            (coqRestrictedPANativeAxiomRowsAllWitnessesRoot deepRoot))))).

Theorem coqRestrictedPANativeAxiomRowsLawRoot_derives : forall deepRoot,
  TemplateRawDerives coqRestrictedPANativeAxiomRowsDeepContext
    coqRestrictedPANativeAxiomRowsShiftedTargetTemplate deepRoot ->
  TemplateRawDerives [] coqRestrictedPANativeAxiomRowsLawTemplate
    (coqRestrictedPANativeAxiomRowsLawRoot deepRoot).
Proof.
  intros deepRoot hdeep.
  unfold coqRestrictedPANativeAxiomRowsLawRoot,
    coqRestrictedPANativeAxiomRowsLawTemplate.
  apply coqRestrictedPADirect_templateRawDerives_impI.
  apply coqRestrictedPADirect_templateRawDerives_impI.
  apply coqRestrictedPADirect_templateRawDerives_impI.
  apply coqRestrictedPADirect_templateRawDerives_impI.
  apply coqRestrictedPADirect_templateRawDerives_impI.
  exact (coqRestrictedPANativeAxiomRowsAllWitnessesRoot_derives
    deepRoot hdeep).
Qed.

