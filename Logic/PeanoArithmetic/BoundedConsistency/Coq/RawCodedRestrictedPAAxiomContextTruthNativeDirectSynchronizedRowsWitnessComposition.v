(** ------------------------------------------------------------------
    Close the five target witnesses from a genuinely pointwise callback.

    The axiom-list traversal is already a projection of the nine-witness
    package.  Consequently the only new derivation needed at the deepest
    scope is the pointwise successor-Sigma assertion itself. *)

Definition coqRestrictedPANativeAxiomRowsFinalWitnessBodyRoot
    : TemplateRawProof :=
  trpAss coqRestrictedPANativeAxiomRowsDeepContext
    coqRestrictedPANativeAxiomRowsFinalWitnessBodyTemplate.

Definition coqRestrictedPANativeAxiomRowsAxiomTraversalPairRoot
    : TemplateRawProof :=
  trpAndE2 coqRestrictedPANativeAxiomRowsDeepContext
    coqRestrictedPANativeAxiomRowsWitnessTraversalTemplate
    (tfAnd coqRestrictedPANativeAxiomRowsAxiomTraversalTemplate
      coqRestrictedPANativeAxiomRowsWitnessedRowsTemplate)
    coqRestrictedPANativeAxiomRowsFinalWitnessBodyRoot.

Definition coqRestrictedPANativeAxiomRowsAxiomTraversalRoot
    : TemplateRawProof :=
  trpAndE1 coqRestrictedPANativeAxiomRowsDeepContext
    coqRestrictedPANativeAxiomRowsAxiomTraversalTemplate
    coqRestrictedPANativeAxiomRowsWitnessedRowsTemplate
    coqRestrictedPANativeAxiomRowsAxiomTraversalPairRoot.

Theorem coqRestrictedPANativeAxiomRowsAxiomTraversalRoot_derives :
  TemplateRawDerives coqRestrictedPANativeAxiomRowsDeepContext
    coqRestrictedPANativeAxiomRowsAxiomTraversalTemplate
    coqRestrictedPANativeAxiomRowsAxiomTraversalRoot.
Proof.
  unfold coqRestrictedPANativeAxiomRowsAxiomTraversalRoot.
  apply coqRestrictedPADirect_templateRawDerives_andE1.
  unfold coqRestrictedPANativeAxiomRowsAxiomTraversalPairRoot.
  apply coqRestrictedPADirect_templateRawDerives_andE2.
  rewrite <- coqRestrictedPANativeAxiomRowsFinalWitnessBody_shape.
  apply templateRawDerives_assumption.
  exact coqRestrictedPANativeAxiomRows_final_witness_body_in.
Qed.

(** The partial opening used by the shape module and the total opening used
    by the reusable raw-proof constructor agree on this literal five-binder
    target. *)
Lemma coqRestrictedPANativeAxiomRowsTarget_total_open_ready :
  templateExistentialWitnessOpeningMany
    coqRestrictedPANativeAxiomRowsTargetWitnesses
    coqRestrictedPANativeAxiomRowsShiftedTargetTemplate =
  coqRestrictedPANativeAxiomRowsOpenedTargetTemplate.
Proof. vm_compute. reflexivity. Qed.

Definition coqRestrictedPANativeAxiomRowsOpenedTargetRoot
    (pointwiseRoot : TemplateRawProof) : TemplateRawProof :=
  trpAndI coqRestrictedPANativeAxiomRowsDeepContext
    coqRestrictedPANativeAxiomRowsAxiomTraversalTemplate
    coqRestrictedPANativeAxiomRowsPointwiseTemplate
    coqRestrictedPANativeAxiomRowsAxiomTraversalRoot pointwiseRoot.

Lemma coqRestrictedPANativeAxiomRowsOpenedTargetRoot_derives : forall
    pointwiseRoot,
  TemplateRawDerives coqRestrictedPANativeAxiomRowsDeepContext
    coqRestrictedPANativeAxiomRowsPointwiseTemplate pointwiseRoot ->
  TemplateRawDerives coqRestrictedPANativeAxiomRowsDeepContext
    coqRestrictedPANativeAxiomRowsOpenedTargetTemplate
    (coqRestrictedPANativeAxiomRowsOpenedTargetRoot pointwiseRoot).
Proof.
  intros pointwiseRoot hpointwise.
  rewrite coqRestrictedPANativeAxiomRowsOpenedTarget_shape.
  unfold coqRestrictedPANativeAxiomRowsOpenedTargetRoot.
  destruct coqRestrictedPANativeAxiomRowsAxiomTraversalRoot_derives as
    [htraversalValid [htraversalContext htraversalConclusion]].
  destruct hpointwise as
    [hpointwiseValid [hpointwiseContext hpointwiseConclusion]].
  unfold TemplateRawDerives.
  cbn [TemplateRawProofValid templateRawContext templateRawConclusion].
  repeat split; try assumption; reflexivity.
Qed.

Definition coqRestrictedPANativeAxiomRowsTargetWitnessesRoot
    (pointwiseRoot : TemplateRawProof) : TemplateRawProof :=
  templateExistentialWitnessIntroductionFrom
    coqRestrictedPANativeAxiomRowsDeepContext
    coqRestrictedPANativeAxiomRowsTargetWitnesses
    coqRestrictedPANativeAxiomRowsShiftedTargetTemplate
    (coqRestrictedPANativeAxiomRowsOpenedTargetRoot pointwiseRoot).

Theorem coqRestrictedPANativeAxiomRowsTargetWitnessesRoot_derives : forall
    pointwiseRoot,
  TemplateRawDerives coqRestrictedPANativeAxiomRowsDeepContext
    coqRestrictedPANativeAxiomRowsPointwiseTemplate pointwiseRoot ->
  TemplateRawDerives coqRestrictedPANativeAxiomRowsDeepContext
    coqRestrictedPANativeAxiomRowsShiftedTargetTemplate
