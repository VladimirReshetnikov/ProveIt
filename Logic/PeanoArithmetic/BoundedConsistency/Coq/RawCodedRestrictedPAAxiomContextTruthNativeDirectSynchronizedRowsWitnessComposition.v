(**
  Eliminate all nineteen synchronized-row table witnesses.

  This module is deliberately independent of the arithmetic proof at the
  deepest row.  Given one proof of the shifted native context-truth target in
  the exact nineteen-witness context, it rebuilds the five adequacy, five
  boundedness, and nine witnessed-context existential eliminations.  It then
  abstracts the transfer source, selected axiom field, and three public
  context hypotheses into one purely logical implication.

  The remaining callback is therefore pointwise only; none of the table
  package opening or implication-introduction plumbing remains downstream.
*)

