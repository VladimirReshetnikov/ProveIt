(** Iterated eigenvariable renaming of the final conclusion. *)
Fixpoint templateFormulaShiftMany
    (count : nat) (formula : TemplateFormula) : TemplateFormula :=
  match count with
  | 0 => formula
  | S smaller =>
      templateFormulaShiftMany smaller (templateFormulaRename S formula)
  end.

(** Compute the literal deepest context created by [count] eliminations.
    At each successful step the opened body is consed over the shifted prior
    context.  Failure records that the source had too few leading binders. *)
Fixpoint templateExistentialEliminationContext
    (count : nat) (source : TemplateFormula) (context : TemplateContext)
    : option TemplateContext :=
  match count with
  | 0 => Some context
  | S smaller =>
      match source with
      | tfEx body =>
          templateExistentialEliminationContext smaller body
            (body :: templateContextShift context)
      | _ => None
      end
  end.

(** Compile a proof from the deepest eigenvariable context back to the
    original context.  The original existential proof is used at the first
    step; every later existential source is the freshly consed assumption
    generated by the preceding step. *)
Theorem raw_codedPALocalProofOf_existential_elimination_chain : forall
    (M : RawPAModel), RawPASatisfies M -> forall
    (translation : RawCodedTemplateTranslation M)
    count source context conclusion deepContext sourceRoot deepRoot,
  templateExistentialEliminationContext count source context =
    Some deepContext ->
  RawCodedPALocalProofOf M
    (rawTemplateContextCode translation context)
    (rawTemplateFormula translation source) sourceRoot ->
  RawCodedPALocalProofOf M
    (rawTemplateContextCode translation deepContext)
    (rawTemplateFormula translation
      (templateFormulaShiftMany count conclusion)) deepRoot ->
  exists root,
    RawCodedPALocalProofOf M
      (rawTemplateContextCode translation context)
      (rawTemplateFormula translation conclusion) root.
Proof.
  intros M hPA translation count.
  induction count as [|count ih];
    intros source context conclusion deepContext sourceRoot deepRoot
      hdeepContext hsource hdeep.
  - cbn [templateExistentialEliminationContext
      templateFormulaShiftMany] in hdeepContext, hdeep.
    inversion hdeepContext; subst deepContext.
    exists deepRoot. exact hdeep.
  - destruct source; try discriminate hdeepContext.
    cbn [templateExistentialEliminationContext] in hdeepContext.
    assert (hbodyAssumption : RawCodedPALocalProofOf M
      (rawTemplateContextCode translation
        (source :: templateContextShift context))
      (rawTemplateFormula translation source)
      (rawProofAssumptionRoot M
        (rawTemplateContextCode translation
          (source :: templateContextShift context))
        (rawTemplateFormula translation source))).
    {
      cbn [rawTemplateContextCode].
      apply (raw_codedPALocalProofOf_assumption M hPA).
      exact (raw_templateContext_realizable M hPA translation
        (templateContextShift context)).
    }
    destruct (ih source
      (source :: templateContextShift context)
      (templateFormulaRename S conclusion)
      deepContext
      (rawProofAssumptionRoot M
        (rawTemplateContextCode translation
          (source :: templateContextShift context))
        (rawTemplateFormula translation source))
      deepRoot hdeepContext hbodyAssumption hdeep)
      as [bodyRoot hbody].
    exists (rawProofExERoot M
      (rawTemplateContextCode translation context)
      (rawTemplateFormula translation source)
      (rawTemplateFormula translation conclusion)
      sourceRoot bodyRoot).
    apply (raw_codedPALocalProofOf_exE M hPA
      (rawTemplateContextCode translation context)
      (rawTemplateContextCode translation (templateContextShift context))
      (rawTemplateFormula translation source)
      (rawTemplateFormula translation conclusion)
      (rawTemplateFormula translation
        (templateFormulaRename S conclusion))
      sourceRoot bodyRoot).
    + rewrite <- rawTemplateFormula_ex.
      exact hsource.
    + exact (raw_templateContext_shift M hPA translation context).
    + exact (rawTemplateFormula_shift translation conclusion).
    + cbn [rawTemplateContextCode] in hbody.
      exact hbody.
Qed.

End PABoundedRawCodedPALocalProofExistentialEliminationChain.
