(**
  Finite chains of represented existential elimination.

  A synchronized traversal extension returns eight nested existential
  witnesses.  Eliminating them one at a time repeatedly performs the same
  delicate operations: shift the complete current context, cons the opened
  body as an eigenvariable assumption, shift the eventual conclusion, and
  rebuild the parent proof node from the existential child and body child.

  This module extracts that pattern for any fixed metatheoretic number of
  leading existential binders.  Carrier-valued formula and proof codes remain
  opaque; only the finite template spine is inspected.
*)

