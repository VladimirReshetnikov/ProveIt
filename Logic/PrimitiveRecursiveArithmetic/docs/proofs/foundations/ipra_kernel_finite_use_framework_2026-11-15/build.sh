#!/usr/bin/env bash
set -euo pipefail
ROOT="$(cd "$(dirname "$0")" && pwd)"
cd "$ROOT"

export PYTHONPATH="$ROOT/code"

python3 - <<'PY2'
from fractions import Fraction
from pathlib import Path
import json
from kffu import cubic_bisection_certificate
Path('examples/cubic_certificate.json').write_text(
    json.dumps(cubic_bisection_certificate(Fraction(7, 3), 12), indent=2) + '\n',
    encoding='utf-8')
PY2
python3 code/generate_lean_schedule.py examples/contract_dag.json examples/GeneratedSchedule.lean
python3 code/test_kffu.py |& tee verification/test_output.txt

(
  cd paper
  latexmk -pdf -interaction=nonstopmode -halt-on-error ipra_kernel_finite_use_framework.tex
  latexmk -c >/dev/null
)

pdfinfo paper/ipra_kernel_finite_use_framework.pdf > verification/pdfinfo.txt
pdftotext paper/ipra_kernel_finite_use_framework.pdf verification/pdf_text.tmp
head -n 80 verification/pdf_text.tmp > verification/pdf_text_head.txt
rm -f verification/pdf_text.tmp
python3 verification/verify.py

# Keep the delivered tree free of generated bytecode and TeX intermediates.
find code verification -type d -name '__pycache__' -prune -exec rm -rf {} +
find . -type f -name '*.pyc' -delete
rm -f verification/pdf_text.txt

find . -type f \
  ! -name 'MANIFEST.sha256' \
  ! -path './.git/*' \
  -print0 | sort -z | xargs -0 sha256sum > MANIFEST.sha256

echo "Build and verification complete."
