"""Compare delivered checker ASTs with the frozen upstream AST index.

The index was generated by parsing, never executing, all 3,247 Python sources
in the pinned Artifacts tree and the five incoming archives. This checks exact
program duplication only. It cannot establish novelty of a mathematical idea.
"""
from pathlib import Path
import ast
import hashlib
import json

ROOT = Path(__file__).resolve().parent


class DropDocstrings(ast.NodeTransformer):
    def generic_visit(self, node):
        super().generic_visit(node)
        if isinstance(node, (ast.Module, ast.FunctionDef, ast.AsyncFunctionDef,
                             ast.ClassDef)) and node.body:
            first = node.body[0]
            if (isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant)
                    and isinstance(first.value.value, str)):
                node.body.pop(0)
        return node


def ast_hash(path):
    tree = DropDocstrings().visit(ast.parse(path.read_text()))
    encoded = ast.dump(tree, include_attributes=False).encode()
    return hashlib.sha256(encoded).hexdigest()


def main():
    index = json.loads((ROOT / 'evidence/corpus_ast_index.json').read_text())
    recorded = json.loads((ROOT / 'evidence/final_duplicate_audit.json').read_text())
    by_hash = {}
    for row in index:
        by_hash.setdefault(row['normalized_ast_sha256'], []).append(row['path'])
    if (len(index) != recorded['python_sources_parsed'] or
            len(by_hash) != recorded['distinct_normalized_asts']):
        raise AssertionError('Corpus index counts differ from the frozen audit')
    results = []
    for row in recorded['candidates']:
        path = ROOT / row['path']
        current = ast_hash(path)
        matches = by_hash.get(current, [])
        if current != row['normalized_ast_sha256']:
            raise AssertionError('Delivered checker changed: ' + row['path'])
        if matches != row['identical_existing_sources']:
            raise AssertionError('Duplicate report differs: ' + row['path'])
        results.append({'path': row['path'], 'identical_existing_sources': matches})
    print(json.dumps({'indexed_sources': len(index), 'results': results}, indent=2))


if __name__ == '__main__':
    main()
