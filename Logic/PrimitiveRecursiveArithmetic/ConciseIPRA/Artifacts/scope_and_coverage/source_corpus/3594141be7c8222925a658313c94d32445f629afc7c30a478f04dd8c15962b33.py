"""Build the standalone LaTeX source and PDF; not part of the checker."""
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parent


def expand(path, ancestors=()):
    path = path.resolve()
    if path in ancestors:
        raise ValueError("Circular TeX input: " + str(path))
    source = path.read_text()

    def include(match):
        child = ROOT / match.group(1)
        if not child.suffix:
            child = child.with_suffix(".tex")
        return "\n% Included from " + child.relative_to(ROOT).as_posix() + "\n" + expand(child, ancestors + (path,))

    source = re.sub(r"\\input\{([^}]+)\}", include, source)

    def listing(match):
        child = ROOT / match.group(2)
        options = match.group(1) or ""
        return "\\begin{lstlisting}" + options + "\n" + child.read_text().rstrip() + "\n\\end{lstlisting}"

    return re.sub(r"\\lstinputlisting(\[[^\]]*\])?\{([^}]+)\}", listing, source)


def main():
    standalone = ROOT / "ipra_local_rewriting.tex"
    standalone.write_text("% Standalone source; generated by build.py from report.tex.\n" + expand(ROOT / "report.tex"))
    command = ["pdflatex", "-interaction=nonstopmode", "-halt-on-error", standalone.name]
    for attempt in range(3):
        result = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
        (ROOT / "evidence" / "latex_build_stdout.txt").write_text(result.stdout + result.stderr)
        if result.returncode:
            print(result.stdout[-7000:])
            raise SystemExit(result.returncode)
        log = standalone.with_suffix(".log").read_text(errors="replace")
        if attempt >= 1 and "Rerun to get" not in log and "Rerun to get /PageLabels" not in log:
            break
    print(str(standalone.with_suffix(".pdf")))


if __name__ == "__main__":
    main()
