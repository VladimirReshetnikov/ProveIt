(** A predicate-selected sublanguage.  Unlike the source's finite-set
    presentation, predicates are kept abstract here and specialized to
    duplicate-tolerant symbol lists below. *)
Definition language_sublanguage (L : language)
    (pfunc : forall k, language_func L k -> Prop)
    (prel : forall k, language_rel L k -> Prop) : language :=
  {| language_func := fun k => { f : language_func L k | pfunc k f };
     language_rel := fun k => { r : language_rel L k | prel k r } |}.

Arguments language_sublanguage L pfunc prel : clear implicits.

Definition language_sublanguage_unsub {L pfunc prel} :
    language_hom (language_sublanguage L pfunc prel) L :=
  @Build_language_hom (language_sublanguage L pfunc prel) L
    (fun k (f : {x : language_func L k | pfunc k x}) => proj1_sig f)
    (fun k (r : {x : language_rel L k | prel k x}) => proj1_sig r).

Lemma language_sublanguage_unsub_func : forall L pfunc prel k
    (f : language_func (language_sublanguage L pfunc prel) k),
  hom_func language_sublanguage_unsub f = proj1_sig f.
Proof. reflexivity. Qed.

Lemma language_sublanguage_unsub_rel : forall L pfunc prel k
    (r : language_rel (language_sublanguage L pfunc prel) k),
  hom_rel language_sublanguage_unsub r = proj1_sig r.
Proof. reflexivity. Qed.

Record language_hom_injective {L K} (h : language_hom L K) : Prop := {
  language_hom_injective_func : forall k,
    forall x y, @hom_func L K h k x = hom_func h y -> x = y;
  language_hom_injective_rel : forall k,
    forall x y, @hom_rel L K h k x = hom_rel h y -> x = y
}.

Definition language_sublanguage_unsub_injective {L pfunc prel} :
  @language_hom_injective (language_sublanguage L pfunc prel) L
    language_sublanguage_unsub.
Proof.
  constructor; intros k [x Hx] [y Hy] H; cbn in H; subst y;
    f_equal; apply proof_irrelevance.
Defined.

(** A singleton inventory concentrated at one arity. *)
Definition indexed_singleton {A : nat -> Type} {j}
    (x : A j) (k : nat) : list (A k) :=
  match Nat.eq_dec j k with
  | left e => [eq_rect j A x k e]
  | right _ => []
  end.

Lemma indexed_singleton_same : forall A j (x : A j),
  indexed_singleton x j = [x].
Proof.
  intros A j x. unfold indexed_singleton.
  destruct (Nat.eq_dec j j) as [e | H]; [|contradiction].
  replace e with (eq_refl j) by apply proof_irrelevance. reflexivity.
Qed.

(** Duplicate-tolerant function-symbol inventories for terms. *)
Fixpoint semiterm_function_symbols {L X n}
    (t : semiterm L X n) : forall k, list (language_func L k) :=
  match t with
  | Semiterm_bvar _ => fun _ => []
  | Semiterm_fvar _ => fun _ => []
  | @Semiterm_func _ _ _ j f v => fun k =>
      indexed_singleton f k ++
      flat_map (fun i => semiterm_function_symbols (v i) k) (fin_enum j)
  end.

Lemma semiterm_function_symbols_root : forall L X n j
    (f : language_func L j) (v : Fin.t j -> semiterm L X n),
  In f (semiterm_function_symbols (Semiterm_func f v) j).
Proof.
  intros. cbn [semiterm_function_symbols].
  rewrite indexed_singleton_same. simpl. now left.
Qed.

Lemma semiterm_function_symbols_child : forall L X n j
    (f : language_func L j) (v : Fin.t j -> semiterm L X n)
    i k g,
  In g (semiterm_function_symbols (v i) k) ->
  In g (semiterm_function_symbols (Semiterm_func f v) k).
Proof.
  intros L X n j f v i k g Hg. cbn [semiterm_function_symbols].
  apply in_or_app. right. apply in_flat_map.
  exists i. split; [apply fin_enum_complete | exact Hg].
Qed.

Fixpoint semiterm_to_sublanguage {L X n pfunc prel}
    (t : semiterm L X n) :
    (forall k f, In f (semiterm_function_symbols t k) -> pfunc k f) ->
    semiterm (language_sublanguage L pfunc prel) X n :=
  match t with
  | Semiterm_bvar i => fun _ => Semiterm_bvar i
  | Semiterm_fvar x => fun _ => Semiterm_fvar x
  | @Semiterm_func _ _ _ j f v => fun H =>
      @Semiterm_func (language_sublanguage L pfunc prel) X n j
        (exist _ f (H j f
        (semiterm_function_symbols_root f v)))
        (fun i => @semiterm_to_sublanguage L X n pfunc prel (v i)
          (fun k g Hg => H k g
            (@semiterm_function_symbols_child L X n j f v i k g Hg)))
  end.

Lemma semiterm_language_map_to_sublanguage : forall L X n
    (pfunc : forall k, language_func L k -> Prop)
    (prel : forall k, language_rel L k -> Prop)
    (t : semiterm L X n)
    (H : forall k f, In f (semiterm_function_symbols t k) -> pfunc k f),
  semiterm_language_map language_sublanguage_unsub
    (@semiterm_to_sublanguage L X n pfunc prel t H) = t.
Proof.
  intros L X n pfunc prel t. induction t as [i | x | j f v IH];
    intro H; cbn [semiterm_to_sublanguage semiterm_language_map].
  - reflexivity.
  - reflexivity.
  - f_equal. apply functional_extensionality. intro i.
    apply IH.
Qed.

(** Formula inventories remain arity-indexed, so no dependent casts or
    decidable equality are needed to collect symbols. *)
Fixpoint semiformula_function_symbols {L X n}
    (p : semiformula L X n) : forall k, list (language_func L k) :=
  match p with
  | @Semiformula_verum _ _ _ => fun _ => []
  | @Semiformula_falsum _ _ _ => fun _ => []
  | @Semiformula_rel _ _ _ j _ v => fun k =>
      flat_map (fun i => semiterm_function_symbols (v i) k) (fin_enum j)
  | @Semiformula_nrel _ _ _ j _ v => fun k =>
      flat_map (fun i => semiterm_function_symbols (v i) k) (fin_enum j)
  | Semiformula_and phi psi => fun k =>
      semiformula_function_symbols phi k ++
      semiformula_function_symbols psi k
  | Semiformula_or phi psi => fun k =>
      semiformula_function_symbols phi k ++
      semiformula_function_symbols psi k
  | Semiformula_all phi => semiformula_function_symbols phi
  | Semiformula_exists phi => semiformula_function_symbols phi
  end.

Fixpoint semiformula_relation_symbols {L X n}
    (p : semiformula L X n) : forall k, list (language_rel L k) :=
  match p with
  | @Semiformula_verum _ _ _ => fun _ => []
  | @Semiformula_falsum _ _ _ => fun _ => []
  | @Semiformula_rel _ _ _ j R _ => fun k => indexed_singleton R k
  | @Semiformula_nrel _ _ _ j R _ => fun k => indexed_singleton R k
  | Semiformula_and phi psi => fun k =>
      semiformula_relation_symbols phi k ++
      semiformula_relation_symbols psi k
  | Semiformula_or phi psi => fun k =>
      semiformula_relation_symbols phi k ++
      semiformula_relation_symbols psi k
  | Semiformula_all phi => semiformula_relation_symbols phi
  | Semiformula_exists phi => semiformula_relation_symbols phi
  end.

Lemma semiformula_function_symbols_atom : forall L X n j
    (R : language_rel L j) (v : Fin.t j -> semiterm L X n) i k f,
  In f (semiterm_function_symbols (v i) k) ->
  In f (semiformula_function_symbols (Semiformula_rel R v) k).
Proof.
  intros. cbn [semiformula_function_symbols]. apply in_flat_map.
  exists i. split; [apply fin_enum_complete | assumption].
Qed.

Lemma semiformula_relation_symbols_rel : forall L X n j
    (R : language_rel L j) (v : Fin.t j -> semiterm L X n),
  In R (semiformula_relation_symbols (Semiformula_rel R v) j).
Proof. intros. cbn. rewrite indexed_singleton_same. now left. Qed.

Lemma semiformula_relation_symbols_nrel : forall L X n j
    (R : language_rel L j) (v : Fin.t j -> semiterm L X n),
  In R (semiformula_relation_symbols (Semiformula_nrel R v) j).
Proof. intros. cbn. rewrite indexed_singleton_same. now left. Qed.

Fixpoint semiformula_to_sublanguage {L X n pfunc prel}
    (p : semiformula L X n) :
    (forall k f, In f (semiformula_function_symbols p k) -> pfunc k f) ->
    (forall k r, In r (semiformula_relation_symbols p k) -> prel k r) ->
    semiformula (language_sublanguage L pfunc prel) X n.
Proof.
  destruct p as [n0 | n0 | n0 j R v | n0 j R v |
      n0 phi psi | n0 phi psi | n0 phi | n0 phi]; intros Hf Hr.
  - exact (@Semiformula_verum (language_sublanguage L pfunc prel) X n0).
  - exact (@Semiformula_falsum (language_sublanguage L pfunc prel) X n0).
  - exact (@Semiformula_rel (language_sublanguage L pfunc prel) X n0 j
      (exist _ R (Hr j R (semiformula_relation_symbols_rel R v)))
      (fun i => @semiterm_to_sublanguage L X n0 pfunc prel (v i)
        (fun k f Hfi => Hf k f
          (@semiformula_function_symbols_atom L X n0 j R v i k f Hfi)))).
  - exact (@Semiformula_nrel (language_sublanguage L pfunc prel) X n0 j
      (exist _ R (Hr j R (semiformula_relation_symbols_nrel R v)))
      (fun i => @semiterm_to_sublanguage L X n0 pfunc prel (v i)
        (fun k f Hfi => Hf k f
          (@semiformula_function_symbols_atom L X n0 j R v i k f Hfi)))).
  - apply Semiformula_and.
    + refine (@semiformula_to_sublanguage L X n0 pfunc prel phi _ _);
        intros k x Hx.
      * apply Hf. apply in_or_app. now left.
      * apply Hr. apply in_or_app. now left.
    + refine (@semiformula_to_sublanguage L X n0 pfunc prel psi _ _);
        intros k x Hx.
      * apply Hf. apply in_or_app. now right.
      * apply Hr. apply in_or_app. now right.
  - apply Semiformula_or.
    + refine (@semiformula_to_sublanguage L X n0 pfunc prel phi _ _);
        intros k x Hx.
      * apply Hf. apply in_or_app. now left.
      * apply Hr. apply in_or_app. now left.
    + refine (@semiformula_to_sublanguage L X n0 pfunc prel psi _ _);
        intros k x Hx.
      * apply Hf. apply in_or_app. now right.
      * apply Hr. apply in_or_app. now right.
  - apply Semiformula_all.
    exact (@semiformula_to_sublanguage L X (S n0) pfunc prel phi Hf Hr).
  - apply Semiformula_exists.
    exact (@semiformula_to_sublanguage L X (S n0) pfunc prel phi Hf Hr).
Defined.

Lemma semiformula_language_map_to_sublanguage : forall L X n
    (pfunc : forall k, language_func L k -> Prop)
    (prel : forall k, language_rel L k -> Prop)
    (p : semiformula L X n)
    (Hf : forall k f,
      In f (semiformula_function_symbols p k) -> pfunc k f)
    (Hr : forall k r,
      In r (semiformula_relation_symbols p k) -> prel k r),
  semiformula_language_map language_sublanguage_unsub
    (@semiformula_to_sublanguage L X n pfunc prel p Hf Hr) = p.
Proof.
  intros L X n pfunc prel p. induction p as [n0 | n0 | n0 j R v |
      n0 j R v | n0 phi IHphi psi IHpsi | n0 phi IHphi psi IHpsi |
      n0 phi IH | n0 phi IH]; intros Hf Hr; cbn.
  - reflexivity.
  - reflexivity.
  - f_equal. apply functional_extensionality. intro i.
    apply semiterm_language_map_to_sublanguage.
  - f_equal. apply functional_extensionality. intro i.
    apply semiterm_language_map_to_sublanguage.
  - now rewrite IHphi, IHpsi.
  - now rewrite IHphi, IHpsi.
  - now rewrite IH.
  - now rewrite IH.
Qed.

Definition semiformula_predicate_sublanguage {L X n}
    (p : semiformula L X n) : language :=
  language_sublanguage L
    (fun k f => In f (semiformula_function_symbols p k))
    (fun k r => In r (semiformula_relation_symbols p k)).

Definition semiformula_to_predicate_sublanguage {L X n}
    (p : semiformula L X n) :
    semiformula (semiformula_predicate_sublanguage p) X n :=
  @semiformula_to_sublanguage L X n
    (fun k f => In f (semiformula_function_symbols p k))
    (fun k r => In r (semiformula_relation_symbols p k)) p
    (fun _ _ H => H) (fun _ _ H => H).

Lemma semiformula_language_map_to_predicate_sublanguage : forall L X n
    (p : semiformula L X n),
  semiformula_language_map language_sublanguage_unsub
    (semiformula_to_predicate_sublanguage p) = p.
Proof. intros. apply semiformula_language_map_to_sublanguage. Qed.

(** Number the members of a duplicate-tolerant list by their first
    occurrence.  The semantic sublanguage below uses finite ordinals as its
    symbols, making encodability computational and independent of proof
    fields. *)
Lemma list_index_lt_length : forall A
    (eq_dec : forall x y : A, {x = y} + {x <> y})
    (x : A) xs,
  In x xs -> list_index eq_dec x xs < length xs.
Proof.
  intros A eq_dec x xs. induction xs as [|y ys IH]; simpl; [tauto |].
  destruct (eq_dec x y) as [-> | Hneq]; simpl; [lia |].
  intros [Heq | Hin].
  - exfalso. apply Hneq. now symmetry.
  - specialize (IH Hin). lia.
Qed.

Definition list_member_position {A}
    (eq_dec : forall x y : A, {x = y} + {x <> y})
    (xs : list A) (x : A) (Hx : In x xs) : Fin.t (length xs) :=
  Fin.of_nat_lt (@list_index_lt_length A eq_dec x xs Hx).

Lemma fin_to_nat_FS_value : forall n (i : Fin.t n),
  proj1_sig (Fin.to_nat (Fin.FS i)) =
  S (proj1_sig (Fin.to_nat i)).
Proof. intros n i. cbn. destruct (Fin.to_nat i). reflexivity. Qed.

Lemma chain_list_index_nth : forall A (xs : list A)
    (i : Fin.t (length xs)) (d : A),
  @chain_list_index A xs i =
  nth (proj1_sig (Fin.to_nat i)) xs d.
Proof.
  intros A xs. induction xs as [|x xs IH]; intro i; [inversion i |].
  refine (@Fin.caseS' (length xs) i
    (fun j => forall d : A,
      @chain_list_index A (x :: xs) j =
      nth (proj1_sig (Fin.to_nat j)) (x :: xs) d) _ _).
  - reflexivity.
  - intros j d. rewrite fin_to_nat_FS_value. cbn. apply IH.
Qed.

Lemma chain_list_index_member_position : forall A
    (eq_dec : forall x y : A, {x = y} + {x <> y})
    (xs : list A) x (Hx : In x xs),
  @chain_list_index A xs (@list_member_position A eq_dec xs x Hx) = x.
Proof.
  intros A eq_dec xs x Hx.
  rewrite (@chain_list_index_nth A xs
    (@list_member_position A eq_dec xs x Hx) x).
  unfold list_member_position.
  rewrite Fin.to_nat_of_nat. cbn.
  exact (@nth_list_index A eq_dec x x xs Hx).
Qed.

(** Finite-list membership is encodable even when the ambient symbol type is
    not.  Encoding by the first matching position also quotient-normalizes
    duplicate occurrences, while decoding retains the actual symbol and its
    membership proof. *)
Lemma nth_error_list_index : forall A
    (eq_dec : forall x y : A, {x = y} + {x <> y})
    (x : A) xs,
  In x xs -> nth_error xs (list_index eq_dec x xs) = Some x.
Proof.
  intros A eq_dec x xs; induction xs as [|y ys IH]; simpl; [tauto |].
  destruct (eq_dec x y) as [-> | Hneq]; simpl; [reflexivity |].
  intros [Heq | Hin].
  - exfalso. apply Hneq. now symmetry.
  - now apply IH.
Qed.

Definition list_member_decode {A} (xs : list A) (n : nat) :
    option {x : A | In x xs}.
Proof.
  destruct (lt_dec n (length xs)) as [Hlt | Hlt].
  - exact (Some (exist _
      (@chain_list_index A xs (Fin.of_nat_lt Hlt))
      (@chain_list_index_member A xs (Fin.of_nat_lt Hlt)))).
  - exact None.
Defined.

Lemma sig_prop_ext : forall A (P : A -> Prop) (x y : {z : A | P z}),
  proj1_sig x = proj1_sig y -> x = y.
Proof.
  intros A P [x Hx] [y Hy] Hxy. cbn in Hxy. subst y.
  f_equal. apply proof_irrelevance.
Qed.

Definition list_member_encoding {A}
    (eq_dec : forall x y : A, {x = y} + {x <> y})
    (xs : list A) : encoding {x : A | In x xs}.
Proof.
  refine {| encode := fun x => list_index eq_dec (proj1_sig x) xs;
            decode := list_member_decode xs |}.
  intros [x Hx].
  change (list_member_decode xs (list_index eq_dec x xs) =
    Some (exist (fun y => In y xs) x Hx)).
  unfold list_member_decode.
  destruct (lt_dec (list_index eq_dec x xs) (length xs))
    as [Hlt | Hlt].
  - assert (Hfin : Fin.of_nat_lt Hlt =
        @list_member_position A eq_dec xs x Hx).
    { unfold list_member_position. f_equal. apply proof_irrelevance. }
    rewrite Hfin.
    pose proof (@chain_list_index_member_position A eq_dec xs x Hx)
      as Hvalue.
    f_equal. apply sig_prop_ext. exact Hvalue.
  - exfalso. apply Hlt. now apply list_index_lt_length.
Defined.

Definition semiformula_predicate_sublanguage_encodable {L X n}
    (D : language_decidable_eq L) (p : semiformula L X n) :
    language_encodable (semiformula_predicate_sublanguage p) :=
  @Build_language_encodable (semiformula_predicate_sublanguage p)
    (fun k => list_member_encoding (@language_func_eq_dec L D k)
      (semiformula_function_symbols p k))
    (fun k => list_member_encoding (@language_rel_eq_dec L D k)
      (semiformula_relation_symbols p k)).

Definition semiformula_sublanguage {L X n}
    (p : semiformula L X n) : language :=
  {| language_func := fun k =>
       Fin.t (length (semiformula_function_symbols p k));
     language_rel := fun k =>
       Fin.t (length (semiformula_relation_symbols p k)) |}.

Definition semiformula_sublanguage_unsub {L X n}
    (p : semiformula L X n) :
    language_hom (semiformula_sublanguage p) L :=
  @Build_language_hom (semiformula_sublanguage p) L
    (fun k i => @chain_list_index (language_func L k)
      (semiformula_function_symbols p k) i)
    (fun k i => @chain_list_index (language_rel L k)
      (semiformula_relation_symbols p k) i).

Definition semiformula_sublanguage_number {L X n}
    (D : language_decidable_eq L) (p : semiformula L X n) :
    language_hom (semiformula_predicate_sublanguage p)
      (semiformula_sublanguage p) :=
  @Build_language_hom (semiformula_predicate_sublanguage p)
    (semiformula_sublanguage p)
    (fun k f => @list_member_position (language_func L k)
      (@language_func_eq_dec L D k)
      (semiformula_function_symbols p k) (proj1_sig f) (proj2_sig f))
    (fun k r => @list_member_position (language_rel L k)
      (@language_rel_eq_dec L D k)
      (semiformula_relation_symbols p k) (proj1_sig r) (proj2_sig r)).

Definition semiformula_to_own_sublanguage {L X n}
    (D : language_decidable_eq L) (p : semiformula L X n) :
    semiformula (semiformula_sublanguage p) X n :=
  semiformula_language_map (semiformula_sublanguage_number D p)
    (semiformula_to_predicate_sublanguage p).

Lemma semiformula_language_map_to_own_sublanguage : forall L X n
    (D : language_decidable_eq L) (p : semiformula L X n),
  semiformula_language_map (semiformula_sublanguage_unsub p)
    (semiformula_to_own_sublanguage D p) = p.
Proof.
  intros L X n D p.
  unfold semiformula_to_own_sublanguage.
  rewrite semiformula_language_map_comp.
  assert (Hhom : language_hom_comp
      (semiformula_sublanguage_unsub p)
      (semiformula_sublanguage_number D p) =
      (@language_sublanguage_unsub L
        (fun k f => In f (semiformula_function_symbols p k))
        (fun k r => In r (semiformula_relation_symbols p k)))).
  { apply language_hom_ext.
    - intros k [f Hf]. cbn. apply chain_list_index_member_position.
    - intros k [r Hr]. cbn. apply chain_list_index_member_position. }
  rewrite Hhom. apply semiformula_language_map_to_predicate_sublanguage.
Qed.

Fixpoint fin_encoding (n : nat) : encoding (Fin.t n).
Proof.
  destruct n as [|n].
  - refine (@Build_encoding (Fin.t 0)
      (fun i : Fin.t 0 => match i with end)
      (fun _ => @None (Fin.t 0)) _).
    intro i. inversion i.
  - pose (E := fin_encoding n).
    refine {| encode := fun i => @Fin.caseS' n i (fun _ => nat)
                0 (fun j => S (encode E j));
              decode := fun k => match k with
                | 0 => Some Fin.F1
                | S j => option_map Fin.FS (decode E j)
                end |}.
    intro i. refine (@Fin.caseS' n i
      (fun j =>
        match
          @Fin.caseS' n j (fun _ => nat) 0
            (fun u => S (encode E u))
        with
        | 0 => Some Fin.F1
        | S m => option_map Fin.FS (decode E m)
        end = Some j) _ _).
    + reflexivity.
    + intro j. cbn. now rewrite decode_encode.
Defined.

Definition language_sublanguage_decidable_eq {L pfunc prel}
    (D : language_decidable_eq L) :
    language_decidable_eq (language_sublanguage L pfunc prel).
Proof.
  constructor; intros k [x Hx] [y Hy].
  - destruct (@language_func_eq_dec L D k x y) as [-> | Hneq].
    + left. f_equal. apply proof_irrelevance.
    + right. intro H. apply Hneq. now dependent destruction H.
  - destruct (@language_rel_eq_dec L D k x y) as [-> | Hneq].
    + left. f_equal. apply proof_irrelevance.
    + right. intro H. apply Hneq. now dependent destruction H.
Defined.

Definition semiformula_sublanguage_encodable {L X n}
    (p : semiformula L X n) :
    language_encodable (semiformula_sublanguage p) :=
  @Build_language_encodable (semiformula_sublanguage p)
    (fun k =>
       fin_encoding (length (semiformula_function_symbols p k)))
    (fun k =>
       fin_encoding (length (semiformula_relation_symbols p k))).

Definition semiformula_sublanguage_decidable_eq {L X n}
    (p : semiformula L X n) :
    language_decidable_eq (semiformula_sublanguage p) :=
  @Build_language_decidable_eq (semiformula_sublanguage p)
    (fun _ => Fin.eq_dec) (fun _ => Fin.eq_dec).

(** * Extending structures along injective language homomorphisms *)

Definition first_order_structure_extend {L K M}
    (Hinh : inhabited M) (h : language_hom L K)
    (S : first_order_structure L M) : first_order_structure K M :=
  {| structure_func := fun k f v =>
       epsilon Hinh (fun y => exists g : language_func L k,
         hom_func h g = f /\ y = structure_func S g v);
     structure_rel := fun k r v => exists s : language_rel L k,
       hom_rel h s = r /\ structure_rel S s v |}.

Lemma first_order_structure_extend_func : forall L K M
    (Hinh : inhabited M) (h : language_hom L K)
    (Hinj : language_hom_injective h) (S : first_order_structure L M)
    k (f : language_func L k) v,
  structure_func (first_order_structure_extend Hinh h S)
    (hom_func h f) v = structure_func S f v.
Proof.
  intros L K M Hinh h Hinj S k f v.
  unfold first_order_structure_extend. cbn.
  pose proof (@epsilon_spec M Hinh
    (fun y => exists g : language_func L k,
      hom_func h g = hom_func h f /\ y = structure_func S g v)
    (ex_intro _ (structure_func S f v)
      (ex_intro _ f (conj eq_refl eq_refl)))) as Hspec.
  destruct Hspec as [g [Hg Hvalue]].
  assert (g = f) by
    (exact (@language_hom_injective_func L K h Hinj k g f Hg)).
  now subst g.
Qed.

Lemma first_order_structure_extend_rel : forall L K M
    (Hinh : inhabited M) (h : language_hom L K)
    (Hinj : language_hom_injective h) (S : first_order_structure L M)
    k (r : language_rel L k) v,
  structure_rel (first_order_structure_extend Hinh h S)
    (hom_rel h r) v <-> structure_rel S r v.
Proof.
  intros L K M Hinh h [Hfunc Hrel] S k r v. split.
  - intros [s [Hs Hholds]].
    assert (s = r) by (exact (@Hrel k s r Hs)). now subst s.
  - intro Hholds. exists r. now split.
Qed.

Lemma semiterm_val_language_map_extend : forall L K M
    (Hinh : inhabited M) (h : language_hom L K)
    (Hinj : language_hom_injective h) (S : first_order_structure L M)
    X n (t : semiterm L X n) (b : Fin.t n -> M) (f : X -> M),
  semiterm_val (first_order_structure_extend Hinh h S) b f
    (semiterm_language_map h t) = semiterm_val S b f t.
Proof.
  intros L K M Hinh h Hinj S X n t.
  induction t as [i | x | k F v IH]; intros b f; cbn;
    try reflexivity.
  etransitivity.
  - exact (@first_order_structure_extend_func L K M Hinh h Hinj S k F
      (fun i => semiterm_val (first_order_structure_extend Hinh h S)
        b f (semiterm_language_map h (v i)))).
  - f_equal. apply functional_extensionality. intro i. apply IH.
Qed.

Lemma semiformula_eval_language_map_extend : forall L K M
    (Hinh : inhabited M) (h : language_hom L K)
    (Hinj : language_hom_injective h) (S : first_order_structure L M)
    X n (p : semiformula L X n) (b : Fin.t n -> M) (f : X -> M),
  semiformula_eval (first_order_structure_extend Hinh h S) b f
    (semiformula_language_map h p) <-> semiformula_eval S b f p.
Proof.
  intros L K M Hinh h Hinj S X n p b f. revert b f.
  induction p as [n0 | n0 | n0 k R v | n0 k R v |
      n0 phi IHphi psi IHpsi | n0 phi IHphi psi IHpsi |
      n0 phi IH | n0 phi IH]; intros b f; cbn; try tauto.
  - assert (Hargs :
      (fun i => semiterm_val (first_order_structure_extend Hinh h S)
        b f (semiterm_language_map h (v i))) =
      (fun i => semiterm_val S b f (v i))).
    { apply functional_extensionality. intro i.
      apply semiterm_val_language_map_extend. exact Hinj. }
    rewrite Hargs.
    exact (@first_order_structure_extend_rel L K M Hinh h Hinj S k R
      (fun i => semiterm_val S b f (v i))).
  - assert (Hargs :
      (fun i => semiterm_val (first_order_structure_extend Hinh h S)
        b f (semiterm_language_map h (v i))) =
      (fun i => semiterm_val S b f (v i))).
    { apply functional_extensionality. intro i.
      apply semiterm_val_language_map_extend. exact Hinj. }
    rewrite Hargs.
    pose proof (@first_order_structure_extend_rel L K M Hinh h Hinj S k R
      (fun i => semiterm_val S b f (v i))) as Hrel.
    tauto.
  - rewrite IHphi, IHpsi. tauto.
  - rewrite IHphi, IHpsi. tauto.
  - split; intros Hall x.
    + apply (proj1 (IH (fin_env_cons x b) f)). apply Hall.
    + apply (proj2 (IH (fin_env_cons x b) f)). apply Hall.
  - split; intros [x Hx]; exists x.
    + apply (proj1 (IH (fin_env_cons x b) f)). exact Hx.
    + apply (proj2 (IH (fin_env_cons x b) f)). exact Hx.
Qed.

Definition first_order_model_extend {L K}
    (h : language_hom L K) (m : first_order_model L) :
    first_order_model K :=
  {| first_order_model_domain := first_order_model_domain m;
     first_order_model_nonempty := first_order_model_nonempty m;
     first_order_model_structure := first_order_structure_extend
       (first_order_model_nonempty m) h
       (first_order_model_structure m) |}.

Lemma first_order_model_extend_realize_language_map : forall L K
    (h : language_hom L K) (Hinj : language_hom_injective h)
    (m : first_order_model L) (p : sentence L),
  first_order_model_realize (first_order_model_extend h m)
    (semiformula_language_map h p) <->
  first_order_model_realize m p.
Proof.
  intros. unfold first_order_model_realize, sentence_realize, formula_eval.
  apply semiformula_eval_language_map_extend. exact Hinj.
Qed.

Theorem first_order_consequence_language_map_iff_injective : forall L K
    (h : language_hom L K) (Hinj : language_hom_injective h)
    (T : theory L) (p : sentence L),
  first_order_consequence (theory_language_map h T)
      (semiformula_language_map h p) <->
  first_order_consequence T p.
Proof.
  intros L K h Hinj T p. split.
  - intros H m Hm.
    apply (proj1 (@first_order_model_extend_realize_language_map
      L K h Hinj m p)).
    apply H. constructor. intros q Hq.
    destruct Hq as [r [Hr Heq]]. subst q.
    apply (proj2 (@first_order_model_extend_realize_language_map
      L K h Hinj m r)).
    exact (generic_models_set_elim Hm Hr).
  - apply first_order_consequence_language_map.
Qed.

Theorem first_order_satisfiable_language_map : forall L K
    (h : language_hom L K) (Hinj : language_hom_injective h)
    (T : theory L),
  first_order_satisfiable T ->
  first_order_satisfiable (theory_language_map h T).
Proof.
  intros L K h Hinj T [m Hm].
  exists (first_order_model_extend h m). constructor.
  intros q Hq. destruct Hq as [p [Hp Heq]]. subst q.
  apply (proj2 (@first_order_model_extend_realize_language_map
    L K h Hinj m p)).
  exact (generic_models_set_elim Hm Hp).
Qed.
