#!/usr/bin/env python3
"""Rebuild exact counts, rational constants, ratios, and the article table.

Requires mpmath for displayed ratios only. Counts remain exact integers.
Default maximum n=400; use --max-n 200 for a faster exploratory run.
The article's supplied table was built with the default setting.
"""
from __future__ import annotations
import argparse
import csv
import json
import platform
import sys
import time
from pathlib import Path
import mpmath as mp
from hardinian import counts, rational_constant

ROOT = Path(__file__).resolve().parents[1]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--max-n", type=int, default=400)
    args = parser.parse_args()
    if args.max_n < 40:
        parser.error("--max-n must be at least 40")
    mp.mp.dps = 70
    sizes = list(range(1, 41)) + [n for n in (80, 120, 200, 400) if n <= args.max_n]
    terms = []
    ratios = []
    timings = []
    for n in sizes:
        start = time.perf_counter()
        h = counts(n, 7)
        timings.append({"n": n, "seconds": round(time.perf_counter()-start, 6)})
        for r, value in enumerate(h):
            terms.append({"n": n, "r": r, "H": str(value)})
            if n in (20, 40, 80, 120, 200, 400) and r >= 1:
                q = rational_constant(r)
                c = mp.mpf(q.numerator) / q.denominator / mp.pi ** (r//2)
                ratio = mp.mpf(value) * n ** (r*(r-1)//2) / (c * mp.mpf(4)**(r*n))
                ratios.append({"n": n, "r": r, "ratio": mp.nstr(ratio, 45)})
        if n >= 40:
            print(n, timings[-1]["seconds"], flush=True)
    for filename, data in (("exact_counts.csv", terms), ("asymptotic_ratios.csv", ratios)):
        with (ROOT / "data" / filename).open("w", newline="") as f:
            writer = csv.DictWriter(f, fieldnames=list(data[0]))
            writer.writeheader(); writer.writerows(data)
    constants = []
    for r in range(21):
        q = rational_constant(r)
        constants.append({"r": r, "Q_numerator": str(q.numerator),
                          "Q_denominator": str(q.denominator), "pi_exponent": -(r//2)})
    (ROOT / "data/constants.json").write_text(json.dumps(constants, indent=2)+"\n")
    audit = {"python": sys.version.split()[0], "platform": platform.platform(),
             "mpmath": mp.__version__, "display_precision_decimal_digits": mp.mp.dps,
             "arithmetic": "Counts and rational constants use exact Python integers/Fraction; ratios use mpmath.",
             "sizes": sizes, "timings": timings}
    (ROOT / "data/computation_run.json").write_text(json.dumps(audit, indent=2)+"\n")
    lookup = {(x['n'], x['r']): x['ratio'] for x in ratios}
    with (ROOT / "data/ratio_table.tex").open("w") as f:
        f.write("% Generated by code/generate_data.py; not a proof.\n")
        for n in (20, 40, 80, 120, 200, 400):
            if (n, 7) not in lookup:
                continue
            vals = [f"{float(lookup[n,r]):.6f}" for r in range(2, 8)]
            f.write(str(n) + " & " + " & ".join(vals) + r" \\" + "\n")


if __name__ == "__main__":
    main()
