#!/usr/bin/env python3
"""Exact coefficients of OEIS A088714, using only the Python standard library.

Arithmetic complexity: N(N+1)(N+2)/6 integer products; O(N^2) integer cells.
The underlying recurrence and its correctness are proved in article.tex.
"""
from __future__ import annotations
import argparse
from pathlib import Path


def coefficients(n_max: int) -> list[int]:
    """Return a[0:n_max+1] exactly. n_max must be a nonnegative integer."""
    if not isinstance(n_max, int) or isinstance(n_max, bool) or n_max < 0:
        raise ValueError("n_max must be a nonnegative integer")
    c: list[list[int]] = [[1] * (n_max + 2)]
    a = [1]
    for n in range(1, n_max + 1):
        row = [0] * (n_max - n + 2)
        for k in range(1, len(row)):
            row[k] = row[k - 1] + sum(
                c[i][k] * c[n - 1 - i][k + 1] for i in range(n)
            )
        c.append(row)
        a.append(row[1])
    return a


def read_coefficients(path: Path) -> list[int]:
    """Read sequential 'n a_n' pairs, accepting comments and blank lines."""
    result: list[int] = []
    with path.open(encoding="utf-8") as stream:
        for line_no, line in enumerate(stream, 1):
            line = line.strip()
            if not line or line.startswith("#"):
                continue
            parts = line.split()
            if len(parts) != 2:
                raise ValueError(f"{path}:{line_no}: expected two fields")
            index, value = map(int, parts)
            if index != len(result) or value < 0:
                raise ValueError(f"{path}:{line_no}: invalid index or value")
            result.append(value)
    if not result:
        raise ValueError(f"{path}: empty coefficient file")
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--n", type=int, default=300, help="largest index (default 300)")
    parser.add_argument("--output", type=Path, default=Path("coefficients.txt"))
    args = parser.parse_args()
    if args.n < 0:
        parser.error("--n must be nonnegative")
    a = coefficients(args.n)
    args.output.parent.mkdir(parents=True, exist_ok=True)
    with args.output.open("w", encoding="utf-8") as out:
        out.write("# OEIS A088714; independently generated by the triangular recurrence.\n")
        for n, value in enumerate(a):
            out.write(f"{n} {value}\n")
    print(f"Wrote {len(a)} exact coefficients to {args.output}")


if __name__ == "__main__":
    main()
