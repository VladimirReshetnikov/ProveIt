#!/usr/bin/env python3
"""Render compact LaTeX tables from the generated JSON data (stdlib only).

Run after verify.py, optionally after inverse_checks.py. The output uses standard
LaTeX tabular/table environments and does not require booktabs or siunitx.
If inverse data are absent, only the normalized-ratio table is produced.
"""

from __future__ import annotations

import argparse
import json
from decimal import Decimal
from pathlib import Path


def tex_number(value: str, digits: int = 5) -> str:
    """Format a decimal string as a short scientific-notation math expression."""
    mantissa, exponent = format(Decimal(value), f".{digits - 1}E").split("E")
    return rf"${mantissa}\times 10^{{{int(exponent)}}}$"


def render_tables(output: Path) -> Path:
    """Write numerical_tables.tex from existing ratio and optional inverse data."""
    lines = ["% Generated by scripts/render_tables.py; do not edit by hand.",
             "% Numerical observations, not certified asymptotic remainder bounds."]
    ratios_path = output / "normalized_ratios.json"
    if ratios_path.exists():
        rows = json.loads(ratios_path.read_text(encoding="utf-8"))
        # Four representative rows keep the article table compact; the JSON/CSV
        # retain every requested index. Include all rows for nonstandard inputs.
        preferred = {50, 100, 200, 500}
        selected = [row for row in rows if row["k"] in preferred]
        if len(selected) < 2:
            selected = rows
        lines += [r"\begin{table}[htbp]", r"\centering\small",
                  r"\begin{tabular}{r r r r}", r"\hline",
                  r"$k$ & $R_k=c_k\rho^k/\Gamma(k)$ & $R_k-Q_3((k-1)^{-1})$ & $R_k-Q_6((k-1)^{-1})$ \\",
                  r"\hline"]
        for row in selected:
            ratio = format(Decimal(row["normalized_ratio"]), ".10f")
            lines.append(f"{row['k']} & ${ratio}$ & "
                         + tex_number(row["residual_Q3"]) + " & "
                         + tex_number(row["residual_Q6"]) + r" \\")
        lines += [r"\hline", r"\end{tabular}",
                  r"\caption{Direct normalized late coefficients and fixed-order residuals. Exact integers are evaluated with 80-digit Decimal arithmetic in the default run.}",
                  r"\label{tab:normalized-checks}", r"\end{table}", ""]
    inverse_path = output / "inverse_checks.json"
    if inverse_path.exists():
        data = json.loads(inverse_path.read_text(encoding="utf-8"))
        lines += [r"\begin{table}[htbp]", r"\centering\small",
                  r"\begin{tabular}{r r r r r}", r"\hline",
                  r"$k$ & $x_*(c_k)-k$ & $x_0^{\rm G}(c_k)-k$ & $x_3^{\rm G}(c_k)-k$ & $x_6^{\rm G}(c_k)-k$ \\",
                  r"\hline"]
        for row in data["checks"]:
            values = [row["lambert_seed_error"]] + [row["orders"][str(j)]["inverse_error"]
                                                      for j in (0, 3, 6)]
            lines.append(str(row["k"]) + " & " + " & ".join(tex_number(v) for v in values) + r" \\")
        lines += [r"\hline", r"\end{tabular}",
                  r"\caption{Lambert seed and selected smooth-model inverse errors at $y=c_k$. Here $x_J^{\rm G}$ solves $\Gamma(x)\rho^{-x}Q_J((x-1)^{-1})=y$, while $x_*$ is the Lambert seed. These are numerical smooth-model errors, not integer-threshold error certificates.}",
                  r"\label{tab:inverse-checks}", r"\end{table}", ""]
    path = output / "numerical_tables.tex"
    # ed. (2026-10-02): newline="\n" so the file is LF on Windows too (as
    # delivered, the platform's line endings).
    path.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    return path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path,
                        default=Path(__file__).resolve().parents[1] / "results")
    args = parser.parse_args()
    if not args.output_dir.is_dir():
        parser.error("Output directory does not exist; run verify.py first")
    render_tables(args.output_dir)
    print("Generated numerical_tables.tex")


if __name__ == "__main__":
    main()
