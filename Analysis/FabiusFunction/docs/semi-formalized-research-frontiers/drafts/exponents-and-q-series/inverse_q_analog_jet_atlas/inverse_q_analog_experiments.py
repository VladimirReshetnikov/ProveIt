#!/usr/bin/env python3
"""Reproducible symbolic and high-precision checks for the inverse-q report.

The script deliberately separates exact algebra (SymPy) from high-precision
numerics (mpmath).  It does not use Internet access or repository-local code.
Its output is a plain-text audit trail suitable for inclusion in an archive.

Experiments implemented here
----------------------------
1.  The critical parameter of (a;q)_n at q=-1, including the exceptional
    exact cubic at n=3, a=-1/3.
2.  Cyclotomic multiplicities of Gaussian coefficients, q-multinomials, and
    q-factorials; in particular, the carry-count formula for q-multinomials.
3.  The fixed-target, q -> 1 double-scaling inverse of (a;q)_infinity.
4.  The q -> 1 expansion of log Gamma_q(x), including the absence of odd
    algebraic powers beyond the linear term.
5.  The square-root inverse of a centered Gaussian polynomial near q=1.
6.  The critical curve xy=1 for the q-beta base inverse near q=1.

Run:
    python inverse_q_analog_experiments.py

Optional:
    python inverse_q_analog_experiments.py --digits 100 --output checks.txt

Dependencies: Python 3.10+, SymPy, mpmath.
"""

from __future__ import annotations

import argparse
import math
from pathlib import Path
from typing import Iterable, Sequence

import mpmath as mp
import sympy as sp


q = sp.Symbol("q")
a = sp.Symbol("a")


def finite_q_pochhammer(argument: sp.Expr, base: sp.Expr, order: int) -> sp.Expr:
    """Return the exact finite product (argument;base)_order."""
    if order < 0:
        raise ValueError("order must be nonnegative")
    return sp.prod(1 - argument * base**j for j in range(order))


def gaussian_polynomial(n: int, k: int, base: sp.Symbol = q) -> sp.Expr:
    """Compute [n choose k]_q by the polynomial recurrence.

    The recurrence avoids a rational expression whose removable singularities
    are inconvenient at roots of unity.
    """
    if k < 0 or k > n:
        return sp.Integer(0)
    k = min(k, n - k)
    row = [sp.Integer(0)] * (k + 1)
    row[0] = sp.Integer(1)
    for upper in range(1, n + 1):
        new = [sp.Integer(0)] * (k + 1)
        new[0] = sp.Integer(1)
        for lower in range(1, min(upper, k) + 1):
            left = row[lower] if lower < len(row) else 0
            new[lower] = sp.expand(left + base ** (upper - lower) * row[lower - 1])
        row = new
    return sp.expand(row[k])


def q_integer(n: int, base: sp.Expr = q) -> sp.Expr:
    """Return [n]_q as a polynomial for integer n >= 0."""
    if n < 0:
        raise ValueError("n must be nonnegative")
    return sp.Add(*(base**j for j in range(n))) if n else sp.Integer(0)


def q_factorial(n: int, base: sp.Expr = q) -> sp.Expr:
    """Return [n]_q! as a polynomial."""
    return sp.prod(q_integer(j, base) for j in range(1, n + 1))


def cyclotomic_exponent_binomial(n: int, k: int, d: int) -> int:
    """Exponent of Phi_d(q) in the Gaussian polynomial."""
    return n // d - k // d - (n - k) // d


def cyclotomic_exponent_multinomial(parts: Sequence[int], d: int) -> int:
    """Exponent of Phi_d(q) in a q-multinomial.

    With n=sum(parts), this equals floor(sum(r_i)/d), where r_i=k_i mod d:
    the number of one-column carries generated by the residues.
    """
    n = sum(parts)
    return n // d - sum(k // d for k in parts)


def cyclotomic_exponent_factorial(n: int, d: int) -> int:
    """Exponent of Phi_d(q), d>1, in [n]_q!."""
    return n // d


def bernoulli_polynomial_coefficient(order: int, x: sp.Expr) -> sp.Expr:
    """Coefficient c_order(x) in log Gamma_{e^-eps}(x)-log Gamma(x).

    order=1 gives c_1.  Positive odd orders greater than one vanish in the
    algebraic asymptotic expansion.  For order=2r, the formula is obtained by
    solving the q-gamma functional equation coefficient by coefficient.
    """
    if order == 1:
        return -((x - 1) * (x - 2)) / 4
    if order <= 0 or order % 2:
        return sp.Integer(0)
    r = order // 2
    B = sp.bernoulli(2 * r)
    numerator = (
        (sp.bernoulli(2 * r + 1, x) - sp.bernoulli(2 * r + 1, 1))
        / (2 * r + 1)
        - (x - 1)
    )
    return sp.simplify(B * numerator / (2 * r * sp.factorial(2 * r)))


def infinite_q_pochhammer_log(argument: mp.mpf, eps: mp.mpf) -> mp.mpf:
    """Compute log((argument; exp(-eps))_infinity) by a Lambert series.

    This representation is stable for the double-scaling tests, where
    argument=O(eps).  The summation is terminated by mpmath's nsum.
    """
    base = mp.e ** (-eps)
    return -mp.nsum(
        lambda r: argument**r / (r * (1 - base**r)), [1, mp.inf]
    )


def double_scaling_argument(L: mp.mpf, eps: mp.mpf, terms: int = 5) -> mp.mpf:
    """Asymptotic inverse a(eps) for (a;e^-eps)_infinity = exp(-L)."""
    coeff = [
        L,
        -L * (L + 2) / 4,
        L * (L**2 + 9 * L + 12) / 72,
        -L * (L**3 + 4 * L**2 + 12 * L + 24) / 576,
        -L * (31 * L**4 - 75 * L**3 - 800 * L**2 - 720) / 86400,
    ]
    if terms < 1 or terms > len(coeff):
        raise ValueError(f"terms must lie in 1..{len(coeff)}")
    return mp.fsum(coeff[j] * eps ** (j + 1) for j in range(terms))


def solve_double_scaling_argument(target: mp.mpf, eps: mp.mpf) -> mp.mpf:
    """Solve (a;e^-eps)_infinity=target for its principal a in (0,1)."""
    L = -mp.log(target)
    guess = double_scaling_argument(L, eps, terms=5)
    f = lambda z: infinite_q_pochhammer_log(z, eps) - mp.log(target)
    # Two nearby secant starts are more reliable than a derivative when eps is tiny.
    return mp.findroot(f, (guess * mp.mpf("0.98"), guess * mp.mpf("1.02")))


def centered_gaussian_cumulants(n: int, k: int) -> tuple[sp.Rational, sp.Rational, sp.Rational]:
    """Return kappa_2, kappa_4, kappa_6 of the centered exponent statistic."""
    def power_sum(m: int, N: int) -> sp.Expr:
        return sp.summation(sp.Symbol("j")**m, (sp.Symbol("j"), 1, N))

    kappas = []
    for r in (1, 2, 3):
        m = 2 * r
        delta = sp.simplify(power_sum(m, n) - power_sum(m, k) - power_sum(m, n - k))
        kappas.append(sp.simplify(sp.bernoulli(m) * delta / m))
    return tuple(kappas)  # type: ignore[return-value]


def centered_gaussian_value(n: int, k: int, eps: mp.mpf) -> mp.mpf:
    """Evaluate H(eps)=e^{d eps/2} G(e^-eps)/binom(n,k)."""
    poly = sp.Poly(gaussian_polynomial(n, k), q)
    coeffs = [mp.mpf(str(c)) for c in reversed(poly.all_coeffs())]
    base = mp.e ** (-eps)
    value = mp.fsum(c * base**j for j, c in enumerate(coeffs))
    d = k * (n - k)
    return mp.e ** (d * eps / 2) * value / math.comb(n, k)


def centered_gaussian_inverse_asymptotic(n: int, k: int, u: mp.mpf) -> mp.mpf:
    """Three-term square-root inverse of u=log H(eps)."""
    k2, k4, k6 = centered_gaussian_cumulants(n, k)
    K2, K4, K6 = map(lambda z: mp.mpf(str(z)), (k2, k4, k6))
    leading = mp.sqrt(2 * u / K2)
    bracket = (
        1
        - K4 * u / (12 * K2**2)
        + (7 * K4**2 / (288 * K2**4) - K6 / (180 * K2**3)) * u**2
    )
    return leading * bracket


def write_header(lines: list[str], title: str) -> None:
    lines.append("")
    lines.append("=" * 79)
    lines.append(title)
    lines.append("=" * 79)


def experiment_minus_one(lines: list[str]) -> None:
    write_header(lines, "1. Finite q-Pochhammer criticality at q=-1")
    lines.append(
        "For each n, the table checks P_q(-1)=0 at the predicted nontrivial "
        "critical parameter and compares the exact logarithmic second derivative."
    )
    for n in range(3, 11):
        s = n // 2
        astar = sp.Rational(1, n - 1) if n % 2 == 0 else -sp.Rational(1, n)
        P = sp.expand(finite_q_pochhammer(astar, q, n))
        P0 = sp.simplify(P.subs(q, -1))
        d1 = sp.simplify(sp.diff(P, q).subs(q, -1))
        d2 = sp.simplify(sp.diff(P, q, 2).subs(q, -1))
        d3 = sp.simplify(sp.diff(P, q, 3).subs(q, -1))
        L2 = sp.simplify(d2 / P0)
        predicted = (
            -sp.Rational((s + 1) * (2 * s - 1) ** 2, 12 * s * (s - 1))
            if n % 2 == 0
            else -sp.Rational((s - 1) * (2 * s + 1) ** 2, 12 * s * (s + 1))
        )
        lines.append(
            f"n={n:2d}, a*={str(astar):>5s}, P(-1)={P0}, P'(-1)={d1}, "
            f"(log P)''={L2}, predicted={predicted}, P'''(-1)={d3}"
        )
        assert d1 == 0
        assert sp.simplify(L2 - predicted) == 0
    cubic = sp.factor(
        finite_q_pochhammer(-sp.Rational(1, 3), q, 3)
        - sp.Rational(32, 27)
    )
    lines.append("")
    lines.append("Exceptional exact identity:")
    lines.append(f"(−1/3;q)_3 − 32/27 = {cubic}")
    assert sp.expand(cubic - sp.Rational(4, 27) * (q + 1) ** 3) == 0


def experiment_cyclotomic(lines: list[str]) -> None:
    write_header(lines, "2. Cyclotomic multiplicities and carry counts")
    lines.append("Gaussian exponents e_d are always 0 or 1:")
    for n, k in ((8, 3), (12, 5), (17, 7)):
        exps = {d: cyclotomic_exponent_binomial(n, k, d) for d in range(2, n + 1)}
        active = {d: e for d, e in exps.items() if e}
        assert set(exps.values()) <= {0, 1}
        lines.append(f"  [ {n} choose {k} ]_q: {active}")

    examples = [([2, 2, 2], 3), ([4, 4, 4, 4], 5), ([1, 1, 1, 1, 1], 2)]
    lines.append("q-multinomial exponents can exceed one:")
    for parts, d in examples:
        residues = [x % d for x in parts]
        exponent = cyclotomic_exponent_multinomial(parts, d)
        carry = sum(residues) // d
        lines.append(
            f"  parts={parts}, d={d}, residues={residues}, exponent={exponent}, carry={carry}"
        )
        assert exponent == carry

    lines.append("Leading coefficient of [n]_q! at q=-1:")
    for n in range(2, 9):
        m = n // 2
        F = sp.expand(q_factorial(n))
        coefficient = sp.simplify(sp.diff(F, q, m).subs(q, -1) / sp.factorial(m))
        lines.append(f"  n={n}: multiplicity={m}, coefficient={coefficient}, predicted={math.factorial(m)}")
        assert coefficient == math.factorial(m)

    lines.append("Simple zero of a Gaussian polynomial at q=-1:")
    for m in range(2, 7):
        for r in range(m):
            G = gaussian_polynomial(2 * m, 2 * r + 1)
            derivative = sp.simplify(sp.diff(G, q).subs(q, -1))
            predicted = (m - r) * math.comb(m, r)
            assert derivative == predicted
        lines.append(f"  n={2*m}: G'(-1)=(m-r) binom(m,r) verified for all odd k")


def experiment_double_scaling(lines: list[str]) -> None:
    write_header(lines, "3. Fixed-target inverse of (a;q)_infinity as q -> 1")
    lines.append(
        "The reported approximation uses five algebraic terms.  The final column "
        "scales the error by eps^6; bounded values are consistent with a remainder O(eps^6)."
    )
    for target in (mp.mpf("0.3"), mp.mpf("0.7")):
        L = -mp.log(target)
        lines.append(f"target={mp.nstr(target, 12)}, L={mp.nstr(L, 20)}")
        for eps in (mp.mpf("0.05"), mp.mpf("0.025"), mp.mpf("0.0125")):
            exact = solve_double_scaling_argument(target, eps)
            approx = double_scaling_argument(L, eps, terms=5)
            err = exact - approx
            scaled = err / eps**6
            lines.append(
                "  eps={:>8s} exact={} approx={} error={} error/eps^6={}".format(
                    mp.nstr(eps, 8),
                    mp.nstr(exact, 32),
                    mp.nstr(approx, 32),
                    mp.nstr(err, 8),
                    mp.nstr(scaled, 12),
                )
            )


def experiment_qgamma(lines: list[str]) -> None:
    write_header(lines, "4. q-gamma expansion at q=e^{-eps} -> 1")
    X = sp.Symbol("x")
    c1 = sp.factor(bernoulli_polynomial_coefficient(1, X))
    c2 = sp.factor(bernoulli_polynomial_coefficient(2, X))
    c4 = sp.factor(bernoulli_polynomial_coefficient(4, X))
    lines.append(f"c1(x) = {c1}")
    lines.append(f"c2(x) = {c2}")
    lines.append(f"c4(x) = {c4}")
    lines.append("Numerical residual after c1 eps + c2 eps^2, divided by eps^4:")
    for xval in (mp.mpf("0.5"), mp.mpf("0.7"), mp.mpf("1.3"), mp.mpf("2.5"), mp.mpf("4.2")):
        c1v = mp.mpf(str(c1.subs(X, str(xval))))
        c2v = mp.mpf(str(c2.subs(X, str(xval))))
        c4v = mp.mpf(str(c4.subs(X, str(xval))))
        lines.append(f"x={mp.nstr(xval,5)}, predicted c4={mp.nstr(c4v,16)}")
        for eps in (mp.mpf("0.08"), mp.mpf("0.04"), mp.mpf("0.02")):
            qq = mp.e ** (-eps)
            actual = mp.log(mp.qgamma(xval, qq)) - mp.log(mp.gamma(xval))
            scaled = (actual - c1v * eps - c2v * eps**2) / eps**4
            lines.append(f"  eps={mp.nstr(eps,5)} scaled={mp.nstr(scaled,18)}")


def experiment_centered_gaussian(lines: list[str]) -> None:
    write_header(lines, "5. Centered Gaussian square-root inverse")
    n, k = 8, 3
    k2, k4, k6 = centered_gaussian_cumulants(n, k)
    lines.append(f"n={n}, k={k}, kappa2={k2}, kappa4={k4}, kappa6={k6}")
    for u in (mp.mpf("1e-2"), mp.mpf("2.5e-3"), mp.mpf("6.25e-4")):
        f = lambda z: mp.log(centered_gaussian_value(n, k, z)) - u
        guess = mp.sqrt(2 * u / mp.mpf(str(k2)))
        exact = mp.findroot(f, (guess * mp.mpf("0.9"), guess * mp.mpf("1.1")))
        approx = centered_gaussian_inverse_asymptotic(n, k, u)
        lines.append(
            f"u={mp.nstr(u,8)} exact eps={mp.nstr(exact,28)} "
            f"Puiseux={mp.nstr(approx,28)} error={mp.nstr(exact-approx,10)}"
        )


def experiment_qbeta(lines: list[str]) -> None:
    write_header(lines, "6. q-beta critical curve at q=1")
    X, Y = sp.symbols("x y", positive=True)
    c1 = lambda z: bernoulli_polynomial_coefficient(1, z)
    c2 = lambda z: bernoulli_polynomial_coefficient(2, z)
    b1 = sp.factor(c1(X) + c1(Y) - c1(X + Y))
    b2 = sp.factor(c2(X) + c2(Y) - c2(X + Y))
    critical = sp.factor(b2.subs(Y, 1 / X))
    lines.append(f"linear coefficient b1(x,y) = {b1}")
    lines.append(f"quadratic coefficient b2(x,y) = {b2}")
    lines.append(f"on xy=1: b2(x,1/x) = {critical}")
    assert sp.simplify(b1 - (X * Y - 1) / 2) == 0
    assert sp.simplify(critical + (X - 1) ** 2 / (24 * X)) == 0


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--digits", type=int, default=80, help="mpmath decimal precision")
    parser.add_argument(
        "--output",
        type=Path,
        default=Path(__file__).with_name("numerical_checks.txt"),
        help="output audit file",
    )
    args = parser.parse_args()
    if args.digits < 40:
        raise SystemExit("Use at least 40 digits for stable residual tests.")
    mp.mp.dps = args.digits

    lines: list[str] = []
    lines.append("Inverse q-analog jet atlas: reproducibility audit")
    lines.append(f"mpmath precision: {mp.mp.dps} decimal digits")
    lines.append(f"SymPy version: {sp.__version__}")
    lines.append(f"mpmath version: {mp.__version__}")

    experiment_minus_one(lines)
    experiment_cyclotomic(lines)
    experiment_double_scaling(lines)
    experiment_qgamma(lines)
    experiment_centered_gaussian(lines)
    experiment_qbeta(lines)

    lines.append("")
    lines.append("All exact assertions passed.")
    args.output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {args.output}")


if __name__ == "__main__":
    main()
