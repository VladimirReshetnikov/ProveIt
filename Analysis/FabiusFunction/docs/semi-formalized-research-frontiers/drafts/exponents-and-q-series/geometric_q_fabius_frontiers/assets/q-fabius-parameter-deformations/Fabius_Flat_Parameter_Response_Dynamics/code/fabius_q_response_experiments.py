#!/usr/bin/env python3
"""Reproducible experiments for the Fabius q-response report.

The script has two layers.

1. Exact symbolic arithmetic
   -------------------------
   At q = 1/2 it computes, as exact rational numbers,

       * centered cumulants of X_q - 1/2,
       * their first q-derivatives,
       * centered moment derivatives, and
       * shifted-Legendre coefficients of the tangent density
         rho(x) = partial_q f_q(x)|_{q=1/2}.

   The formulas used in this layer are proved in the accompanying report.
   SymPy is used only as a rational/polynomial arithmetic engine.

2. Common-random-number Monte Carlo checks
   ----------------------------------------
   A single set of uniform digits U_j is used to evaluate both

       X = sum_j 2^(-j-1) U_j,
       V = partial_q X_q|_{q=1/2}.

   For every smooth test function phi,

       d/dq E[phi(X_q)]|_{1/2} = E[phi'(X) V].

   This pathwise formula gives low-variance checks of the exact moment and
   Legendre coefficients.  A separate common-random-number central difference
   estimates the tangent CDF G(x) = partial_q F_q(x)|_{1/2} and tests its exact
   antisymmetry G(1-x) = -G(x).

The numerical layer is evidence only; none of the report's proofs depends on
Monte Carlo output.
"""

from __future__ import annotations

import argparse
import csv
import math
from pathlib import Path
from typing import Dict, Iterable, List, Tuple

import matplotlib.pyplot as plt
import numpy as np
import sympy as sp
from numpy.polynomial import legendre as npleg


Q0 = sp.Rational(1, 2)


def exact_cumulant(r: int) -> sp.Rational:
    """Centered cumulant kappa_r at q=1/2.

    For r >= 2,
        kappa_r(q) = B_r/r * (1-q)^r/(1-q^r).
    Odd Bernoulli numbers above B_1 vanish automatically.
    """
    if r == 1:
        return sp.Rational(0)
    return sp.factor(sp.bernoulli(r) / (r * (2**r - 1)))


def exact_cumulant_q_derivative(r: int) -> sp.Rational:
    """First q-derivative of the centered cumulant at q=1/2."""
    if r == 1:
        return sp.Rational(0)
    return sp.factor(-2 * sp.bernoulli(r) * (2**r - 2) / (2**r - 1) ** 2)


def exact_moment_tables(max_degree: int) -> Tuple[List[sp.Rational], List[sp.Rational]]:
    """Return centered moments and their first q-derivatives at q=1/2.

    If M(z,q) = exp(K(z,q)), then partial_q M = M partial_q K.  Comparing
    exponential generating functions gives

        dot(mu_n) = sum_{r=1}^n binom(n,r) dot(kappa_r) mu_{n-r}.

    Ordinary moments themselves are generated by the standard cumulant
    recurrence

        mu_n = sum_{r=1}^n binom(n-1,r-1) kappa_r mu_{n-r}.
    """
    kappa = [sp.Rational(0)] * (max_degree + 1)
    kappa_dot = [sp.Rational(0)] * (max_degree + 1)
    for r in range(1, max_degree + 1):
        kappa[r] = exact_cumulant(r)
        kappa_dot[r] = exact_cumulant_q_derivative(r)

    mu = [sp.Rational(0)] * (max_degree + 1)
    mu_dot = [sp.Rational(0)] * (max_degree + 1)
    mu[0] = sp.Rational(1)

    for n in range(1, max_degree + 1):
        mu[n] = sp.factor(
            sum(
                sp.binomial(n - 1, r - 1) * kappa[r] * mu[n - r]
                for r in range(1, n + 1)
            )
        )
        mu_dot[n] = sp.factor(
            sum(
                sp.binomial(n, r) * kappa_dot[r] * mu[n - r]
                for r in range(1, n + 1)
            )
        )

    return mu, mu_dot


def shifted_legendre_tangent_coefficients(
    max_even_degree: int, mu_dot: List[sp.Rational]
) -> Dict[int, sp.Rational]:
    """Compute exact coefficients of rho in shifted Legendre polynomials.

    With P_k the ordinary Legendre polynomial and P_k^*(x)=P_k(2x-1),

        rho(x) = sum_k a_k P_k^*(x),
        a_k = (2k+1) integral_0^1 rho(x) P_k^*(x) dx.

    Symmetry kills odd k.  Since Y=2(X-1/2), the integral is the q-derivative
    of E[P_k(Y)] at q=1/2, which is a rational combination of mu_dot[j].
    """
    y = sp.Symbol("y")
    result: Dict[int, sp.Rational] = {}
    for k in range(2, max_even_degree + 1, 2):
        poly = sp.Poly(sp.legendre(k, y), y)
        expectation_derivative = sp.Rational(0)
        for (power,), coefficient in poly.terms():
            expectation_derivative += coefficient * (2**power) * mu_dot[power]
        result[k] = sp.factor((2 * k + 1) * expectation_derivative)
    return result


def write_exact_tables(data_dir: Path, max_degree: int, max_legendre: int) -> Tuple[List[sp.Rational], List[sp.Rational], Dict[int, sp.Rational]]:
    """Write the exact CSV tables used by the report."""
    mu, mu_dot = exact_moment_tables(max(max_degree, max_legendre))
    legendre = shifted_legendre_tangent_coefficients(max_legendre, mu_dot)

    cumulant_path = data_dir / "exact_cumulant_and_moment_jets.csv"
    with cumulant_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(
            [
                "degree",
                "kappa_at_half",
                "q_derivative_kappa_at_half",
                "centered_moment_at_half",
                "q_derivative_centered_moment_at_half",
                "q_derivative_centered_moment_decimal",
            ]
        )
        for n in range(0, max_degree + 1):
            kappa = exact_cumulant(n) if n >= 1 else sp.Rational(0)
            kappa_dot = exact_cumulant_q_derivative(n) if n >= 1 else sp.Rational(0)
            writer.writerow(
                [
                    n,
                    str(kappa),
                    str(kappa_dot),
                    str(mu[n]),
                    str(mu_dot[n]),
                    f"{float(mu_dot[n]):.17g}",
                ]
            )

    legendre_path = data_dir / "exact_tangent_legendre_coefficients.csv"
    with legendre_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(["degree", "exact_coefficient", "decimal_coefficient", "sign"])
        for degree, coefficient in legendre.items():
            sign = 0 if coefficient == 0 else (1 if coefficient > 0 else -1)
            writer.writerow([degree, str(coefficient), f"{float(coefficient):.17g}", sign])

    return mu, mu_dot, legendre


def half_weights(number_of_digits: int) -> Tuple[np.ndarray, np.ndarray]:
    """Return the q=1/2 weights and their q-derivatives.

    c_j = 2^(-j-1),
    d_0 = -1, d_1 = 0, d_j = (j-1)2^(-j) for j >= 2.
    """
    j = np.arange(number_of_digits, dtype=np.float64)
    c = np.power(2.0, -(j + 1.0))
    d = np.empty(number_of_digits, dtype=np.float64)
    d[0] = -1.0
    if number_of_digits > 1:
        d[1] = 0.0
    if number_of_digits > 2:
        jj = j[2:]
        d[2:] = (jj - 1.0) * np.power(2.0, -jj)
    return c, d


def update_running_sums(sum_value: float, sum_square: float, values: np.ndarray) -> Tuple[float, float]:
    """Accumulate first and second raw sample moments in float64."""
    return sum_value + float(np.sum(values)), sum_square + float(np.dot(values, values))


def monte_carlo_pathwise_checks(
    data_dir: Path,
    samples: int,
    chunk_size: int,
    number_of_digits: int,
    max_moment_order: int,
    max_legendre_degree: int,
    exact_mu_dot: List[sp.Rational],
    exact_legendre: Dict[int, sp.Rational],
    seed: int,
) -> None:
    """Validate exact q-derivative formulas by the pathwise identity."""
    rng = np.random.default_rng(seed)
    c, d = half_weights(number_of_digits)

    moment_orders = list(range(2, max_moment_order + 1, 2))
    legendre_degrees = list(range(2, max_legendre_degree + 1, 2))

    moment_sums = {order: [0.0, 0.0] for order in moment_orders}
    legendre_sums = {degree: [0.0, 0.0] for degree in legendre_degrees}

    # Derivative coefficients in the NumPy Legendre basis.  Evaluating these
    # arrays is faster and more stable than converting high-degree polynomials
    # to the monomial basis for the Monte Carlo layer.
    derivative_basis: Dict[int, np.ndarray] = {}
    for degree in legendre_degrees:
        coeff = np.zeros(degree + 1)
        coeff[degree] = 1.0
        derivative_basis[degree] = npleg.legder(coeff)

    completed = 0
    while completed < samples:
        size = min(chunk_size, samples - completed)
        digits = rng.random((size, number_of_digits), dtype=np.float64)
        x = digits @ c
        v = digits @ d
        z = x - 0.5
        y = 2.0 * z

        for order in moment_orders:
            contribution = order * np.power(z, order - 1) * v
            first, second = moment_sums[order]
            moment_sums[order] = list(update_running_sums(first, second, contribution))

        for degree in legendre_degrees:
            p_prime = npleg.legval(y, derivative_basis[degree])
            contribution = (2 * degree + 1) * 2.0 * p_prime * v
            first, second = legendre_sums[degree]
            legendre_sums[degree] = list(update_running_sums(first, second, contribution))

        completed += size

    moment_path = data_dir / "monte_carlo_moment_derivative_validation.csv"
    with moment_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(
            [
                "moment_order",
                "exact_derivative",
                "estimate",
                "standard_error",
                "z_score_estimate_minus_exact",
                "samples",
                "digits",
            ]
        )
        for order in moment_orders:
            total, total_square = moment_sums[order]
            estimate = total / samples
            variance = max(0.0, total_square / samples - estimate * estimate)
            standard_error = math.sqrt(variance / samples)
            exact = float(exact_mu_dot[order])
            z_score = (estimate - exact) / standard_error if standard_error > 0 else math.nan
            writer.writerow(
                [
                    order,
                    str(exact_mu_dot[order]),
                    f"{estimate:.17g}",
                    f"{standard_error:.17g}",
                    f"{z_score:.9g}",
                    samples,
                    number_of_digits,
                ]
            )

    legendre_path = data_dir / "monte_carlo_legendre_validation.csv"
    with legendre_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(
            [
                "degree",
                "exact_coefficient",
                "estimate",
                "standard_error",
                "z_score_estimate_minus_exact",
                "samples",
                "digits",
            ]
        )
        for degree in legendre_degrees:
            total, total_square = legendre_sums[degree]
            estimate = total / samples
            variance = max(0.0, total_square / samples - estimate * estimate)
            standard_error = math.sqrt(variance / samples)
            exact = float(exact_legendre[degree])
            z_score = (estimate - exact) / standard_error if standard_error > 0 else math.nan
            writer.writerow(
                [
                    degree,
                    str(exact_legendre[degree]),
                    f"{estimate:.17g}",
                    f"{standard_error:.17g}",
                    f"{z_score:.9g}",
                    samples,
                    number_of_digits,
                ]
            )


def q_weights(q: float, number_of_digits: int) -> np.ndarray:
    """Truncated normalized geometric weights (1-q)q^j."""
    j = np.arange(number_of_digits, dtype=np.float64)
    return (1.0 - q) * np.power(q, j)


def tangent_cdf_common_random_numbers(
    data_dir: Path,
    figure_dir: Path,
    samples: int,
    chunk_size: int,
    number_of_digits: int,
    q_step: float,
    seed: int,
) -> None:
    """Estimate G(x)=partial_q F_q(x)|_{1/2} by a central difference.

    The same uniform digits are used for q+h and q-h, which cancels most of the
    sampling noise.  The geometric tail omitted after ``number_of_digits`` has
    total weight q**number_of_digits; with the defaults this is far below the
    Monte Carlo resolution near q=1/2.
    """
    rng = np.random.default_rng(seed + 1)
    c_plus = q_weights(0.5 + q_step, number_of_digits)
    c_minus = q_weights(0.5 - q_step, number_of_digits)

    x_plus = np.empty(samples, dtype=np.float64)
    x_minus = np.empty(samples, dtype=np.float64)

    completed = 0
    while completed < samples:
        size = min(chunk_size, samples - completed)
        digits = rng.random((size, number_of_digits), dtype=np.float64)
        x_plus[completed : completed + size] = digits @ c_plus
        x_minus[completed : completed + size] = digits @ c_minus
        completed += size

    x_plus.sort()
    x_minus.sort()
    grid = np.linspace(0.01, 0.99, 197)
    cdf_plus = np.searchsorted(x_plus, grid, side="right") / samples
    cdf_minus = np.searchsorted(x_minus, grid, side="right") / samples
    tangent = (cdf_plus - cdf_minus) / (2.0 * q_step)

    # Pair grid[i] with 1-grid[i].  The exact theory predicts the sum is zero.
    symmetry_residual = tangent + tangent[::-1]

    output_path = data_dir / "tangent_cdf_common_random_numbers.csv"
    with output_path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle, lineterminator="\n")
        writer.writerow(
            [
                "x",
                "estimated_G",
                "estimated_G_at_1_minus_x",
                "antisymmetry_residual",
                "samples",
                "digits",
                "q_step",
            ]
        )
        for index, x in enumerate(grid):
            writer.writerow(
                [
                    f"{x:.17g}",
                    f"{tangent[index]:.17g}",
                    f"{tangent[::-1][index]:.17g}",
                    f"{symmetry_residual[index]:.17g}",
                    samples,
                    number_of_digits,
                    q_step,
                ]
            )

    plt.figure(figsize=(7.0, 4.3))
    plt.plot(grid, tangent, linewidth=1.4, label=r"common-random-number estimate of $G(x)$")
    plt.axhline(0.0, linewidth=0.8)
    plt.axvline(0.5, linewidth=0.8)
    plt.xlabel(r"$x$")
    plt.ylabel(r"$G(x)=\partial_qF_q(x)|_{q=1/2}$")
    plt.title("Tangent CDF at the Fabius parameter")
    plt.legend()
    plt.tight_layout()
    plt.savefig(figure_dir / "tangent_cdf.png", dpi=180)
    plt.close()


def plot_legendre_coefficients(figure_dir: Path, coefficients: Dict[int, sp.Rational]) -> None:
    """Plot the exact shifted-Legendre coefficients on a linear scale."""
    degrees = np.array(sorted(coefficients), dtype=int)
    values = np.array([float(coefficients[d]) for d in degrees], dtype=float)
    plt.figure(figsize=(7.0, 4.3))
    markerline, stemlines, baseline = plt.stem(degrees, values)
    plt.setp(markerline, markersize=5)
    plt.setp(stemlines, linewidth=1.1)
    plt.setp(baseline, linewidth=0.8)
    plt.xlabel("even shifted-Legendre degree")
    plt.ylabel("exact tangent coefficient (decimal value)")
    plt.title("Shifted-Legendre spectrum of the q-tangent density")
    plt.tight_layout()
    plt.savefig(figure_dir / "tangent_legendre_coefficients.png", dpi=180)
    plt.close()


def write_readme(output_root: Path, args: argparse.Namespace) -> None:
    """Write a compact reproducibility note next to the generated data."""
    text = f"""Fabius q-response numerical bundle
===================================

Generated by code/fabius_q_response_experiments.py.

Exact layer
-----------
* data/exact_cumulant_and_moment_jets.csv
* data/exact_tangent_legendre_coefficients.csv

These use exact SymPy rational arithmetic.  They are deterministic.

Numerical validation layer
--------------------------
* data/monte_carlo_moment_derivative_validation.csv
* data/monte_carlo_legendre_validation.csv
* data/tangent_cdf_common_random_numbers.csv
* figures/tangent_cdf.png
* figures/tangent_legendre_coefficients.png

Parameters used in this run:
* pathwise samples: {args.samples}
* CDF samples: {args.cdf_samples}
* chunk size: {args.chunk_size}
* geometric digits: {args.digits}
* central-difference step: {args.q_step}
* RNG seed: {args.seed}

The Monte Carlo results are checks only.  The accompanying report proves the
identities independently.
"""
    (output_root / "NUMERICAL_README.txt").write_text(text, encoding="utf-8")


def parse_arguments() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-root", type=Path, required=True)
    parser.add_argument("--samples", type=int, default=1_000_000)
    parser.add_argument("--cdf-samples", type=int, default=1_500_000)
    parser.add_argument("--chunk-size", type=int, default=25_000)
    parser.add_argument("--digits", type=int, default=32)
    parser.add_argument("--q-step", type=float, default=0.005)
    parser.add_argument("--seed", type=int, default=20260830)
    parser.add_argument("--max-moment", type=int, default=14)
    parser.add_argument("--max-legendre", type=int, default=20)
    return parser.parse_args()


def main() -> None:
    args = parse_arguments()
    output_root = args.output_root.resolve()
    data_dir = output_root / "data"
    figure_dir = output_root / "figures"
    data_dir.mkdir(parents=True, exist_ok=True)
    figure_dir.mkdir(parents=True, exist_ok=True)

    _, mu_dot, legendre = write_exact_tables(
        data_dir=data_dir,
        max_degree=args.max_moment,
        max_legendre=args.max_legendre,
    )

    monte_carlo_pathwise_checks(
        data_dir=data_dir,
        samples=args.samples,
        chunk_size=args.chunk_size,
        number_of_digits=args.digits,
        max_moment_order=args.max_moment,
        max_legendre_degree=args.max_legendre,
        exact_mu_dot=mu_dot,
        exact_legendre=legendre,
        seed=args.seed,
    )

    tangent_cdf_common_random_numbers(
        data_dir=data_dir,
        figure_dir=figure_dir,
        samples=args.cdf_samples,
        chunk_size=args.chunk_size,
        number_of_digits=args.digits,
        q_step=args.q_step,
        seed=args.seed,
    )

    plot_legendre_coefficients(figure_dir, legendre)
    write_readme(output_root, args)


if __name__ == "__main__":
    main()
