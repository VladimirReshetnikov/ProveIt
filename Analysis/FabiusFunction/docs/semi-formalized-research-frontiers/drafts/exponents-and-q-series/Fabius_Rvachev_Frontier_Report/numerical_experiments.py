#!/usr/bin/env python3
"""Reproducible numerical experiments for the Fabius/Rvachev frontier report.

For real |q|<1, the geometric-uniform random variable is

    X_q = (1-q) * sum_{n>=0} q**n U_n,

where U_n are independent Uniform(0,1) variables.  The experiments verify:

1. the negative/positive affine duality by an exact reflected-digit coupling;
2. finite reciprocal-base duality q <-> 1/q by exact digit reversal;
3. the Gaussian boundary |q| -> 1;
4. the central plateau for |q|<1/2 and its affine transport.

The script uses a fixed seed.  Coupling errors should be at floating-point roundoff;
they are not statistical estimates.  All figures and CSV/LaTeX tables used in the
report are generated by this file.
"""

from __future__ import annotations

import csv
import math
from pathlib import Path
from typing import Iterable

import matplotlib.pyplot as plt
import numpy as np
from numpy.random import Generator
from scipy import stats

ROOT = Path(__file__).resolve().parent
FIG = ROOT / "figures"
FIG.mkdir(exist_ok=True)
SEED = 20260830


def truncation_length(q: float, tol: float = 1.0e-13) -> int:
    """Choose N so |1-q| |q|^N /(1-|q|) <= tol."""
    r = abs(q)
    if not 0.0 <= r < 1.0:
        raise ValueError("truncation_length requires |q|<1")
    if r == 0.0:
        return 1
    rhs = tol * (1.0 - r) / abs(1.0 - q)
    n = math.ceil(math.log(rhs) / math.log(r))
    return max(1, n + 2)


def sample_xq(q: float, size: int, rng: Generator, tol: float = 1.0e-13) -> np.ndarray:
    """Sample the truncated series without allocating a size-by-N matrix."""
    n_terms = truncation_length(q, tol)
    out = np.zeros(size, dtype=np.float64)
    weight = 1.0 - q
    for _ in range(n_terms):
        out += weight * rng.random(size)
        weight *= q
    return out


def coupled_negative_positive(
    r: float, size: int, rng: Generator, n_terms: int | None = None
) -> tuple[np.ndarray, np.ndarray]:
    """Exactly couple finite centered sums for X_r and X_-r.

    If V_n=U_n-1/2, use V_n^- = (-1)^n V_n on the negative side.  Then the
    alternating sign from (-r)^n cancels digitwise, giving the affine identity
    exactly at the chosen truncation.
    """
    if not 0.0 < r < 1.0:
        raise ValueError("r must lie in (0,1)")
    if n_terms is None:
        n_terms = truncation_length(r)

    centered_pos = np.zeros(size, dtype=np.float64)
    centered_neg = np.zeros(size, dtype=np.float64)
    pos_weight = 1.0 - r
    neg_weight = 1.0 + r
    sign = 1.0
    for _ in range(n_terms):
        v = rng.random(size) - 0.5
        centered_pos += pos_weight * v
        centered_neg += neg_weight * sign * (sign * v)
        pos_weight *= r
        neg_weight *= r
        sign *= -1.0
    return 0.5 + centered_pos, 0.5 + centered_neg


def finite_normalized_sum(q: float, digits: np.ndarray) -> np.ndarray:
    """Evaluate X_{q,N}=sum q^n U_n/[N]_q for digit rows."""
    if q in (1.0, -1.0):
        raise ValueError("q=1 and q=-1 need separate limiting conventions")
    n = digits.shape[1]
    weights = (1.0 - q) * q ** np.arange(n, dtype=np.float64) / (1.0 - q**n)
    return digits @ weights


def exact_variance(q: float) -> float:
    """Variance of X_q for real |q|<1."""
    return (1.0 - q) / (12.0 * (1.0 + q))


def standardized_fourth_cumulant(r: float) -> float:
    """Exact excess kurtosis of standardized X_{+/-r}."""
    return -(6.0 / 5.0) * (1.0 - r * r) / (1.0 + r * r)


def save_negative_duality_figure(rng: Generator) -> None:
    size = 350_000
    xp = sample_xq(0.5, size, rng)
    xn = sample_xq(-0.5, size, rng)
    transformed = 0.5 + 3.0 * (xp - 0.5)

    plt.figure(figsize=(8.4, 4.8))
    bins = np.linspace(-1.0, 2.0, 241)
    plt.hist(xn, bins=bins, density=True, histtype="step", linewidth=1.25,
             label=r"direct $X_{-1/2}$ sample")
    plt.hist(transformed, bins=bins, density=True, histtype="step", linewidth=1.25,
             label=r"$3X_{1/2}-1$")
    plt.xlabel(r"$x$")
    plt.ylabel("density")
    plt.title("Negative dyadic law: direct and affine-transformed samples")
    plt.legend()
    plt.tight_layout()
    plt.savefig(FIG / "negative_duality_histogram.pdf")
    plt.savefig(FIG / "negative_duality_histogram.png", dpi=180)
    plt.close()


def save_plateau_figure(rng: Generator) -> None:
    r = 0.30
    size = 650_000
    xp = sample_xq(r, size, rng)
    xn = sample_xq(-r, size, rng)

    pos_left, pos_right, pos_height = r, 1.0 - r, 1.0 / (1.0 - r)
    neg_left = r * r / (1.0 - r)
    neg_right = 1.0 - neg_left
    neg_height = 1.0 / (1.0 + r)

    plt.figure(figsize=(8.4, 4.8))
    bins = np.linspace(-r / (1.0 - r), 1.0 / (1.0 - r), 300)
    plt.hist(xp, bins=bins, density=True, histtype="step", linewidth=1.2,
             label=r"$q=0.30$")
    plt.hist(xn, bins=bins, density=True, histtype="step", linewidth=1.2,
             label=r"$q=-0.30$")
    plt.plot([pos_left, pos_right], [pos_height, pos_height], linewidth=2.0,
             label="exact positive plateau")
    plt.plot([neg_left, neg_right], [neg_height, neg_height], linewidth=2.0,
             label="exact negative plateau")
    plt.xlabel(r"$x$")
    plt.ylabel("density")
    plt.title("Dominant-digit plateaux and affine transport")
    plt.legend()
    plt.tight_layout()
    plt.savefig(FIG / "plateau_phase.pdf")
    plt.savefig(FIG / "plateau_phase.png", dpi=180)
    plt.close()


def save_gaussian_figure(rng: Generator) -> list[dict[str, float]]:
    rs = (0.50, 0.80, 0.95, 0.98)
    sizes = {0.50: 260_000, 0.80: 230_000, 0.95: 180_000, 0.98: 120_000}
    table: list[dict[str, float]] = []

    plt.figure(figsize=(8.4, 4.8))
    grid = np.linspace(-4.0, 4.0, 500)
    plt.plot(grid, stats.norm.pdf(grid), linewidth=2.0, label="standard normal")

    for r in rs:
        sample = sample_xq(r, sizes[r], rng, tol=2.0e-12)
        z = (sample - 0.5) / math.sqrt(exact_variance(r))
        hist, edges = np.histogram(z, bins=260, range=(-4.0, 4.0), density=True)
        mids = 0.5 * (edges[:-1] + edges[1:])
        plt.plot(mids, hist, linewidth=0.9, label=fr"$r={r:.2f}$")

        ks = stats.kstest(z, "norm").statistic
        empirical_excess = float(stats.kurtosis(z, fisher=True, bias=False))
        exact_excess = standardized_fourth_cumulant(r)
        table.append({
            "r": r,
            "sample_size": sizes[r],
            "ks_to_normal": float(ks),
            "empirical_excess": empirical_excess,
            "exact_excess": exact_excess,
            "absolute_excess_error": abs(empirical_excess - exact_excess),
        })

    plt.xlabel(r"standardized coordinate $z$")
    plt.ylabel("density")
    plt.title(r"Gaussian boundary for $Z_r=(X_r-1/2)/\sigma_r$")
    plt.legend()
    plt.tight_layout()
    plt.savefig(FIG / "gaussian_boundary.pdf")
    plt.savefig(FIG / "gaussian_boundary.png", dpi=180)
    plt.close()
    return table


def write_csv(path: Path, rows: Iterable[dict[str, float]], fieldnames: list[str]) -> None:
    with path.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def write_latex_tables(
    coupling_rows: list[dict[str, float]],
    reciprocal_rows: list[dict[str, float]],
    gaussian_rows: list[dict[str, float]],
) -> None:
    lines: list[str] = ["% Generated by numerical_experiments.py; do not edit by hand.\n"]

    lines += [
        "\\begin{table}[htbp]\n\\centering\n",
        "\\caption{Digit-reflection coupling for the negative/positive affine duality.}\n",
        "\\label{tab:negative-coupling}\n",
        "\\begin{tabular}{@{}rrrr@{}}\\toprule\n",
        "$r$ & samples & terms & maximum coupling error \\\\ \\midrule\n",
    ]
    for row in coupling_rows:
        lines.append(f"{row['r']:.2f} & {int(row['sample_size'])} & {int(row['terms'])} & {row['max_error']:.3e} \\\\\n")
    lines += ["\\bottomrule\\end{tabular}\n\\end{table}\n\n"]

    lines += [
        "\\begin{table}[htbp]\n\\centering\n",
        "\\caption{Reversal coupling for finite reciprocal-base duality.}\n",
        "\\label{tab:reciprocal-coupling}\n",
        "\\begin{tabular}{@{}rrrr@{}}\\toprule\n",
        "$q$ & $N$ & samples & maximum coupling error \\\\ \\midrule\n",
    ]
    for row in reciprocal_rows:
        lines.append(f"{row['q']:.0f} & {int(row['N'])} & {int(row['sample_size'])} & {row['max_error']:.3e} \\\\\n")
    lines += ["\\bottomrule\\end{tabular}\n\\end{table}\n\n"]

    lines += [
        "\\begin{table}[htbp]\n\\centering\n",
        "\\caption{Standardized geometric-uniform laws approaching the Gaussian boundary.}\n",
        "\\label{tab:gaussian-numerics}\n",
        "\\begin{tabular}{@{}rrrrr@{}}\\toprule\n",
        "$r$ & samples & KS distance & empirical excess & exact excess \\\\ \\midrule\n",
    ]
    for row in gaussian_rows:
        lines.append(
            f"{row['r']:.2f} & {int(row['sample_size'])} & {row['ks_to_normal']:.4f} & "
            f"{row['empirical_excess']:.5f} & {row['exact_excess']:.5f} \\\\\n"
        )
    lines += ["\\bottomrule\\end{tabular}\n\\end{table}\n"]
    (ROOT / "numerical_results.tex").write_text("".join(lines), encoding="utf-8")


def main() -> None:
    rng = np.random.default_rng(SEED)

    coupling_rows: list[dict[str, float]] = []
    for r in (0.20, 0.50, 0.80):
        n_terms = truncation_length(r)
        xp, xn = coupled_negative_positive(r, 40_000, rng, n_terms=n_terms)
        c = (1.0 + r) / (1.0 - r)
        error = np.max(np.abs((xn - 0.5) - c * (xp - 0.5)))
        coupling_rows.append({"r": r, "sample_size": 40_000, "terms": n_terms,
                              "max_error": float(error)})

    reciprocal_rows: list[dict[str, float]] = []
    n = 14
    digits = rng.random((35_000, n))
    for q in (2.0, -2.0, 4.0, -4.0):
        lhs = finite_normalized_sum(q, digits)
        rhs = finite_normalized_sum(1.0 / q, digits[:, ::-1])
        reciprocal_rows.append({"q": q, "N": n, "sample_size": digits.shape[0],
                                "max_error": float(np.max(np.abs(lhs - rhs)))})

    save_negative_duality_figure(rng)
    save_plateau_figure(rng)
    gaussian_rows = save_gaussian_figure(rng)

    write_csv(ROOT / "negative_coupling.csv", coupling_rows,
              ["r", "sample_size", "terms", "max_error"])
    write_csv(ROOT / "reciprocal_coupling.csv", reciprocal_rows,
              ["q", "N", "sample_size", "max_error"])
    write_csv(ROOT / "gaussian_convergence.csv", gaussian_rows,
              ["r", "sample_size", "ks_to_normal", "empirical_excess", "exact_excess",
               "absolute_excess_error"])
    write_latex_tables(coupling_rows, reciprocal_rows, gaussian_rows)

    print("Generated figures and tables in", ROOT)
    for name, rows in (("negative coupling", coupling_rows),
                       ("reciprocal coupling", reciprocal_rows),
                       ("Gaussian", gaussian_rows)):
        print(name)
        for row in rows:
            print(row)


if __name__ == "__main__":
    main()
