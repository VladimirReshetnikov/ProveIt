#!/usr/bin/env python3
"""Numerical and symbolic checks for the multivariate Fabius--Rvachev report.

The report studies the common-digit geometric-uniform process

    X(q) = sum_{n>=0} (1-q) q^n U_n,

where the same independent U_n ~ Uniform[0,1] are used for every parameter q.
For distinct parameters q_1,...,q_d in (0,1), the support of
(X(q_1),...,X(q_d)) is the infinite zonotope generated by

    v_n = ((1-q_1)q_1^n, ..., (1-q_d)q_d^n).

This script does not prove any theorem.  It reproducibly checks the exact
closed forms derived in the report, produces convergence tables, and draws
figures used in the PDF.  Exact formulas are evaluated with SymPy whenever
possible; floating-point computations are explicitly identified as checks.

Outputs (under --output-root/generated):
  * volume_convergence.csv
  * gram_volume_identity.csv
  * jet_volume_convergence.csv
  * monte_carlo_covariance.csv
  * legendre_coefficients.tex
  * euler_hankel_determinants.csv
  * gaussianization_cumulants.csv
  * exact_summary.txt
  * support_zonotope_q050_q080.pdf/.png
  * volume_convergence.pdf/.png
  * hyperbolic_geometry.pdf/.png
  * jet_volume_convergence.pdf/.png
  * gaussianization_cumulants.pdf/.png

The default random seed and all numerical parameters are recorded in
exact_summary.txt and in the CSV files.
"""

from __future__ import annotations

import argparse
import csv
import itertools
import math
from pathlib import Path
from typing import Iterable, Sequence

import matplotlib.pyplot as plt
import numpy as np
import sympy as sp


def exact_zonoid_volume(qs: Sequence[float]) -> float:
    """Return the exact support volume for ordered positive parameters.

    The Schur--Littlewood product used by the report requires
    0 < q_1 < ... < q_d < 1.  Signed parameters belong to a different
    orientation chamber and are intentionally rejected here.
    """
    if not all(0.0 < q < 1.0 for q in qs):
        raise ValueError("exact volume formula requires every q in (0, 1)")
    if any(qi >= qj for qi, qj in zip(qs, qs[1:])):
        raise ValueError("parameters must be strictly increasing")
    value = 1.0
    for i, qi in enumerate(qs):
        for qj in qs[i + 1 :]:
            value *= (qj - qi) / (1.0 - qi * qj)
    return value


def generator_vector(n: int, qs: Sequence[float]) -> np.ndarray:
    """The n-th zonotope generator v_n."""
    return np.array([(1.0 - q) * q**n for q in qs], dtype=float)


def truncated_zonoid_volume(qs: Sequence[float], max_index: int) -> float:
    """Finite-zonotope volume from the sum of absolute maximal minors.

    The truncation uses generators v_0,...,v_max_index.  For the increasing
    positive parameter lists used here, all generalized Vandermonde minors
    have the same sign.  We retain abs(det) to make the numerical routine
    robust to harmless row/column orientation choices.
    """
    d = len(qs)
    total = 0.0
    for indices in itertools.combinations(range(max_index + 1), d):
        matrix = np.column_stack([generator_vector(n, qs) for n in indices])
        total += abs(float(np.linalg.det(matrix)))
    return total


def correlation_matrix(qs: Sequence[float]) -> np.ndarray:
    """Correlation matrix of the standardized common-digit process."""
    q = np.asarray(qs, dtype=float)
    return np.sqrt(1.0 - q[:, None] ** 2) * np.sqrt(1.0 - q[None, :] ** 2) / (
        1.0 - q[:, None] * q[None, :]
    )


def coefficient_covariance(q: float, r: float, max_index: int) -> float:
    """Truncated coefficient-sum covariance of X(q), X(r)."""
    n = np.arange(max_index + 1, dtype=float)
    return float(
        np.sum((1.0 - q) * q**n * (1.0 - r) * r**n) / 12.0
    )


def exact_covariance(q: float, r: float) -> float:
    return (1.0 - q) * (1.0 - r) / (12.0 * (1.0 - q * r))


def pair_zonotope_vertices(q: float, r: float, max_index: int) -> np.ndarray:
    """Boundary vertices of the finite pair-zonotope.

    For 0<q<r<1 the generator slopes increase with n.  The positively oriented
    boundary first accumulates the generators in increasing slope order and
    then returns using their negatives.  The resulting polygon has exactly
    2(max_index+2) listed vertices including the repeated initial endpoint.
    """
    vectors = [generator_vector(n, (q, r)) for n in range(max_index + 1)]
    vertices = [np.zeros(2)]
    current = np.zeros(2)
    for vector in vectors:
        current = current + vector
        vertices.append(current.copy())
    for vector in vectors:
        current = current - vector
        vertices.append(current.copy())
    return np.asarray(vertices)


def polygon_area(vertices: np.ndarray) -> float:
    x = vertices[:, 0]
    y = vertices[:, 1]
    return 0.5 * abs(float(np.dot(x, np.roll(y, -1)) - np.dot(y, np.roll(x, -1))))


def normalized_weight_derivative(n: int, order: int, q: float) -> float:
    """(1/order!) d^order/dq^order [(1-q)q^n], evaluated stably.

    Since (1-q)q^n = q^n-q^(n+1), the derivative is a difference of falling
    factorials.  Terms with n<order are interpreted as zero.
    """

    def term(power: int) -> float:
        if power < order:
            return 0.0
        return math.comb(power, order) * q ** (power - order)

    return term(n) - term(n + 1)


def truncated_jet_volume(q: float, dimension: int, max_index: int) -> float:
    """Volume of the truncated support of the divided-derivative jet.

    Coordinates are X(q), X'(q), X''(q)/2!, ... .
    """
    total = 0.0
    for indices in itertools.combinations(range(max_index + 1), dimension):
        matrix = np.array(
            [
                [normalized_weight_derivative(n, order, q) for n in indices]
                for order in range(dimension)
            ],
            dtype=float,
        )
        total += abs(float(np.linalg.det(matrix)))
    return total


def exact_jet_volume(q: float, dimension: int) -> float:
    """Exact positive-chamber volume of the divided-derivative jet."""
    if not 0.0 < q < 1.0:
        raise ValueError("exact jet-volume formula requires q in (0, 1)")
    if dimension < 1:
        raise ValueError("dimension must be positive")
    return (1.0 - q * q) ** (-(dimension * (dimension - 1) // 2))


def write_volume_convergence(output: Path) -> None:
    cases = [
        ("d2", (0.5, 0.8), (5, 10, 15, 20, 25, 30, 35, 40)),
        ("d3", (0.2, 0.5, 0.8), (5, 8, 11, 14, 17, 20, 25, 30, 35, 40)),
        ("d4", (0.2, 0.4, 0.6, 0.8), (5, 7, 9, 11, 13, 15, 18, 20, 22)),
    ]
    rows: list[dict[str, object]] = []
    for label, qs, indices in cases:
        exact = exact_zonoid_volume(qs)
        for maximum in indices:
            approximation = truncated_zonoid_volume(qs, maximum)
            rows.append(
                {
                    "case": label,
                    "parameters": ";".join(f"{q:.12g}" for q in qs),
                    "max_index": maximum,
                    "truncated_volume": f"{approximation:.17g}",
                    "exact_volume": f"{exact:.17g}",
                    "absolute_error": f"{abs(exact-approximation):.17g}",
                    "relative_error": f"{abs(exact-approximation)/exact:.17g}",
                }
            )
    with (output / "volume_convergence.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


def write_gram_identity(output: Path) -> None:
    parameter_sets = [
        (0.10, 0.35),
        (0.50, 0.80),
        (0.15, 0.45, 0.75),
        (0.20, 0.40, 0.60, 0.80),
        (0.08, 0.23, 0.41, 0.67, 0.86),
    ]
    rows = []
    for qs in parameter_sets:
        volume = exact_zonoid_volume(qs)
        determinant = float(np.linalg.det(correlation_matrix(qs)))
        rows.append(
            {
                "parameters": ";".join(f"{q:.12g}" for q in qs),
                "dimension": len(qs),
                "volume": f"{volume:.17g}",
                "det_correlation": f"{determinant:.17g}",
                "volume_squared": f"{volume*volume:.17g}",
                "difference": f"{determinant-volume*volume:.17g}",
            }
        )
    with (output / "gram_volume_identity.csv").open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader()
        writer.writerows(rows)


