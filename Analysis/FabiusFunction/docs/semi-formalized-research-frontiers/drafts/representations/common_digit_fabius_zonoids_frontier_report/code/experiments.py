def write_summary(output: Path, seed: int, samples: int, digits: int) -> None:
    q, r = 0.5, 0.8
    u, v = math.atanh(q), math.atanh(r)
    area = exact_zonoid_volume((q, r))
    correlation = math.sqrt((1-q*q)*(1-r*r))/(1-q*r)
    lines = [
        "Reproducibility summary for experiments.py",
        "==============================================",
        f"NumPy version: {np.__version__}",
        f"SymPy version: {sp.__version__}",
        f"Monte Carlo seed: {seed}",
        f"Monte Carlo samples: {samples}",
        f"Retained geometric digits: {digits}",
        "",
        "Representative exact identities checked:",
        f"q={q}, r={r}",
        f"u=atanh(q)={u:.17g}",
        f"v=atanh(r)={v:.17g}",
        f"support area=(r-q)/(1-qr)={area:.17g}",
        f"tanh(v-u)={math.tanh(v-u):.17g}",
        f"correlation=sech(v-u)={correlation:.17g}",
        f"area^2+correlation^2={area*area+correlation*correlation:.17g}",
        "",
        "All Monte Carlo values are checks only and are not used in proofs.",
        "All plots use Matplotlib defaults and contain no manually selected colors.",
    ]
    (output / "exact_summary.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")


