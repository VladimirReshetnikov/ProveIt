#!/usr/bin/env python3
"""Exact symbolic coefficient generation for the article's two expansions.

Only rational arithmetic and formal polynomial identities are used here.
The analytic remainder theorems are proved in article.tex, not by this script.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import sympy as sp


def saddle_coefficients(order: int = 3) -> tuple[sp.Symbol, dict[int, sp.Symbol], list[sp.Expr]]:
    """Return rho, b_r symbols, and C_0,...,C_order.

    b_r = (r-1)! + kappa_r/n, rho = variance/n.
    Includes the Stirling normalization of the gamma smoothing kernel.
    """
    if not 0 <= order <= 5:
        raise ValueError("symbolic order must be between 0 and 5")
    z, rho = sp.symbols("z rho")
    b = {r: sp.Symbol(f"b{r}") for r in range(3, 2 * order + 3)}
    degree = 2 * order
    e: dict[int, sp.Expr] = {}
    for p in range(1, degree + 1):
        e[p] = z**p / sp.Integer(p) + b[p + 2] * z**(p + 2) / sp.factorial(p + 2)
    for k in range(1, order + 2):
        p = 4 * k - 2
        if p <= degree:
            e[p] += sp.bernoulli(2 * k) / (2 * k * (2 * k - 1))
    q = [sp.Integer(1)]
    for m in range(1, degree + 1):
        q.append(sp.expand(sum(p * e[p] * q[m-p] for p in range(1, m+1)) / m))
    c = []
    for j in range(order + 1):
        result = sp.Integer(0)
        for (power,), coefficient in sp.Poly(q[2*j], z).terms():
            if power % 2 == 0:
                r = power // 2
                contraction = (-1)**r * sp.factorial2(2*r-1) / (1 + rho)**r
                result += coefficient * contraction
        c.append(sp.factor(result))
    return rho, b, c


def laplace_polynomials(order: int = 5) -> tuple[sp.Symbol, list[sp.Expr]]:
    if order < 0:
        raise ValueError("order must be nonnegative")
    y = sp.Symbol("y")
    p = [sp.Integer(1)]
    for j in range(1, order+1):
        p.append(sp.expand(-sum(sp.Rational(r, r+1) * y**(r+1) * p[j-r]
                                for r in range(1, j+1)) / j))
    return y, p


def write_outputs(directory: Path, order: int = 3) -> None:
    directory.mkdir(parents=True, exist_ok=True)
    rho, b, c = saddle_coefficients(order)
    y, p = laplace_polynomials(5)
    payload = {
        "normalization": "rho=v/n; b_r=(r-1)!+kappa_r/n; expansion=sum C_j/n^j",
        "saddle": {str(j): sp.sstr(value) for j, value in enumerate(c)},
        "laplace": {str(j): sp.sstr(value) for j, value in enumerate(p)},
    }
    (directory / "coefficients.json").write_text(json.dumps(payload, indent=2) + "\n")
    # Do not dump large multivariate rational functions into the article body.
    tex = "% Automatically generated by code/coefficients.py\n"
    tex += "\\begin{align*}\n" + "\\\\\n".join(
        f"P_{{{j}}}(y)&={sp.latex(value)}" for j, value in enumerate(p[:5]))
    tex += "\n\\end{align*}\n"
    (directory / "laplace_coefficients.tex").write_text(tex)


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path, default=Path(__file__).resolve().parents[1] / "data")
    parser.add_argument("--order", type=int, default=3)
    args = parser.parse_args()
    write_outputs(args.out, args.order)
