#!/usr/bin/env python3
"""Deterministic experiments for the Fabius--Rvachev integral/frontier report.

The program checks only statements that are proved analytically in the report.  It
uses no Monte Carlo sampling and no network access.  The main numerical object is
Rvachev's up-function, reconstructed on a period-four FFT grid from its exact
Fourier transform

    up_hat(xi) = product_{k>=0} sinc(pi*xi/2**k).

The support is [-1,1], so period four keeps periodic copies disjoint.  From this
grid the program builds the Fabius function F(x)=up(x-1) on [0,1] and a monotone
numerical inverse Q=F^{-1}.  It then checks:

1. exact centered moments generated by the Bernoulli/moment recurrence;
2. exterior moment series for the fractional Laplacian and Riesz potential of up;
3. the logarithmic Cauchy-transform fixed-point equation and its resolvent hierarchy;
4. the first digamma correction for fractional Volterra integrals of Q;
5. the leading/corrected endpoint law for the Caputo/Riemann--Liouville derivative
   of Q of order 0<sigma<1.

Outputs:
    new_numerical_results.tex   tables included by the LaTeX report
    numerical_results.txt      human-readable ledger
    numerical_results.json     machine-readable values and parameters

Dependencies: Python 3.10+, NumPy, SciPy, and mpmath.
"""

from __future__ import annotations

import json
import math
from dataclasses import asdict, dataclass
from fractions import Fraction
from math import comb
from pathlib import Path
from typing import Callable

import mpmath as mp
import numpy as np
from scipy.integrate import simpson
from scipy.interpolate import PchipInterpolator
from scipy.special import roots_jacobi

HERE = Path(__file__).resolve().parent


# ---------------------------------------------------------------------------
# Exact centered moments
# ---------------------------------------------------------------------------


def exact_centered_even_moments(max_index: int) -> list[Fraction]:
    """Return mu_{2j}=int x^(2j) up(x) dx for 0<=j<=max_index.

    The recurrence is the exact one used in the ProveIt Fabius development:

      (2j+1)(2^(2j)-1) mu_{2j}
          = sum_{k<j} binom(2j+1,2k) mu_{2k}.

    Hence every entry is rational and no floating-point arithmetic is used here.
    """

    if max_index < 0:
        raise ValueError("max_index must be nonnegative")
    values = [Fraction(1)]
    for j in range(1, max_index + 1):
        numerator = sum(
            Fraction(comb(2 * j + 1, 2 * k)) * values[k]
            for k in range(j)
        )
        denominator = (2 * j + 1) * (2 ** (2 * j) - 1)
        values.append(numerator / denominator)
    return values


# ---------------------------------------------------------------------------
# FFT reconstruction of up and numerical F/Q
# ---------------------------------------------------------------------------


def build_up_fft(
    n_grid: int = 2**18,
    period: float = 4.0,
    n_product_factors: int = 38,
) -> tuple[np.ndarray, np.ndarray]:
    """Return up on the portion of a period lying in [-1,1].

    With Fourier convention f_hat(xi)=int f(x) exp(-2*pi*i*x*xi) dx,
    the k-th Fourier-series coefficient on a period of length L is f_hat(k/L)/L.
    NumPy's inverse FFT includes a 1/N factor, so the coefficient vector is scaled
    by N/L before inversion.
    """

    if n_grid <= 0 or n_grid & (n_grid - 1):
        raise ValueError("n_grid must be a positive power of two")
    if period <= 2.0:
        raise ValueError("period must exceed the support diameter")

    dx = period / n_grid
    frequencies = np.fft.fftfreq(n_grid, d=dx)
    transform = np.ones(n_grid, dtype=float)
    for k in range(n_product_factors):
        # np.sinc(z)=sin(pi*z)/(pi*z), matching the normalized product.
        transform *= np.sinc(frequencies / (2**k))

    coefficients = (n_grid / period) * transform
    periodic_values = np.fft.ifft(coefficients).real
    centered_values = np.fft.fftshift(periodic_values)
    centered_grid = (np.arange(n_grid) - n_grid // 2) * dx
    mask = (centered_grid >= -1.0) & (centered_grid <= 1.0)
    x = centered_grid[mask]
    up = centered_values[mask]

    # Remove FFT noise only at a level far below every reported value.
    up[np.abs(up) < 2e-14] = 0.0
    up = np.maximum(up, 0.0)
    up[0] = 0.0
    up[-1] = 0.0

    # A tiny renormalization compensates for discretization of the integral.
    mass = float(simpson(up, x=x))
    up /= mass
    return x, up


@dataclass
class NumericalFabius:
    x_up: np.ndarray
    up: np.ndarray
    x_f: np.ndarray
    f: np.ndarray
    up_interp: PchipInterpolator
    f_interp: PchipInterpolator
    q: Callable[[np.ndarray | float], np.ndarray]


def build_numerical_fabius() -> NumericalFabius:
    """Build monotone interpolants for up, F, and Q=F^{-1}."""

    x_up, up = build_up_fft()
    midpoint = (len(x_up) - 1) // 2
    x_f = x_up[: midpoint + 1] + 1.0
    f = up[: midpoint + 1].copy()  # F(x)=up(x-1) on [0,1]
    f[0] = 0.0
    f[-1] = 1.0
    f = np.maximum.accumulate(np.clip(f, 0.0, 1.0))

    up_interp = PchipInterpolator(x_up, up, extrapolate=False)
    f_interp = PchipInterpolator(x_f, f, extrapolate=False)

    unique_f, indices = np.unique(f, return_index=True)
    unique_x = x_f[indices]
    if unique_f[0] != 0.0:
        unique_f = np.insert(unique_f, 0, 0.0)
        unique_x = np.insert(unique_x, 0, 0.0)
    if unique_f[-1] != 1.0:
        unique_f = np.append(unique_f, 1.0)
        unique_x = np.append(unique_x, 1.0)

    def inverse(values: np.ndarray | float) -> np.ndarray:
        arr = np.asarray(values, dtype=float)
        return np.interp(arr, unique_f, unique_x)

    return NumericalFabius(x_up, up, x_f, f, up_interp, f_interp, inverse)


# ---------------------------------------------------------------------------
# Nonlocal operators and transform fixed points
# ---------------------------------------------------------------------------


def fractional_laplacian_constant(s: float) -> float:
    """C_{1,s} for (-Delta)^s with kernel |x-y|^{-1-2s}."""

    return float(
        4.0**s
        * mp.gamma(0.5 + s)
        / (mp.sqrt(mp.pi) * abs(mp.gamma(-s)))
    )


def riesz_constant(alpha: float) -> float:
    """One-dimensional Riesz-potential constant with multiplier |xi|^{-alpha}."""

    return float(
        mp.gamma((1.0 - alpha) / 2.0)
        / (2.0**alpha * mp.sqrt(mp.pi) * mp.gamma(alpha / 2.0))
    )


def rising(a: float, n: int) -> float:
    return float(mp.rf(a, n))


def exterior_fractional_laplacian_series(
    radius: float,
    s: float,
    moments: list[Fraction],
    terms: int,
) -> float:
    """Moment expansion of (-Delta)^s up(x) for |x|=radius>1."""

    total = 0.0
    for j in range(min(terms, len(moments))):
        mu = float(moments[j])
        total += (
            rising(1.0 + 2.0 * s, 2 * j)
            / math.factorial(2 * j)
            * mu
            / radius ** (2 * j)
        )
    return -fractional_laplacian_constant(s) * total / radius ** (1.0 + 2.0 * s)


def exterior_riesz_series(
    radius: float,
    alpha: float,
    moments: list[Fraction],
    terms: int,
) -> float:
    """Moment expansion of I_alpha up(x) for |x|=radius>1."""

    total = 0.0
    for j in range(min(terms, len(moments))):
        mu = float(moments[j])
        total += (
            rising(1.0 - alpha, 2 * j)
            / math.factorial(2 * j)
            * mu
            / radius ** (2 * j)
        )
    return riesz_constant(alpha) * radius ** (alpha - 1.0) * total


def cauchy_transform(model: NumericalFabius, z: complex, power: int = 1) -> complex:
    """R_power(z)=int up(x)/(z-x)^power dx."""

    values = model.up.astype(np.complex128) / (z - model.x_up) ** power
    return complex(simpson(values, x=model.x_up))


# ---------------------------------------------------------------------------
# Fractional endpoint calculus for Q
# ---------------------------------------------------------------------------


def gauss_jacobi_integral_on_unit(
    func: Callable[[np.ndarray], np.ndarray],
    exponent_at_one: float,
    nodes: int = 180,
) -> float:
    """Integrate (1-u)^a func(u) over [0,1] by Gauss--Jacobi quadrature."""

    if exponent_at_one <= -1.0:
        raise ValueError("Jacobi exponent must exceed -1")
    x, w = roots_jacobi(nodes, exponent_at_one, 0.0)
    u = (x + 1.0) / 2.0
    # Mapping [-1,1] to [0,1] contributes 2^{-(a+1)}.
    return float(2.0 ** (-(exponent_at_one + 1.0)) * np.dot(w, func(u)))


def quantile_elasticity(model: NumericalFabius, y: float) -> tuple[float, float]:
    """Return Q(y) and eta(y)=y Q'(y)/Q(y)."""

    q = float(model.q(y))
    density = 2.0 * float(model.up_interp(2.0 * q - 1.0))  # F'(q)
    if q <= 0.0 or density <= 0.0:
        raise FloatingPointError("quantile or density underflowed")
    eta = y / (q * density)
    return q, eta


def fractional_quantile_integral(
    model: NumericalFabius,
    y: float,
    alpha: float,
    beta: float,
) -> float:
    """Compute I_{0+}^alpha(Q^beta)(y) by weighted Gaussian quadrature."""

    integral = gauss_jacobi_integral_on_unit(
        lambda u: np.asarray(model.q(y * u), dtype=float) ** beta,
        exponent_at_one=alpha - 1.0,
    )
    return y**alpha * integral / math.gamma(alpha)


def caputo_quantile_derivative(
    model: NumericalFabius,
    y: float,
    sigma: float,
    beta: float,
) -> float:
    """Compute D_{0+}^sigma(Q^beta)(y) by differentiating I^{1-sigma}.

    For Q(0)=0 the Riemann--Liouville and Caputo derivatives coincide.
    Direct quadrature of Q' is numerically ill-conditioned because F' is extremely
    flat near the endpoint.  A symmetric five-point derivative of the much better
    conditioned fractional integral is substantially more stable.
    """

    gamma = 1.0 - sigma
    h = 2.0e-3 * y
    if y - 2.0 * h <= 0.0:
        raise ValueError("finite-difference step crossed the endpoint")

    def primitive(v: float) -> float:
        return fractional_quantile_integral(model, v, gamma, beta)

    return (
        -primitive(y + 2.0 * h)
        + 8.0 * primitive(y + h)
        - 8.0 * primitive(y - h)
        + primitive(y - 2.0 * h)
    ) / (12.0 * h)


# ---------------------------------------------------------------------------
# Main experiment and output
# ---------------------------------------------------------------------------


def fmt(value: float | complex, digits: int = 8) -> str:
    if isinstance(value, complex):
        return f"{value.real:.{digits}e}{value.imag:+.{digits}e}i"
    return f"{value:.{digits}e}"


def main() -> None:
    mp.mp.dps = 60
    model = build_numerical_fabius()
    moments = exact_centered_even_moments(18)

    results: dict[str, object] = {
        "parameters": {
            "fft_grid": 2**18,
            "fft_period": 4.0,
            "product_factors": 38,
            "jacobi_nodes_integral": 180,
            "jacobi_nodes_derivative": 220,
        },
        "moments": [
            {"j": j, "mu_2j": str(value), "decimal": float(value)}
            for j, value in enumerate(moments[:8])
        ],
    }

    # Exterior nonlocal-operator checks.
    exterior_rows: list[dict[str, float]] = []
    for s in (0.25, 0.50, 0.75):
        c = fractional_laplacian_constant(s)
        for radius in (1.20, 1.50, 2.00):
            direct = -c * float(
                simpson(
                    model.up / (radius - model.x_up) ** (1.0 + 2.0 * s),
                    x=model.x_up,
                )
            )
            series = exterior_fractional_laplacian_series(
                radius, s, moments, terms=len(moments)
            )
            exterior_rows.append(
                {
                    "operator": "fractional_laplacian",
                    "parameter": s,
                    "radius": radius,
                    "direct": direct,
                    "series": series,
                    "abs_error": abs(direct - series),
                }
            )

    riesz_rows: list[dict[str, float]] = []
    for alpha in (0.25, 0.50, 0.75):
        c = riesz_constant(alpha)
        for radius in (1.20, 1.50, 2.00):
            direct = c * float(
                simpson(
                    model.up * (radius - model.x_up) ** (alpha - 1.0),
                    x=model.x_up,
                )
            )
            series = exterior_riesz_series(radius, alpha, moments, len(moments))
            riesz_rows.append(
                {
                    "operator": "riesz_potential",
                    "parameter": alpha,
                    "radius": radius,
                    "direct": direct,
                    "series": series,
                    "abs_error": abs(direct - series),
                }
            )

    results["fractional_laplacian"] = exterior_rows
    results["riesz_potential"] = riesz_rows

    # Cauchy fixed point and resolvent hierarchy.
    z = 1.35 + 0.60j
    c_z = cauchy_transform(model, z)
    log_rhs = complex(
        simpson(
            model.up.astype(np.complex128)
            * np.log((2.0 * z - model.x_up + 1.0) / (2.0 * z - model.x_up - 1.0)),
            x=model.x_up,
        )
    )
    derivative_direct = -cauchy_transform(model, z, power=2)
    derivative_rhs = 2.0 * (
        cauchy_transform(model, 2.0 * z + 1.0)
        - cauchy_transform(model, 2.0 * z - 1.0)
    )
    hierarchy_rows: list[dict[str, object]] = []
    for m in (1, 2, 3):
        lhs = cauchy_transform(model, z, power=m + 1)
        rhs = (2.0**m / m) * (
            cauchy_transform(model, 2.0 * z - 1.0, power=m)
            - cauchy_transform(model, 2.0 * z + 1.0, power=m)
        )
        hierarchy_rows.append(
            {"m": m, "lhs": fmt(lhs), "rhs": fmt(rhs), "abs_error": abs(lhs - rhs)}
        )
    results["cauchy"] = {
        "z": fmt(z),
        "C": fmt(c_z),
        "log_rhs": fmt(log_rhs),
        "log_abs_error": abs(c_z - log_rhs),
        "derivative_abs_error": abs(derivative_direct - derivative_rhs),
        "hierarchy": hierarchy_rows,
    }

    # Fractional quantile endpoint checks.
    quantile_rows: list[dict[str, float]] = []
    alpha, beta = 0.65, 1.0
    harmonic_alpha = float(mp.digamma(alpha + 1.0) + mp.euler)
    for y in (1e-2, 3e-3, 1e-3, 3e-4, 1e-4):
        q, eta = quantile_elasticity(model, y)
        integral = fractional_quantile_integral(model, y, alpha, beta)
        normalized = integral * math.gamma(alpha + 1.0) / (y**alpha * q**beta)
        first = 1.0 - beta * harmonic_alpha * eta
        quantile_rows.append(
            {
                "y": y,
                "Q": q,
                "eta": eta,
                "normalized": normalized,
                "leading_error": abs(normalized - 1.0),
                "first_correction": first,
                "corrected_error": abs(normalized - first),
            }
        )
    results["fractional_quantile_integral"] = {
        "alpha": alpha,
        "beta": beta,
        "rows": quantile_rows,
    }

    derivative_rows: list[dict[str, float]] = []
    sigma, beta_d = 0.40, 1.0
    k_sigma = float(-mp.euler - mp.digamma(1.0 - sigma))
    for y in (1e-2, 3e-3, 1e-3, 3e-4, 1e-4):
        q, eta = quantile_elasticity(model, y)
        derivative = caputo_quantile_derivative(model, y, sigma, beta_d)
        normalized = (
            derivative * math.gamma(1.0 - sigma) * y**sigma / q**beta_d
        )
        first = 1.0 + beta_d * k_sigma * eta
        derivative_rows.append(
            {
                "y": y,
                "Q": q,
                "eta": eta,
                "normalized": normalized,
                "leading_error": abs(normalized - 1.0),
                "first_correction": first,
                "corrected_error": abs(normalized - first),
            }
        )
    results["fractional_quantile_derivative"] = {
        "sigma": sigma,
        "beta": beta_d,
        "rows": derivative_rows,
    }

    # Machine-readable JSON.
    (HERE / "numerical_results.json").write_text(
        json.dumps(results, indent=2), encoding="utf-8"
    )

    # Human-readable ledger.
    lines: list[str] = []
    lines.append("FABIUS--RVACHEV FRACTIONAL INTEGRAL/TRANSFORM CHECKS")
    lines.append("=" * 64)
    lines.append(f"FFT mass after normalization: {simpson(model.up, x=model.x_up):.16g}")
    lines.append(f"Grid spacing: {model.x_up[1]-model.x_up[0]:.16g}")
    lines.append("")
    lines.append("Exact centered moments")
    for row in results["moments"]:  # type: ignore[index]
        lines.append(f"  mu_{2*row['j']} = {row['mu_2j']}")
    lines.append("")
    lines.append("Fractional-Laplacian exterior series")
    for row in exterior_rows:
        lines.append(
            f"  s={row['parameter']:.2f}, r={row['radius']:.2f}: "
            f"direct={row['direct']:.12e}, series={row['series']:.12e}, "
            f"error={row['abs_error']:.3e}"
        )
    lines.append("")
    lines.append("Riesz-potential exterior series")
    for row in riesz_rows:
        lines.append(
            f"  alpha={row['parameter']:.2f}, r={row['radius']:.2f}: "
            f"direct={row['direct']:.12e}, series={row['series']:.12e}, "
            f"error={row['abs_error']:.3e}"
        )
    lines.append("")
    lines.append("Cauchy transform")
    lines.append(f"  log fixed-point residual: {abs(c_z-log_rhs):.3e}")
    lines.append(f"  derivative equation residual: {abs(derivative_direct-derivative_rhs):.3e}")
    for row in hierarchy_rows:
        lines.append(f"  hierarchy m={row['m']}: residual={row['abs_error']:.3e}")
    lines.append("")
    lines.append("Fractional quantile integral: normalized ratio and first correction")
    for row in quantile_rows:
        lines.append(
            f"  y={row['y']:.1e}: ratio={row['normalized']:.10f}, "
            f"1-Ha*eta={row['first_correction']:.10f}, "
            f"corrected error={row['corrected_error']:.3e}"
        )
    lines.append("")
    lines.append("Fractional quantile derivative: normalized ratio and first correction")
    for row in derivative_rows:
        lines.append(
            f"  y={row['y']:.1e}: ratio={row['normalized']:.10f}, "
            f"1+Ks*eta={row['first_correction']:.10f}, "
            f"corrected error={row['corrected_error']:.3e}"
        )
    (HERE / "numerical_results.txt").write_text("\n".join(lines) + "\n", encoding="utf-8")

    # LaTeX tables.  Keep them compact enough for A4 layout.
    tex: list[str] = []
    tex.append("% Generated by fractional_frontier_experiments.py")
    tex.append("\\begin{table}[htbp]")
    tex.append("\\centering\\small")
    tex.append("\\begin{tabular}{@{}rrrrr@{}}")
    tex.append("\\toprule")
    tex.append("$s$ & $|x|$ & direct $(-\\Delta)^s\\upf$ & moment series & absolute error\\\\")
    tex.append("\\midrule")
    for row in exterior_rows:
        tex.append(
            f"{row['parameter']:.2f} & {row['radius']:.2f} & "
            f"${row['direct']:.8e}$ & ${row['series']:.8e}$ & ${row['abs_error']:.2e}$\\\\"
        )
    tex.append("\\bottomrule\\end{tabular}")
    tex.append("\\caption{Exterior fractional-Laplacian series checked against direct FFT-grid quadrature.}")
    tex.append("\\label{tab:fraclap-check}")
    tex.append("\\end{table}")

    tex.append("\\begin{table}[htbp]")
    tex.append("\\centering\\small")
    tex.append("\\begin{tabular}{@{}rrrrr@{}}")
    tex.append("\\toprule")
    tex.append("$\\alpha$ & $|x|$ & direct $\\mathcal I_\\alpha\\upf$ & moment series & absolute error\\\\")
    tex.append("\\midrule")
    for row in riesz_rows:
        tex.append(
            f"{row['parameter']:.2f} & {row['radius']:.2f} & "
            f"${row['direct']:.8e}$ & ${row['series']:.8e}$ & ${row['abs_error']:.2e}$\\\\"
        )
    tex.append("\\bottomrule\\end{tabular}")
    tex.append("\\caption{Exterior Riesz-potential series checked against direct quadrature.}")
    tex.append("\\label{tab:riesz-check}")
    tex.append("\\end{table}")

    tex.append("\\begin{table}[htbp]")
    tex.append("\\centering\\small")
    tex.append("\\begin{tabular}{@{}rrrrrr@{}}")
    tex.append("\\toprule")
    tex.append("$y$ & $Q(y)$ & $\\eta(y)$ & normalized integral & first correction & corrected error\\\\")
    tex.append("\\midrule")
    for row in quantile_rows:
        tex.append(
            f"${row['y']:.1e}$ & ${row['Q']:.8e}$ & ${row['eta']:.5e}$ & "
            f"${row['normalized']:.8f}$ & ${row['first_correction']:.8f}$ & "
            f"${row['corrected_error']:.2e}$\\\\"
        )
    tex.append("\\bottomrule\\end{tabular}")
    tex.append(
        f"\\caption{{Fractional quantile primitive with $\\alpha={alpha}$ and $\\beta={beta}$. "
        "The normalized integral is $\\Gamma(\\alpha+1)I^\\alpha(Q^\\beta)/(y^\\alpha Q(y)^\\beta)$.}"
    )
    tex.append("\\label{tab:quantile-frac-int}")
    tex.append("\\end{table}")

    tex.append("\\begin{table}[htbp]")
    tex.append("\\centering\\small")
    tex.append("\\begin{tabular}{@{}rrrrrr@{}}")
    tex.append("\\toprule")
    tex.append("$y$ & $Q(y)$ & $\\eta(y)$ & normalized derivative & first correction & corrected error\\\\")
    tex.append("\\midrule")
    for row in derivative_rows:
        tex.append(
            f"${row['y']:.1e}$ & ${row['Q']:.8e}$ & ${row['eta']:.5e}$ & "
            f"${row['normalized']:.8f}$ & ${row['first_correction']:.8f}$ & "
            f"${row['corrected_error']:.2e}$\\\\"
        )
    tex.append("\\bottomrule\\end{tabular}")
    tex.append(
        f"\\caption{{Caputo/Riemann--Liouville quantile derivative with $\\sigma={sigma}$ and "
        f"$\\beta={beta_d}$.  The normalized derivative is "
        "$\\Gamma(1-\\sigma)y^\\sigma D^\\sigma(Q^\\beta)/Q(y)^\\beta$.}"
    )
    tex.append("\\label{tab:quantile-frac-der}")
    tex.append("\\end{table}")

    tex.append("\\begin{table}[htbp]")
    tex.append("\\centering\\small")
    tex.append("\\begin{tabular}{@{}lr@{}}")
    tex.append("\\toprule")
    tex.append("transform identity & absolute residual\\\\")
    tex.append("\\midrule")
    tex.append(f"logarithmic Cauchy fixed point & ${abs(c_z-log_rhs):.3e}$\\\\")
    tex.append(f"Cauchy differential equation & ${abs(derivative_direct-derivative_rhs):.3e}$\\\\")
    for row in hierarchy_rows:
        tex.append(f"resolvent hierarchy, $m={row['m']}$ & ${row['abs_error']:.3e}$\\\\")
    tex.append("\\bottomrule\\end{tabular}")
    tex.append("\\caption{Residuals for the transform fixed-point and higher-resolvent identities at $z=1.35+0.60i$.}")
    tex.append("\\label{tab:cauchy-check}")
    tex.append("\\end{table}")

    (HERE / "new_numerical_results.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")

    print("\n".join(lines))


if __name__ == "__main__":
    main()
