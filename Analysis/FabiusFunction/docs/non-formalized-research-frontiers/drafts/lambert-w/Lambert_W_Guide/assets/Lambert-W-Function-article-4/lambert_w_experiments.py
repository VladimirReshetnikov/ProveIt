#!/usr/bin/env python3
"""Numerical experiments for the accompanying Lambert-W article.

The script has four purposes:

1. Draw the two real branches W_0 and W_{-1}.
2. Check the Puiseux expansions at the common branch point -1/e.
3. Check the logarithmic asymptotic expansions of W_0(+infinity) and
   W_{-1}(0-).
4. Demonstrate the branch-safe logarithmic Newton iteration discussed in
   the article.

All reference values are evaluated by mpmath with high precision.  The
figures are deterministic and can be regenerated by running

    python3 lambert_w_experiments.py

in the directory containing this file.  The script writes four PDF figures
and one small LaTeX table into the same directory.
"""

from __future__ import annotations

import math
from pathlib import Path
from typing import Callable, Iterable

import matplotlib.pyplot as plt
import mpmath as mp
import numpy as np

OUT = Path(__file__).resolve().parent
mp.mp.dps = 100


def w0(x: mp.mpf) -> mp.mpf:
    """Principal real branch, returned as an mp.mpf."""
    return mp.re(mp.lambertw(x, 0))


def wm1(x: mp.mpf) -> mp.mpf:
    """Lower real branch on [-1/e,0), returned as an mp.mpf."""
    return mp.re(mp.lambertw(x, -1))


def puiseux_branch(x: mp.mpf, branch: int, order: int = 6) -> mp.mpf:
    """Puiseux approximation at x=-1/e through p**order.

    p = sqrt(2(1+e*x)).  The analytic inverse U(q) has coefficients

      1, -1/3, 11/72, -43/540, 769/17280, -221/8505, ...

    W_0 uses q=+p and W_{-1} uses q=-p.  Consequently the even powers
    have the same signs on both real branches and the odd powers have
    opposite signs.
    """
    coeff = {
        1: mp.mpf(1),
        2: -mp.mpf(1) / 3,
        3: mp.mpf(11) / 72,
        4: -mp.mpf(43) / 540,
        5: mp.mpf(769) / 17280,
        6: -mp.mpf(221) / 8505,
    }
    if branch not in (0, -1):
        raise ValueError("branch must be 0 or -1")
    p = mp.sqrt(2 * (1 + mp.e * x))
    q = p if branch == 0 else -p
    return -1 + mp.fsum(coeff[n] * q**n for n in range(1, order + 1))


def asymptotic_w0(x: mp.mpf, order: int = 5) -> mp.mpf:
    """Large-positive-x asymptotic expansion through L1**(-order)."""
    l1 = mp.log(x)
    l2 = mp.log(l1)
    terms = [l1 - l2]
    if order >= 1:
        terms.append(l2 / l1)
    if order >= 2:
        terms.append(l2 * (-2 + l2) / (2 * l1**2))
    if order >= 3:
        terms.append(l2 * (6 - 9 * l2 + 2 * l2**2) / (6 * l1**3))
    if order >= 4:
        terms.append(
            l2 * (-12 + 36 * l2 - 22 * l2**2 + 3 * l2**3)
            / (12 * l1**4)
        )
    if order >= 5:
        terms.append(
            l2
            * (60 - 300 * l2 + 350 * l2**2 - 125 * l2**3 + 12 * l2**4)
            / (60 * l1**5)
        )
    return mp.fsum(terms)


def asymptotic_wm1(x: mp.mpf, order: int = 5) -> mp.mpf:
    """Asymptotic expansion of W_{-1}(x) as x approaches 0 from below.

    Put eta=log(1/(-x)) and B=log(eta).  Then -W_{-1}(x) solves
    u-log(u)=eta.  The displayed real expansion avoids complex logarithms.
    """
    eta = mp.log(1 / (-x))
    b = mp.log(eta)
    u_terms = [eta + b]
    if order >= 1:
        u_terms.append(b / eta)
    if order >= 2:
        u_terms.append(b * (2 - b) / (2 * eta**2))
    if order >= 3:
        u_terms.append(b * (6 - 9 * b + 2 * b**2) / (6 * eta**3))
    if order >= 4:
        u_terms.append(
            b * (12 - 36 * b + 22 * b**2 - 3 * b**3) / (12 * eta**4)
        )
    if order >= 5:
        u_terms.append(
            b
            * (60 - 300 * b + 350 * b**2 - 125 * b**3 + 12 * b**4)
            / (60 * eta**5)
        )
    return -mp.fsum(u_terms)


def logarithmic_newton_step(x: mp.mpf, b: mp.mpf) -> mp.mpf:
    """One Newton step for b + log|b| = log|x|.

    Algebraically this is

        b_next = b/(1+b) * (1 + log(x/b)),

    and x/b is positive on either real branch.  Unlike Newton applied
    directly to b*exp(b)-x, this form does not need exp(b) and remains
    well-scaled for extremely large or extremely small arguments.
    """
    if b == -1:
        raise ZeroDivisionError("the logarithmic Newton map is singular at -1")
    ratio = x / b
    if ratio <= 0:
        raise ValueError("x and the iterate b must have the same sign")
    return b / (1 + b) * (1 + mp.log(ratio))


def iterate(
    step: Callable[[mp.mpf, mp.mpf], mp.mpf],
    x: mp.mpf,
    b0: mp.mpf,
    count: int,
) -> list[mp.mpf]:
    """Return b_0,...,b_count."""
    values = [mp.mpf(b0)]
    for _ in range(count):
        values.append(step(x, values[-1]))
    return values


def start_w0(x: mp.mpf) -> mp.mpf:
    """Simple branch-safe starting value for W_0."""
    if x < 0:
        # Since x=w*exp(w)>w for -1<w<0, x lies above W_0(x).
        return x
    if x < mp.e:
        # Concavity of W_0 on (0,infinity) puts the chord x/e below W_0.
        return x / mp.e
    # The first two logarithmic asymptotic terms form a strict lower bound.
    return mp.log(x) - mp.log(mp.log(x))


def start_wm1(x: mp.mpf) -> mp.mpf:
    """A global lower starting value for W_{-1}.

    Writing x=-exp(-1-u), the elementary Chatzigeorgiou bound gives

      -1-sqrt(2u)-u < W_{-1}(x).

    Starting below the root makes logarithmic Newton increase monotonically.
    """
    u = -1 - mp.log(-x)
    return -1 - mp.sqrt(2 * u) - u


def relative_or_absolute_error(approx: mp.mpf, exact: mp.mpf) -> mp.mpf:
    """Relative error unless exact is zero; used only away from zero here."""
    return abs((approx - exact) / exact) if exact != 0 else abs(approx - exact)


def make_branch_plot() -> None:
    eps = 2e-8
    x0 = np.linspace(-1 / math.e + eps, 8.0, 1400)
    xm = -np.geomspace(1e-5, 1 / math.e - eps, 1000)[::-1]
    y0 = np.array([float(w0(mp.mpf(v))) for v in x0])
    ym = np.array([float(wm1(mp.mpf(v))) for v in xm])

    fig, ax = plt.subplots(figsize=(8.0, 5.0))
    ax.plot(x0, y0, label=r"$W_0(x)$")
    ax.plot(xm, ym, label=r"$W_{-1}(x)$")
    ax.axhline(0, linewidth=0.8)
    ax.axvline(0, linewidth=0.8)
    ax.scatter([-1 / math.e], [-1], zorder=5)
    ax.annotate(r"$(-1/e,-1)$", (-1 / math.e, -1), xytext=(12, -18),
                textcoords="offset points")
    ax.set_xlim(-0.45, 8)
    ax.set_ylim(-12, 3)
    ax.set_xlabel(r"$x$")
    ax.set_ylabel(r"$W(x)$")
    ax.set_title("The two real branches of the Lambert W function")
    ax.legend()
    ax.grid(True, linewidth=0.35)
    fig.tight_layout()
    fig.savefig(OUT / "fig_real_branches.pdf")
    plt.close(fig)


def make_branch_point_error_plot() -> None:
    hs = np.logspace(-14, -2, 180)
    e0: dict[int, list[float]] = {2: [], 4: [], 6: []}
    em: dict[int, list[float]] = {2: [], 4: [], 6: []}
    for h_float in hs:
        h = mp.mpf(str(h_float))
        x = -1 / mp.e + h
        exact0 = w0(x)
        exactm = wm1(x)
        for order in e0:
            e0[order].append(float(abs(puiseux_branch(x, 0, order) - exact0)))
            em[order].append(float(abs(puiseux_branch(x, -1, order) - exactm)))

    fig, ax = plt.subplots(figsize=(8.0, 5.2))
    for order in (2, 4, 6):
        ax.loglog(hs, e0[order], label=rf"$W_0$, through $p^{order}$")
        ax.loglog(hs, em[order], linestyle="--",
                  label=rf"$W_{{-1}}$, through $p^{order}$")
    ax.set_xlabel(r"$h=x+1/e$")
    ax.set_ylabel("absolute error")
    ax.set_title("Puiseux truncation errors near the common branch point")
    ax.grid(True, which="both", linewidth=0.35)
    ax.legend(ncol=2, fontsize=8)
    fig.tight_layout()
    fig.savefig(OUT / "fig_branch_point_error.pdf")
    plt.close(fig)


def make_asymptotic_error_plot() -> None:
    ts = np.linspace(1.2, 40.0, 170)
    xs0 = [mp.power(10, mp.mpf(str(t))) for t in ts]
    xsm = [-mp.power(10, -mp.mpf(str(t))) for t in ts]

    fig, ax = plt.subplots(figsize=(8.0, 5.2))
    for order in (0, 1, 3, 5):
        err0 = [float(relative_or_absolute_error(asymptotic_w0(x, order), w0(x)))
                for x in xs0]
        errm = [float(relative_or_absolute_error(asymptotic_wm1(x, order), wm1(x)))
                for x in xsm]
        ax.semilogy(ts, err0, label=rf"$W_0(10^t)$, order {order}")
        ax.semilogy(ts, errm, linestyle="--",
                    label=rf"$W_{{-1}}(-10^{{-t}})$, order {order}")
    ax.set_xlabel(r"$t$")
    ax.set_ylabel("relative error")
    ax.set_title("Logarithmic asymptotic expansions on both real branches")
    ax.grid(True, which="both", linewidth=0.35)
    ax.legend(ncol=2, fontsize=8)
    fig.tight_layout()
    fig.savefig(OUT / "fig_asymptotic_error.pdf")
    plt.close(fig)


def make_iteration_plot() -> None:
    cases = [
        (mp.mpf("1e80"), 0, start_w0(mp.mpf("1e80")), r"$W_0(10^{80})$"),
        (mp.mpf("-0.36"), 0, start_w0(mp.mpf("-0.36")), r"$W_0(-0.36)$"),
        (mp.mpf("-1e-80"), -1, start_wm1(mp.mpf("-1e-80")),
         r"$W_{-1}(-10^{-80})$"),
    ]
    fig, ax = plt.subplots(figsize=(8.0, 5.2))
    for x, branch, b0, label in cases:
        exact = w0(x) if branch == 0 else wm1(x)
        values = iterate(logarithmic_newton_step, x, b0, 10)
        errors = [max(float(abs(v - exact)), 1e-100) for v in values]
        ax.semilogy(range(len(values)), errors, marker="o", label=label)
    ax.set_xlabel("iteration number")
    ax.set_ylabel("absolute error")
    ax.set_title("Quadratic convergence of the logarithmic Newton iteration")
    ax.set_xticks(range(0, 11))
    ax.grid(True, which="both", linewidth=0.35)
    ax.legend()
    fig.tight_layout()
    fig.savefig(OUT / "fig_iteration_error.pdf")
    plt.close(fig)


def format_mpf(x: mp.mpf, digits: int = 18) -> str:
    """Scientific notation suitable for a LaTeX table."""
    return mp.nstr(x, digits).replace("e+", r"\mathrm{e}{+}").replace(
        "e-", r"\mathrm{e}{-}"
    )


def make_numerical_table() -> None:
    points = [
        (r"$-1/e$", -1 / mp.e),
        (r"$-0.1$", mp.mpf("-0.1")),
        (r"$0$", mp.mpf("0")),
        (r"$1$", mp.mpf("1")),
        (r"$e$", mp.e),
        (r"$10$", mp.mpf("10")),
    ]
    lines = [
        r"\begin{tabular}{@{}rll@{}}",
        r"\toprule",
        r"$x$ & $W_0(x)$ & $W_{-1}(x)$ when real \\",
        r"\midrule",
    ]
    for label, x in points:
        v0 = w0(x)
        if x < 0:
            vm = wm1(x)
            sm = rf"${mp.nstr(vm, 18)}$"
        else:
            sm = r"--"
        lines.append(rf"{label} & ${mp.nstr(v0, 18)}$ & {sm} \\")
    lines.extend([r"\bottomrule", r"\end{tabular}"])
    (OUT / "numerical_values.tex").write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> None:
    make_branch_plot()
    make_branch_point_error_plot()
    make_asymptotic_error_plot()
    make_iteration_plot()
    make_numerical_table()
    print("Generated figures and numerical_values.tex in", OUT)


if __name__ == "__main__":
    main()
