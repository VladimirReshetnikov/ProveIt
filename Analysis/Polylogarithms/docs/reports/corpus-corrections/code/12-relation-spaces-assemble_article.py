#!/usr/bin/env python3
"""Assemble the editable TeX fragments into one portable article source."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PARTS = [
    "preamble", "introduction", "stieltjes_zeros", "distribution_ranks",
    "bridge_completion", "gaussian_reduction", "audit_introduction",
    "corrections_polylogs", "corrections_gamma", "corrections_additional",
    "verification", "research_questions", "bibliography",
]

def main():
    text = "% Generated by code/assemble_article.py; edit the sections/ fragments.\n"
    for name in PARTS:
        path = ROOT / "sections" / f"{name}.tex"
        text += f"\n% ----- sections/{name}.tex -----\n"
        text += path.read_text(encoding="utf-8").rstrip() + "\n"
    out = ROOT / "polylogarithms_research.tex"
    out.write_text(text, encoding="utf-8")
    print(f"Assembled {len(PARTS)} fragments: {out.name}")

if __name__ == "__main__":
    main()
