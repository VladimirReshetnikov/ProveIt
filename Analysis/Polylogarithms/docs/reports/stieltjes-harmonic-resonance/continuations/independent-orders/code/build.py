#!/usr/bin/env python3
"""Flatten the modular article and compile its standalone TeX without network access.

Usage: python3 code/build.py [--flatten-only]
Requires pdflatex or lualatex and the standard TeX packages in preamble.tex.
The PDF is written beside the standalone TeX at package root.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import shutil
import subprocess
import time

ROOT = Path(__file__).resolve().parents[1]
BASENAME = 'Independent_Orders_and_Exact_Reductions'


def flatten(path, stack=()):
    path = path.resolve()
    if path in stack:
        raise ValueError(f'Recursive TeX input: {path}')
    if not path.is_relative_to(ROOT):
        raise ValueError(f'TeX input leaves package: {path}')
    source = path.read_text(encoding='utf-8')
    def include(match):
        target = ROOT / match.group(1)
        if target.suffix != '.tex':
            target = target.with_suffix('.tex')
        body = flatten(target, (*stack, path))
        return f'\n% BEGIN {target.relative_to(ROOT)}\n{body}\n% END {target.relative_to(ROOT)}\n'
    return re.sub(r'\\input\{([^}]+)\}', include, source)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--flatten-only', action='store_true')
    args = parser.parse_args()
    target = ROOT / f'{BASENAME}.tex'
    target.write_text('% Generated by code/build.py from the modular article.\n' +
                      flatten(ROOT / 'article.tex'), encoding='utf-8')
    if args.flatten_only:
        print(target.name)
        return
    engine = shutil.which('pdflatex') or shutil.which('lualatex')
    if not engine:
        raise SystemExit('Install a TeX distribution providing pdflatex or lualatex.')
    build = ROOT / '.build'
    build.mkdir(exist_ok=True)
    results = ROOT / 'results'
    results.mkdir(exist_ok=True)
    started = time.monotonic()
    command = [engine, '-interaction=nonstopmode', '-halt-on-error',
               '-file-line-error', '-output-directory', str(build), str(target)]
    for number in range(1, 4):
        run = subprocess.run(command, cwd=ROOT, capture_output=True, text=True)
        (build / f'pass_{number}.txt').write_text(run.stdout + run.stderr)
        if run.returncode:
            print((run.stdout + run.stderr)[-7000:])
            raise SystemExit(f'LaTeX pass {number} failed; inspect .build/pass_{number}.txt')
    log = (build / f'{BASENAME}.log').read_text(errors='replace')
    warnings = [line for line in log.splitlines()
                if ('Overfull' in line or 'Warning:' in line or 'undefined' in line)]
    pdf = ROOT / f'{BASENAME}.pdf'
    shutil.copy2(build / pdf.name, pdf)
    record = {'schema': 'proveit.article.build.v1',
              'engine': Path(engine).name, 'passes': 3,
              'elapsed_seconds': round(time.monotonic()-started, 3),
              'standalone_tex': target.name, 'pdf': pdf.name,
              'pdf_bytes': pdf.stat().st_size,
              'tex_sha256': hashlib.sha256(target.read_bytes()).hexdigest(),
              'warnings': warnings}
    (results / 'build.json').write_text(json.dumps(record, indent=2)+'\n')
    print(json.dumps(record, indent=2))


if __name__ == '__main__':
    main()
