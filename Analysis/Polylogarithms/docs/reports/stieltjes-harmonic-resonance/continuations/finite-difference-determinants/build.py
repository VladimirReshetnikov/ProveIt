#!/usr/bin/env python3
"""Build modular and standalone articles with a local LaTeX installation."""
from pathlib import Path
import json, re, shutil, subprocess, sys
ROOT=Path(__file__).resolve().parent
BASENAME='Finite_Difference_Determinants'

def expand(path:Path)->str:
    text=path.read_text(encoding='utf-8')
    def sub(match):
        child=ROOT/(match.group(1)+'.tex')
        if not child.exists(): raise FileNotFoundError(child)
        return '% BEGIN '+str(child.relative_to(ROOT))+'\n'+expand(child)+'\n% END '+str(child.relative_to(ROOT))
    return re.sub(r'\\input\{([^}]+)\}',sub,text)

def main():
    standalone=ROOT/(BASENAME+'.tex')
    standalone.write_text('% Standalone source generated by build.py; edit article.tex and sections/.\n'+expand(ROOT/'article.tex'),encoding='utf-8')
    build=ROOT/'build';build.mkdir(exist_ok=True)
    if shutil.which('latexmk'):
        cmd=['latexmk','-pdf','-interaction=nonstopmode','-halt-on-error','-file-line-error','-outdir='+str(build),'article.tex']
        subprocess.run(cmd,cwd=ROOT,check=True,stdout=subprocess.PIPE,stderr=subprocess.STDOUT)
    elif shutil.which('pdflatex'):
        cmd=['pdflatex','-interaction=nonstopmode','-halt-on-error','-output-directory='+str(build),'article.tex']
        for _ in range(3):subprocess.run(cmd,cwd=ROOT,check=True,stdout=subprocess.PIPE,stderr=subprocess.STDOUT)
    else:
        raise RuntimeError('Install latexmk or pdflatex with the packages listed in README.md')
    out=ROOT/(BASENAME+'.pdf');shutil.copy2(build/'article.pdf',out)
    log=(build/'article.log').read_text(errors='replace')
    report={'status':'compiled','engine':cmd[0],'overfull_boxes':len(re.findall('Overfull',log)),
            'undefined_references':bool(re.search(r'There were undefined references|Reference .* undefined',log)),
            'pdf':out.name,'standalone_tex':standalone.name}
    (ROOT/'results/build_report.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2))
if __name__=='__main__':
    try:main()
    except subprocess.CalledProcessError as exc:
        print(exc.stdout.decode(errors='replace') if isinstance(exc.stdout,bytes) else exc.stdout,file=sys.stderr)
        raise
