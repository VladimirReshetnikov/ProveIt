#!/usr/bin/env python3
"""Build the self-contained TeX and PDF without network access."""
from pathlib import Path
import argparse
import re
import subprocess

ROOT = Path(__file__).resolve().parent
NAME = 'Exact_Resonant_Identities'


def inline(name, stack=()):
    path = (ROOT / name).resolve()
    if path in stack:
        raise ValueError('Recursive TeX input: ' + str(path))
    if ROOT not in path.parents:
        raise ValueError('TeX input outside package')
    value = path.read_text(encoding='utf-8')
    def expand(match):
        child = match.group(1)
        if not child.endswith('.tex'):
            child += '.tex'
        return '\n% BEGIN ' + child + '\n' + inline(child, stack+(path,)) + '\n% END ' + child + '\n'
    return re.sub(r'\\input\{([^}]+)\}', expand, value)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--source-only', action='store_true')
    ap.add_argument('--engine', default='pdflatex')
    args = ap.parse_args()
    standalone = ROOT / (NAME + '.tex')
    standalone.write_text('% Self-contained source generated by build.py.\n' + inline('article.tex'), encoding='utf-8')
    if args.source_only:
        print(standalone.name)
        return
    build = ROOT / 'build'
    build.mkdir(exist_ok=True)
    for turn in range(3):
        command = [args.engine, '-interaction=nonstopmode', '-halt-on-error',
                   '-file-line-error', '-output-directory='+str(build), str(standalone)]
        process = subprocess.run(command, cwd=ROOT, text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
        (build / f'pass-{turn+1}.txt').write_text(process.stdout, encoding='utf-8')
        if process.returncode:
            print('\n'.join(process.stdout.splitlines()[-90:]))
            raise SystemExit(process.returncode)
        print(f'LaTeX pass {turn+1}: complete', flush=True)
    pdf = ROOT / (NAME + '.pdf')
    pdf.write_bytes((build / pdf.name).read_bytes())
    log = (build / (NAME+'.log')).read_text(encoding='utf-8', errors='replace')
    warnings = [line for line in log.splitlines() if 'Warning:' in line or 'Overfull' in line]
    for line in warnings:
        print(line)
    print(pdf.name)


if __name__ == '__main__':
    main()
