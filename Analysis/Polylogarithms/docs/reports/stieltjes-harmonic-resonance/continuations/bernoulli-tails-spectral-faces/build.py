#!/usr/bin/env python3
"""Build a self-contained TeX source and its PDF using a local TeX installation."""
from pathlib import Path
import json
import re
import shutil
import subprocess
import tempfile

ROOT = Path(__file__).resolve().parent
STEM = 'Bernoulli_Tails_and_Spectral_Faces'


def flatten(path, ancestors=()):
    path = path.resolve()
    if path in ancestors:
        raise ValueError(f'Cyclic TeX input: {path}')
    text = path.read_text()
    def replace(match):
        child = path.parent / match.group(1)
        if not child.suffix:
            child = child.with_suffix('.tex')
        return ('\n% BEGIN INCLUDED FILE: ' + str(child.relative_to(ROOT)) + '\n'
                + flatten(child, ancestors + (path,))
                + '\n% END INCLUDED FILE: ' + str(child.relative_to(ROOT)) + '\n')
    return re.sub(r'\\input\{([^}]+)\}', replace, text)


def main():
    engine = shutil.which('pdflatex')
    if not engine:
        raise SystemExit('pdflatex is required; install a TeX distribution with the listed packages.')
    source = ROOT / (STEM + '.tex')
    source.write_text('% Generated by build.py from article.tex and its section inputs.\n'
                      + flatten(ROOT / 'article.tex'))
    logs = ROOT / 'verification' / 'build'
    logs.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='proveit-tex-') as temporary:
        work = Path(temporary)
        shutil.copy2(source, work / source.name)
        for iteration in range(1, 4):
            result = subprocess.run(
                [engine, '-interaction=nonstopmode', '-halt-on-error',
                 '-file-line-error', source.name], cwd=work,
                text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
            (logs / f'pass_{iteration}.txt').write_text(result.stdout)
            if result.returncode:
                print(result.stdout[-12000:])
                raise SystemExit(result.returncode)
        final_log = (work / (STEM + '.log')).read_text(errors='replace')
        shutil.copy2(work / (STEM + '.pdf'), ROOT / (STEM + '.pdf'))
        (logs / 'latex.log').write_text(final_log)
        warning_lines = [line for line in final_log.splitlines()
                         if ('Overfull' in line or 'undefined' in line
                             or 'multiply defined' in line)]
        page_match = re.search(r'Output written on .*?\((\d+) pages',
                               final_log, re.DOTALL)
        receipt = {
            'engine': subprocess.run([engine, '--version'], text=True,
                                     stdout=subprocess.PIPE).stdout.splitlines()[0],
            'passes': 3,
            'pages': int(page_match.group(1)) if page_match else None,
            'layout_or_reference_warnings': warning_lines,
            'standalone_source': source.name,
            'pdf': STEM + '.pdf',
        }
        (logs / 'build_receipt.json').write_text(json.dumps(receipt, indent=2) + '\n')
        print(json.dumps(receipt, indent=2))


if __name__ == '__main__':
    main()
