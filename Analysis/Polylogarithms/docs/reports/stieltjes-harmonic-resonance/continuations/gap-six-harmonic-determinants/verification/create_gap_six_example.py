#!/usr/bin/env python3
"""Exact new gap-six example (p,q)=(14,20), including a finite telescoper."""
import json, math
from pathlib import Path
from functools import reduce
import sympy as s
OUT=Path(__file__).resolve().parents[1] / "results"
b=10;p=2*b-6;q=2*b
N,x,y=s.symbols('N x y')
a=b-3

def source_entry(i,k):
    r=i+k-a+1
    if r<0:return s.S.Zero
    n1,n2=2*i+2,2*b+2*i-2*a+2
    k1,k2=2*a-2*k,2*b-2*k
    z=s.S.Zero
    if 2<=k1<=n1:z+=s.binomial(n1,k1)/n1
    if 2<=k2<=n2:z+=s.binomial(n2,k2)/n2
    return s.bernoulli(2*r)*z
M=s.Matrix(b,b,source_entry)
invrow=list(M.inv()[0,:])
mult=s.ilcm(*[v.q for v in invrow])
row=[int(v*mult) for v in invrow]
g=reduce(math.gcd,row)
row=[v//g for v in row]
scale=s.Rational(mult,g)
assert s.Matrix([row])*M == s.Matrix([[scale]+[0]*(b-1)])
K=sum(s.Integer(v)*y**(2*j+1) for j,v in enumerate(row,start=b))
P=s.Poly(s.expand(K.subs(y,x+s.Rational(1,2))-K.subs(y,x-s.Rational(1,2))),x)
w=[P.nth(2*r) for r in range(q)]
def c(v,h):
    return 1/s.Integer(v-1) if h==0 else s.bernoulli(2*h,s.Rational(1,2))*s.rf(v,2*h-1)/s.factorial(2*h)
u=[sum(c(p,e)*c(q,h-e) for e in range(h+1)) for h in range(4)]
S=s.Poly(sum(sum(u[e]*w[q-1-h+e] for e in range(h+1))*x**(6-2*h) for h in range(4)),x)
def faulhaber(k):
    return s.expand((s.bernoulli(k+1,N+1)-s.bernoulli(k+1))/(k+1))
Up=s.expand(sum(v*faulhaber(2*j+1-q) for j,v in enumerate(row,start=b)))
Uq=s.expand(sum(v*faulhaber(2*j+1-p) for j,v in enumerate(row,start=b)))
assert s.expand(Up-Up.subs(N,N-1)-K.subs(y,N)/N**q)==0
assert s.expand(Uq-Uq.subs(N,N-1)-K.subs(y,N)/N**p)==0
Vdiff=s.cancel(K.subs(y,N)/N**(p+q)+Up.subs(N,N-1)/N**p+Uq.subs(N,N-1)/N**q-S.as_expr().subs(x,N-s.Rational(1,2)))
Vpoly=s.Poly(Vdiff,N)
V=s.expand(sum(coeff*faulhaber(k[0]) for k,coeff in Vpoly.terms()))
assert s.expand(V-V.subs(N,N-1)-Vdiff)==0
assert V.subs(N,0)==0

def tail_trunc(v):
    return N**(1-v)/s.Integer(v-1)-N**(-v)/2+sum(s.bernoulli(2*h)*s.rf(v,2*h-1)/s.factorial(2*h)*N**(-v-2*h+1) for h in range(1,4))
F=s.expand(K.subs(y,N)*tail_trunc(p)*tail_trunc(q)+Up*tail_trunc(p)+Uq*tail_trunc(q)+V)
nonnegative={e:int(0) for e in range(8)}
for e in range(8):
    nonnegative[e]=s.expand(F).coeff(N,e)
    assert nonnegative[e]==(-scale/2 if e==0 else 0),(e,nonnegative[e])

# Independent check of leading inverse coefficient through boundary determinant ratio.
def rational_fundamental(c,nmax):
    aa=lambda u:s.ff(2*u,2*c) if u>c else s.S.Zero
    bb=lambda u:s.ff(2*u-1,2*c)
    alpha=lambda k:2*abs(s.bernoulli(2*k))/s.factorial(2*k)
    ret=[[s.S.Zero]*c]+[[s.Integer(int(i==j)) for j in range(1,c+1)] for i in range(1,c+1)]
    for v in range(c+1,nmax+1):
        ret.append([sum(alpha(v-u)*(bb(v)+aa(u))*ret[u][j] for u in range(1,v))/(2*(aa(v)+bb(v))) for j in range(c)])
    return ret
rr=rational_fundamental(3,b+3)
fb=s.det(s.Matrix(rr[b+1:b+4]));fm=s.det(s.Matrix(rr[b:b+3]))
ss=b+3
d=2*(s.ff(2*ss,6)+s.ff(2*ss-1,6))
assert invrow[-1]==4*b*fm/(d*fb)
assert w[-1]==scale*4*b*(4*b-1)*fm/(d*fb)

obj={'p':p,'q':q,'b':b,'row_increasing_block_index':row,
     'block_indices':list(range(b,2*b)),
     'row_times_M':['%s'%scale]+['0']*(b-1),
     'ordinary_sum_value':str(-scale/2),
     'K_y':str(K),'P_x':str(P.as_expr()),'S_x':str(S.as_expr()),
     'U_p_N':str(Up),'U_q_N':str(Uq),'V_N':str(V),
     'telescoper':'F(N)=K(N)A_p(N)A_q(N)+U_p(N)A_p(N)+U_q(N)A_q(N)+V(N)',
     'difference':'F(N)-F(N-1)=P(N-1/2)A_p(N-1)A_q(N-1)-S(N-1/2)',
     'asymptotic_nonnegative_powers':{str(k):str(v) for k,v in nonnegative.items()},
     'checks':'Exact rational matrix row, centered difference, subtraction, three finite differences, positive-power cancellation, limiting constant, leading-coefficient determinant ratio.'}
(OUT/'gap_six_14_20_example.json').write_text(json.dumps(obj,indent=2)+'\n')
tex='''% Exact ordinary convergent example. K is encoded by its integer coefficient row.
\\subsection{A first example beyond the previously settled smaller orders}
For $(p,q)=(14,20)$ put $K(y)=y^{21}\\sum_{j=0}^{9}c_jy^{2j}$,
where the coefficient row $(c_0,\\ldots,c_9)$ is
\\[\\begin{aligned}
'''
for k in range(0,len(row),2):
    tex+=str(row[k])+'&,\\quad '+str(row[k+1])+('\\\\\n' if k+2<len(row) else '\n')
tex+='\\end{aligned}\\]\n'
tex+='Then the centered difference $P(x)=K(x+1/2)-K(x-1/2)$ and the polynomial\n\\[ S(x)='+s.latex(S.as_expr())+'\\]\n'
tex+='give the exact absolutely convergent identity\n\\[\\sum_{n\\ge0}\\left\\{\\frac{P(n+1/2)}{13!\\,19!}\\psi^{(13)}(n+1)\\psi^{(19)}(n+1)-S(n+1/2)\\right\\}='+s.latex(-scale/2)+'.\\]\n'
tex+='The complete finite telescoper is recorded in \\texttt{gap\\_six\\_14\\_20\\_example.json} and regenerated by \\texttt{create\\_gap\\_six\\_example.py}. Its verification uses only polynomial and rational-function identities followed by the displayed tail asymptotics.\n'
(OUT/'gap_six_14_20_example.tex').write_text(tex)
print('integer row:',row)
print('scale:',scale,'sum:',-scale/2)
print('S:',S.as_expr())
print('all exact checks passed')
