#!/usr/bin/env python3
"""Build a standalone TeX source and PDF from the modular article.

Requires pdflatex and the LaTeX packages listed in preamble.tex.
The mathematical checks are separate; building does not run them.
"""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent
STEM = 'Ordered_Hurwitz_Resonances'


def flatten(path: Path, stack=()):
    path = path.resolve()
    if path in stack:
        raise RuntimeError('Recursive TeX input: ' + str(path))
    source = path.read_text(encoding='utf-8')
    pattern = re.compile(r'\\input\{([^}]+)\}')
    def include(match):
        child = path.parent / match.group(1)
        if not child.suffix:
            child = child.with_suffix('.tex')
        return ('\n% BEGIN ' + child.relative_to(ROOT).as_posix() + '\n'
                + flatten(child, (*stack, path))
                + '\n% END ' + child.relative_to(ROOT).as_posix() + '\n')
    return pattern.sub(include, source)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--tex-only', action='store_true')
    args = parser.parse_args()
    standalone = ROOT / (STEM + '.tex')
    standalone.write_text('% Generated by build.py from the modular sources.\n'
                          + flatten(ROOT/'article.tex'), encoding='utf-8')
    if args.tex_only:
        print(standalone.name)
        return
    if shutil.which('pdflatex') is None:
        raise SystemExit('pdflatex is required; alternatively compile the standalone TeX in a LaTeX installation.')
    build_dir = ROOT / 'build'
    build_dir.mkdir(exist_ok=True)
    command = ['pdflatex', '-interaction=nonstopmode', '-halt-on-error',
               '-file-line-error', '-output-directory='+str(build_dir), standalone.name]
    outputs = []
    for run in range(3):
        proc = subprocess.run(command, cwd=ROOT, text=True, capture_output=True)
        outputs.append('PASS '+str(run+1)+'\n'+proc.stdout+proc.stderr)
        (build_dir/'build.stdout.txt').write_text('\n'.join(outputs), encoding='utf-8')
        if proc.returncode:
            print(proc.stdout[-6000:])
            raise SystemExit(proc.returncode)
    pdf = ROOT / (STEM+'.pdf')
    shutil.copyfile(build_dir/(STEM+'.pdf'), pdf)
    log = (build_dir/(STEM+'.log')).read_text(encoding='utf-8', errors='replace')
    warnings = [line for line in log.splitlines()
                if ('Warning:' in line or 'Overfull' in line or 'Underfull' in line)]
    receipt = {'status':'compiled', 'passes':3, 'engine':'pdflatex',
               'standalone_tex':standalone.name, 'pdf':pdf.name,
               'pdf_sha256':hashlib.sha256(pdf.read_bytes()).hexdigest(),
               'tex_sha256':hashlib.sha256(standalone.read_bytes()).hexdigest(),
               'final_log_warnings':warnings,
               'scope':'Build receipt only; analytic proofs and verification results are separate.'}
    (ROOT/'results').mkdir(exist_ok=True)
    (ROOT/'results/build_receipt.json').write_text(json.dumps(receipt,indent=2)+'\n',encoding='utf-8')
    print(json.dumps({'pdf':pdf.name,'bytes':pdf.stat().st_size,'warnings':warnings},indent=2))


if __name__ == '__main__':
    main()
