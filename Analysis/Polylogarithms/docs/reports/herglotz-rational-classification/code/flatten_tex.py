#!/usr/bin/env python3
"""Create a standalone source by expanding the report's local input files."""
from __future__ import annotations
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
INPUT = re.compile(r"\\input\{([^}]+)\}")


def expand(path: Path, active: frozenset[Path] = frozenset()) -> str:
    path = path.resolve()
    if not path.is_relative_to(ROOT):
        raise ValueError(f"Input escapes the package: {path}")
    if path in active:
        raise ValueError(f"Cyclic TeX input: {path}")
    text = path.read_text(encoding="utf-8")
    def replace(match: re.Match[str]) -> str:
        child = ROOT / match.group(1)
        if child.suffix != '.tex':
            child = child.with_suffix('.tex')
        return (f"% BEGIN expanded input: {match.group(1)}\n"
                + expand(child, active | {path})
                + f"\n% END expanded input: {match.group(1)}\n")
    return INPUT.sub(replace, text)


if __name__ == '__main__':
    target = ROOT / 'article-standalone.tex'
    target.write_text('% Generated by code/flatten_tex.py; edit modular sources.\n'
                      + expand(ROOT / 'article.tex'), encoding='utf-8')
    print(target)
