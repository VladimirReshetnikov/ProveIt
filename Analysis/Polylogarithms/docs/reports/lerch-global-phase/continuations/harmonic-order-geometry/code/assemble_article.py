#!/usr/bin/env python3
"""Expand the modular TeX into article.tex; no external Python packages."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
INCLUDE = re.compile(r"\\input\{([^}]+)\}")

def expand(path: Path, stack=()):
    path = path.resolve()
    if path in stack:
        raise RuntimeError(f"Circular TeX input: {path}")
    text = path.read_text(encoding="utf-8")
    def substitute(match):
        child = ROOT / match.group(1)
        return ("% Begin " + match.group(1) + "\n" +
                expand(child, stack + (path,)) +
                "\n% End " + match.group(1) + "\n")
    return INCLUDE.sub(substitute, text)

if __name__ == "__main__":
    output = ROOT / "article.tex"
    output.write_text(
        "% Generated by code/assemble_article.py from article_template.tex.\n"
        "% The mathematical text is fully expanded; figures reside in figures/.\n"
        + expand(ROOT / "article_template.tex"), encoding="utf-8")
    print(output)
