#!/usr/bin/env python3
"""Create a single TeX source while retaining relative figure paths."""
from pathlib import Path
import re

ARTICLE = Path(__file__).resolve().parents[1] / "article"
pattern = re.compile(r"^\\input\{([^}]+)\}[ \t]*$", re.MULTILINE)


def expand(path, stack=()):
    path = path.resolve()
    if path in stack:
        raise ValueError("Cyclic TeX input: " + str(path))
    source = path.read_text()

    def replace(match):
        child = path.parent / match.group(1)
        if not child.suffix:
            child = child.with_suffix(".tex")
        body = expand(child, stack + (path,))
        if not body.endswith("\n"):
            body += "\n"
        return "% BEGIN " + match.group(1) + "\n" + body + "% END " + match.group(1)

    return pattern.sub(replace, source)


if __name__ == "__main__":
    out = ARTICLE / "standalone.tex"
    out.write_text("% Generated by code/flatten_tex.py; edit main.tex and sections instead.\n" + expand(ARTICLE / "main.tex"))
    print(out)
