#!/usr/bin/env python3
"""Assemble a single TeX source from the integration sections (stdlib only)."""
from pathlib import Path

ROOT = Path(__file__).resolve().parent
parts = [ROOT / "preamble.tex", ROOT / "frontmatter.tex"]
parts += sorted((ROOT / "sections").glob("*.tex"))
parts += [ROOT / "references.tex"]
text = "% Generated by build_article.py; edit the modular section files.\n"
for path in parts:
    text += "\n% ===== " + path.relative_to(ROOT).as_posix() + " =====\n"
    text += path.read_text(encoding="utf-8") + "\n"
text += "\\end{document}\n"
(ROOT / "article.tex").write_text(text, encoding="utf-8")
print("Assembled article.tex from", len(parts), "source files.")
