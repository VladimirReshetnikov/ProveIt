#!/usr/bin/env python3
"""Render the article's comparison of sufficient Lerch saturation bounds.

Run from any working directory after placing the certified source JSON next
to this script::

    python /path/to/package/code/make_figures.py

Dependencies: NumPy and Matplotlib.  The standard-library Fraction class is
used for the harmonic numbers and integer ceilings; floats enter only when
plotting logarithms.  Output paths are resolved relative to this script,
not to the working directory.

The finite data are generated by verify_polynomial_mesh.py.  This plotting
script checks their threshold arithmetic but does not repeat Sturm root
isolation.  All displayed quantities are sufficient bounds: none is
asserted to be the least deformation order producing zero saturation.
"""

from __future__ import annotations

import argparse
from fractions import Fraction
import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.ticker import MaxNLocator
import numpy as np


PACKAGE_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_CERTIFICATES = Path(__file__).with_name("polynomial_mesh_certificates.json")


def harmonic(n: int) -> Fraction:
    return sum((Fraction(1, j) for j in range(1, n + 1)), Fraction(0))


def ceiling(value: Fraction) -> int:
    return -(-value.numerator // value.denominator)


def old_threshold(n: int) -> int:
    return 576 * n**2 * (3 * n) ** (2 * n - 4)


def new_threshold(n: int) -> int:
    return ceiling((16 + 6 * n * (n - 1) * (n - 2) * harmonic(n - 1)) ** 2)


def finite_thresholds(source: Path) -> dict[int, int]:
    """Read and cross-check the exact finite sufficient bounds for n=3..16."""
    data = json.loads(source.read_text(encoding="utf-8"))
    if data.get("status") != "PASS":
        raise ValueError("The mesh-certificate JSON does not report PASS.")
    selected: dict[int, int] = {}
    for row in data["indices"]:
        n = row["n"]
        if not 3 <= n <= 16:
            continue
        if n in selected:
            raise ValueError(f"Duplicate certificate index n={n}.")
        if row["previous_explicit_threshold"] != old_threshold(n):
            raise ValueError(f"Previous-threshold arithmetic disagrees for n={n}.")
        if row["new_sufficient_threshold"] != new_threshold(n):
            raise ValueError(f"New-threshold arithmetic disagrees for n={n}.")
        mesh = Fraction(row["certified_ordinary_mesh_lower"])
        if mesh <= 0:
            raise ValueError(f"The certified mesh is not positive for n={n}.")
        threshold = ceiling((16 + 24 * harmonic(n - 1) / mesh) ** 2)
        if threshold != row["sufficient_threshold_from_certified_mesh"]:
            raise ValueError(f"Certified-threshold arithmetic disagrees for n={n}.")
        if not 0 < threshold <= new_threshold(n):
            raise ValueError(f"The certified threshold is inconsistent for n={n}.")
        selected[n] = threshold
    if set(selected) != set(range(3, 17)):
        raise ValueError("The source must contain every certified index n=3..16.")
    return selected


def make_figure(source: Path, output_dir: Path, dpi: int) -> tuple[Path, Path]:
    certified = finite_thresholds(source)
    n = np.arange(3, 41, dtype=int)
    previous = np.log10(np.array([old_threshold(int(j)) for j in n], dtype=float))
    current = np.log10(np.array([new_threshold(int(j)) for j in n], dtype=float))
    n_finite = np.array(sorted(certified), dtype=int)
    finite = np.log10(np.array([certified[int(j)] for j in n_finite], dtype=float))

    # Line style as well as color distinguishes the two analytic bounds.
    old_color = "#766756"
    new_color = "#087F8C"
    finite_color = "#B5542D"
    plt.rcParams.update({
        "font.family": "STIXGeneral",
        "mathtext.fontset": "stix",
        "font.size": 10,
        "axes.labelsize": 11,
        "axes.titlesize": 10,
        "xtick.labelsize": 9,
        "ytick.labelsize": 9,
        "legend.fontsize": 9.5,
        "axes.edgecolor": "#4C5054",
        "axes.linewidth": 0.65,
        "xtick.major.width": 0.65,
        "ytick.major.width": 0.65,
        "xtick.major.size": 3,
        "ytick.major.size": 3,
        "text.color": "#20262A",
        "axes.labelcolor": "#20262A",
        "xtick.color": "#20262A",
        "ytick.color": "#20262A",
        "pdf.fonttype": 42,
        "ps.fonttype": 42,
        "savefig.facecolor": "white",
    })

    fig, axes = plt.subplots(1, 2, figsize=(6.6, 3.55))
    fig.subplots_adjust(left=0.09, right=0.985, bottom=0.16, top=0.81, wspace=0.34)
    for ax in axes:
        ax.set_axisbelow(True)
        ax.grid(axis="y", color="#D7DCDF", linewidth=0.5)
        ax.spines[["top", "right"]].set_visible(False)
        ax.set_xlabel(r"Order $n$")
        ax.set_ylabel(r"$\log_{10} k_{\mathrm{suff}}$")

    axes[0].plot(n, previous, color=old_color, linewidth=1.8, linestyle=(0, (4, 2)))
    axes[0].plot(n, current, color=new_color, linewidth=2.0)
    axes[0].set_title(r"(a) General bounds: $3\leq n\leq40$", loc="left", pad=9)
    axes[0].set_xlim(2.2, 40.8)
    axes[0].set_ylim(0, 170)
    axes[0].set_xticks([3, 10, 20, 30, 40])
    axes[0].set_yticks([0, 40, 80, 120, 160])

    detail_mask = n <= 16
    axes[1].plot(n[detail_mask], current[detail_mask], color=new_color, linewidth=2.0)
    axes[1].scatter(n_finite, finite, s=21, marker="o", color=finite_color,
                    edgecolors="white", linewidths=0.5, zorder=4)
    axes[1].set_title(r"(b) Finite certificates: $3\leq n\leq16$", loc="left", pad=9)
    axes[1].set_xlim(2.6, 16.4)
    axes[1].set_ylim(3.0, 10.1)
    axes[1].set_xticks([3, 6, 9, 12, 16])
    axes[1].yaxis.set_major_locator(MaxNLocator(integer=True, nbins=7))

    handles = [
        Line2D([0], [0], color=old_color, linewidth=1.8, linestyle=(0, (4, 2)),
               label="Previous analytic bound"),
        Line2D([0], [0], color=new_color, linewidth=2.0, label="New analytic bound"),
        Line2D([0], [0], color=finite_color, marker="o", markersize=4.5,
               linestyle="None", label=r"Certified $B_n$ mesh"),
    ]
    fig.legend(handles=handles, loc="upper center", bbox_to_anchor=(0.525, 0.989),
               ncol=3, frameon=False, columnspacing=1.3, handlelength=2.1,
               handletextpad=0.6, borderaxespad=0)

    output_dir.mkdir(parents=True, exist_ok=True)
    pdf_path = output_dir / "lerch_thresholds.pdf"
    png_path = output_dir / "lerch_thresholds.png"
    metadata = {
        "Title": "Sufficient thresholds for Lerch zero saturation",
        "Author": "ProveIt research continuation",
        "Subject": (
            "Previous and new analytic sufficient bounds for n=3..40; "
            "exact finite polynomial-mesh bounds for n=3..16. "
            "The plotted bounds are not asserted to be sharp."
        ),
        "Creator": "make_figures.py (NumPy and Matplotlib)",
        "CreationDate": None,
        "ModDate": None,
    }
    fig.savefig(pdf_path, metadata=metadata)
    fig.savefig(png_path, dpi=dpi, metadata={
        "Title": metadata["Title"],
        "Description": metadata["Subject"],
        "Software": "make_figures.py (NumPy and Matplotlib)",
    })
    plt.close(fig)
    return pdf_path, png_path


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--certificates", type=Path, default=DEFAULT_CERTIFICATES,
                        help="mesh-certificate JSON (default: beside this script)")
    parser.add_argument("--output-dir", type=Path, default=PACKAGE_ROOT / "figures",
                        help="figure directory (default: package/figures)")
    parser.add_argument("--dpi", type=int, default=300, help="PNG resolution (default: 300)")
    args = parser.parse_args()
    if args.dpi <= 0:
        parser.error("--dpi must be positive")
    for path in make_figure(args.certificates.resolve(), args.output_dir.resolve(), args.dpi):
        print(path)


if __name__ == "__main__":
    main()
