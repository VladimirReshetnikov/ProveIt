#!/usr/bin/env python3
"""Create the single-file TeX convenience copy from the canonical article."""
from pathlib import Path


def main() -> None:
    root = Path(__file__).resolve().parents[1]
    source = (root/'article.tex').read_text()
    for weight in (8,10):
        name = f'generated/weight{weight}.tex'
        marker = r'\input{' + name + '}'
        if source.count(marker) != 1:
            raise ValueError(f'Expected exactly one input of {name}')
        source = source.replace(marker, f'% BEGIN {name}\n'+(root/name).read_text()+f'% END {name}\n')
    (root/'article-standalone.tex').write_text('% Generated by code/flatten_tex.py; edit article.tex instead.\n'+source)


if __name__ == '__main__':
    main()
