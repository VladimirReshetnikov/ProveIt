"""Emit exact rational Gaussian coefficients for one-2 words of weights 4-6.

Requires SymPy. Every coefficient is exported as two integers. The script
also verifies the assigned weight of every monomial before writing output.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import sympy as sp


def symbolic_context():
    names = ["ell", "pi", "G", "zeta_3", "zeta_5",
             "lambda_3", "lambda_4", "lambda_5", "lambda_6",
             "mu_4", "mu_5", "mu_6"]
    atoms = {name: sp.Symbol(name, real=True) for name in names}
    ell, pi, G = [atoms[name] for name in ("ell", "pi", "G")]
    L = -ell / 2 + sp.I * pi / 4
    values = {
        1: -sp.conjugate(L),
        2: 5*pi**2/96 - ell**2/8 + sp.I*(G-pi*ell/8),
        3: 35*atoms["zeta_3"]/64 - 5*pi**2*ell/192 + ell**3/48
           + sp.I*atoms["lambda_3"],
    }
    for k in (4, 5, 6):
        values[k] = atoms[f"mu_{k}"] + sp.I*atoms[f"lambda_{k}"]
    zeta = {2: pi**2/6, 3: atoms["zeta_3"], 4: pi**4/90,
            5: atoms["zeta_5"], 6: pi**6/945}
    weights = {"ell": 1, "pi": 1, "G": 2}
    weights.update({name: int(name.rsplit("_", 1)[1])
                    for name in names if "_" in name})
    return atoms, weights, L, values, zeta


def expression(a, b, context=None):
    if context is None:
        context = symbolic_context()
    atoms, weights, L, values, zeta = context
    n = a + b + 2
    return (
        sum((-1)**(a+k)*sp.binomial(k-1, a)*L**(n-k)
            / sp.factorial(n-k)*values[k]
            for k in range(a+1, n+1))
        + (-1)**(b+1)*sum(sp.binomial(b+j+1, j)*L**(a-j)
                          / sp.factorial(a-j)*zeta[b+j+2]
                          for j in range(a+1))
        - L**n / sp.factorial(n)
    )


def emit(outdir):
    outdir = Path(outdir)
    outdir.mkdir(parents=True, exist_ok=True)
    context = symbolic_context()
    atoms, weights, _, _, _ = context
    result = {
        "schema": "one-two-gaussian-rational-polynomial-v1",
        "definition": "Li_indices(i,1,...,1), strictly decreasing indices",
        "half_point": "(1+i)/2",
        "atom_definitions": {
            "ell": "log(2)", "pi": "pi", "G": "Dirichlet beta(2)",
            "zeta_k": "Riemann zeta(k)",
            "lambda_k": "Im Li_k((1+i)/2)",
            "mu_k": "Re Li_k((1+i)/2)",
        },
        "assigned_weights": weights,
        "rows": [],
    }
    latex = ["% Generated by derive_rows.py; exact rational arithmetic."]
    for n in (4, 5, 6):
        for a in range(n - 1):
            b = n - a - 2
            indices = [1]*a + [2] + [1]*b
            full = expression(a, b, context)
            for component, operation in (("real", sp.re), ("imag", sp.im)):
                expr = sp.expand(operation(full))
                terms = []
                for exponents, coefficient in sp.Poly(expr, *atoms.values()).terms():
                    powers = {name: int(power) for name, power
                              in zip(atoms, exponents) if power}
                    assert sum(weights[name]*power for name, power
                               in powers.items()) == n
                    numerator, denominator = coefficient.as_numer_denom()
                    terms.append({"numerator": int(numerator),
                                  "denominator": int(denominator),
                                  "powers": powers})
                result["rows"].append({
                    "weight": n, "a": a, "b": b, "indices": indices,
                    "component": component, "terms": terms,
                    "sympy_expression": str(expr), "latex": sp.latex(expr),
                })
                opname = "Re" if component == "real" else "Im"
                subscripts = ",".join(map(str, indices))
                latex.extend([
                    f"% weight {n}, a={a}, b={b}, component={component}",
                    "\\[",
                    f"\\{opname}\\Li_{{{subscripts}}}(i) = " + sp.latex(expr),
                    "\\]",
                ])
    (outdir / "coefficients.json").write_text(
        json.dumps(result, indent=2) + "\n", encoding="utf-8")
    (outdir / "generated_rows.tex").write_text(
        "\n".join(latex) + "\n", encoding="utf-8")
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--outdir", default=str(
        Path(__file__).resolve().parents[3]/"results"/"independent"/"one_two"))
    args = parser.parse_args()
    result = emit(args.outdir)
    print(f"Generated {len(result['rows'])} exact rational rows; "
          "all assigned-weight checks passed.")
