#!/usr/bin/env python3
"""Numerical diagnostics for P2 and the fixed-exponent theorem.

These computations are not interval certificates.  Exact interval certificates
are generated by polylog_research.py.  No network access is used.
"""
from pathlib import Path
import json
import mpmath as mp
import sympy as sp
from polylog_research import normalized_integral
from transition_polynomials import polynomials


def fixed_exponent_normalized(p, r: int, a):
    """Return T divided by the leading term in the fixed-p theorem.

The factor r! and the exponentially small power (log 2)^r are cancelled
analytically, before quadrature.  x=v^p removes the v=0 singularity.
    """
    p, a = mp.mpf(p), mp.mpf(a)
    if p <= 0 or a <= 0 or r < 1:
        raise ValueError('require p,a>0, integer r>=1')
    b = mp.log(2)
    def f(x):
        y = 2*b*mp.power(x, 1/p)/r
        t = mp.exp(-y)
        return mp.exp(-a*y)/(1+t)*mp.power(mp.log1p(t)/b, r)
    return 2*mp.quad(f, [0, 1, mp.power(4,p), mp.power(16,p), mp.inf])/mp.gamma(p+1)


def main():
    mp.mp.dps = 55
    variables, P = polynomials(2)
    funcs = [sp.lambdify(variables, p, 'mpmath') for p in P]
    trans = []
    for a in [mp.mpf(1)/3, mp.mpf(2)]:
        for r in [80, 320, 1280]:
            L = mp.log(r)
            lam = mp.mpf('0.5')
            value = normalized_integral(r*L, r, a)
            approximations = [mp.exp(-lam)*sum(funcs[j](a,L,lam)/mp.mpf(r)**j
                                              for j in range(k+1)) for k in range(3)]
            errors = [abs(value-v) for v in approximations]
            assert errors[2] < errors[1] < errors[0]
            trans.append({'a':mp.nstr(a,20), 'r':r, 'c':0,
                          'value':mp.nstr(value,35),
                          'errors_orders_0_1_2':[mp.nstr(v,12) for v in errors],
                          'scaled_second_order_remainder':mp.nstr((value-approximations[2])*r**3/L**3,12)})
    fixed = []
    for p in [mp.mpf('0.75'), mp.mpf(2), mp.mpf(5)]:
        a = mp.mpf('0.5')
        for r in [20, 80, 320]:
            value = fixed_exponent_normalized(p,r,a)
            first = 1+((1-2*a)*mp.log(2)*p+(mp.log(2)-1)*p*(p+1)/2)/r
            err0, err1 = abs(value-1), abs(value-first)
            assert err1 < err0
            fixed.append({'p':str(p), 'a':'1/2', 'r':r,
                          'normalized_value':mp.nstr(value,35),
                          'leading_error':mp.nstr(err0,12),
                          'first_corrected_error':mp.nstr(err1,12),
                          'scaled_remainder':mp.nstr((value-first)*r*r,12)})
    result={'status':'PASS', 'mpmath_dps':mp.mp.dps,
            'scope':'15 non-interval numerical diagnostics; asymptotic improvements checked at these points only.',
            'transition_second_order':trans, 'fixed_exponent':fixed}
    out=Path(__file__).resolve().parents[1]/'results'/'additional_diagnostics.json'
    out.write_text(json.dumps(result,indent=2)+'\n')
    print('PASS: 6 second-order transition cases and 9 fixed-exponent cases.')

if __name__ == '__main__':
    main()
