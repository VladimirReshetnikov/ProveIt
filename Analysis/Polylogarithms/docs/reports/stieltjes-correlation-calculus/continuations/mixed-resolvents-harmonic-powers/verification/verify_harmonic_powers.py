"""Independent finite diagnostics for the higher-digamma reduction.

This verifies finite polynomial identities, the separate printed fifth
finite sum, and compiled moving-order identities on finite lattices.
Classical convergent MZV reductions are explicitly enumerated inputs,
not assertions established by the tests. The analytic proof is in TeX.
"""

import argparse
import json
import platform
from functools import lru_cache
from pathlib import Path

import sympy as s

from harmonic_power_reduce import PowerReduction


@lru_cache(None)
def H(N, word):
    if not word:
        return s.S(1)
    if N <= 0:
        return s.S(0)
    return sum(s.Rational(1, n ** word[0]) * H(n - 1, word[1:])
               for n in range(1, N + 1))


def verify():
    checks = []

    def check(name, expression):
        ok = s.expand(expression) == 0
        checks.append({"name": name, "passed": ok})
        if not ok:
            raise AssertionError((name, s.expand(expression)))

    R = PowerReduction(5).run()
    g = R.g
    z2, z3, z4, z5 = (R.z[j] for j in range(2, 6))
    b, c, d, e, x = s.symbols("b c d e x")
    r = -b**4 + 6*b*b*c - 2*c*c - 4*b*d + e
    a = -b**3 + 3*b*c - d
    dr = r.subs({b: b+x, c: c+x*x, d: d+x**3, e: e+x**4}) - r
    check("residue difference hp:resdiff", dr - (4*a*x + 2*c*x*x + 4*b*x**3))
    substitution = {b: R.H[0]-g, c: R.H[1]+z2, d: R.H[2]-z3, e: R.H[3]+z4}
    check("printed simple pole", R.p[1] - 5*r.subs(substitution))
    check("B5 minus C5", R.simplify(R.B-R.C) - (30*g*g*z2-60*g*z3+s.Rational(35,3)*z4))
    Cr = -g**5/5+6*g**3*z2-16*g*g*z3-s.Rational(13,2)*g*z4+12*z2*z3-s.Rational(69,5)*z5
    check("printed C5", R.C - 5*Cr)

    # This is the explicitly printed finite identity, not generated by
    # the quasi-shuffle compiler, and uses direct rational nested sums.
    A = 4*g**3-12*g*z2+4*z3
    C0 = -g**4+6*g*g*z2-4*g*z3-2*z2*z2+z4
    for N in range(1, 13):
        left = s.S(0)
        for n in range(1, N+1):
            values = {b:H(n,(1,))-g, c:H(n,(2,))+z2,
                      d:H(n,(3,))-z3, e:H(n,(4,))+z4}
            left += r.subs(values)/n
        right = (
            -24*H(N,(1,1,1,1,1))+24*g*H(N,(1,1,1,1))
            +12*(z2-g*g)*H(N,(1,1,1))+A*H(N,(1,1))+C0*H(N,(1,))
            -24*H(N,(2,1,1,1))+24*g*H(N,(2,1,1))
            +12*(z2-g*g)*H(N,(2,1))+A*H(N,(2,))
            +4*H(N,(1,1,3))+2*H(N,(1,2,2))+4*H(N,(1,3,1))
            +4*H(N,(2,3))+2*H(N,(3,2))+4*H(N,(4,1))
            -4*g*(H(N,(1,3))+H(N,(4,)))
            +2*z2*(H(N,(1,2))+H(N,(3,)))
        )
        check("finite fifth residue sum N="+str(N), left-right)

    # Compiler result against a direct finite lattice calculation at
    # several moving-order specializations, including the next power.
    for k in range(1, 7):
        Rk = PowerReduction(k).run()
        if k >= 2:
            check("maximal depth coefficient k="+str(k),
                  Rk.E.get((1,)*(k-1),0)+s.factorial(k))
        for N in (1, 3, 6):
            for u in (1, 2):
                left = s.S(0)
                for n in range(1, N+1):
                    now = {h:H(n,(j+1,)) for j,h in enumerate(Rk.H)}
                    prev = {h:H(n-1,(j+1,)) for j,h in enumerate(Rk.H)}
                    left += (Rk.p[1].subs(now)-Rk.p[1].subs(prev))/n**u
                right = sum(c*H(N,(word[0]+u,)+word[1:]) for word,c in Rk.E.items())
                check("finite E k=%d N=%d u=%d"%(k,N,u),Rk.simplify(left-right))

    # The original third and fourth formulas are useful convention checks.
    R2, R3, R4 = (PowerReduction(k).run() for k in (2,3,4))
    check("quadratic constant", R2.simplify(R2.B-R2.C)+2*R2.z[2])
    check("cubic constant", R3.simplify(R3.B-R3.C)-3*R3.z[2])
    check("quartic constant", R4.simplify(R4.B-R4.C)
          -(12*R4.z[3]-12*R4.g*R4.z[2]+18*R4.z[4]))
    return {
        "status": "all exact finite checks passed",
        "checks_count": len(checks),
        "checks": checks,
        "python": platform.python_version(),
        "sympy": s.__version__,
        "scope": "Finite algebra only; analytic claims are proved in the article",
    }


if __name__ == "__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument("--output", type=Path)
    args=parser.parse_args()
    result=json.dumps(verify(),indent=2)+"\n"
    if args.output:
        args.output.write_text(result,encoding="utf-8")
    print(result)
