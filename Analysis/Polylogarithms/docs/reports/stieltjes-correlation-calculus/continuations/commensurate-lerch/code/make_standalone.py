#!/usr/bin/env python3
"""Flatten the modular TeX into a self-contained source file."""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parents[1]
NAME='ProveIt_Commensurate_Lerch_Calculus_2026-10-10'
def expand(path:Path, stack=()):
    path=path.resolve()
    if path in stack:raise RuntimeError(f'Recursive TeX input: {path}')
    if not path.is_relative_to(ROOT):raise ValueError('Input outside the package')
    text=path.read_text(encoding='utf-8')
    def substitute(match):
        rel=match.group(1);target=ROOT/(rel if rel.endswith('.tex') else rel+'.tex')
        return f'% BEGIN {target.relative_to(ROOT)}\n'+expand(target,stack+(path,))+f'\n% END {target.relative_to(ROOT)}'
    return re.sub(r'\\input\{([^}]+)\}',substitute,text)
if __name__=='__main__':
    target=ROOT/(NAME+'.tex')
    target.write_text('% Generated by code/make_standalone.py. Edit the modular files.\n'+expand(ROOT/'article.tex'),encoding='utf-8')
    print(target)
