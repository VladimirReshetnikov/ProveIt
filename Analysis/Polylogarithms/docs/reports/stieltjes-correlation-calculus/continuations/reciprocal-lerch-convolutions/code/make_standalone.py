#!/usr/bin/env python3
"""Flatten the modular article into one self-contained LaTeX source file."""
from __future__ import annotations
import re
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
PATTERN=re.compile(r'\\input\{([^}]+)\}')

def expand(path: Path, active: set[Path]) -> str:
    path=path.resolve()
    if not path.is_relative_to(ROOT):
        raise ValueError(f'input outside package: {path}')
    if path in active:
        raise ValueError(f'cyclic LaTeX input: {path}')
    text=path.read_text(encoding='utf-8')
    def replace(match):
        rel=Path(match.group(1))
        if not rel.suffix:
            rel=rel.with_suffix('.tex')
        target=(ROOT/rel).resolve()
        return '\n% BEGIN '+str(rel)+'\n'+expand(target,active|{path})+'\n% END '+str(rel)+'\n'
    return PATTERN.sub(replace,text)

def main():
    target=ROOT/'reciprocal_lerch_convolutions.tex'
    target.write_text('% Generated by code/make_standalone.py; edit the modular sources.\n'+expand(ROOT/'article.tex',set()),encoding='utf-8')
    print(target)
if __name__=='__main__':
    main()
