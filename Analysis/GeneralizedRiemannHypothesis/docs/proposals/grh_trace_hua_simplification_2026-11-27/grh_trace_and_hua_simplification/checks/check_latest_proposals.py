#!/usr/bin/env python3
"""Record the late proposal-corpus update without changing the checkout.

Usage:
  python3 check_latest_proposals.py --repo /path/to/ProveIt --output manifest.json

Both commits must already exist in the checkout's Git object database.  This
script verifies snapshot facts; the mathematical overlap judgments are the
separate human-readable review, not conclusions generated by text search.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import subprocess
from pathlib import Path


BASELINE = "f2d6ab6c4b70ea73b2deac9e33ad966bc92ea36f"
LATEST = "51aa1e3b5807c635a6fb6244a9ce4678b9106bc6"
BASE = "Analysis/GeneralizedRiemannHypothesis/docs/proposals"
LEAN = "Analysis/GeneralizedRiemannHypothesis/Lean/grh"
PRIMARY_RELATIVE = [
    "grh-inert-prime-polynomial-coefficient/README.txt",
    "grh-inert-prime-polynomial-coefficient/report.tex",
    "grh_coefficient_contraction/README.md",
    "grh_coefficient_contraction/report.tex",
    "grh_finite_grids/README.md",
    "grh_finite_grids/report.tex",
]
TARGET_RELATIVE = [
    "src/Statements.lean",
    "src/Main.lean",
    "src/New/Main.lean",
    "src/New/Reduction/MainInequality.lean",
    "src/Lib/Adelic/TraceFormula/LineDeterminant.lean",
    "src/Lib/Adelic/TraceFormula/LevelCut.lean",
    "src/Lib/Adelic/TraceFormula/CuspidalComparison.lean",
    "src/New/Spanning/Multiplicities/EqualMultiplicities.lean",
    "src/New/Spanning/RemainingTerms/OneRealPlace.lean",
    "src/New/Spanning/RemainingTerms/SchurOrbit.lean",
    "src/Lib/General/Analysis/HolomorphicIntegrals.lean",
    "src/Lib/General/LinearAlgebra/HermitianMatrices.lean",
    "src/Lib/General/LinearAlgebra/MinorProducts.lean",
    "lean-toolchain",
    "lake-manifest.json",
    "lakefile.toml",
]


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    args = parser.parse_args()

    def git(*arguments: str) -> bytes:
        return subprocess.check_output(["git", "-C", str(args.repo), *arguments])

    def tree(revision: str, path: str) -> dict[str, str]:
        result = {}
        for record in git("ls-tree", "-rz", revision, "--", path).split(b"\0"):
            if not record:
                continue
            metadata, filename = record.split(b"\t", 1)
            _, object_type, object_id = metadata.decode().split()
            if object_type == "blob":
                result[filename.decode()] = object_id
        return result

    old = tree(BASELINE, BASE)
    new = tree(LATEST, BASE)
    relative = lambda path: path.removeprefix(BASE + "/")
    old_dirs = {relative(path).split("/")[0] for path in old}
    new_dirs = {relative(path).split("/")[0] for path in new}
    added = sorted(new_dirs - old_dirs)
    removed = sorted(old_dirs - new_dirs)
    common_files = sorted(old.keys() & new.keys())
    changed_common = [path for path in common_files if old[path] != new[path]]
    assert len(old_dirs) == 28 and len(new_dirs) == 29
    assert len(old_dirs | new_dirs) == 31
    assert added == [
        "grh-inert-prime-polynomial-coefficient",
        "grh_coefficient_contraction",
        "grh_finite_grids",
    ]
    assert removed == ["grh-class-count-finite-quotient", "rh_two_order_tests_proposal"]
    assert not changed_common

    def file_record(path: str) -> dict:
        data = git("show", f"{LATEST}:{path}")
        rel = relative(path)
        return {
            "repository_path": path,
            "proposal_relative_path": rel,
            "role": "primary_report_or_readme" if rel in PRIMARY_RELATIVE else "supporting_text",
            "git_blob": new[path],
            "sha256": hashlib.sha256(data).hexdigest(),
            "bytes": len(data),
            "physical_lines": len(data.splitlines()),
            "url": f"https://github.com/VladimirReshetnikov/ProveIt/blob/{LATEST}/{path}",
        }

    new_text_paths = sorted(
        path for path in new
        if relative(path).split("/")[0] in added
        and Path(path).suffix in {".tex", ".md", ".txt"}
    )
    text_records = [file_record(path) for path in new_text_paths]
    primary_records = [record for record in text_records if record["role"] == "primary_report_or_readme"]
    assert len(primary_records) == 6
    targets = []
    for rel in TARGET_RELATIVE:
        path = f"{LEAN}/{rel}"
        old_blob = git("rev-parse", f"{BASELINE}:{path}").decode().strip()
        new_blob = git("rev-parse", f"{LATEST}:{path}").decode().strip()
        assert old_blob == new_blob, path
        targets.append({"path": path, "baseline_blob": old_blob, "later_blob": new_blob, "unchanged": True})

    result = {
        "baseline_commit": BASELINE,
        "late_cutoff_commit": LATEST,
        "late_commit_committer_date_iso8601": git("show", "-s", "--format=%cI", LATEST).decode().strip(),
        "source_accounting_remains_at_baseline": True,
        "proposal_directory_counts": {
            "baseline": len(old_dirs),
            "late_cutoff": len(new_dirs),
            "old_new_union_excluded_as_existing_work": len(old_dirs | new_dirs),
        },
        "added_directories": added,
        "removed_but_retained_in_exclusion_audit": removed,
        "baseline_directories": sorted(old_dirs),
        "late_cutoff_directories": sorted(new_dirs),
        "union_directories": sorted(old_dirs | new_dirs),
        "common_proposal_file_count": len(common_files),
        "common_proposal_files_all_unchanged": not changed_common,
        "changed_common_proposal_files": changed_common,
        "new_primary_text_count": len(primary_records),
        "new_primary_text_bytes": sum(item["bytes"] for item in primary_records),
        "new_primary_texts_read_in_full": primary_records,
        "new_text_inventory_count": len(text_records),
        "new_text_inventory_scope": "Hashes and targeted keyword/future-direction screening; primary reports and READMEs were read in full. This field does not claim line-by-line review of all supporting texts.",
        "new_text_inventory": text_records,
        "target_and_configuration_files_compared": len(targets),
        "target_and_configuration_files_all_unchanged": True,
        "target_and_configuration_files": targets,
        "review_conclusion": {
            "canonical_negative_frame_and_bordered_hua": "No duplication found in the three new primary reports or their stated future directions.",
            "logarithmic_spectral_trace_transfer": "No duplication found in the three new primary reports or their stated future directions.",
            "scope": "Relative nonduplication against the audited 31-bundle union; no global literature-priority or full-proof-correctness claim.",
            "closest_new_item": "grh_finite_grids principal-minor matrix-flow companion: a near-identity exponential determinant estimate in MinorSecondOrder/OneMinor; different hypotheses, output, and consumers from both proposed replacements.",
        },
    }
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(result, indent=2) + "\n")
    print(json.dumps({
        "status": "passed",
        "baseline_dirs": len(old_dirs),
        "late_dirs": len(new_dirs),
        "union_dirs": len(old_dirs | new_dirs),
        "primary_texts": len(primary_records),
        "new_text_inventory": len(text_records),
        "unchanged_common_proposal_files": len(common_files),
        "unchanged_source_and_configuration_files": len(targets),
    }, indent=2))


if __name__ == "__main__":
    main()
