"""Reproduce the zeta prime-window diagnostic and the exact modulo-5 sieve.

Requires Python 3, numpy, scipy. The accompanying ordinate file is sufficient
for the default run. Pass --regenerate-zeros to recompute it using mpmath.
Settings and numerical cutoffs are described in window_demo.txt.
"""
import argparse
import cmath
import itertools
import math
from pathlib import Path

import numpy as np
from scipy.integrate import simpson
from scipy.interpolate import BSpline
from scipy.special import digamma, k0, roots_legendre

HERE = Path(__file__).resolve().parent
CENTER = 105.0
WIDTH = 72.0
ROOTS, WEIGHTS = roots_legendre(240)
Y = 6.0 * ROOTS


class Kernel:
    def __init__(self, paper_kernel):
        self.paper_kernel = paper_kernel
        self.order = 4 if paper_kernel else 6
        self.scale = WIDTH / self.order
        self.M = math.ceil(10 * math.log(math.log(CENTER)))
        self.radius = WIDTH + math.asinh(self.M) / math.pi if paper_kernel else 78.0
        self.spline = BSpline.basis_element(np.arange(self.order + 1), extrapolate=False)
        # The original profile has a closed-form mass. The second profile uses
        # the same normalized quadrature for both its real-space and Fourier forms.
        mass = 6.0 * np.dot(WEIGHTS, self.core(Y)) if paper_kernel else 2.0 * k0(1.0)
        self.quad = 6.0 * WEIGHTS / mass
        self.real_core = self.quad * self.core(Y)

    def core(self, z):
        if self.paper_kernel:
            return np.cosh(z) ** -2 * (1 + np.cosh(np.pi * z) / self.M) ** -self.M
        return np.exp(-np.cosh(z))

    def __call__(self, x):
        # The integration variable is the real part of the core argument.
        x = np.atleast_1d(np.asarray(x))
        u = (x.real[:, None] - Y + WIDTH) / (2.0 * self.scale)
        spline_density = np.nan_to_num(self.spline(u)) / (2.0 * self.scale)
        core = self.core(Y + 1j * x.imag[:, None])
        return np.sum(spline_density * core * self.quad, axis=1)

    def fourier(self, freq):
        frequencies = np.atleast_1d(np.asarray(freq))
        result = np.empty(len(frequencies))
        for start in range(0, len(frequencies), 2000):
            chunk = frequencies[start:start + 2000]
            core_transform = np.cos(chunk[:, None] * Y) @ self.real_core
            result[start:start + len(chunk)] = core_transform * np.sinc(self.scale * chunk / np.pi) ** self.order
        return result


def regenerate_zeros():
    import mpmath as mp

    mp.mp.dps = 23
    lines = ["# Positive zeros, indexed from 1. Generated by mpmath 1.3.0 zetazero at 23 decimal digits."]
    for n in itertools.count(1):
        t = mp.im(mp.zetazero(n))
        lines.append(f"{n} {mp.nstr(t, 18)}")
        if t > 185:
            break
    (HERE / "zeta_ordinates.txt").write_text("\n".join(lines) + "\n")


def prime_powers(limit):
    is_prime = np.ones(limit + 1, dtype=bool)
    is_prime[:2] = False
    for p in range(2, math.isqrt(limit) + 1):
        if is_prime[p]:
            is_prime[p*p::p] = False
    pairs = []
    for p in np.flatnonzero(is_prime):
        n = int(p)
        while n <= limit:
            pairs.append((n, math.log(p)))
            n *= int(p)
    pairs.sort()
    return map(np.asarray, zip(*pairs))


def show_character_matrix():
    # Map each value i^k to an *exactly representable* Gaussian integer.
    roots = [1, 1j, -1, -1j]
    discrete_log = {pow(2, j, 5): j for j in range(4)}
    primes = [11, 2, 19, 3]
    rows = [[roots[(j * discrete_log[p % 5]) % 4] for j in range(4)] for p in primes]
    det = 0j
    for perm in itertools.permutations(range(4)):
        inversions = sum(perm[i] > perm[j] for j in range(4) for i in range(j))
        det += (-1) ** inversions * math.prod(row[index] for row, index in zip(rows, perm))
    print("Modulo 5: primes", primes, "have residues", [p % 5 for p in primes])
    for row in rows:
        print(" ", row)
    print(f"Exact character determinant = {det}; squared magnitude = {round(abs(det)**2)}")


def demo(limit, step, kernel):
    radius = kernel.radius
    data = np.loadtxt(HERE / "zeta_ordinates.txt")
    assert np.array_equal(data[:, 0], np.arange(1, len(data) + 1))
    ordinates = data[:, 1]
    assert np.all(np.diff(ordinates) > 0)
    left = np.searchsorted(ordinates, CENTER - radius)
    right = np.searchsorted(ordinates, CENTER + radius)
    assert 0 < left < right < len(ordinates)
    selected = ordinates[left:right]
    prime_n, von_mangoldt = prime_powers(limit)
    prime_log = np.log(prime_n)
    gamma_t = np.linspace(CENTER - radius, CENTER + radius, round(2 * radius / step) + 1)
    gamma_density = (digamma(0.25 + 0.5j * gamma_t).real - np.log(np.pi)) / (2 * np.pi)
    print(f"Center {CENTER:g}; zero/gamma window [{CENTER-radius:g}, {CENTER+radius:g}]; prime powers <= {limit}.")
    print(f"Zeros #{left+1} ... #{right} ({len(selected)} in all); exterior neighbors {ordinates[left-1]:.9f}, {ordinates[right]:.9f}.")
    for p in (2, 3):
        freq = math.log(p)
        mean = kernel.fourier([freq])[0]

        def h(t):
            u = np.atleast_1d(t) - CENTER
            return kernel(u) * (np.exp(1j * freq * u) - mean)

        def h_hat(xi):
            return np.exp(-1j * CENTER * xi) * (kernel.fourier(xi - freq) - mean * kernel.fourier(xi))

        zeros = np.sum(h(selected))
        gamma = simpson(h(gamma_t) * gamma_density, x=gamma_t)
        poles = np.sum(h(np.array([0.5j, -0.5j])))
        prime_sum = np.sum((h_hat(prime_log) + h_hat(-prime_log)) * von_mangoldt / np.sqrt(prime_n)) / (2 * np.pi)
        factor = 2 * np.pi * math.sqrt(p) * cmath.exp(1j * CENTER * freq) / freq
        from_zeros = -factor * (zeros - gamma - poles)
        from_primes = factor * prime_sum
        raw_estimate = -factor * zeros
        print(f"p={p}: zero-only {raw_estimate:.10f}, gamma/pole-adjusted {from_zeros:.10f}")
        print(f"     prime-side {from_primes:.10f}, |adjusted-prime| {abs(from_zeros-from_primes):.3e}, |adjusted-1| {abs(from_zeros-1):.3e}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--regenerate-zeros", action="store_true")
    parser.add_argument("--paper-kernel", action="store_true", help="Use the height-dependent cutoff from the paper.")
    parser.add_argument("--prime-limit", type=int, default=100000)
    parser.add_argument("--gamma-step", type=float, default=0.05)
    args = parser.parse_args()
    if args.regenerate_zeros:
        regenerate_zeros()
    show_character_matrix()
    demo(args.prime_limit, args.gamma_step, Kernel(args.paper_kernel))
