#!/usr/bin/env python3
"""Exact finite checks; these do not verify analytic or geometric claims."""
from itertools import permutations
from fractions import Fraction
from math import factorial
from collections import Counter
import warnings
import sympy as sp
from sympy.utilities.exceptions import SymPyDeprecationWarning
warnings.filterwarnings('ignore', category=SymPyDeprecationWarning)

def compose(a,b): return tuple(a[b[i]] for i in range(len(a)))
def cycles(g):
    visited=set(); out=[]
    for i in range(len(g)):
        if i in visited: continue
        cyc=[]; j=i
        while j not in visited:
            visited.add(j); cyc.append(j); j=g[j]
        out.append(cyc)
    return out

def reflect_decomp(g):
    u=list(range(len(g))); v=u.copy()
    for cyc in cycles(g):
        h=len(cyc)
        for i,z in enumerate(cyc): u[z]=cyc[(1-i)%h]; v[z]=cyc[-i%h]
    return tuple(u),tuple(v)

def transpositions(g): return sum(len(c)==2 for c in cycles(g))
def check(n):
    identity=tuple(range(n)); t=(1,0)+tuple(range(2,n)); perms=list(permutations(range(n)))
    cycle_total=0; weighted=0; pattern_counts=Counter()
    for g in perms:
        cs=cycles(g); c=len(cs); cycle_total+=c
        u,v=reflect_decomp(g)
        assert compose(u,u)==identity and compose(v,v)==identity and compose(u,v)==g
        assert transpositions(u)+transpositions(v)==n-c
        pattern=tuple(sorted(map(len,cs)));pattern_counts[pattern]+=1
        r=factorial(n)//2 if g==identity else factorial(n-2) if pattern==(1,)*(n-2)+(2,) else 0
        # Direct coset enumeration for n<=5, formula checks for larger n.
        if n<=5:
            inv=lambda a:tuple(a.index(i) for i in range(n))
            count=sum(compose(compose(inv(a),g),a) in (identity,t) for a in perms)//2
            assert count==r
        weighted+=r
    H=sum((Fraction(1,k) for k in range(1,n+1)),Fraction(0))
    assert Fraction(cycle_total,len(perms))==H and weighted==len(perms)
    C=2*(n-H)
    print(f'S_{n}: {len(perms)} elements, mean cycles={H}, bound={C}, weight average={Fraction(weighted,len(perms))}; checks PASS')
    return pattern_counts

for n in range(2,9): check(n)
x=sp.symbols('x'); f=x**5-x-1
D=int(sp.discriminant(f,x)); assert D==2869==19*151

def pattern(p):
    factors=sp.factor_list(f,modulus=p)[1]
    assert all(e==1 for _,e in factors)
    return tuple(sorted(int(sp.degree(g,x)) for g,e in factors))
assert pattern(2)==(2,3) and pattern(3)==(5,)
# Prove group generated by the 5-cycle and any transposition is S5, exactly.
base=(1,2,3,4,0)
for i in range(5):
    for j in range(i+1,5):
        t=list(range(5));t[i],t[j]=t[j],t[i];t=tuple(t)
        seen={tuple(range(5))}; frontier=list(seen)
        while frontier:
            g=frontier.pop()
            for a in (base,t):
                h=compose(a,g)
                if h not in seen: seen.add(h);frontier.append(h)
        assert len(seen)==120
print('x^5-x-1: discriminant=2869, mod 2=(2,3), mod 3=(5); all 10 generation checks PASS')
counts=Counter(); witnesses={}; rows=[]
for p0 in sp.primerange(2,2001):
    p=int(p0)
    if D%p==0: continue
    pat=pattern(p);counts[pat]+=1; witnesses.setdefault(pat,p)
    if pat==(1,)*5: weight=60
    elif pat==(1,1,1,2): weight=6
    else: weight=0
    rows.append((p,'+'.join(map(str,pat)),weight))
print('Finite illustration (unramified p<=2000):')
for pat in sorted(counts): print(f'  {pat}: {counts[pat]}, first={witnesses[pat]}')
import csv
from pathlib import Path
with (Path(__file__).parent/'quintic_prime_sample.csv').open('w',newline='') as fobj:
    w=csv.writer(fobj);w.writerow(['p','factor_degrees','fixed_coset_weight']);w.writerows(rows)
print('All checks passed. No inference about asymptotic prime errors is made.')
