#!/usr/bin/env python3
"""Certify a low signed-zero discrepancy for the conjugate quartic characters mod 5.

Requires Python 3 and mpmath 1.3.0. Uses outward-rounded interval arithmetic
only for elementary real/complex operations. The two analytic bounds are in
rouche_certificate(). No external tables of L-function zeros are used.
"""
from fractions import Fraction
from math import factorial, isqrt, prod
from mpmath import iv

iv.dps = 40


def prime_power(n):
    """Return the unique prime base of a prime power, or None."""
    if n < 2:
        return None
    for p in range(2, isqrt(n) + 1):
        if n % p == 0:
            while n % p == 0:
                n //= p
            return p if n == 1 else None
    return n


def arithmetic_certificate():
    # chi(2)=i in the cyclic group generated by 2 modulo 5.
    log_two = {pow(2, j, 5): j for j in range(4)}
    p = 113
    lower, upper = Fraction(32 * p, 33), Fraction(33 * p, 32)
    box = range(lower.__ceil__(), upper.__floor__() + 1)
    powers = [n for n in box if prime_power(n)]
    assert powers == [p] and log_two[p % 5] == 3
    print(f"p = {p} in [100,200]; chi(p)=-i, conjugate(p)=+i; distance 2.")
    print(f"[32p/33,33p/32]=[{lower},{upper}]; prime powers present: {powers}.")


def l_enclosure(s, conjugate):
    """Euler--Maclaurin for each progression 5k+a, including 8th-order remainder."""
    chi = [0, 1, -1j if conjugate else 1j, 1j if conjugate else -1j, -1]
    assert s.real >= iv.mpf('0.5') and abs(s) <= 5
    value = iv.mpc(0)
    terms = 40
    bernoulli = [(1,6), (-1,30), (1,42), (-1,30)]
    for a in range(1, 5):
        start = iv.mpf(5 * terms + a)
        block = sum(iv.exp(-s * iv.log(5*k+a)) for k in range(terms))
        leading = iv.exp(-s * iv.log(start))
        tail = start / (5*(s-1)) + iv.mpf('0.5')
        for j, (num, den) in enumerate(bernoulli, 1):
            m = 2*j-1
            pochhammer = prod(s+k for k in range(m))
            tail += iv.mpf(num) / (den*factorial(2*j)) * pochhammer * (5/start)**m
        value += chi[a] * (block + leading * tail)
    # For each of the four progressions use sup |B8({x})|/8! <= 1/(30*8!)
    # (from its absolutely convergent cosine series). The integral of the
    # absolute 8th derivative is at most the following expression, since
    # |s|<=5, Re s>=1/2 and 5N+a>=200. Both coordinates are bounded by
    # the absolute remainder. All quantities in this bound are positive.
    bound = (4 * 5**7 * prod(range(5,13)) / iv.mpf(30 * factorial(8))
             * iv.mpf(200)**iv.mpf('-7.5') / iv.mpf('7.5'))
    assert bound < iv.mpf('4e-12')
    error = iv.mpf([-1, 1]) * bound
    return value + iv.mpc(error, error)


def rouche_certificate():
    c = iv.mpc('0.5', '4.13290')
    radius = iv.mpf('0.0001')
    delta = iv.mpf('0.0001')
    R = iv.mpf('0.25')
    M = iv.mpf(26)
    # L(s)=s integral_1^infty A(x)/x^(s+1) dx and |A(x)|<=sqrt(2) for
    # both characters, by listing the five partial sums in a period.
    assert iv.sqrt(2)*(abs(c)+R)/(c.real-R) < M
    small = l_enclosure(c, True)
    large = l_enclosure(c, False)
    assert abs(small) < iv.mpf('0.00000414')
    assert abs(large) > iv.mpf('1.97')
    difference_quotient = (l_enclosure(c+delta, True)-small)/delta
    # If L(c+z)=sum a_k z^k then |a_k|<=M/R^k. This controls both
    # the finite difference derivative error and the linearization error.
    derivative_error = M*delta/R**2/(1-delta/R)
    assert abs(difference_quotient)-derivative_error > iv.mpf('1.07')
    remainder = M*(radius/R)**2/(1-radius/R)
    assert remainder < iv.mpf('0.00000417')
    assert iv.mpf('0.00000414')+remainder < iv.mpf('1.07')*radius
    # Rouche with linear polynomial L'(c)z yields exactly one zero of
    # the conjugate character's L-series in |s-c|<radius, with multiplicity.
    variation = M*radius/(R-radius)
    assert variation < iv.mpf('0.011') < abs(large)
    # Hence the unconjugated character's L-function does not vanish there.
    # Reflection of zeros across the critical line fixes this disk, so its
    # unique zero is on the line. No use of GRH is needed for this example.
    print("c = 0.5 + 4.13290 i; disk radius 0.0001.")
    print("|L(c,conjugate)| < 0.00000414; |L'(c,conjugate)| > 1.07.")
    print("Linearization remainder on the circle < 0.00000417.")
    print("|L(c,chi)| > 1.97; variation on the disk < 0.011.")
    print("Certified: exactly one simple zero of L(s,conjugate) on the line")
    print("with 4.13280 < Im(s) < 4.13300, and no zero of L(s,chi) in the disk.")


if __name__ == '__main__':
    arithmetic_certificate()
    rouche_certificate()
