#!/usr/bin/env python3
"""Supplementary exact checks for Baire-Category Arithmetic Rigidity.

These tests exercise algebraic identities in Z + t Q[t]. They do not prove
category statements, statements about uncountable sets, or arbitrary rings.
The manuscript supplies conventional proofs of those results.

Run with Python 3.10+: python verify.py
No third-party packages are required.
"""
from __future__ import annotations
from collections import Counter
from fractions import Fraction as F
from pathlib import Path
import json
import random

Poly = tuple[F, ...]
ZERO: Poly = (F(0),)
ONE: Poly = (F(1),)
T: Poly = (F(0), F(1))


def norm(a: list[F] | tuple[F, ...]) -> Poly:
    b = list(a) or [F(0)]
    while len(b) > 1 and not b[-1]:
        b.pop()
    return tuple(b)


def add(a: Poly, b: Poly) -> Poly:
    return norm([(a[i] if i < len(a) else F(0)) +
                 (b[i] if i < len(b) else F(0))
                 for i in range(max(len(a), len(b)))])


def neg(a: Poly) -> Poly:
    return tuple(-x for x in a)


def sub(a: Poly, b: Poly) -> Poly:
    return add(a, neg(b))


def mul(a: Poly, b: Poly) -> Poly:
    c = [F(0)] * (len(a) + len(b) - 1)
    for i, x in enumerate(a):
        for j, y in enumerate(b):
            c[i + j] += x * y
    return norm(c)


def sign(a: Poly) -> int:
    return (a[-1] > 0) - (a[-1] < 0)


def abs_poly(a: Poly) -> Poly:
    return neg(a) if sign(a) < 0 else a


def lt(a: Poly, b: Poly) -> bool:
    return sign(sub(b, a)) > 0


def le(a: Poly, b: Poly) -> bool:
    return not lt(b, a)


def scalar(n: int) -> Poly:
    return (F(n),)


def monomial(d: int) -> Poly:
    if d < 0:
        raise ValueError('The exponent must be nonnegative.')
    return tuple([F(0)] * d + [F(1)])


def truncate(a: Poly, k: int) -> Poly:
    return norm(a[:k])


def sample(rng: random.Random, max_degree: int = 7) -> Poly:
    d = rng.randrange(max_degree + 1)
    return norm([F(rng.randint(-7, 7))] +
                [F(rng.randint(-7, 7), rng.randint(1, 7)) for _ in range(d)])


def main() -> None:
    rng = random.Random(20261003)
    counts: Counter[str] = Counter()

    def check(label: str, condition: bool) -> None:
        if not condition:
            raise AssertionError(f'Exact check failed: {label}')
        counts[label] += 1

    for _ in range(2400):
        r, s, u = (sample(rng) for _ in range(3))
        a = add(abs_poly(u), ONE)
        b = add(add(a, a), ONE)
        p, q = add(abs_poly(r), ONE), add(abs_poly(s), ONE)
        check('integer_constant_closed_add', add(r, s)[0].denominator == 1)
        check('integer_constant_closed_mul', mul(r, s)[0].denominator == 1)
        check('least_positive_unit', sign(r) <= 0 or le(ONE, r))
        check('positive_products', lt(ZERO, mul(p, q)))
        check('absolute_product', abs_poly(mul(r, s)) == mul(abs_poly(r), abs_poly(s)))
        check('distributivity', mul(r, add(s, u)) == add(mul(r, s), mul(r, u)))
        check('sign_trichotomy', sum((lt(r, s), r == s, lt(s, r))) == 1)
        if r != s:
            check('distinct_points_unit_separated', le(ONE, abs_poly(sub(r, s))))
            check('packing_separation', lt(add(a, a), abs_poly(mul(b, sub(r, s)))))
        # Difference completion of the nonnegative cone: r=(r+A)-A.
        A, B = add(abs_poly(r), ONE), add(abs_poly(s), ONE)
        rp, sp = add(r, A), add(s, B)
        check('positive_decompositions', le(ZERO, rp) and le(ZERO, sp))
        product_formula = sub(add(mul(rp, sp), mul(A, B)),
                              add(mul(rp, B), mul(A, sp)))
        check('grothendieck_product_formula', product_formula == mul(r, s))
        k = rng.randrange(1, 7)
        check('convolution_prefix_locality', truncate(mul(r, s), k) ==
              truncate(mul(truncate(r, k), truncate(s, k)), k))

    # In Z+t Q[t], the principal convex subgroup generated by t^d is exactly
    # the polynomials of degree <= d.  Multiplying a nonzero difference by
    # t^(d+1) moves it outside that subgroup.
    for d in range(9):
        a = monomial(d)
        for _ in range(180):
            r, s = sample(rng), sample(rng)
            if r != s:
                shifted = mul(monomial(d + 1), sub(r, s))
                check('convex_quotient_degree_escape', len(shifted) - 1 > d)
                for n in (1, 2, 7, 101):
                    check('convex_quotient_sample_bounds',
                          lt(mul(scalar(n), a), abs_poly(shifted)))

    # Formal-power-series inverse of 1-t: every finite truncation satisfies
    # a precise polynomial identity, which also tests the sign of the error.
    for n in range(101):
        geometric = tuple([F(1)] * (n + 1))
        check('completion_geometric_identity',
              mul(sub(ONE, T), geometric) == sub(ONE, monomial(n + 1)))

    result = {
        'title': 'Baire-Category Rigidity for Discretely Ordered Rings',
        'seed': 20261003,
        'arithmetic': 'Exact fractions; finite polynomials in Z + t Q[t]',
        'status': 'PASS',
        'checks_by_family': dict(sorted(counts.items())),
        'total_checks': sum(counts.values()),
        'scope': ('Finite exact algebraic checks only. No topological theorem, '
                  'uncountable cardinal assertion, or general ring theorem '
                  'is claimed to be verified by this script.'),
        'formal_proof_assistant_check': False,
    }
    target = Path(__file__).resolve().parent / 'verification_results.json'
    target.write_text(json.dumps(result, indent=2) + '\n', encoding='utf-8')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
