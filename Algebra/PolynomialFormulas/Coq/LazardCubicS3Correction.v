(** * Correcting the subgroup sentence in Lazard's cubic discussion

    The literal claim that [S3] has only one subgroup [A3 = C3] is false:
    every transposition generates a subgroup of order two.  The strongest
    statement needed by the cubic resolvent argument is that [A3 = C3] is
    the unique proper transitive subgroup of [S3].

    The proof below avoids enumerating subgroup records.  It derives the
    small permutation facts pointwise and proves the universal subgroup
    theorem structurally, using transitivity, Lagrange, Cauchy, parity, and
    a cardinality argument.  No native-code or external certificate is
    used. *)
Module PolynomialFormulasLazardCubicS3Correction.

Local Open Scope group_scope.
Local Open Scope action_scope.

Definition S3 := {perm 'I_3}.

Definition o0 : 'I_3 := @Ordinal 3 0 isT.
Definition o1 : 'I_3 := @Ordinal 3 1 isT.
Definition o2 : 'I_3 := @Ordinal 3 2 isT.

(** The standard cycle [(0 1 2)] in MathComp's multiplication convention. *)
Definition three_cycle : S3 :=
  (tperm o0 o1 * tperm o1 o2)%g.

Definition standard_C3 : {group S3} := <[three_cycle]>.
Definition standard_A3 : {group S3} := 'Alt_('I_3).

Definition transposition : S3 := tperm o0 o1.
Definition transposition_subgroup : {group S3} := <[transposition]>.

Lemma three_cycle_o0 : three_cycle o0 = o2.
Proof. by rewrite /three_cycle permM !tpermL. Qed.

Lemma three_cycle_o1 : three_cycle o1 = o0.
Proof.
rewrite /three_cycle permM tpermR.
by rewrite (tpermD (x := o1) (y := o2) (z := o0)).
Qed.

Lemma three_cycle_o2 : three_cycle o2 = o1.
Proof.
rewrite /three_cycle permM.
rewrite (tpermD (x := o0) (y := o1) (z := o2)) //.
exact: tpermR o1 o2.
Qed.

Lemma perm_expg3E (s : S3) i :
  (s ^+ 3) i = s (s (s i)).
Proof. by rewrite !expgS expg0 !permM perm1. Qed.

Lemma three_cycle_cube : three_cycle ^+ 3%N = 1%g.
Proof.
apply/permP=> i; rewrite perm1 perm_expg3E.
case: i=> [[|[|[|n]]] hn].
- have -> : @Ordinal 3 0 hn = o0 by apply: val_inj.
  by rewrite three_cycle_o0 three_cycle_o2 three_cycle_o1.
- have -> : @Ordinal 3 1 hn = o1 by apply: val_inj.
  by rewrite three_cycle_o1 three_cycle_o0 three_cycle_o2.
- have -> : @Ordinal 3 2 hn = o2 by apply: val_inj.
  by rewrite three_cycle_o2 three_cycle_o1 three_cycle_o0.
- by move: hn.
Qed.

Lemma three_cycle_ne_one : three_cycle != 1%g.
Proof.
have hc0 : three_cycle o0 != o0 by rewrite three_cycle_o0.
apply/eqP=> h.
by move: hc0; rewrite h perm1 eqxx.
Qed.

Lemma order_three_cycle : #[three_cycle] = 3%N.
Proof.
exact: nt_prime_order (isT : prime 3) three_cycle_cube
  three_cycle_ne_one.
Qed.

Lemma card_standard_C3 : #|standard_C3| = 3%N.
Proof. exact: order_three_cycle. Qed.

Lemma transposition_square : transposition ^+ 2%N = 1%g.
Proof. by rewrite !expgS expg0 mulg1 /transposition tperm2. Qed.

Lemma transposition_ne_one : transposition != 1%g.
Proof.
have ht0 : transposition o0 != o0.
  by rewrite /transposition tpermL.
apply/eqP=> h.
by move: ht0; rewrite h perm1 eqxx.
Qed.

Lemma order_transposition : #[transposition] = 2%N.
Proof.
exact: nt_prime_order (isT : prime 2) transposition_square
  transposition_ne_one.
Qed.

Lemma card_transposition_subgroup : #|transposition_subgroup| = 2%N.
Proof. exact: order_transposition. Qed.

Lemma card_standard_A3 : #|standard_A3| = 3%N.
Proof.
apply: double_inj.
by rewrite -mul2n /standard_A3 card_Alt card_ord.
Qed.

Lemma three_cycle_mem_standard_A3 : three_cycle \in standard_A3.
Proof.
rewrite /standard_A3 Alt_even /three_cycle odd_permM !odd_tperm.
by [].
Qed.

(** On three letters the alternating subgroup is exactly the subgroup
    generated by a three-cycle. *)
Lemma standard_C3_eq_standard_A3 : standard_C3 = standard_A3.
Proof.
have hsub : standard_C3 \subset standard_A3.
  by rewrite cycle_subG three_cycle_mem_standard_A3.
apply: val_inj; apply/eqP.
by rewrite eqEcard hsub card_standard_C3 card_standard_A3.
Qed.

Lemma transposition_subgroup_ne_standard_A3 :
  transposition_subgroup <> standard_A3.
Proof.
move=> h.
have hcard : #|transposition_subgroup| = #|standard_A3|.
  by rewrite h.
by rewrite card_transposition_subgroup card_standard_A3 in hcard.
Qed.

(** Formal counterexample to the literal "only one subgroup" reading. *)
Theorem printed_only_subgroup_sentence_false :
  exists H : {group S3},
    #|H| = 2%N /\ H <> standard_A3.
Proof.
exists transposition_subgroup.
split.
- exact: card_transposition_subgroup.
- exact: transposition_subgroup_ne_standard_A3.
Qed.

Lemma standard_C3_transitive :
  [transitive standard_C3, on [set: 'I_3] | 'P].
Proof.
rewrite standard_C3_eq_standard_A3 /standard_A3.
have htrans := Alt_trans ('I_3).
rewrite card_ord /= in htrans.
exact: ntransitive1 htrans.
Qed.

Lemma card_S3 : #|[set: S3]| = 6%N.
Proof. by rewrite cardsT /S3 card_Sn. Qed.

(** Odd permutations cannot have odd order three. *)
Lemma cube_one_mem_standard_A3 (c : S3) :
  c ^+ 3%N = 1%g -> c \in standard_A3.
Proof.
move=> hcube.
rewrite /standard_A3 Alt_even.
case hodd: (odd_perm c) => //.
have hodd_cube : odd_perm (c ^+ 3%N) = odd_perm (1%g : S3).
  by rewrite hcube.
move: hodd_cube.
by rewrite !expgSr expg0 mul1g !odd_permM odd_perm1 hodd.
Qed.

Lemma three_dvd_divisor_six_not_six (n : nat) :
  (3 %| n)%N -> (n %| 6)%N -> n != 6%N -> n = 3%N.
Proof.
move=> h3 h6 hn6.
have hnle : (n <= 6)%N := @dvdn_leq n 6 isT h6.
move: hnle h3 h6 hn6.
by case: n => [|[|[|[|[|[|[|n]]]]]]] //=.
Qed.

Definition proper_transitiveb (G : {group S3}) : bool :=
  [transitive G, on [set: 'I_3] | 'P] &&
    (G != [set: S3]%G).

(** Structural certificate for the universal corrected classification.
    Transitivity and Lagrange force the order to be three or six;
    properness removes six, and Cauchy's theorem supplies the standard
    order-three subgroup. *)
Lemma proper_transitive_subgroup_certificate :
  [forall G : {group S3},
    proper_transitiveb G ==> (G == standard_C3)].
Proof.
apply/forallP=> G; apply/implyP.
rewrite /proper_transitiveb.
case/andP=> htrans hproper.
have h3div : (3 %| #|G|)%N.
  by move: (atrans_dvd htrans); rewrite cardsT card_ord.
have [c cG hcorder] := Cauchy (isT : prime 3) h3div.
have hcube_one : c ^+ 3%N = 1%g.
  have hc_pow := expg_order c.
  by rewrite hcorder in hc_pow.
have hcA : c \in standard_A3.
  exact: cube_one_mem_standard_A3 hcube_one.
have hcycleA : <[c]>%g \subset standard_A3.
  by rewrite cycle_subG.
have hcyclecard : #|<[c]>%g| = 3%N.
  exact: hcorder.
have hcycleAeq : <[c]>%g == standard_A3.
  by rewrite eqEcard hcycleA hcyclecard card_standard_A3.
have hcycle : <[c]>%g = standard_C3.
  apply/eqP.
  by rewrite standard_C3_eq_standard_A3 hcycleAeq.
have hCsub : standard_C3 \subset G.
  by rewrite -hcycle cycle_subG.
have hcarddiv : (#|G| %| 6)%N.
  have hsubtop : G \subset [set: S3]%G := subsetT G.
  move: (cardSg hsubtop).
  by rewrite card_S3.
have hcardne6 : #|G| != 6%N.
  apply/negP=> /eqP hcard6.
  have htop : G = [set: S3]%G.
    apply: val_inj; apply/eqP.
    by rewrite eqEcard subsetT hcard6 card_S3.
  by move: hproper; rewrite htop eqxx.
have hcard : #|G| = 3%N :=
  three_dvd_divisor_six_not_six h3div hcarddiv hcardne6.
apply/eqP; apply: val_inj; apply/eqP.
by rewrite eq_sym eqEcard hCsub card_standard_C3 hcard.
Qed.

(** Strongest intended correction: a proper transitive subgroup is equal,
    not merely conjugate, to [A3 = C3]. *)
Theorem unique_proper_transitive_subgroup (G : {group S3}) :
  [transitive G, on [set: 'I_3] | 'P] ->
  G <> [set: S3]%G ->
  G = standard_C3.
Proof.
move=> htrans hproper.
have hproperb : G != [set: S3]%G.
  apply/negP=> /eqP htop.
  exact: hproper htop.
have hante : proper_transitiveb G.
  by rewrite /proper_transitiveb htrans hproperb.
have hcert := forallP proper_transitive_subgroup_certificate G.
exact/eqP/(implyP hcert hante).
Qed.

Theorem unique_proper_transitive_subgroup_is_A3 (G : {group S3}) :
  [transitive G, on [set: 'I_3] | 'P] ->
  G <> [set: S3]%G ->
  G = standard_A3.
Proof.
move=> htrans hproper.
rewrite -standard_C3_eq_standard_A3.
exact: unique_proper_transitive_subgroup htrans hproper.
Qed.

Print Assumptions standard_C3_eq_standard_A3.
Print Assumptions printed_only_subgroup_sentence_false.
Print Assumptions proper_transitive_subgroup_certificate.
Print Assumptions unique_proper_transitive_subgroup.
Print Assumptions unique_proper_transitive_subgroup_is_A3.

End PolynomialFormulasLazardCubicS3Correction.
