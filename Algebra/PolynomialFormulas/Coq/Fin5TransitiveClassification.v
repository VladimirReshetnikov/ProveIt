(** * The transitive subgroups of [S5]

    This is the corrected form of the group-theoretic classification used in
    Section 5 of Lazard's paper.  There are five conjugacy classes of
    transitive subgroups of [S5]: [C5], [D5], [F20], [A5], and [S5].
    Lazard's displayed four-item list is the list of *proper* transitive
    subgroups, and is stated separately below with that hypothesis.

    The concrete calculations are finite boolean certificates checked by
    Coq's kernel through [vm_compute].  No axiom, admitted fact, or native-code
    certificate is used. *)
Module PolynomialFormulasFin5TransitiveClassification.

Module F20 := PolynomialFormulasQuinticF20Data.
Module SolvableCriterion := PolynomialFormulasQuinticSolvableCriterion.

Local Open Scope group_scope.
Local Open Scope action_scope.

Local Notation S5 := F20.S5.

(** ** The explicit standard [D5] *)

(** In the affine model, [multiplier_two] is multiplication by 2 modulo 5,
    so its square is the reflection [x |-> -x]. *)
Definition reflection : S5 := F20.multiplier_two ^+ 2.

(** The subgroup generated by translations and the reflection. *)
Definition standard_D5 : {group S5} :=
  F20.standard_C5 <*> <[reflection]>.

Definition standard_A5 : {group S5} := 'Alt_('I_5).

Lemma reflection_order_two : #[reflection] = 2%N.
Proof. vm_compute. Qed.

Lemma reflection_conjugates_five_cycle_to_inverse :
  F20.five_cycle ^ reflection = F20.five_cycle^-1.
Proof. apply/eqP; vm_compute. Qed.

Lemma standard_C5_sub_standard_D5 :
  F20.standard_C5 \subset standard_D5.
Proof. exact: joing_subl _ _. Qed.

Lemma standard_D5_sub_standard_F20 :
  standard_D5 \subset F20.standard_F20.
Proof.
rewrite /standard_D5 join_subG.
apply/andP; split.
- exact: normG F20.standard_C5.
- rewrite cycle_subG /reflection.
  exact: groupX F20.multiplier_two_mem_standard_F20.
Qed.

Lemma card_standard_D5 : #|standard_D5| = 10%N.
Proof. vm_compute. Qed.

Lemma index_standard_C5_in_standard_D5 :
  #|standard_D5 : F20.standard_C5| = 2%N.
Proof. vm_compute. Qed.

Lemma index_standard_D5_in_standard_F20 :
  #|F20.standard_F20 : standard_D5| = 2%N.
Proof. vm_compute. Qed.

Lemma standard_C5_D5_F20_chain :
  F20.standard_C5 \subset standard_D5 /\
  standard_D5 \subset F20.standard_F20.
Proof.
split.
- exact: standard_C5_sub_standard_D5.
- exact: standard_D5_sub_standard_F20.
Qed.

(** ** Transitivity of the affine groups *)

Lemma standard_C5_transitive :
  [transitive F20.standard_C5, on [set: 'I_5] | 'P].
Proof. vm_compute. Qed.

(** The affine group is 2-transitive. *)
Lemma standard_F20_two_transitive :
  [transitive^2 F20.standard_F20, on [set: 'I_5] | 'P].
Proof. vm_compute. Qed.

Definition pair_map_set (G : {group S5})
    (a b c d : 'I_5) : {set S5} :=
  [set g in G | (g a == c) && (g b == d)].

Definition sharply_two_transitiveb (G : {group S5}) : bool :=
  [forall a : 'I_5,
    [forall b : 'I_5, (a != b) ==>
      [forall c : 'I_5,
        [forall d : 'I_5, (c != d) ==>
          (#|pair_map_set G a b c d| == 1%N)]]]].

Lemma standard_F20_sharply_two_transitive_certificate :
  sharply_two_transitiveb F20.standard_F20.
Proof. vm_compute. Qed.

Lemma standard_F20_pair_map_card a b c d :
  a != b -> c != d ->
  #|pair_map_set F20.standard_F20 a b c d| = 1%N.
Proof.
move=> ab cd.
have h := standard_F20_sharply_two_transitive_certificate.
rewrite /sharply_two_transitiveb in h.
have h := forallP h a.
have h := forallP h b.
have h := implyP h ab.
have h := forallP h c.
have h := forallP h d.
exact/eqP/(implyP h cd).
Qed.

(** Sharp 2-transitivity in its ordinary, proof-relevant form. *)
Lemma standard_F20_exists_unique_map_pair a b c d :
  a != b -> c != d ->
  exists! g : S5,
    g \in F20.standard_F20 /\ g a = c /\ g b = d.
Proof.
move=> ab cd.
have hcard : #|pair_map_set F20.standard_F20 a b c d| == 1%N.
  apply/eqP.
  exact: standard_F20_pair_map_card ab cd.
case/card1P: hcard=> g singleton_g.
have gset : g \in pair_map_set F20.standard_F20 a b c d.
  by rewrite singleton_g eqxx.
move: gset; rewrite /pair_map_set inE.
case/andP=> gF /andP[/eqP gac /eqP gbd].
exists g; first by split=> //; split.
move=> h [hF [hac hbd]].
apply/eqP.
have hset : h \in pair_map_set F20.standard_F20 a b c d.
  by rewrite /pair_map_set inE hF hac hbd !eqxx.
by move: hset; rewrite singleton_g inE.
Qed.

(** ** A one-generator finite certificate for the normalized classification *)

Definition generated_with_C5 (g : S5) : {group S5} :=
  F20.standard_C5 <*> <[g]>.

Definition expected_generated_with_C5 (g : S5) : {group S5} :=
  if g \in F20.standard_C5 then F20.standard_C5
  else if g \in standard_D5 then standard_D5
  else if g \in F20.standard_F20 then F20.standard_F20
  else if ~~ odd_perm g then standard_A5
  else [set: S5]%G.

(** Adjoining one permutation to the standard 5-cycle produces precisely the
    first group in the chain [C5,D5,F20,A5,S5] that contains it. *)
Lemma generated_with_C5_certificate :
  [forall g : S5,
    generated_with_C5 g == expected_generated_with_C5 g].
Proof. vm_compute. Qed.

Definition generated_with_A5 (g : S5) : {group S5} :=
  standard_A5 <*> <[g]>.

Definition expected_generated_with_A5 (g : S5) : {group S5} :=
  if ~~ odd_perm g then standard_A5 else [set: S5]%G.

Lemma generated_with_A5_certificate :
  [forall g : S5,
    generated_with_A5 g == expected_generated_with_A5 g].
Proof. vm_compute. Qed.

Lemma generated_with_C5_sub (G : {group S5}) g :
  F20.standard_C5 \subset G -> g \in G -> generated_with_C5 g \subset G.
Proof.
move=> CG Gg.
by rewrite /generated_with_C5 join_subG cycle_subG CG Gg.
Qed.

Lemma generated_with_A5_sub (G : {group S5}) g :
  standard_A5 \subset G -> g \in G -> generated_with_A5 g \subset G.
Proof.
move=> AG Gg.
by rewrite /generated_with_A5 join_subG cycle_subG AG Gg.
Qed.

Lemma subgroup_above_standard_A5 (G : {group S5}) :
  standard_A5 \subset G ->
  G = standard_A5 \/ G = [set: S5]%G.
Proof.
move=> AG; case GA: (G \subset standard_A5).
- left; apply: val_inj; apply/eqP.
  by rewrite eqEsubset GA AG.
- right.
  case/subsetPn: GA=> g Gg notAg.
  have oddg : odd_perm g.
    by move: notAg; rewrite /standard_A5 Alt_even negbK.
  have hgen := eqP (forallP generated_with_A5_certificate g).
  rewrite /expected_generated_with_A5 oddg in hgen.
  have topG : [set: S5]%G \subset G.
    rewrite -hgen.
    exact: generated_with_A5_sub AG Gg.
  apply: val_inj; apply/eqP.
  by rewrite eqEsubset subsetT topG.
Qed.

Inductive transitive_class : Type :=
  | class_C5
  | class_D5
  | class_F20
  | class_A5
  | class_S5.

Definition class_subgroup (c : transitive_class) : {group S5} :=
  match c with
  | class_C5 => F20.standard_C5
  | class_D5 => standard_D5
  | class_F20 => F20.standard_F20
  | class_A5 => standard_A5
  | class_S5 => [set: S5]%G
  end.

Definition class_card (c : transitive_class) : nat :=
  match c with
  | class_C5 => 5
  | class_D5 => 10
  | class_F20 => 20
  | class_A5 => 60
  | class_S5 => 120
  end.

Lemma card_standard_A5 : #|standard_A5| = 60%N.
Proof. vm_compute. Qed.

Lemma card_S5 : #|[set: S5]| = 120%N.
Proof. vm_compute. Qed.

Lemma card_class_subgroup c : #|class_subgroup c| = class_card c.
Proof.
case: c=> /=.
- exact: F20.card_standard_C5.
- exact: card_standard_D5.
- exact: F20.card_standard_F20.
- exact: card_standard_A5.
- exact: card_S5.
Qed.

Lemma class_card_injective c d :
  class_card c = class_card d -> c = d.
Proof. by case: c; case: d. Qed.

(** Classification of a subgroup already normalized to contain the standard
    [C5].  The repeated adjoining argument is isolated in the two lemmas
    [generated_with_C5_sub] and [generated_with_A5_sub]. *)
Lemma normalized_transitive_classification (G : {group S5}) :
  F20.standard_C5 \subset G ->
  exists c : transitive_class, G = class_subgroup c.
Proof.
move=> CG.
case GF: (G \subset F20.standard_F20).
- case GD: (G \subset standard_D5).
  + case GC: (G \subset F20.standard_C5).
    * exists class_C5; apply: val_inj; apply/eqP.
      by rewrite eqEsubset GC CG.
    * case/subsetPn: GC=> g Gg notCg.
      have Dg : g \in standard_D5 := subsetP GD _ Gg.
      have hgen := eqP (forallP generated_with_C5_certificate g).
      rewrite /expected_generated_with_C5 notCg Dg in hgen.
      have DG : standard_D5 \subset G.
        rewrite -hgen.
        exact: generated_with_C5_sub CG Gg.
      exists class_D5; apply: val_inj; apply/eqP.
      by rewrite eqEsubset GD DG.
  + case/subsetPn: GD=> g Gg notDg.
    have Fg : g \in F20.standard_F20 := subsetP GF _ Gg.
    have notCg : g \notin F20.standard_C5.
      apply/negP=> Cg.
      move: notDg.
      by rewrite (subsetP standard_C5_sub_standard_D5 _ Cg).
    have hgen := eqP (forallP generated_with_C5_certificate g).
    rewrite /expected_generated_with_C5 notCg notDg Fg in hgen.
    have FG : F20.standard_F20 \subset G.
      rewrite -hgen.
      exact: generated_with_C5_sub CG Gg.
    exists class_F20; apply: val_inj; apply/eqP.
    by rewrite eqEsubset GF FG.
- case/subsetPn: GF=> g Gg notFg.
  have notDg : g \notin standard_D5.
    apply/negP=> Dg.
    move: notFg.
    by rewrite (subsetP standard_D5_sub_standard_F20 _ Dg).
  have notCg : g \notin F20.standard_C5.
    apply/negP=> Cg.
    move: notDg.
    by rewrite (subsetP standard_C5_sub_standard_D5 _ Cg).
  case eveng: (~~ odd_perm g).
  + have hgen := eqP (forallP generated_with_C5_certificate g).
    rewrite /expected_generated_with_C5 notCg notDg notFg eveng in hgen.
    have AG : standard_A5 \subset G.
      rewrite -hgen.
      exact: generated_with_C5_sub CG Gg.
    case: (subgroup_above_standard_A5 AG)=> hG.
    * by exists class_A5.
    * by exists class_S5.
  + have hgen := eqP (forallP generated_with_C5_certificate g).
    rewrite /expected_generated_with_C5 notCg notDg notFg eveng in hgen.
    have topG : [set: S5]%G \subset G.
      rewrite -hgen.
      exact: generated_with_C5_sub CG Gg.
    exists class_S5; apply: val_inj; apply/eqP.
    by rewrite eqEsubset subsetT topG.
Qed.

(** ** Normalization by a Sylow 5-subgroup *)

Lemma transitive_contains_conjugate_standard_C5 (G : {group S5}) :
  [transitive G, on [set: 'I_5] | 'P] ->
  exists s : S5, F20.standard_C5 :^ s \subset G.
Proof.
move=> transG.
have five_dvd_G : (5 %| #|G|)%N.
  move: (atrans_dvd transG).
  by rewrite cardsT card_ord.
have [c cG order_c] := Cauchy (isT : prime 5) five_dvd_G.
have sylow_c : 5.-Sylow([set: S5]) <[c]>.
  rewrite pHallE subsetT -orderE order_c cardsT /F20.S5 card_Sn.
  rewrite andTb p_part (logn_fact 5) //.
  do 5! rewrite big_nat_recr //=.
  by rewrite big_geq //=.
have [s _ cycle_conj] := Sylow_trans F20.standard_C5_sylow sylow_c.
have cycle_sub_G : <[c]> \subset G.
  apply/subsetP=> x /cycleP[i ->].
  exact: groupX cG.
exists s.
by rewrite -cycle_conj.
Qed.

Definition is_conjugate_to_class
    (G : {group S5}) (c : transitive_class) : Prop :=
  exists s : S5, G = class_subgroup c :^ s.

Lemma transitive_classification_exists (G : {group S5}) :
  [transitive G, on [set: 'I_5] | 'P] ->
  exists c : transitive_class, is_conjugate_to_class G c.
Proof.
move=> transG.
have [s CsG] := transitive_contains_conjugate_standard_C5 transG.
have Cnorm : F20.standard_C5 \subset G :^ s^-1.
  by move: CsG; rewrite sub_conjg.
have [c normalized] := normalized_transitive_classification Cnorm.
exists c, s.
by rewrite -(conjsgKV s G) normalized.
Qed.

Lemma card_of_is_conjugate_to_class G c :
  is_conjugate_to_class G c -> #|G| = class_card c.
Proof.
case=> s ->.
by rewrite cardJg card_class_subgroup.
Qed.

(** Corrected classification: every transitive subgroup of [S5] is conjugate
    to exactly one of [C5,D5,F20,A5,S5]. *)
Theorem transitive_subgroup_classification (G : {group S5}) :
  [transitive G, on [set: 'I_5] | 'P] ->
  exists! c : transitive_class, is_conjugate_to_class G c.
Proof.
move=> transG.
have [c conjugate_c] := transitive_classification_exists transG.
exists c=> // d conjugate_d.
apply: class_card_injective.
rewrite -(card_of_is_conjugate_to_class conjugate_d)
  -(card_of_is_conjugate_to_class conjugate_c).
reflexivity.
Qed.

(** ** Lazard's four-item list: the proper case *)

Inductive lazard_proper_class : Type :=
  | proper_C5
  | proper_D5
  | proper_F20
  | proper_A5.

Definition proper_class_subgroup (c : lazard_proper_class) : {group S5} :=
  match c with
  | proper_C5 => F20.standard_C5
  | proper_D5 => standard_D5
  | proper_F20 => F20.standard_F20
  | proper_A5 => standard_A5
  end.

Definition proper_class_card (c : lazard_proper_class) : nat :=
  match c with
  | proper_C5 => 5
  | proper_D5 => 10
  | proper_F20 => 20
  | proper_A5 => 60
  end.

Definition is_conjugate_to_proper_class
    (G : {group S5}) (c : lazard_proper_class) : Prop :=
  exists s : S5, G = proper_class_subgroup c :^ s.

Lemma card_proper_class_subgroup c :
  #|proper_class_subgroup c| = proper_class_card c.
Proof.
case: c=> /=.
- exact: F20.card_standard_C5.
- exact: card_standard_D5.
- exact: F20.card_standard_F20.
- exact: card_standard_A5.
Qed.

Lemma proper_class_card_injective c d :
  proper_class_card c = proper_class_card d -> c = d.
Proof. by case: c; case: d. Qed.

Lemma card_of_is_conjugate_to_proper_class G c :
  is_conjugate_to_proper_class G c -> #|G| = proper_class_card c.
Proof.
case=> s ->.
by rewrite cardJg card_proper_class_subgroup.
Qed.

(** Lazard's four groups, now with the missing properness hypothesis stated
    explicitly. *)
Theorem lazard_proper_transitive_subgroup_classification (G : {group S5}) :
  [transitive G, on [set: 'I_5] | 'P] ->
  G != [set: S5]%G ->
  exists! c : lazard_proper_class, is_conjugate_to_proper_class G c.
Proof.
move=> transG properG.
have [c conjugate_c] := transitive_classification_exists transG.
have proper_exists :
    exists c : lazard_proper_class, is_conjugate_to_proper_class G c.
  case: c conjugate_c=> conjugate_c.
  - by exists proper_C5.
  - by exists proper_D5.
  - by exists proper_F20.
  - by exists proper_A5.
  - case: conjugate_c=> s top_conj.
    have topG : G = [set: S5]%G.
      by move: top_conj; rewrite /class_subgroup conjTg.
    by move: properG; rewrite topG eqxx.
case: proper_exists=> c conjugate_c.
exists c=> // d conjugate_d.
apply: proper_class_card_injective.
rewrite -(card_of_is_conjugate_to_proper_class conjugate_d)
  -(card_of_is_conjugate_to_proper_class conjugate_c).
reflexivity.
Qed.

(** ** Maximal solvability and the six conjugates of [F20] *)

Lemma transitive_of_standard_C5_sub (G : {group S5}) :
  F20.standard_C5 \subset G ->
  [transitive G, on [set: 'I_5] | 'P].
Proof.
move=> CG.
rewrite (atrans_supgroup CG standard_C5_transitive).
apply/actsP=> g Gg x.
by rewrite !inE.
Qed.

(** No strictly larger subgroup containing the standard [F20] is solvable. *)
Theorem standard_F20_maximal_solvable (G : {group S5}) :
  F20.standard_F20 \subset G -> solvable G -> G = F20.standard_F20.
Proof.
move=> FG solG.
have CG := subset_trans standard_C5_sub_standard_D5
  (subset_trans standard_D5_sub_standard_F20 FG).
have transG := transitive_of_standard_C5_sub CG.
have [s GFs] :=
  (proj1 (SolvableCriterion.solvable_transitive_S5_iff transG)) solG.
have card20G : 20 <= #|G|.
  move: (cardSg FG).
  by rewrite F20.card_standard_F20.
have cardG20 : #|G| <= 20.
  move: (cardSg GFs).
  by rewrite cardJg F20.card_standard_F20.
have cardG : #|G| = 20%N := anti_leq cardG20 card20G.
apply: val_inj; apply/eqP.
by rewrite eq_sym eqEcard FG cardG F20.card_standard_F20.
Qed.

Lemma normalizer_standard_F20 :
  'N(F20.standard_F20) = F20.standard_F20.
Proof. apply: val_inj; apply/eqP; vm_compute. Qed.

(** The copy of [S3] fixing points 0 and 1 pointwise. *)
Definition pointwise_stabilizer_01 : {group S5} :=
  'C[F20.o0 | 'P] :&: 'C[F20.o1 | 'P].

Lemma card_pointwise_stabilizer_01 :
  #|pointwise_stabilizer_01| = 6%N.
Proof. vm_compute. Qed.

(** Sharp 2-transitivity is equivalently the following trivial intersection. *)
Lemma standard_F20_inter_pointwise_stabilizer_01 :
  F20.standard_F20 :&: pointwise_stabilizer_01 = 1%G.
Proof. apply: val_inj; apply/eqP; vm_compute. Qed.

Definition pointwise_conjugate_injectiveb : bool :=
  [forall g : S5,
    [forall h : S5,
      [&& g \in pointwise_stabilizer_01,
          h \in pointwise_stabilizer_01 &
          (F20.standard_F20 :^ g == F20.standard_F20 :^ h)] ==>
        (g == h)]].

Lemma pointwise_conjugate_injective_certificate :
  pointwise_conjugate_injectiveb.
Proof. vm_compute. Qed.

Lemma pointwise_conjugate_injective :
  {in pointwise_stabilizer_01 &,
    injective (fun g : S5 => F20.standard_F20 :^ g)}.
Proof.
move=> g h Gg Gh eq_conj.
apply/eqP.
have hc := pointwise_conjugate_injective_certificate.
rewrite /pointwise_conjugate_injectiveb in hc.
have hc := forallP (forallP hc g) h.
apply: implyP hc.
by rewrite Gg Gh eq_conj !eqxx.
Qed.

Definition pointwise_conjugate_exhaustiveb : bool :=
  [forall g : S5,
    [exists h : S5,
      (h \in pointwise_stabilizer_01) &&
      (F20.standard_F20 :^ g == F20.standard_F20 :^ h)]].

Lemma pointwise_conjugate_exhaustive_certificate :
  pointwise_conjugate_exhaustiveb.
Proof. vm_compute. Qed.

Lemma pointwise_conjugate_exhaustive (g : S5) :
  exists h : S5,
    h \in pointwise_stabilizer_01 /\
    F20.standard_F20 :^ g = F20.standard_F20 :^ h.
Proof.
have hc := pointwise_conjugate_exhaustive_certificate.
rewrite /pointwise_conjugate_exhaustiveb in hc.
case/existsP: (forallP hc g)=> h /andP[hpoint /eqP hconj].
by exists h.
Qed.

Definition pointwise_F20_conjugates : {set {set S5}} :=
  [set F20.standard_F20 :^ g | g in pointwise_stabilizer_01].

Lemma card_pointwise_F20_conjugates :
  #|pointwise_F20_conjugates| = 6%N.
Proof.
rewrite /pointwise_F20_conjugates
  (card_imset pointwise_stabilizer_01 pointwise_conjugate_injective).
exact: card_pointwise_stabilizer_01.
Qed.

(** Exact paper-facing wording: [M = F20] has six conjugates corresponding to
    the six permutations fixing [x0 = o0] and [x1 = o1]. *)
Theorem standard_F20_has_six_pointwise_represented_conjugates :
  pointwise_F20_conjugates =
    F20.standard_F20 :^: [set: S5] /\
  #|pointwise_F20_conjugates| = 6%N.
Proof.
split; last exact: card_pointwise_F20_conjugates.
apply/setP=> K; apply/imsetP/imsetP.
- case=> g gpoint ->.
  exists g; first by rewrite inE.
  reflexivity.
- case=> g _ ->.
  have [h [hpoint hconj]] := pointwise_conjugate_exhaustive g.
  exists h=> //.
  exact: esym hconj.
Qed.

Lemma card_all_standard_F20_conjugates :
  #|F20.standard_F20 :^: [set: S5]| = 6%N.
Proof.
rewrite -standard_F20_has_six_pointwise_represented_conjugates.1.
exact: card_pointwise_F20_conjugates.
Qed.

