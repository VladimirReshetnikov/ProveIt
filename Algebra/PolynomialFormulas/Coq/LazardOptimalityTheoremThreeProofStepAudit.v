(** * The literal prime-eleven witness *)

Lemma zeta11_pow_eleven_mem_rational_base :
  T4.zeta11 ^+ 11 \in (1%AS : {subfield T4.Ambient}).
Proof.
rewrite (prim_expr_order T4.zeta11_primitive).
exact: mem1v.
Qed.

(** The numerical inference in the paper is false: the exponent is the
    prime eleven, the adjoining degree is ten and is divisible by five, but
    eleven is not five. *)
Theorem theoremThree_prime_exponent_inference_counterexample :
  [/\
    prime 11,
    T4.zeta11 ^+ 11 \in (1%AS : {subfield T4.Ambient}),
    \dim T4.ElevenField = 10%N,
    (5 %| \dim T4.ElevenField)%N
  & (11 != 5)%N].
Proof.
split.
- by vm_compute.
- exact: zeta11_pow_eleven_mem_rational_base.
- exact: T3.elevenField_dim.
- by rewrite T3.elevenField_dim.
- by vm_compute.
Qed.

