(** A line-by-line audit of the prime-exponent step in the proof printed
    after Lazard's Theorem 3.

    From [z ^+ p \in K] one obtains only

      [adjoin_degree K z <= p].

    The proof in the paper silently treats this upper bound as an exact
    prime degree.  The concrete primitive eleventh root below has radical
    exponent eleven but adjoining degree ten, which is divisible by five.
    It also contains the degree-five field generated by
    [zeta11 + zeta11^-1].

    The final section uses an explicit exponent-21 cyclotomic automorphism
    to refute the next displayed equality after adjoining [zeta5]. *)
Module PolynomialFormulasLazardOptimalityTheoremThreeProofStepAudit.

Import GRing.Theory.
Local Open Scope ring_scope.

Module T4 :=
  PolynomialFormulasLazardOptimalityCyclicQuinticCounterexample.
Module T3 :=
  PolynomialFormulasLazardOptimalityTheoremThreeCounterexample.

(* -------------------------------------------------------------------- *)
(** * The corrected generic degree bound *)

Section CorrectedDegreeBound.

Variables (F0 : fieldType) (L : fieldExtType F0).

(** The honest conclusion of a prime-power radical equation.  Primality is
    used only to discharge positivity of the exponent. *)
Lemma adjoin_degree_le_prime_exponent_of_pow_mem
    (K : {subfield L}) (z : L) (p : nat) :
  prime p -> z ^+ p \in K -> (adjoin_degree K z <= p)%N.
Proof.
move=> p_prime zpK.
pose q : {poly L} := 'X^p - (z ^+ p)%:P.
have q_over : q \is a polyOver K.
  by rewrite /q polyOverXnsubC.
have q_root : root q z.
  by rewrite /q rootE !hornerE subrr eqxx.
have min_dvd : minPoly K z %| q := minPoly_dvdp q_over q_root.
have q_monic : q \is monic.
  exact: monicXnsubC (prime_gt0 p_prime).
have hsize := dvdp_leq (monic_neq0 q_monic) min_dvd.
move: hsize.
by rewrite size_minPoly /q size_XnsubC ?prime_gt0 // leqSS.
Qed.

End CorrectedDegreeBound.

