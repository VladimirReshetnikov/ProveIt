(** * Failure of the final all-roots equality *)

Lemma cyclicQuinticSplittingField_le_elevenField :
  (T4.CyclicQuinticSplittingField <= T4.ElevenField)%VS.
Proof.
exact: T4.cyclic_quintic_splittingField_le
  T4.every_cyclic_quintic_root_in_ElevenField.
Qed.

Lemma zeta5_notin_cyclicQuinticSplittingField :
  T4.zeta5 \notin T4.CyclicQuinticSplittingField.
Proof.
apply/negP=> zeta5_in.
have zeta5_in_eleven : T4.zeta5 \in T4.ElevenField :=
  (subvP cyclicQuinticSplittingField_le_elevenField)
    T4.zeta5 zeta5_in.
by move: T4.zeta5_notin_ElevenField; rewrite zeta5_in_eleven.
Qed.

(** The field [Q(zeta5, x)] contains [zeta5], whereas the field generated by
    the full proved factor list is contained in [Q(zeta11)] and omits it. *)
Theorem cyclicQuinticCompositum_ne_allRootsField :
  T3.CyclicQuinticCompositum <> T4.CyclicQuinticSplittingField.
Proof.
move=> fields_eq.
have zeta5_in_left : T4.zeta5 \in T3.CyclicQuinticCompositum.
  by rewrite /T3.CyclicQuinticCompositum; exact: memv_adjoin.
have zeta5_in_roots : T4.zeta5 \in T4.CyclicQuinticSplittingField.
  by rewrite -fields_eq.
move: zeta5_notin_cyclicQuinticSplittingField.
by rewrite zeta5_in_roots.
Qed.

End PolynomialFormulasLazardOptimalityTheoremThreeProofStepAudit.
