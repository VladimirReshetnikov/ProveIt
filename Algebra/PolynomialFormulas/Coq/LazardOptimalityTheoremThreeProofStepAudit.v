(** * Failure of [K(z) = K(x)] *)

(** Here [T3.CyclicQuinticField] is definitionally
    [Q(zeta11 + zeta11^-1)].  Its degree is five, while
    [T4.ElevenField = Q(zeta11)] has degree ten. *)
Theorem elevenField_ne_realCyclicQuinticField :
  T4.ElevenField <> T3.CyclicQuinticField.
Proof.
move=> fields_eq.
move: T3.elevenField_dim.
by rewrite fields_eq T3.cyclicQuinticField_dim.
Qed.

(** No single fifth radical can generate the degree-ten eleventh-cyclotomic
    field: the generic bound makes every such adjunction have degree at most
    five.  This directly refutes [K(z) = K(root_5(y))]. *)
Theorem elevenField_ne_adjoin_fifth_radical
    (r : T4.Ambient) :
  r ^+ 5 \in (1%AS : {subfield T4.Ambient}) ->
  T4.ElevenField <> <<1; r>>%AS.
Proof.
move=> r5 fields_eq.
have prime5 : prime 5 by vm_compute.
have hle := adjoin_degree_le_prime_exponent_of_pow_mem
  (p := 5%N) prime5 r5.
have hdim : \dim <<1; r>>%AS = adjoin_degree 1 r.
  by rewrite dim_Fadjoin dimv1 muln1.
move: hle.
by rewrite -hdim -fields_eq T3.elevenField_dim.
Qed.

