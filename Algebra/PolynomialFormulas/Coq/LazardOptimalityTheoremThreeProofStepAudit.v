(** * Failure after adjoining the primitive fifth root *)

Definition ElevenFifthCompositum : {subfield T4.Ambient} :=
  <<T4.ElevenField; T4.zeta5>>%AS.

(** An endomorphism fixing a subfield and the adjoined generator fixes the
    entire simple adjunction. *)
Lemma endomorphism_fixed_on_adjoin
    (K : {subfield T4.Ambient}) (a : T4.Ambient)
    (u : 'AEnd(T4.Ambient)) :
  {in K, u =1 id} -> u a = a -> {in <<K; a>>%AS, u =1 id}.
Proof.
move=> uK ua x /Fadjoin_polyP[p p_over ->].
have u_homK : kHom K {:T4.Ambient} u.
  apply/kAHomP=> y yK.
  exact: uK y yK.
rewrite -[u p.[a]](horner_map u)
  (kHom_poly_id u_homK p_over).
rewrite /=.
by rewrite ua.
Qed.

Lemma endomorphism_fixed_on_cyclicQuinticField
    (u : 'AEnd(T4.Ambient)) :
  u T4.cyclic_quintic_root = T4.cyclic_quintic_root ->
  {in T3.CyclicQuinticField, u =1 id}.
Proof.
move=> uroot x.
rewrite /T3.CyclicQuinticField=> /Fadjoin_polyP[p p_over ->].
have u_hom : kHom 1 {:T4.Ambient} u := k1AHom {:T4.Ambient} u.
rewrite -[u p.[T4.cyclic_quintic_root]](horner_map u)
  (kHom_poly_id u_hom p_over).
rewrite /=.
by rewrite uroot.
Qed.

Lemma endomorphism_fixed_on_cyclicQuinticCompositum
    (u : 'AEnd(T4.Ambient)) :
  u T4.zeta5 = T4.zeta5 ->
  u T4.cyclic_quintic_root = T4.cyclic_quintic_root ->
  {in T3.CyclicQuinticCompositum, u =1 id}.
Proof.
move=> uzeta5 uroot.
rewrite /T3.CyclicQuinticCompositum.
exact: endomorphism_fixed_on_adjoin
  (endomorphism_fixed_on_cyclicQuinticField uroot) uzeta5.
Qed.

(** Exponent `21` modulo `55` is `1` modulo `5` and `-1` modulo `11`.
    The resulting cyclotomic automorphism fixes [zeta5] and
    [zeta11 + zeta11^-1], but moves [zeta11]. *)
Lemma exists_endomorphism_fixing_zeta5_and_cyclic_root_moving_zeta11 :
  {u : 'AEnd(T4.Ambient) |
    u T4.zeta5 = T4.zeta5 /\
    u T4.cyclic_quintic_root = T4.cyclic_quintic_root /\
    u T4.zeta11 != T4.zeta11}.
Proof.
have co21_55 : coprime 21 55 by vm_compute.
have [nu nuE] := Qn_aut_exists co21_55.
have [uL uE] := restrict_aut_to_normal_num_field T4.ambient_inC nu.
pose u : 'AEnd(T4.Ambient) := AHom (linfun_is_ahom uL).
have uAE : {morph T4.ambient_inC : x / u x >-> nu x}.
  move=> x; rewrite /u /=.
  rewrite (@lfunE _ _ T4.Ambient) /=.
  exact: uE x.
exists u; split.
- apply: (fmorph_inj T4.ambient_inC).
  rewrite uAE /T4.zeta5 !rmorphXn /= T4.ambient_inC_zeta55.
  rewrite (nuE T4.zeta55C
    (prim_expr_order T4.zeta55C_primitive)) -!exprM.
  apply/eqP.
  rewrite (eq_prim_root_expr T4.zeta55C_primitive).
  by vm_compute.
- split.
  + have uzeta11_pow10 : u T4.zeta11 = T4.zeta11 ^+ 10.
      apply: (fmorph_inj T4.ambient_inC).
      rewrite uAE /T4.zeta11 !rmorphXn /= T4.ambient_inC_zeta55.
      rewrite (nuE T4.zeta55C
        (prim_expr_order T4.zeta55C_primitive)) -!exprM.
      apply/eqP.
      rewrite (eq_prim_root_expr T4.zeta55C_primitive).
      by vm_compute.
    have zeta11_neq0 : T4.zeta11 != 0.
      by rewrite (prim_root_eq0 T4.zeta11_primitive).
    have zeta11_pow10_inv :
        T4.zeta11 ^+ 10 = T4.zeta11^-1.
      apply: (mulfI zeta11_neq0).
      by rewrite divff // -exprS
        (prim_expr_order T4.zeta11_primitive).
    have uzeta11_inv : u T4.zeta11 = T4.zeta11^-1 :=
      eq_trans uzeta11_pow10 zeta11_pow10_inv.
    have nuzeta11_inv :
        nu (T4.ambient_inC T4.zeta11) =
          (T4.ambient_inC T4.zeta11)^-1.
      by rewrite -uAE uzeta11_inv rmorphV ?unitfE ?zeta11_neq0.
    apply: (fmorph_inj T4.ambient_inC).
    rewrite uAE /T4.cyclic_quintic_root !rmorphD !rmorphV
      ?unitfE ?fmorph_eq0 ?zeta11_neq0 //.
    rewrite nuzeta11_inv invrK addrC.
    reflexivity.
  + apply/negP=> /eqP u_zeta11.
    have h := congr1 T4.ambient_inC u_zeta11.
    move: h.
    rewrite uAE /T4.zeta11 !rmorphXn /= T4.ambient_inC_zeta55.
    rewrite (nuE T4.zeta55C
      (prim_expr_order T4.zeta55C_primitive)) -exprM.
    move=> hpow.
    have hpowb :
        T4.zeta55C ^+ (21 * 5) == T4.zeta55C ^+ 5
      by exact/eqP/hpow.
    move: hpowb.
    rewrite (eq_prim_root_expr T4.zeta55C_primitive).
    vm_compute.
    move=> hfalse.
    discriminate hfalse.
Qed.

Lemma zeta11_mem_elevenFifthCompositum :
  T4.zeta11 \in ElevenFifthCompositum.
Proof.
apply: (subvP (subv_adjoin T4.ElevenField T4.zeta5)).
by rewrite /T4.ElevenField; exact: memv_adjoin.
Qed.

(** The paper's next displayed equality fails as well:

      [Q(zeta5, zeta11) != Q(zeta5, zeta11 + zeta11^-1)].

    The exponent-21 automorphism fixes every element of the right-hand field
    but moves [zeta11], which belongs to the left-hand field. *)
Theorem elevenFifthCompositum_ne_cyclicQuinticCompositum :
  ElevenFifthCompositum <> T3.CyclicQuinticCompositum.
Proof.
move=> fields_eq.
have [u [uzeta5 [uroot uzeta11]]] :=
  exists_endomorphism_fixing_zeta5_and_cyclic_root_moving_zeta11.
have zeta11_in_right : T4.zeta11 \in T3.CyclicQuinticCompositum.
  rewrite -fields_eq.
  exact: zeta11_mem_elevenFifthCompositum.
have uzeta11_fixed : u T4.zeta11 = T4.zeta11 :=
  endomorphism_fixed_on_cyclicQuinticCompositum
    uzeta5 uroot zeta11_in_right.
move: uzeta11.
by rewrite uzeta11_fixed eqxx.
Qed.

