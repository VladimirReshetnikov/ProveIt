"""Regenerate the article's tables from the actual benchmark JSON, not literals."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    data = json.loads((ROOT/'results/benchmark.json').read_text())
    rows = {(r['case'], r['task'], r['implementation']): r for r in data['rows']}
    out = ['% Generated by tools/benchmark_tables.py from results/benchmark.json.']
    labels = {'conway': 'Conway', 'figure_eight': 'Figure eight',
              'grid_determinant_one_knot': 'Determinant-one grid',
              'grid_scrambled_unknot': 'Scrambled grid unknot',
              'hard_unknot_8': 'Hard unknot (8 crossings)',
              'kinoshita_terasaka': 'Kinoshita--Terasaka', 'torus_3_5': '$T(3,5)$',
              'trefoil': 'Trefoil', 'unknot': 'Small unknot',
              'unknot_braid40': '40-crossing braid unknot',
              'original_random_5_braid_36': '36-crossing stress braid'}
    def time_value(r):
        if r is None:
            return r'\textemdash'
        if r['result']['status'] in ('UNKNOWN', 'ERROR'):
            if 'external worker' in r['result'].get('reason',''):
                return r'\textit{worker timeout}'
            return r'\textit{cutoff at }' + f"{1000*r['median_seconds']:,.1f}"
        return f"{1000*r['median_seconds']:,.3f}"
    def ratio(a,b):
        if a is None or b is None or any(r['result']['status'] in ('UNKNOWN','ERROR') for r in (a,b)):
            return r'\textemdash'
        return f"{a['median_seconds']/b['median_seconds']:.2f}" + r'$\times$'
    def table_start(caption,label,columns,heading):
        out.extend([r'\begin{table}[htbp]',r'\centering\small',r'\caption{'+caption+'}',
                    r'\label{'+label+'}',r'\begin{tabular}{'+columns+'}',r'\toprule',heading+r' \\',r'\midrule'])
    def table_end(note=''):
        out.extend([r'\bottomrule',r'\end{tabular}'])
        if note:
            out.extend([r'\par\smallskip',r'\begin{minipage}{0.97\linewidth}\footnotesize '+note+r'\end{minipage}'])
        out.extend([r'\end{table}',''])
    out.append(r'\newcommand{\PipelineTable}{')
    table_start('Default recognition, milliseconds. All completed verdicts agree.',
                'tab:pipeline','lrrrr','Input & $n$ & Original & New & Original/new')
    for case in [r['case'] for r in data['rows'] if r['task']=='pipeline' and r['implementation']=='baseline']:
        a=rows[case,'pipeline','baseline']; b=rows[case,'pipeline','accelerated']
        label=labels.get(case, '$'+case+'$')
        out.append(f"{label} & {a['crossings']} & {time_value(a)} & {time_value(b)} & {ratio(a,b)}"+r' \\')
    table_end('The $T(3,121)$ original worker was stopped after 43.05 seconds for the entire job; no completed-sample summary was returned. This is not a measured single-run time. Small-input regressions are included.')
    out.append('}')
    out.append(r'\newcommand{\RankTable}{')
    table_start('Raw unreduced homology, milliseconds; no recognition prefilters.',
                'tab:rank','lrrrr','Input & $n$ & Original & New, no factors & New')
    for case in ('conway','kinoshita_terasaka','hard_unknot_8','unknot_braid40',
                 'curl_family_16','curl_family_64','curl_family_256','original_random_5_braid_36'):
        a=rows[case,'rank','baseline']; b=rows[case,'rank','accelerated']
        c=rows.get((case,'rank','accelerated-no-factors'))
        label=labels[case] if case in labels else 'Curl family '+case.rsplit('_',1)[1]
        out.append(f"{label} & {a['crossings']} & {time_value(a)} & {time_value(c)} & {time_value(b)}"+r' \\')
    table_end('The stress baseline cutoff is one unfinished sample, not a median completion. A separate 60-second baseline run also remained unfinished (60.10 seconds elapsed). Dashes mean not run. Factor detection can add small overhead when no cut exists.')
    out.append('}')
    out.append(r'\newcommand{\OrderingTable}{')
    table_start('Identical greedy ordering policy on the curl family, milliseconds.',
                'tab:ordering','rrrr','$n$ & Original & New & Original/new')
    for n in (64,256,1024):
        a=rows[f'order_{n}','order','baseline'];b=rows[f'order_{n}','order','accelerated']
        out.append(f'{n} & {time_value(a)} & {time_value(b)} & {ratio(a,b)}'+r' \\')
    table_end()
    out.append('}')
    out.append(r'\newcommand{\FactorTable}{')
    table_start('Raw homology of $k$ trefoil summands, milliseconds.',
                'tab:factors','rrlrrr','$k$ & $n$ & Unreduced rank & Original & New & Original/new')
    for k in (2,4,6,8,16,32):
        a=rows.get((f'trefoil_sum_{k}','rank','baseline'));b=rows[f'trefoil_sum_{k}','rank','accelerated']
        rank=f"{b['result']['rank']:,}" if k<16 else '$2\\cdot3^{'+str(k)+'}$'
        out.append(f'{k} & {3*k} & {rank} & {time_value(a)} & {time_value(b)} & {ratio(a,b)}'+r' \\')
    table_end('Baseline runs at $k=16,32$ were not attempted. The new algorithm reports integer degree counts, not one basis vector per homology generator. These are raw-homology timings: both recognition pipelines can reject trefoil sums much earlier.')
    out.append('}')
    generated = '\n'.join(out)+'\n'
    (ROOT/'docs/benchmark_tables.tex').write_text(generated)
    article = ROOT/'docs/report.tex'
    if article.exists():
        text = article.read_text()
        begin = '% BEGIN GENERATED BENCHMARK TABLES'
        end = '% END GENERATED BENCHMARK TABLES'
        if begin in text and end in text:
            before, rest = text.split(begin, 1)
            _, after = rest.split(end, 1)
            article.write_text(before+begin+'\n'+generated+end+after)


if __name__ == '__main__':
    main()
