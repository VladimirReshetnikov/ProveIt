#!/usr/bin/env python3
"""Regenerate the article's figures and measured tables from retained data.

No mathematical decision or timing result is generated by this script.
The geometric picture plots the exact formula of Theorem 8.1 on x+y=1;
floating point is used only to draw the already proved affine functions.
"""

from fractions import Fraction
import json
from pathlib import Path
from statistics import median

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.ticker import NullFormatter
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
FIGURES = ROOT / 'article' / 'figures'
TABLES = ROOT / 'article' / 'tables'


def ms(ns):
    return f'{ns / 1_000_000:,.3f}'


def ratio(value):
    return f'{value:,.2f}'


def write_measurements(benchmark, coverage):
    lines = [r'''\subsection{Controlled complete-enumeration measurements}

The retained experiment has 13 geometric cohorts, one warm-up per scope,
and five paired rounds in alternating AB/BA order. The eight-tetrahedron
base with cap type one also has duplicate same-method A/A arms. There are
280 measured calls and 52 warm-up calls across the two scopes, followed by
three new-method-only capacity runs. The immutable predecessor is copied
from the pinned repository revision, rather than recreated by editing the
optimized implementation. Every measured output hash agrees between arms,
and the timed source-file hashes are checked before and after the run.

Table~\ref{tab:enumeration} reports medians in milliseconds. Its speedup is
the median of the five \emph{paired ratios}, which need not equal the ratio
of the two separately reported medians. The last column isolates enumeration
with an already constructed kernel. Full raw calls, order, setup costs,
work counters, and source hashes are in \texttt{results/benchmark.json}.

\begin{table}[htbp]
\centering\small
\begin{tabular}{@{}rrrrrr@{}}
\toprule
$t$ & Cap & Old full (ms) & New full (ms) & Full speedup & Reused speedup\\
\midrule''']
    for i, case in enumerate(benchmark['cases']):
        full = case['scopes']['full']['summary']
        reused = case['scopes']['reused_kernel']['summary']
        if i == 10:
            lines.append(r'\midrule')
        lines.append(
            f"{case['tetrahedra']} & {case['cap_type']} & "
            f"{ms(full['old_median_ns'])} & {ms(full['new_median_ns'])} & "
            f"{ratio(full['paired_speedup_median'])}$\\times$ & "
            f"{ratio(reused['paired_speedup_median'])}$\\times$\\\\")
    lines.append(r'''\bottomrule
\end{tabular}
\caption{Complete enumeration on capped Fibonacci solid tori. Here
$t=n+1$ includes the cap. ``Full'' includes kernel construction and full
standard-coordinate emission. Types one and two have three rays; type zero
is the two-ray control. Every query has matching nullity two.}
\label{tab:enumeration}
\end{table}

For $t=33$ and cap type one, the old and new full medians are
6.064 seconds and 29.023 milliseconds, with paired speedup $202.71\times$.
The reused-kernel medians are 6.593 seconds and 8.204 milliseconds,
with paired speedup $781.17\times$. These are local complete-enumeration
measurements on the declared family, not whole-recognizer measurements.

The growth in redundant work is also visible without a clock. At base size
$n=32$, the old backend constructs 35 distinct hyperplanes, tries 34
nonnegative directions, and rejects 31; the new method lifts precisely three
directions. Corollary~\ref{cor:oldfamily} proves these counts for every
size. The timing difference also includes the cost of constructing pairwise
forms and applying dense supported-rank tests, so it should not be explained
only by the ratio of candidate counts.
''')
    duplicate = next(c for c in benchmark['cases']
                     if c['base_tetrahedra'] == 8 and c['cap_type'] == 1)
    aa = {}
    for scope, values in duplicate['scopes'].items():
        for arm in ('old', 'new'):
            aa[(scope, arm)] = median(
                r['arms'][arm]['total_ns'] / r['arms'][arm + '_AA']['total_ns']
                for r in values['rounds'])
    lines.append(
        'The same-method duplicate ratios (first call divided by duplicate) '
        'have medians '
        f"{aa[('reused_kernel', 'old')]:.3f} and "
        f"{aa[('reused_kernel', 'new')]:.3f} for reused old/new calls, and "
        f"{aa[('full', 'old')]:.3f} and "
        f"{aa[('full', 'new')]:.3f} for full old/new calls. "
        'This visible host variability argues against treating small '
        'differences or last decimal places as reliable. No confidence '
        'interval or power-law fit is claimed.\n')
    lines.append(r'''
\begin{table}[htbp]
\centering\small
\begin{tabular}{@{}rrrrr@{}}
\toprule
$t$ & Kernel (ms) & Enumeration (ms) & Total (ms) & Kernel share\\
\midrule''')
    for c in benchmark['capacity']:
        share = 100 * c['build_ns'] / c['total_ns']
        lines.append(f"{c['tetrahedra']} & {ms(c['build_ns'])} & "
                     f"{ms(c['enumeration_ns'])} & {ms(c['total_ns'])} & "
                     f"{share:.1f}\\%\\\\")
    lines.append(r'''\bottomrule
\end{tabular}
\caption{New-method-only capacity runs with cap type one and three emitted
rays. Each row is a single call, not a paired comparison or a median.}
\label{tab:capacity}
\end{table}

At $t=257$, approximately 95\% of the new full call is kernel construction.
This identifies a concrete implementation target after removing arrangement
work. The capacity rows do not imply a measured speedup at these sizes:
the predecessor was not run there.

\begin{figure}[htbp]
\centering
\includegraphics[width=\linewidth]{figures/measurements.pdf}
\caption{Measured complete-enumeration times. Left: five-round medians of
full calls on cap-type-one inputs, including kernel construction. Right:
the three new-method-only capacity calls, separated into kernel and
enumeration time. Both axes in each panel are logarithmic. Lines connect
observations and are not fitted complexity laws.}
\label{fig:measurements}
\end{figure}

\subsection{Production followed by independent coverage checking}

A separate matched workflow includes completeness checking. The old arm
constructs the pinned kernel, enumerates with the pinned arrangement, then
reconstructs the independent dense matching model and runs its complete
reference enumeration to check equality. The new arm produces an envelope
coverage certificate and replays it with the independent uncontracted-graph
checker. Both workflows require the same complete ray list. The new API
constructs its plan for both production and certification; this duplicate
constant-factor work is included in the timings.

There is one warm-up and three paired AB/BA rounds for each compared size.
Fixture generation and final reporting serialization and hashing are outside
the timed regions. The old arm's ray-list equality check and the new arm's
certificate verification, including their internal hashes, are included.
\texttt{results/coverage.json} retains every call, source hash, and six
independently replayable source/certificate pairs.

\begin{table}[htbp]
\centering\small
\begin{tabular}{@{}rrrr@{}}
\toprule
$t$ & Old production + replay (ms) & New production + replay (ms) & Paired speedup\\
\midrule''')
    for c in coverage['cases']:
        lines.append(f"{c['tetrahedra']} & {ms(c['old_median_ns'])} & "
                     f"{ms(c['new_median_ns'])} & "
                     f"{ratio(c['paired_speedup_median'])}$\\times$\\\\")
    lines.append(r'''\bottomrule
\end{tabular}
\caption{Complete production and independent coverage, cap type one.
Reported times are medians; speedups are medians of paired ratios.}
\label{tab:coveragebench}
\end{table}

\begin{table}[htbp]
\centering\small
\begin{tabular}{@{}rrrrrr@{}}
\toprule
$t$ & Production (ms) & Replay (ms) & Total (ms) & Certificate bytes & Tests\\
\midrule''')
    for c in coverage['capacity']:
        lines.append(f"{c['tetrahedra']} & {ms(c['producer_ns'])} & "
                     f"{ms(c['verifier_ns'])} & {ms(c['total_ns'])} & "
                     f"{c['certificate_bytes']:,} & "
                     f"{c['verifier_stats']['dominance_tests']}\\\\")
    lines.append(r'''\bottomrule
\end{tabular}
\caption{New-only production and coverage capacity calls. ``Tests'' counts
slope-bracket dominance checks, exactly $4t$ per row. Each list has three
rays. JSON sizes include the complete coordinates; serialization is untimed.}
\label{tab:coveragecapacity}
\end{table}

The coverage workflow at $t=17$ has median paired speedup $51.92\times$;
its three ratios range from $34.61\times$ to $60.72\times$. This broader
scope shows that the benefit persists after checking a complete answer.
At $t=129$, new production and replay take a single combined 3.939 seconds;
this is a capacity observation without a comparative claim. The $4t$
dominance count does not imply a linear-time full checker, since matching
elimination, projection, and coordinate validation must also be performed.
''')
    TABLES.mkdir(parents=True, exist_ok=True)
    (TABLES / 'measurements.tex').write_text('\n'.join(lines) + '\n')


def figure_style():
    plt.rcParams.update({
        'font.family': 'DejaVu Sans', 'font.size': 9,
        'axes.titlesize': 10, 'axes.labelsize': 9, 'legend.fontsize': 8,
        'axes.spines.top': False, 'axes.spines.right': False,
        'pdf.fonttype': 42, 'ps.fonttype': 42,
        'axes.grid': False, 'savefig.facecolor': 'white',
    })


def draw_envelope():
    teal, red, grey = '#147d80', '#b34937', '#acb4c0'
    n, a = 4, 5
    coefficients = [1, 2, 3, 5, 8]
    s = np.linspace(0, 1, 1201)
    fig, (ax, events) = plt.subplots(
        2, 1, figsize=(7.0, 4.15), sharex=True,
        gridspec_kw={'height_ratios': [4.2, 1.15]}, layout='constrained')
    for i, c in enumerate(coefficients):
        ax.plot(s, c * (1 - s), color=grey, lw=1,
                label='Other triangle potentials' if i == 0 else None)
    ax.plot(s, np.zeros_like(s), color=grey, lw=1)
    ax.plot(s, a - (a + 1) * s, color=red, lw=1.5,
            label=r'$5(1-s)-s$')
    ax.plot(s, np.minimum(0, a - (a + 1) * s), color=teal, lw=3.0,
            label='True lower envelope')
    inactive = [Fraction(a - c, a + 1 - c) for c in (1, 2, 3)]
    for v in inactive:
        vf = float(v)
        ax.scatter([vf], [a - (a + 1) * vf], color=red, s=22, zorder=4)
    switch = Fraction(5, 6)
    ax.scatter([float(switch)], [0], color=teal, s=33, zorder=5)
    ax.annotate('Only one interior\nminimum change',
                xy=(float(switch), 0), xytext=(.44, 3.8),
                arrowprops={'arrowstyle': '->', 'color': teal},
                color=teal, fontsize=9,
                bbox={'facecolor': 'white', 'edgecolor': 'none', 'alpha': .88,
                      'pad': 1.5})
    ax.set(ylabel='Potential value', ylim=(-1.35, 8.4), xlim=(-.018, 1.018))
    ax.set_title('Actual capped Fibonacci sector: four base tetrahedra and one cap',
                 loc='left', pad=12)
    ax.legend(loc='upper right', frameon=False)
    ax.grid(axis='y', alpha=.16)
    old = sorted([Fraction(0), Fraction(1), switch, *inactive])
    true = [Fraction(0), switch, Fraction(1)]
    events.hlines([0, 1], 0, 1, color='#dce0e5', linewidth=1)
    events.scatter([float(v) for v in old], [1] * len(old),
                   color=grey, s=31, zorder=3)
    events.scatter([float(v) for v in inactive], [1] * len(inactive),
                   color=red, marker='x', s=31, zorder=4)
    events.scatter([float(v) for v in true], [0] * len(true),
                   color=teal, s=36, zorder=4)
    events.set(yticks=[0, 1], yticklabels=['True rays: 3', 'Old candidates: 6'],
               ylim=(-.5, 1.5), xlabel=r'Projective parameter $s=y/(x+y)$')
    events.set_xticks([0, .25, .5, 2 / 3, 5 / 6, 1],
                      ['0', '1/4', '1/2', '2/3', '5/6', '1'])
    events.spines['left'].set_visible(False)
    events.tick_params(axis='y', length=0)
    fig.savefig(FIGURES / 'minimum_envelope.pdf')
    fig.savefig(FIGURES / 'minimum_envelope.png', dpi=180)
    plt.close(fig)


def draw_measurements(benchmark):
    teal, red = '#147d80', '#b34937'
    fig, (left, right) = plt.subplots(1, 2, figsize=(7.1, 3.35),
                                    layout='constrained')
    cap_one = [c for c in benchmark['cases'] if c['cap_type'] == 1]
    t = [c['tetrahedra'] for c in cap_one]
    for key, color, marker, label in (
            ('old_median_ns', red, 's', 'Pinned arrangement'),
            ('new_median_ns', teal, 'o', 'Minimum envelopes')):
        values = [c['scopes']['full']['summary'][key] / 1e9 for c in cap_one]
        left.loglog(t, values, color=color, marker=marker, ms=4, lw=1.5,
                    label=label)
    left.set_title('Full complete enumeration', loc='left')
    left.set(xlabel='Tetrahedra', ylabel='Seconds', xticks=t)
    left.set_xticklabels([str(x) for x in t])
    left.xaxis.set_minor_formatter(NullFormatter())
    left.legend(frameon=False, loc='upper left')
    left.grid(which='major', alpha=.18)
    ct = [c['tetrahedra'] for c in benchmark['capacity']]
    for key, color, marker, label in (
            ('build_ns', '#536780', 's', 'Kernel construction'),
            ('enumeration_ns', teal, 'o', 'Enumeration')):
        right.loglog(ct, [c[key] / 1e9 for c in benchmark['capacity']],
                     color=color, marker=marker, ms=4, lw=1.5, label=label)
    right.set_title('Capacity calls: new method only', loc='left')
    right.set(xlabel='Tetrahedra', ylabel='Seconds', xticks=ct)
    right.set_xticklabels([str(x) for x in ct])
    right.xaxis.set_minor_formatter(NullFormatter())
    right.legend(frameon=False, loc='upper left')
    right.grid(which='major', alpha=.18)
    fig.savefig(FIGURES / 'measurements.pdf')
    fig.savefig(FIGURES / 'measurements.png', dpi=180)
    plt.close(fig)


def main():
    benchmark = json.loads((ROOT / 'results' / 'benchmark.json').read_text())
    coverage = json.loads((ROOT / 'results' / 'coverage.json').read_text())
    FIGURES.mkdir(parents=True, exist_ok=True)
    figure_style()
    write_measurements(benchmark, coverage)
    draw_envelope()
    draw_measurements(benchmark)
    print('Generated two figures and measured tables from retained data.')


if __name__ == '__main__':
    main()
