#!/usr/bin/env python3
"""Build the article's tables and exact-data plot from the frozen main run.

No benchmark is rerun. Error bars show measured minima and maxima, not
confidence intervals. Requires matplotlib only when building the figure.
"""

import argparse
import json
from pathlib import Path
from statistics import median

ROOT = Path(__file__).resolve().parents[1]


def samples(case, prefix):
    return [r['seconds'] for r in case['records']
            if not r['warmup'] and r['arm'].startswith(prefix)]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data', type=Path, default=ROOT/'results'/'benchmarks.json')
    parser.add_argument('--output-dir', type=Path, default=ROOT/'article')
    args = parser.parse_args()
    data = json.loads(args.data.read_text())
    assert data['source_hashes_unchanged'] is True
    sparse = [r for r in data['records'] if r['family'] == 'sparse_boundary_caps']
    dense = [r for r in data['records'] if r['family'] == 'dense_fibonacci_certified']
    for case in data['records']:
        assert len({r['answer_sha256'] for r in case['records']}) == 1
    lines = [r'% Generated by scripts/make_measurement_tables.py; do not edit.',
             r'\begin{table}[htbp]', r'\centering\small',
             r'\begin{tabular}{@{}rrrrrr@{}}', r'\toprule',
             r'$t$ & Dense variables & Kernel variables & Kernel (ms) & Dense (ms) & Paired ratio \\',
             r'\midrule']
    summary = []
    for c in sparse:
        n = c['tetrahedra']
        m = next(r['stats']['kernel_variables'] for r in c['records']
                 if r['arm'].startswith('kernel'))
        ktime, dtime = median(samples(c, 'kernel')), median(samples(c, 'dense'))
        ratio = c['median_paired_dense_over_kernel']
        lines.append(f'{n} & {4*n+1} & {m} & {1000*ktime:.3f} & {1000*dtime:,.3f} & {ratio:.2f}'+r' \\')
        summary.append(dict(family=c['family'], tetrahedra=n,
                            kernel_median_ms=1000*ktime, dense_median_ms=1000*dtime,
                            median_paired_dense_over_kernel=ratio))
    lines += [r'\bottomrule', r'\end{tabular}',
              r'\caption{The identical fixed-sector Q-ray task on boundary-cap triangulations.',
              r'Every case has $k=d=1$. Times are medians of ten measured calls per method;',
              r'the last column is the median of ten within-round dense/kernel ratios.',
              r'The comparator is the independent dense Python reference.}',
              r'\label{tab:sparsebench}', r'\end{table}', '',
              r'\begin{table}[htbp]', r'\centering\small',
              r'\begin{tabular}{@{}rrrrr@{}}', r'\toprule',
              r'$t=k$ & Maximum coordinate bits & Certificate bytes & Median (s) & Measured calls \\',
              r'\midrule']
    for c in dense:
        n = c['tetrahedra']
        records = [r for r in c['records'] if not r['warmup']]
        bits = {r['maximum_coordinate_bits'] for r in records}
        sizes = {r['certificate_bytes'] for r in records}
        assert len(bits) == len(sizes) == 1
        bits, size = bits.pop(), sizes.pop()
        duration = median(r['seconds'] for r in records)
        lines.append(f'{n} & {bits} & {size:,} & {duration:.6f} & {len(records)}'+r' \\')
        summary.append(dict(family=c['family'], tetrahedra=n,
                            coordinate_bits=bits, certificate_bytes=size,
                            certified_median_seconds=duration, measured_calls=len(records)))
    lines += [r'\bottomrule', r'\end{tabular}',
              r'\caption{Complete certified discovery on supplied dense Fibonacci sectors.',
              r'All have $d=1$ and return one verified essential meridian.',
              r'The clock includes native independent disc replay and JSON serialization.',
              r'These are timings of the new method, without a cross-algorithm ratio.}',
              r'\label{tab:fibbench}', r'\end{table}', '',
              r'\begin{figure}[htbp]', r'\centering',
              r'\includegraphics[width=\textwidth]{benchmark_scaling.pdf}',
              r'\caption{Measured scaling for two different supplied-sector workloads.',
              r'Points are medians; bars span the observed minimum and maximum.',
              r'Both axes are logarithmic. The bars describe repeat variability,',
              r'not confidence intervals or a distribution over inputs.}',
              r'\label{fig:bench}', r'\end{figure}', '',
              f'The main run completed {data["measured_calls"]} measured calls and',
              f'{data["warmup_calls"]} retained warm-up calls on Python {data["python"]}.',
              r'The frozen runtime and benchmark source hashes were unchanged from the',
              r'beginning to the end of that run. A first exploratory timing run is also',
              r'retained separately; the tables use only the second, controlled run.',
              r'No other agent computation was scheduled concurrently with this main run.']
    args.output_dir.mkdir(parents=True, exist_ok=True)
    (args.output_dir/'measurement_tables.tex').write_text('\n'.join(lines)+'\n')
    (ROOT/'results'/'benchmark_summary.json').write_text(json.dumps({
        'source': str(args.data.relative_to(ROOT)) if args.data.is_relative_to(ROOT) else str(args.data),
        'scope': data['scope'], 'measured_calls':data['measured_calls'],
        'warmup_calls':data['warmup_calls'], 'records':summary}, indent=2)+'\n')

    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    import numpy as np
    plt.rcParams.update({'font.family':'DejaVu Sans', 'font.size':9,
                         'axes.spines.top':False, 'axes.spines.right':False,
                         'axes.labelcolor':'#17384C', 'text.color':'#17384C',
                         'axes.titleweight':'bold', 'pdf.fonttype':42})
    fig, axes = plt.subplots(1, 2, figsize=(7.5, 3.0), layout='constrained')
    for prefix, label, color, marker in [
            ('kernel','Support kernel','#126B87','o'),
            ('dense','Dense Python reference','#B76332','s')]:
        x = [r['tetrahedra'] for r in sparse]
        arrays = [samples(r, prefix) for r in sparse]
        y = np.array([1000*median(a) for a in arrays])
        err = np.array([[v-1000*min(a) for v,a in zip(y,arrays)],
                        [1000*max(a)-v for v,a in zip(y,arrays)]])
        axes[0].errorbar(x,y,yerr=err,label=label,color=color,marker=marker,
                         markersize=4,capsize=2,linewidth=1.6)
    axes[0].set(title='A. Matched Q-ray enumeration', ylabel='Time (milliseconds)')
    axes[0].legend(frameon=False, fontsize=8, loc='upper left')
    x = [r['tetrahedra'] for r in dense]
    arrays = [samples(r, 'new') for r in dense]
    y = np.array([median(a) for a in arrays])
    err = np.array([[v-min(a) for v,a in zip(y,arrays)],
                    [max(a)-v for v,a in zip(y,arrays)]])
    axes[1].errorbar(x,y,yerr=err,color='#126B87',marker='o',markersize=4,
                    capsize=2,linewidth=1.6)
    axes[1].set(title='B. Certified Fibonacci discovery', ylabel='Time (seconds)')
    for ax in axes:
        ax.set_xscale('log',base=2)
        ax.set_yscale('log')
        ax.set_xticks([4,8,16,32,64,128], labels=['4','8','16','32','64','128'])
        ax.set_xlabel('Tetrahedra')
        ax.grid(axis='y',alpha=.18,which='major')
        ax.tick_params(which='both',labelsize=8)
    fig.savefig(args.output_dir/'benchmark_scaling.pdf',metadata={
        'Title':'Fixed-sector discovery timings', 'Creator':'make_measurement_tables.py'})
    fig.savefig(args.output_dir/'benchmark_scaling.png',dpi=180)
    plt.close(fig)
    print(json.dumps(summary,indent=2))


if __name__ == '__main__':
    main()
