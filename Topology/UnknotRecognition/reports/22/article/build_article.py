#!/usr/bin/env python3
"""Assemble the self-contained TeX text, then optionally compile its PDF.

Run from any directory:
    python3 /path/to/article/build_article.py --pdf

The combined source includes all sections and the bibliography. The plot is
optional at TeX compile time; the archive supplies it in figures/.
"""
from __future__ import annotations
import argparse
from pathlib import Path
import shutil
import subprocess

HERE = Path(__file__).resolve().parent
SECTIONS = [
    "00_preamble.tex", "01_scope.tex", "02_continuations.tex",
    "03_checkpoint.tex", "04_montesinos.tex", "05_implementation.tex",
    "06_experiments.tex", "07_research.tex", "08_appendix_references.tex",
]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--pdf", action="store_true")
    args = parser.parse_args()
    target = HERE / "unknot_arithmetic_continuations.tex"
    combined = "% Generated by build_article.py from the numbered source sections.\n"
    for name in SECTIONS:
        combined += "\n% ===== " + name + " =====\n"
        combined += (HERE / name).read_text(encoding="utf-8").rstrip() + "\n"
    target.write_text(combined, encoding="utf-8")
    print(f"Assembled {target.name}: {len(combined):,} characters.", flush=True)
    if args.pdf:
        executable = shutil.which("pdflatex")
        if executable is None:
            raise SystemExit("pdflatex is needed for --pdf; the combined TeX is ready.")
        # Three passes settle section, table, bibliography and contents references.
        for _ in range(3):
            subprocess.run(
                [executable, "-interaction=nonstopmode", "-halt-on-error",
                 target.name], cwd=HERE, check=True,
            )
        print("Compiled unknot_arithmetic_continuations.pdf.", flush=True)


if __name__ == "__main__":
    main()
