"""Build the publication tables and precision figure from archived raw JSON.

Default: read this package's results/ and write article/tables/ and
article/figures/.  Optional --fast-dir snapshots the specified ProveIt fast/
results first.  Historical tensor runs are marked as checkpoints and are
never pooled into the final six-arm timing comparison.

The figure requires matplotlib.  --tables-only creates all numerical tables
without a plotting dependency.  No benchmark is rerun by this script.
"""
from hashlib import sha256
from pathlib import Path
from statistics import median
import argparse
import json
import math
import shutil


FINAL_FILES = (
    "tensor_jones_valuation_20261008.json",
    "tensor_jones_valuation_benchmark_20261008.log",
    "tensor_jones_audit_20261008.json",
    "cocycle_seed_20261008.json",
)
CHECKPOINT_FILES = (
    "tensor_jones_20261008.json",
    "tensor_jones_benchmark_20261008.log",
    "tensor_jones_integer_20261008.json",
    "tensor_jones_integer_benchmark_20261008.log",
)
ARMS = ("faithful", "control", "laurent", "integer-global", "integer", "integer-ordinary")
NAMES = {
    "trefoil": "Trefoil",
    "conway": "Conway",
    "kinoshita_terasaka": "Kinoshita--Terasaka",
    "hard_unknot_8": "Hard unknot",
    "stress_braid5_36": "Five-strand stress",
    "weaving-5": r"Weaving $q=5$",
    "weaving-13": r"Weaving $q=13$",
    "weaving-17": r"Weaving $q=17$",
    "tree-6": "Tree, depth 6",
    "tree-7": "Tree, depth 7",
    "grid-4": r"Grid $4\times4$",
    "grid-6": r"Grid $6\times6$",
    "grid-8": r"Grid $8\times8$",
    "grid-10": r"Grid $10\times10$",
    "grid-8-shuffled": r"Shuffled $8\times8$",
}


def digest(path):
    return sha256(path.read_bytes()).hexdigest()


def write_json(path, value):
    path.write_text(json.dumps(value, indent=2, sort_keys=True)+"\n")


def snapshot_raw(fast, package):
    """Copy exact bytes, retaining the distinction between final and earlier runs."""
    records = []
    for checkpoint, names in ((False, FINAL_FILES), (True, CHECKPOINT_FILES)):
        target = package/"results"/("checkpoints" if checkpoint else "")
        target.mkdir(parents=True, exist_ok=True)
        for name in names:
            source = fast/"results"/name
            destination = target/name
            shutil.copy2(source, destination)
            assert digest(source) == digest(destination)
            records.append(dict(file=str(destination.relative_to(package)),
                                original_repository_path="Topology/UnknotRecognition/fast/results/"+name,
                                checkpoint=checkpoint, sha256=digest(destination)))
    write_json(package/"results"/"tensor_data_manifest.json", dict(
        final_timing_source="results/tensor_jones_valuation_20261008.json",
        policy="Use the final six-arm valuation run for publication comparisons. "
               "Earlier four-arm Laurent and five-arm global-integer runs are "
               "development checkpoints, preserved for traceability; do not pool their timings.",
        files=records))


def table(path, headers, rows, caption, label, first_align="l"):
    """Distribute spare width between all columns, not inside the first one."""
    columns = r"@{\extracolsep{\fill}}" + first_align + "r"*(len(headers)-1) + "@{}"
    text = [
        "% Generated by reproduce/make_research_tables.py; edit the generator, not this file.",
        r"\begin{table}[H]",
        r"\centering\footnotesize",
        r"\setlength{\tabcolsep}{3pt}",
        r"\renewcommand{\arraystretch}{1.12}",
        r"\begin{tabular*}{\linewidth}{"+columns+"}",
        r"\toprule",
        " & ".join(headers)+r"\\",
        r"\midrule",
    ]
    text += [" & ".join(map(str, row))+r"\\" for row in rows]
    text += [r"\bottomrule", r"\end{tabular*}",
             r"\caption{"+caption+"}", r"\label{"+label+"}", r"\end{table}", ""]
    path.write_text("\n".join(text))


def completed_result(row, arm):
    results = [sample["results"][arm] for sample in row["samples"]]
    if any(result["status"] != "COMPLETE" for result in results):
        return None
    return [result["result"] for result in results]


def same_bit_count(row, arm):
    results = completed_result(row, arm)
    if results is None:
        raise ValueError("a capped arm cannot supply a completed-query precision statistic")
    counts = {result["max_coefficient_bits"] for result in results}
    if len(counts) != 1:
        raise ValueError("the selected precision statistic varies across repeated runs")
    return counts.pop()


def milliseconds(seconds):
    return f"{1000*seconds:.3f}"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--package-dir", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--fast-dir", type=Path,
                        help="optional ProveIt fast/ directory to snapshot before rendering")
    parser.add_argument("--tables-only", action="store_true")
    args = parser.parse_args()
    package = args.package_dir.resolve()
    tables, figures = package/"article"/"tables", package/"article"/"figures"
    tables.mkdir(parents=True, exist_ok=True)
    figures.mkdir(parents=True, exist_ok=True)
    (package/"results").mkdir(parents=True, exist_ok=True)
    if args.fast_dir is not None:
        snapshot_raw(args.fast_dir.resolve(), package)

    tensor_path = package/"results"/"tensor_jones_valuation_20261008.json"
    cocycle_path = package/"results"/"cocycle_seed_20261008.json"
    tensor = json.loads(tensor_path.read_text())
    cocycle = json.loads(cocycle_path.read_text())
    assert len(tensor["rows"]) == 15 and len(cocycle["cases"]) == 7
    assert len(cocycle["finite_exterior_audit"]) == 2

    # Recompute medians from individual samples; never interpret cap time as
    # completed-query time.  The raw file keeps all cap times and reasons.
    time_rows, time_records = [], []
    for row in tensor["rows"]:
        assert len(row["samples"]) == tensor["rounds"]
        cells, record = [NAMES[row["name"]], row["crossings"]], {}
        for arm in ARMS:
            values = [sample["seconds"][arm] for sample in row["samples"]]
            computed_median = median(values)
            assert math.isclose(computed_median, row["median_seconds"][arm], rel_tol=1e-12, abs_tol=1e-12)
            complete = completed_result(row, arm) is not None
            cells.append(milliseconds(computed_median) if complete else r"\textsf{LIMIT}")
            record[arm] = dict(complete=complete, median_seconds=computed_median,
                               published_milliseconds=milliseconds(computed_median) if complete else None)
        time_rows.append(cells)
        time_records.append(dict(name=row["name"], crossings=row["crossings"], arms=record))
    cap = (
        "Complete full-Jones queries: median milliseconds over " + str(tensor["rounds"]) +
        " randomized paired rounds after " + str(tensor["warmups"]) +
        " warmup round. A/A is an independently timed repeat of the faithful arm. "
        "Order construction and verification are included; the ordinary-integer arm "
        "omits the universal width certificate. "
        r"\textsf{LIMIT} denotes a capped arm, not a completed-query runtime; "
        "no ratio is assigned to it. Per-query limits were " + str(tensor["seconds_per_query"]) +
        " seconds, " + f'{tensor["max_states"]:,}' + " states, and " +
        f'{tensor["max_transitions"]:,}' + " transitions. "
        "These invariant-query measurements do not measure complete recognition."
    )
    table(tables/"tensor_times.tex", [
        "Case", "$n$", r"\shortstack{Faithful\\(ms)}", r"\shortstack{A/A\\(ms)}",
        r"\shortstack{Laurent\\(ms)}", r"\shortstack{Global\\integer (ms)}",
        r"\shortstack{Normalized\\integer (ms)}", r"\shortstack{Ordinary\\integer (ms)}",
    ], time_rows, cap, "tab:tensor-times")

    selected = [next(row for row in tensor["rows"] if row["name"] == name)
                for name in ("tree-6", "tree-7", "grid-10")]
    precision_rows, precision_records = [], []
    for row in selected:
        values = {arm: same_bit_count(row, arm)
                  for arm in ("faithful", "laurent", "integer-global", "integer")}
        precision_rows.append([NAMES[row["name"]], row["crossings"]]
                              + [f'{values[arm]:,}' for arm in
                                 ("faithful", "laurent", "integer-global", "integer")])
        precision_records.append(dict(name=row["name"], crossings=row["crossings"], bits=values))
    table(tables/"tensor_precision.tex", [
        "Case", "$n$", r"\shortstack{Faithful\\scalar bits}",
        r"\shortstack{Laurent\\coefficient bits}", r"\shortstack{Global\\integer bits}",
        r"\shortstack{Normalized\\mantissa bits}",
    ], precision_rows,
        "Maximum bit length of one stored scalar, Laurent coefficient, or normalized "
        "mantissa in completed queries from the final paired run. The values agree "
        "across all repeated samples. They are not total table-memory measurements: "
        "the normalized mode also stores a valuation, and every mode stores frontier "
        "keys and other metadata. The two integer tensor modes use the same exact "
        "polynomial model and certified order.", "tab:tensor-precision")

    product_rows, product_records = [], []
    for row in cocycle["cases"]:
        stat = row["statistics"]
        bits = row["initial_disc_count"].bit_length()
        product_rows.append([stat["tetrahedra"], stat["height_bits"], bits,
                             row["optimal_disc_count"], milliseconds(row["seconds"]),
                             milliseconds(row["verification_seconds"])])
        product_records.append(dict(name=row["name"], tetrahedra=stat["tetrahedra"],
                                    height_bits=stat["height_bits"], initial_disc_bits=bits,
                                    optimal_disc_count=row["optimal_disc_count"],
                                    optimizer_seconds=row["seconds"],
                                    checker_seconds=row["verification_seconds"]))
    table(tables/"cocycle_times.tex", [
        "$T$", r"\shortstack{Height\\bits}", r"$\bits(D_0)$", r"$D_\star$",
        r"\shortstack{Optimizer\\(ms)}", r"\shortstack{Checker\\(ms)}",
    ], product_rows,
        r"All seven product-solid-torus cases. $T$ is the number of tetrahedra; "
        r"$D_0$ and $D_\star$ are the initial and optimal numbers of normal discs. "
        "Height bits are measured from the supplied local heights, rather than "
        "inferred from a case-name parameter. Times are single recorded calls, "
        "not paired benchmark medians. Optimization includes its internal certificate check; "
        "the checker column measures an additional certificate and face-matching check. "
        "These cases verify binary-height handling and the fixed-family optimum; "
        "they do not establish an end-to-end recognition speedup.", "tab:cocycle-times", first_align="r")

    exterior_rows, exterior_records = [], []
    for row in cocycle["finite_exterior_audit"]:
        geometry = row["regina"]
        assert geometry["manifold_valid"] and not geometry["manifold_ideal"]
        assert geometry["surface_connected"] and geometry["surface_orientable"]
        chi = int(geometry["surface_euler_characteristic"])
        boundary = geometry["surface_boundary_components"]
        exterior_rows.append(["Trefoil" if row["name"] == "trefoil" else "Figure-eight",
                              row["tetrahedra"], row["vertices"], row["initial_disc_count"],
                              row["optimal_disc_count"], milliseconds(row["seconds"]), chi, boundary])
        exterior_records.append(dict(name=row["name"], tetrahedra=row["tetrahedra"],
                                     vertices=row["vertices"], initial_disc_count=row["initial_disc_count"],
                                     optimal_disc_count=row["optimal_disc_count"],
                                     optimizer_seconds=row["seconds"],
                                     euler_characteristic=chi, boundary_components=boundary))
    table(tables/"cocycle_exteriors.tex", [
        "Knot exterior", "$T$", r"$|V|$", "$D_0$", r"$D_\star$",
        r"\shortstack{Optimizer\\(ms)}", r"$\chi$", "$b$",
    ], exterior_rows,
        "Two genuine finite knot exteriors obtained by truncating Regina's ideal "
        "examples. A primitive tree-gauge cocycle is optimized within its vertex-potential "
        r"family. Regina independently verifies that each output is connected and orientable; "
        r"$\chi$ and $b$ denote its Euler characteristic and boundary-component count. "
        "The single-call times include the triangulation adapter's seed construction "
        "and consistency checks, but exclude triangulation construction, cohomology "
        "preparation, and the independent Regina check. Disc-count optimality in this "
        "family does not assert genus minimality or incompressibility.", "tab:cocycle-exteriors")

    outputs = [tables/name for name in ("tensor_times.tex", "tensor_precision.tex",
                                       "cocycle_times.tex", "cocycle_exteriors.tex")]
    plotting = None
    if not args.tables_only:
        import matplotlib
        matplotlib.use("Agg")
        import matplotlib.pyplot as plt

        plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 9,
                             "pdf.fonttype": 42, "ps.fonttype": 42})
        fig, ax = plt.subplots(figsize=(6.25, 3.8))
        fig.subplots_adjust(left=0.135, right=0.985, bottom=0.20, top=0.78)
        positions = list(range(len(precision_records)))
        width = 0.32
        global_bits = [r["bits"]["integer-global"] for r in precision_records]
        normalized_bits = [r["bits"]["integer"] for r in precision_records]
        bars1 = ax.bar([x-width/2 for x in positions], global_bits, width,
                       color="#153E63", edgecolor="#153E63", linewidth=0.6,
                       label="Global integer")
        bars2 = ax.bar([x+width/2 for x in positions], normalized_bits, width,
                       color="#D8A16C", edgecolor="#80542D", linewidth=0.6,
                       hatch="//", label="Normalized mantissa")
        ax.set_yscale("log", base=2)
        ax.set_ylim(2**8, 2**18)
        powers = list(range(8, 19, 2))
        ax.set_yticks([2**p for p in powers], [f"$2^{{{p}}}$" for p in powers])
        ax.set_ylabel("Maximum stored bit length\n(log₂ scale)", fontsize=9)
        ax.set_xticks(positions, ["Tree\n$n=126$", "Tree\n$n=254$", "Grid\n$n=100$"])
        ax.tick_params(axis="both", which="both", length=0, pad=6)
        ax.grid(axis="y", color="#D8DEE6", linewidth=0.6)
        ax.set_axisbelow(True)
        for spine in ("top", "right", "bottom"):
            ax.spines[spine].set_visible(False)
        ax.spines["left"].set_color("#A7B0BA")
        for bars in (bars1, bars2):
            for bar in bars:
                value = int(bar.get_height())
                ax.annotate(f"{value:,}", (bar.get_x()+bar.get_width()/2, value),
                            xytext=(0, 5), textcoords="offset points", ha="center",
                            va="bottom", fontsize=8, color="#202A35")
        ax.legend(loc="lower left", bbox_to_anchor=(-0.01, 1.10), ncol=2,
                  frameon=False, fontsize=8.5, handlelength=1.7, columnspacing=2.0)
        fig.text(0.035, 0.965, "Stored integer precision", fontsize=12,
                 fontweight="bold", color="#153E63", va="top")
        fig.text(0.135, 0.035,
                 "Exact bit counts; these are neither elapsed times nor total memory sizes.",
                 fontsize=7.5, color="#425466")
        pdf, png = figures/"tensor_precision.pdf", figures/"tensor_precision.png"
        fig.savefig(pdf, metadata={"Title": "Stored integer precision in exact Jones tensors",
                                   "Author": "ProveIt research continuation",
                                   "CreationDate": None, "ModDate": None})
        fig.savefig(png, dpi=220, metadata={"Software": "ProveIt make_research_tables.py"})
        plt.close(fig)
        wrapper = figures/"tensor_precision.tex"
        wrapper.write_text(
            "% Generated by reproduce/make_research_tables.py.\n"
            "\\begin{figure}[htbp]\n\\centering\n"
            "\\includegraphics[width=0.97\\linewidth]{figures/tensor_precision.pdf}\n"
            "\\caption{Maximum stored integer precision for three completed exact tensor queries. "
            "The vertical axis uses a base-two logarithmic scale; labels give exact bit counts. "
            "Valuation normalization removes monomial padding from the stored mantissa. "
            "Valuations, frontier keys, and other bookkeeping are not included. "
            "This finite comparison is not an asymptotic fit or a timing measurement.}\n"
            "\\label{fig:tensor-precision}\n\\end{figure}\n")
        outputs += [pdf, png, wrapper]
        plotting = dict(matplotlib_version=matplotlib.__version__,
                        figure_inches=[6.25, 3.8], vertical_axis="log2 bit length",
                        scope="single-integer precision, not total memory or elapsed time")

    values_path = package/"results"/"research_table_values.json"
    write_json(values_path, dict(tensor_times=time_records, tensor_precision=precision_records,
                                cocycle_products=product_records, cocycle_exteriors=exterior_records))
    outputs.append(values_path)
    manifest = dict(
        generator_sha256=digest(Path(__file__)),
        input_sha256={str(path.relative_to(package)): digest(path) for path in (tensor_path, cocycle_path)},
        output_sha256={str(path.relative_to(package)): digest(path) for path in outputs},
        row_counts=dict(tensor_times=15, tensor_precision=3, cocycle_products=7, cocycle_exteriors=2),
        plotting=plotting)
    write_json(package/"results"/"research_tables_manifest.json", manifest)
    print(json.dumps(dict(status="PASS", tables=4, figure=not args.tables_only,
                          row_counts=manifest["row_counts"])))


if __name__ == "__main__":
    main()
