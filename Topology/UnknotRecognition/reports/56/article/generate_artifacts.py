#!/usr/bin/env python3
"""Generate publication figures and LaTeX tables from the final saved results.

No experiments are run.  Published time medians and paired ratios are read
directly from the JSON summaries.  Only recorded-work medians are computed
from the already saved measured samples.  Unresolved runs never acquire a
completion time or completion-time ratio.  Requires Python and matplotlib.
"""

import argparse
import hashlib
import json
from pathlib import Path
from statistics import median

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
from matplotlib.lines import Line2D
from matplotlib.ticker import FixedLocator, LogFormatterMathtext, NullLocator, ScalarFormatter


HERE = Path(__file__).resolve().parent
NAVY = '#243B53'
TEAL = '#008B88'
AMBER = '#B46B25'
GRID = '#DCE3E9'
FILES = {
    'kernels': 'raw_saturation_kernels.json',
    'stage': 'raw_saturation_stage.json',
    'pipeline': 'raw_saturation_pipeline.json',
    'membership': 'orbit_index.json',
    'rank': 'orbit_rank_select.json',
}


def number(value, digits=3, scale=1):
    return '--' if value is None else f'{value * scale:,.{digits}f}'.replace(',', r'\,')


def milliseconds(value):
    return number(value, scale=1000)


def case_name(name):
    return r'\texttt{' + name.replace('_', r'\_\allowbreak ').replace('-', r'-\allowbreak ') + '}'


def status_pair(row):
    codes = {'UNKNOT': 'U', 'KNOTTED': 'K', 'INCONCLUSIVE': 'I', 'UNKNOWN': '?'}
    out = []
    for arm in ('baseline', 'saturation'):
        statuses = sorted(set(row['outcomes'][arm]))
        out.append('+'.join(codes.get(status, status) for status in statuses))
    return '/'.join(out)


def tabular(specification, header, rows, note=None):
    lines = [r'% Generated by generate_artifacts.py; edit the source JSON or generator.',
             r'\begingroup', r'\small', r'\setlength{\tabcolsep}{5pt}',
             r'\renewcommand{\arraystretch}{1.12}',
             r'\begin{tabular}{' + specification + '}', r'\toprule',
             ' & '.join(header) + r' \\', r'\midrule']
    lines.extend(' & '.join(row) + r' \\' for row in rows)
    lines += [r'\bottomrule', r'\end{tabular}']
    if note:
        lines += [r'\par\smallskip', r'\begin{minipage}{0.96\linewidth}',
                  r'\footnotesize ' + note, r'\end{minipage}']
    lines += [r'\endgroup', '']
    return '\n'.join(lines)


def full_table(rows, title, label):
    header = [r'Input', '$n$', r'\shortstack{Old\\complete}',
              r'\shortstack{New\\complete}', r'\shortstack{Old\\observed}',
              r'\shortstack{New\\observed}', 'Ratio', r'\shortstack{Old/new\\status}']
    spec = r'@{}>{\raggedright\arraybackslash}p{3.45cm}rrrrrrc@{}'
    note = (r'All times are milliseconds. Completion medians and paired ratios are copied from '
            r'the recorded JSON summaries. An unresolved arm has -- for completion time and no '
            r'completion ratio; only then is its observed elapsed median shown. '
            r'U = \texttt{UNKNOT}, K = \texttt{KNOTTED}, '
            r'I = \texttt{INCONCLUSIVE}, ? = \texttt{UNKNOWN}. '
            r'All measured outcomes for each arm agree within every row in this data set.')
    lines = [r'% Generated by generate_artifacts.py. This is a longtable, not a float.',
             r'\begingroup', r'\small', r'\setlength{\tabcolsep}{3pt}',
             r'\setlength{\LTcapwidth}{\linewidth}',
             r'\renewcommand{\arraystretch}{1.08}',
             r'\begin{longtable}{' + spec + '}',
             r'\caption{' + title + r'}\label{' + label + r'}\\',
             r'\toprule', ' & '.join(header) + r' \\', r'\midrule', r'\endfirsthead',
             r'\toprule', ' & '.join(header) + r' \\', r'\midrule', r'\endhead',
             r'\midrule', r'\multicolumn{8}{r}{\footnotesize Continued on the next page.}\\',
             r'\endfoot', r'\bottomrule',
             r'\multicolumn{8}{@{}p{\linewidth}@{}}{\footnotesize ' + note + r'}\\',
             r'\endlastfoot']
    for row in rows:
        med = row['median_seconds']
        obs = row['median_observed_seconds']
        values = [case_name(row['name']), str(row['crossings']),
                  milliseconds(med['baseline']), milliseconds(med['saturation']),
                  milliseconds(obs['baseline']) if med['baseline'] is None else '--',
                  milliseconds(obs['saturation']) if med['saturation'] is None else '--',
                  number(row['paired_ratios']['saturation']), status_pair(row)]
        lines.append(' & '.join(values) + r' \\')
    lines += [r'\end{longtable}', r'\endgroup', '']
    return '\n'.join(lines)


def make_tables(data, destination):
    kernels = data['kernels']['rows']
    rows = [[str(row['bits']), milliseconds(row['median_seconds']['ordinary']),
             milliseconds(row['median_seconds']['saturation']), number(row['paired_ratio'])]
            for row in kernels]
    censored = [row for row in kernels if row['median_seconds']['ordinary'] is None]
    details = '; '.join('$b=' + str(row['bits']) + '$: '
                        + milliseconds(row['median_observed_seconds']['ordinary'])
                        for row in censored)
    note = (r'Old observed elapsed medians for work-limited, unfinished runs (ms): '
            + details + '. These observations are not completion times.')
    (destination / 'raw_kernels.tex').write_text(tabular(
        '@{}rrrr@{}', [r'$b$ in $N=2^b$', 'Ordinary (ms)', 'Saturation (ms)', 'Paired ratio'], rows, note))
    (destination / 'raw_stage_full.tex').write_text(full_table(
        data['stage']['rows'], 'Full group-stage benchmark: all 28 inputs.', 'tab:raw-stage-full'))
    (destination / 'raw_pipeline_full.tex').write_text(full_table(
        data['pipeline']['rows'], 'All full-recognizer benchmark inputs.', 'tab:raw-pipeline-full'))
    membership = []
    for row in data['membership']['cases']:
        if row['name'].startswith('layered_'):
            t = row['tetrahedra']
            if row['coordinate_scale'] == 1:
                name = f'Primitive meridian, $t={t}$'
            else:
                bits = int(row['coordinate_scale']).bit_length() - 1
                name = f'Meridian, $t={t}$, scale $2^{{{bits}}}+1$'
        elif row['name'].startswith('mobius'):
            name = r'M\"obius band, scale $2^{1024}+1$'
        elif row['name'].startswith('mixed'):
            name = 'Four-tetrahedron compatible mixture'
        elif row['name'].startswith('periodic_chain'):
            name = '64-pair periodic chain'
        else:
            name = case_name(row['name'])
        med = row['median_seconds']
        membership.append([name, str(row['queries']), milliseconds(med['shared']),
                           milliseconds(med['compiled']), number(row['paired_ratios']['shared_over_compiled'])])
    (destination / 'orbit_membership.tex').write_text(tabular(
        '@{}p{6.5cm}rrrr@{}', ['Supplied relation', '$q$', 'Shared (ms)', 'Compiled (ms)', 'Ratio'], membership))
    ranks = []
    for row in data['rank']['cases']:
        med = row['median_seconds']
        ranks.append([str(row['blocks']), str(row['endpoint_bits']),
                      milliseconds(med['emission_select']), milliseconds(med['canonical_select']),
                      number(row['paired_ratios']['emission_over_canonical']),
                      milliseconds(med['canonical_rank'])])
    (destination / 'orbit_rank.tex').write_text(tabular(
        '@{}rrrrrr@{}', [r'\shortstack{Minimum\\intervals}', r'\shortstack{Endpoint\\bits}',
                        r'\shortstack{Emission\\(ms)}', r'\shortstack{Canonical\\(ms)}',
                        'Ratio', r'\shortstack{Rank\\(ms)}'], ranks))


def style():
    plt.rcParams.update({
        'font.family': 'DejaVu Sans', 'font.size': 8.5,
        'mathtext.fontset': 'dejavusans', 'axes.titlesize': 10,
        'axes.labelsize': 9, 'xtick.labelsize': 8, 'ytick.labelsize': 8,
        'axes.labelcolor': NAVY, 'text.color': NAVY, 'xtick.color': NAVY,
        'ytick.color': NAVY, 'axes.edgecolor': '#93A3AF', 'axes.linewidth': 0.6,
        'axes.spines.top': False, 'axes.spines.right': False,
        'grid.color': GRID, 'grid.linewidth': 0.55, 'grid.alpha': 0.8,
        'legend.fontsize': 8, 'legend.frameon': False,
        'lines.linewidth': 1.55, 'lines.markersize': 4.2,
        'pdf.fonttype': 42, 'ps.fonttype': 42,
        'savefig.facecolor': 'white', 'figure.facecolor': 'white',
    })


def save_figure(fig, destination, name, title):
    metadata = {'Title': title, 'Creator': 'generate_artifacts.py / matplotlib',
                'CreationDate': None, 'ModDate': None}
    fig.savefig(destination / f'{name}.pdf', metadata=metadata)
    fig.savefig(destination / f'{name}.png', dpi=240)
    plt.close(fig)


def raw_stage_figure(data, destination):
    by_name = {row['name']: row for row in data['stage']['rows']}
    rows = [by_name[f'circle-{n}'] for n in (15, 31, 63, 127, 255, 511)]
    crossings = [row['crossings'] for row in rows]
    work = {arm: [median(sample['arms'][arm]['result']['search_stats']['work']
                         for sample in row['samples']) for row in rows]
            for arm in ('baseline', 'saturation')}
    fig, axes = plt.subplots(1, 2, figsize=(6.14, 3.35))
    fig.subplots_adjust(left=0.10, right=0.98, top=0.89, bottom=0.32, wspace=0.31)
    for ax in axes:
        ax.set_xscale('log', base=2)
        ax.set_yscale('log')
        ax.set_xticks(crossings, [str(x) for x in crossings])
        ax.xaxis.set_minor_locator(NullLocator())
        ax.set_xlabel('Crossings')
        ax.grid(True, which='major', axis='both')
        ax.set_xlim(12, 650)
    for arm, color, marker in (('baseline', NAVY, 'o'), ('saturation', TEAL, 's')):
        complete = [i for i, row in enumerate(rows)
                    if row['completion_counts'][arm] == data['stage']['rounds']]
        axes[0].plot([crossings[i] for i in complete],
                     [1000 * rows[i]['median_seconds'][arm] for i in complete],
                     color=color, marker=marker)
        axes[1].plot([crossings[i] for i in complete], [work[arm][i] for i in complete],
                     color=color, marker=marker)
        incomplete = [i for i in range(len(rows)) if i not in complete]
        for i in incomplete:
            for ax, observed in ((axes[0], 1000 * rows[i]['median_observed_seconds'][arm]),
                                 (axes[1], work[arm][i])):
                ax.plot(crossings[i], observed, linestyle='none', marker='^',
                        markersize=6.5, markerfacecolor='white', markeredgecolor=AMBER,
                        markeredgewidth=1.4, zorder=5)
    axes[0].set_title('(a) Elapsed time', loc='left')
    axes[0].set_ylabel('Milliseconds')
    axes[0].set_ylim(0.8, 2200)
    axes[0].yaxis.set_major_locator(FixedLocator([1, 10, 100, 1000]))
    axes[0].yaxis.set_major_formatter(ScalarFormatter())
    axes[1].set_title('(b) Recorded work', loc='left')
    axes[1].set_ylabel('Work units')
    axes[1].set_ylim(3500, 4e6)
    axes[1].yaxis.set_major_formatter(LogFormatterMathtext())
    legend = [Line2D([], [], color=NAVY, marker='o', label='Old search: complete'),
              Line2D([], [], color=TEAL, marker='s', label='Raw saturation'),
              Line2D([], [], linestyle='none', marker='^', markerfacecolor='white',
                     markeredgecolor=AMBER, markeredgewidth=1.3,
                     label='Old: node-limited observation')]
    fig.legend(handles=legend, loc='lower center', bbox_to_anchor=(0.5, 0.075),
               ncol=3, columnspacing=1.1, handletextpad=0.55, handlelength=1.4)
    fig.text(0.5, 0.025, 'Five measured rounds; the 511-crossing old run did not complete.',
             ha='center', fontsize=8, color=NAVY)
    save_figure(fig, destination, 'raw_stage', 'Complete group stage and recorded work')
    return work


def orbit_figure(data, destination):
    by_name = {row['name']: row for row in data['membership']['cases']}
    fig, axes = plt.subplots(1, 2, figsize=(6.14, 3.35), sharey=True)
    fig.subplots_adjust(left=0.10, right=0.98, top=0.85, bottom=0.34, wspace=0.22)
    for ax, tetrahedra, bits in zip(axes, (8, 24), (512, 128)):
        rows = [by_name[f'layered_{tetrahedra}_scale_{bits+1}bit_q{q}'] for q in (1, 8, 32)]
        for arm, color, marker in (('shared', NAVY, 'o'), ('compiled', TEAL, 's')):
            ax.plot([row['queries'] for row in rows],
                    [1000 * row['median_seconds'][arm] for row in rows],
                    color=color, marker=marker)
        ax.set_xscale('log', base=2)
        ax.set_yscale('log')
        ax.set_xticks([1, 8, 32], ['1', '8', '32'])
        ax.xaxis.set_minor_locator(NullLocator())
        ax.set_xlim(0.78, 41)
        ax.set_ylim(1.8, 800)
        ax.set_xlabel('Requested comparisons')
        ax.grid(True, which='major', axis='both')
        ax.set_title(f'{tetrahedra} tetrahedra; scale $2^{{{bits}}}+1$', loc='left')
        ax.yaxis.set_major_locator(FixedLocator([2, 10, 50, 200, 800]))
        ax.yaxis.set_major_formatter(ScalarFormatter())
    axes[0].set_ylabel('Complete batch time (ms)')
    legend = [Line2D([], [], color=NAVY, marker='o', label='Shared-count baseline'),
              Line2D([], [], color=TEAL, marker='s', label='Compiled index, including preparation')]
    fig.legend(handles=legend, loc='lower center', bbox_to_anchor=(0.5, 0.075),
               ncol=2, columnspacing=2.0, handletextpad=0.6, handlelength=1.5)
    fig.text(0.5, 0.025, 'Seven measured rounds; discovery, verification, construction, and queries included.',
             ha='center', fontsize=7.8, color=NAVY)
    save_figure(fig, destination, 'orbit_queries', 'Complete repeated membership batches')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--results', type=Path, default=HERE.parent / 'fast' / 'results',
                        help='final JSON directory (default: ../fast/results relative to this script)')
    parser.add_argument('--output', type=Path, default=HERE,
                        help='article directory receiving figures/ and tables/')
    args = parser.parse_args()
    data = {name: json.loads((args.results / filename).read_text())
            for name, filename in FILES.items()}
    expected = {'kernels': 5, 'stage': 28, 'pipeline': 22, 'membership': 10, 'rank': 4}
    for name, count in expected.items():
        records = data[name]['rows' if name in ('kernels', 'stage', 'pipeline') else 'cases']
        if len(records) != count:
            raise ValueError(f'{FILES[name]}: expected all {count} final records, got {len(records)}')
    figures, tables = args.output / 'figures', args.output / 'tables'
    figures.mkdir(parents=True, exist_ok=True)
    tables.mkdir(parents=True, exist_ok=True)
    make_tables(data, tables)
    style()
    work = raw_stage_figure(data, figures)
    orbit_figure(data, figures)
    manifest = dict(
        generated_by='generate_artifacts.py',
        source_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
        input_sha256={filename: hashlib.sha256((args.results / filename).read_bytes()).hexdigest()
                      for filename in FILES.values()},
        record_counts=expected, circle_recorded_work_medians=work,
        notes=['No experiment was rerun.', 'Time medians and paired ratios copied from JSON.',
               'Recorded work medians use measured saved samples only.',
               'Unresolved observations have no completion time or completion ratio.',
               'PDFs contain no generation-time metadata.'],
    )
    generated = [*sorted(figures.glob('raw_stage.*')), *sorted(figures.glob('orbit_queries.*')),
                 *(tables / name for name in ('raw_kernels.tex', 'raw_stage_full.tex',
                    'raw_pipeline_full.tex', 'orbit_membership.tex', 'orbit_rank.tex'))]
    manifest['artifact_sha256'] = {str(path.relative_to(args.output)):
                                  hashlib.sha256(path.read_bytes()).hexdigest() for path in generated}
    (tables / 'artifact_manifest.json').write_text(json.dumps(manifest, indent=2) + '\n')
    for path in generated:
        print(path)
    print(tables / 'artifact_manifest.json')


if __name__ == '__main__':
    main()
