#!/usr/bin/env python3
"""Derive readable tables from the preserved independent experiment records."""
from __future__ import annotations

from collections import Counter
import argparse
import csv
import json
from pathlib import Path
from statistics import median


HERE = Path(__file__).resolve().parent
PRIMARY = ("baseline_default", "baseline_forest", "singleton")


def read(name):
    return json.loads((HERE / name).read_text())


def group_measurement(row, arm):
    groups = row["samples"][0]["measurements"][arm]["groups"]
    return groups[0] if groups else {}


def write_csv(name, records):
    with (HERE / name).open("w", newline="") as stream:
        writer = csv.DictWriter(stream, fieldnames=list(records[0]))
        writer.writeheader()
        writer.writerows(records)


def table(headers, rows):
    return "\n".join([
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
        *("| " + " | ".join(str(v) for v in row) + " |" for row in rows),
    ])


def tex_table(headers, rows, align, note=""):
    return "\n".join([
        "% Generated by experiments/summarize_singleton_dag.py; do not hand edit.",
        "% " + note,
        r"\begingroup",
        r"\small\setlength{\tabcolsep}{4pt}",
        r"\begin{tabular}{" + align + "}",
        r"\toprule",
        " & ".join(headers) + r" \\",
        r"\midrule",
        *(" & ".join(str(v) for v in row) + r" \\" for row in rows),
        r"\bottomrule",
        r"\end{tabular}",
        r"\endgroup", "",
    ])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--article-generated", type=Path,
                        default=HERE.parent / "article" / "generated")
    args = parser.parse_args()
    audit = read("audit-guarded.json")
    eager = read("audit-eager.json")
    stages = read("stages-guarded.json")
    pipeline = read("benchmark-guarded.json")
    assert audit["source_sha256"] == stages["source_sha256"] == pipeline["source_sha256"]
    assert len({d["script_sha256"] for d in (audit, stages, pipeline)}) == 1
    versions, moves = Counter(), Counter()
    for row in audit["cases"]:
        proof = row["singleton"]["proof"]
        if proof:
            versions[proof["certificate_version"]] += 1
            for move in audit["certificates"][proof["certificate_sha256"]]["moves"]:
                moves[move["kind"]] += 1
                if move["kind"] == "singleton_dag":
                    moves["singleton_pivots"] += len(move["pivots"])
    legacy_stats = all(m["old_stats"] == m["new_stats"]
                       for row in audit["cases"] for m in row["legacy"].values())
    stage_rows = []
    for row in stages["cases"]:
        record = {"crossings": row["source"]["crossings"]}
        for arm in PRIMARY:
            group = group_measurement(row, arm)
            stats = group.get("search_stats", {})
            record[arm + "_median_ms"] = 1000 * row["medians"][arm]
            record[arm + "_search_work"] = stats.get("work")
            record[arm + "_nodes"] = stats.get("nodes")
            record[arm + "_certificate_bytes"] = group.get("certificate_bytes")
        record["forest_batches"] = group_measurement(row, "baseline_forest")["move_kinds"].get("primitive_forest", 0)
        record["singleton_batches"] = group_measurement(row, "singleton")["move_kinds"].get("singleton_dag", 0)
        record["singleton_pivots"] = group_measurement(row, "singleton")["search_stats"].get("singleton_dag_pivots", 0)
        for name, ratio in row["paired_ratios"].items():
            record[name + "_paired_median"] = ratio["median"]
        stage_rows.append(record)
    pipeline_rows = []
    for row in pipeline["cases"]:
        representative = row["samples"][0]["measurements"]["singleton"]
        record = {"name": row["source"]["name"], "crossings": row["source"].get("crossings"),
                  "status": representative["status"], "method": representative["method"],
                  "group_reached": bool(representative["groups"])}
        for arm in PRIMARY:
            group = group_measurement(row, arm)
            record[arm + "_median_ms"] = 1000 * row["medians"][arm]
            record[arm + "_search_work"] = group.get("search_stats", {}).get("work")
            record[arm + "_certificate_bytes"] = group.get("certificate_bytes")
        record["singleton_batches"] = group_measurement(row, "singleton").get("move_kinds", {}).get("singleton_dag", 0)
        for name, ratio in row["paired_ratios"].items():
            record[name + "_paired_median"] = ratio["median"]
        pipeline_rows.append(record)
    all_arms = [a for arm in PRIMARY for a in (arm, arm + "_AA")]
    sums = {
        arm: [sum(row["samples"][i]["measurements"][arm]["seconds"]
                  for row in pipeline["cases"]) for i in range(pipeline["rounds"])]
        for arm in all_arms
    }
    ratios = {"versus_default": median(a / b for a, b in zip(sums["baseline_default"], sums["singleton"])),
              "versus_forest": median(a / b for a, b in zip(sums["baseline_forest"], sums["singleton"]))}
    ratios.update({arm + "_AA": median(a / b for a, b in zip(sums[arm], sums[arm + "_AA"]))
                   for arm in PRIMARY})
    summary = {
        "audit": {k: audit[k] for k in ("diagrams", "legacy_mode_comparisons", "singleton_certificates",
                                        "newly_closed_versus_default", "lost_positives_versus_default",
                                        "newly_closed_versus_forest", "lost_positives_versus_forest")},
        "legacy_stats_identical": legacy_stats,
        "guarded_certificate_versions": dict(versions), "guarded_certificate_moves": dict(moves),
        "stage_rows": stage_rows, "pipeline_rows": pipeline_rows,
        "pipeline_round_total_seconds": sums,
        "pipeline_round_total_paired_median_ratios": ratios,
        "pipeline_median_round_total_seconds": {a: median(v) for a, v in sums.items()},
        "baseline_commit": audit["baseline_commit"], "harness_sha256": audit["script_sha256"],
    }
    write_csv("stages-guarded-summary.csv", stage_rows)
    write_csv("benchmark-guarded-summary.csv", pipeline_rows)
    (HERE / "results-summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    stage_table = table(
        ["Crossings", "Default ms", "Forest ms", "Singleton ms", "Paired default/singleton", "Paired forest/singleton", "Forest batches", "Singleton pivots"],
        [[r["crossings"], *[f'{r[a + "_median_ms"]:.3f}' for a in PRIMARY],
          f'{r["versus_default_paired_median"]:.3f}', f'{r["versus_forest_paired_median"]:.3f}',
          r["forest_batches"], r["singleton_pivots"]] for r in stage_rows],
    )
    pipeline_table = table(
        ["Input", "Crossings", "Default ms", "Forest ms", "Singleton ms", "Paired default/singleton", "Paired forest/singleton", "Singleton batches"],
        [[r["name"], r["crossings"], *[f'{r[a + "_median_ms"]:.3f}' for a in PRIMARY],
          f'{r["versus_default_paired_median"]:.3f}', f'{r["versus_forest_paired_median"]:.3f}',
          r["singleton_batches"]] for r in pipeline_rows],
    )
    aa_stage = [r["paired_ratios"][arm + "_AA"]["median"] for r in stages["cases"] for arm in PRIMARY]
    aa_pipeline = [r["paired_ratios"][arm + "_AA"]["median"] for r in pipeline["cases"] for arm in PRIMARY]
    text = f"""# Independent singleton-DAG experimental record

The guarded implementation gives a large checked-group-stage gain on the
stabilized-circle family. The preserved ordinary corpus does **not** show a
whole-recognizer acceleration. The optional terminal guard was selected after
an eager partial-batch prototype caused a concrete lost positive within the
established work budget. The complete eager result is retained separately.

## Reproducible boundary and protocol

Baseline commit: `{audit['baseline_commit']}`.
Python: `{audit['python']}`; platform: `{audit['platform']}`.
Full packages are copied into distinct frozen directories and imported as
`fastunknot` in separate persistent subprocesses. Every package `.py` file is
hashed before and after, as is the harness. Baseline/current source hashes
match across the guarded audit and both timing runs. This avoids mixing
absolute imports from different versions. `PYTHONHASHSEED=0`.

Each timed call encloses exactly `fn(Diagram.from_pd(pd), **options)` inside
the corresponding worker. Fresh source validation, search, and mandatory
independent compressed replay are included; imports, interprocess transport,
and result serialization are outside this timer. Each case has six randomly
shuffled arms: baseline default and forest, current guarded singleton, and an
A/A duplicate of each. One warmup per arm is excluded; five rounds are
retained. Ratios are medians of per-round paired ratios, so they need not
equal ratios of the displayed medians. All source PDs, settings, sample
orders, statuses, counters, certificates, and hashes are stored in the JSON.
This is one machine and five measured rounds; no general performance claim
or statistical confidence interval is inferred from those timings.

## Independent source audit

The guarded audit contains {audit['diagrams']} actual validated source diagrams,
{audit['legacy_mode_comparisons']} exact legacy default/projection/forest
certificate-and-nondecision comparisons, and {audit['singleton_certificates']}
singleton-enabled positives that each pass both independent literal and
compressed replay from the original diagram. Legacy statistics are also
identical: `{legacy_stats}`. There are zero newly closed and zero lost
positives against either default or forest in this finite audit.

Guarded certificate versions: `{dict(versions)}`. The 29 version-8 positive
proofs contain {moves['singleton_dag']} singleton batches and
{moves['singleton_pivots']} certified pivots. The corpus consists of 19
preserved ordinary cases, fixed-seed random valid one-component braid
closures, and seven stabilized circles. This is a soundness/regression
audit, not evidence of completeness on arbitrary unknots.

The eager prototype audit had {eager['singleton_certificates']} positives,
zero newly closed cases, and one lost positive: the 141-crossing Gordian
input. Its initial partial batch eliminated 60 generators, but subsequent
search exhausted work 20,000,000. The guarded mode skips partial batches
and eventually accepts a terminal batch of three pivots on this input,
restoring a source-checked certificate. Its search work is 1,292,253 versus
baseline default 1,215,145; the guard is a search-policy correction, not a
claim of zero overhead.

## Checked group stage on an actual unknot source family

Each input is the closure of `sigma_1 ... sigma_n` on n+1 strands; it has n
crossings and is a succession of stabilizations of the circle. The
repository's initial group presentation has n generators. Earlier diagram
simplification is deliberately bypassed here. These are easy unknots, and
the following numbers are **not whole-recognition speedups**.

All {stages['measured_calls']} measured calls and {stages['warmup_calls']}
warmups completed. The common options are `seconds=None`,
`max_work=50_000_000`, `max_nodes=1_000_000`, `compressed_search=True`.

{stage_table}

The singleton mode takes one raw terminal batch in every row. For n=256,
search work is 1,905,056 (default), 595,473 (forest), and 92,547 (singleton).
Corresponding grammar node counts are 98,939, 2,041, and 2,547; the singleton
batch does not minimize every size metric. Canonical JSON certificate sizes
are 17,600, 49,244, and 12,770 bytes. The measured mechanism is fewer
repeated passes and a shorter trace, with shared raw composition. Across
the stage cases, paired A/A medians span {min(aa_stage):.3f}–{max(aa_stage):.3f}.
Node construction is linear on this family; charged producer work includes
sorting, and these finite timings do not establish an asymptotic bound.

## Complete ordinary-corpus recognition

All {pipeline['measured_calls']} measured calls and {pipeline['warmup_calls']}
warmups completed. Fifteen unknots reach the checked group stage. Four
knots finish earlier: trefoil and figure-eight by the homogeneous Seifert
genus filter, Conway and Kinoshita–Terasaka by the modular Jones filter.
Timing differences for those four cannot be attributed to this feature.

Only Gordian uses a singleton batch under the terminal guard; the other
fourteen unknot cases preserve the default version-5 proof but pay
eligibility-planning overhead. No new ordinary case is solved.

{pipeline_table}

The median of paired ratios of the per-round total time for the entire
19-case workload is {ratios['versus_default']:.6f} for default/singleton and
{ratios['versus_forest']:.6f} for forest/singleton. Ratios below one favor
the baseline. Corresponding workload A/A medians are
{ratios['baseline_default_AA']:.6f}, {ratios['baseline_forest_AA']:.6f}, and
{ratios['singleton_AA']:.6f}. Per-case A/A medians span
{min(aa_pipeline):.3f}–{max(aa_pipeline):.3f}, including submillisecond cases.
This record supports keeping the feature opt-in and investigating cheaper
eligibility discovery; it does not support a broad speedup claim.

## Files and rerun

- `singleton_dag_research.py`: frozen audit and randomized paired harness.
- `summarize_singleton_dag.py`: derives this summary and the CSV tables.
- `audit-guarded.json`, `stages-guarded.json`, `benchmark-guarded.json`:
  complete final guarded records with source hashes and certificates.
- `audit-eager.json`: retained development regression evidence.
- `frozen-guarded/`: package snapshots used by all final records.
- `frozen-eager/`: package snapshots used by the eager audit.

Run the harness's `audit`, `stages`, and `benchmark` modes sequentially,
providing `--baseline-fast`, `--current-fast`, `--corpus`, `--snapshots`,
and `--output`; use fresh snapshot/output directories for changed code.
Default stage sizes are 16,32,64,128,256; default measured rounds are five.
Then run `python summarize_singleton_dag.py` beside the named output files.
No timing run should overlap other CPU-intensive work.
"""
    (HERE / "results-summary.md").write_text(text)
    generated = args.article_generated
    generated.mkdir(parents=True, exist_ok=True)
    (generated / "stages.tex").write_text(tex_table(
        ["$n$", "Default ms", "Forest ms", "Singleton ms", "Default/singleton", "Forest/singleton"],
        [[r["crossings"], *[f'{r[a + "_median_ms"]:.3f}' for a in PRIMARY],
          f'{r["versus_default_paired_median"]:.3f}', f'{r["versus_forest_paired_median"]:.3f}']
         for r in stage_rows],
        "rrrrrr", "Fresh source checked group stage only; five paired rounds; ratios are medians of ratios.",
    ))
    (generated / "stage-structure.tex").write_text(tex_table(
        ["$n$", "Forest batches", "Singleton pivots", "Default nodes", "Forest nodes", "Singleton nodes"],
        [[r["crossings"], r["forest_batches"], r["singleton_pivots"],
          *[r[a + "_nodes"] for a in PRIMARY]] for r in stage_rows],
        "rrrrrr", "One singleton batch in every row; nodes are search-arena total nodes.",
    ))
    ordinary_tex_rows = []
    for r in pipeline_rows:
        source = {"figure_eight": "figure-eight", "kinoshita_terasaka": "Kinoshita--Terasaka"}.get(r["name"], r["name"])
        boundary = (r"$\mathrm{U}_{G}$" if r["group_reached"] else
                    r"$\mathrm{K}_{S}$" if r["method"] == "homogeneous-seifert-genus" else r"$\mathrm{K}_{J}$")
        ordinary_tex_rows.append([source, boundary, *[f'{r[a + "_median_ms"]:.3f}' for a in PRIMARY],
                                  f'{r["versus_default_paired_median"]:.3f}'])
    (generated / "ordinary.tex").write_text(tex_table(
        ["Input", "Outcome", "Default ms", "Forest ms", "Singleton ms", "Default/singleton"],
        ordinary_tex_rows, "llrrrr",
        "U_G: unknot via group stage; K_S: knotted via homogeneous Seifert genus; K_J: knotted via Jones. Only Gordian has a singleton batch.",
    ))
    (generated / "independent-summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    (generated / "stage-plot-data.csv").write_bytes((HERE / "stages-guarded-summary.csv").read_bytes())
    (generated / "ordinary-data.csv").write_bytes((HERE / "benchmark-guarded-summary.csv").read_bytes())
    print(json.dumps({"audit": summary["audit"], "versions": dict(versions),
                      "moves": dict(moves), "workload_ratios": ratios}, indent=2))


if __name__ == "__main__":
    main()
