#!/usr/bin/env python3
"""Expand this article's local TeX inputs into one independently compilable file."""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
INPUT = re.compile(r"\\input\{([^{}]+)\}")


def expand(path: Path, stack: tuple[Path, ...] = ()) -> str:
    path = path.resolve()
    if path in stack:
        raise ValueError(f"Cyclic TeX input: {path.name}")
    if not path.is_file() or ROOT not in path.parents:
        raise ValueError(f"Missing or nonlocal TeX input: {path}")
    text = path.read_text(encoding="utf-8")
    def replace(match: re.Match[str]) -> str:
        name = match.group(1)
        child = path.parent / (name if Path(name).suffix else name + ".tex")
        return "\n% Begin inlined " + name + "\n" + expand(child, stack + (path,)) + "\n% End inlined " + name + "\n"
    return INPUT.sub(replace, text)


def main() -> None:
    destination = ROOT / "Projective_Port_Atlases.tex"
    destination.write_text("% Standalone edition; regenerated by experiments/inline_article.py.\n" +
                           expand(ROOT / "article" / "article.tex"), encoding="utf-8")
    print(destination)


if __name__ == "__main__":
    main()
