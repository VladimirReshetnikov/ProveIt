#!/usr/bin/env python3
"""Reproduce the rounding-extinction computations without network access.

Exact thresholds and stopping times use Python integers and Fraction only.
mpmath and matplotlib are imported only for numerical diagnostics and figures.

Examples:
    python reproduce.py
    python reproduce.py --exact-only
    python reproduce.py --threshold 1000 --m 2/3
    python reproduce.py --stop 12345 --m 3/2

The threshold T_m(K) is the least starting integer n with tau_m(n) > K.
Consequently tau_m(n)=K+1 on T_m(K) <= n < T_m(K+1).
Our convention is tau_m(0)=1; the positive-input block formula has an
explicit exception at zero.
"""
