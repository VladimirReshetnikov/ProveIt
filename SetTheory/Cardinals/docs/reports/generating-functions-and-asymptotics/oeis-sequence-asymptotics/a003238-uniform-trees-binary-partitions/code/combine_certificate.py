"""Combine directed receipts under the constant-profile hypothesis.
No empirical amplitude values or floating-point arithmetic are used.
All certification guards remain active with python -O.
"""
from pathlib import Path
import json, hashlib
from certified_interval import IV, PREC
ROOT=Path(__file__).resolve().parent

def require(condition,message):
 if not condition:raise ValueError(message)

def read_iv(row,key):
 endpoints=row[key+'_integer_bounds']
 require(len(endpoints)==2,'interval must have two endpoints')
 v=IV(*map(int,endpoints))
 require(v.lo<=v.hi,'reversed interval endpoints')
 return v

def combine_receipts(r,o):
 require(r['status']=='RADIAL_VALUES_ENCLOSED','unexpected radial receipt status')
 require(o['status']=='POSITIVE_OPERATOR_ENCLOSED','unexpected operator receipt status')
 require(r['precision_bits']==o['precision_bits']==PREC,'precision mismatch')
 require(len(r['rows'])==len(o['rows'])==2,'exactly two matching receipt rows required')
 rows=[];intervals=[]
 for rr,oo in zip(r['rows'],o['rows']):
  require(rr['t']==oo['t'],'test point mismatch')
  H=read_iv(rr,'H');s=read_iv(oo,'S3');R4=read_iv(oo,'14T4');eb=read_iv(oo,'epsilon_b')
  require(s.lo>0,'positive S3 not certified')
  require(R4.lo>=0 and eb.lo>=0,'nonnegative remainder bounds required')
  c=(H+IV(-R4.hi-eb.hi,eb.hi))/s
  intervals.append(c)
  rows.append({'t':rr['t'],'hypothetical_constant_interval':c.decimal(40),'integer_bounds':c.integer_bounds()})
 gap=intervals[0]-intervals[1]
 require(gap.lo>0,'No contradiction certified: intervals overlap or have the wrong order')
 return rows,gap

def main():
 r=json.loads((ROOT/'RADIAL_VALUE_CERTIFICATE.json').read_text())
 o=json.loads((ROOT/'OPERATOR_VALUE_CERTIFICATE.json').read_text())
 rows,gap=combine_receipts(r,o)
 inputs=['certified_interval.py','verify_exact.py','certify_global_bound.py','GLOBAL_BOUND_CERTIFICATE.json','operator_constants.py','OPERATOR_CONSTANTS_CERTIFICATE.json','certify_radial_values.py','RADIAL_VALUE_CERTIFICATE.json','certify_operator.py','OPERATOR_VALUE_CERTIFICATE.json','combine_certificate.py']
 result={'status':'CONSTANT_PROFILE_CONTRADICTION','precision_bits':PREC,'scope':'The intervals constrain a hypothetical common constant under Pcal == C; they are NOT pointwise amplitude enclosures and the gap is NOT an oscillation lower bound. All finite receipts are regenerated by the public reproduction runner; the analytic proof is in Report215.','rows':rows,'contradiction_gap':gap.decimal(40),'gap_integer_bounds':gap.integer_bounds(),'input_sha256':{x:hashlib.sha256((ROOT/x).read_bytes()).hexdigest() for x in inputs}}
 (ROOT/'NONCONSTANCY_CERTIFICATE.json').write_text(json.dumps(result,indent=2)+'\n')
 print(json.dumps(result,indent=2))
if __name__=='__main__':main()
