#!/usr/bin/env python3
"""Reproducible diagnostics, deliberately not an asymptotic proof.

Requires mpmath and numpy. Counts generated by exact_counts.cpp are compared
with the unmodified OEIS b-file. The floating continuation is explicitly
labeled and never replaces the exact coefficients in the common range.
"""
from pathlib import Path
import json, hashlib
import mpmath as mp
import numpy as np

ROOT = Path(__file__).resolve().parent
mp.mp.dps = 90
mu = mp.mpf(8)/(3*mp.pi**2)

def read(name, cast):
    return {int(n): cast(v) for n,v in
            (line.split() for line in (ROOT/name).read_text().splitlines()
             if line and not line.startswith('#'))}

exact = read('exact-counts-400.txt', int)
published = read('oeis-b202058.txt', int)
floating = read('floating-counts-1000.txt', mp.mpf)
assert all(exact[n] == a for n,a in published.items())
N = max(exact)
strict_failures = [n for n in range(2,N)
                   if (n+1)*exact[n]**2 <= n*exact[n-1]*exact[n+1]]
assert not strict_failures
exact_h = {n: mp.log(a)-mp.loggamma(n+1)-n*mp.log(mu)
           for n,a in exact.items()}
errors = [(abs(mp.log(floating[n])-exact_h[n]), n)
          for n in floating.keys() & exact.keys()]
max_error = max(errors)
h = {n: mp.log(b) for n,b in floating.items()}
h.update(exact_h)
g = {n:n*(h[n]-h[n-1]) for n in range(1,max(h)+1)}
c = {n:n*(g[n]-g[n-1]) for n in range(2,max(h)+1)}
sigma = {n:n*(c[n]-c[n-1])/c[n] for n in range(3,max(h)+1)}
selected = [10,20,40,60,80,100,120,160,176,200,250,300,350,400,
            500,600,700,800,900,1000]
selected = [n for n in selected if n in h]
with (ROOT/'diagnostics.tsv').open('w') as f:
    f.write('n\tsource\th\tg=n*delta_h\tc=n*delta_g\tsigma_eff=n*delta_c/c\n')
    for n in range(3,max(h)+1):
        f.write(str(n)+'\t'+('exact' if n<=N else 'long-double')+'\t'+
                '\t'.join(mp.nstr(d[n],30) for d in [h,g,c,sigma])+'\n')

out = {
    'meaning': 'Finite numerical diagnostics only; no limiting correction coefficient is established.',
    'mu': str(mu),
    'oeis_source': 'https://oeis.org/A202058/b202058.txt',
    'oeis_matches_through': max(published),
    'computed_exact_through': N,
    'computed_floating_through': max(floating),
    'largest_log_error_floating_vs_exact': str(max_error[0]),
    'largest_error_index': max_error[1],
    'normalized_strict_log_concavity_exact_indices': [2,N-1],
    'normalized_log_concavity_n_1': 'equality',
    'normalized_ratios_above_mu_exact': all(h[n]>h[n-1] for n in range(1,N+1)),
    'selected_diagnostics': [dict(n=n, source='exact' if n<=N else 'long-double',
                                h=mp.nstr(h[n],30),g=mp.nstr(g[n],30),
                                curvature=mp.nstr(c[n],30),
                                sigma_eff=mp.nstr(sigma[n],30)) for n in selected],
    'inverse_log_fits': [],
    'log_residual_fits': [],
    'sha256': {name: hashlib.sha256((ROOT/name).read_bytes()).hexdigest()
               for name in ['exact-counts-400.txt','oeis-b202058.txt',
                            'floating-counts-1000.txt','exact_counts.cpp',
                            'floating_counts.cpp']},
}

# Fits intentionally show sensitivity to degree and fitting window.
for hi in sorted(set([400,max(h)])):
    for lo in sorted(set([max(40,hi//4),hi//2,3*hi//4])):
        ns=np.arange(lo,hi+1);x=1/np.log(ns)
        y=np.array([float(c[n]) for n in ns])
        for degree in [1,2,3]:
            coeff=np.polynomial.polynomial.polyfit(x,y,degree)
            error=np.max(abs(np.polynomial.polynomial.polyval(x,coeff)-y))
            out['inverse_log_fits'].append(dict(lo=lo,hi=hi,degree=degree,
                extrapolated_curvature=float(coeff[0]),coeff=coeff.tolist(),
                max_fit_error=float(error)))

def basis(model,n):
    n=np.asarray(n,dtype=float);L=np.log(n)
    if model=='power': return [np.ones_like(n),L]
    if model=='power+inverse_n': return [np.ones_like(n),L,1/n,1/n**2]
    if model=='lognormal': return [np.ones_like(n),L,L**2]
    if model=='lognormal+inverse_n': return [np.ones_like(n),L,L**2,1/n,1/n**2]
    if model=='lognormal+log_n_over_n': return [np.ones_like(n),L,L**2,L/n,1/n]
    if model=='lognormal+LlogL': return [np.ones_like(n),L,L**2,L*np.log(L),np.log(L)]
    if model.startswith('stretch:'):
        ss=float(model.split(':')[1])
        return [np.ones_like(n),L,n**ss]
    raise ValueError(model)

models=['power','power+inverse_n','lognormal','lognormal+inverse_n',
        'lognormal+log_n_over_n','lognormal+LlogL',
        'stretch:0.06','stretch:0.08','stretch:0.1']
for lo,hi in [(100,200),(200,400),(400,800)]:
    if hi>max(h):continue
    ns=np.arange(lo,hi+1);ys=np.array([float(h[n]) for n in ns])
    validation_end=min(2*hi,max(h));vs=np.arange(hi+1,validation_end+1)
    for model in models:
        X=np.array(basis(model,ns)).T
        coeff=np.linalg.lstsq(X,ys,rcond=None)[0]
        fiterr=np.max(abs(X@coeff-ys))
        valerr=None
        if len(vs):
            valerr=float(np.max(abs(np.array(basis(model,vs)).T@coeff-
                                    np.array([float(h[n]) for n in vs]))))
        out['log_residual_fits'].append(dict(model=model,lo=lo,hi=hi,
            coefficients=coeff.tolist(),max_fit_error=float(fiterr),
            validation_end=validation_end,max_validation_error=valerr))

(ROOT/'analysis.json').write_text(json.dumps(out,indent=2)+'\n')
print(json.dumps({k:v for k,v in out.items()
                  if k not in ['sha256','inverse_log_fits','log_residual_fits']},indent=2))
