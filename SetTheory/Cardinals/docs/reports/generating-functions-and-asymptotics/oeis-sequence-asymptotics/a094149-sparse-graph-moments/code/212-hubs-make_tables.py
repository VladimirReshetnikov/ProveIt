#!/usr/bin/env python3
"""Generate exact-rational finite tables, with Decimal rounding only at display."""
import argparse
from fractions import Fraction
import json
from pathlib import Path
from common import (bells, display_ratio, exact_ratio, load_rows, require,
                    threshold_s, union_counts, read_json_unique)
ROOT = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--data-dir', type=Path, required=True)
parser.add_argument('--expected-max', type=int, required=True)
parser.add_argument('--ks', default='16,32,64,128,256')
parser.add_argument('--output-dir', type=Path, default=ROOT/'build'/'tables')
parser.add_argument('--compare', type=Path, help='Exact JSON comparison, not a decimal tolerance.')
parser.add_argument('--inject-failure', choices=('table_comparison',))
args = parser.parse_args()
ks = [int(x) for x in args.ks.split(',')]
M,F = load_rows(args.data_dir,args.expected_max)
require(all(k in M and k>0 for k in ks), 'table_range', ks)
B = bells(max(ks)+1)
rows = []
for k in ks:
    require(sum(F[k].values()) == M[k], 'stored_row_sum', k)
    Q = B[k+1]
    ratio = Fraction(M[k],2*Q)
    row = {'k':k,'M2k':str(M[k]),'Bell_k_plus_1':str(Q),
           'M_over_2B':exact_ratio(ratio), 'M_over_2B_display':display_ratio(ratio),'windows':{}}
    for family in ('quarter','log_squared'):
        S = threshold_s(k,family)
        L = k-S
        R = sum((Fraction(2*k*f,m) for m,f in F[k].items() if S<m<k-S),Fraction(0))
        union = union_counts(k,L,F,M[k])
        values = {'S':S,'L':L,'two_hub_formula_valid':2*L>k,
                  'R':exact_ratio(R),'R_over_B':exact_ratio(R/Q),'R_over_B_display':display_ratio(R/Q)}
        if union is None:
            values.update({'U':None,'D':None,'U_over_2B':None,'U_over_2B_display':'N/A',
                           'complement':None,'complement_over_B':None,'complement_over_B_display':'N/A'})
        else:
            U = union['U']
            complement = M[k]-U
            values.update({'U':str(U),'D':str(union['D']),'U_over_2B':exact_ratio(Fraction(U,2*Q)),
                           'U_over_2B_display':display_ratio(Fraction(U,2*Q)),
                           'complement':str(complement),'complement_over_B':exact_ratio(Fraction(complement,Q)),
                           'complement_over_B_display':display_ratio(Fraction(complement,Q))})
        row['windows'][family] = values
    rows.append(row)
result = {'schema':'report212-exact-table-v1','B_convention':'B=B_(k+1)',
          'quarter_window':'S=floor(k^(1/4))', 'log_squared_window':'S=ceil((ln k)^2)',
          'union_availability':'The two-hub formula is used only when L=k-S>k/2. N/A does not mean zero.',
          'arithmetic':'Counts are integers; every ratio and weighted sum is a fractions.Fraction; display uses Decimal only.',
          'rows':rows}
if args.compare:
    reference = read_json_unique(args.compare)
    if args.inject_failure == 'table_comparison':
        result['rows'][0]['M2k'] = str(int(result['rows'][0]['M2k'])+1)
    require(result == reference,'table_comparison',str(args.compare))


def tex_number(text):
    if text == 'N/A':
        return r'\text{N/A}'
    if 'e' in text:
        mantissa,exponent = text.split('e')
        return mantissa+r'\!\times\!10^{'+str(int(exponent))+'}'
    return text


args.output_dir.mkdir(parents=True,exist_ok=True)
(args.output_dir/'table_values.json').write_text(json.dumps(result,indent=2)+'\n')
lines = ['k\twindow\tS\tM_over_2B\tU_over_2B\tcomplement_over_B\tR_over_B']
for family in ('quarter','log_squared'):
    table = [r'% Generated by code/make_tables.py from exact fractions. Do not hand-edit.',
             r'\begin{tabular}{@{}rrrrrr@{}}',r'\toprule',
             r'$k$ & $M_{2k}/(2B)$ & $S$ & $U/(2B)$ & $(M_{2k}-U)/B$ & $R/B$ \\',
             r'\midrule']
    for row in rows:
        window = row['windows'][family]
        displays = [row['M_over_2B_display'],window['U_over_2B_display'],
                    window['complement_over_B_display'],window['R_over_B_display']]
        lines.append('\t'.join([str(row['k']),family,str(window['S'])]+displays))
        table.append(str(row['k'])+' & $'+tex_number(displays[0])+'$ & '+str(window['S'])+
                     ' & '+' & '.join('$'+tex_number(x)+'$' for x in displays[1:])+r' \\')
    table += [r'\bottomrule',r'\end{tabular}']
    (args.output_dir/f'numeric_table_{family}.tex').write_text('\n'.join(table)+'\n')
(args.output_dir/'numeric_table.tsv').write_text('\n'.join(lines)+'\n')
print(json.dumps({'all_checks_passed':True,'table_ks':ks,
                  'exact_reference_comparison_passed':bool(args.compare)},indent=2))
