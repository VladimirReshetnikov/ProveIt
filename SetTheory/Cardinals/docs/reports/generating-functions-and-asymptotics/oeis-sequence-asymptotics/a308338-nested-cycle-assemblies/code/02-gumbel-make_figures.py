#!/usr/bin/env python3
"""Create publication figures and TeX tables from the retained CSV data.

The plots are numerical illustrations. Read the article and the numerical
scripts for the distinctions between exact counts, quadrature, and proofs.
Run from any directory; inputs and outputs resolve relative to this file.
"""
from __future__ import annotations

import csv
import math
from pathlib import Path

import matplotlib
matplotlib.use('Agg')
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
FIG = ROOT/'figures'
FIG.mkdir(exist_ok=True)
COLORS = dict(navy='#17324D',teal='#167D8D',coral='#B84B32',purple='#79568E',gray='#65717D')
plt.rcParams.update({
    'font.family':'DejaVu Serif', 'font.size':9,
    'axes.titlesize':10, 'axes.labelsize':9, 'legend.fontsize':8,
    'axes.spines.top':False, 'axes.spines.right':False,
    'axes.edgecolor':'#9AA4AD', 'axes.labelcolor':COLORS['navy'],
    'xtick.color':COLORS['gray'], 'ytick.color':COLORS['gray'],
    'grid.color':'#E3E8EC', 'grid.linewidth':0.6,
    'savefig.bbox':'tight', 'pdf.fonttype':42, 'ps.fonttype':42,
})


def read_csv(name: str) -> list[dict[str,float]]:
    with (ROOT/'data'/name).open() as handle:
        return [{k:float(v) for k,v in row.items()} for row in csv.DictReader(handle)]


def tex_float(value: float, digits: int = 3) -> str:
    mantissa,exponent = f'{value:.{digits-1}e}'.split('e')
    return rf'\({mantissa}\times10^{{{int(exponent)}}}\)'


def main() -> None:
    nested = read_csv('nested_errors.csv')
    profile = read_csv('nested_profile.csv')
    forest = read_csv('forest_errors.csv')
    last = nested[-1]
    x = np.array([r['x'] for r in profile])
    F = np.array([r['cdf'] for r in profile])
    G = np.array([r['gumbel'] for r in profile])
    beta = np.exp(-x)
    keep = (x >= -2.3) & (x <= 4.0)
    fig,axes = plt.subplots(1,2,figsize=(6.8,2.65),layout='constrained')
    ax = axes[0]
    ax.plot(x[keep],(F-G)[keep],color=COLORS['navy'],lw=1.7,label=r'Numerical $F_n-G$')
    ax.plot(x[keep],(last['delta']*G*beta*(1-beta))[keep],color=COLORS['coral'],ls='--',lw=1.5,label=r'Leading profile $\delta H$')
    ax.set_title('(a) Ordinary Gumbel discrepancy',loc='left')
    ax.set_ylabel('Signed CDF error')
    ax.legend(frameon=False,loc='lower right')
    ax = axes[1]
    for key,label,color in [('smooth',r'$F_n-J_n$',COLORS['teal']),
                            ('lattice',r'$F_n-U_n$',COLORS['coral']),
                            ('sensitive',r'$F_n-\widetilde U_n$',COLORS['purple'])]:
        values=np.array([r[key] for r in profile])
        ax.plot(x[keep],(F-values)[keep],color=color,lw=1.5,label=label)
    ax.set_title('(b) Residuals after correction',loc='left')
    ax.legend(frameon=False,loc='lower right')
    for ax in axes:
        ax.axhline(0,color=COLORS['gray'],lw=0.6,zorder=0)
        ax.grid(axis='y')
        ax.set_xlabel(r'Normalized cutoff $x=\tau m-L$')
        ax.ticklabel_format(axis='y',style='sci',scilimits=(0,0),useMathText=True)
    fig.savefig(FIG/'error_profiles.pdf')
    fig.savefig(FIG/'error_profiles.png',dpi=220)
    plt.close(fig)

    ns=np.array([r['n'] for r in forest])
    raw=np.array([r['raw_max_error'] for r in forest])
    corrected=np.array([r['corrected_max_error'] for r in forest])
    fig,axes=plt.subplots(1,2,figsize=(6.8,2.75),layout='constrained')
    ax=axes[0]
    ax.loglog(ns,raw,'o-',color=COLORS['navy'],ms=3.5,label='Ordinary Gumbel')
    ax.loglog(ns,corrected,'s-',color=COLORS['teal'],ms=3.5,label='Calibrated continuous')
    ax.loglog(ns,np.array([r['tau'] for r in forest])/(2*math.e),ls='--',color=COLORS['gray'],label=r'$\tau/(2e)$')
    ax.set_title('(a) Numerical maximum errors',loc='left')
    ax.set_ylabel('Absolute CDF error')
    ax.legend(frameon=False,loc='lower left')
    ax=axes[1]
    ax.semilogx(ns,[r['raw_over_delta_kappa'] for r in forest],'o-',color=COLORS['navy'],ms=3.5,label=r'Raw / $(\kappa\delta)$')
    ax.semilogx(ns,[r['corrected_over_lattice_optimum'] for r in forest],'s-',color=COLORS['teal'],ms=3.5,label=r'Calibrated / $(\tau/(2e))$')
    ax.axhline(1,color=COLORS['gray'],ls='--',lw=1)
    ax.set_title('(b) Ratios to proved equivalents',loc='left')
    ax.set_ylabel('Ratio')
    ax.set_ylim(0.8,5.4)
    ax.legend(frameon=False,loc='upper right')
    for ax in axes:
        ax.grid(axis='y',which='major')
        ax.set_xlabel(r'Total size $n$')
        ax.set_xticks([1e4,1e6,1e8,1e10,1e12])
    fig.savefig(FIG/'forest_convergence.pdf')
    fig.savefig(FIG/'forest_convergence.png',dpi=220)
    plt.close(fig)

    lines=[r'% Generated by code/make_figures.py from retained CSV files.',
           r'\begin{table}[htbp]',r'\centering',r'\small',
           r'\caption{Nested-cycle numerical errors. Continuous comparisons include both ends of each examined step; lattice comparisons use the exact lattice points. The window is finite and the arithmetic is not interval-certified.}',
           r'\label{tab:nested-errors}',r'\begin{tabular}{rcccc}',r'\toprule',
           r'$n$ & Gumbel $G$ & Continuous $J_n$ & Lattice $U_n$ & Refined $\widetilde U_n$\\',r'\midrule']
    for r in nested:
        fields=[rf'\(10^{{{round(math.log10(r["n"]))}}}\)']
        fields += [tex_float(r[k]) for k in ('raw_error','smooth_error','lattice_error','sensitive_error')]
        lines.append(' & '.join(fields)+r'\\')
    lines += [r'\bottomrule',r'\end{tabular}',r'\end{table}',
              r'\begin{table}[htbp]',r'\centering',r'\small',
              r'\caption{Path-forest numerical errors and ratios to the proved leading equivalents. For the largest sizes, the values are sampled maxima on a dense normalized grid.}',
              r'\label{tab:forest-errors}',r'\begin{tabular}{rcccc}',r'\toprule',
              r'$n$ & Raw error & Raw / $(\kappa\delta)$ & Calibrated error & Calibrated / $(\tau/(2e))$\\',r'\midrule']
    for r in forest[::2]:
        fields=[rf'\(10^{{{round(math.log10(r["n"]))}}}\)',
                tex_float(r['raw_max_error']),f'{r["raw_over_delta_kappa"]:.4f}',
                tex_float(r['corrected_max_error']),f'{r["corrected_over_lattice_optimum"]:.4f}']
        lines.append(' & '.join(fields)+r'\\')
    lines += [r'\bottomrule',r'\end{tabular}',r'\end{table}']
    (ROOT/'numerical_tables.tex').write_text('\n'.join(lines)+'\n')
    print('Created two PDF/PNG figures and numerical_tables.tex.')


if __name__ == '__main__':
    main()
