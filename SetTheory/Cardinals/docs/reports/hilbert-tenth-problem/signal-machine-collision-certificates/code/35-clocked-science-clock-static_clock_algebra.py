#!/usr/bin/env python3
"""Fresh static rational certificate for the 30D five-signal clock.

This checks declared affine rows and finite word-length ledgers only. It does
not select a next collision, evolve a configuration, read an earlier checker,
load a saved event schedule, or execute author/upstream scientific software.
Coordinates of rows are (D,x,y), or explicitly the positive gaps (a,b,c).
"""
from fractions import Fraction as F
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
CORE = Path('/workspace/shared/five-signal-branching64-20261004/PROOF.md')
CORE_SHA = '85f5de45c0a30f8bdf45b82a613ef9e5a8c766b5d8215d17a3ebbbd0f60b370f'


def row(*a):
    return tuple(F(x) for x in a)


def add(*rows):
    return tuple(sum(t, F(0)) for t in zip(*rows))


def scale(q, r):
    return tuple(q*x for x in r)


def sub(r, s):
    return add(r, scale(-1, s))


def encode(x):
    if isinstance(x, F):
        return str(x)
    if isinstance(x, dict):
        return {k: encode(v) for k, v in x.items()}
    if isinstance(x, (list, tuple, set)):
        return [encode(v) for v in x]
    return x


D, X, Y, ZERO = row(1,0,0), row(0,1,0), row(0,0,1), row(0,0,0)
# Derive costs from the primitive formulas, not from asserted final triples.
inc_t_coefficient = 2*(1+F(1,2)) + 2*(F(1,2)+F(1,2)/ (1-F(1,40)))
dec_t_coefficient = 2*(1+F(2)) + 2*(F(2)+F(2)/(1+F(1,20)))
assert inc_t_coefficient == F(196,39)
assert dec_t_coefficient == F(290,21)
test_N_coefficient = F(250,9)
positive_t_coefficient = test_N_coefficient + dec_t_coefficient
assert positive_t_coefficient == F(2620,63)

# All x,y on the right-hand side now denote OUTPUT coordinates.
A_inc_input_t = sub(scale(2,X), scale(F(1,20),D))
A_pos_input_t = add(scale(F(1,2),X), scale(F(1,40),D))
B_inc_input_r = sub(scale(F(39,20),D), scale(2,Y))
B_pos_input_r = sub(scale(F(21,40),D), scale(F(1,2),Y))
costs = {
    'A_inc': add(scale(2,D), scale(inc_t_coefficient,A_inc_input_t)),
    'A_zero': scale(F(25,9),add(scale(2,X),Y)),
    'A_positive': add(scale(2,D),scale(positive_t_coefficient,A_pos_input_t)),
    'B_inc': add(scale(4,D),scale(inc_t_coefficient,B_inc_input_r)),
    'B_zero': add(scale(2,D),scale(F(25,9),add(scale(2,sub(D,Y)),sub(D,X)))),
    'B_positive': add(scale(4,D),scale(positive_t_coefficient,B_pos_input_r)),
}
expected = {
    'A_inc':row(F(341,195),F(392,39),0),
    'A_zero':row(0,F(50,9),F(25,9)),
    'A_positive':row(F(383,126),F(1310,63),0),
    'B_inc':row(F(897,65),0,-F(392,39)),
    'B_zero':row(F(31,3),-F(25,9),-F(50,9)),
    'B_positive':row(F(1085,42),0,-F(1310,63)),
}
assert costs == expected
# Independently recover outputs from each inverse row.
assert add(scale(F(1,2), A_inc_input_t), scale(F(1,40), D)) == X
assert sub(scale(2,A_pos_input_t),scale(F(1,20),D)) == X
assert sub(D,add(scale(F(1,2),B_inc_input_r),scale(F(1,40),D))) == Y
assert sub(D,sub(scale(2,B_pos_input_r),scale(F(1,20),D))) == Y

# STATIC PRIMITIVE ROWS, in positive gap coordinates a=x,b=y-x,c=D-y.
# These are declared flight-length rows, not a next-event algorithm.
a,b,c = row(1,0,0),row(0,1,0),row(0,0,1)
span = add(a,b,c)
primitive_lengths = {
    'LX': [a,a],
    'LY': [a,b,b,a],
    'RX': [c,b,b,c],
    'RY': [c,c],
    'LR': [a,b,c],
    'RL': [c,b,a],
    'full': [a,b,c,c,b,a],
}
primitive_sums = {
    'LX':scale(2,a), 'LY':scale(2,add(a,b)),
    'RX':scale(2,add(b,c)), 'RY':scale(2,c),
    'LR':span, 'RL':span, 'full':scale(2,span),
}
for primitive, lengths in primitive_lengths.items():
    assert add(*lengths) == primitive_sums[primitive]
    for length in lengths:
        assert all(v>=0 for v in length) and any(v>0 for v in length)

# Verify the declared contact positions and signed displacements independently.
# These finite rows state the proof's words; they are not generated by dynamics.
primitive_positions = {
    'LX':[ZERO,a,ZERO],
    'LY':[ZERO,a,add(a,b),a,ZERO],
    'RX':[span,add(a,b),a,add(a,b),span],
    'RY':[span,add(a,b),span],
    'LR':[ZERO,a,add(a,b),span],
    'RL':[span,add(a,b),a,ZERO],
    'full':[ZERO,a,add(a,b),span,add(a,b),a,ZERO],
}
primitive_directions = {
    'LX':[1,-1], 'LY':[1,1,-1,-1], 'RX':[-1,-1,1,1],
    'RY':[-1,1], 'LR':[1,1,1], 'RL':[-1,-1,-1],
    'full':[1,1,1,-1,-1,-1],
}
for primitive, positions in primitive_positions.items():
    lengths=primitive_lengths[primitive]
    directions=primitive_directions[primitive]
    assert len(positions)==len(lengths)+1==len(directions)+1
    for before,after,length,direction in zip(positions,positions[1:],lengths,directions):
        assert sub(after,before)==scale(direction,length)
        # For arbitrary positive v, dt=length/v gives displacement=(sign*v)*dt.


# Local gap rows at every possible padding contact. The contact gap is omitted;
# the other three stationary distances are positive sums of a,b,c.
contact_separations = {
    'L': [a,add(a,b),span],
    'X': [a,b,add(b,c)],
    'Y': [add(a,b),b,c],
    'R': [span,add(b,c),c],
}
for distances in contact_separations.values():
    for distance in distances:
        assert all(v>=0 for v in distance) and any(v>0 for v in distance)

core_counts = dict(A_inc=14,A_zero=14,A_positive=26,B_inc=20,B_zero=20,B_positive=32)
distance_rows = {'LX':X,'LY':Y,'RX':sub(D,X),'RY':sub(D,Y)}
ledger = {}
new_magnitudes = set()
for name, (alpha,beta,gamma) in costs.items():
    coeffs = {'LX':max(-beta,F(0)), 'LY':max(-gamma,F(0)),
              'RY':max(gamma,F(0)), 'RX':max(beta,F(0))}
    k = F(30)-alpha-max(beta,F(0))-max(gamma,F(0))-4
    assert k>0
    # Mandatory entry full loop and two transfers cost 4D; final full loop kD.
    padding = scale(4+k,D)
    loop_events=0
    loops=[]
    for primitive, coefficient in coeffs.items():
        if coefficient:
            speed=2/coefficient
            assert speed>0 and F(2)/speed==coefficient
            padding=add(padding,scale(coefficient,distance_rows[primitive]))
            loop_events+=len(primitive_lengths[primitive])
            loops.append(dict(primitive=primitive,coefficient=coefficient,speed=speed,
                              events=len(primitive_lengths[primitive])))
            new_magnitudes.add(speed)
    final_speed=2/k
    assert F(2)/final_speed == k
    new_magnitudes.add(final_speed)
    assert add(costs[name],padding)==scale(30,D)
    padding_events=6+3+3+6+loop_events
    assert padding_events<=26
    total_events=core_counts[name]+padding_events
    assert total_events<=58
    ledger[name]=dict(core_duration=costs[name],k=k,final_speed=final_speed,
                     loops=loops,padding_duration=padding,
                     core_events=core_counts[name],padding_events=padding_events,
                     total_events=total_events)

old_magnitudes={F(1),F(1,3),F(1,79),F(1,41),F(3,2),F(1,4),F(4),F(1,2),F(2)}
assert len(new_magnitudes)==10
assert old_magnitudes.isdisjoint(new_magnitudes)
all_speeds={F(0)} | old_magnitudes | {-s for s in old_magnitudes} | new_magnitudes | {-s for s in new_magnitudes}
assert len(all_speeds)==39
assert max(v['total_events'] for v in ledger.values())==54
assert min(v['k'] for v in ledger.values())==F(1,6)
assert hashlib.sha256(CORE.read_bytes()).hexdigest()==CORE_SHA
result=dict(status='passed', method='fresh exact rational row identities; no physical simulation',
            frozen_core_sha256=CORE_SHA, primitive_lengths=primitive_lengths,
            primitive_positions=primitive_positions,primitive_directions=primitive_directions,
            contact_separations=contact_separations, ledger=ledger,
            new_positive_speed_magnitudes=sorted(new_magnitudes),
            complete_speed_set=sorted(all_speeds),speed_count=len(all_speeds),
            maximum_total_events=54,common_instruction_duration='30D',
            checker_sha256=hashlib.sha256(Path(__file__).read_bytes()).hexdigest())
(ROOT/'evidence'/'static_clock_checks.json').write_text(json.dumps(encode(result),indent=2)+'\n')
print(json.dumps(encode(result),indent=2))
