#!/usr/bin/env python3
"""Read and verify every term of the full T328 polynomial from the saved sparse
witness, streaming the repeated fixed forms rather than materializing a bulky
unrolled JSON. Also checks all 328 explicit one-step arithmetic chunks.
"""
from pathlib import Path
import json,hashlib
from quadratic_core import semantic_table,compile_schema,evaluate
R=Path(__file__).resolve().parent
program=json.loads((R/'virtual3.json').read_text());table=semantic_table(program)
assert json.loads((R/'semantic_branches.json').read_text())==table
B=len(table['branches']);S=table['sub_count'];d=table['register_count']
assert (B,S,d)==(761,233,3)
# Independently construct the coordinate map; no positive slack coordinates exist.
layout=[];k=0
for z in table['branches']:
    coords=[]
    for i in range(d):
        if z['guard']=='zero' and z['register']==i:coords.append(None)
        else:coords.append(k);k+=1
    layout.append(coords)
stride=B+k;assert (k,stride)==(2050,2811)
data=json.loads((R/'accepting_quadratic_witness.json').read_text());T=data['register_instructions']
assert T==328 and data['parameters']=={'L':6,'R':0}
assert data['program_sha256']==hashlib.sha256((R/'virtual3.json').read_bytes()).hexdigest()
w=dict(data['nonzero_coordinates']);assert len(w)==len(data['nonzero_coordinates'])
assert data['variable_count']==stride*T==922008
assert all(type(i) is int and 0<=i<stride*T and type(v) is int and v>0 for i,v in w.items())
# Each source row's branch constants are checked directly against the literal program.
position=0
for source,(label,row) in enumerate(program['rows'].items()):
    op,reg,*targets=row;n=1 if op=='ADD' else 2;branches=table['branches'][position:position+n];position+=n
    assert [table['labels'][b['target']] for b in branches]==targets
    assert all(z['source']==source and z['register']==reg for z in branches)
    assert [z['guard'] for z in branches]==([None] if op=='ADD' else ['positive','zero'])
    assert branches[0]['delta']==[(1 if op=='ADD' else -1)*int(i==reg) for i in range(d)]
    if op=='SUB':assert branches[1]['delta']==[0]*d
assert position==B
assert json.loads((R/'quadratic_schema_T1.json').read_text())==compile_schema(table,1,initial=['L','R',0])
prevcontrol=table['entry'];prevnew=[6,0,0];squares=products=0;value=0;zero_count=0;chunks=0
trace=json.loads((R/'accepting_counter_trace.json').read_text())['trace']
for j in range(T):
    offset=j*stride;e=[w.get(offset+r,0) for r in range(B)];E=sum(e)
    old=[0]*d;new=[0]*d;Q=D=0
    for r,z in enumerate(table['branches']):
        bases=[0 if c is None else w.get(offset+B+c,0) for c in layout[r]]
        ov=bases.copy();nv=bases.copy()
        if z['guard']=='positive':ov[z['register']]+=e[r]
        elif z['guard'] is None:nv[z['register']]+=e[r]
        old=[x+y for x,y in zip(old,ov)];new=[x+y for x,y in zip(new,nv)]
        Q+=z['source']*e[r];D+=z['target']*e[r]
        left=E-e[r];right=e[r]+sum(bases);assert min(left,right)>=0
        value+=left*right;products+=1
        zero_count+=e[r]*int(z['guard']=='zero')
    residuals=[E-1,Q-prevcontrol]+[x-y for x,y in zip(old,prevnew)]
    value+=sum(x*x for x in residuals);squares+=len(residuals)
    assert not any(residuals)
    assert table['labels'][Q]==trace[j]['control'] and old==trace[j]['registers']
    assert table['labels'][D]==trace[j]['next_control'] and new==trace[j]['next_registers']
    # Rebuild the complete one-step arithmetic chunk with constant old counters,
    # checking its actual stored expressions/products through the generic evaluator.
    piece=compile_schema(table,1,entry=prevcontrol,target=D,initial=prevnew)
    column={i-offset:v for i,v in w.items() if offset<=i<offset+stride}
    assert evaluate(piece,column,{})==0;chunks+=1
    prevcontrol=D;prevnew=new
value+=(prevcontrol-table['halt'])**2;squares+=1
assert (value,squares,products,zero_count,prevnew)==(0,1641,249608,29,[0,11,0])
assert 3*T+zero_count==1013
# The last actual instruction is ADD, so no pending-successful-SUB cleanup remains.
assert program['rows'][trace[-1]['control']][0]=='ADD'
out={'status':'passed','natural_coordinate_slots':stride*T,'nonzero_saved_coordinates':len(w),'affine_squares_evaluated':squares,'quadratic_products_evaluated':products,
     'polynomial_value':value,'explicit_one_step_chunks_checked':chunks,'register_instructions':T,'zero_SUB_selectors':zero_count,
     'correct_membrane_steps':3*T+zero_count,'final_registers':prevnew,
     'scope':'Every term of the full fixed-T accepting polynomial evaluated exactly; sparse omission means zero and does not reduce the declared witness arity. The bulky full unrolled JSON is reproducibly generated by build_quadratic.py --steps 328.'}
(R/'accepting_quadratic_receipt.json').write_text(json.dumps(out,indent=2)+'\n');print(json.dumps(out,indent=2))
