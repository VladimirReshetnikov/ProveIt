#!/usr/bin/env python3
"""Regenerate the literal circuit appendix and build the research article."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
import shutil
import subprocess

ROOT = Path(__file__).resolve().parent
REPORT = ROOT / "report"
EXPECTED = "458aa30130504edf7e00b6a4aea294a6dbab110d904032d19ff8803a651ad96f"


def circuit_appendix() -> None:
    data = json.loads((ROOT / "artifacts/fixed_input.json").read_text())
    packet = next(p for p in data["packets"] if p["name"] == "fixed70")
    rows = packet["source"]
    digest = hashlib.sha256(
        json.dumps(rows, separators=(",", ":")).encode()
    ).hexdigest()
    if digest != EXPECTED:
        raise ValueError("The main circuit changed; review it before rebuilding.")

    def register(value):
        return r"\texttt{\detokenize{" + str(value) + "}}"

    lines = [
        "% Generated by build_report.py from artifacts/fixed_input.json.",
        r"\begingroup",
        r"\footnotesize",
        r"\setlength{\tabcolsep}{4pt}",
        r"\begin{longtable}{rll}",
        r"\caption{The complete 70-operation evaluator.}\\",
        r"\toprule",
        r"Row & Output register & Binary expression\\",
        r"\midrule",
        r"\endfirsthead",
        r"\toprule",
        r"Row & Output register & Binary expression\\",
        r"\midrule",
        r"\endhead",
        r"\midrule",
        r"\multicolumn{3}{r}{Continued on the next page}\\",
        r"\endfoot",
        r"\bottomrule",
        r"\endlastfoot",
    ]
    symbols = {"+": r"$+$", "-": r"$-$", "*": r"$\times$"}
    for number, (out, op, left, right) in enumerate(rows, 1):
        expression = register(left) + " " + symbols[op] + " " + register(right)
        lines.append(f"{number} & {register(out)} & {expression}" + r"\\")
    lines += [r"\end{longtable}", r"\endgroup", ""]
    (REPORT / "circuit70.tex").write_text("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--appendix-only", action="store_true")
    args = parser.parse_args()
    circuit_appendix()
    if args.appendix_only:
        print("Generated report/circuit70.tex")
        return
    executable = shutil.which("pdflatex")
    if executable is None:
        raise SystemExit("Install pdfLaTeX, or use --appendix-only.")
    for run in (1, 2):
        result = subprocess.run(
            [executable, "-interaction=nonstopmode", "-halt-on-error",
             "zfc_diophantine.tex"],
            cwd=REPORT, text=True, stdout=subprocess.PIPE,
            stderr=subprocess.STDOUT,
        )
        (REPORT / f"build_run_{run}.log").write_text(result.stdout)
        if result.returncode:
            print(result.stdout[-6000:])
            raise SystemExit(result.returncode)
    print("Built report/zfc_diophantine.pdf")


if __name__ == "__main__":
    main()
