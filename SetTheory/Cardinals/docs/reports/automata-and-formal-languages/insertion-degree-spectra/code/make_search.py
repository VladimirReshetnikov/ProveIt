#!/usr/bin/env python3
"""Generate an SMT-LIB counterexample search; standard library only.

The default search has A subset {a,b}^4, B subset {a,b}^3, no degree 3,
and an output of degree 4.  Optional --fix-example pins the verified model.
Run the generated file with any suitable SMT-LIB solver, e.g.:
    z3 data/search_binary.smt2
The exact verifier does not depend on this search or on an SMT solver.
"""
from __future__ import annotations
import argparse
from collections import defaultdict
from pathlib import Path
from verify import pair_degrees, words


def disjunction(terms):
    terms = list(terms)
    if not terms:
        return 'false'
    if len(terms) == 1:
        return terms[0]
    return '(or ' + ' '.join(terms) + ')'


def generate(m: int, n: int, alphabet: str, gap: int, fix: bool = False) -> str:
    maximum = min(m, n+1)
    if not alphabet or len(set(alphabet)) != len(alphabet):
        raise ValueError('Alphabet must consist of distinct characters.')
    if not (2 <= gap < maximum):
        raise ValueError('Need 2 <= gap < min(m,n+1).')
    U, V = words(alphabet, m), words(alphabet, n)
    records = defaultdict(lambda: defaultdict(list))
    lines = ['; Generated by code/make_search.py', '(set-logic QF_UF)',
             '(set-option :produce-models true)']
    lines += [f'(declare-fun a{i} () Bool) ; {u}' for i, u in enumerate(U)]
    lines += [f'(declare-fun b{j} () Bool) ; {v}' for j, v in enumerate(V)]
    for i, u in enumerate(U):
        for j, v in enumerate(V):
            p = f'p{i}_{j}'
            lines.append(f'(define-fun {p} () Bool (and a{i} b{j}))')
            for w, k in pair_degrees(u, v).items():
                records[w][k].append(p)
    witnesses = []
    for i, w in enumerate(sorted(records)):
        by_cost = records[w]
        lo = disjunction(p for k, ps in by_cost.items() if k < gap for p in ps)
        upto = disjunction(p for k, ps in by_cost.items() if k <= gap for p in ps)
        any_cost = disjunction(p for ps in by_cost.values() for p in ps)
        lines.append(f'; output {w}')
        lines.append(f'(assert (=> {upto} {lo}))')
        h = f'h{i}'
        lines.append(f'(define-fun {h} () Bool (and {any_cost} (not {upto})))')
        witnesses.append(h)
    lines.append('(assert '+disjunction(witnesses)+')')
    if fix:
        if (m, n, alphabet, gap) != (4, 3, 'ab', 3):
            raise ValueError('--fix-example is only defined for default parameters.')
        A = {'aaba', 'aabb', 'abbb', 'bbaa', 'bbba', 'bbbb'}
        B = {'aaa', 'aba', 'bab'}
        for i, u in enumerate(U):
            lines.append(f'(assert (= a{i} {str(u in A).lower()}))')
        for j, v in enumerate(V):
            lines.append(f'(assert (= b{j} {str(v in B).lower()}))')
    lines += ['(check-sat)', '(get-model)']
    return '\n'.join(lines)+'\n'


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--m', type=int, default=4)
    p.add_argument('--n', type=int, default=3)
    p.add_argument('--alphabet', default='ab')
    p.add_argument('--gap', type=int, default=3)
    p.add_argument('--fix-example', action='store_true')
    p.add_argument('--out', type=Path, default=Path(__file__).resolve().parents[1]/'data/search_binary.smt2')
    a = p.parse_args()
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text(generate(a.m, a.n, a.alphabet, a.gap, a.fix_example), encoding='utf-8')
    print(a.out)

if __name__ == '__main__':
    main()
