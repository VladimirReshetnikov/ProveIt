#!/usr/bin/env python3
"""Numerical checks of proved asymptotic formulas (requires mpmath).

Counts, means and variances are computed exactly with integers and rational
numbers; decimal conversions occur last. Nothing here enters any proof.

Run: python code/asymptotics.py [--output DIRECTORY] [--maximum N]

Two independent expressions for the boundary constant are evaluated and
compared: the finite radical product K_d(t) = prod_r g(xi^r/R(t), t) and the
convergent exponential sum exp(sum_m B_{dm}(t)/(m R(t)^{dm})). Both are used
in the article and neither is dropped.
"""
from __future__ import annotations
import argparse
import csv
import json
from fractions import Fraction
from math import comb
from pathlib import Path
import mpmath as mp

BLOCK_SIZES = (1, 2, 3, 4, 5, 8)


def totals(d: int, n: int, t: int = 1) -> list[int]:
    """Exact H_{n,d}(t) evaluations from the exponential recurrence."""
    if d < 1 or n < 0 or t < 1:
        raise ValueError('Require d,t >= 1 and n >= 0.')
    if t == 1:
        b = [comb(2*d*m, d*m) for m in range(n+1)]
    else:
        b = [sum(comb(d*m, j)**2*t**j for j in range(d*m+1))
             for m in range(n+1)]
    a = [1]
    for k in range(1, n+1):
        value = sum(b[m]*a[k-m] for m in range(1, k+1))
        if value % k:
            raise ArithmeticError('Nonintegral recurrence')
        a.append(value//k)
    return a


def moments(d: int, n: int) -> tuple[list[int], list[int], list[int]]:
    """Exact totals and the first two support moments at t=1."""
    b = [comb(2*d*j, d*j) for j in range(n+1)]
    first = [0] + [(d*j)*b[j]//2 for j in range(1, n+1)]
    second = [0] + [(d*j)*(d*j-1)**2*b[j]//(2*(2*d*j-1))
                    for j in range(1, n+1)]
    h, hd, he = [1], [0], [0]
    for k in range(1, n+1):
        x = sum(b[j]*h[k-j] for j in range(1, k+1))
        y = sum(first[j]*h[k-j]+b[j]*hd[k-j] for j in range(1, k+1))
        z = sum(second[j]*h[k-j]+2*first[j]*hd[k-j]+b[j]*he[k-j]
                for j in range(1, k+1))
        if x % k or y % k or z % k:
            raise ArithmeticError('Nonintegral moment')
        h.append(x//k)
        hd.append(y//k)
        he.append(z//k)
    return h, hd, he


def constants(d: int, t=1):
    """Radical product K_d(t), leading constant, growth factor and kappa_d."""
    t = mp.mpf(t)
    root = mp.sqrt(t)
    R = (1+root)**2
    Rminus = (1-root)**2
    K = mp.mpc(1)
    for r in range(d):
        xi = mp.exp(2j*mp.pi*r/d)
        x = xi/R
        discriminant_root = (mp.mpc(0) if r == 0 else
                             mp.sqrt(1-R*x)*mp.sqrt(1-Rminus*x))
        K *= 2/(1-(1+t)*x+discriminant_root)
    if abs(K.imag) > mp.mpf('1e-65'):
        raise ArithmeticError('Unexpected imaginary residual in K_d')
    K = K.real
    C = K*(1+root)/(2*mp.sqrt(mp.pi*d)*mp.sqrt(root))
    kappa = mp.mpf(1)/16 + mp.mpf(d)/8
    for r in range(d):
        xi = mp.exp(2j*mp.pi*r/d)
        kappa -= (mp.mpc(0) if r == 0 else mp.sqrt(1-xi))/8
    if abs(mp.im(kappa)) > mp.mpf('1e-65'):
        raise ArithmeticError('Unexpected imaginary residual in kappa_d')
    return K, C, R**d, mp.re(kappa)


def boundary_constant_exponential(d: int, terms: int = 5000) -> mp.mpf:
    """The same constant from exp(sum_m B_{dm}(1)/(m 4^{dm})).

    The summands are B_{dm}(1)/(m 4^{dm}) = binom(2dm,dm)/(m 4^{dm}), which
    decay only like m^{-3/2}. The central binomial ratios are generated by the
    exact recursion r_{N+1} = r_N (2N+1)/(2N+2), and the truncated tail is
    replaced by its Euler-Maclaurin estimate, which is accurate to about
    1e-7 at the default truncation. This is a slowly convergent but wholly
    independent route to the constant computed as a radical product above.
    """
    ratio = mp.mpf(1)
    n = 0
    total = mp.mpf(0)
    for m in range(1, terms+1):
        for _ in range(d):
            ratio *= mp.mpf(2*n+1)/(2*n+2)
            n += 1
        total += ratio/m
    tail = (2/mp.sqrt(terms)-mp.mpf(1)/(2*mp.power(terms, mp.mpf('1.5'))))
    total += tail/mp.sqrt(mp.pi*d)
    return mp.exp(total)


def main(output: Path, maximum: int) -> None:
    mp.mp.dps = 80
    output.mkdir(parents=True, exist_ok=True)
    rows = []
    const_rows = []
    ratio_rows = []
    constant_rows = []
    samples = sorted({n for n in (25, 50, 100, 200, 400, maximum)
                      if n <= maximum})
    for d in BLOCK_SIZES:
        K, C, growth, kappa = constants(d)
        K_series = boundary_constant_exponential(d)
        if abs(K-K_series) > mp.mpf('1e-5'):
            raise ArithmeticError('The two boundary-constant forms disagree')
        const_rows.append(dict(d=d, K=mp.nstr(K, 30),
                               K_from_exponential_sum=mp.nstr(K_series, 30),
                               leading_constant=mp.nstr(C, 30),
                               growth=int(growth), kappa=mp.nstr(kappa, 30)))
        constant_rows.append((d, mp.nstr(K, 40)))
        h, hd, he = moments(d, maximum)
        for n in samples:
            approximation = C * growth**n / mp.mpf(n)**mp.mpf('1.5')
            variance = Fraction(d*sum(comb(2*d*m-2, d*m-1)*h[n-m]
                                      for m in range(1, n+1)), 2*h[n])
            v = mp.mpf(variance.numerator)/variance.denominator
            rows.append([d, 1, n, mp.nstr(mp.mpf(h[n])/approximation, 24),
                         mp.nstr(v-mp.mpf(d*n)/8, 24), mp.nstr(kappa, 24)])
            # Independent moment recursion: exact mean and variance.
            mean = Fraction(hd[n], h[n])
            if mean != Fraction(d*n, 2):
                raise ArithmeticError('Mean identity failed')
            moment_variance = Fraction(he[n]+hd[n], h[n])-mean**2
            if moment_variance != variance:
                raise ArithmeticError('Two exact variance routes disagree')
            ratio = (mp.mpf(h[n])/mp.power(4, d*n)*mp.sqrt(mp.pi*d)
                     * mp.power(n, mp.mpf('1.5'))/K)
            variance_ratio = (mp.mpf(moment_variance.numerator)
                              / moment_variance.denominator*8/(d*n))
            ratio_rows.append((d, n, mp.nstr(ratio, 18),
                               mp.nstr(variance_ratio, 18)))
    # Positive weights away from t=1, with counts still exact integers.
    for d in (1, 2, 3):
        upper = min(160, maximum)
        a = totals(d, upper, t=4)
        K, C, growth, _ = constants(d, 4)
        for n in sorted({n for n in (40, 80, 160, upper) if n <= upper}):
            approximation = C * growth**n/mp.mpf(n)**mp.mpf('1.5')
            rows.append([d, 4, n, mp.nstr(mp.mpf(a[n])/approximation, 24),
                         '', ''])
    with (output/'asymptotics.csv').open('w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['d', 't', 'n', 'exact_over_leading_asymptotic',
                    'exact_variance_minus_dn_over_8',
                    'predicted_variance_constant'])
        w.writerows(rows)
    with (output/'asymptotic_constants.csv').open('w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['d', 'K_d_at_t_1'])
        w.writerows(constant_rows)
    with (output/'asymptotic_checks.csv').open('w', newline='') as f:
        w = csv.writer(f)
        w.writerow(['d', 'n', 'total_over_leading_asymptotic',
                    'variance_over_dn_div_8'])
        w.writerows(ratio_rows)
    (output/'constants.json').write_text(json.dumps(const_rows, indent=2)+'\n')
    print(json.dumps({'status': 'COMPLETED',
                      'mpmath_decimal_precision': mp.mp.dps,
                      'observations': len(rows)+len(ratio_rows),
                      'maximum_n': maximum,
                      'note': 'Numerical corroboration, not interval '
                              'certification.',
                      'constants': const_rows}, indent=2))


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output', '--out', dest='output', type=Path,
                        default=Path(__file__).resolve().parents[1]/'results')
    parser.add_argument('--maximum', type=int, default=400)
    args = parser.parse_args()
    if args.maximum < 1:
        parser.error('--maximum must be positive')
    main(args.output, args.maximum)
