"""Translate public Metamath proof tables to explicit Lean proof terms.

The generator is untrusted. Lean checks all generated terms, using only the
abstract input axiom and modus ponens. It never invokes Boolean completeness.
The input files are the public-domain impsingle derivations by Larry Lesyna
and Jeffrey P. Machado in the Metamath Proof Explorer, based on Lukasiewicz.
"""
from __future__ import annotations
from pathlib import Path
import html
import json
import re

ROOT = Path(__file__).resolve().parent
LABELS = [
    'impsingle-step4', 'impsingle-step8', 'impsingle-ax1',
    'impsingle-step15', 'impsingle-step18', 'impsingle-step19',
    'impsingle-step20', 'impsingle-step21', 'impsingle-step22',
    'impsingle-step25', 'impsingle-imim1', 'impsingle-peirce',
    'tarski-bernays-ax2',
]
ALIASES = {'ax-1': 'impsingle-ax1', 'imim1': 'impsingle-imim1',
           'peirce': 'impsingle-peirce'}

def plain(s):
    return html.unescape(re.sub(r'<[^>]*>', '', s))

def parse_formula(s):
    s = ''.join(plain(s).split()).split('⊢')[-1]
    def parse(i):
        if s[i] != '(':
            assert s[i] not in '→)', (s, i)
            return s[i], i + 1
        a, i = parse(i + 1)
        assert s[i] == '→', (s, i)
        b, i = parse(i + 1)
        assert s[i] == ')', (s, i)
        return (a, b), i + 1
    f, end = parse(0)
    assert end == len(s), (s, end)
    return f

def variables(f):
    if isinstance(f, str):
        return [f]
    return list(dict.fromkeys(variables(f[0]) + variables(f[1])))

def subst(f, env):
    if isinstance(f, str):
        return env.get(f, f)
    return subst(f[0], env), subst(f[1], env)

def match(pattern, target, env=None):
    if env is None:
        env = {}
    if isinstance(pattern, str):
        if pattern in env:
            assert env[pattern] == target, (pattern, env[pattern], target)
        else:
            env[pattern] = target
    else:
        assert isinstance(target, tuple), (pattern, target)
        match(pattern[0], target[0], env)
        match(pattern[1], target[1], env)
    return env

def lean(f):
    if isinstance(f, str):
        return f
    return '(imp ' + lean(f[0]) + ' ' + lean(f[1]) + ')'

def norm_name(label):
    return label.replace('-', '_')

def read_table(label):
    # The canonical extracted formal steps make regeneration fully offline.
    # HTML is only needed for the initial extraction; Lean checks both paths.
    saved = ROOT / 'metamath-proof-steps.json'
    if saved.exists():
        records = json.loads(saved.read_text())
        record = next(r for r in records if r['label'] == label)
        def tree(f):
            return f if isinstance(f, str) else (tree(f[0]), tree(f[1]))
        return tree(record['conclusion']), [
            {**r, 'formula':tree(r['formula'])} for r in record['steps']]
    source = (ROOT / 'metamath' / (label + '.html')).read_text()
    assertion = re.search(
        r'<TABLE\b[^>]*SUMMARY="Assertion"[^>]*>(.*?)</TABLE>',
        source, re.I | re.S).group(1)
    assertion_rows = re.findall(r'<TR\b[^>]*>(.*?)</TR>', assertion, re.I | re.S)
    assertion_cells = re.findall(r'<TD\b[^>]*>(.*?)</TD>', assertion_rows[-1], re.I | re.S)
    target = parse_formula(assertion_cells[-1])
    proof = re.search(
        r'<TABLE\b[^>]*SUMMARY="Proof of theorem"[^>]*>(.*?)</TABLE>',
        source, re.I | re.S).group(1)
    rows = []
    for raw in re.findall(r'<TR\b[^>]*>(.*?)</TR>', proof, re.I | re.S):
        cells = re.findall(r'<TD\b[^>]*>(.*?)</TD>', raw, re.I | re.S)
        if not cells:
            continue
        assert len(cells) == 4
        n = int(plain(cells[0]))
        hyp = list(map(int, re.findall(r'HREF="#(\d+)"', cells[1], re.I)))
        ref = re.search(r'HREF="([^"]+)\.html"', cells[2], re.I).group(1)
        expression = cells[3][cells[3].find('<SPAN CLASS=math>'):]
        rows.append({'n': n, 'hyp': hyp, 'ref': ref,
                     'formula': parse_formula(expression)})
    assert rows[-1]['formula'] == target
    assert [r['n'] for r in rows] == list(range(1, len(rows) + 1))
    return target, rows

def main():
    ax = parse_formula('(((p→q)→r)→((r→p)→(s→p)))')
    table = {'impsingle': (ax, [])}
    records = []
    lines = [
        '/-!',
        '# Explicit reconstruction of the Lukasiewicz implicational basis',
        '',
        'Source: the public-domain Metamath `impsingle-*` proof tables by',
        'Larry Lesyna and Jeffrey P. Machado (2023), based on Lukasiewicz',
        '(1948), and their `tarski-bernays-ax2` derivation.',
        'Generated by `generate_lukasiewicz.py`; every step is an explicit',
        'instance of the single axiom, a previously proved lemma, or MP.',
        'No semantic completeness or additional logical axiom is used.',
        '',
        'The interface is generic: `imp` need not be injective and `T` is an',
        'arbitrary predicate. In particular this applies to numerical codes.',
        '-/',
        '',
        'namespace SetTheory.BusyBeaver.ZFC.Lukasiewicz',
        '',
        'universe u',
        'variable {α : Type u} (imp : α → α → α) (T : α → Prop)',
        'variable (mp : ∀ {a b : α}, T (imp a b) → T a → T b)',
        'variable (axL : ∀ p q r s : α,',
        '  T (imp (imp (imp p q) r) (imp (imp r p) (imp s p))))',
        'include mp axL',
        '',
    ]
    for label in LABELS:
        target, rows = read_table(label)
        vars_ = variables(target)
        mapping = {v: 'x' + str(i) for i, v in enumerate(vars_)}
        for row in rows:
            for v in variables(row['formula']):
                mapping.setdefault(v, 'x0')
        target = subst(target, mapping)
        rows = [{**r, 'formula': subst(r['formula'], mapping)} for r in rows]
        params = variables(target)
        lines += [f'/-- https://us.metamath.org/mpeuni/{label}.html -/',
                  f'theorem {norm_name(label)} ({" ".join(params)} : α) :',
                  f'    T {lean(target)} := by']
        previous = {}
        for row in rows:
            n, f = row['n'], row['formula']
            ref = ALIASES.get(row['ref'], row['ref'])
            if ref == 'ax-mp':
                assert len(row['hyp']) == 2
                minor, major = row['hyp']
                assert previous[major] == (previous[minor], f), (label, row)
                term = f'mp h{major} h{minor}'
            else:
                assert not row['hyp']
                pattern = table[ref][0]
                env = match(pattern, f)
                args = ' '.join(lean(env[v]) for v in variables(pattern))
                if ref == 'impsingle':
                    term = 'axL ' + args
                else:
                    term = norm_name(ref) + ' imp T mp axL ' + args
            lines += [f'  have h{n} : T {lean(f)} :=', f'    {term}']
            previous[n] = f
        lines += [f'  exact h{rows[-1]["n"]}', '']
        table[label] = (target, rows)
        records.append({'label':label,'url':'https://us.metamath.org/mpeuni/'+label+'.html',
                        'conclusion':target,'steps':rows})
    lines += ['#print axioms impsingle_ax1', '#print axioms impsingle_imim1',
              '#print axioms impsingle_peirce', '#print axioms tarski_bernays_ax2',
              '', 'end SetTheory.BusyBeaver.ZFC.Lukasiewicz', '']
    output = ROOT / 'lean' / 'BusyBeaver' / 'ZFC' / 'Lukasiewicz.lean'
    output.write_text('\n'.join(lines))
    (ROOT / 'metamath-proof-steps.json').write_text(
        json.dumps(records, ensure_ascii=False, indent=2) + '\n')
    print('Generated', output)
    print('Theorems:', len(records), 'proof lines:',sum(len(r['steps']) for r in records))

if __name__ == '__main__':
    main()
