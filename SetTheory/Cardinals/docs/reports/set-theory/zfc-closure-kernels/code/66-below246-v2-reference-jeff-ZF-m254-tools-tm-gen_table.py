"""Generate coq/Table254.v (the literal transition table of zfc_254.tm) and check the file hash.
Usage: python -I gen_table.py ../../inputs/zfc_254.tm ../coq/Table254.v"""
import sys, hashlib
src, out = sys.argv[1], sys.argv[2]
data = open(src, 'rb').read()
print('sha256', hashlib.sha256(data).hexdigest())
rows = {}
for line in data.decode().splitlines():
    line = line.strip()
    if not line or line.startswith('#'): continue
    s, r, w, d, n = line.split()
    rows[(int(s), int(r))] = (int(w), d, int(n))
N = 254
assert sorted(rows) == [(q, b) for q in range(N) for b in (0, 1)]
assert all(0 <= v[2] <= N for v in rows.values())
B = lambda x: 'true' if x else 'false'
lines = ['(** * Table254: the literal transition table of zfc_254.tm (generated by tools/gen_table.py).',
         '    Row [q] is [(w0, d0, n0, w1, d1, n1)]: on reading 0 write [w0], move [d0], go to [n0]; same for 1.',
         '    State 254 (halt) has no row.  sha256 of the source file: %s *)' % hashlib.sha256(data).hexdigest(),
         '', 'From BusyCoq Require Import TM.', 'From Coq Require Import Lists.List.', 'Import ListNotations.', '',
         'Definition table254 : list (bool * dir * nat * bool * dir * nat) := [']
for q in range(N):
    a, b = rows[(q, 0)], rows[(q, 1)]
    lines.append('  (%s, %s, %d, %s, %s, %d)%s  (* %d *)' % (B(a[0]), a[1], a[2], B(b[0]), b[1], b[2], ';' if q < N - 1 else '', q))
lines.append('].')
open(out, 'w', newline='\n').write('\n'.join(lines) + '\n')
print('wrote', out)
