#!/usr/bin/env python3
"""Compare exact affine duration records for boundary239 and combined238.

Both records must have been generated by the complete universal checker.
This is an algebraic comparison of their outputs, not a replacement for
either underlying proof. The baseline file is supplied explicitly.
"""
from pathlib import Path
import argparse
import hashlib
import json
import sys

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--baseline-cases', type=Path, required=True)
    ap.add_argument('--candidate-cases', type=Path,
                    default=Path(__file__).resolve().parent / 'universal_runtime_cases.json')
    ap.add_argument('--output', type=Path,
                    default=Path(__file__).resolve().parent / 'duration_comparison.json')
    args = ap.parse_args()
    if not __debug__ or sys.flags.optimize:
        raise RuntimeError('Assertions must be enabled.')
    old, new = [json.loads(path.read_text())
                for path in (args.baseline_cases, args.candidate_cases)]
    assert len(old) == len(new) == 8386
    signatures = {}
    for a, b in zip(old, new):
        assert (a['site_index'], a['positive']) == (b['site_index'], b['positive'])
        assert len(a['duration']) == len(b['duration']) == 13
        delta = tuple(v - u for u, v in zip(a['duration'], b['duration']))
        assert all(x >= 0 for x in delta)
        assert all(5 * u - v >= 0 for u, v in zip(a['duration'], b['duration']))
        assert not any(delta[1:]) and delta[0] in (0, 8, 12)
        signatures[delta] = signatures.get(delta, 0) + 1
    result = {
        'status': 'AFFINE_DURATION_COMPARISON_PASS', 'cases': 8386,
        'changed_cases': sum(n for d, n in signatures.items() if any(d)),
        'duration_difference': 'Exactly 0, 8, or 12 additional literal TM steps per instruction, independent of all natural parameters.',
        'difference_signatures': [{'added_duration': list(d), 'cases': n}
                                  for d, n in sorted(signatures.items())],
        'baseline_cases_sha256': hashlib.sha256(args.baseline_cases.read_bytes()).hexdigest(),
        'candidate_cases_sha256': hashlib.sha256(args.candidate_cases.read_bytes()).hexdigest(),
        'scope': 'Algebraic comparison of complete symbolic duration records; underlying universal proofs are separate dependencies.',
    }
    args.output.write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(result, indent=2))

if __name__ == '__main__':
    main()
