"""Generate coq/Prog254.v: the program p254 (RM.v [prog]) of zfc_254 = the decoder tree of paths.json.
Usage: python -I gen_prog.py ../../inputs/paths.json ../coq/Prog254.v

Internal nodes are the proper prefixes of the leaf paths (the constant '110' file prefix dropped),
numbered in DFS preorder (root = 0, car before cdr).  Car edge = bit 0, cdr edge = bit 1.
Registers are numbered in source.py declaration order.  Also emits the height / break / continue
tables used to check RMEquiv.wf by computation."""
import sys, json, hashlib
REG = dict(nextproof=0, topwff=1, wffstack=2, axiomcode=3, param1=4, param2=5, scratch1=6, scratch2=7, prooflist=8)
data = open(sys.argv[1], 'rb').read()
paths = json.loads(data)
leaf = {}
for p, op in paths:
    assert p.startswith('110')
    q = p[3:]; assert q not in leaf; leaf[q] = op
order = []
def dfs(pre):
    assert pre not in leaf
    order.append(pre)
    for b in '01':
        if pre + b not in leaf: dfs(pre + b)
sys.setrecursionlimit(10000)
dfs('')
idx = {p: i for i, p in enumerate(order)}
assert len(order) + 1 == len(leaf)   # complete binary tree
def edge(q):
    if q in idx: return ('N', idx[q])
    op = leaf[q]
    if op == 'halt': return ('H',)
    if op.startswith('_break.'): return ('B', int(op.split('.')[1]))
    if op.startswith('_continue.'): return ('C', int(op.split('.')[1]))
    _, r, kind = op.split('.')
    return ('I' if kind == 'inc' else 'D', REG[r])
nodes = [(edge(p + '0'), edge(p + '1')) for p in order]
for a, b in nodes:
    for e in (a, b):
        if e[0] in 'BC': assert e[1] >= 1
# tables (RMEquiv: hE / bE / cE), bottom-up
n = len(nodes); H = [0] * n; Bt = [0] * n; Ct = [0] * n
def hE(e): return H[e[1]] if e[0] == 'N' else 0
def bE(e): return Bt[e[1]] if e[0] == 'N' else (1 if e[0] == 'D' else (e[1] if e[0] == 'B' else 0))
def cE(e): return Ct[e[1]] if e[0] == 'N' else (e[1] if e[0] == 'C' else 0)
for i in reversed(range(n)):            # preorder: children have larger indices
    a, b = nodes[i]
    H[i] = 1 + max(hE(a), hE(b))
    Bt[i] = max(bE(a) - 1, bE(b), 0)
    Ct[i] = max(cE(a), cE(b) - 1, 0)
assert Bt[0] == 0 and Ct[0] == 0, (Bt[0], Ct[0])
def ce(e):
    return {'N': 'CN %d', 'I': 'CI %d', 'D': 'CD %d', 'B': 'CB %d', 'C': 'CC %d'}[e[0]] % e[1] if e[0] != 'H' else 'CH'
def tab(t): return '[' + '; '.join(map(str, t)) + ']'
L = []
L.append('''(** * Prog254: the program run by zfc_254.tm, as an RM.v [prog] (generated by tools/gen_prog.py).

    [p254] is the decoder tree of inputs/paths.json (sha256 %s): its 6460 leaves are the
    instruction sites, with the constant prefix '110' of the file's words dropped.  Node [n] is the
    [n]-th internal node in DFS preorder (root 0, car = bit 0 before cdr = bit 1).  Registers are
    numbered in source.py declaration order:
      nextproof 0, topwff 1, wffstack 2, axiomcode 3, param1 4, param2 5, scratch1 6, scratch2 7, prooflist 8
    ([param3] of source.py is axiomcode).  [R0] is the register vector reached by the boot:
    nextproof = 2, all others 0, with the IP at the root.

    Node indices are stored in binary ([N]) and converted on lookup, to keep the term small. *)

From Coq Require Import Lists.List Bool.Bool Arith.Arith NArith.
From M254 Require Import RM RMEquiv.
Import ListNotations.

Inductive cedge : Type := CN (m : N) | CI (r : nat) | CD (r : nat) | CB (k : nat) | CC (k : nat) | CH.
Arguments CN m%%N_scope.

Definition cv (e : cedge) : edge :=
  match e with
  | CN m => ENode (N.to_nat m)
  | CI r => EInc r
  | CD r => EDecnz r
  | CB k => EBreak k
  | CC k => EContinue k
  | CH => EHalt
  end.
''' % hashlib.sha256(data).hexdigest())
L.append('Definition p254_tab : list (cedge * cedge) := [\n  ' + ';\n  '.join('(%s, %s)' % (ce(a), ce(b)) for a, b in nodes) + '\n].\n')
L.append('''Definition p254 : prog := {|
  nodes := fun n => let '(a, b) := nth n p254_tab (CH, CH) in (cv a, cv b);
  root := 0;
  nnodes := %d
|}.

Definition R0 : regs := upd regs0 0 2.

(** ** Well-formedness, by computation with the tables of gen_prog.py *)
Definition p254_H : list nat := %s.
Definition p254_B : list nat := %s.
Definition p254_C : list nat := %s.

Lemma p254_wf : wf p254.
Proof. apply (wf_check_with_sound p254 p254_H p254_B p254_C). vm_compute. reflexivity. Qed.
''' % (n, tab(H), tab(Bt), tab(Ct)))
open(sys.argv[2], 'w', newline='\n').write('\n'.join(L))
print('nodes', n, 'leaves', len(leaf), 'max height', H[0])
