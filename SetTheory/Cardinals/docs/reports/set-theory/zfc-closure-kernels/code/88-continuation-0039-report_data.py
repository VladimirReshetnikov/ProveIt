#!/usr/bin/env python3
"""Render exact table-derived LaTeX data, without numerical estimation."""
from pathlib import Path
import json,hashlib
from canonicalize import read
ROOT=Path(__file__).resolve().parents[1]

def metrics(path):
 d=json.loads(path.read_text());E=d['entries'];depth=zero=0;leaves=0
 def visit(n,p):
  nonlocal depth,zero,leaves
  e=E[str(n)]
  if e[0]=='N':visit(e[1],p+'0');visit(e[2],p+'1')
  else:leaves+=1;depth=max(depth,len(p));zero=max(zero,max(map(len,p.split('1'))))
 visit(d['root'],'');assert leaves==6460
 return sum(e[0]=='N' for e in E.values()),depth,zero

rows=[('Existing prefix246',203,34,246,'36')]
for label,name,fails in [('A: exact reassociation','reassociated246',25),('B: commuted and reassociated','commuted_reassociated246',21),('C: normalized arithmetic entries','normalized246',16)]:
 pairs,depth,zeros=metrics(ROOT/'machines'/(name+'.graph.json'))
 T,Q=read(ROOT/'machines'/(name+'_old.tm'))
 cert=json.loads((ROOT/'results'/(name+'_runtime.json')).read_text())
 assert cert['status']=='PASS' and cert['universally_verified_cases']==8391
 rows.append((label,pairs,depth,len(Q),str(fails)))
lines=[r'\begin{center}',r'\small',r'\begin{tabularx}{\linewidth}{@{}Xrrrr@{}}',r'\toprule',r'Control & \shortstack{Source\\pairs} & Depth & States & \shortstack{Short-scanner\\rejections}\\',r'\midrule']
for label,pairs,depth,states,fails in rows:lines.append(f'{label} & {pairs} & {depth} & {states} & {fails}'+r'\\')
lines += [r'\bottomrule',r'\end{tabularx}',r'\end{center}',r'All three new controls A--C pass the complete 8,391-case universal runtime audit and an independent full-tape bootstrap at 410,735 transitions. The last column concerns an explicitly rejected 245-state scanner edit, not the certified table. The directly commuted seed is also included and checked.']
(ROOT/'results/control-summary.tex').write_text('\n'.join(lines)+'\n')
(ROOT/'results/summary-macros.tex').write_text('% Exact report data are generated by code/report_data.py.\n')
T,Q=read(ROOT/'machines/normalized246.tm');assert Q==set(range(246))
lines=[]
for page in range(2):
 if page:lines.append(r'\clearpage')
 lines += [r'\begin{center}',r'\small',r'\setlength{\tabcolsep}{6pt}',r'\renewcommand{\arraystretch}{1.13}',r'\begin{tabular}{@{}rrr@{\qquad}rrr@{\qquad}rrr@{}}',r'\toprule',r'$q$ & Read 0 & Read 1 & $q$ & Read 0 & Read 1 & $q$ & Read 0 & Read 1\\',r'\midrule']
 for i in range(41):
  fields=[]
  for panel in range(3):
   q=page*123+panel*41+i;fields.append(str(q))
   for b in (0,1):
    w,d,t=T[q,b];fields.append(r'\texttt{'+f'{w}{d}{t}'+r'}')
  lines.append(' & '.join(fields)+r'\\')
 lines += [r'\bottomrule',r'\end{tabular}',r'\end{center}']
lines += [r'\small Canonical SHA-256: \texttt{'+hashlib.sha256((ROOT/'machines/normalized246.tm').read_bytes()).hexdigest()+r'}.']
(ROOT/'machines/principal-table.tex').write_text('\n'.join(lines)+'\n')
print('Rendered',len(Q),'states in two table panels/pages; control counts are exact.')
