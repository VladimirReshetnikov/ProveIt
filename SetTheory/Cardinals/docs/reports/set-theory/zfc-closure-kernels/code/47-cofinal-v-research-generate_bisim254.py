#!/usr/bin/env python3
"""Generate BusyBeaver/ZFC/Bisim254.lean: Prog254 and the 219-node DAG halt alike.

Builds the segment bisimulation of `bisim254.py` (untrusted) and writes it as
a balanced certificate tree for `RMBisim.check_halts_iff`. The tree is split
into chunks, each re-checked by the kernel in its own theorem, so no single
kernel evaluation has to hold the whole computation.

By default the literal program uses the shared, separately checked
`ActualTree254`, and the DAG's unfolding is written out and identified by
kernel definitional equality. `--plain` reproduces the older numerical-lookup
version; `--literal-trees` writes both trees out directly.

Usage (from the repository root):
    python Computability/BusyBeaver/Research/ZFC/generate_bisim254.py [--plain | --literal-trees] [--check] [--out FILE]
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import bisim254  # noqa: E402

REPO = Path(__file__).resolve().parents[4]
TARGET = REPO / "Computability/BusyBeaver/Lean/BusyBeaver/ZFC/Bisim254.lean"
CHUNK_DEPTH = 4  # 2^4 = 16 chunks


def code(P) -> int:
    return int("1" + "".join("1" if b else "0" for b in P), 2)


def edge_lean(e) -> str:
    kind, a = e
    return ".halt" if kind == "halt" else f"(.{kind} {a})"


def literal_tree(rows) -> str:
    """The full unfolding of a program from node 0, as a `Tree` term."""
    sys.setrecursionlimit(100000)

    def go(n):
        return f"(.node {child(rows[n][0])} {child(rows[n][1])})"

    def child(e):
        return go(e[1]) if e[0] == "node" else f"(.leaf {edge_lean(e)})"

    return go(0)


def tree(entries, lo, hi) -> str:
    if hi - lo == 1:
        a, b, j, k = entries[lo]
        return f".leaf ({code(a)}, {code(b)}, {j}, {k})"
    mid = (lo + hi) // 2
    return f".branch {mid - lo} ({tree(entries, lo, mid)})\n  ({tree(entries, mid, hi)})"


HEADER = """import BusyBeaver.ZFC.RMBisim
import BusyBeaver.ZFC.Prog254
import BusyBeaver.ZFC.RMEquiv254

/-!
The decoder tree `Prog254` and the 219-node DAG halt on the same register files.

The literal machine table decodes the 6459-row tree `Prog254.program` (Codex
lane, attributed port of the public `Prog254.v`); L1–L3 are about the 219-node
DAG `Dag254.dag254`, read as the path program `RMEquiv254.pathDag254`. Their
unfoldings agree except for local re-associations and reorderings made by the
two compilations, so they are related by a segment bisimulation
(`RMBisim`): {n} pairs of related register-test sites, generated by
`Computability/BusyBeaver/Research/ZFC/generate_bisim254.py` (untrusted) and
re-checked here by the kernel in {chunks} chunks. Upstream relates the same two
programs by `Bisim254.v` with its own certificate `Cert254.v`; this
certificate was regenerated independently.

Pointers are coded as numbers (`RMBisim.decode`: binary `1` followed by the
bits). Each entry is `(P₁, P₂, j, k)`: test sites in `Prog254` and in the DAG,
and the entries reached after a nonzero / zero test. Entry 0 is the start pair.
-/

namespace SetTheory.BusyBeaver.ZFC.Bisim254

open RegisterPath RMBisim
"""

TREES_PLAIN = """/-- The decoder tree of the literal program. -/
def t1 : Tree := ptree Prog254.program

/-- The decoder tree of the 219-node DAG. -/
def t2 : Tree := ptree RMEquiv254.pathDag254
"""

TREES_LITERAL = """/-- The decoder tree of the literal program, written out. -/
def t1 : Tree :=
  {t1}

/-- The decoder tree of the 219-node DAG, written out (its full unfolding). -/
def t2 : Tree :=
  {t2}

/-- The written-out trees are the decoder trees (one kernel evaluation each). -/
theorem t1_eq : ptree Prog254.program = t1 := by rfl

theorem t2_eq : ptree RMEquiv254.pathDag254 = t2 := by rfl
"""

FOOTER = """theorem all_ok : allC F cert = true := by
  unfold cert
  simp only [allC, {oks}, Bool.and_self]

theorem start_ok' :
    branchOk (ptree Prog254.program) (ptree RMEquiv254.pathDag254) cert [] [] 0 = true := by
  {transfer} start_ok

theorem all_ok' :
    allC (entryOk (ptree Prog254.program) (ptree RMEquiv254.pathDag254) cert) cert = true := by
  {transfer} all_ok

/-- **The decoder tree and the DAG halt alike**, from every register file. -/
theorem prog254_halts_iff (R : Registers) :
    Halts Prog254.program ⟨[], R⟩ ↔ Halts RMEquiv254.pathDag254 ⟨[], R⟩ :=
  check_halts_iff (T := cert) start_ok' all_ok' R

/-- **L4 + L3 + L2 + L1.** The literal 6459-row register program, from the public
initial configuration (`nextproof = 2`, empty pointer), halts iff the falsity
code is derivable in the code calculus. -/
theorem literal_halts_iff : Halts Prog254.program Prog254.initial ↔ Code254.C254 Code254.F :=
  (prog254_halts_iff _).trans RMEquiv254.path_halts_iff

end SetTheory.BusyBeaver.ZFC.Bisim254
"""


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    modes = ap.add_mutually_exclusive_group()
    modes.add_argument("--literal-trees", action="store_true",
                       help="write both decoder trees out directly")
    modes.add_argument("--plain", action="store_true",
                       help="reproduce the original numerical-lookup version")
    ap.add_argument("--check", action="store_true", help="require byte-exact existing output")
    ap.add_argument("--out", type=Path, default=TARGET)
    args = ap.parse_args()
    if not __debug__:
        ap.error("Assertions must remain enabled")
    shared = not args.plain and not args.literal_trees
    literal = not args.plain

    p254, dag = bisim254.Prog(bisim254.load_prog254()), bisim254.Prog(bisim254.load_dag254())
    entries = bisim254.build(p254, dag)
    n = len(entries)

    chunks: list[tuple[int, int]] = []

    def split(lo, hi, depth):
        if depth == 0 or hi - lo == 1:
            chunks.append((lo, hi))
            return f"c{len(chunks) - 1}"
        mid = (lo + hi) // 2
        return f".branch {mid - lo} ({split(lo, mid, depth - 1)}) ({split(mid, hi, depth - 1)})"

    top = split(0, n, CHUNK_DEPTH)

    out = [HEADER.replace("{n}", str(n)).replace("{chunks}", str(len(chunks)))]
    if literal:
        out.append(TREES_LITERAL.replace("{t1}", literal_tree(p254.rows))
                   .replace("{t2}", literal_tree(dag.rows)))
        transfer = "rw [t1_eq, t2_eq]; exact"
    else:
        out.append(TREES_PLAIN)
        transfer = "exact"
    for i, (lo, hi) in enumerate(chunks):
        out.append(f"/-- Entries {lo}–{hi - 1}. -/\ndef c{i} : CTree :=\n  {tree(entries, lo, hi)}\n")
    out.append(f"/-- The certificate: {n} entries. -/\ndef cert : CTree :=\n  {top}\n")
    out.append("/-- The per-entry check. -/\ndef F : Entry → Bool := entryOk t1 t2 cert\n")
    out.append("theorem start_ok : branchOk t1 t2 cert [] [] 0 = true := by decide +kernel\n")
    for i in range(len(chunks)):
        out.append(f"theorem ok{i} : allC F c{i} = true := by decide +kernel\n")
    oks = ", ".join(f"ok{i}" for i in range(len(chunks)))
    footer = FOOTER.replace("{oks}", oks).replace("{transfer}", transfer)
    if not literal:
        i = footer.index("theorem start_ok'")
        j = footer.index("/-- **The decoder tree")
        footer = footer[:i] + footer[j:]
        footer = footer.replace("start_ok' all_ok' R", "start_ok all_ok R")
    out.append(footer)
    source = "\n".join(out)
    if shared:
        # Keep the checked module byte-exact while factoring the literal tree
        # into the independently reusable ActualTree254 data/proof module.
        start = source.index("/-- The decoder tree of the literal program, written out. -/")
        stop = source.index("/-- The decoder tree of the 219-node DAG, written out", start)
        source = source[:start] + (
            "/-- Reuse the independently checked literal6459-row decoder identity. -/\n"
            "def t1 : Tree := ActualTree254.tree\n\n") + source[stop:]
        source = source.replace("import BusyBeaver.ZFC.RMBisim",
            "import BusyBeaver.ZFC.ActualTree254\nimport BusyBeaver.ZFC.RMBisim", 1)
        source = source.replace("open RegisterPath RMBisim",
            "open RegisterPath RMBisim\nset_option maxRecDepth 65536\nset_option maxHeartbeats 8000000", 1)
        source = source.replace("theorem t1_eq : ptree Prog254.program = t1 := by rfl",
            "theorem t1_eq : ptree Prog254.program = t1 := ActualTree254.tree_eq")
    if args.check:
        if args.out.read_bytes() != source.encode("utf-8"):
            ap.error("Generated bisimulation source differs")
        print(f"PASS: exact bisimulation source ({n} entries in {len(chunks)} chunks)")
    else:
        args.out.write_text(source, encoding="utf-8", newline="\n")
        print(f"wrote {args.out}: {n} entries in {len(chunks)} chunks")
    return 0


if __name__ == "__main__":
    sys.exit(main())
