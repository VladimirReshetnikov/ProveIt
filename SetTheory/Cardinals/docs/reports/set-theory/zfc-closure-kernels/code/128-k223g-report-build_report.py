#!/usr/bin/env python3
"""Generate the literal table appendix and compile the report with pdfLaTeX.

Run from any directory; requires Python 3 and a standard TeX installation.
The numerical table is checked against its fixed SHA-256 before typesetting.
"""
from pathlib import Path
import argparse
import hashlib
import subprocess

HERE = Path(__file__).resolve().parent
TABLE = HERE.parent / "portable" / "results" / "candidate223.tm"
TABLE_SHA = "0d4eb8ffbcd5dc025c8dac198c7d8a15404c35f63134b5e3ed0b7df7673d9231"


def generate_table():
    raw = TABLE.read_bytes()
    if hashlib.sha256(raw).hexdigest() != TABLE_SHA:
        raise ValueError("The literal candidate table does not match its pin")
    rows = {}
    for line in raw.decode("ascii").splitlines():
        if line.startswith("#") or not line.strip():
            continue
        q, read, write, move, nxt = line.split()
        q, read, write, nxt = map(int, (q, read, write, nxt))
        if (q, read) in rows or move not in ("L", "R"):
            raise ValueError("Invalid transition table")
        if write not in (0, 1) or not 0 <= nxt <= 223:
            raise ValueError("Invalid transition action")
        rows[q, read] = f"{write}{move}{nxt}"
    if set(rows) != {(q, bit) for q in range(223) for bit in (0, 1)}:
        raise ValueError("Expected exactly 223 working states and 446 rows")

    lines = [
        "% Generated by build_report.py from the literal pinned machine.",
        "% SHA-256: " + TABLE_SHA,
        r"\begingroup",
        r"\fontsize{9}{10}\selectfont",
        r"\setlength{\tabcolsep}{4pt}",
        r"\renewcommand{\arraystretch}{0.94}",
        r"\begin{center}",
        r"\begin{tabular}{rrr@{\hspace{5mm}}rrr@{\hspace{5mm}}rrr@{\hspace{5mm}}rrr}",
        r"\toprule",
        " & ".join([r"$q$ & Read 0 & Read 1"] * 4) + r" \\",
        r"\midrule",
    ]
    for offset in range(56):
        cells = []
        for group in range(4):
            q = group * 56 + offset
            if q >= 223:
                cells.extend(["", "", ""])
            else:
                cells.extend([str(q), r"\texttt{" + rows[q, 0] + "}",
                              r"\texttt{" + rows[q, 1] + "}"])
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{center}", r"\endgroup"]
    (HERE / "transition_table.tex").write_text("\n".join(lines) + "\n", encoding="ascii")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output-dir", type=Path, default=HERE)
    parser.add_argument("--table-only", action="store_true")
    args = parser.parse_args()
    generate_table()
    if args.table_only:
        print("TABLE_APPENDIX_PASS: 223 states, 446 transitions")
        return
    out = args.output_dir.resolve()
    out.mkdir(parents=True, exist_ok=True)
    cmd = ["pdflatex", "-halt-on-error", "-interaction=nonstopmode",
           "-file-line-error", "-output-directory=" + str(out), "main.tex"]
    for _ in range(2):
        subprocess.run(cmd, cwd=HERE, check=True)
    print("Report: " + str(out / "main.pdf"))


if __name__ == "__main__":
    main()
