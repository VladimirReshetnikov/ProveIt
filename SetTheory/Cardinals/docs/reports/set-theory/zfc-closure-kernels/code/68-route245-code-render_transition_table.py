#!/usr/bin/env python3
"""Generate the manuscript's complete table directly from the canonical TM."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]


def rendered():
    rows = {}
    start = None
    for line in (ROOT / "machine/zfc245.tm").read_text().splitlines():
        if line.startswith("#! start "):
            start = int(line.split()[-1])
        elif line and not line.startswith("#"):
            q, bit, write, move, target = line.split()
            key = int(q), int(bit)
            assert key not in rows
            rows[key] = int(write), move, int(target)
    assert start == 0 and len(rows) == 490
    assert {q for q, _ in rows} == set(range(245))
    lines = [
        "% Generated by code/render_transition_table.py; do not edit by hand.",
        r"\begingroup\small\setlength{\tabcolsep}{5pt}",
        r"\begin{longtable}{@{}rll@{\hspace{8mm}}rll@{}}",
        r"\toprule State & Read 0 & Read 1 & State & Read 0 & Read 1\\",
        r"\midrule\endfirsthead",
        r"\toprule State & Read 0 & Read 1 & State & Read 0 & Read 1\\",
        r"\midrule\endhead",
        r"\midrule\multicolumn{6}{r}{Continued on next page}\\\endfoot",
        r"\bottomrule\endlastfoot",
    ]

    def triple(q, b):
        w, d, t = rows[q, b]
        assert w in (0, 1) and d in ("L", "R") and 0 <= t <= 245
        return rf"$({w},{d},{t})$"

    for q in range(123):
        left = [str(q), triple(q, 0), triple(q, 1)]
        other = q + 123
        right = [str(other), triple(other, 0), triple(other, 1)] if other < 245 else ["", "", ""]
        lines.append(" & ".join(left + right) + r"\\")
    lines.extend([r"\end{longtable}", r"\endgroup", ""])
    return "\n".join(lines)


if __name__ == "__main__":
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    target = ROOT / "machine/transition-table.tex"
    text = rendered()
    if args.check:
        assert target.read_text() == text, "Printed transition table differs from machine."
        print("PASS: all 490 displayed transitions match the canonical machine.")
    else:
        target.write_text(text)
        print(target)
