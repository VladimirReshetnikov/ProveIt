"""Generate the data files of zf/m254/prog/coq:

  Dag254.v    the Wade-compiled program DAG of source_local.py (219 nodes, root 0 = main().0)
  Cert254.v   the bisimulation certificate between p254 and dag254 (Bisim.v format)

Usage: python -I tools/gen_coq.py      (from anywhere)
"""
import sys, os
HERE = os.path.dirname(os.path.abspath(__file__))
COQ = os.path.normpath(os.path.join(HERE, '..', 'coq'))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.normpath(os.path.join(HERE, '..', '..', 'logic')))
import rmpath
from build_dag import load_dag


def coq_leaf(e):
    k = e[0]
    if k == 'inc':
        return f'EInc {e[1]}'
    if k == 'dec':
        return f'EDecnz {e[1]}'
    if k == 'brk':
        return f'EBreak {e[1]}'
    if k == 'cont':
        return f'EContinue {e[1]}'
    if k == 'halt':
        return 'EHalt'
    raise ValueError(e)


def write(name, text):
    with open(os.path.join(COQ, name), 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote', name, len(text), 'bytes')


def gen_dag(nodes):
    names = sorted(nodes)
    names.remove('main().0')
    names = ['main().0'] + names
    idx = {n: i for i, n in enumerate(names)}

    def edge(e):
        return f'ENode {idx[e[1]]}' if e[0] == 'node' else coq_leaf(rmpath.dag_edge(e))
    L = ['(** Generated by tools/gen_coq.py from logic/m254_wade.tm (Wade TMBuilder compile of source_local.py)',
         f'    -- do not edit.  {len(names)} nodes; node 0 = main().0 (root).',
         '    Registers (declaration order): ' + ', '.join(f'{r} {i}' for i, r in enumerate(rmpath.REGS)) + '. *)',
         'From M254 Require Import RM.', '',
         'Definition dag_nodes (n : nat) : edge * edge :=', '  match n with']
    for n in names:
        a, b = nodes[n]
        L.append(f'  | {idx[n]} => ({edge(a)}, {edge(b)})   (* {n} *)')
    L += ['  | _ => (EHalt, EHalt)', '  end.', '',
          f'Definition dag254 : prog := mkProg dag_nodes 0 {len(names)}.', '']
    write('Dag254.v', '\n'.join(L))


def bits(P):
    return '[' + ';'.join('t' if b else 'f' for b in P) + ']'


def gen_cert(ents):
    L = ['(** Generated by tools/gen_coq.py -- do not edit.  Bisimulation certificate p254 ~ dag254',
         f'    ({len(ents)} entries; entry 0 = start pair).  Checked in Bisim254.v. *)',
         'From Coq Require Import Lists.List NArith.',
         'From M254P Require Import Bisim.',
         'Import ListNotations.',
         'Local Notation t := true.', 'Local Notation f := false.', '',
         'Definition cert254 : list entry := [']
    rows = [f'  ({bits(a)}, {bits(b)}, {j}%N, {k}%N)' for a, b, j, k in
            [(e[0], e[1], e[2] if e[2] is not None else 0, e[3] if e[3] is not None else 0) for e in ents]]
    L.append(';\n'.join(rows))
    L += ['].', '']
    write('Cert254.v', '\n'.join(L))


if __name__ == '__main__':
    nodes, regidx = load_dag()
    assert [r for r, _ in sorted(regidx.items(), key=lambda x: x[1])] == rmpath.REGS
    gen_dag(nodes)
    t1 = rmpath.load_p254()
    t2 = rmpath.tree_of_dag(nodes)
    gen_cert(rmpath.certificate(t1, t2))
