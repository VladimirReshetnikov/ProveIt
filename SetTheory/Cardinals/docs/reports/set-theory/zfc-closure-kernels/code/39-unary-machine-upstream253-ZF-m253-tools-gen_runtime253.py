#!/usr/bin/env python3
"""Generate the exact compact ZF253 table and its old-label proof view.

Derived from Mira-Cult's accepted ZFC254 machine and the local conditional
helper reduction. Preserves all source notices; see ZF/m254/README.md and
ZF/m253/README.md. No external imports or downloads are required.
"""
import argparse
import hashlib
import importlib.util
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
SHA = '84a21f714017c1d491008d86e9bd19c43cc6c5c9ae99a538b4f2314387827d95'


def generate(machine, generator):
    data = machine.read_bytes()
    assert hashlib.sha256(data).hexdigest() == SHA
    spec = importlib.util.spec_from_file_location('generate_candidate', generator)
    author = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(author)
    assert author.CANDIDATE_SHA256 == SHA
    assert author.generate_candidate(ROOT/'ZF/m254/machine/zfc_254.tm') == data
    forward = author.OLD_TO_COMPACT
    assert set(forward) == set(range(255)) - {8}
    assert set(forward.values()) == set(range(254)) and len(forward) == 254
    assert forward[5] == 0 and forward[254] == 253
    inverse = {n:q for q,n in forward.items()}
    rows, start = {}, None
    for line in data.decode().splitlines():
        if line.startswith('#!'):
            _, command, value = line.split()
            assert command == 'start' and start is None
            start = int(value)
        elif line and not line.startswith('#'):
            q,b,w,d,n = line.split()
            q,b,w,n = int(q),int(b),int(w),int(n)
            assert (q,b) not in rows and b in (0,1) and w in (0,1) and d in ('L','R')
            assert 0 <= n <= 253
            rows[q,b] = w,d,n
    assert start == 0
    assert set(rows) == {(q,b) for q in range(253) for b in (0,1)}
    logical = {(inverse[q],b):(w,d,inverse[n]) for (q,b),(w,d,n) in rows.items()}
    assert set(logical) == {(q,b) for q in range(254) if q != 8 for b in (0,1)}
    assert logical[3,0] == (0,'L',48) and logical[5,0] == (1,'R',97)
    assert logical[5,1] == (1,'R',64) and logical[49,1] == (0,'R',5)
    def boolean(b):
        return 'true' if b else 'false'
    def row(a,b):
        return f'({boolean(a[0])}, {a[1]}, {a[2]}, {boolean(b[0])}, {b[1]}, {b[2]})'
    out = ['(** * Table253: literal compact table and a certified old-label proof view.',
           '    Machine derived from Mira-Cult ZFC254 by a local conditional-helper reduction.',
           '    There are exactly 253 working rows; compact state 253 is terminal.',
           '    SHA256 of machine/zfc_253.tm: '+SHA,
           '    Generated by tools/gen_runtime253.py; provenance: ZF/m254/README.md. *)',
           '', 'From BusyCoq Require Import TM.',
           'From Coq Require Import Lists.List.', 'Import ListNotations.', '',
           'Definition table253 : list (bool * dir * nat * bool * dir * nat) := [']
    for q in range(253):
        out.append('  '+row(rows[q,0],rows[q,1])+(';' if q<252 else '')+f'  (* compact {q} *)')
    out += ['].', '', '(** Old state 8 is deleted and maps to the compact halt as a total default. *)',
            'Definition compact_labels : list nat := [',
            '  '+'; '.join(str(forward.get(q,253)) for q in range(255)), '].', '',
            'Definition old_labels : list nat := [',
            '  '+'; '.join(str(inverse[q]) for q in range(254)), '].', '',
            '(** A proof-execution view; these labels are not extra physical TM states. *)',
            'Definition logical_table253 : list (option (bool * dir * nat * bool * dir * nat)) := [']
    for q in range(254):
        value = 'None' if q == 8 else 'Some '+row(logical[q,0],logical[q,1])
        out.append('  '+value+(';' if q<253 else '')+f'  (* old {q} *)')
    out += ['].','']
    return '\n'.join(out)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--machine',type=Path,default=ROOT/'ZF/m253/machine/zfc_253.tm')
    parser.add_argument('--generator',type=Path,default=Path(__file__).with_name('generate_candidate.py'))
    parser.add_argument('--output',type=Path,default=ROOT/'ZF/m253/coq/tm/Table253.v')
    parser.add_argument('--check',action='store_true')
    args=parser.parse_args()
    text=generate(args.machine,args.generator)
    if args.check:
        assert args.output.read_text() == text, 'Table253.v differs from exact regeneration'
        print('exact 506-transition table, old-label view and compact map match')
    else:
        args.output.write_text(text)
        print('wrote',args.output)


if __name__ == '__main__':
    main()
