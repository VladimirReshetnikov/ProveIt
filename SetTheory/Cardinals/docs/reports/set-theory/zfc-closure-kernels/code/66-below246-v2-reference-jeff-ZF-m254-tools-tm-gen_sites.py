"""Generate coq/Sites254.v: the 6460 instruction sites (decoder path, operation) of zfc_254,
read from inputs/paths.json (data only).  Path bits exclude the constant '110' prefix of the file;
a path is stored as the positive number with binary digits 1<path>.  Registers are numbered
physically: wffstack 0, param1 1, axiomcode 2, scratch2 3, scratch1 4, prooflist 5, nextproof 6,
topwff 7, param2 8."""
import sys, json
paths = json.load(open(sys.argv[1]))
REG = dict(wffstack=0, param1=1, axiomcode=2, scratch2=3, scratch1=4, prooflist=5, nextproof=6, topwff=7, param2=8)
out = []
for p, op in paths:
    assert p.startswith('110'); P = p[3:]
    code = int('1' + P, 2)
    if op == 'halt': o = 'OHalt'
    elif op.startswith('_continue.'): o = 'OCont %d' % int(op.split('.')[1])
    elif op.startswith('_break.'): o = 'OBrk %d' % int(op.split('.')[1])
    else:
        _, r, kind = op.split('.')
        o = ('OInc %d' if kind == 'inc' else 'ODec %d') % REG[r]
        assert kind in ('inc', 'decnz')
    out.append('(%d, %s)' % (code, o))
with open(sys.argv[2], 'w', newline='\n') as f:
    f.write('(** * Sites254: the %d instruction sites of zfc_254 (generated by tools/gen_sites.py from paths.json). *)\n\n' % len(out))
    f.write('From Coq Require Import PArith Lists.List.\nFrom M254 Require Import Site.\nImport ListNotations.\nLocal Open Scope positive_scope.\n\n')
    f.write('Definition sites : list (positive * op) := [\n  ' + ';\n  '.join(out) + '\n].\n')
print(len(out), 'sites')
