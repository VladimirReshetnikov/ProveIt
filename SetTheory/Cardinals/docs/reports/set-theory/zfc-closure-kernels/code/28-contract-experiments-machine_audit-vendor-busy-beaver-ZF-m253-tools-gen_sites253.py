#!/usr/bin/env python3
"""Regenerate the inspection inventory from the committed, pinned RM program.

The mandatory Coq certificate in Check253 independently enumerates the leaves
of this same program. No external author bundle or paths.json is needed.
"""
import argparse
import hashlib
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[3]
PROGRAM_SHA256 = '1fbc30fcf82a1442ed88d1a1dde412630a431d32a7265d22bdf8517bffe01746'
PHYS_OF = (6, 7, 0, 2, 1, 8, 4, 3, 5)


def generate(program):
    data = program.read_bytes()
    if hashlib.sha256(data).hexdigest() != PROGRAM_SHA256:
        raise ValueError('Prog254.v differs from the pinned accepted program')
    body = data.decode('utf-8').split('Definition p254_tab', 1)[1].split('[', 1)[1].split('].', 1)[0]
    edge = r'(?:CN \d+|CI \d+|CD \d+|CB \d+|CC \d+|CH)'
    nodes = re.findall(r'\((' + edge + r'),\s*(' + edge + r')\)', body)
    if len(nodes) != 6459:
        raise ValueError('expected the complete 6459-node accepted decoder tree')
    sites = []
    stack = [('CN 0', 1)]
    while stack:
        value, code = stack.pop()
        kind, *argument = value.split()
        if kind == 'CN':
            left, right = nodes[int(argument[0])]
            stack.extend(((right, 2 * code + 1), (left, 2 * code)))
        elif kind in ('CI', 'CD'):
            operation = 'OInc' if kind == 'CI' else 'ODec'
            sites.append((code, operation + ' ' + str(PHYS_OF[int(argument[0])])))
        elif kind in ('CB', 'CC'):
            sites.append((code, ('OBrk' if kind == 'CB' else 'OCont') + ' ' + argument[0]))
        else:
            if kind != 'CH':
                raise ValueError('unknown instruction')
            sites.append((code, 'OHalt'))
    if len(sites) != 6460 or max(code.bit_length() - 1 for code, _ in sites) != 34:
        raise ValueError('unexpected instruction-site count or maximum depth')
    return ('(** * Sites253: the 6460 instruction sites, generated by tools/gen_sites253.py\n'
            '    from the pinned, committed ../m254/coq/tm/Prog254.v. *)\n\n'
            'From Coq Require Import PArith Lists.List.\n'
            'From M253 Require Import Site.\n'
            'Import ListNotations.\n'
            'Local Open Scope positive_scope.\n\n'
            'Definition sites : list (positive * op) := [\n  '
            + ';\n  '.join(f'({code}, {operation})' for code, operation in sites) + '\n].\n')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--program', type=Path, default=ROOT / 'ZF/m254/coq/tm/Prog254.v')
    parser.add_argument('--output', type=Path, default=ROOT / 'ZF/m253/coq/tm/Sites253.v')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate(args.program)
    if args.check:
        if args.output.read_text() != text:
            raise ValueError('Sites253.v differs from exact regeneration')
        print('all 6460 instruction sites match the pinned accepted program')
    else:
        args.output.write_text(text)
        print('wrote', args.output)


if __name__ == '__main__':
    main()
