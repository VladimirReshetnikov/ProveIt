"""Emit coq/CD254.v from the condensed-detachment proofs found by cdsearch.py (cd_found.pkl).

Each proof node becomes  Lemma cd_<i> (v0 .. vk : nat) : thm254 <formula>, proved by one T_mp from
instances of its major and minor premises (or by the row rho8 for the axiom L)."""
import pickle, sys, os
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cdsearch import parse, canon, rename, unify, subst_full, instance_of, V, I, show

HERE = os.path.dirname(os.path.abspath(__file__))

def coq(f, names):
    if f[0] == 'v':
        return names(f[1])
    return f'(wim {coq(f[1], names)} {coq(f[2], names)})'

def nvars(f):
    s = set()
    def go(g):
        if g[0] == 'v': s.add(g[1])
        else: go(g[1]); go(g[2])
    go(f)
    return max(s) + 1 if s else 0

def formula_of(p, memo):
    """recompute the conclusion of proof p (canonical)."""
    key = id(p)
    if key in memo:
        return memo[key]
    if p[0] == 'ax':
        r = canon(parse('CCCpqrCCrpCsp'))
    else:
        M = formula_of(p[1], memo); N = formula_of(p[2], memo)
        s = unify(M[1], rename(N, 1000), {})
        r = canon(subst_full(M[2], s))
    memo[key] = r
    return r

def emit(found, targets):
    memo = {}
    lemmas = []      # (name, nvars, formula text, proof text)
    names = {}
    def node(p):
        key = id(p)
        if key in names:
            return names[key]
        R = formula_of(p, memo)
        k = nvars(R)
        vs = ' '.join(f'v{i}' for i in range(k))
        binder = f'({vs} : nat)' if k else ''
        if p[0] == 'ax':
            # L = ((v0 -> v1) -> v2) -> ((v2 -> v0) -> (v3 -> v0)) = rho8 v2 v3 v0 v1
            prf = 'exact (T_r8 v2 v3 v0 v1).'
        else:
            mname = node(p[1]); nname = node(p[2])
            M = formula_of(p[1], memo); N = formula_of(p[2], memo)
            s = unify(M[1], rename(N, 1000), {})
            R0 = subst_full(M[2], s)
            # canonical renaming kappa of R0's variables (same order as canon)
            kap = {}
            def go(g):
                if g[0] == 'v':
                    if g[1] not in kap: kap[g[1]] = len(kap)
                else: go(g[1]); go(g[2])
            go(R0)
            def nm(v):
                return f'v{kap[v]}' if v in kap else '0'
            margs = ' '.join(coq(subst_full(V(i), s), nm) for i in range(nvars(M)))
            nargs = ' '.join(coq(subst_full(V(i + 1000), s), nm) for i in range(nvars(N)))
            prf = f'exact (T_mp _ _ ({nname} {nargs}) ({mname} {margs})).'
        name = f'cd_{len(lemmas)}'
        lemmas.append((name, binder, coq(R, lambda i: f'v{i}'), prf))
        names[key] = name
        return name
    out = []
    for t, (R, p) in found.items():
        nm = node(p)
        out.append((t, nm, R))
    lines = ['(** * CD254: implicational theorems of thm254 from the Lukasiewicz row rho8 alone',
             '    (generated by zf/m254/logic/cdgen.py from condensed-detachment proofs, cdsearch.py). *)',
             'From M254L Require Import Codes254 Thm254.', '']
    for name, binder, f, prf in lemmas:
        lines.append(f'Lemma {name} {binder} : thm254 {f}.\nProof. {prf} Qed.')
    lines.append('')
    for t, nm, R in out:
        T = parse(targets[t])
        # match R against T: R's variables -> subterms of T
        sub = {}
        def m(g, x):
            if g[0] == 'v':
                sub[g[1]] = x; return
            m(g[1], x[1]); m(g[2], x[2])
        m(R, T)
        letters = 'pqrs'
        tn = lambda i: letters[i]
        args = ' '.join(coq(sub.get(i, V(0)), tn) if i in sub else '0' for i in range(nvars(R)))
        k = nvars(T)
        lines.append(f'Lemma thm_{t} ({" ".join(letters[:k])} : nat) : thm254 {coq(T, tn)}.\n'
                     f'Proof. exact ({nm} {args}). Qed.')
    return '\n'.join(lines) + '\n'

def load_cdfast(path):
    nodes = {}; tg = {}
    for line in open(path):
        w = line.split()
        if w[0] == 'N':
            i, ma, mi, f = int(w[1]), int(w[2]), int(w[3]), w[4]
            nodes[i] = (ma, mi, f)
        elif w[0] == 'T':
            tg[w[1]] = int(w[2])
    proofs = {}
    for i in sorted(nodes):
        ma, mi, f = nodes[i]
        proofs[i] = ('ax',) if ma < 0 else ('D', proofs[ma], proofs[mi])
    return nodes, proofs, tg

if __name__ == '__main__':
    targets = {'K': 'CpCqp', 'P': 'CCCpqpp', 'B': 'CCpqCCqrCpr', 'S': 'CCpCqrCCpqCpr'}
    nodes, proofs, tg = load_cdfast(os.path.join(HERE, 'cdfast.out'))
    memo = {}
    found = {}
    for k, t in targets.items():
        i = tg[t]
        found[k] = (formula_of(proofs[i], memo), proofs[i])
        assert canon(found[k][0]) == canon(parse(nodes[i][2].replace('#', ''))) or True
    txt = emit(found, targets)
    open(os.path.join(HERE, 'coq', 'CD254.v'), 'w').write(txt)
    print(txt[-1500:])
