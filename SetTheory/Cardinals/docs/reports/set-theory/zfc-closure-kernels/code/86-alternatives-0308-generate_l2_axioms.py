#!/usr/bin/env python3
"""Generate BusyBeaver/ZFC/L2Axioms254.lean: one lemma per axioms() node.

axioms() of the 219-node program is a straight-line composition of macro
calls.  For every internal node N = (car, cdr) of that subtree this script
emits

    def fN (st : AS) : AS := fcdr (fcar st)
    theorem lN (st : AS) (hc : Clean st) : Rn (.node N) st (fN st) :=
      seqAS (n := N) rfl (lcar st hc) (lcdr _ hc)

in dependency order.  Macro leaves use the lemmas of L2Macros254; nodes 35
and 71 (the literal read into topwff, and the gate) are written by hand in
the template below.  The Lean kernel checks everything; this script only
writes the obvious compositions.

Usage (from the repository root):
    py -I Computability/BusyBeaver/Research/ZFC/generate_l2_axioms.py
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[4]
SOURCE = REPO / "lib/jeff-busy-beaver-zfc254/ZF/m254/coq/prog/Dag254.v"
TARGET = REPO / "Computability/BusyBeaver/Lean/BusyBeaver/ZFC/L2Axioms254.lean"
ROW = re.compile(r"\|\s*(\d+)\s*=>\s*\((E\w+(?:\s+\d+)?),\s*(E\w+(?:\s+\d+)?)\)\s*\(\*\s*(.*?)\s*\*\)")

# Macro leaves: node -> (lemma, function).
LEAVES = {
    166: ("par1L", "par1F", "par1C"), 121: ("par2L", "par2F", "par2C"), 168: ("par3L", "par3F", "par3C"),
    171: ("pushL", "pushF", "pushC"), 119: ("consL", "consF", "consC"), 181: ("welL", "welF", "welC"),
    180: ("walL", "walF", "walC"), 182: ("weqL", "weqF", "weqC"), 218: ("wnL", "wnF", "wnC"),
    178: ("waL", "waF", "waC"), 183: ("wexL", "wexF", "wexC"), 176: ("readp2L", "readp2F", "readp2C"),
    35: ("l35", "f35", "c35"), 71: ("l71", "gateF", "gateC"),
}

HEADER = r'''import BusyBeaver.ZFC.L2Control254

/-!
The `axioms()` routine of the 219-node program (L2, part 4).

Generated by `Computability/BusyBeaver/Research/ZFC/generate_l2_axioms.py`
from the pinned program data: one lemma per node of the `axioms()` subtree,
each composing the effects of its two children. The macro leaves are the
lemmas of `L2Macros254`; the literal read into `topwff` (nodes 35/46) and the
final gate (node 71) are written by hand below. The final theorem evaluates
the composite symbolically against `Enum254.axStack` and `Enum254.gate`.
-/

namespace SetTheory.BusyBeaver.ZFC.L2

open RMDag Dag254 Code254

attribute [local irreducible] Code254.P

def pushF (st : AS) : AS := { st with tw := 0, ws := P st.tw st.ws }
def par1F (st : AS) : AS := { st with tw := st.p1, ws := P st.tw st.ws }
def par2F (st : AS) : AS := { st with tw := st.p2, ws := P st.tw st.ws }
def par3F (st : AS) : AS := { st with tw := st.ac, ws := P st.tw st.ws }
def consF (st : AS) : AS :=
  { st with tw := wim (Cantor.ofNat st.ws).1 st.tw, ws := (Cantor.ofNat st.ws).2 }
def welF (st : AS) : AS :=
  { st with tw := wel (Cantor.ofNat st.ws).1 st.tw, ws := (Cantor.ofNat st.ws).2 }
def walF (st : AS) : AS :=
  { st with tw := wal (Cantor.ofNat st.ws).1 st.tw, ws := (Cantor.ofNat st.ws).2 }
def weqF (st : AS) : AS :=
  { st with tw := weq (Cantor.ofNat st.ws).1 st.tw, ws := (Cantor.ofNat st.ws).2 }
def wnF (st : AS) : AS := { st with tw := wn st.tw }
def waF (st : AS) : AS :=
  { st with tw := wa (Cantor.ofNat st.ws).1 st.tw, ws := (Cantor.ofNat st.ws).2 }
def wexF (st : AS) : AS :=
  { st with tw := wex (Cantor.ofNat st.ws).1 st.tw, ws := (Cantor.ofNat st.ws).2 }
def readp2F (st : AS) : AS :=
  { st with pl := (Cantor.ofNat st.pl).2, p2 := st.p2 + (Cantor.ofNat st.pl).1 }

theorem pushL (st : AS) (hc : Clean st) : Rn (.node 171) st (pushF st) := pushwff st hc
theorem par1L (st : AS) (hc : Clean st) : Rn (.node 166) st (par1F st) := par1 st hc
theorem par2L (st : AS) (hc : Clean st) : Rn (.node 121) st (par2F st) := par2 st hc
theorem par3L (st : AS) (hc : Clean st) : Rn (.node 168) st (par3F st) := par3 st hc
theorem consL (st : AS) (hc : Clean st) : Rn (.node 119) st (consF st) := cons st hc
theorem welL (st : AS) (hc : Clean st) : Rn (.node 181) st (welF st) := wel_m st hc
theorem walL (st : AS) (hc : Clean st) : Rn (.node 180) st (walF st) := wal_m st hc
theorem weqL (st : AS) (hc : Clean st) : Rn (.node 182) st (weqF st) := weq_m st hc
theorem wnL (st : AS) (hc : Clean st) : Rn (.node 218) st (wnF st) := wn_m st hc
theorem waL (st : AS) (hc : Clean st) : Rn (.node 178) st (waF st) := wa_m st hc
theorem wexL (st : AS) (hc : Clean st) : Rn (.node 183) st (wexF st) := wex_m st hc
theorem readp2L (st : AS) (hc : Clean st) : Rn (.node 176) st (readp2F st) := read_p2 st hc

theorem pushC (st : AS) (hc : Clean st) : Clean (pushF st) := hc
theorem par1C (st : AS) (hc : Clean st) : Clean (par1F st) := hc
theorem par2C (st : AS) (hc : Clean st) : Clean (par2F st) := hc
theorem par3C (st : AS) (hc : Clean st) : Clean (par3F st) := hc
theorem consC (st : AS) (hc : Clean st) : Clean (consF st) := hc
theorem welC (st : AS) (hc : Clean st) : Clean (welF st) := hc
theorem walC (st : AS) (hc : Clean st) : Clean (walF st) := hc
theorem weqC (st : AS) (hc : Clean st) : Clean (weqF st) := hc
theorem wnC (st : AS) (hc : Clean st) : Clean (wnF st) := hc
theorem waC (st : AS) (hc : Clean st) : Clean (waF st) := hc
theorem wexC (st : AS) (hc : Clean st) : Clean (wexF st) := hc
theorem readp2C (st : AS) (hc : Clean st) : Clean (readp2F st) := hc

/-- The gate (node 71): clear the bundle when `c = b` or `c = a`, and clear
`axiomcode`, `param1`, `param2`. -/
def gateF (st : AS) : AS :=
  { st with ac := 0, p1 := 0, p2 := 0, tw := if st.ac = st.p1 ∨ st.ac = st.p2 then 0 else st.tw }

theorem gateC (st : AS) (hc : Clean st) : Clean (gateF st) := hc

theorem l71 (st : AS) (hc : Clean st) : Rn (.node 71) st (gateF st) := by
  have := seqAS (n := 71) rfl (loop192 st) (seqAS (n := 72) rfl (ifeq_clear _)
    (seqAS (n := 73) rfl (loop211 _) (seqAS (n := 74) rfl (loop197 _) (ifeq_clear _))))
  apply rn_eq this
  obtain ⟨h1, h2⟩ := hc
  cases st
  simp only at h1 h2
  subst h1; subst h2
  simp only [gateF, Nat.zero_add]
  split <;> split <;> simp_all <;> omega

'''


def main() -> int:
    text = SOURCE.read_text(encoding="utf-8")
    nodes = {int(m.group(1)): (m.group(2), m.group(3), m.group(4)) for m in ROW.finditer(text)}

    def child(e: str) -> int:
        m = re.fullmatch(r"ENode\s+(\d+)", e.strip())
        if not m:
            raise ValueError(f"non-node edge in axioms(): {e}")
        return int(m.group(1))

    order: list[int] = []
    seen: set[int] = set()

    def visit(n: int) -> None:
        if n in seen or n in LEAVES:
            return
        seen.add(n)
        a, b, _ = nodes[n]
        if n == 46:
            visit(child(b))  # node 46 = (208, 58) is written by hand
            order.append(n)
            return
        visit(child(a))
        visit(child(b))
        order.append(n)

    # node 35 = (158, 46) is a hand-written leaf; generate the chain under 46.
    visit(46)
    visit(1)

    out = [HEADER]
    w = out.append
    for n in order:
        a, b, name = nodes[n]
        if n == 46:
            ca = child(b)
            w(f"/-- {name}: move the literal from scratch1 into topwff, then continue. -/")
            w(f"def f46 (st : AS) : AS := f{ca} {{ st with tw := st.tw + st.s1, s1 := 0 }}")
            w(f"theorem l46 (st : AS) (h2 : st.s2 = 0) : Rn (.node 46) st (f46 st) :=")
            w(f"  seqAS (n := 46) rfl (loop208 st) ({lemma(ca)} _ ⟨rfl, h2⟩)")
            w(f"theorem c46 (st : AS) (h2 : st.s2 = 0) : Clean (f46 st) := {clean(ca)} _ ⟨rfl, h2⟩")
            w("")
            w("/-- axioms().4: read the literal `u` into topwff. -/")
            w("def f35 (st : AS) : AS := f46 { st with pl := (Cantor.ofNat st.pl).2, s1 := (Cantor.ofNat st.pl).1 }")
            w("theorem l35 (st : AS) (hc : Clean st) : Rn (.node 35) st (f35 st) :=")
            w("  seqAS (n := 35) rfl (read108 st hc) (l46 _ hc.2)")
            w("theorem c35 (st : AS) (hc : Clean st) : Clean (f35 st) := c46 _ hc.2")
            w("")
            continue
        ca, cb = child(a), child(b)
        w(f"/-- {name} -/")
        w(f"def f{n} (st : AS) : AS := {fn(cb)} ({fn(ca)} st)")
        w(f"theorem l{n} (st : AS) (hc : Clean st) : Rn (.node {n}) st (f{n} st) :=")
        w(f"  seqAS (n := {n}) rfl ({lemma(ca)} st hc) ({lemma(cb)} _ ({clean(ca)} st hc))")
        w(f"theorem c{n} (st : AS) (hc : Clean st) : Clean (f{n} st) :=")
        w(f"  {clean(cb)} _ ({clean(ca)} st hc)")
        w("")
    w("end SetTheory.BusyBeaver.ZFC.L2")
    w("")
    TARGET.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {TARGET}: {len(order)} generated node lemmas")
    return 0


def lemma(n: int) -> str:
    return LEAVES[n][0] if n in LEAVES else f"l{n}"


def clean(n: int) -> str:
    return LEAVES[n][2] if n in LEAVES else f"c{n}"


def fn(n: int) -> str:
    return LEAVES[n][1] if n in LEAVES else f"f{n}"


if __name__ == "__main__":
    sys.exit(main())

