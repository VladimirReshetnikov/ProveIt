#!/usr/bin/env python3
"""Deterministic release checks; no consistency or new state-record claim.

Run from any working directory. No optional synthesis jobs are rerun here.
Python 3.10+ and the standard library suffice.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile
import time

import ground_kernel as K
import validate_kernel as V
import check_countermodels as CM
import coded_extensional as CE
import refute
import baseline_metrics

ROOT = Path(__file__).resolve().parents[1]


def require(condition, message):
    if not condition:
        raise RuntimeError(message)


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--output", type=Path, default=ROOT / "data/release_validation.json")
    args = ap.parse_args()
    start = time.monotonic()
    results = {}
    with tempfile.TemporaryDirectory(prefix="zfc_kernel_release_") as directory:
        temp = Path(directory)
        K.generate(temp)
        coded = CE.generate(temp)
        baseline_metrics.generate(temp)
        reproduced = 0
        for generated in sorted(temp.iterdir()):
            if generated.suffix not in (".json", ".bits", ".bin"):
                continue
            retained = ROOT / "data" / generated.name
            require(retained.exists(), "missing retained data: " + generated.name)
            require(generated.read_bytes() == retained.read_bytes(),
                    "generated bytes differ: " + generated.name)
            reproduced += 1
        results["generated_files_identical"] = reproduced
        print("Generated clause streams and metrics match.", flush=True)

        results["kernel"] = {
            "codec": V.codec_checks(),
            "equality": V.equality_checks(),
            "solver": V.solver_checks(),
            "closure": V.finite_closure_checks(),
        }
        retained_validation = json.loads((ROOT / "data/validation.json").read_text())
        for key, value in results["kernel"].items():
            require(value == retained_validation[key], "validation differs: " + key)
        print("Ground encoding, equality, SAT and closure checks pass.", flush=True)

        results["coded_extensional"] = coded["validation"]
        results["countermodel_evaluations"] = sum(
            CM.audit(deleted)["total_assignments"] for deleted in (1, 2, 5))
        require(results["countermodel_evaluations"] == 1257, "countermodel census")

        stage_results = {}
        for name in ("fc15", "fc16", "fc17"):
            stream = refute.stages(name)
            stage_results[name] = [next(stream), next(stream)]
            require(all(x["satisfiable"] for x in stage_results[name]),
                    "unexpected initial refutation")
        results["outer_loop_two_stages"] = stage_results
        print("FC16 diagnostics, exact countermodels and reference loops pass.", flush=True)

        machine_temp = temp / "machine"
        machine_temp.mkdir()
        for name in ("composed253.tm", "composed_guard_invariant.json"):
            shutil.copy2(ROOT / "machine" / name, machine_temp / name)
        process = subprocess.run([
            sys.executable, str(ROOT / "machine/check_composition_certificate.py"),
            str(ROOT / "machine/inputs/public253.tm"),
            str(ROOT / "machine/inputs/faster253.tm"),
            "--dir", str(machine_temp),
        ], check=True, capture_output=True, text=True)
        results["machine"] = json.loads(process.stdout)
        require(results["machine"]["status"] == "PASS", "machine certificate failed")
        print("Independent invariant and all three complete bootstraps pass.", flush=True)

    results["all_passed"] = True
    results["elapsed_seconds"] = round(time.monotonic() - start, 3)
    results["scope"] = (
        "Finite deterministic validation of reference encodings and supplied "
        "certificates. No Lean/Coq build, no consistency proof by experiment, "
        "and no sub-253-state machine."
    )
    args.output.write_text(json.dumps(results, indent=2) + "\n")
    print(json.dumps({"all_passed": True,
                      "elapsed_seconds": results["elapsed_seconds"],
                      "output": str(args.output)}))


if __name__ == "__main__":
    main()
