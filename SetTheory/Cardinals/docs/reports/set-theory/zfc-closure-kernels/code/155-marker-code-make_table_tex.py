#!/usr/bin/env python3
"""Generate the entire canonical transition table appendix, without transcription."""
from pathlib import Path
import argparse, hashlib

ROOT = Path(__file__).resolve().parent.parent
PIN = 'a2b8bc2d4822962ad32819fe475a7d62b0d483bc4f41977bff292742f70b3e8c'

def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--table', type=Path, default=ROOT/'machine/k217.tm')
    ap.add_argument('--output', type=Path, default=ROOT/'appendix/full_table.tex')
    a = ap.parse_args()
    raw = a.table.read_bytes()
    if hashlib.sha256(raw).hexdigest() != PIN:
        raise ValueError('The appendix input is not the frozen canonical K217 table.')
    rows = {}
    for line in raw.decode('ascii').splitlines():
        if not line or line.startswith('#'):
            continue
        q,b,w,d,z = line.split()
        rows[int(q),int(b)] = (w,d,z)
    if set(rows) != {(q,b) for q in range(217) for b in (0,1)}:
        raise ValueError('Incomplete canonical table')
    head = r'\normalfont\bfseries State & \normalfont\bfseries Read 0 & \normalfont\bfseries Read 1'
    header = (head + ' & ' + head + ' & ' + head + r'\\')
    out = [
        '% Generated by code/make_table_tex.py from the exact canonical table.',
        '% SHA-256: '+PIN,
        r'\begingroup\small\ttfamily',
        r'\setlength{\tabcolsep}{5pt}',
        r'\renewcommand{\arraystretch}{1.08}',
        r'\begin{longtable}{@{}rll@{\qquad}rll@{\qquad}rll@{}}',
        r'\toprule', header, r'\midrule', r'\endfirsthead',
        r'\multicolumn{9}{c}{\normalfont\small Complete canonical table (continued)}\\[3pt]',
        r'\toprule', header, r'\midrule', r'\endhead',
        r'\midrule\multicolumn{9}{r}{\normalfont\small Continued on the next page}\\',
        r'\endfoot', r'\bottomrule', r'\endlastfoot',
    ]
    emitted = []
    for i in range(73):
        cells = []
        for q in (i,i+73,i+146):
            if q >= 217:
                cells += ['','','']
            else:
                cells += [str(q)] + [r'\,'.join(rows[q,b]) for b in (0,1)]
                emitted.append(q)
        out.append(' & '.join(cells) + r'\\')
    if sorted(emitted) != list(range(217)):
        raise ValueError('Appendix state inventory')
    out += [r'\end{longtable}', r'\endgroup', '']
    a.output.parent.mkdir(parents=True, exist_ok=True)
    a.output.write_bytes('\n'.join(out).encode('ascii'))
    print('FULL_TABLE_TEX_PASS: 217 working states, 434 transitions')

if __name__ == '__main__':
    main()
