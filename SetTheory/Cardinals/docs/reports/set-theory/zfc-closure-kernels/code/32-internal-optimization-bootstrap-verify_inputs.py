#!/usr/bin/env python3
"""Verify the packaged diagnostic inputs against the pinned DAG and direct RM run.

No Turing-machine acceleration is used. The 100,001 reference configurations
are generated by the explicit register interpreter in generate_rm_prefix.py.
"""
from pathlib import Path
import hashlib
import json
import re
import shutil
import subprocess
import sys
import tempfile

ROOT=Path(__file__).resolve().parent
source=ROOT.parent/'vendor/upstream/ZF/m254/coq/tm/Prog254.v'
text=source.read_text()
table=text.split('Definition p254_tab : list (cedge * cedge) := [',1)[1].split('].',1)[0]
nodes=re.findall(r'\((C\w+(?: \d+)?), (C\w+(?: \d+)?)\)',table)
assert len(nodes)==6459
paths=[]
mapping={kind:kind for kind in ['CI','CD','CB','CC','CH']}
def walk(q,prefix):
    for bit,edge in enumerate(nodes[q]):
        word=prefix+str(bit)
        kind,*arg=edge.split()
        if kind=='CN':
            walk(int(arg[0]),word)
        else:
            paths.append([word,mapping[kind]+((' '+arg[0]) if arg else '')])
walk(0,'')
assert paths==json.loads((ROOT/'paths.json').read_text())
assert len(paths)==6460
assert ''.join(p+'\n' for p,_ in paths)==(ROOT/'path_strings.txt').read_text()
with tempfile.TemporaryDirectory(prefix='zfc-rm-prefix-') as tmp:
    tmp=Path(tmp)
    shutil.copyfile(ROOT/'paths.json',tmp/'paths.json')
    run=subprocess.run([sys.executable,'-B',str(ROOT/'generate_rm_prefix.py')],
                       cwd=tmp,check=True,capture_output=True,text=True)
    got=(tmp/'rm_prefix100k.txt').read_bytes()
    assert got==(ROOT/'rm_prefix100k.txt').read_bytes()
result={'catalogue_paths':len(paths),'reference_configurations':100001,
        'reference_sha256':hashlib.sha256(got).hexdigest(),
        'decoder_source_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),
        'scope':'finite diagnostic inputs, not a blank-start or consistency theorem'}
print(json.dumps(result,indent=2))
