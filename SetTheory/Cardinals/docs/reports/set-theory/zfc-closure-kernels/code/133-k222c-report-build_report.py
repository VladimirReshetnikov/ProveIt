#!/usr/bin/env python3
"""Build the K222 report and its audited literal transition-table appendix.

Python 3.10+ and pdflatex are the only dependencies. Normal use creates a new,
initially empty build directory outside this packet, copies all report TeX
inputs there, generates the appendix from the pinned canonical machine, and
runs pdflatex twice. The packet itself is left untouched in this mode.

Examples:
    python3 -B report/build_report.py --output-dir /tmp/k222-report
    python3 -B report/build_report.py --generate-only

The second command writes report/transition_table.tex without compiling. With
--generate-only --output-dir DIR, the generated table and TeX inputs are written
to the selected external directory, but pdflatex is not invoked.

All 444 generated transition entries are parsed back from the TeX data rows and
compared with the canonical table before an output is accepted. This checks the
appendix transcription; it is not an additional machine-correctness proof.
"""
from __future__ import annotations

import argparse
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import re
import shutil
import subprocess
import sys

REPORT = Path(__file__).resolve().parent
PACKET = REPORT.parent
MACHINE = PACKET / 'portable/machine/candidate222.tm'
MACHINE_SHA256 = '01fb8d9813824ebf67b0f8b7f420c7719ae83d21217fde16eae7ab6c78ec2e26'
STATE_COUNT = 222
TERMINAL_STATE = 222
DATA_ROW = re.compile(
    r'^(\d+) & \\texttt\{([01]) ([LR]) (\d+)\} & '
    r'\\texttt\{([01]) ([LR]) (\d+)\} \\\\$',
)


def require(condition, message):
    if not condition:
        raise ValueError(message)


def digest(data):
    return hashlib.sha256(data).hexdigest()


def load_machine(path=MACHINE):
    raw = path.read_bytes()
    require(digest(raw) == MACHINE_SHA256, 'Canonical machine SHA-256 does not match the pinned K222 table')
    transitions, starts = {}, []
    for line_number, line in enumerate(raw.decode('ascii').splitlines(), 1):
        if line.startswith('#! start '):
            starts.append(int(line[9:])); continue
        if not line or line.startswith('#'):
            continue
        fields = line.split()
        require(len(fields) == 5, f'Invalid transition row at machine line {line_number}')
        state, read, write, direction, target = fields
        state, read, write, target = map(int, (state, read, write, target))
        require(0 <= state < STATE_COUNT, 'Noncanonical working-state label')
        require(read in (0, 1) and write in (0, 1), 'Nonbinary transition')
        require(direction in ('L', 'R'), 'Transition does not move exactly one cell')
        require(0 <= target <= TERMINAL_STATE, 'Undefined transition target')
        require((state, read) not in transitions, 'Duplicate transition row')
        transitions[state, read] = write, direction, target
    require(starts == [0], 'Expected a unique declaration of initial state 0')
    require(set(transitions) == {(q, bit) for q in range(STATE_COUNT) for bit in (0, 1)},
            'Canonical table does not have exactly 444 complete working-state rows')
    require(any(target == TERMINAL_STATE for _, _, target in transitions.values()),
            'Canonical table has no transition to the terminal state')
    return transitions


def render_transition_table(transitions):
    lines = [
        '% Generated by report/build_report.py; do not edit the data rows manually.',
        f'% Canonical machine SHA-256: {MACHINE_SHA256}',
        '% 222 working states, two symbols, start 0, separate terminal state 222.',
        r'\begingroup',
        r'\small',
        r'\setlength{\tabcolsep}{10pt}',
        r'\renewcommand{\arraystretch}{1.06}',
        r'\begin{longtable}{rcc}',
        r'\caption{Complete canonical transition table. Each action lists the written bit, movement, and next state.}\label{tab:canonical222}\\',
        r'\toprule',
        r'State & On $0$: write, move, next & On $1$: write, move, next\\',
        r'\midrule',
        r'\endfirsthead',
        r'\multicolumn{3}{c}{\tablename\ \thetable{}: complete transition table (continued)}\\',
        r'\toprule',
        r'State & On $0$: write, move, next & On $1$: write, move, next\\',
        r'\midrule',
        r'\endhead',
        r'\midrule',
        r'\multicolumn{3}{r}{\footnotesize Continued on the next page}\\',
        r'\endfoot',
        r'\bottomrule',
        r'\endlastfoot',
    ]
    for state in range(STATE_COUNT):
        action0 = ' '.join(map(str, transitions[state, 0]))
        action1 = ' '.join(map(str, transitions[state, 1]))
        lines.append(f'{state} & \\texttt{{{action0}}} & \\texttt{{{action1}}} \\\\')
    lines.extend([r'\end{longtable}', r'\endgroup', ''])
    result = '\n'.join(lines)
    verify_generated_rows(result, transitions)
    return result


def verify_generated_rows(tex, transitions):
    reconstructed, states = {}, []
    for line in tex.splitlines():
        match = DATA_ROW.fullmatch(line)
        if match is None:
            require(not re.match(r'^\d+\s*&', line), 'Malformed numeric data row in generated TeX')
            continue
        q, w0, d0, n0, w1, d1, n1 = match.groups()
        q = int(q)
        require(q not in states, 'Duplicate state in generated appendix')
        states.append(q)
        reconstructed[q, 0] = int(w0), d0, int(n0)
        reconstructed[q, 1] = int(w1), d1, int(n1)
    require(states == list(range(STATE_COUNT)), 'Appendix state order or census differs')
    require(len(reconstructed) == 2 * STATE_COUNT and reconstructed == transitions,
            'Generated appendix does not reproduce all 444 canonical transitions exactly')
    return len(reconstructed)


def prepare_output(path):
    output = path.expanduser().resolve()
    require(output != PACKET and PACKET not in output.parents,
            '--output-dir must be outside the K222 packet')
    require(not output.exists() or (output.is_dir() and not any(output.iterdir())),
            '--output-dir must be a new or initially empty directory')
    require((REPORT / 'main.tex').is_file(), 'The report main.tex input is missing')
    output.mkdir(parents=True, exist_ok=True)
    copied = []
    for source in sorted(REPORT.rglob('*.tex')):
        relative = source.relative_to(REPORT)
        # The appendix is regenerated from the canonical machine below.
        if relative == Path('transition_table.tex'):
            continue
        destination = output / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(source, destination)
        copied.append(str(relative))
    return output, copied


def compile_pdf(output):
    executable = shutil.which('pdflatex')
    require(executable is not None, 'pdflatex is not available; install a TeX distribution before compiling')
    for number in (1, 2):
        command = [executable, '-interaction=nonstopmode', '-halt-on-error',
                   '-file-line-error', 'main.tex']
        completed = subprocess.run(command, cwd=output, stdout=subprocess.PIPE,
                                   stderr=subprocess.STDOUT, text=True,
                                   encoding='utf-8', errors='replace', check=False)
        log = output / f'pdflatex-pass{number}.txt'
        log.write_text(completed.stdout, encoding='utf-8')
        if completed.returncode != 0:
            tail = '\n'.join(completed.stdout.splitlines()[-45:])
            raise RuntimeError(f'pdflatex pass {number} failed. Full log: {log}\n{tail}')
        print(f'pdflatex pass {number}: completed', flush=True)
    pdf = output / 'main.pdf'
    require(pdf.is_file() and pdf.stat().st_size > 0, 'pdflatex did not produce main.pdf')
    with pdf.open('rb') as stream:
        require(stream.read(5) == b'%PDF-', 'The generated main.pdf lacks a PDF header')
    return pdf


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path,
                        help='New or empty build directory outside this packet; required for PDF compilation')
    parser.add_argument('--generate-only', action='store_true',
                        help='Generate the audited transition-table TeX without invoking pdflatex')
    args = parser.parse_args()
    if args.output_dir is None and not args.generate_only:
        parser.error('--output-dir is required unless --generate-only is specified')

    transitions = load_machine()
    appendix = render_transition_table(transitions)
    if args.output_dir is None:
        target = REPORT / 'transition_table.tex'
        target.write_text(appendix, encoding='ascii')
        checked = verify_generated_rows(target.read_text(encoding='ascii'), transitions)
        print(f'Generated {target}\nVerified {checked} canonical transitions in 222 table rows.')
        return

    output, copied = prepare_output(args.output_dir)
    target = output / 'transition_table.tex'
    target.write_text(appendix, encoding='ascii')
    checked = verify_generated_rows(target.read_text(encoding='ascii'), transitions)
    receipt = {'status': 'TRANSITION_APPENDIX_TRANSCRIPTION_PASS',
               'machine_sha256': MACHINE_SHA256, 'working_states': STATE_COUNT,
               'state_rows': STATE_COUNT, 'verified_transitions': checked,
               'transition_table_tex_sha256': digest(target.read_bytes()),
               'copied_tex_inputs': copied,
               'pdflatex_passes': 0}
    if not args.generate_only:
        pdf = compile_pdf(output)
        receipt.update({'status': 'REPORT_BUILD_AND_APPENDIX_TRANSCRIPTION_PASS',
                        'pdflatex_passes': 2, 'pdf_sha256': digest(pdf.read_bytes()),
                        'pdf_size_bytes': pdf.stat().st_size,
                        'built_at_utc': datetime.now(timezone.utc).isoformat(),
                        'visual_review': 'Separate visual inspection is required before delivery.'})
    (output / 'report_build_receipt.json').write_text(json.dumps(receipt, indent=2) + '\n')
    print(json.dumps(receipt, indent=2))
    if not args.generate_only:
        print(f'PDF: {output / "main.pdf"}')
    else:
        print(f'Generated TeX: {target}')


if __name__ == '__main__':
    try:
        main()
    except (OSError, ValueError, RuntimeError) as error:
        print(f'Build failed: {error}', file=sys.stderr)
        raise SystemExit(1)
