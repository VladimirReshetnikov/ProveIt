#!/usr/bin/env python3
"""Reproduce the finite experiments packaged with the PSC research report.

Python 3.10+, standard library only. Run normally, never with -O. Generated
files go to a temporary directory; the supplied reference results are not
overwritten. This driver checks evidence, not set-theoretic consistency.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile


ROOT = Path(__file__).resolve().parent


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(args: list[str], *, cwd: Path = ROOT) -> str:
    environment = os.environ.copy()
    environment["PYTHONDONTWRITEBYTECODE"] = "1"
    result = subprocess.run([sys.executable, *map(str, args)], cwd=cwd,
                            env=environment, capture_output=True, text=True)
    if result.returncode:
        raise RuntimeError("Command failed: " + " ".join(map(str, args)) +
                           "\n" + result.stdout + result.stderr)
    return result.stdout


def check_manifest() -> int:
    count = 0
    for line in (ROOT / "SHA256SUMS.txt").read_text().splitlines():
        if not line:
            continue
        digest, name = line.split("  ", 1)
        path = (ROOT / name).resolve()
        if ROOT not in path.parents or len(digest) != 64:
            raise ValueError("Invalid manifest entry")
        if sha(path) != digest:
            raise ValueError("File hash mismatch: " + name)
        count += 1
    if not count:
        raise ValueError("Empty manifest")
    return count


def audit_total_table(path: Path) -> dict:
    rows = {}
    lines = path.read_text().splitlines()
    assert lines[0] == "#! start 0"
    for line in lines[1:]:
        q, b, write, move, target = line.split()
        q, b, write, target = map(int, (q, b, write, target))
        assert 0 <= q < 269 and b in (0, 1) and write in (0, 1)
        assert move in ("L", "R") and 0 <= target <= 269
        assert (q, b) not in rows
        rows[q, b] = write, move, target
    assert set(rows) == {(q, b) for q in range(269) for b in (0, 1)}
    assert any(target == 269 for _, _, target in rows.values())
    return dict(working_states=269, transitions=len(rows), start=0, halt=269,
                sha256=sha(path))


def main() -> None:
    if sys.version_info < (3, 10) or not __debug__:
        raise SystemExit("Use Python 3.10 or newer without -O.")
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--output", type=Path,
                        help="Optional JSON record of this reproduction")
    parser.add_argument("--upstream-kernel", type=Path,
                        help="Optional exact pinned kernel_metrics.py to compare")
    args = parser.parse_args()
    kernel = args.upstream_kernel.resolve() if args.upstream_kernel else None
    checked = check_manifest()
    print("Package hashes verified.", flush=True)
    record = dict(kind="finite executable reproduction; no consistency proof",
                  python=sys.version.split()[0], file_hashes_verified=True,
                  manifest_entries_at_run=checked)

    with tempfile.TemporaryDirectory(prefix="psc-report-reproduction-") as td:
        scratch = Path(td)
        generated = scratch / "machine"
        run([ROOT / "machine/rebracket_axioms.py", "--inputs",
             ROOT / "machine/inputs", "--output", generated])
        reference = ROOT / "machine/results"
        compared = {}
        for old in sorted(reference.iterdir()):
            if old.is_file():
                new = generated / old.name
                assert sha(new) == sha(old), "Machine output changed: " + old.name
                compared[old.name] = sha(new)
        cert = json.loads(run([
            ROOT / "machine/verify_rm_certificate.py", "--source",
            ROOT / "machine/inputs/source_dag.json", "--candidate",
            generated / "rebracketed_dag.json", "--certificate",
            generated / "rm_bisimulation.json"]))
        assert cert["verified"] and cert["pairs"] == 4533
        record["machine"] = dict(regenerated_outputs=compared,
                                  independent_certificate=cert,
                                  table=audit_total_table(
                                      generated / "rebracketed_wade_total.tm"))
        print("269-state table regenerated byte-for-byte; 4,533-pair certificate verified.",
              flush=True)

        checker = scratch / "proof_checker"
        shutil.copytree(ROOT / "proof_checker", checker,
                        ignore=shutil.ignore_patterns("__pycache__"))
        validation_args = [checker / "validate.py"]
        if kernel is not None:
            validation_args += ["--upstream-kernel", kernel]
        run(validation_args, cwd=checker)
        current = json.loads((checker / "validation.json").read_text())
        expected = json.loads((ROOT / "proof_checker/validation.json").read_text())
        stable = ["tests_run", "tests_successful", "deep_binder_test_depth",
                  "substitution_semantics_comparisons", "identity",
                  "bounded_census", "file_sha256"]
        for key in stable:
            assert current[key] == expected[key], "Checker evidence changed: " + key
        if kernel is not None:
            assert current["upstream_comparison"] == expected["upstream_comparison"]
            stable.append("upstream_comparison")
        record["proof_checker"] = {key: current[key] for key in stable}
        print("12 checker tests and the 131,071-word regression census passed.", flush=True)

        finite = scratch / "finite_saturation_results.json"
        run([ROOT / "code/finite_saturation.py", "--output", finite])
        assert finite.read_bytes() == (ROOT / "data/finite_saturation_results.json").read_bytes()
        record["finite_relations"] = json.loads(finite.read_text())
        print("530 finite membership-graph regressions reproduced.", flush=True)

    record["all_checks_passed"] = True
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(record, indent=2, sort_keys=True) + "\n")
    print(json.dumps({"all_checks_passed": True,
                      "formal_proof_assistant_verification": False,
                      "new_binary_compiler_correctness_proved": False,
                      "sub_254_record_claimed": False}, indent=2))


if __name__ == "__main__":
    main()
